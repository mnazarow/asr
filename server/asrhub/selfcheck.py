def _мониторинг(state: Any, глубоко: bool) -> dict[str, Any]:
    """Экспорт метрик, приёмники и тревоги."""
    служба = getattr(state, "monitoring", None)
    settings = state.settings
    экспорт = bool(settings.get("metrics_enabled", True))
    проверки: list[dict[str, Any]] = []

    проверки.append(_проверка(
        "export", "Экспорт метрик", "ok" if экспорт else "off",
        "включён, /api/metrics отвечает" if экспорт else "выключен",
        "", enabled=экспорт,
        public=bool(settings.get("monitoring_public", True))))

    if служба is None:
        проверки.append(_проверка(
            "service", "Подсистема мониторинга", "warn", "не поднята",
            "Метрики отдаются прежним, урезанным набором; тревоги не "
            "считаются вовсе. Смотрите журнал запуска."))
        return {"state": "warn", "value": "подсистема не поднята",
                "checks": проверки}

    # При обычном опросе берём то, что уже посчитано: `info()` снимает
    # свежие метрики, а это обход базы и оборудования. Панель опрашивает
    # свод постоянно — сбор на каждый её опрос удвоил бы нагрузку сбора.
    сведения: dict[str, Any] = {}
    if глубоко:
        try:
            сведения = dict(служба.info())
        except Exception as exc:                                      # noqa: BLE001
            log.debug("Сведения мониторинга не собраны: %s", exc)

    try:
        приёмники = list(служба.push.targets())
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Приёмники метрик не прочитаны: %s", exc)
        приёмники = []
    if приёмники:
        # Условие «была попытка» обязательно: у приёмника, которому ещё ни
        # разу не отправляли, `healthy` ложно по определению, и без этой
        # оговорки каждый только что настроенный приёмник объявлялся бы
        # сломанным на первую минуту жизни — ровно тогда, когда человек
        # смотрит, принялась ли настройка.
        сломанные = [п for п in приёмники
                     if п.get("enabled", True) and п.get("last_attempt")
                     and not п.get("healthy", True)]
        последняя = max((_число(п.get("last_success")) for п in приёмники),
                        default=0.0)
        проверки.append(_проверка(
            "targets", "Приёмники метрик",
            "warn" if сломанные else "ok",
            f"{len(приёмники)} шт., последняя отправка {_когда(последняя)}"
            + (f"; не отвечают: {len(сломанные)}" if сломанные else ""),
            "Метрики не доходят до приёмника: проверьте адрес и доступность "
            "его из сети сервера. Тексты ошибок — в разделе «Мониторинг»."
            if сломанные else "",
            total=len(приёмники), broken=len(сломанные),
            last_success=последняя or None,
            targets=[{"name": п.get("name"), "kind": п.get("kind"),
                      "healthy": п.get("healthy"),
                      "last_error": п.get("last_error")} for п in приёмники]))
    else:
        проверки.append(_проверка(
            "targets", "Приёмники метрик", "off", "не настроены",
            "", total=0))

    try:
        тревоги = dict(служба.alerts.summary())
        горят = list(служба.alerts.firing())
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Тревоги не прочитаны: %s", exc)
        тревоги, горят = {}, []
    критичных = int(тревоги.get("critical") or 0)
    предупреждений = int(тревоги.get("warning") or 0)
    проверки.append(_проверка(
        "alerts", "Тревоги",
        "fail" if критичных else ("warn" if предупреждений else "ok"),
        f"правил {int(тревоги.get('rules') or 0)}, горят "
        f"{int(тревоги.get('firing') or 0)}"
        + (f": {', '.join(str(т.get('summary'))[:80] for т in горят[:3])}"
           if горят else ""),
        "Тревога сработала по порогу из настройки monitoring_rules — "
        "смотрите её текст: он называет и величину, и порог."
        if горят else "",
        **{к: тревоги.get(к) for к in ("rules", "firing", "pending",
                                       "critical", "warning", "worst")}))

    ошибки_сбора = list(сведения.get("collection_errors") or [])
    if ошибки_сбора:
        проверки.append(_проверка(
            "collect", "Сбор метрик", "warn",
            f"источников с ошибкой: {len(ошибки_сбора)} — "
            + "; ".join(str(о)[:80] for о in ошибки_сбора[:3]),
            "Часть метрик не собирается: значения по этим источникам в "
            "выгрузке отсутствуют, а не равны нулю.",
            errors=[str(о)[:200] for о in ошибки_сбора[:20]]))

    беда = _первая_беда(проверки)
    return {
        "value": ("экспорт выключен" if not экспорт else
                  f"приёмников {len(приёмники)}, тревог "
                  f"{int(тревоги.get('firing') or 0)}"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"enabled": экспорт, "targets": len(приёмники),
                    "alerts": тревоги},
        "checks": проверки,
    }


