#: Ключ отпечатка в таблице настроек.
КЛЮЧ_ОТПЕЧАТКА = "selfcheck:seen"

#: Сколько проблем держим в отпечатке. Предел не про память, а про
#: испорченные настройки: станции и приёмники задаются списком, и опечатка
#: в нём способна породить сотни разных проверок. Хранить их все — значит
#: класть в `kv` строку, которую потом никто не прочтёт.
ПРЕДЕЛ_ОТПЕЧАТКА = 200


def _отпечаток(проблема: dict[str, Any]) -> str:
    """Ключ проблемы: раздел, проверка и состояние.

    Состояние входит в ключ намеренно: переход warn → fail — это новость,
    а не «та же самая проблема». Значение (`value`) в ключ не входит: там
    числа, которые меняются на каждом опросе, и запись о «новой» проблеме
    появлялась бы каждые несколько секунд.
    """
    return f"{проблема.get('component')}/{проблема.get('id')}/{проблема.get('state')}"


def записать_проблемы(db: Any, свод: dict[str, Any]) -> dict[str, Any]:
    """Пишет в ленту событий только изменения: появилось и ушло.

    Свод опрашивается панелью постоянно, и запись каждой проблемы на
    каждый опрос за сутки превратила бы ленту событий в один и тот же
    текст, повторённый десять тысяч раз, — а вместе с ним и таблицу
    событий в основную по размеру.

    Поэтому в `kv` под одним ключом лежит отпечаток: словарь «ключ
    проблемы → когда впервые увидели и как называется». Он не растёт,
    потому что хранит РОВНО текущий набор проблем: ушедшая проблема из
    него удаляется в том же заходе, в котором о ней пишется «устранено».
    Сверху — предел на число записей, на случай настройки, порождающей
    проверки пачками.

    Возвращает, что именно записано, — чтобы вызывающий мог это показать,
    а проверка убедиться, не заглядывая в журнал.
    """
    проблемы = list(свод.get("problems") or [])
    сейчас = float(свод.get("at") or time.time())

    прежние: dict[str, Any] = {}
    try:
        сырое = db.get_kv(КЛЮЧ_ОТПЕЧАТКА, None)
        if isinstance(сырое, dict):
            прежние = {str(к): з for к, з in сырое.items()}
    except Exception as exc:                                          # noqa: BLE001
        # Отпечаток нечитаем — не повод молчать о проблемах. Хуже всего
        # здесь было бы бросить исключение: диагностика перестала бы
        # отвечать из-за испорченной служебной записи.
        log.warning("Отпечаток прошлых проблем не прочитан: %s", exc)

    текущие: dict[str, Any] = {}
    появились: list[dict[str, Any]] = []
    for проблема in проблемы[:ПРЕДЕЛ_ОТПЕЧАТКА]:
        ключ = _отпечаток(проблема)
        подпись = f"{проблема.get('component_title') or проблема.get('component')}: " \
                  f"{проблема.get('title')}"
        было = прежние.get(ключ)
        if isinstance(было, dict) and было.get("at"):
            # Та же проблема, что и в прошлый раз: первую отметку времени
            # сохраняем — по ней интерфейс отвечает «длится с такого-то».
            текущие[ключ] = {"at": было["at"], "title": подпись}
            continue
        текущие[ключ] = {"at": сейчас, "title": подпись}
        появились.append(проблема)

    ушли = [(ключ, значение) for ключ, значение in прежние.items()
            if ключ not in текущие]

    for проблема in появились:
        знак = "Неисправность" if проблема.get("state") == "fail" else "Предупреждение"
        текст = (f"{знак}: {проблема.get('component_title')} — "
                 f"{проблема.get('title')}: {проблема.get('value')}")
        try:
            db.add_event(None, "selfcheck", текст[:500])
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Событие о проблеме не записано: %s", exc)

    for ключ, значение in ушли:
        название = ""
        if isinstance(значение, dict):
            название = str(значение.get("title") or "")
        # Отпечаток лежит в общей таблице настроек, и его правят руками
        # вместе с соседними ключами. Разбор отметки времени поэтому
        # защищённый: испорченная запись не должна отменять сообщение о
        # том, что неисправность ушла.
        с_какого = значение.get("at") if isinstance(значение, dict) else None
        try:
            длилось = _длительность(max(0.0, сейчас - float(с_какого or 0)))
        except (TypeError, ValueError):
            длилось = ""
        текст = (f"Устранено: {название or ключ}"
                 + (f" (длилось {длилось})" if с_какого and длилось else ""))
        try:
            db.add_event(None, "selfcheck", текст[:500])
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Событие об устранении не записано: %s", exc)

    if появились or ушли or (текущие != прежние):
        try:
            db.set_kv(КЛЮЧ_ОТПЕЧАТКА, текущие)
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Отпечаток проблем не сохранён: %s", exc)

    return {
        "appeared": [{"id": п["id"], "component": п["component"],
                      "title": п["title"], "state": п["state"]}
                     for п in появились],
        "resolved": [{"key": к,
                      "title": (з or {}).get("title", "") if isinstance(з, dict) else ""}
                     for к, з in ушли],
        "known": len(текущие),
    }


