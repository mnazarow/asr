def _устройство_проверка(state: Any, железо: Any,
                         проверки: list[dict[str, Any]]) -> None:
    """Добавляет проверку «видит ли процесс то устройство, которое настроено».

    Отдельно от проверки видеокарт не случайно: там речь про железо, которое
    есть в машине, а здесь — про то, доступно ли оно этому процессу. Эти два
    ответа расходятся ровно в тех случаях, ради которых проверка и написана.
    """
    from .hardware import проверить_ускоритель  # noqa: PLC0415

    настроено = str(state.settings.get("device") or "auto").strip()
    if настроено == "auto":
        # При «auto» сервер сам уходит на процессор, если карты нет, — жаловаться
        # не на что. Но сказать, чем это кончилось, стоит: молчаливый уход на
        # процессор выглядит как «сервер стал медленным без причины».
        проверки.append(_проверка(
            "device", "Устройство", "ok",
            f"auto → {железо.accelerator}",
            "Видеокарта не используется: при «auto» сервер уходит на процессор, "
            "когда карты нет. Если она должна быть — смотрите проверку выше."
            if железо.accelerator == "cpu" else "",
            configured="auto", effective=железо.accelerator))
        return

    годно, причина = проверить_ускоритель(настроено)
    проверки.append(_проверка(
        "device", "Устройство", "ok" if годно else "fail",
        настроено if годно else f"{настроено} — недоступно: {причина}",
        "" if годно else
        "Задания на этом устройстве падают все до одного. Проверьте "
        "nvidia-smi -L, затем CUDA_VISIBLE_DEVICES в окружении службы, "
        "затем dmesg на Xid: после отвала карты ошибка CUDA липкая и "
        "уходит только с перезапуском службы. Пока карта чинится, приём "
        "держит device=cpu.",
        configured=настроено, available=bool(годно)))


#: Что сказать по каждому приговору о драйвере. Состояние, текст и подсказка —
