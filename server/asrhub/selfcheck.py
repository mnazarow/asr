def _очередь(state: Any, глубоко: bool) -> dict[str, Any]:
    """Глубина, работники, неудачи за сутки, ожидание."""
    свод = state.queue.status()
    проверки: list[dict[str, Any]] = []
    счётчики = dict(свод.get("counts") or {})
    глубина = int(свод.get("queue_depth") or 0)
    предел = int(свод.get("max_queue_size") or 0)

    приостановлена = bool(свод.get("paused"))
    проверки.append(_проверка(
        "paused", "Обработка", "warn" if приостановлена else "ok",
        "ПРИОСТАНОВЛЕНА" if приостановлена else "идёт",
        "Очередь на паузе: задания принимаются, но не выполняются. "
        "Возобновить: POST /api/queue/resume." if приостановлена else "",
        paused=приостановлена))

    if предел and глубина >= предел:
        состояние, подсказка = "fail", (
            "Очередь заполнена до предела — новые задания отвергаются. "
            "Поднимите max_queue_size или разберите очередь.")
    elif предел and глубина >= предел * 0.8:
        состояние, подсказка = "warn", (
            "Очередь подошла к пределу: при заполнении сервер начнёт "
            "отказывать в приёме заданий.")
    else:
        состояние, подсказка = "ok", ""
    проверки.append(_проверка(
        "depth", "Глубина очереди", состояние,
        f"ждут {глубина}" + (f" из {предел}" if предел else "")
        + f", выполняются {int(свод.get('active') or 0)}",
        подсказка, depth=глубина, limit=предел,
        active=int(свод.get("active") or 0),
        workers=int(свод.get("worker_count") or 0),
        pending_audio_s=свод.get("pending_audio_s"),
        eta_s=свод.get("eta_s")))

    # Экземпляр, переставший отвечать, держит задания «выполняющимися», и
    # они вернутся в очередь только по истечении срока. На одном сервере
    # это всегда он сам, на нескольких — видно, кто отвалился.
    отставшие = [и for и in (свод.get("instances") or []) if и.get("stale")]
    if отставшие:
        проверки.append(_проверка(
            "instances", "Экземпляры сервера", "warn",
            f"не отвечают: {len(отставшие)} из {len(свод.get('instances') or [])}",
            "Экземпляр держит задания, но перестал подавать признаки жизни. "
            "Его задания вернутся в очередь сами; если он выключен навсегда — "
            "это ожидаемо.",
            stale=[str(и.get("instance")) for и in отставшие]))

    сутки_назад = time.time() - СУТКИ
    неудач = завершено = 0
    try:
        неудач = int(state.db.count_jobs(status="failed", since=сутки_назад))
        завершено = int(state.db.count_jobs(status="completed", since=сутки_назад))
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Счётчики заданий за сутки не прочитаны: %s", exc)
    всего_за_сутки = неудач + завершено
    доля = (неудач / всего_за_сутки) if всего_за_сутки else 0.0
    if неудач >= ОШИБОК_ДЛЯ_ДОЛИ and доля >= ДОЛЯ_ОШИБОК_FAIL:
        состояние, подсказка = "fail", (
            "Падает заметная часть заданий — это уже не отдельные файлы. "
            "Причины разобраны в разделе «Аналитика» → «Ошибки»; чаще всего "
            "это нехватка видеопамяти, битые файлы или недоступная модель.")
    elif неудач:
        состояние, подсказка = "warn", (
            "Посмотрите причины в разделе «Аналитика» → «Ошибки». "
            "Повторить все неудавшиеся: POST /api/queue/retry-failed.")
    else:
        состояние, подсказка = "ok", ""
    проверки.append(_проверка(
        "failed", "Неудачи за сутки", состояние,
        f"{неудач} из {всего_за_сутки}"
        + (f" ({доля * 100:.0f} %)" if всего_за_сутки else ""),
        подсказка, failed=неудач, completed=завершено, share=round(доля, 3)))

    # Среднее ожидание считаем по образцу завершённых за сутки: в готовых
    # заданиях `queue_time_s` уже посчитан очередью, и повторять его
    # арифметикой по отметкам времени незачем.
    ожидания: list[float] = []
    try:
        for задание in state.db.list_jobs(status="completed", since=сутки_назад,
                                          limit=ОБРАЗЕЦ_ЗАДАНИЙ, light=True):
            значение = задание.get("queue_time_s")
            if значение is not None:
                ожидания.append(float(значение))
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Ожидание в очереди не посчитано: %s", exc)
    if ожидания:
        среднее = sum(ожидания) / len(ожидания)
        долгих = sum(1 for з in ожидания if з > 600)
        проверки.append(_проверка(
            "wait", "Ожидание в очереди",
            "warn" if среднее > 600 else "ok",
            f"в среднем {среднее:.0f} с по {len(ожидания)} заданиям, "
            f"дольше десяти минут ждали {долгих}",
            "Задания подолгу стоят перед обработкой. Прибавьте работников "
            "(max_concurrent_jobs), если хватает памяти видеокарты, или "
            "разберите очередь." if среднее > 600 else "",
            avg_s=round(среднее, 1), sampled=len(ожидания), over_10min=долгих))
    else:
        проверки.append(_проверка(
            "wait", "Ожидание в очереди", "ok",
            "за сутки заданий не было", avg_s=None, sampled=0))

    беда = _первая_беда(проверки)
    return {
        "value": f"ждут {глубина}, выполняются {int(свод.get('active') or 0)}, "
                 f"неудач за сутки {неудач}"
                 + (", ПАУЗА" if приостановлена else ""),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"depth": глубина, "active": int(свод.get("active") or 0),
                    "paused": приостановлена, "counts": счётчики,
                    "failed_24h": неудач, "completed_24h": завершено},
        "checks": проверки,
    }


