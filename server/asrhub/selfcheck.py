# 10. Разбор содержания
# ---------------------------------------------------------------------------

def _содержание(state: Any, глубоко: bool) -> dict[str, Any]:
    """Сколько записей разобрано, сколько ждёт, какой версией."""
    разбор = getattr(state, "content", None)
    if разбор is None:
        return {"state": "off", "value": "разбор не поднят", "checks": []}

    try:
        свод = dict(разбор.status())
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Состояние разбора не прочитано: %s", exc)
        свод = {}
    включён = bool(свод.get("enabled", True))
    всего = int(свод.get("total") or 0)
    разобрано = int(свод.get("analyzed") or 0)
    ждут = int(свод.get("pending") or 0)
    проверки: list[dict[str, Any]] = []

    проверки.append(_проверка(
        "enabled", "Разбор содержания", "ok" if включён else "off",
        "включён" if включён else "выключен",
        "", enabled=включён, version=свод.get("version")))

    # «Ожидают разбора» само по себе не беда: фоновый досчёт разбирает
    # архив порциями. Бедой это становится, когда досчёт выключен — тогда
    # ждать можно вечно, а показатели считаются по разобранной части и
    # выглядят как показатели по всему архиву.
    досчёт = bool(свод.get("backfill", True))
    if ждут and not досчёт:
        состояние, подсказка = "warn", (
            "Записи ждут разбора, а фоновый досчёт выключен: показатели "
            "считаются по разобранной части архива. Включите content_backfill "
            "или пересчитайте вручную: POST /api/content/recompute.")
    elif ждут > max(100, всего * 0.5):
        состояние, подсказка = "warn", (
            "Разобрано меньше половины архива — сводные показатели пока "
            "говорят не обо всём корпусе. Досчёт идёт порциями в фоне.")
    else:
        состояние, подсказка = "ok", ""
    проверки.append(_проверка(
        "coverage", "Покрытие разбором", состояние,
        f"разобрано {разобрано} из {всего}, ждут {ждут}, версия разбора "
        f"{свод.get('version')}",
        подсказка, total=всего, analyzed=разобрано, pending=ждут,
        version=свод.get("version"), backfill=досчёт))

    сломанные = list(свод.get("categories_broken") or [])
    if сломанные:
        проверки.append(_проверка(
            "categories", "Свои категории", "fail",
            "с ошибкой: " + ", ".join(str(к) for к in сломанные[:5]),
            "Правило категории не разбирается, и записи по ней не "
            "размечаются вовсе. Исправьте выражение в настройке "
            "content_categories.",
            broken=сломанные))

    if свод.get("last_error"):
        проверки.append(_проверка(
            "last_error", "Последняя ошибка разбора", "warn",
            str(свод["last_error"])[:200],
            "Разбор пропустил запись и пошёл дальше; смотрите журнал."))

    живой = bool(свод.get("running"))
    проверки.append(_проверка(
        "worker", "Фоновый досчёт",
        "ok" if (живой or not досчёт or not включён) else "warn",
        "работает" if живой else ("выключен" if not досчёт else "не запущен"),
        "Поток досчёта не поднят: архив не разбирается. Перезапустите "
        "сервер." if включён and досчёт and not живой else "",
        running=живой, backfill=досчёт))

    беда = _первая_беда(проверки)
    return {
        "state": None if включён else "off",
        "value": ("выключен" if not включён else
                  f"разобрано {разобрано} из {всего}, ждут {ждут}"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"enabled": включён, "total": всего, "analyzed": разобрано,
                    "pending": ждут, "version": свод.get("version"),
                    "vocabulary": свод.get("vocabulary")},
        "checks": проверки,
    }


