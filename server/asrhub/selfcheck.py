def _модели(state: Any, глубоко: bool) -> dict[str, Any]:
    """Модель по умолчанию, её веса и место под моделями."""
    from . import (
        catalog,  # noqa: PLC0415
        model_files,  # noqa: PLC0415
    )

    settings = state.settings
    paths = getattr(settings, "paths", None)
    каталог_моделей = Path(str(settings.get("models_dir")
                               or (paths.models if paths else ".")))
    имя = str(settings.get("model") or "").strip()
    описание = catalog.get_model(имя)
    проверки: list[dict[str, Any]] = []

    if описание is None:
        проверки.append(_проверка(
            "default", "Модель по умолчанию", "fail",
            f"«{имя or 'не задана'}» нет в каталоге",
            "Задание без явно указанной модели будет отвергнуто. Список "
            "моделей: GET /api/models. Похожие названия подскажет сам "
            "сервер при попытке поставить задание.",
            model=имя))
        веса = None
    else:
        проверки.append(_проверка(
            "default", "Модель по умолчанию", "ok",
            f"{описание.name} ({описание.engine})",
            model=имя, engine=описание.engine))
        # Встроенные модели весов не имеют вовсе: у демонстрационного
        # движка источник «builtin», и проверка «скачаны ли веса» на нём
        # показывала бы вечное «не скачаны» на исправном сервере.
        нужны_веса = bool(описание.source) and not описание.source.startswith("builtin")
        веса: Any = None if нужны_веса else "не нужны"
        if нужны_веса:
            try:
                веса = model_files.find_local(каталог_моделей, описание.source,
                                              описание.revision or "")
            except Exception as exc:                                  # noqa: BLE001
                log.debug("Поиск весов модели не удался: %s", exc)
            размер_весов = model_files.directory_size(веса) if веса else 0
            проверки.append(_проверка(
                "weights", "Веса модели", "ok" if веса else "warn",
                f"скачаны, {_объём(размер_весов)}" if веса else "не скачаны",
                "" if веса else
                "Первое задание скачает веса само — это несколько гигабайт и "
                "несколько минут, и всё это время задание будет выглядеть "
                "зависшим. Скачать заранее: POST /api/models/"
                f"{имя}/download",
                downloaded=bool(веса), bytes=размер_весов,
                path=str(веса) if веса else ""))
        else:
            проверки.append(_проверка(
                "weights", "Веса модели", "ok", "не нужны (встроенная модель)",
                downloaded=True, bytes=0))

    # Сколько всего занято моделями — только при глубокой проверке: это
    # обход каталога, в котором лежат десятки гигабайт.
    if глубоко:
        байт, файлов, полностью = _размер_каталога(каталог_моделей)
        скачано = 0
        try:
            for спец in catalog.MODELS:
                if not спец.source or спец.source.startswith("builtin"):
                    continue
                if model_files.find_local(каталог_моделей, спец.source,
                                          спец.revision or ""):
                    скачано += 1
        except Exception as exc:                                      # noqa: BLE001
            log.debug("Список скачанных моделей не собран: %s", exc)
        проверки.append(_проверка(
            "storage", "Каталог моделей", "ok",
            f"скачано моделей {скачано}, занято "
            + ("не меньше " if not полностью else "") + _объём(байт),
            "", bytes=байт, files=файлов, complete=полностью,
            downloaded=скачано, path=str(каталог_моделей)))

    беда = _первая_беда(проверки)
    состояние_весов = ("не нужны" if веса == "не нужны" else
                       "на месте" if веса else "не скачаны")
    return {
        "value": (f"{описание.name}, веса {состояние_весов}" if описание
                  else f"модель «{имя or 'не задана'}» неизвестна"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"model": имя, "downloaded": bool(веса),
                    "path": str(каталог_моделей)},
        "checks": проверки,
    }


