def _языковая_модель(state: Any, глубоко: bool) -> dict[str, Any]:
    """Смысловой слой: подключение, очередь разбора, ошибки."""
    клиент = getattr(state, "llm", None)
    if клиент is None:
        return {"state": "off", "value": "слой не поднят", "checks": []}

    backend = str(клиент.backend)
    включён = bool(клиент.enabled)
    проверки: list[dict[str, Any]] = []
    if not включён:
        проверки.append(_проверка(
            "backend", "Смысловой слой", "off", f"выключен (llm_backend = {backend})",
            "", backend=backend))
    else:
        # Слой включён, а модель не названа — это не «настроено не до
        # конца», а падение на каждом вызове: клиент отправит запрос с
        # пустым именем модели, и сервер модели ответит отказом.
        проверки.append(_проверка(
            "backend", "Смысловой слой", "ok" if клиент.model else "fail",
            f"{backend}, модель «{клиент.model or 'не задана'}»",
            "" if клиент.model else
            "Модель не задана (llm_model): разбор будет падать на каждом "
            "вызове. Список моделей, которые знает сервер модели, — в "
            "разделе «Смысловой слой».",
            backend=backend, model=str(клиент.model or ""),
            url=str(клиент.url or "")))

        # Проба ходит в сеть, поэтому при обычном опросе её не зовём: у
        # клиента есть свой кеш на минуту, но первый вызов всё равно был бы
        # сетевым — и панель, опрашивающая свод, держала бы сервер модели
        # под постоянным опросом.
        if глубоко:
            try:
                проба = клиент.probe(fresh=True)
            except Exception as exc:                                  # noqa: BLE001
                проба = {"available": False, "reason": str(exc)}
            доступен = bool(проба.get("available"))
            известна = проба.get("model_known", True)
            проверки.append(_проверка(
                "server", "Сервер модели",
                "ok" if доступен and известна else
                ("warn" if доступен else "fail"),
                "отвечает" if доступен and известна else
                str(проба.get("reason") or "недоступен")[:200],
                "" if доступен and известна else
                ("Сервер модели не отвечает: проверьте, запущен ли он "
                 "(ollama serve) и верен ли адрес в llm_url."
                 if not доступен else
                 "Сервер отвечает, но названной модели у него нет — "
                 "скачайте её или исправьте llm_model."),
                available=доступен, model_known=bool(известна),
                reason=проба.get("reason")))

        if клиент.last_error:
            проверки.append(_проверка(
                "last_error", "Последняя ошибка вызова", "warn",
                str(клиент.last_error)[:200],
                "Разбор пропускает записи, на которых модель ответила "
                "ошибкой; к ним он вернётся сам.",
                calls=int(getattr(клиент, "calls", 0) or 0),
                errors=int(getattr(клиент, "errors", 0) or 0)))

    счётчики: dict[str, int] = {}
    сводка: dict[str, Any] = {}
    try:
        счётчики = dict(state.db.llmq_counts())
        сводка = dict(state.db.llmq_stats(time.time() - СУТКИ))
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Очередь разбора не прочитана: %s", exc)
    ошибок = int(счётчики.get("ошибка") or 0)
    ждут = int(счётчики.get("ждёт") or 0)
    неудач_сутки = int(_число(сводка.get("failed")))
    готово_сутки = int(_число(сводка.get("ok")))
    проверки.append(_проверка(
        "queue", "Очередь разбора",
        "warn" if (ошибок or неудач_сутки) else "ok",
        f"ждут {ждут}, идут {int(счётчики.get('идёт') or 0)}, "
        f"готово {int(счётчики.get('готово') or 0)}, с ошибкой {ошибок}; "
        f"за сутки разобрано {готово_сутки}, не вышло {неудач_сутки}",
        "Записи с ошибкой разбора лежат в очереди и не повторяются сами. "
        "Повторить: POST /api/llm/queue/retry-failed."
        if (ошибок or неудач_сутки) else "",
        counts=счётчики, failed_24h=неудач_сутки, done_24h=готово_сутки,
        avg_ms=сводка.get("avg_ms"), wait_s=сводка.get("wait_s")))

    работник = getattr(state, "llm_worker", None)
    if работник is not None:
        try:
            свод_работника = dict(работник.status())
        except Exception as exc:                                      # noqa: BLE001
            log.debug("Состояние разборщика не прочитано: %s", exc)
            свод_работника = {}
        живой = bool(свод_работника.get("running"))
        проверки.append(_проверка(
            "worker", "Фоновый разбор",
            "ok" if (живой or not включён) else "warn",
            "работает" if живой else "не запущен",
            "Поток разбора не поднят: новые записи в очередь попадают, но "
            "никто их не берёт. Перезапустите сервер."
            if включён and not живой else "",
            **{к: свод_работника.get(к)
               for к in ("running", "queued", "done", "failed", "auto",
                         "backfill", "last_error")}))

    беда = _первая_беда(проверки)
    return {
        "state": None if включён else "off",
        "value": ("выключен" if not включён else
                  f"{backend}/{клиент.model or '—'}, в очереди {ждут}, "
                  f"с ошибкой {ошибок}"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"backend": backend, "enabled": включён,
                    "model": str(клиент.model or ""), "queue": счётчики},
        "checks": проверки,
    }


