#: Что выполняется по расписанию: ключ отметки в `kv`, название, срок в
#: часах (или имя настройки, из которой он берётся) и признак включённости.
_РАБОТЫ = (
    ("maintenance.backup_at", "backup", "Резервная копия", 24.0, "backup_enabled"),
    ("maintenance.digest_at", "digest", "Сводка о работе", None, "digest_url"),
    ("review_sampled_at", "review", "Выборка на проверку", 24.0, "review_enabled"),
    ("control_sampled_at", "control", "Контрольные прогоны", 24.0, "control_model"),
    ("employees_synced_at", "employees", "Справочник сотрудников", None,
     "employees_sync_enabled"),
)


def _обслуживание(state: Any, глубоко: bool) -> dict[str, Any]:
    """Когда в последний раз выполнялись фоновые работы и не отстали ли они."""
    settings = state.settings
    db = state.db
    проверки: list[dict[str, Any]] = []
    # Служебный цикл проходит раз в двадцать секунд и сам ставит
    # отсутствующие отметки. Пока сервер поднялся только что, «отметки
    # нет» означает «цикл ещё не успел», а не поломку: без этой поправки
    # каждая перезагрузка сервера на несколько минут зажигала бы пять
    # предупреждений подряд — и к ним быстро привыкли бы как к шуму.
    молод = max(0.0, time.time() - float(getattr(state, "started_at", 0) or 0)) < 600

    for ключ, имя, название, часов, признак in _РАБОТЫ:
        try:
            отметка = db.get_kv(ключ)
        except Exception as exc:                                      # noqa: BLE001
            log.debug("Отметка «%s» не прочитана: %s", ключ, exc)
            отметка = None
        включено = bool(settings.get(признак)) if признак else True
        if признак == "control_model":
            включено = bool(str(settings.get("control_model") or "").strip())
        if признак == "digest_url":
            включено = bool(str(settings.get("digest_url") or "").strip())

        срок = часов
        if имя == "digest":
            срок = _число(settings.get("digest_interval_hours"), 0.0) or None
        if имя == "employees":
            срок = _число(settings.get("employees_sync_hours"), 0.0) or None
        if имя == "backup":
            интервал = _число(settings.get("backup_interval_hours"), 0.0)
            срок = интервал or 24.0

        возраст = _секунд_назад(отметка)
        if not включено:
            состояние, подсказка = "off", ""
        elif возраст is None:
            # Отметка ставится «сейчас» при первом заходе после запуска:
            # её отсутствие у давно работающего сервера значит, что
            # служебный цикл не идёт вовсе, — а это тихо отменяет разом и
            # копии, и уборку, и сводки.
            состояние, подсказка = ("ok", "") if молод else ("warn", (
                "Заход не выполнялся ни разу, а сервер работает давно: "
                "служебный цикл не идёт. Вместе с ним не делаются копии, "
                "уборка хранилища и сводки — смотрите журнал сервера."))
        elif срок and возраст > срок * 2 * ЧАС:
            состояние, подсказка = "warn", (
                f"Работа отстаёт: срок — раз в {срок:g} ч, а последний заход "
                f"был {_возраст(возраст)}. Служебный цикл встал или падает "
                f"на каждом заходе — смотрите журнал сервера.")
        else:
            состояние, подсказка = "ok", ""
        проверки.append(_проверка(
            имя, название, состояние,
            ("выключено" if not включено else _когда(отметка)),
            подсказка, key=ключ, last_at=отметка, every_hours=срок,
            enabled=включено))

    срок_хранения = int(_число(settings.get("result_retention_days"), 30))
    проверки.append(_проверка(
        "retention", "Срок хранения результатов",
        "warn" if срок_хранения <= 0 else "ok",
        f"{срок_хранения} дн" if срок_хранения > 0 else "не ограничен",
        "Результаты не удаляются никогда: архив и каталог результатов "
        "растут без предела. Задайте result_retention_days."
        if срок_хранения <= 0 else "",
        days=срок_хранения))

    беда = _первая_беда(проверки)
    отстающие = [п for п in проверки if п["state"] == "warn"]
    return {
        "value": ("всё по расписанию" if not отстающие else
                  f"отстают: {', '.join(п['title'].lower() for п in отстающие[:3])}"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"retention_days": срок_хранения,
                    "behind": len(отстающие)},
        "checks": проверки,
    }


