ДИСК_МАЛО_ГБ = 20.0
ДИСК_КРИТИЧНО_ГБ = 5.0

#: Оперативная память — тоже по `doctor.py`.
ПАМЯТЬ_МАЛО_ГБ = 16.0
ПАМЯТЬ_КРИТИЧНО_ГБ = 6.0

