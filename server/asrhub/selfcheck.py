def состояние(state: Any, *, глубоко: bool = False) -> dict[str, Any]:
    """Полный свод о сервере: разделы, их проверки и список неисправностей.

    `глубоко=False` — обычный опрос панели: только то, что читается из
    памяти, настроек и базы. `глубоко=True` добавляет проверку целостности
    базы, разбор станций, пробу сервера языковой модели, обход каталогов и
    попытку достучаться до внешних адресов — это секунды, а не миллисекунды.

    Падение одного раздела не должно уносить остальные: свод нужен именно
    тогда, когда что-то сломано, и «диагностика упала» — худший из
    возможных ответов. Поэтому каждый раздел выполняется в своём
    `try/except`, а споткнувшийся показывается как `fail` с текстом ошибки:
    это тоже неисправность, и прятать её незачем.
    """
    момент = time.time()
    разделы: list[dict[str, Any]] = []
    for ид, название, группа, зависит, проверка in РАЗДЕЛЫ:
        try:
            итог = проверка(state, глубоко)
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Раздел диагностики «%s» не собрался: %s", ид, exc)
            итог = {
                "state": "fail",
                "value": f"проверка прервалась: {exc}",
                "hint": "Сама диагностика этого раздела споткнулась — "
                        "смотрите журнал сервера. Остальные разделы в своде "
                        "посчитаны.",
                "checks": [_проверка(
                    "selfcheck", "Проверка раздела", "fail",
                    f"{type(exc).__name__}: {exc}",
                    "Ошибка внутри самой диагностики. Остальные разделы "
                    "посчитаны и достоверны.")],
            }
        разделы.append(_раздел(ид, название, группа, зависит, итог))

    проблемы: list[dict[str, Any]] = []
    for раздел in разделы:
        for пункт in раздел["checks"]:
            if _ВЕС.get(пункт.get("state", "ok"), 0) <= 0:
                continue
            проблемы.append({
                "id": пункт["id"],
                "component": раздел["id"],
                "component_title": раздел["title"],
                "title": пункт["title"],
                "state": пункт["state"],
                "value": пункт.get("value", ""),
                "hint": пункт.get("hint", ""),
                "at": момент,
            })
    # Сначала поломки, потом предупреждения, внутри — в порядке разделов:
    # список читают сверху вниз, и первым должно стоять то, из-за чего
    # сервер не работает, а не то, что работает не лучшим образом.
    проблемы.sort(key=lambda п: -_ВЕС.get(п["state"], 0))

    сводка = {"ok": 0, "warn": 0, "fail": 0, "off": 0}
    for раздел in разделы:
        сводка[раздел["state"]] = сводка.get(раздел["state"], 0) + 1
    общее = ("fail" if сводка["fail"] else
             "warn" if сводка["warn"] else "ok")
    return {
        "at": момент,
        "deep": bool(глубоко),
        "state": общее,
        "summary": сводка,
        "components": разделы,
        "problems": проблемы,
    }


