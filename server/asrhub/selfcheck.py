def _проверка(id: str, title: str, state: str, value: str = "",       # noqa: A002
              hint: str = "", **metrics: Any) -> dict[str, Any]:
    """Одна проверка. Поля те же, что у разбора телефонии, — панель одна."""
    return {"id": id, "title": title, "state": state, "value": value,
            "hint": hint, "metrics": metrics}


def _худшее(состояния: Any) -> str:
    """Самое плохое из состояний. Пусто — значит «выключено»."""
    худшее = "off"
    for состояние in состояния:
        if _ВЕС.get(состояние, 0) > _ВЕС.get(худшее, 0):
            худшее = состояние
        elif состояние == "ok" and худшее == "off":
            худшее = "ok"
    return худшее


def _возраст(секунды: float | None) -> str:
    """Человеческая запись возраста: «14 мин назад», «3 дн назад»."""
    if секунды is None or секунды < 0:
        return "неизвестно"
    if секунды < 90:
        return f"{int(секунды)} с назад"
    if секунды < 5400:
        return f"{int(секунды // 60)} мин назад"
    if секунды < 172800:
        return f"{секунды / 3600:.1f} ч назад"
    return f"{int(секунды // 86400)} дн назад"


def _длительность(секунды: Any) -> str:
    """Сколько времени прошло: «18 мин», «3.5 ч», «6 дн».

    Отдельно от `_возраст`: тот отвечает на «когда это было», а здесь
    нужно «сколько это длится», и отрезать у первого слово «назад» —
    приём, который однажды отрежет полстроки у слова «неизвестно».
    """
    try:
        значение = max(0.0, float(секунды or 0))
    except (TypeError, ValueError):
        return "неизвестно"
    if значение < 60:
        return f"{int(значение)} с"
    if значение < 3600:
        return f"{int(значение // 60)} мин"
    if значение < 172800:
        return f"{значение / 3600:.1f} ч"
    return f"{int(значение // 86400)} дн"


def _когда(момент: Any) -> str:
    """Возраст отметки времени, устойчивый к тому, что в ней лежит.

    Отметки приходят из `kv`, из настроек и из ответов станций: там
    встречается и число, и строка с числом, и `None`, и мусор после
    ручной правки базы. Падать на этом диагностика не имеет права.
    """
    try:
        значение = float(момент or 0)
    except (TypeError, ValueError):
        return "неизвестно"
    if значение <= 0:
        return "никогда"
    return _возраст(time.time() - значение)


def _секунд_назад(момент: Any) -> float | None:
    """Сколько прошло с отметки. None — отметки нет или она не число."""
    try:
        значение = float(момент or 0)
    except (TypeError, ValueError):
        return None
    if значение <= 0:
        return None
    return max(0.0, time.time() - значение)


def _объём(байт: Any) -> str:
    """Размер словами: «412 МБ», «12.4 ГБ»."""
    try:
        число = float(байт or 0)
    except (TypeError, ValueError):
        return "неизвестно"
    if число >= 1024 ** 3:
        return f"{число / 1024 ** 3:.1f} ГБ"
    if число >= 1024 ** 2:
        return f"{число / 1024 ** 2:.0f} МБ"
    if число >= 1024:
        return f"{число / 1024:.0f} КБ"
    return f"{int(число)} Б"


def _размер_каталога(путь: Path | None) -> tuple[int, int, bool]:
    """Размер каталога: байты, файлы и признак «обход не закончен».

    Свой обход, а не `model_files.directory_size`: тот считает каталог
    одной модели и обходит его целиком, а здесь каталог результатов, в
    котором на живом сервере лежат сотни тысяч файлов. Полный обход такого
    каталога — секунды на каждый опрос панели; поэтому обход ограничен, и
    ответ честно помечается неполным, вместо того чтобы показывать
    заниженный размер как точный.
    """
    if путь is None:
        return 0, 0, True
    всего = файлов = 0
    полностью = True
    try:
        стек = [путь]
        while стек:
            текущий = стек.pop()
            with os.scandir(текущий) as записи:
                for запись in записи:
                    try:
                        if запись.is_dir(follow_symlinks=False):
                            стек.append(Path(запись.path))
                            continue
                        if запись.is_file(follow_symlinks=False):
                            всего += запись.stat(follow_symlinks=False).st_size
                            файлов += 1
                    except OSError:
                        continue
                    if файлов >= ПРЕДЕЛ_ОБХОДА:
                        return всего, файлов, False
    except (OSError, ValueError):
        полностью = False
    return всего, файлов, полностью


def _свободно(путь: Any) -> tuple[float, float]:
    """Свободно и всего в байтах по пути. Нули — измерить не удалось."""
    try:
        место = shutil.disk_usage(str(путь))
    except (OSError, ValueError, TypeError):
        return 0.0, 0.0
    return float(место.free), float(место.total)


def _число(значение: Any, по_умолчанию: float = 0.0) -> float:
    """Число из настройки. Настройки правят руками, и там бывает всякое."""
    try:
        return float(значение)
    except (TypeError, ValueError):
        return по_умолчанию


#: Свод по копиям, посчитанный недавно: {ключ каталога: (когда, свод)}.
_КЕШ_КОПИЙ: dict[str, tuple[float, dict[str, Any]]] = {}

#: На сколько его хватает. Свод по копиям открывает каждый архив, чтобы
#: прочитать опись; на десятке копий это десяток распаковок. К нему в
#: одном заходе обращаются два раздела — «База данных» и «Копии», — а сам
#: заход панель повторяет каждые несколько секунд: без короткой памяти
#: диагностика читала бы каталог копий целиком по нескольку раз в секунду.
_КЕШ_КОПИЙ_СРОК_С = 5.0


def _свод_копий(settings: Any) -> dict[str, Any]:
    """Состояние резервного копирования с памятью на несколько секунд.

    Ошибку не пропускаем наружу: каталог копий может быть на отвалившемся
    сетевом диске, и раздел «База данных» не должен из-за этого пропадать
    вместе с разделом «Копии».
    """
    from . import backup as резерв  # noqa: PLC0415

    ключ = str(резерв.каталог(settings))
    было = _КЕШ_КОПИЙ.get(ключ)
    if было and time.time() - было[0] < _КЕШ_КОПИЙ_СРОК_С:
        return было[1]
    свод = резерв.свод(settings)
    _КЕШ_КОПИЙ[ключ] = (time.time(), свод)
    # Каталог копий задаётся настройкой и может меняться на ходу; без
    # ограничения словарь копил бы по записи на каждое значение.
    if len(_КЕШ_КОПИЙ) > 8:
        for старый in sorted(_КЕШ_КОПИЙ, key=lambda к: _КЕШ_КОПИЙ[к][0])[:-4]:
            _КЕШ_КОПИЙ.pop(старый, None)
    return свод


def _раздел(id: str, title: str, group: str,                          # noqa: A002
            depends_on: tuple[str, ...], итог: dict[str, Any]) -> dict[str, Any]:
    """Собирает раздел из того, что вернула его проверка.

    Состояние раздела — худшее из его проверок, если проверка сама не
    сказала иначе: «выключено» умеет сказать только она (выключенная
    телефония без станций и телефония со сломанной станцией внешне дают
    одинаково пустой список проверок).
    """
    проверки = list(итог.get("checks") or [])
    состояние = итог.get("state") or _худшее(п.get("state", "ok") for п in проверки)
    return {
        "id": id, "title": title, "group": group, "state": состояние,
        "value": str(итог.get("value") or ""),
        "hint": str(итог.get("hint") or ""),
        "metrics": dict(итог.get("metrics") or {}),
        "depends_on": list(depends_on),
        "checks": проверки,
    }


def _первая_беда(проверки: list[dict[str, Any]]) -> dict[str, Any] | None:
    """Худшая из проверок — из неё берётся короткий итог раздела."""
    плохие = sorted(проверки, key=lambda п: -_ВЕС.get(п.get("state", "ok"), 0))
    if плохие and _ВЕС.get(плохие[0].get("state", "ok"), 0) > 0:
        return плохие[0]
    return None


