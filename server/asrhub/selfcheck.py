# 3. База данных
# ---------------------------------------------------------------------------

def _база(state: Any, глубоко: bool) -> dict[str, Any]:
    """Размер, содержимое, версия схемы, режим журнала, копия."""
    from .db import SCHEMA_VERSION  # noqa: PLC0415

    db = state.db
    проверки: list[dict[str, Any]] = []
    путь = Path(getattr(db, "path", "") or "")

    размер = 0
    try:
        размер = путь.stat().st_size if путь.exists() else 0
    except OSError as exc:
        log.debug("Размер базы не прочитан: %s", exc)

    # Счётчики — по одному запросу на таблицу. COUNT(*) в SQLite обходит
    # указатель, а не таблицу, и на архиве в сотни тысяч строк это доли
    # миллисекунды; отдельные «сводки» тут были бы лишней сущностью.
    счётчики: dict[str, int] = {}
    for ключ, таблица in (("jobs", "jobs"), ("segments", "segments"),
                          ("calls", "calls"), ("content", "content"),
                          ("events", "events")):
        try:
            строка = db.query_one(f"SELECT COUNT(*) AS n FROM {таблица}")
            счётчики[ключ] = int((строка or {"n": 0})["n"] or 0)
        except Exception as exc:                                      # noqa: BLE001
            # Минус один, а не ноль: «строк не прочитали» и «строк нет» —
            # разные ответы, и подменять первый вторым нельзя. Пустой архив
            # и нечитаемая таблица выглядели бы одинаково, а лечатся они
            # совсем по-разному.
            log.debug("Счётчик таблицы %s не прочитан: %s", таблица, exc)
            счётчики[ключ] = -1

    def показ(ключ: str) -> str:
        значение = счётчики.get(ключ, -1)
        return "?" if значение < 0 else str(значение)

    нечитаемых = [к for к, з in счётчики.items() if з < 0]
    проверки.append(_проверка(
        "size", "Файл базы",
        "fail" if нечитаемых else ("ok" if размер else "warn"),
        f"{_объём(размер)}, заданий {показ('jobs')}, "
        f"реплик {показ('segments')}, звонков {показ('calls')}, "
        f"записей разбора {показ('content')}",
        "Часть таблиц не читается — база повреждена или недоступна. "
        "Остановите сервер и восстановите её из копии." if нечитаемых else
        ("" if размер else
         "Файл базы пуст или не найден — сервер только что создал её заново. "
         "Если архив был, проверьте, туда ли указывает каталог данных."),
        bytes=размер, path=str(путь), **счётчики))

    # Версия схемы. Номер поднимают руками, и забыть его — обычное дело:
    # тогда колонка не появляется, а каждый запрос к таблице падает на
    # боевом сервере с «no such column». Обратный случай не лучше: база от
    # будущей версии сервера открывается, но часть колонок в ней лишняя, и
    # починить это откатом нельзя.
    try:
        строка = db.query_one("PRAGMA user_version")
        версия = int((строка or [0])[0] or 0)
    except Exception as exc:                                          # noqa: BLE001
        версия = -1
        log.debug("Версия схемы не прочитана: %s", exc)
    if версия == SCHEMA_VERSION:
        проверки.append(_проверка("schema", "Версия схемы", "ok",
                                  f"{версия}", schema=версия,
                                  expected=SCHEMA_VERSION))
    elif версия > SCHEMA_VERSION:
        проверки.append(_проверка(
            "schema", "Версия схемы", "fail",
            f"в базе {версия}, сервер знает {SCHEMA_VERSION}",
            "Базу открывала более новая версия сервера. Откат на старую "
            "версию не поддерживается: поставьте прежнюю сборку сервера "
            "или восстановите базу из копии, снятой этой версией.",
            schema=версия, expected=SCHEMA_VERSION))
    else:
        проверки.append(_проверка(
            "schema", "Версия схемы", "warn",
            f"в базе {версия}, сервер знает {SCHEMA_VERSION}",
            "Миграция не доведена до конца. Перезапустите сервер — он "
            "доводит схему при открытии базы; если состояние осталось, "
            "смотрите журнал запуска.",
            schema=версия, expected=SCHEMA_VERSION))

    # Режим журнала. Вне WAL читатели блокируют писателя: интерфейс,
    # опрашивающий состояние, начинает мешать очереди писать результаты —
    # и это выглядит как «сервер тормозит», а не как режим журнала.
    try:
        строка = db.query_one("PRAGMA journal_mode")
        режим = str((строка or [""])[0] or "").lower()
    except Exception as exc:                                          # noqa: BLE001
        режим = ""
        log.debug("Режим журнала не прочитан: %s", exc)
    проверки.append(_проверка(
        "journal", "Режим журнала", "ok" if режим == "wal" else "warn",
        режим or "неизвестен",
        "" if режим == "wal" else
        "Сервер просит WAL при каждом открытии базы. Отказ обычно значит, "
        "что база лежит на сетевой файловой системе (NFS, SMB): держите её "
        "на локальном диске, иначе возможны и блокировки, и порча.",
        mode=режим))

    wal = путь.with_name(путь.name + "-wal") if путь.name else None
    if wal is not None:
        try:
            размер_wal = wal.stat().st_size if wal.exists() else 0
        except OSError:
            размер_wal = 0
        большой = размер_wal > WAL_ПРЕДЕЛ_БАЙТ
        проверки.append(_проверка(
            "wal", "Размер журнала WAL", "warn" if большой else "ok",
            _объём(размер_wal),
            "Журнал не сворачивается: контрольная точка не проходит, пока "
            "открыт долгий читатель. Место он занимает рядом с базой, а при "
            "аварии восстановление идёт по нему же. Перезапуск сервера "
            "сворачивает журнал." if большой else "",
            bytes=размер_wal))

    # Целостность — только по просьбе. `quick_check` читает всю базу: на
    # архиве в гигабайты это секунды, а панель опрашивает свод постоянно.
    if глубоко:
        try:
            строки = db.query("PRAGMA quick_check(1)")
            ответ = str(строки[0][0]).lower() if строки else ""
        except Exception as exc:                                      # noqa: BLE001
            ответ = f"проверка не прошла: {exc}"
        цела = ответ == "ok"
        проверки.append(_проверка(
            "integrity", "Быстрая проверка целостности",
            "ok" if цела else "fail",
            "повреждений не найдено" if цела else ответ[:200],
            "" if цела else
            "База повреждена. Остановите сервер и восстановите её из "
            "резервной копии: раздел «Копии» или POST /api/backup/restore. "
            "Работа на повреждённой базе теряет данные дальше.",
            result=ответ[:200]))

    # Последняя копия — одной строкой, рядом с размером базы: человек,
    # смотрящий на «база выросла до 12 ГБ», тем же взглядом должен видеть,
    # есть ли с неё копия. Приговор выносит раздел «Копии» — он разбирает и
    # расписание, и срок хранения, и место под следующую копию. Здесь
    # состояние намеренно не поднимается выше «ok»: одна и та же беда,
    # попавшая в список проблем дважды, читается как две разные.
    try:
        свод_копий = _свод_копий(state.settings)
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Свод копий не собран: %s", exc)
        свод_копий = {}
    последняя = (свод_копий or {}).get("last") or {}
    if последняя:
        проверки.append(_проверка(
            "backup", "Последняя копия", "ok",
            f"{_когда(последняя.get('created_at'))}, {_объём(последняя.get('size'))}",
            created_at=последняя.get("created_at"),
            kind=последняя.get("kind"), bytes=последняя.get("size")))
    else:
        проверки.append(_проверка(
            "backup", "Последняя копия", "off", "копий нет",
            "", created_at=None))

    беда = _первая_беда(проверки)
    return {
        "value": f"{_объём(размер)}, заданий {счётчики.get('jobs', 0)}, "
                 f"звонков {счётчики.get('calls', 0)}",
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"bytes": размер, "schema": версия,
                    "expected_schema": SCHEMA_VERSION,
                    "journal_mode": режим, "path": str(путь), **счётчики},
        "checks": проверки,
    }


