def _движки(state: Any, глубоко: bool) -> dict[str, Any]:
    """Какие движки установлены и доступен ли выбранный."""
    from .engines import engine_status  # noqa: PLC0415

    список = engine_status()
    доступные = [д for д in список if д.get("available")]
    выбран = str(state.settings.get("engine") or "").strip()
    проверки: list[dict[str, Any]] = []

    свой = next((д for д in список if д.get("id") == выбран), None)
    if свой is None:
        проверки.append(_проверка(
            "selected", "Выбранный движок", "fail",
            f"«{выбран or 'не задан'}» серверу неизвестен",
            "Такого движка нет. Доступные: "
            + ", ".join(sorted(д["id"] for д in список))
            + ". Смените значение параметра engine.",
            engine=выбран))
    elif not свой.get("available"):
        проверки.append(_проверка(
            "selected", "Выбранный движок", "fail",
            f"{свой.get('name') or выбран} — не установлен: "
            f"{str(свой.get('reason') or '')[:120]}",
            f"Каждое задание будет падать на загрузке модели. Установить: "
            f"bash scripts/models.sh install-engine {выбран}",
            engine=выбран, reason=свой.get("reason")))
    else:
        проверки.append(_проверка(
            "selected", "Выбранный движок", "ok",
            str(свой.get("name") or выбран), engine=выбран))

    проверки.append(_проверка(
        "installed", "Установлено движков",
        "ok" if доступные else "fail",
        f"{len(доступные)} из {len(список)}: "
        + (", ".join(д["id"] for д in доступные) or "ни одного"),
        "" if доступные else
        "Не установлен ни один движок распознавания — сервер принимает "
        "задания и падает на каждом. Установка: bash scripts/models.sh "
        "install-engine faster_whisper",
        available=[д["id"] for д in доступные],
        missing=[д["id"] for д in список if not д.get("available")]))

    беда = _первая_беда(проверки)
    return {
        "value": f"выбран {выбран or 'не задан'}, "
                 f"установлено {len(доступные)} из {len(список)}",
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"engine": выбран, "available": len(доступные),
                    "total": len(список)},
        "checks": проверки,
    }


