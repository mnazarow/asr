"""Автодиагностика всей системы: один свод вместо обхода десяти разделов.

Сервер знает о себе всё — и рассказывает это по частям. Свободное место
видно в «Оборудовании», очередь с ошибками — в «Заданиях», не поднявшийся
поток станции — в «АТС», неснятая резервная копия — в «Копиях», а то, что
выбранный движок вообще не установлен, не видно нигде, кроме журнала
запуска, который никто не открывает. Человек узнаёт о поломке не от
сервера, а от того, что работа встала: записи не приезжают вторую неделю,
разбор не считается, места на диске нет.

Этот модуль обходит всё сразу и отвечает одинаково про каждую часть: что
это, в каком оно состоянии, что именно видно и что делать, если плохо.
Дальше по этому своду рисуется схема системы (`depends_on`) и список
неисправностей (`problems`), а `записать_проблемы` кладёт изменения в
журнал событий — чтобы «когда это началось» можно было ответить, не
вспоминая.

Правила, которые тут важнее удобства:

* **Ничего не меняет.** Разбор читает: файлы, базу, настройки. Он не
  ставит задания, не двигает позиции чтения, не трогает копии.
* **Отвечает всегда.** Каждая проверка обёрнута в `try/except`, каждый
  раздел — тоже. Диагностика, падающая вместе с тем, что она
  диагностирует, бесполезна ровно тогда, когда нужна.
* **Дорогое — только по просьбе.** При `глубоко=False` не делается ничего,
  что ходит в сеть или обходит диск целиком: свод опрашивается панелью раз
  в несколько секунд, и полная проверка на каждый опрос легла бы на сервер
  тяжелее, чем сама работа.

Состояния — те же четыре слова, что и в разборе телефонии
(`telephony/diagnose.py`), плюс «выключено»:

``ok``    работает;
``warn``  работает, но что-то не так;
``fail``  не работает;
``off``   выключено намеренно — это не поломка и в список проблем не идёт.
"""
