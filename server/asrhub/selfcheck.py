def _достучаться(адрес: str) -> tuple[bool, str]:
    """Открыт ли порт по адресу. Возвращает «дошли» и пояснение.

    Соединение, а не HTTP-запрос: по адресу обратного вызова стоит чужой
    приёмник (Slack, Teams, своя интеграция), и проверка, отправляющая
    туда запрос, доставляет пустое уведомление каждому, кто нажал
    «проверить». Открытый порт отвечает на вопрос «дотягиваемся ли мы
    отсюда» полностью, и при этом ничего не доставляет.
    """
    import socket  # noqa: PLC0415
    from urllib.parse import urlsplit  # noqa: PLC0415

    try:
        части = urlsplit(адрес)
        узел = части.hostname
        порт = части.port or (443 if части.scheme == "https" else 80)
        if not узел:
            return False, "адрес не разобран"
    except ValueError as exc:
        return False, f"адрес не разобран: {exc}"
    try:
        with socket.create_connection((узел, int(порт)), СВЯЗЬ_ТАЙМАУТ_С):
            return True, f"порт {порт} открыт"
    except OSError as exc:
        return False, f"{type(exc).__name__}: {exc}"


def _сеть(state: Any, глубоко: bool) -> dict[str, Any]:
    """Слушаемый адрес и доступность заданных внешних адресов."""
    settings = state.settings
    адрес = str(settings.get("server_host") or "")
    порт = int(_число(settings.get("server_port"), 0))
    вход = bool(settings.get("auth_enabled", True))
    проверки: list[dict[str, Any]] = []

    всем = адрес in ("0.0.0.0", "::", "")                             # noqa: S104
    открыт_всем = всем and not вход
    проверки.append(_проверка(
        "listen", "Слушаемый адрес",
        "fail" if открыт_всем else "ok",
        (f"порт {порт}, " + ("все адреса" if всем else "один адрес"))
        + (" — БЕЗ АУТЕНТИФИКАЦИИ" if открыт_всем else ""),
        "Сервер слушает все сетевые адреса и не спрашивает ключ: любой, кто "
        "дотянулся до порта, работает от имени администратора. Включите "
        "auth_enabled или привяжите сервер к 127.0.0.1."
        if открыт_всем else "",
        host=адрес, listen=f"{адрес}:{порт}", port=порт, auth=вход))

    источники = str(settings.get("cors_origins") or "")
    if источники.strip() == "*":
        проверки.append(_проверка(
            "cors", "Разрешённые источники", "warn", "разрешены любые (*)",
            "Любая страница в браузере может обращаться к серверу от имени "
            "вошедшего человека. Перечислите свои адреса в cors_origins.",
            origins=источники))

    for ключ, название in (("webhook_url", "Адрес уведомлений"),
                           ("digest_url", "Адрес сводки")):
        значение = str(settings.get(ключ) or "").strip()
        if not значение:
            проверки.append(_проверка(ключ, название, "off", "не задан"))
            continue
        if not глубоко:
            проверки.append(_проверка(
                ключ, название, "ok", "задан, доступность не проверялась",
                "", url=значение))
            continue
        дошли, пояснение = _достучаться(значение)
        проверки.append(_проверка(
            ключ, название, "ok" if дошли else "warn", пояснение,
            "Сервер не дотягивается до этого адреса: уведомления и сводки "
            "уходят в никуда. Проверьте адрес и правила исходящих "
            "соединений." if not дошли else "",
            url=значение, reachable=дошли))

    беда = _первая_беда(проверки)
    return {
        "value": f"порт {порт}, " + ("все адреса" if всем else адрес),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"host": адрес, "port": порт, "auth": вход},
        "checks": проверки,
    }


