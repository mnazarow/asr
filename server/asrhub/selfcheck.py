def _сервер(state: Any, глубоко: bool) -> dict[str, Any]:
    """Версия, время работы, настройки, вход."""
    settings = state.settings
    проверки: list[dict[str, Any]] = []

    работает = max(0.0, time.time() - float(getattr(state, "started_at", 0) or 0))
    проверки.append(_проверка(
        "version", "Версия и время работы", "ok",
        f"{state.version}, в работе {_длительность(работает)}",
        version=str(state.version), uptime_s=round(работает, 1)))

    # Сервер поднимается даже с негодной строкой в config.yaml: берёт
    # умолчание и откладывает разбирательство. Если не сказать об этом
    # здесь, «сервер работает» и «настройки применились» станут одним
    # утверждением — а это разные вещи, и именно на их разнице держатся
    # жалобы вида «я поменял модель, а он распознаёт прежней».
    проблемы_настроек = list(getattr(settings, "problems", []) or [])
    if проблемы_настроек:
        проверки.append(_проверка(
            "config", "Значения в конфигурации", "fail",
            f"не принято значений: {len(проблемы_настроек)} — "
            + "; ".join(проблемы_настроек[:3]),
            "Сервер работает на значениях по умолчанию вместо ваших. "
            "Исправьте записи в файле конфигурации и перезапустите сервер.",
            problems=проблемы_настроек[:20], count=len(проблемы_настроек)))
    else:
        проверки.append(_проверка("config", "Значения в конфигурации", "ok",
                                  "приняты все"))

    вход = bool(settings.get("auth_enabled", True))
    ключей = len(getattr(settings, "api_keys", {}) or {})
    учёток = 0
    пароль_по_умолчанию = False
    try:
        accounts = getattr(state, "accounts", None)
        if accounts is not None:
            учёток = int(accounts.count())
            пароль_по_умолчанию = bool(accounts.uses_default_password())
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Учётные записи не прочитаны: %s", exc)

    проверки.append(_проверка(
        "auth", "Аутентификация", "ok" if вход else "warn",
        f"включена, ключей {ключей}, учётных записей {учёток}" if вход
        else f"ОТКЛЮЧЕНА, ключей {ключей}, учётных записей {учёток}",
        "" if вход else
        "Любой, кто дотянулся до порта, работает от имени администратора: "
        "может забрать чужие расшифровки, сменить настройки и удалить архив. "
        "На сервере, доступном по сети, аутентификация обязательна.",
        enabled=вход, keys=ключей, accounts=учёток))

    # Пароль по умолчанию живёт до первой смены и переживает всё остальное:
    # он заводится при первом запуске, о нём предупреждает журнал — и в
    # журнал никто не смотрит. Пара admin/admin123 общеизвестна.
    проверки.append(_проверка(
        "password", "Пароль администратора",
        "fail" if пароль_по_умолчанию else "ok",
        "стоит пароль по умолчанию" if пароль_по_умолчанию else "сменён",
        "Пароль по умолчанию известен всем, кто читал документацию. "
        "Смените его в разделе «Доступ» или командой: "
        "python -m asrhub --set-password admin" if пароль_по_умолчанию else "",
        default_password=пароль_по_умолчанию))

    файл = getattr(settings, "config_file", None)
    проверки.append(_проверка(
        "config_file", "Файл конфигурации", "ok" if файл else "warn",
        "используется" if файл else "не используется, значения подобраны сами",
        "" if файл else
        "Настройки живут только в памяти процесса и не переживут "
        "перезапуск, если их не сохранить: POST /api/settings/save.",
        config_file=str(файл) if файл else ""))

    беда = _первая_беда(проверки)
    # Адрес и порт — в показателях раздела, а не отдельной проверкой:
    # приговор им выносит раздел «Сеть» (открытый порт без аутентификации —
    # это его забота), а здесь они нужны для шапки, где человек сверяет,
    # тот ли сервер он вообще смотрит.
    return {
        "value": f"версия {state.version}, в работе {_длительность(работает)}"
                 + (f", {len(проблемы_настроек)} проблем в конфигурации"
                    if проблемы_настроек else ""),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"version": str(state.version), "uptime_s": round(работает, 1),
                    "started_at": getattr(state, "started_at", None),
                    "auth_enabled": вход, "keys": ключей, "accounts": учёток,
                    "config_problems": len(проблемы_настроек),
                    "port": int(_число(settings.get("server_port"), 0)),
                    "listen": f"{settings.get('server_host')}:"
                              f"{settings.get('server_port')}"},
        "checks": проверки,
    }


# ---------------------------------------------------------------------------
# 2. Диск
# ---------------------------------------------------------------------------

def _диск(state: Any, глубоко: bool) -> dict[str, Any]:
    """Свободное место и на что оно уходит."""
    settings = state.settings
    paths = getattr(settings, "paths", None)
    проверки: list[dict[str, Any]] = []
    if paths is None:
        return {"state": "fail", "value": "каталог данных неизвестен",
                "checks": [_проверка("paths", "Каталог данных", "fail",
                                     "настройки без раскладки каталогов",
                                     "Сервер поднят в обход обычной загрузки "
                                     "настроек — перезапустите его штатно.")]}

    # Свободное место меряем сами, а не берём из `hardware.detect`: тот
    # кеширован на весь процесс (`lru_cache`), и панель показывала бы
    # значение на момент запуска сервера — то есть «свободно 40 ГБ» на
    # забитом под завязку диске.
    свободно, всего = _свободно(paths.data)
    свободно_гб = свободно / 1024 ** 3
    if not всего:
        проверки.append(_проверка(
            "free", "Свободное место", "warn", "измерить не удалось",
            "Каталог данных недоступен — проверьте, смонтирован ли том и "
            "видит ли его пользователь, от которого работает сервер."))
    else:
        состояние = ("fail" if свободно_гб < ДИСК_КРИТИЧНО_ГБ else
                     "warn" if свободно_гб < ДИСК_МАЛО_ГБ else "ok")
        проверки.append(_проверка(
            "free", "Свободное место", состояние,
            f"свободно {_объём(свободно)} из {_объём(всего)}",
            "" if состояние == "ok" else
            "Заполнившийся диск повреждает и базу, и уже посчитанные "
            "результаты. Освободите место: POST /api/maintenance/cleanup "
            "убирает старые задания, ненужные модели удаляются в разделе "
            "«Модели». Полный набор моделей занимает свыше 100 ГБ.",
            free_bytes=int(свободно), total_bytes=int(всего),
            free_gb=round(свободно_гб, 2), path=str(paths.data)))

    # Порог приёма заданий — отдельная проверка: при его срабатывании
    # сервер отвечает отказом на каждую загрузку, и выглядит это как
    # поломка загрузки, а не как кончившееся место.
    порог = _число(settings.get("disk_min_free_gb"), 0.0)
    if порог > 0:
        не_принимает = bool(всего) and свободно_гб < порог
        проверки.append(_проверка(
            "limit", "Порог приёма заданий", "fail" if не_принимает else "ok",
            f"{порог:g} ГБ" + (" — новые задания НЕ принимаются" if не_принимает else ""),
            "Сервер отказывает в приёме файлов, пока места меньше порога. "
            "Освободите место или уменьшите disk_min_free_gb." if не_принимает else "",
            limit_gb=порог, blocked=не_принимает))

    # Раскладка по каталогам — только при глубокой проверке: обход каталога
    # результатов на живом сервере это десятки тысяч файлов, и делать его
    # на каждый опрос панели нельзя.
    if глубоко:
        разложено: dict[str, Any] = {}
        неполно = []
        for имя, подпись, путь in (
                ("uploads", "загрузки", paths.uploads),
                ("results", "результаты", paths.results),
                ("models", "модели", Path(str(settings.get("models_dir")
                                              or paths.models))),
                ("logs", "журналы", paths.logs)):
            байт, файлов, полностью = _размер_каталога(путь)
            разложено[имя] = {"bytes": байт, "files": файлов, "complete": полностью}
            if not полностью:
                неполно.append(подпись)
        занято = sum(int(з["bytes"]) for з in разложено.values())
        проверки.append(_проверка(
            "usage", "На что уходит место", "ok",
            ", ".join(f"{подпись} {_объём(разложено[имя]['bytes'])}"
                      for имя, подпись in (("uploads", "загрузки"),
                                           ("results", "результаты"),
                                           ("models", "модели"),
                                           ("logs", "журналы")))
            + (f" (посчитано не до конца: {', '.join(неполно)})" if неполно else ""),
            "", used_bytes=занято, **разложено))

    беда = _первая_беда(проверки)
    return {
        "value": (f"свободно {_объём(свободно)}" if всего else "место не измеряется"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"free_bytes": int(свободно), "total_bytes": int(всего),
                    "free_gb": round(свободно_гб, 2), "path": str(paths.data)},
        "checks": проверки,
    }


