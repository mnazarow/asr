def _копии(state: Any, глубоко: bool) -> dict[str, Any]:
    """Включены ли копии, когда последняя, сколько их и хватит ли места."""
    свод = _свод_копий(state.settings)
    включены = bool(свод.get("enabled"))
    копии = list(свод.get("items") or [])
    последняя = свод.get("last") or {}
    проверки: list[dict[str, Any]] = []

    проверки.append(_проверка(
        "enabled", "Копирование по расписанию",
        "ok" if включены else "warn",
        (f"включено, {свод.get('time')}, вид «{свод.get('kind')}»"
         if включены else "выключено"),
        "" if включены else
        "Копии не снимаются. Восстановить настройки, станции, словари и "
        "архив после сбоя диска будет не из чего.",
        enabled=включены, time=свод.get("time"), kind=свод.get("kind"),
        interval_hours=свод.get("interval_hours")))

    # Срок, после которого копия считается несвежей. Если задан интервал в
    # часах — берём двойной интервал: один пропуск бывает (сервер
    # перезагружали), два подряд — уже расписание не работает.
    интервал = _число(свод.get("interval_hours"), 0.0)
    предел = (интервал * 2 * ЧАС) if интервал > 0 else 2 * СУТКИ
    возраст = _секунд_назад(последняя.get("created_at")) if последняя else None
    if not копии:
        проверки.append(_проверка(
            "last", "Последняя копия", "fail" if включены else "warn",
            "копий нет ни одной",
            "Снимите первую копию вручную (раздел «Копии» или POST "
            "/api/backup) и убедитесь, что каталог копий доступен на запись: "
            "иначе расписание молча не сработает и во второй раз.",
            count=0))
    elif возраст is not None and возраст > предел:
        проверки.append(_проверка(
            "last", "Последняя копия", "warn",
            f"{_когда(последняя.get('created_at'))}, "
            f"{_объём(последняя.get('size'))}",
            "Копия старше, чем должна быть по расписанию: заход либо не "
            "случается, либо падает. Смотрите события «backup» в журнале.",
            created_at=последняя.get("created_at"),
            age_s=round(возраст, 1), limit_s=предел))
    else:
        проверки.append(_проверка(
            "last", "Последняя копия", "ok",
            f"{_когда(последняя.get('created_at'))}, "
            f"{_объём(последняя.get('size'))}, вид «{последняя.get('kind')}»",
            created_at=последняя.get("created_at"),
            bytes=последняя.get("size"), kind=последняя.get("kind")))

    занято = int(_число(свод.get("bytes")))
    свободно = int(_число(свод.get("free_bytes")))
    самая_большая = max((int(_число(к.get("size"))) for к in копии), default=0)
    не_влезет = bool(самая_большая) and свободно and свободно < самая_большая
    проверки.append(_проверка(
        "storage", "Хранилище копий", "warn" if не_влезет else "ok",
        f"копий {len(копии)}, занято {_объём(занято)}, "
        f"свободно {_объём(свободно)}",
        "Свободного места меньше, чем весит одна копия: очередная не "
        "поместится. Уменьшите срок хранения (backup_keep_days), число "
        "копий (backup_keep) или укажите другой каталог."
        if не_влезет else "",
        count=len(копии), bytes=занято, free_bytes=свободно,
        largest=самая_большая, dir=str(свод.get("dir") or "")))

    # Срок хранения и число копий. Ноль в обоих — «держать всё»: это
    # документированное значение, но вместе они означают, что каталог
    # копий будет расти без предела, и однажды он и кончит диск.
    дней = int(_число(свод.get("keep_days")))
    штук = int(_число(свод.get("keep_count")))
    проверки.append(_проверка(
        "retention", "Срок хранения",
        "warn" if (not дней and not штук) else "ok",
        (f"дней {дней or '—'}, копий {штук or '—'}"),
        "Ни срока, ни числа копий не задано — старые копии не удаляются "
        "никогда и рано или поздно займут весь диск."
        if (not дней and not штук) else "",
        keep_days=дней, keep_count=штук))

    беда = _первая_беда(проверки)
    return {
        "value": (f"копий {len(копии)}, последняя "
                  f"{_когда(последняя.get('created_at'))}"
                  if копии else "копий нет"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"enabled": включены, "count": len(копии),
                    "bytes": занято, "free_bytes": свободно,
                    "last_at": последняя.get("created_at"),
                    "dir": str(свод.get("dir") or "")},
        "checks": проверки,
    }


