def _станция_в_проверке(станция: Any, живая: dict[str, Any],
                        глубоко: bool, разборы: dict[str, Any]) -> dict[str, Any]:
    """Одна станция: включена, работает ли поток, что было в последний заход.

    Путь источника проверяется всегда, даже при `глубоко=False`: это
    единственный `stat` на файл, а отвечает он на самую частую поломку —
    «журнал не там». Всё остальное (чтение хвоста журнала, поиск записей,
    разговор с AMI) делает `telephony/diagnose.py`, и его мы зовём только
    по просьбе: он ходит по диску и в сеть.
    """
    ид = str(станция.id)
    if not станция.enabled:
        return _проверка(f"station:{ид}", f"Станция «{станция.name}»", "off",
                         "выключена", "", station=ид, enabled=False)

    состояния = ["ok"]
    части: list[str] = []
    подсказки: list[str] = []
    метрики: dict[str, Any] = {"station": ид, "enabled": True,
                               "source": станция.source}

    работает = bool(живая.get("running"))
    части.append("поток работает" if работает else "поток НЕ запущен")
    if not работает:
        состояния.append("warn")
        подсказки.append("Поток забора не поднят: перезапустите сервер или "
                         "выключите и включите станцию.")
    метрики["running"] = работает

    # Источник на диске. «Файла нет» и «нет доступа на чтение» — две самые
    # частые причины «заход прошёл, новых звонков ноль», и обе выглядят
    # как исправная работа: заход честно отчитывается нулём.
    поле = "recordings_dir" if станция.source == "folder" else "cdr_file"
    if станция.source != "ami":
        путь = станция.путь(поле)
        метрики[поле] = str(путь) if путь else ""
        if путь is None:
            состояния.append("fail")
            части.append("путь к источнику не задан")
            подсказки.append(
                "Укажите файл журнала CDR (обычно Master.csv из cdr-csv) "
                "или каталог записей — без него забирать нечего."
                if поле == "cdr_file" else
                "Укажите каталог записей — без него забирать нечего.")
        elif not путь.exists():
            состояния.append("fail")
            части.append("источника нет на диске")
            подсказки.append(
                "Файл журнала или каталог записей не найден. Если сервер "
                "стоит отдельно от АТС, каталог нужно смонтировать или "
                "поставить на станцию агента (раздел «АТС» → «Агент»).")
        elif not os.access(путь, os.R_OK):
            состояния.append("fail")
            части.append("источник не читается")
            подсказки.append(
                "Нет прав на чтение источника: дайте их пользователю, от "
                "которого работает сервер.")
        else:
            изменён = None
            try:
                изменён = путь.stat().st_mtime
            except OSError:
                pass
            метрики["source_mtime"] = изменён
            if изменён and time.time() - изменён > СУТКИ:
                состояния.append("warn")
                части.append(f"источник не менялся {_когда(изменён)}")
                подсказки.append(
                    "Станция сутки ничего не дописала. Либо звонков не было, "
                    "либо журнал пишется не сюда — проверьте cdr.conf и "
                    "cdr_csv.conf на АТС.")

    свод_захода = dict(живая.get("last_scan") or {})
    последний = живая.get("last_run")
    if свод_захода or последний:
        поставлено = int(свод_захода.get("imported") or 0)
        увидено = int(свод_захода.get("seen") or 0)
        части.append(f"последний заход {_когда(последний)}: "
                     f"увидено {увидено}, поставлено {поставлено}")
        метрики["last_run"] = последний
        метрики["last_scan"] = свод_захода
        if увидено and not поставлено:
            состояния.append("warn")
            подсказки.append(
                "Звонки читаются, но ни один не дошёл до очереди: «нет "
                "записи» чинится каталогом и шаблоном имени, «короткий» и "
                "«без ответа» — порогами станции.")
    else:
        части.append("заходов ещё не было")

    ошибка = живая.get("last_error")
    if ошибка:
        состояния.append("warn")
        части.append(f"последняя ошибка: {str(ошибка)[:120]}")
        метрики["last_error"] = str(ошибка)[:400]

    # Полный разбор — только по просьбе и только если он уже посчитан
    # вызывающей стороной: звать его на каждую станцию внутри общего свода
    # значит ходить по диску и в сеть столько раз, сколько станций.
    разбор = разборы.get(ид) if глубоко else None
    if разбор:
        метрики["diagnosis"] = {"state": разбор.get("state"),
                                "verdict": разбор.get("verdict"),
                                "failed": разбор.get("failed"),
                                "warned": разбор.get("warned")}
        состояния.append(str(разбор.get("state") or "ok"))
        if разбор.get("verdict"):
            части.append(str(разбор["verdict"])[:200])

    return _проверка(f"station:{ид}", f"Станция «{станция.name}»",
                     _худшее(состояния), "; ".join(части),
                     " ".join(подсказки), **метрики)


def _телефония(state: Any, глубоко: bool) -> dict[str, Any]:
    """Станции, их заходы и агенты на них."""
    телефония = getattr(state, "telephony", None)
    if телефония is None:
        return {"state": "off", "value": "подсистема не поднята", "checks": []}

    включена = bool(телефония.enabled)
    станции = list(телефония.станции())
    живые: dict[str, dict[str, Any]] = {}
    try:
        свод = телефония.status(for_admin=True)
        живые = {str(с.get("id")): с for с in (свод.get("stations") or [])}
    except Exception as exc:                                          # noqa: BLE001
        log.warning("Состояние станций не прочитано: %s", exc)
        свод = {}

    разборы: dict[str, Any] = {}
    if глубоко and включена and станции:
        try:
            for разбор in телефония.диагностика():
                разборы[str(разбор.get("station"))] = разбор
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Разбор станций не выполнен: %s", exc)

    проверки: list[dict[str, Any]] = []
    if not включена:
        проверки.append(_проверка(
            "enabled", "Забор записей", "off", "выключен",
            "", enabled=False, stations=len(станции)))
    elif not станции:
        проверки.append(_проверка(
            "enabled", "Забор записей", "warn", "включён, но станций нет",
            "Забор включён, а ни одной станции не настроено — забирать "
            "неоткуда. Добавьте станцию в разделе «АТС».",
            enabled=True, stations=0))
    else:
        проверки.append(_проверка(
            "enabled", "Забор записей", "ok",
            f"включён, станций {len(станции)}, "
            f"в работе {int(свод.get('running') or 0)}",
            enabled=True, stations=len(станции),
            running=int(свод.get("running") or 0)))

    for станция in станции:
        try:
            проверки.append(_станция_в_проверке(
                станция, живые.get(str(станция.id)) or {}, глубоко, разборы))
        except Exception as exc:                                      # noqa: BLE001
            log.warning("Станция «%s» не разобрана: %s", станция.id, exc)
            проверки.append(_проверка(
                f"station:{станция.id}", f"Станция «{станция.name}»", "fail",
                f"разбор прервался: {exc}",
                "Смотрите журнал сервера: диагностика станции сама "
                "споткнулась, и это тоже неисправность."))

    # Агенты ставятся на станции, до которых сервер не дотягивается сам:
    # связь всегда начинает агент. Замолчавший агент — это не «тихо на
    # линии», а прекратившийся забор, и увидеть его больше негде.
    try:
        агенты = list(state.db.agent_list())
    except Exception as exc:                                          # noqa: BLE001
        log.debug("Список агентов не прочитан: %s", exc)
        агенты = []
    if агенты:
        молчат = [а for а in агенты
                  if (_секунд_назад(а.get("last_seen")) or АГЕНТ_МОЛЧИТ_С + 1)
                  > АГЕНТ_МОЛЧИТ_С]
        проверки.append(_проверка(
            "agents", "Агенты на станциях",
            "warn" if молчат else "ok",
            f"{len(агенты)} всего, прислали звонков "
            f"{sum(int(а.get('calls_sent') or 0) for а in агенты)}, "
            f"файлов {sum(int(а.get('files_sent') or 0) for а in агенты)}"
            + (f"; молчат больше суток: "
               f"{', '.join(str(а.get('id')) for а in молчат[:5])}"
               if молчат else ""),
            "Агент не выходил на связь больше суток: записи с этой станции "
            "не приезжают. Проверьте, работает ли служба агента на АТС и "
            "открыт ли доступ к серверу." if молчат else "",
            total=len(агенты), silent=len(молчат),
            items=[{"id": а.get("id"), "station": а.get("station"),
                    "last_seen": а.get("last_seen"),
                    "calls_sent": а.get("calls_sent"),
                    "files_sent": а.get("files_sent"),
                    "errors": а.get("errors")} for а in агенты[:20]]))

    архив = dict(свод.get("archive") or {})
    беда = _первая_беда(проверки)
    return {
        "state": "off" if (not включена and not станции) else None,
        "value": ("выключено" if not включена else
                  f"станций {len(станции)}, в работе "
                  f"{int(свод.get('running') or 0)}, звонков в архиве "
                  f"{int(архив.get('total') or 0)}"),
        "hint": (беда or {}).get("hint", ""),
        "metrics": {"enabled": включена, "stations": len(станции),
                    "running": int(свод.get("running") or 0),
                    "agents": len(агенты), "archive": архив},
        "checks": проверки,
    }


