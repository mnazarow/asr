def спрятать_пути(свод: dict[str, Any], settings: Any = None) -> dict[str, Any]:
    """Тот же свод, но без раскладки каталогов и адресов.

    Раскладка файловой системы и внутренние адреса — это разведка перед
    атакой, а не сведения, нужные оператору для работы: соседние
    GET /api/system и GET /api/settings прячут `paths` от неадминистратора
    ровно с этой мыслью, и диагностика, отдающая путь к базе и адрес
    приёмника любому ключу, сводила бы ту защиту на нет.

    Работа в два приёма. Сначала выбрасываются метрики с известными
    именами (`path`, `url`, `dir` и прочие из `ЗАКРЫТЫЕ_КЛЮЧИ`). Потом —
    подстраховка: в оставшихся строках маскируется всё, что похоже на
    адрес, и всё, что начинается с каталога данных. Второй приём нужен
    потому, что первый держится на дисциплине автора проверки, а
    дисциплина однажды даёт сбой — и путь уезжает наружу в тексте `value`.
    """
    import re  # noqa: PLC0415

    корни: list[str] = []
    paths = getattr(settings, "paths", None) if settings is not None else None
    if paths is not None:
        for значение in vars(paths).values():
            текст = str(значение)
            if len(текст) > 3:
                корни.append(текст)
    # Длинные пути первыми: иначе корень каталога данных съест начало
    # своего же подкаталога и в тексте останется хвост вида «/uploads».
    корни.sort(key=len, reverse=True)
    адрес_ре = re.compile(r"\b[a-z][a-z0-9+.-]*://\S+", re.IGNORECASE)

    def почистить_текст(значение: str) -> str:
        итог = адрес_ре.sub("<адрес скрыт>", значение)
        for корень in корни:
            итог = итог.replace(корень, "<путь скрыт>")
        return итог

    def обойти(значение: Any) -> Any:
        if isinstance(значение, dict):
            return {ключ: обойти(вложенное)
                    for ключ, вложенное in значение.items()
                    if str(ключ) not in ЗАКРЫТЫЕ_КЛЮЧИ}
        if isinstance(значение, list):
            return [обойти(э) for э in значение]
        if isinstance(значение, str):
            return почистить_текст(значение)
        return значение

    return обойти(свод)
