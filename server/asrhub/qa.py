"""Контроль качества работы операторов: процесс вокруг скоркарты.

Балл оператора сервер считает давно. Сам по себе он не процесс, а число, и
превращается в процесс только когда вокруг него есть четыре вещи:

1. **Выборка.** Кто-то решает, какие разговоры смотреть. Отрасль считает
   сплошной контроль своим главным преимуществом перед ручной выборкой в
   1–3 %, и это правда — но и при сплошном автоматическом разборе человек
   всё равно слушает часть записей сам, и от того, какую именно, зависит
   всё остальное.
2. **Назначение.** У проверки есть исполнитель и срок, иначе она не
   проверка, а пожелание.
3. **Оценка человеком рядом с оценкой автомата.** Не вместо: смысл в том,
   чтобы видеть, где они расходятся.
4. **Калибровка проверяющих.** Два руководителя ставят за один и тот же
   разговор 60 и 85, и пока это не измерено, сравнивать операторов между
   отделами нельзя вовсе.

Здесь всё четыре. Самое важное и самое неочевидное — четвёртое: сдвиг
проверяющего (насколько он систематически строже или мягче автомата) говорит
о проверяющем, а средний балл — о записях, и путать их нельзя.

Выборка намеренно смешанная: часть случайная, часть — самые слабые по баллу.
Только случайная даёт честную картину по всем операторам; только слабые —
быстро находят, кого учить. Одна без другой превращает контроль качества либо
в лотерею, либо в травлю одних и тех же людей.
"""
from __future__ import annotations

import time
from typing import Any

from .logging_setup import get_logger

log = get_logger("qa")

#: Сколько записей в сутки ставится на проверку по умолчанию.
В_СУТКИ = 10

#: Какая доля выборки берётся из самых слабых, остальное — случайные.
ДОЛЯ_СЛАБЫХ = 0.4

#: Через сколько часов проверка считается просроченной.
СРОК_ЧАСОВ = 48.0

#: За какое окно берутся кандидаты. Разбирать позавчерашние разговоры можно,
#: но бессмысленно: оператор их уже не помнит, и разговор о них выходит не про
#: работу, а про то, кто что записал.
ОКНО_ЧАСОВ = 72.0


def настройки(settings: Any) -> dict[str, Any]:
    """Значения настроек контроля качества с запасными."""
    from . import settings_access as S

    return {
        "enabled": bool(settings.get("qa_enabled", False)) if settings else False,
        "daily": S.integer(settings or {}, "qa_daily", В_СУТКИ),
        "worst_share": S.num(settings or {}, "qa_worst_share", ДОЛЯ_СЛАБЫХ),
        "due_hours": S.num(settings or {}, "qa_due_hours", СРОК_ЧАСОВ),
        "window_hours": S.num(settings or {}, "qa_window_hours", ОКНО_ЧАСОВ),
        "assign_to": str((settings.get("qa_assign_to") if settings else "") or ""),
    }


def набрать(db: Any, settings: Any, *, now: float | None = None,
            assigned_by: str = "автоматически") -> list[dict[str, Any]]:
    """Ставит на проверку порцию записей. Возвращает назначенные.

    Ничего не делает, когда выключено или когда на сегодня уже набрано:
    задача этой функции — держать поток проверок ровным, а не набирать
    впрок. Проверка, поставленная пачкой в двести штук, не делается никогда.
    """
    свои = настройки(settings)
    if not свои["enabled"] or свои["daily"] <= 0:
        return []
    сейчас = float(now if now is not None else time.time())
    за_сутки = db.query_one(
        "SELECT COUNT(*) AS n FROM qa_reviews WHERE assigned_at>=?",
        (сейчас - 86400.0,))
    уже = int((за_сутки or {"n": 0})["n"] or 0)
    осталось = max(0, свои["daily"] - уже)
    if not осталось:
        return []

    окно = сейчас - max(1.0, свои["window_hours"]) * 3600.0
    слабых = min(осталось, int(round(осталось * max(0.0, min(1.0, свои["worst_share"])))))
    случайных = осталось - слабых
    кандидаты: list[dict[str, Any]] = []
    взятые: set[str] = set()
    for сколько, худшие in ((слабых, True), (случайных, False)):
        if сколько <= 0:
            continue
        for запись in db.qa_candidates(since=окно, limit=сколько * 3, worst=худшие):
            ид = str(запись.get("job_id") or "")
            if not ид or ид in взятые:
                continue
            взятые.add(ид)
            запись["reason"] = "слабый балл" if худшие else "случайная выборка"
            кандидаты.append(запись)
            if len([к for к in кандидаты if к["reason"] == запись["reason"]]) >= сколько:
                break

    назначено: list[dict[str, Any]] = []
    for запись in кандидаты:
        ид = db.qa_assign(
            str(запись["job_id"]), assigned_to=свои["assign_to"],
            assigned_by=assigned_by,
            due_at=сейчас + max(1.0, свои["due_hours"]) * 3600.0,
            agent=str(запись.get("agent") or запись.get("agent_speaker") or ""),
            auto_score=запись.get("auto_score"),
            reason=str(запись.get("reason") or ""))
        if ид is not None:
            назначено.append({**запись, "id": ид})
    if назначено:
        log.info("Контроль качества: поставлено на проверку %d записей",
                 len(назначено))
    return назначено


def просроченные(db: Any, *, now: float | None = None,
                 owner: str | list[str] | None = None) -> list[dict[str, Any]]:
    """Проверки, срок которых прошёл, а исхода нет. `owner` — только свои."""
    сейчас = float(now if now is not None else time.time())
    return [з for з in db.qa_list(status="pending", limit=500, owner=owner)
            if з.get("due_at") and float(з["due_at"]) < сейчас]
