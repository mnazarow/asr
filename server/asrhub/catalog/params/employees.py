    recommendation=(
        "Держите включённым, если по адресу отдаётся справочник целиком: это "
        "единственный способ узнать об увольнении — приказы сервер не читает. "
        "Выключайте, только когда в один и тот же источник приезжает часть "
        "справочника (выгрузка одного отдела, доливка новичков): при полном "
        "проходе все остальные отделы разом «уволятся». Правильнее в таком "
        "случае развести отделы по разным источникам — тогда каждый останется "
        "самим собой. Удаления карточек не происходит ни при каких настройках: "
        "по уволенному есть звонки, и удаление превратило бы часть архива в "
        "разговоры неизвестно с кем."
    ),
    examples=[
        Ex("Полная выгрузка", True, "По адресу весь штат сразу"),
        Ex("Доливка по частям", False, "В источник приезжает только один отдел"),
    ],
    see_also=["employees_url", "employees_sync_enabled"],
    impact={"quality": "neutral", "speed": "neutral", "memory": "neutral"},
