# Речевая аналитика начинается не с распознавания, а с вопроса «где взять
# записи». Пока их носят руками, разбор охватывает те разговоры, о которых
# кто-то вспомнил, — то есть в основном скандальные, и выводы получаются про
# скандалы, а не про работу. Здесь сервер забирает записи сам.

