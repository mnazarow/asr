"""Параметры группы «Потоковый режим»."""
from __future__ import annotations

from ._base import Ex, P, _p

# ===========================================================================
# ГРУППА: Потоковый режим
# ===========================================================================

_p(P(
    key="streaming_partial_results",
    label="Промежуточные результаты",
    group="streaming",
    type="bool",
    default=True,
    description=(
        "Отправлять клиенту потока (/api/stream) предварительный текст, который ещё может "
        "измениться, до закрепления фразы. Выключено — приходят только закреплённые фразы, "
        "а движок без настоящего потока не пересчитывает окно ради черновика, которого "
        "никто не увидит."
    ),
    recommendation=(
        "Включено для интерфейсов, где важен эффект «печатается на глазах». "
        "Выключайте, если потребитель не умеет обрабатывать изменение уже показанного текста."
    ),
    examples=[Ex("Интерфейс с живым выводом", True, ""), Ex("Запись в файл", False, "")],
    impact={"quality": "neutral", "speed": "neutral", "memory": "neutral"},
))

_p(P(
    key="streaming_endpoint_silence_ms",
    label="Тишина для завершения фразы",
    group="streaming",
    type="int",
    default=600,
    minimum=0,
    maximum=5000,
    step=50,
    unit="мс",
    description=(
        "Сколько тишины после речи считать концом фразы и закреплять её окончательно — у "
        "движков без настоящего потока, которые распознают скользящим окном (все, кроме "
        "Vosk: тот определяет конец фразы сам). Ноль — закреплять только по пределу "
        "хвоста в 30 секунд и в конце сессии."
    ),
    recommendation=(
        "600 мс подходит для диалога. Уменьшайте до 350 мс для быстрого обмена короткими "
        "репликами, увеличивайте до 1000 мс для размеренной речи с задумчивыми паузами."
    ),
    examples=[Ex("Диалог", 600, ""), Ex("Быстрый обмен репликами", 350, ""),
              Ex("Размеренная речь", 1000, "")],
    advanced=True,
    impact={"quality": "up", "speed": "down", "memory": "neutral"},
))
