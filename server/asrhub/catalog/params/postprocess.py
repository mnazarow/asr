_p(P(
    key="glossary",
    label="Словарь замен",
    group="postprocess",
    type="json",
    default={},
    description=(
        "Пары «что заменить» → «на что» применяются к готовому тексту. "
        "Исправляет систематические ошибки в терминах, названиях и фамилиях, "
        "которые не удалось решить подсказкой и ключевыми словами. "
        "Поддерживаются регулярные выражения, если ключ начинается с «re:».\n\n"
        "Регулярные выражения задаёт только администратор — в настройках сервера; "
        "задание может повторить серверные, но не прислать свои. Выражения с "
        "повтором внутри повтора («(\\w+\\s?)+») не принимаются нигде: модуль re "
        "откатывается на них без предела времени и останавливает весь сервер на "
        "часы. Пишите границу обязательной: «\\w+(?:\\s\\w+)*». Принятые выражения "
        "выполняются отдельным процессом не дольше 20 секунд на запись — иначе они "
        "пропускаются с предупреждением в задании."
    ),
    recommendation=(
        "Ведите словарь по результатам первых прогонов на своём материале — это самый "
        "быстрый способ довести качество до приемлемого на доменной лексике. "
        "Замены выполняются с учётом границ слов, регистр первой буквы сохраняется."
    ),
    examples=[
        Ex("Названия продуктов",
           {"гига чат": "ГигаЧат", "сбер клауд": "СберКлауд", "кубернетес": "Kubernetes"}, ""),
        Ex("Аббревиатуры", {"эс кью эль": "SQL", "эй пи ай": "API"}, ""),
        Ex("Регулярное выражение", {"re:\\bверсия (\\d+) точка (\\d+)": "версия \\1.\\2"},
           "«версия 3 точка 2» → «версия 3.2»"),
    ],
    impact={"quality": "up", "speed": "neutral", "memory": "neutral"},
    see_also=["initial_prompt", "hotwords"],
))

