"""Заглушка языковой модели: отвечает по правилам, без модели.

Нужна двум вещам: проверкам (набор тестов не может зависеть от девяти
гигабайт весов и видеокарты) и показу интерфейса на сервере без модели.
Отвечает тем же JSON, что просят подсказки, и делает это предсказуемо:
резюме — первые предложения разговора, причина и исход — пункт списка,
чьи слова встретились в тексте, действия — реплики с глаголами
договорённости, трекеры и скоркарта — по совпадению слов из описания.

Это не «маленькая модель» и не подмена: качество ответов здесь ровно
такое, какое даёт совпадение слов, — и в интерфейсе ответы заглушки
подписаны так же, как ответы модели, с именем «stub».
"""
from __future__ import annotations

import json
import re

_СЛОВО = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)
_ПРЕДЛОЖЕНИЕ = re.compile(r"[^.!?]+[.!?]?")

#: Глаголы договорённостей: по ним заглушка находит действия к исполнению.
_ДОГОВОРЁННОСТЬ = re.compile(
    r"перезвон|отправл|передам|передад|оформ|вышл|провер|верн|подготов|напиш|свяж",
    re.IGNORECASE)

_СРОК = re.compile(r"сегодня|завтра|в течение[^.,]*|через[^.,]*|до конца[^.,]*|"
                   r"в понедельник|во вторник|в среду|в четверг|в пятницу", re.IGNORECASE)


def _задача(system: str) -> str:
    m = re.search(r"### задача: (\w+)", system or "")
    return m.group(1) if m else "main"


def _разговор(user: str) -> str:
    m = re.search(r'"""\n(.*?)\n"""', user or "", re.DOTALL)
    return m.group(1) if m else (user or "")


def _список(user: str, заголовок: str) -> list[str]:
    m = re.search(rf"{заголовок}[^:]*:\s*(.+)", user or "")
    if not m:
        return []
    return [x.strip() for x in m.group(1).split(";") if x.strip()]


#: Слова, которые есть в любом вопросе о разговоре и ничего не отличают.
_ПУСТЫЕ = {"сотру", "клиен", "опера", "разго", "котор", "когда", "предл", "выпол"}


def _основы(текст: str) -> set[str]:
    return {w.lower()[:5] for w in _СЛОВО.findall(текст or "") if len(w) >= 5} - _ПУСТЫЕ


def _выбрать(варианты: list[str], основы: set[str], запасное: tuple[str, ...]) -> str | None:
    if not варианты:
        return None
    for в in варианты:
        if _основы(в) & основы:
            return в
    for в in варианты:
        if any(з in в.lower() for з in запасное):
            return в
    return варианты[-1]


def _цитата(разговор: str, основы_нужные: set[str]) -> str:
    for строка in разговор.split("\n"):
        реплика = re.sub(r"^[^:\n]{1,30}: ", "", строка)
        if _основы(реплика) & основы_нужные:
            return реплика.strip()[:200]
    return ""


def reply(system: str, user: str) -> str:
    """Ответ заглушки на подсказку — строка JSON."""
    задача = _задача(system)
    разговор = _разговор(user)
    основы = _основы(разговор)
    if задача == "chunk":
        предложения = [п.strip() for п in _ПРЕДЛОЖЕНИЕ.findall(re.sub(r"^[^:\n]{1,30}: ", "", разговор, flags=re.M))
                       if п.strip()]
        return json.dumps({"summary": " ".join(предложения[:3])[:600]}, ensure_ascii=False)
    if задача == "trackers":
        трекеры = re.findall(r"- id «([^»]+)», «([^»]+)»: (.+)", user or "")
        return json.dumps({"trackers": [
            {"id": id_, "fired": bool(_основы(описание) & основы),
             "quote": _цитата(разговор, _основы(описание))}
            for id_, _, описание in трекеры]}, ensure_ascii=False)
    if задача == "scorecard":
        вопросы = re.findall(r"- id «([^»]+)»: (.+)", user or "")
        return json.dumps({"answers": [
            {"id": id_, "answer": "да" if _основы(вопрос) & основы else "нет",
             "quote": _цитата(разговор, _основы(вопрос))}
            for id_, вопрос in вопросы]}, ensure_ascii=False)

    # Основной вызов.
    чистый = re.sub(r"^[^:\n]{1,30}: ", "", разговор, flags=re.M)
    предложения = [п.strip() for п in _ПРЕДЛОЖЕНИЕ.findall(чистый) if len(п.strip()) > 3]
    ответ: dict = {}
    if '"summary"' in (user or ""):
        ответ["summary"] = " ".join(предложения[:3])[:700] or "Разговор без содержания."
        нижний = чистый.lower()
        ответ["resolved"] = (True if re.search(r"спасибо|решил|сделал|отправил|готово", нижний)
                             and not re.search(r"жалоб|суд|отврат|не реш", нижний)
                             else False if re.search(r"жалоб|суд|отврат|не реш|не помог", нижний)
                             else None)
    причины = _список(user, "Причины обращения")
    исходы = _список(user, "Исходы разговора")
    if причины:
        ответ["reason"] = _выбрать(причины, основы, ("друг", "проч"))
        ответ["reason_quote"] = _цитата(разговор, _основы(ответ["reason"] or ""))
    if исходы:
        нижний = чистый.lower()
        if "перезвон" in нижний and any("перезвон" in и for и in исходы):
            ответ["outcome"] = next(и for и in исходы if "перезвон" in и)
        elif re.search(r"жалоб|суд|отказ", нижний) and any("отказ" in и or "не реш" in и for и in исходы):
            ответ["outcome"] = next(и for и in исходы if "отказ" in и or "не реш" in и)
        elif re.search(r"спасибо|готово|решил|отправил", нижний):
            ответ["outcome"] = next((и for и in исходы if "реш" in и), исходы[0])
        else:
            ответ["outcome"] = _выбрать(исходы, основы, ("неясн", "друг"))
        ответ["outcome_quote"] = _цитата(разговор, _основы(ответ["outcome"] or ""))
    if '"actions"' in (user or ""):
        действия = []
        for строка in разговор.split("\n"):
            реплика = re.sub(r"^[^:\n]{1,30}: ", "", строка)
            for предложение in _ПРЕДЛОЖЕНИЕ.findall(реплика):
                if _ДОГОВОРЁННОСТЬ.search(предложение):
                    срок = _СРОК.search(предложение)
                    кто = "клиент" if re.match(r"^(Клиент|SPEAKER_01|Говорящий 2)", строка) else "сотрудник"
                    действия.append({"what": предложение.strip()[:200], "who": кто,
                                     "when": срок.group(0).strip() if срок else None,
                                     "quote": предложение.strip()[:200]})
        ответ["actions"] = действия[:10]
    return json.dumps(ответ, ensure_ascii=False)
