"""Срок договорённости словами — в момент времени.

Модель пишет срок так, как он прозвучал: «завтра», «до пятницы», «в
течение трёх дней», «к 15 ноября». Чтобы проверить, выполнено ли обещание
(перезвонили ли клиенту), и чтобы поставить задачу в CRM, нужен момент
времени. Здесь — разбор самых частых оборотов от времени разговора.

Чего здесь нет намеренно: «на днях», «как можно скорее», «потом» — это не
срок, и выдумывать для них дату значит назначать задаче срок, которого
никто не называл. Такие договорённости остаются без срока.

Конец срока — конец названного дня (23:59:59 местного времени): «завтра»
значит «до конца завтрашнего дня», а не «через 24 часа от разговора».
"""
from __future__ import annotations

import datetime as dt
import re

_ЧИСЛА = {
    "один": 1, "одного": 1, "одну": 1, "одна": 1, "два": 2, "двух": 2, "две": 2,
    "три": 3, "трёх": 3, "трех": 3, "четыре": 4, "четырёх": 4, "четырех": 4,
    "пять": 5, "пяти": 5, "шесть": 6, "шести": 6, "семь": 7, "семи": 7,
    "десять": 10, "десяти": 10, "пару": 2, "пары": 2, "несколько": 3,
    "нескольких": 3,
}

_ДНИ_НЕДЕЛИ = {
    r"понедельник\w*": 0, r"вторник\w*": 1, r"сред[уыае]": 2, r"четверг\w*": 3,
    r"пятниц\w*": 4, r"суббот\w*": 5, r"воскресень\w*": 6,
}

_МЕСЯЦЫ = {
    "январ": 1, "феврал": 2, "март": 3, "апрел": 4, "ма": 5, "июн": 6, "июл": 7,
    "август": 8, "сентябр": 9, "октябр": 10, "ноябр": 11, "декабр": 12,
}

#: Сколько рабочих часов считать «в течение часа/двух часов»: срок в часах
#: — от момента разговора, а не до конца дня.
_ЧАС = 3600.0


def _конец_дня(день: dt.date) -> float:
    return dt.datetime.combine(день, dt.time(23, 59, 59)).timestamp()


def _число(слово: str) -> int | None:
    слово = слово.lower()
    if слово.isdigit():
        return int(слово)
    return _ЧИСЛА.get(слово)


def срок(текст: str | None, от: float) -> float | None:
    """Момент, к которому обещали, — или None, если срок словами не назван.

    `от` — время разговора (секунды эпохи). Разбор — по местному времени
    сервера: «завтра» у оператора и у сервера одно и то же.
    """
    if not текст:
        return None
    t = " ".join(str(текст).lower().replace("ё", "е").split())
    начало = dt.datetime.fromtimestamp(float(от))
    день = начало.date()

    if re.search(r"\bсейчас\b|\bсразу\b|в течение (?:этого )?разговора", t):
        return float(от) + _ЧАС
    if re.search(r"\bпослезавтра\b", t):
        return _конец_дня(день + dt.timedelta(days=2))
    if re.search(r"\bзавтра\b", t):
        return _конец_дня(день + dt.timedelta(days=1))
    if re.search(r"\bсегодня\b|до конца (?:рабочего )?дня|до вечера|\bвечером\b", t):
        return _конец_дня(день)

    m = re.search(r"(?:через|в течение|в течении|не позднее чем через)\s+"
                  r"(\d+|[а-я]+)?\s*(час|минут|дн|день|сут|недел|месяц)", t)
    if m:
        n = _число(m.group(1)) if m.group(1) else 1
        if n is None:
            n = 1
        единица = m.group(2)
        if единица == "час":
            return float(от) + n * _ЧАС
        if единица == "минут":
            return float(от) + n * 60.0
        if единица in ("дн", "день", "сут"):
            return _конец_дня(день + dt.timedelta(days=n))
        if единица == "недел":
            return _конец_дня(день + dt.timedelta(days=7 * n))
        return _конец_дня(день + dt.timedelta(days=30 * n))

    if re.search(r"до конца недели|на этой неделе", t):
        return _конец_дня(день + dt.timedelta(days=(6 - день.weekday())))
    if re.search(r"на следующей неделе|на неделе", t):
        сдвиг = (7 - день.weekday()) + 6 if "следующ" in t else (6 - день.weekday())
        return _конец_дня(день + dt.timedelta(days=сдвиг))
    if re.search(r"до конца месяца|в этом месяце", t):
        следующий = (день.replace(day=28) + dt.timedelta(days=4)).replace(day=1)
        return _конец_дня(следующий - dt.timedelta(days=1))

    for основа, номер in _ДНИ_НЕДЕЛИ.items():
        if re.search(rf"\b{основа}\b", t):
            вперёд = (номер - день.weekday()) % 7 or 7
            return _конец_дня(день + dt.timedelta(days=вперёд))

    m = re.search(r"\b(\d{1,2})[./](\d{1,2})(?:[./](\d{2,4}))?\b", t)
    if m:
        try:
            год = int(m.group(3)) if m.group(3) else день.year
            if год < 100:
                год += 2000
            дата = dt.date(год, int(m.group(2)), int(m.group(1)))
        except ValueError:
            дата = None
        if дата:
            if not m.group(3) and дата < день:
                дата = дата.replace(year=дата.year + 1)
            return _конец_дня(дата)
    m = re.search(r"\b(\d{1,2})\s+([а-я]+)", t)
    if m:
        for основа, номер in _МЕСЯЦЫ.items():
            if m.group(2).startswith(основа) and (основа != "ма" or m.group(2).startswith("мая")):
                try:
                    дата = dt.date(день.year, номер, int(m.group(1)))
                except ValueError:
                    return None
                if дата < день:
                    дата = дата.replace(year=дата.year + 1)
                return _конец_дня(дата)
    return None


#: Договорённость, выполнение которой видно по журналу звонков: перезвонить,
#: связаться, набрать. «Отправить письмо» или «оформить возврат» по журналу
#: не проверишь — такие остаются «не проверяется».
ЗВОНОК = re.compile(r"перезвон|позвон|набер|наберу|свяж|созвон|звонок|звякн", re.IGNORECASE)


def про_звонок(текст: str | None) -> bool:
    """Обещан ли звонок клиенту — то, что видно по журналу звонков."""
    return bool(текст and ЗВОНОК.search(str(текст)))


