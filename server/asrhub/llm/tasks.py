#: Метки блока с расшифровкой. Прежде расшифровка стояла между тройными
#: кавычками, и реплика с `"""` закрывала блок и дописывала свой «список
#: исходов» — в распечатке подсказки неотличимый от служебного: исход
#: «отказ клиента» становился «вопрос решён», без единого предупреждения.
#: Номер метки — отпечаток самого текста: вписать в разговор закрывающую
#: метку с верным номером нельзя, номер от этой вписки и зависит. И он
#: постоянен для одного текста — кеш ответов модели продолжает работать.
_НАЧАЛО_БЛОКА = "<<<РАСШИФРОВКА {метка}>>>"
_КОНЕЦ_БЛОКА = "<<<КОНЕЦ РАСШИФРОВКИ {метка}>>>"


def блок(текст: str) -> str:
    """Расшифровка между метками с номером-отпечатком (см. `_НАЧАЛО_БЛОКА`)."""
    чистый = str(текст or "").replace("<<<", "‹‹‹").replace(">>>", "›››")
    метка = hashlib.sha256(чистый.encode("utf-8")).hexdigest()[:10]
    return (f"{_НАЧАЛО_БЛОКА.format(метка=метка)}\n{чистый}\n"
            f"{_КОНЕЦ_БЛОКА.format(метка=метка)}")


def transcript_of(segments: list[dict[str, Any]], text: str, *,
                  agent_speaker: str = "") -> str:
    """Разговор строками «Кто: реплика». Без разметки говорящих — сплошной текст."""
    строки = []
    for с in segments or []:
        реплика = str(с.get("text") or "").strip()
        if not реплика:
            continue
        кто = str(с.get("speaker") or "").strip()
        if кто and agent_speaker and кто == agent_speaker:
            кто = "Сотрудник"
        строки.append(f"{кто}: {реплика}" if кто else реплика)
    return "\n".join(строки) if строки else str(text or "").strip()


def chunks_of(transcript: str, limit: int) -> list[str]:
    """Режет по строкам-репликам на куски не длиннее предела."""
    limit = max(500, int(limit))
    if len(transcript) <= limit:
        return [transcript]
    куски: list[str] = []
    текущий: list[str] = []
    длина = 0
    for строка in transcript.split("\n"):
        if длина + len(строка) + 1 > limit and текущий:
            куски.append("\n".join(текущий))
            текущий, длина = [], 0
        # Реплика длиннее предела режется по словам.
        while len(строка) > limit:
            куски.append(строка[:limit])
            строка = строка[limit:]
        текущий.append(строка)
        длина += len(строка) + 1
    if текущий:
        куски.append("\n".join(текущий))
    return куски


#: Сколько раз пробовать начать объект с очередной «{». Ответ модели — это
#: страница текста, а не мегабайт, но и перебирать каждую скобку длинного
#: пояснения незачем.
_ПОПЫТОК_РАЗБОРА = 50


def parse_json(text: str) -> dict[str, Any]:
    """Объект JSON из ответа модели — даже если она обернула его в текст.

    Объект берётся первый целый — от «{», с которой он разбирается, до его
    собственного конца (`raw_decode`), а не от первой «{» до последней «}».
    Модель нередко дописывает после ответа пояснение, и если в пояснении
    есть фигурные скобки («поле {reason} заполнено по…»), вырезка до
    последней «}» захватывала их и давала «повреждённый JSON». При
    temperature 0 модель отвечает так же и на повторе — запись не
    разбиралась никогда.
    """
    text = (text or "").strip()
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\s*|\s*```$", "", text)
    try:
        данные = json.loads(text)
    except (TypeError, ValueError):
        начало = text.find("{")
        if начало < 0:
            raise LLMError("Модель ответила не JSON.") from None
        разборщик = json.JSONDecoder()
        данные = None
        for _n in range(_ПОПЫТОК_РАЗБОРА):
            try:
                найдено, _конец = разборщик.raw_decode(text, начало)
            except ValueError:
                найдено = None
                # Не разобрался объект, который начинается как JSON — «{» и
                # сразу ключ в кавычках. Это ответ, оборванный на пределе
                # или испорченный, а не скобка из пояснения («поле {reason}
                # заполнено по…»). Искать дальше внутри него нельзя: первым
                # целым там окажется вложенный объект — одно действие из
                # списка или один ответ скоркарты, — и он молча выдавался за
                # весь ответ модели.
                if text[начало + 1:].lstrip().startswith('"'):
                    raise LLMError("Модель ответила оборванным JSON: объект не закрыт "
                                   "(ответ упёрся в предел или испорчен).") from None
            if isinstance(найдено, dict):
                данные = найдено
                break
            начало = text.find("{", начало + 1)
            if начало < 0:
                break
        if данные is None:
            raise LLMError("Модель ответила повреждённым JSON.") from None
    if not isinstance(данные, dict):
        raise LLMError("Модель ответила не объектом JSON.")
    return данные


def ответ_с(*ключи: str, хоть_одно: bool = False) -> Callable[[str], dict[str, Any]]:
    """Разбор ответа задачи: объект JSON с полями этой задачи.

    Одной проверки «это JSON» мало: объект без нужных полей разбирался
    «успешно», запись ложилась разобранной с пустым пересказом и исходом
    «неясно», и такой ответ оседал в кеше. Тот же разбор служит проверкой
    перед кешем (`validate` у `LLMClient.chat`): ответ без полей задачи
    туда не попадает и при повторе спрашивается заново.

    `хоть_одно` — для основного вызова: модель вправе опустить поле, которому
    нечего сказать (пустой список действий), но объект, где нет ни одного из
    заказанных полей, — не ответ на этот вопрос: так выглядит одно действие
    или цитата, выхваченные из оборванного ответа.
    """
    def разобрать(текст: str) -> dict[str, Any]:
        данные = parse_json(текст)
        нет = [к for к in ключи if к not in данные]
        if нет and (not хоть_одно or len(нет) == len(ключи)):
            raise LLMError("В ответе модели нет полей: " + ", ".join(нет) + ".")
        return данные
    return разобрать


def _из_списка(значение: Any, варианты: list[str],
               запасные: tuple[str, ...]) -> tuple[str | None, bool]:
    """Ответ модели — строго из списка.

    Возвращает пункт списка и признак «модель попала в список». Не попала
    — берётся запасной пункт («другое», «неясно»), но признак остаётся
    ложным: выдуманный моделью ответ должен быть виден, а не растворяться
    в общей доле «неясно».

    Неточное совпадение разбирается по смыслу, а не по порядку списка. Из
    пунктов, целиком попавших в ответ, берётся самый длинный: при списке
    «оплата; оплата картой» ответ «оплата картой в приложении» — это
    второй пункт, а не первый, который просто стоит раньше. Наоборот —
    ответ короче пункта — берётся самый узкий из содержащих его, чтобы
    короткое «оплата» не уезжало в «оплата картой при доставке».
    """
    if not варианты:
        return None, False
    # Сравниваем записи, приведённые к одному виду: без регистра, «ё» и
    # знаков. Модель вправе ответить «Вопрос решен.» на пункт «вопрос
    # решён» — раньше это был исход «неясно» с пометкой «вне списка», и доля
    # решённых в отчётах занижалась ровно на такие ответы.
    текст = _для_сравнения(значение)
    пункты = [(в, _для_сравнения(в)) for в in варианты if _для_сравнения(в)]
    for в, нижний in пункты:
        if текст == нижний:
            return str(в), True
    if текст:
        # Сравнение — целыми словами (с точностью до окончания) и с оглядкой
        # на отрицание. Подстрока здесь давала противоположный исход: «решён»
        # — часть «не решено», и короткий ответ модели «решено» становился
        # «не решено»; «да» — часть «продажа или оформление», «нет» —
        # «интернет не работает».
        слова = _слова_пункта(текст)
        внутри = [(в, нижний) for в, нижний in пункты
                  if _слова_пункта(нижний) <= слова
                  and _с_отрицанием(нижний) == _с_отрицанием(текст)]
        if внутри:
            return str(max(внутри, key=lambda пара: len(пара[1]))[0]), True
        содержат = [(в, нижний) for в, нижний in пункты
                    if слова <= _слова_пункта(нижний)
                    and _с_отрицанием(нижний) == _с_отрицанием(текст)
                    and any(len(с) >= 4 for с in слова)]
        # Ответ короче пункта — самый узкий из содержащих его: короткое
        # «картой» не должно уезжать в «оплата картой при доставке».
        if содержат:
            return str(min(содержат, key=lambda пара: len(пара[1]))[0]), True
    for в in варианты:
        if any(з in str(в).lower() for з in запасные):
            return str(в), False
    return None, False


#: Слова отрицания в пункте списка и в ответе модели.
_ОТРИЦАНИЕ = frozenset({"не", "нет", "без", "ни"})

#: Слова, которые ничего не различают в пунктах списка.
_СВЯЗКИ = frozenset({"и", "или", "а", "в", "на", "по", "с", "к", "о", "у"})


def _слитное_не(слово: str) -> bool:
    """«Нерешённый», «неясно» — отрицание, написанное слитно."""
    return len(слово) > 4 and слово.startswith("не")


def _с_отрицанием(текст: str) -> bool:
    """Есть ли в записи отрицание: «не решено» и «решено» — разные исходы."""
    return any(с in _ОТРИЦАНИЕ or _слитное_не(с) for с in текст.split())


def _слова_пункта(текст: str) -> set[str]:
    """Значимые слова записи — первыми пятью буквами, чтобы «решён», «решено»
    и «решен» совпадали, а «не» и «или» не мешали; слитное «не» снимается:
    «нерешённый» — это «не» и «решённый»."""
    return {(с[2:] if _слитное_не(с) else с)[:5] for с in текст.split()
            if с not in _СВЯЗКИ and с not in _ОТРИЦАНИЕ}


def _для_сравнения(значение: Any) -> str:
    """Запись для сравнения с пунктом списка: регистр, «ё», знаки, пробелы."""
    низ = str(значение or "").lower().replace("ё", "е")
    низ = re.sub(r"[^\w\s-]", " ", низ)
    return " ".join(низ.split())


def _строка(значение: Any, предел: int = 600) -> str:
    """Строка из ответа модели. Список склеивается, а не превращается в
    `"['…', '…']"` — так резюме, присланное пунктами, и попадало в отчёт."""
    if isinstance(значение, (list, tuple)):
        значение = "; ".join(str(ч).strip() for ч in значение if str(ч or "").strip())
    elif isinstance(значение, dict):
        значение = ""
    return str(значение or "").strip()[:предел]


#: Как модель пишет «да» и «нет», если не булевым значением.
_ДА = frozenset({"да", "yes", "true", "1", "истина", "верно"})
_НЕТ = frozenset({"нет", "no", "false", "0", "ложь", "неверно"})


def _да_нет(значение: Any) -> bool | None:
    """Да/нет из ответа модели — или None, если ответ не читается.

    `bool("false")` истинно: трекер, на который модель ответила строкой
    «false», считался сработавшим, и в своде копились ложные срабатывания.
    А `"resolved": "true"` превращалось в «не известно».
    """
    if isinstance(значение, bool):
        return значение
    if isinstance(значение, (int, float)) and значение in (0, 1):
        return bool(значение)
    if isinstance(значение, str):
        низ = значение.strip().lower().rstrip(".!")
        if низ in _ДА:
            return True
        if низ in _НЕТ:
            return False
    return None


def _да_нет_ответ(значение: Any) -> bool | None:
    """Да/нет — и по первому слову развёрнутого ответа: «да, сработал»."""
    точно = _да_нет(значение)
    if точно is not None or not isinstance(значение, str):
        return точно
    первое = re.split(r"[\s,.;:!—-]+", значение.strip().lower(), maxsplit=1)[0]
    return _да_нет(первое)


#: Ответы скоркарты, означающие «неприменимо». Проверяются ПЕРЕД «нет»:
#: подсказка сама предлагает модели это слово, а начинается оно с «не» — и
#: ответ «ситуации в разговоре не было» шёл в «нет», штрафуя оператора за
#: то, чего он не мог сделать.
_НЕПРИМЕНИМО = ("нп", "н п", "неприменим", "не применим", "na", "n a", "n/a",
                "not applicable", "none", "null")

#: Ответы, по которым нельзя сказать ни «да», ни «нет»: «неизвестно»,
#: «не уверен». Прежде всё, что начиналось с «не», считалось «нет».
_НЕ_ЗНАЮ = ("неизвестн", "неясн", "не уверен", "не знаю", "трудно сказать",
            "непонятн", "unknown", "unsure")


def _ответ_скоркарты(значение: Any) -> str | None:
    """«да», «нет» или «н/п» из ответа модели; None — ответ не читается.

    Сначала булево и «да/нет» по-русски и по-английски (`_да_нет`): `True`,
    `"yes"` и `1` превращались в «н/п», а пункт скоркарты молча выпадал из
    балла.
    """
    if значение is None:
        return None
    точно = _да_нет(значение)
    if точно is not None:
        return "да" if точно else "нет"
    низ = _строка(значение, 40).lower().replace("/", " ").strip(" .!")
    if not низ:
        return None
    if низ.startswith(_НЕПРИМЕНИМО) or "не было" in низ:
        return "н/п"
    if низ.startswith(_НЕ_ЗНАЮ):
        return None
    первое = re.split(r"[\s,.;:!—-]+", низ, maxsplit=1)[0]
    if первое in _ДА:
        return "да"
    if первое in _НЕТ or первое == "не":
        return "нет"
    return None


def есть_в(цитата: str, разговор: str) -> bool:
    """Есть ли цитата в разговоре — без оглядки на регистр, «ё» и знаки.

    Модель цитирует не буква в букву: меняет кавычки, ставит точку, пропускает
    подпись говорящего. Поэтому сравнение — по словам: цитата, все слова
    которой подряд стоят в разговоре, найдена.
    """
    def слова(текст: str) -> str:
        return " ".join(_для_сравнения(текст).split())

    искомое = слова(цитата)
    if not искомое:
        return True
    return искомое in слова(разговор)


def _список(значение: Any) -> list[Any]:
    """Список из ответа модели — или пустой, если пришло что-то другое.

    Ответ модели — чужие данные, и форма у них любая. Поле `trackers`,
    описанное в подсказке как список объектов, приезжало числом: `or []`
    такое пропускает (число истинно), а перебор по нему падает с
    `TypeError: 'int' object is not iterable`.

    Дальше это исключение никто не ждал. Разбор по кнопке отдавал человеку
    пятисотку без объяснений, строка очереди оставалась «идёт» навсегда, а
    фоновый разбор помечал запись сбойной и шёл дальше — то есть одна
    неудачная генерация модели стоила записи навсегда. Достаточно было
    модели «поторопиться» с форматом ответа один раз.
    """
    return значение if isinstance(значение, list) else []


def analyze(client: LLMClient, *, text: str, segments: list[dict[str, Any]],
            settings: Any, agent_speaker: str = "",
            script: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """Полный смысловой разбор одной записи по включённым задачам."""
    задачи = set(settings.get("llm_tasks") or [])
    предел = int(settings.get("llm_context_chars") or 12000)
    причины = [str(x) for x in (settings.get("llm_reasons") or []) if str(x).strip()]
    исходы = [str(x) for x in (settings.get("llm_outcomes") or []) if str(x).strip()]
    трекеры = [т for т in (settings.get("llm_trackers") or []) if isinstance(т, dict)]
    вопросы = [в for в in (settings.get("llm_scorecard") or []) if isinstance(в, dict)]
    if not вопросы and script:
        вопросы = [{"id": str(п.get("id") or f"item{i}"),
                    "question": f"Сотрудник выполнил пункт скрипта: {п.get('label')}?"}
                   for i, п in enumerate(script) if п.get("label")]

    начало = time.perf_counter()
    итог: dict[str, Any] = {"summary": None, "reason": None, "outcome": None,
                            "resolved": None, "actions": None, "trackers": None,
                            "scorecard": None, "chunks": 1, "calls": 0,
                            "model": client.model, "warnings": []}
    разговор = transcript_of(segments, text, agent_speaker=agent_speaker)
    if not разговор:
        итог["warnings"].append("пустая расшифровка")
        итог["latency_ms"] = 0.0
        return итог

    куски = chunks_of(разговор, предел)
    if len(куски) > 1:
        пересказы = []
        пустых = 0
        for n, кусок in enumerate(куски, 1):
            разбор = ответ_с("summary")
            ответ = client.chat(МЕТКА.format(kind="chunk") + _СИСТЕМА,
                                _ПЕРЕСКАЗ.format(n=n, total=len(куски), chunk=блок(кусок)),
                                kind="chunk", validate=разбор)
            итог["calls"] += 1
            # Проверка полей здесь — только для кеша: часть без пересказа
            # считается пустой (ниже), а не роняет разбор всего разговора.
            пересказ = _строка(parse_json(ответ).get("summary"), 2000)
            if not пересказ:
                пустых += 1
                continue
            пересказы.append(f"Часть {n}: {пересказ}")
        # Пустой пересказ — не пустяк. Склейка «Часть 1: \nЧасть 2: \n…» шла
        # в основной вызов как расшифровка разговора, и модель честно
        # отвечала на пустоту: «ничего конкретного не обсуждалось». Этот
        # ответ ложился в базу обычным разбором, с пустым полем `error` — то
        # есть длинный разговор, которого разбор не увидел вовсе, выглядел
        # разобранным и попадал в отчёты как «без содержания». Часовые
        # разговоры режутся на части всегда, так что это про них.
        if пустых:
            итог["warnings"].append(
                f"без пересказа осталось частей: {пустых} из {len(куски)}")
        if not пересказы:
            итог["warnings"].append(
                "модель не пересказала ни одной части — разбирать нечего")
            итог["chunks"] = len(куски)
            итог["latency_ms"] = round((time.perf_counter() - начало) * 1000, 1)
            return итог
        разговор = "\n".join(пересказы)
        итог["chunks"] = len(куски)
        итог["warnings"].append(f"разбор по пересказам {len(куски)} частей")

    # Цитаты сверяются с расшифровкой: модель вправе цитировать только
    # разговор, а цитата, которой в нём нет, — либо выдумка, либо то, что
    # вписали в сам разговор, чтобы ей подсказать. По пересказам частей
    # сверять не с чем — там цитаты и так из пересказа.
    сверять = итог["chunks"] == 1
    исходный = разговор

    def цитата(значение: Any, где: str) -> str:
        текст = _строка(значение)
        if текст and сверять and not есть_в(текст, исходный):
            итог["warnings"].append(f"цитата не найдена в расшифровке: {где}")
        return текст

    основные = задачи & {"summary", "outcome", "actions"}
    if основные:
        поля = []
        списки = []
        нужны: list[str] = []
        if "summary" in задачи:
            нужны.append("summary")
            поля.append('"summary": "резюме в три-пять предложений: причина обращения, '
                        'что сделано, чем закончилось"')
            поля.append('"resolved": true, если вопрос клиента решён в разговоре, false, '
                        'если не решён, null, если неясно')
        if "outcome" in задачи:
            if причины:
                нужны.append("reason")
                списки.append("Причины обращения (выбери ровно одну): " + "; ".join(причины))
                поля.append('"reason": "одна причина из списка"')
                поля.append('"reason_quote": "цитата из расшифровки, по которой выбрана причина"')
            if исходы:
                нужны.append("outcome")
                списки.append("Исходы разговора (выбери ровно один): " + "; ".join(исходы))
                поля.append('"outcome": "один исход из списка"')
                поля.append('"outcome_quote": "цитата, по которой выбран исход"')
        if "actions" in задачи:
            нужны.append("actions")
            поля.append('"actions": список действий к исполнению, о которых договорились: '
                        '[{"what": "что сделать", "who": "сотрудник" или "клиент", '
                        '"when": "срок словами из разговора или null", '
                        '"quote": "цитата"}]; пустой список, если договорённостей нет')
        разбор = ответ_с(*нужны, хоть_одно=True)
        ответ = client.chat(
            МЕТКА.format(kind="main") + _СИСТЕМА,
            _ОСНОВНОЙ.format(transcript=блок(разговор),
                             lists=("\n".join(списки) + "\n") if списки else "",
                             fields="\n".join(поля)),
            kind="main", validate=разбор)
        итог["calls"] += 1
        данные = разбор(ответ)
        if "summary" in задачи:
            итог["summary"] = _строка(данные.get("summary"), 2000) or None
            итог["resolved"] = _да_нет(данные.get("resolved"))
        if "outcome" in задачи:
            if причины:
                итог["reason"], попала = _из_списка(данные.get("reason"), причины,
                                                    ("друг", "проч"))
                итог["reason_quote"] = цитата(данные.get("reason_quote"), "причина")
                if not попала:
                    итог["warnings"].append("причина вне списка")
            if исходы:
                итог["outcome"], попала = _из_списка(данные.get("outcome"), исходы,
                                                     ("неясн", "друг"))
                итог["outcome_quote"] = цитата(данные.get("outcome_quote"), "исход")
                if not попала:
                    итог["warnings"].append("исход вне списка")
        if "actions" in задачи:
            действия = данные.get("actions")
            итог["actions"] = [
                {"what": _строка(д.get("what")), "who": _строка(д.get("who"), 40) or "сотрудник",
                 "when": _строка(д.get("when"), 120) or None,
                 "quote": цитата(д.get("quote"), "действие")}
                for д in _список(действия)
                if isinstance(д, dict) and _строка(д.get("what"))][:20]

    if "trackers" in задачи and трекеры:
        описания = "\n".join(
            f"- id «{т.get('id')}», «{т.get('label')}»: {т.get('description') or т.get('label')}"
            for т in трекеры if т.get("id"))
        разбор = ответ_с("trackers")
        ответ = client.chat(МЕТКА.format(kind="trackers") + _СИСТЕМА,
                            _ТРЕКЕРЫ.format(transcript=блок(разговор), trackers=описания),
                            kind="trackers", validate=разбор)
        итог["calls"] += 1
        данные = разбор(ответ)
        ответы = {str(o.get("id")): o for o in _список(данные.get("trackers"))
                  if isinstance(o, dict)}
        итог["trackers"] = []
        for т in трекеры:
            if not т.get("id"):
                continue
            о = ответы.get(str(т.get("id")))
            # «Да, сработал» и «нет, не было» — тоже ответы: первое слово
            # решает. Прежде такой ответ читался как «не сработал».
            сработал = _да_нет_ответ(о.get("fired")) if о else None
            if о is None:
                итог["warnings"].append(f"модель не ответила про трекер «{т.get('id')}»")
            elif сработал is None:
                итог["warnings"].append(f"ответ про трекер «{т.get('id')}» не разобран")
            итог["trackers"].append(
                {"id": str(т.get("id")), "label": str(т.get("label") or т.get("id")),
                 "fired": bool(сработал),
                 "quote": цитата((о or {}).get("quote"), f"трекер «{т.get('id')}»")})

    if "scorecard" in задачи and вопросы:
        список = "\n".join(f"- id «{в.get('id')}»: {в.get('question')}" for в in вопросы
                           if в.get("id") and в.get("question"))
        разбор = ответ_с("answers")
        ответ = client.chat(МЕТКА.format(kind="scorecard") + _СИСТЕМА,
                            _СКОРКАРТА.format(transcript=блок(разговор), questions=список),
                            kind="scorecard", validate=разбор)
        итог["calls"] += 1
        данные = разбор(ответ)
        ответы = {str(o.get("id")): o for o in _список(данные.get("answers"))
                  if isinstance(o, dict)}
        итог["scorecard"] = []
        for в in вопросы:
            if not (в.get("id") and в.get("question")):
                continue
            о = ответы.get(str(в.get("id")))
            if о is None:
                итог["warnings"].append(f"модель не ответила на вопрос «{в.get('id')}»")
            ответ_модели = _ответ_скоркарты((о or {}).get("answer"))
            if о is not None and ответ_модели is None:
                итог["warnings"].append(
                    f"ответ на вопрос «{в.get('id')}» не разобран: "
                    f"«{_строка((о or {}).get('answer'), 40)}»")
            итог["scorecard"].append({
                "id": str(в.get("id")), "question": str(в.get("question")),
                "answer": ответ_модели or "н/п",
                "quote": цитата((о or {}).get("quote"), f"вопрос «{в.get('id')}»")})

    итог["latency_ms"] = round((time.perf_counter() - начало) * 1000, 1)
    return итог


def summarize_for_digest(результаты: list[dict[str, Any]]) -> dict[str, Any]:
    """Распределения исходов и причин по ответам — для свода и сводки."""
    def доли(ключ: str) -> list[dict[str, Any]]:
        счёт: dict[str, int] = {}
        for р in результаты:
            з = р.get(ключ)
            if з:
                счёт[str(з)] = счёт.get(str(з), 0) + 1
        всего = sum(счёт.values())
        return [{"key": k, "records": v, "share": round(100.0 * v / всего, 1)}
                for k, v in sorted(счёт.items(), key=lambda kv: -kv[1])]
    решено = [р.get("resolved") for р in результаты if р.get("resolved") is not None]
    действий = sum(len(_список(р.get("actions"))) for р in результаты)
    return {
        "outcomes": доли("outcome"), "reasons": доли("reason"),
        "resolved_share": round(100.0 * sum(1 for x in решено if x) / len(решено), 1)
        if решено else None,
        "actions": действий,
        "records_with_actions": sum(1 for р in результаты if р.get("actions")),
    }
