"""Здоровье распознавания: подозрительные расшифровки и сомнительная разметка.

Распознавание ошибается не только словом: Whisper на тишине, музыке и шуме
дописывает то, чего в звуке нет, — «Субтитры сделал DimaTorzok»,
«Продолжение следует», одну и ту же фразу десять раз подряд, счёт от одного
до ста. По измерениям (Careless Whisper, FAccT 2024) целые выдуманные фразы
есть примерно в одной расшифровке из ста, и до этой правки ни одна проверка
сервера их не видела: средняя уверенность по заданию оставалась приличной.

Здесь — набор безэталонных признаков по каждому сегменту. Ни один из них не
доказательство; их ценность в отборе «что послушать», в доле по моделям и в
ходе по дням. Пороги — из первоисточников: `compression_ratio > 2.4` и
`no_speech_prob > 0.6` при `avg_logprob < -1.0` (а это уверенность ниже
`e^-1 ≈ 0.37`) — значения по умолчанию самого Whisper; темп в символах в
секунду — самый сильный одиночный безэталонный детектор из измеренных
(AUC 68 %); повторы n-грамм и словарь известных фраз — дешёвые и точные там,
где срабатывают.

Считается сразу после распознавания и складывается в задание: доля
подозрительных сегментов, перечень признаков и до двух десятков примеров с
временем — для карточки.
"""
from __future__ import annotations

import json
import re
from collections import Counter
from typing import Any

#: Порог сжатия текста сегмента — значение Whisper по умолчанию. Всё выше
#: Whisper и сам считает сбоем и перебирает температуры, но последний
#: результат принимает даже с 14: сбой остаётся в расшифровке.
ПОРОГ_СЖАТИЯ = 2.4

#: Тишина по Whisper: `no_speech_prob` выше порога И низкая уверенность —
#: `avg_logprob < -1.0`, что в наших единицах `confidence < e^-1`.
ПОРОГ_ТИШИНЫ = 0.6
ПОРОГ_УВЕРЕННОСТИ_ТИШИНЫ = 0.37

#: Темп сегмента. Разборчивая русская речь — до 20 символов в секунду и
#: до 4–5 слов; выше — текста больше, чем могло прозвучать. Порог взят с
#: запасом: он ловит не быструю речь, а невозможную.
ПОРОГ_СИМВОЛОВ_В_СЕКУНДУ = 30.0
ПОРОГ_СЛОВ_В_СЕКУНДУ = 7.0

#: Повторы: одна и та же тройка слов от трёх раз в сегменте, или сегмент,
#: дословно повторяющий два предыдущих.
ПОВТОРОВ_В_СЕГМЕНТЕ = 3
ПОВТОРОВ_ПОДРЯД = 3

#: Реплики короче этого считаются осколками разметки: когда их больше
#: трети, говорящих разделили не по голосу, а как попало.
КОРОТКАЯ_РЕПЛИКА_С = 1.0
ДОЛЯ_ОСКОЛКОВ = 0.34

#: Известные фразы-галлюцинации. Русские — из субтитров, на которых учили
#: модель; английские — те же, в языке оригинала. Сравнение — по вхождению
#: в нижнем регистре, чтобы «Субтитры сделал DimaTorzok» ловилось и как
#: «субтитры сделал диматорзок».
ФРАЗЫ: tuple[str, ...] = (
    "субтитры сделал", "субтитры делал", "субтитры создавал", "субтитры подготовил",
    "субтитры подогнал", "редактор субтитров", "корректор а.егорова",
    "dimatorzok", "диматорзок", "продолжение следует", "спасибо за просмотр",
    "подписывайтесь на канал", "ставьте лайк", "до новых встреч",
    "thank you for watching", "thanks for watching", "subtitles by",
    "amara.org", "like and subscribe", "transcription by castingwords",
    "the end.", "♪",
)

#: Сколько примеров класть в задание для карточки.
ПРИМЕРОВ = 20

_СЛОВО = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)


def _текст(сегмент: dict[str, Any]) -> str:
    return str(сегмент.get("text") or "").strip()


def _длина(сегмент: dict[str, Any]) -> float:
    начало = float(сегмент.get("start") or сегмент.get("start_s") or 0.0)
    конец = float(сегмент.get("end") or сегмент.get("end_s") or 0.0)
    return max(0.0, конец - начало)


def _повтор_внутри(слова: list[str]) -> bool:
    if len(слова) < ПОВТОРОВ_В_СЕГМЕНТЕ * 3:
        return False
    тройки = Counter(tuple(слова[i:i + 3]) for i in range(len(слова) - 2))
    return max(тройки.values()) >= ПОВТОРОВ_В_СЕГМЕНТЕ


def _известная_фраза(текст: str) -> str | None:
    низкий = текст.lower()
    for фраза in ФРАЗЫ:
        if фраза in низкий:
            return фраза
    return None


def assess(segments: list[dict[str, Any]], *, expected_speakers: int = 0) -> dict[str, Any]:
    """Признаки по сегментам и по записи целиком.

    `expected_speakers` — сколько говорящих ожидается (в звонке — двое);
    ноль — не проверять. Возвращает то, что кладётся в задание: число и
    долю подозрительных сегментов, перечень признаков записи и примеры.
    """
    сегменты = list(segments or [])
    причины: Counter[str] = Counter()
    примеры: list[dict[str, Any]] = []
    подозрительных = 0
    предыдущие: list[str] = []
    короткие = 0
    говорящие: set[str] = set()

    for i, с in enumerate(сегменты):
        текст = _текст(с)
        длина = _длина(с)
        слова = [w.lower() for w in _СЛОВО.findall(текст)]
        if с.get("speaker"):
            говорящие.add(str(с["speaker"]))
        if длина < КОРОТКАЯ_РЕПЛИКА_С:
            короткие += 1

        свои: list[str] = []
        сжатие = с.get("compression") if с.get("compression") is not None else с.get("compression_ratio")
        if сжатие is not None and float(сжатие) > ПОРОГ_СЖАТИЯ:
            свои.append("compression")
        тишина = с.get("no_speech") if с.get("no_speech") is not None else с.get("no_speech_prob")
        уверенность = с.get("confidence")
        if (тишина is not None and float(тишина) > ПОРОГ_ТИШИНЫ
                and уверенность is not None
                and float(уверенность) < ПОРОГ_УВЕРЕННОСТИ_ТИШИНЫ):
            свои.append("silence")
        температура = с.get("temperature")
        if температура is not None and float(температура) > 0:
            свои.append("temperature")
        if длина > 0.2 and текст:
            if (len(текст) / длина > ПОРОГ_СИМВОЛОВ_В_СЕКУНДУ
                    or len(слова) / длина > ПОРОГ_СЛОВ_В_СЕКУНДУ):
                свои.append("tempo")
        if _повтор_внутри(слова) or (
                текст and len(предыдущие) >= ПОВТОРОВ_ПОДРЯД - 1
                and all(п == текст for п in предыдущие[-(ПОВТОРОВ_ПОДРЯД - 1):])):
            свои.append("repeat")
        фраза = _известная_фраза(текст)
        if фраза:
            свои.append("phrase")

        предыдущие.append(текст)
        if not свои:
            continue
        подозрительных += 1
        for п in свои:
            причины[п] += 1
        if len(примеры) < ПРИМЕРОВ:
            примеры.append({
                "idx": i,
                "start_s": round(float(с.get("start") or с.get("start_s") or 0.0), 2),
                "reasons": свои,
                "phrase": фраза,
                "text": текст[:160],
            })

    всего = len(сегменты)
    признаки = sorted(причины)
    if всего and короткие / всего >= ДОЛЯ_ОСКОЛКОВ and всего >= 6:
        признаки.append("fragments")
    несовпадение = bool(expected_speakers and говорящие
                        and len(говорящие) != int(expected_speakers))
    if несовпадение:
        признаки.append("speakers")
    return {
        "segments": всего,
        "suspect": подозрительных,
        "suspect_share": round(подозрительных / всего, 4) if всего else 0.0,
        "reasons": dict(причины),
        "flags": признаки,
        "speakers": len(говорящие),
        "speakers_expected": int(expected_speakers or 0),
        "short_share": round(короткие / всего, 4) if всего else 0.0,
        "items": примеры,
    }


def for_job(оценка: dict[str, Any]) -> dict[str, Any]:
    """Поля задания из оценки: число, доля, признаки строкой и подробности."""
    return {
        "suspect_segments": int(оценка.get("suspect") or 0),
        "suspect_share": float(оценка.get("suspect_share") or 0.0),
        "quality_flags": ",".join(оценка.get("flags") or []),
        "quality_detail": json.dumps(
            {к: оценка[к] for к in ("reasons", "items", "speakers",
                                   "speakers_expected", "short_share")},
            ensure_ascii=False),
    }


#: Как называть признаки человеку — один перечень для карточки, разреза
#: и документации.
ПРИЗНАКИ: dict[str, str] = {
    "compression": "сжимаемый текст",
    "silence": "текст на тишине",
    "temperature": "перебор температур",
    "tempo": "невозможный темп",
    "repeat": "повторы фраз",
    "phrase": "известная фраза-галлюцинация",
    "fragments": "осколки разметки говорящих",
    "speakers": "говорящих не столько, сколько ожидалось",
}
