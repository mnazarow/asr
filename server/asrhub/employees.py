#: Кодировки, в которых приезжают выгрузки. Порядок важен: utf-8-sig
#: снимает метку порядка байтов, которую Excel пишет в начало файла, — без
#: неё первый заголовок стал бы «﻿работает» и не узнался бы.
КОДИРОВКИ = ("utf-8-sig", "utf-8", "cp1251")

#: Разделители в порядке убывания «русскости»: Excel в русской локали
#: пишет CSV через точку с запятой, потому что запятая занята под
#: десятичный разделитель.
РАЗДЕЛИТЕЛИ = (";", "\t", ",")


#: Во сколько раз правильных многобайтных знаков UTF-8 должно быть больше,
#: чем битых последовательностей, чтобы файл считался UTF-8 с огрехами, а
#: не cp1251. В настоящем cp1251 правильных последовательностей UTF-8 почти
#: не бывает (русская буква с последующим знаком из 0x80–0xBF — редкость),
#: а в UTF-8 с одним чужим байтом их — все фамилии штата.
ПЕРЕВЕС_UTF8 = 10


def _декодировать(данные: bytes) -> tuple[str, str]:
    """Текст выгрузки и имя кодировки, в которой он прочитался.

    Кодировку определяем перебором, а не «догадками» по частотам байтов:
    вариантов ровно три, ошибка стоит справочника в кракозябрах, а строгий
    режим декодирования отвечает на вопрос точно. cp1251 идёт последней:
    в ней декодируется почти любой байт, поэтому ставить её раньше значит
    никогда не увидеть utf-8.

    Но строгий UTF-8 проваливался из-за ОДНОГО чужого байта — тире 0x96 из
    cp1251, вставленного в выгрузку руками, — и весь файл уходил в cp1251:
    все фамилии импортировались кракозябрами («РРІР°РЅРѕРІ») и по ключу
    внутреннего номера затирали настоящие карточки. Теперь, если правильных
    знаков UTF-8 в файле намного больше битых, он читается как UTF-8 с
    заменой битых — и замечание говорит, сколько их.
    """
    for кодировка in ("utf-8-sig", "utf-8"):
        try:
            return данные.decode(кодировка), кодировка
        except UnicodeDecodeError:
            continue
    как_utf8 = данные.decode("utf-8", errors="replace")
    битых = как_utf8.count("�")
    правильных = sum(1 for знак in как_utf8 if ord(знак) > 127 and знак != "�")
    if правильных >= ПЕРЕВЕС_UTF8 * битых:
        return как_utf8.lstrip("﻿"), f"utf-8 (с потерями: {битых} знак.)"
    for кодировка in КОДИРОВКИ[2:]:
        try:
            return данные.decode(кодировка), кодировка
        except UnicodeDecodeError:
            continue
    return данные.decode("cp1251", errors="replace"), "cp1251 (с потерями)"


def _разделитель(первая_строка: str) -> str:
    """Разделитель колонок — по тому, чего в строке заголовков больше.

    `csv.Sniffer` здесь не годится: он гадает по всему куску текста и в
    строке «Иванов, Пётр; отдел продаж» уверенно выбирает запятую, потому
    что её больше. Заголовки же — это ровно та строка, где лишних знаков
    не бывает, и счёт по ней даёт правильный ответ без сюрпризов.
    """
    лучший, счёт = ",", -1
    for знак in РАЗДЕЛИТЕЛИ:
        сколько = первая_строка.count(знак)
        if сколько > счёт:
            лучший, счёт = знак, сколько
    return лучший if счёт > 0 else ";"


def _разобрать_csv(данные: bytes | str, итог: Разбор) -> list[list[str]]:
    """Строки CSV: кодировка и разделитель определяются сами."""
    if isinstance(данные, bytes):
        текст, кодировка = _декодировать(данные)
    else:
        текст, кодировка = данные, "уже текст"
    первая = текст.lstrip("﻿").splitlines()[0] if текст.strip() else ""
    знак = _разделитель(первая)
    итог.замечание(f"CSV: кодировка {кодировка}, разделитель «{знак}»")
    чтец = csv.reader(io.StringIO(текст.lstrip("﻿")), delimiter=знак)
    строки = [[_схлопнуть(я) for я in строка] for строка in чтец]
    return [с for с in строки if any(с)]


