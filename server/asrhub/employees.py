#: Готовая таблица «заголовок → поле». Собирается один раз: разбор строки
#: заголовков идёт по каждому файлу, и перебирать словарь синонимов на
#: каждую колонку — лишняя работа на ровном месте.
_ПО_ЗАГОЛОВКУ: dict[str, str] = {}

#: Поля карточки, которые заполняются из колонок выгрузки. `note` сюда не
#: входит: он собирается из неузнанных колонок, а не приходит колонкой.
ПОЛЯ = tuple(СИНОНИМЫ)

_ПРОБЕЛЫ = re.compile(r"\s+")
_НЕ_ЦИФРА = re.compile(r"\D")
#: Что вычищается из телефона: пробелы (в том числе неразрывный), скобки,
#: дефисы всех видов, точки. Плюс остаётся — это код страны.
_МУСОР_В_НОМЕРЕ = re.compile(r"[\s ()\[\].\-–—_/\\]+")

#: Значения «работает» и «не работает» во всех видах, что встречались.
#: Пустое значение сюда не входит: оно означает «колонку не заполнили», и
#: считать такого человека уволенным нельзя (см. `_работает`).
_ДА = frozenset({"да", "yes", "y", "true", "1", "+", "работает", "активен",
                 "active", "вкл", "включен", "включён", "истина", "есть"})
_НЕТ = frozenset({"нет", "no", "n", "false", "0", "-", "—", "не работает",
                  "уволен", "уволена", "уволился", "уволилась", "неактивен",
                  "inactive", "disabled", "выкл", "выключен", "ложь",
                  "отсутствует"})


def _схлопнуть(текст: Any) -> str:
    """Строка без краевых и двойных пробелов. Внутри — один пробел.

    Лишние пробелы приезжают отовсюду: из объединённых ячеек, из переносов
    строк внутри `<Data>`, из копирования в Excel. «Иванов  Иван» и
    «Иванов Иван» — это один человек, а без схлопывания это две разные
    строки, два разных ключа и две карточки.
    """
    if текст is None:
        return ""
    return _ПРОБЕЛЫ.sub(" ", str(текст)).strip()


def _ключ_заголовка(заголовок: Any) -> str:
    """Заголовок в виде, пригодном для поиска в таблице синонимов.

    Нижний регистр, схлопнутые пробелы, `ё` → `е`. Регистр и пробелы в
    выгрузках гуляют («Тел. Внутренний», «ФАМИЛИЯ»), а `ё` в заголовке —
    это ровно тот случай, когда её писать не обязательно: «Электропочта» и
    «Электропочта» через `ё` должны попасть в одно поле.
    """
    return _схлопнуть(заголовок).lower().replace("ё", "е")


def _без_знаков(ключ: str) -> str:
    """То же, но без точек и прочих знаков: «тел. рабочий» → «тел рабочий»."""
    return _схлопнуть(re.sub(r"[^0-9a-zа-я_ ]+", " ", ключ))


def _собрать_таблицу() -> None:
    """Раскладывает синонимы в плоскую таблицу поиска.

    Каждый синоним кладётся дважды: как есть и без знаков препинания.
    Выгрузка пишет «тел. внутренний», «тел внутренний» и «тел.внутренний» —
    это одна и та же колонка, и заводить три синонима на каждую форму
    значит однажды забыть четвёртую.
    """
    for поле, названия in СИНОНИМЫ.items():
        for название in названия:
            ключ = _ключ_заголовка(название)
            _ПО_ЗАГОЛОВКУ.setdefault(ключ, поле)
            _ПО_ЗАГОЛОВКУ.setdefault(_без_знаков(ключ), поле)
            _ПО_ЗАГОЛОВКУ.setdefault(ключ.replace(" ", ""), поле)
    # Имена колонок базы всегда подходят сами себе — на случай, если
    # выгрузку делали прямо из этой же таблицы.
    for поле in СИНОНИМЫ:
        _ПО_ЗАГОЛОВКУ.setdefault(поле, поле)


_собрать_таблицу()


def поле_заголовка(заголовок: Any) -> str:
    """Поле карточки по заголовку колонки или пустая строка, если не узнали."""
    ключ = _ключ_заголовка(заголовок)
    поле = _ПО_ЗАГОЛОВКУ.get(ключ)
    if поле:
        return поле
    return _ПО_ЗАГОЛОВКУ.get(_без_знаков(ключ)) or _ПО_ЗАГОЛОВКУ.get(
        ключ.replace(" ", "")) or ""


