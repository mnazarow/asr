"""Справочник сотрудников: разбор выгрузок и их приём в базу.

Звонок с АТС приносит внутренний номер оператора — «1043». Так он и стоит
в журнале, в отчёте и в карточке разговора, и человек, читающий отчёт,
каждый раз идёт выяснять в чужую таблицу, кто это. Справочник закрывает
ровно это: номер превращается в «Петрова Мария Ивановна, отдел снабжения».

Выгрузку даёт кадровая система или внутренний портал, и почти всегда это
**Excel XML 2003 (SpreadsheetML)** — тот самый «Excel.Sheet», который
отдают 1С, SharePoint и добрая половина самописных справочников. Реже
встречаются CSV и JSON; их разбираем тем же кодом, потому что заголовки
колонок у всех трёх одинаковые, а различается только способ добраться до
строки с ячейками.

Что здесь важно знать заранее:

* **Колонки не привязаны к порядку.** Справочник в следующем квартале
  поменяет местами «отдел» и «должность» или вставит новую колонку в
  середину — и всё поедет, если читать по номерам. Читаем по заголовкам,
  приведённым к нижнему регистру, со схлопнутыми пробелами и по таблице
  синонимов: и русские названия, и английские.
* **Неизвестная колонка не теряется.** Она уходит в `note` строкой
  «колонка: значение». Кадровик, добавивший колонку «кабинет», не должен
  обнаруживать, что сервер молча её съел.
* **Одна испорченная строка не роняет импорт.** Всё, что не разобралось,
  превращается в замечание с номером строки, а остальные люди всё равно
  попадают в базу. Выгрузка на тысячу человек с одной кривой датой — это
  999 заведённых карточек и одно замечание, а не пустой справочник.
* **Разбор XML недоверенный.** Файл приезжает по внешнему адресу, а
  разбор XML со включёнными сущностями — это чтение файлов сервера и
  «миллиард смешков» (см. `_разобрать_xml`).

Записи отдаются наружу словарями с латинскими ключами — ровно теми, что
перечислены в `Database.ПОЛЯ_СОТРУДНИКА`: этот модуль ничего не пишет в
базу сам, он готовит данные для `db.employees_import`.
"""
