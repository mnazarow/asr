class _БезDTD(ET.TreeBuilder):
    """Сборщик дерева, отвергающий документы с объявлением типа (DTD).

    Почему так, а не «просто разобрать». Файл приезжает по адресу из
    настройки, то есть содержимое недоверенное, а разбор XML с включённым
    объявлением типа — это две настоящие дыры сразу:

    * **XXE.** `<!ENTITY x SYSTEM "file:///etc/shadow">` заставляет
      разборщик подставить в ячейку содержимое файла сервера — и оно
      уезжает в карточку сотрудника, откуда его спокойно читают через API.
    * **«Миллиард смешков».** Десяток вложенных друг в друга внутренних
      сущностей разворачивается в гигабайты текста и кладёт сервер по
      памяти, а файл при этом весит килобайт.

    В стандартной библиотеке `xml.etree.ElementTree` внешние сущности не
    подставляет сам (документация раздела «XML vulnerabilities» называет
    его safe по этому пункту: неизвестная сущность даёт `ParseError`), но
    от разрастания ВНУТРЕННИХ сущностей он не защищён никак — это
    задокументированная уязвимость, и закрывать её надо здесь.

    Отдельного «безопасного режима» у `ElementTree` нет, а у C-версии
    `XMLParser` нет и доступа к expat-разборщику (`parser.parser`
    существует только в чистой реализации), так что выставить
    `EntityDeclHandler` снаружи нельзя. Зато документация сама предлагает
    определить `doctype()` у цели разбора — и это единственный способ,
    который работает на обеих реализациях: любой `<!DOCTYPE …>` приводит
    сюда, а без DOCTYPE объявить сущность негде.

    Выгрузка Excel DOCTYPE не содержит и содержать не может, поэтому
    ложных срабатываний тут нет: если он есть, файл сделан не Excel'ем.
    """

    def doctype(self, name: str, pubid: str, system: str) -> None:  # noqa: D102
        raise РазметкаОтвергнута(
            f"В файле выгрузки объявлен тип документа (<!DOCTYPE {name}>). "
            "Такие файлы не разбираются: через объявление типа в XML "
            "подставляют содержимое файлов сервера и раздувают документ до "
            "гигабайтов.")


_ПРЕФИКС_ТЕГА = re.compile(rb"</?([A-Za-z_][\w.\-]*):")
_ПРЕФИКС_АТРИБУТА = re.compile(rb"[\s\"']([A-Za-z_][\w.\-]*):[A-Za-z_][\w.\-]*\s*=")
_КОРНЕВОЙ_ТЕГ = re.compile(rb"<([A-Za-z_][\w.\-:]*)((?:\"[^\"]*\"|'[^']*'|[^>\"'])*)>")
_ОБЪЯВЛЕНИЕ = re.compile(rb"encoding\s*=\s*([\"'])([^\"']+)\1")


def _в_байты(данные: bytes | str) -> bytes:
    """XML всегда разбираем из байтов — из-за объявления кодировки.

    `ElementTree` отказывается разбирать строку, в которой написано
    `<?xml … encoding="windows-1251"?>`: «Unicode strings with encoding
    declaration are not supported». Байты он разбирает по объявленной
    кодировке сам и не ошибается. Поэтому строку кодируем в utf-8 и правим
    объявление под неё — иначе разборщик прочитал бы utf-8 как cp1251 и
    выдал бы вместо фамилий кракозябры.
    """
    if isinstance(данные, bytes):
        return данные
    текст = данные.encode("utf-8")
    return _ОБЪЯВЛЕНИЕ.sub(b'encoding="utf-8"', текст, count=1)


def _объявить_пространства(данные: bytes) -> bytes:
    """Дописывает в корневой тег объявления для префиксов, которых в нём нет.

    В SpreadsheetML префикс `ss:` стоит почти на каждом атрибуте, но
    объявлен он не везде: выгрузки, собранные строками в шаблонизаторе,
    сплошь и рядом теряют `xmlns:ss` в корне. Для XML это не «мелкая
    небрежность», а неправильный документ: разборщик падает с «unbound
    prefix» на первой же ячейке, и справочник не читается совсем.

    Чинить такой файл руками ради одной строки в корне — не дело, поэтому
    недостающие объявления дописываются здесь. Адрес пространства имён
    значения не имеет: дальше мы всё равно смотрим только на локальные
    имена тегов и атрибутов.
    """
    совпадение = _КОРНЕВОЙ_ТЕГ.search(данные)
    if совпадение is None:
        return данные
    префиксы = set(_ПРЕФИКС_ТЕГА.findall(данные))
    префиксы |= set(_ПРЕФИКС_АТРИБУТА.findall(данные))
    префиксы.discard(b"xmlns")
    добавить = [п for п in sorted(префиксы)
                if b"xmlns:" + п not in данные]
    if not добавить:
        return данные
    вставка = b"".join(
        b' xmlns:%s="%s"' % (п, NS_SS.encode() if п == b"ss"
                             else b"urn:asrhub:undeclared:" + п)
        for п in добавить)
    начало, конец = совпадение.span()
    тег = данные[начало:конец]
    # Самозакрывающийся корень («<Workbook/>») — вставляем перед «/>».
    хвост = b"/>" if тег.endswith(b"/>") else b">"
    тело = тег[:-len(хвост)]
    return данные[:начало] + тело + вставка + хвост + данные[конец:]


def _разобрать_xml(данные: bytes | str) -> ET.Element:
    """Корень документа. Объявления типа отвергаются, префиксы чинятся.

    Разбор идёт ровно два раза: первый — как есть, второй — с дописанными
    объявлениями пространств имён, и только если первый упал именно на
    необъявленном префиксе. Городить починку в общем случае нельзя:
    подменять содержимое файла до разбора — верный способ однажды
    «починить» правильный документ.
    """
    сырые = _в_байты(данные)
    try:
        return ET.fromstring(сырые, parser=ET.XMLParser(target=_БезDTD()))
    except ET.ParseError as ошибка:
        if "unbound prefix" not in str(ошибка).lower():
            raise ConfigError(
                f"Файл выгрузки не разбирается как XML: {ошибка}",
                hint="Проверьте, что скачался сам файл, а не страница входа "
                     "или сообщение об ошибке от веб-сервера.") from ошибка
    исправленные = _объявить_пространства(сырые)
    try:
        return ET.fromstring(исправленные, parser=ET.XMLParser(target=_БезDTD()))
    except ET.ParseError as ошибка:
        raise ConfigError(
            f"Файл выгрузки не разбирается как XML: {ошибка}",
            hint="В файле не объявлены пространства имён, и дописать их не "
                 "получилось. Пересохраните справочник из Excel как "
                 "«Таблица XML 2003».") from ошибка


def _локальное(имя: str) -> str:
    """Имя тега или атрибута без пространства имён и без префикса."""
    без_ns = имя.rsplit("}", 1)[-1]
    return без_ns.rsplit(":", 1)[-1].lower()


def _атрибут(элемент: ET.Element, имя: str) -> str:
    """Значение атрибута по локальному имени: `ss:Index` и `Index` — одно."""
    for ключ, значение in элемент.attrib.items():
        if _локальное(ключ) == имя.lower():
            return значение
    return ""


def _значение_ячейки(ячейка: ET.Element) -> str:
    """Текст ячейки со всей разметкой внутри, схлопнутый в одну строку.

    Внутри `<Data>` встречается разметка: Excel хранит там оформленные
    куски (`<Данные>Иванов <span>(ЧЛБ)</span></Данные>` — ровно так
    выглядит пометка филиала в справочнике заказчика). `.text` вернул бы
    только «Иванов » и потерял бы «(ЧЛБ)», поэтому берётся `itertext()` —
    весь текст вместе с вложенными узлами и их хвостами.

    Пустая ячейка `<Cell><Data ss:Type="String"/></Cell>` даёт пустую
    строку, а не `None`: дальше с ней работают как с обычным значением.
    """
    данные = None
    for ребёнок in ячейка:
        if _локальное(ребёнок.tag) == "data":
            данные = ребёнок
            break
    if данные is None:
        # Ячейка без <Data> — бывает у оформительских колонок; текст всё
        # равно забираем: вдруг он там есть.
        return _схлопнуть("".join(ячейка.itertext()))
    текст = _схлопнуть("".join(данные.itertext()))
    тип = _атрибут(данные, "type").lower()
    if тип == "number":
        # Excel хранит внутренние номера числами, и «1043» приезжает как
        # «1043.0». Без подрезки такой номер не совпадёт с полем `agent`
        # в журнале звонков ни в одном разговоре.
        if re.fullmatch(r"-?\d+\.0+", текст):
            текст = текст.split(".", 1)[0]
    elif тип == "datetime":
        # «2026-03-01T00:00:00.000» — это дата, а время в ней служебное.
        совпадение = re.fullmatch(r"(\d{4}-\d{2}-\d{2})T00:00:00(?:\.0+)?", текст)
        if совпадение:
            текст = совпадение.group(1)
        else:
            текст = текст.replace("T", " ")
    return текст


def _строки_листа(таблица: ET.Element) -> list[list[str]]:
    """Строки таблицы списками значений ячеек — с уважением к `ss:Index`.

    `ss:Index` — это «следующая ячейка стоит в такой-то колонке»: пустые
    ячейки Excel просто не пишет. Пропустить этот атрибут значит сдвинуть
    все последующие значения строки влево: у человека без рабочего
    телефона мобильный окажется в колонке рабочего, почта — в колонке
    мобильного, а поставщики — в почте. Такой импорт выглядит успешным и
    портит справочник целиком.
    """
    строки: list[list[str]] = []
    for ряд in таблица:
        if _локальное(ряд.tag) != "row":
            continue
        значения: list[str] = []
        позиция = 0
        for ячейка in ряд:
            if _локальное(ячейка.tag) != "cell":
                continue
            индекс = _атрибут(ячейка, "index")
            if индекс:
                try:
                    позиция = max(позиция, int(индекс) - 1)
                except (TypeError, ValueError):
                    # Испорченный ss:Index — не повод терять строку целиком,
                    # но и доверять ему нельзя: продолжаем по порядку.
                    pass
            while len(значения) < позиция:
                значения.append("")
            значения.append(_значение_ячейки(ячейка))
            позиция = len(значения)
        строки.append(значения)
    return строки


def _листы(корень: ET.Element) -> list[tuple[str, list[list[str]]]]:
    """Листы книги: имя и строки. Имя берётся из `ss:Name`."""
    листы: list[tuple[str, list[list[str]]]] = []
    for лист in корень.iter():
        if _локальное(лист.tag) != "worksheet":
            continue
        имя = _атрибут(лист, "name") or f"лист {len(листы) + 1}"
        for таблица in лист:
            if _локальное(таблица.tag) == "table":
                листы.append((имя, _строки_листа(таблица)))
                break
    if not листы:
        # Книга без <Worksheet> — бывает у выгрузок, отдающих сразу
        # <Table>. Берём все таблицы, какие есть.
        for таблица in корень.iter():
            if _локальное(таблица.tag) == "table":
                листы.append((f"лист {len(листы) + 1}", _строки_листа(таблица)))
    return листы


def _разобрать_spreadsheetml(данные: bytes | str, итог: Разбор) -> list[list[str]]:
    """Строки первого пригодного листа книги.

    Листов в книге бывает несколько, и разбирается только первый, в
    котором заголовки узнаются. Остальные попадают в замечания. Сводить
    листы в один список нельзя: второй лист в справочниках — это почти
    всегда легенда, список отделов или «лист1» из шаблона, и вклеивать его
    строки к людям значит заводить карточки с фамилией «Сокращения».
    """
    листы = _листы(_разобрать_xml(данные))
    if not листы:
        raise ConfigError(
            "В файле выгрузки нет ни одной таблицы.",
            hint="Ожидается книга Excel XML 2003: <Workbook> → <Worksheet> → "
                 "<Table> → <Row>. Проверьте, что выгрузка сохранена в этом формате.")
    выбран: list[list[str]] = []
    имя_выбранного = ""
    пропущенные: list[str] = []
    for имя, строки in листы:
        осмысленные = [с for с in строки if any(_схлопнуть(з) for з in с)]
        if not выбран and len(осмысленные) >= 2 and _есть_заголовки(осмысленные[0]):
            выбран, имя_выбранного = осмысленные, имя
        elif осмысленные:
            пропущенные.append(имя)
    if not выбран:
        # Ни на одном листе заголовки не узнались — берём первый непустой
        # и разбираем как есть: пусть человек увидит замечания про
        # неизвестные колонки, а не пустой ответ без объяснений.
        for имя, строки in листы:
            осмысленные = [с for с in строки if any(_схлопнуть(з) for з in с)]
            if len(осмысленные) >= 2:
                выбран, имя_выбранного = осмысленные, имя
                пропущенные = [и for и, _ in листы if и != имя]
                break
    if пропущенные:
        итог.замечание("разобран лист «" + имя_выбранного + "»; пропущены: "
                       + ", ".join(f"«{и}»" for и in пропущенные))
    return выбран


def _есть_заголовки(строка: list[str]) -> bool:
    """Похожа ли строка на строку заголовков.

    Достаточно двух узнанных колонок: справочник без фамилии и хоть
    какого-то второго поля бесполезен, а одна случайно совпавшая ячейка
    («Имя» в шапке отчёта) заголовком строку не делает.
    """
    узнано = sum(1 for ячейка in строка if поле_заголовка(ячейка))
    return узнано >= 2


