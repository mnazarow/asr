#: Где в объекте искать список людей, если пришёл не голый список.
ГНЁЗДА = ("items", "employees", "records", "data", "rows", "result", "list")


def _разобрать_json(данные: bytes | str) -> list[dict[str, Any]]:
    """Список объектов из JSON — хоть голым списком, хоть в обёртке."""
    текст = _декодировать(данные)[0] if isinstance(данные, bytes) else данные
    try:
        разобрано = json.loads(текст)
    except ValueError as ошибка:
        raise ConfigError(
            f"Файл выгрузки не разбирается как JSON: {ошибка}",
            hint="Проверьте, что по адресу отдаётся сам справочник, а не "
                 "страница входа и не сообщение об ошибке.") from ошибка
    if isinstance(разобрано, dict):
        for гнездо in ГНЁЗДА:
            вложенное = разобрано.get(гнездо)
            if isinstance(вложенное, list):
                разобрано = вложенное
                break
        else:
            # Один человек одним объектом — тоже выгрузка, пусть и из одного.
            разобрано = [разобрано]
    if not isinstance(разобрано, list):
        raise ConfigError(
            "В JSON ожидался список сотрудников.",
            hint="Допустимы список объектов или объект с полем items/employees.")
    return [з for з in разобрано if isinstance(з, dict)]


