@dataclass
class Разбор:
    """Что вышло из выгрузки: карточки, замечания и счётчики.

    Замечания — не ошибки, а то, что человек должен увидеть после импорта:
    непонятая строка, повторившийся ключ, подозрительный адрес почты.
    Импорт из-за них не отменяется.
    """

    записи: list[dict[str, Any]] = field(default_factory=list)
    замечания: list[str] = field(default_factory=list)
    формат: str = ""
    #: Сколько строк с людьми было в выгрузке (строка заголовков не в счёт).
    строк: int = 0
    #: Сколько из них не стало карточками.
    пропущено: int = 0
    #: Почему пропустили: причина → сколько раз.
    причины: dict[str, int] = field(default_factory=dict)
    #: Заголовки, которые не удалось сопоставить ни с одним полем.
    неизвестные: list[str] = field(default_factory=list)

    def замечание(self, текст: str) -> None:
        """Добавляет замечание, не давая списку разрастись без предела."""
        if len(self.замечания) < МАКС_ЗАМЕЧАНИЙ:
            self.замечания.append(текст)
        elif len(self.замечания) == МАКС_ЗАМЕЧАНИЙ:
            self.замечания.append(
                f"…замечаний больше {МАКС_ЗАМЕЧАНИЙ}, остальные не показаны")

    def пропустить(self, причина: str) -> None:
        self.пропущено += 1
        self.причины[причина] = self.причины.get(причина, 0) + 1

    def to_dict(self) -> dict[str, Any]:
        return {"format": self.формат, "rows": self.строк,
                "parsed": len(self.записи), "skipped": self.пропущено,
                "skip_reasons": dict(self.причины),
                "notes": list(self.замечания),
                "unknown_columns": list(self.неизвестные)}


