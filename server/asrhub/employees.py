def _карточка(пары: list[tuple[str, str]], итог: Разбор,
              номер: int) -> dict[str, Any] | None:
    """Одна карточка из пар «заголовок — значение».

    Возвращает `None`, если строка не человек: без фамилии и имени карточку
    заводить не на кого, а строки-разделители и итоговые строки в выгрузках
    встречаются постоянно.
    """
    поля: dict[str, Any] = {}
    хвост: list[str] = []
    for заголовок, значение in пары:
        поле = поле_заголовка(заголовок)
        значение = _схлопнуть(значение)
        if not поле:
            # Неизвестная колонка не теряется: её видно в карточке, и по
            # ней понятно, что в справочнике появилось новое поле.
            if значение:
                хвост.append(f"{_схлопнуть(заголовок) or '?'}: {значение}")
            continue
        if поле in поля and поля[поле] and значение:
            # Две колонки легли в одно поле (например, «почта» и «email»).
            # Первую не затираем: она стояла раньше и, скорее всего, главная.
            хвост.append(f"{_схлопнуть(заголовок)}: {значение}")
            continue
        поля[поле] = значение

    фамилия = _фио(поля.get("last_name"))
    имя = _фио(поля.get("first_name"))
    отчество = _фио(поля.get("middle_name"))
    if not фамилия and not имя:
        return None

    адрес_почты = почта(поля.get("email"))
    if адрес_почты and not похоже_на_адрес(адрес_почты):
        итог.замечание(f"строка {номер}: «{адрес_почты}» не похоже на адрес почты — "
                       "значение сохранено как есть")

    карточка: dict[str, Any] = {
        "last_name": фамилия,
        "first_name": имя,
        "middle_name": отчество,
        "position": _схлопнуть(поля.get("position")),
        "department": _схлопнуть(поля.get("department")),
        "phone_work": рабочий(поля.get("phone_work")),
        "phone_ext": внутренний(поля.get("phone_ext")),
        "phone_mobile": мобильный(поля.get("phone_mobile")),
        "email": адрес_почты,
        "suppliers": _схлопнуть(поля.get("suppliers")),
        "active_until": _дата(поля.get("active_until")),
        # Признак «работает» кладём числом, а не булевым. Импорт в базе
        # сравнивает прежнее значение с новым через `str()`, а в базе
        # лежит 1: «True» != «1», и каждый повторный импорт считал бы всех
        # до одного изменившимися, поднимая «обновлено» до размера штата.
        "active": 1 if _работает(поля.get("active")) else 0,
    }
    # Примечание кладём, только если в выгрузке действительно нашлось, что
    # в него положить. Пустое значение затирало бы примечание, написанное
    # человеком руками, при каждом обновлении справочника — а пишут туда
    # как раз то, чего в выгрузке нет («в декрете до осени»).
    if хвост:
        карточка["note"] = "; ".join(хвост)
    return карточка


def _проставить_ключи(записи: list[dict[str, Any]], итог: Разбор) -> None:
    """Внешний ключ каждой карточки — тот, по которому её узнают потом.

    Почему именно так.

    Ключ должен переживать повторный импорт: по нему `db.employees_import`
    решает, завести карточку или обновить существующую. Кандидатов ровно
    два, и оба неидеальны.

    * **Внутренний номер.** Самое устойчивое, что есть в справочнике:
      фамилия меняется (замужество, смена документов), должность и отдел
      меняются, а номер за столом — почти никогда. И это именно то поле,
      по которому звонок находит человека.
    * **«фамилия|имя|отчество» в нижнем регистре.** Работает всегда, но
      разваливается на полных тёзках и меняется вместе с фамилией.

    Поэтому номер берётся, только если он есть и **уникален в этой
    выгрузке**. Неуникальный номер — это комната на двоих, общий телефон
    склада или дежурная линия, и заводить по нему одну карточку значит
    склеить двух людей в одного: второй перезапишет первого, и половина
    штата исчезнет молча. Когда номер не годится, остаётся ФИО.

    **Что будет при смене номера.** Ключ карточки изменится, и при
    следующем импорте прежняя карточка не найдётся среди приехавших: с
    `deactivate_missing` она станет «не работает», а рядом появится новая
    с тем же человеком. Звонки старого номера останутся привязанными к
    старой карточке — и это правильно: разговоры велись тогда, когда номер
    был тот. Лечится это одним действием — удалить старую карточку
    (`DELETE /api/employees/{id}`), если дубль не нужен; замечание об этом
    в импорт не попадает, потому что отличить смену номера от увольнения и
    выхода нового человека на то же место по выгрузке невозможно.

    Тёзки, попавшие в один ключ, из справочника видны сразу, поэтому про
    них замечание есть.
    """
    сколько: dict[str, int] = {}
    for запись in записи:
        номер = str(запись.get("phone_ext") or "")
        if номер:
            сколько[номер] = сколько.get(номер, 0) + 1
    занятые: dict[str, int] = {}
    for позиция, запись in enumerate(записи, start=1):
        номер = str(запись.get("phone_ext") or "")
        if номер and сколько.get(номер) == 1:
            ключ = номер
        else:
            ключ = "|".join((str(запись.get("last_name") or ""),
                             str(запись.get("first_name") or ""),
                             str(запись.get("middle_name") or ""))).lower()
            if номер:
                итог.замечание(
                    f"внутренний номер {номер} встречается "
                    f"{сколько.get(номер)} раза — карточки этих людей "
                    "опознаются по ФИО")
        запись["external_id"] = ключ
        предыдущая = занятые.get(ключ)
        if предыдущая is not None:
            итог.замечание(
                f"строки {предыдущая} и {позиция}: одинаковый ключ «{ключ}» — "
                "в справочнике останется одна карточка")
        занятые[ключ] = позиция


def _из_таблицы(строки: list[list[str]], итог: Разбор) -> None:
    """Таблица (CSV или лист книги) в карточки."""
    if len(строки) < 2:
        raise ConfigError(
            "В выгрузке нет ни одной строки с людьми.",
            hint="Первая строка — заголовки колонок, дальше по строке на "
                 "сотрудника. Проверьте, что скачался нужный файл.")
    заголовки = строки[0]
    неизвестные = [_схлопнуть(з) for з in заголовки
                   if _схлопнуть(з) and not поле_заголовка(з)]
    итог.неизвестные = неизвестные
    if неизвестные:
        итог.замечание("колонки без известного поля (уйдут в примечание): "
                       + ", ".join(f"«{з}»" for з in неизвестные))
    если_нет_фио = [п for п in ("last_name", "first_name")
                    if п not in {поле_заголовка(з) for з in заголовки}]
    if len(если_нет_фио) == 2:
        raise ConfigError(
            "В выгрузке не найдено ни колонки с фамилией, ни колонки с именем.",
            hint="Ожидаются заголовки «фамилия», «имя», «отчество», "
                 "«должность», «отдел», «тел. внутренний» и им подобные. "
                 f"Найдено: {', '.join(_схлопнуть(з) for з in заголовки[:12]) or '—'}.")

    for позиция, строка in enumerate(строки[1:], start=2):
        итог.строк += 1
        try:
            пары = [(заголовки[н] if н < len(заголовки) else f"колонка {н + 1}",
                     значение)
                    for н, значение in enumerate(строка)]
            карточка = _карточка(пары, итог, позиция)
        except Exception as ошибка:                          # noqa: BLE001
            # Сюда попадает всё неожиданное в одной строке. Ронять из-за
            # неё импорт тысячи человек нельзя: строка называется по
            # номеру, и её правят в выгрузке.
            итог.замечание(f"строка {позиция}: не разобрана ({ошибка})")
            итог.пропустить("не разобрана")
            continue
        if карточка is None:
            итог.пропустить("нет фамилии и имени")
            continue
        итог.записи.append(карточка)


def _из_объектов(объекты: list[dict[str, Any]], итог: Разбор) -> None:
    """Список объектов JSON в карточки — через ту же таблицу синонимов."""
    неизвестные: list[str] = []
    for позиция, объект in enumerate(объекты, start=1):
        итог.строк += 1
        try:
            пары = [(str(ключ), "" if значение is None else str(значение))
                    for ключ, значение in объект.items()]
            for ключ, _ in пары:
                if not поле_заголовка(ключ) and ключ not in неизвестные:
                    неизвестные.append(ключ)
            карточка = _карточка(пары, итог, позиция)
        except Exception as ошибка:                          # noqa: BLE001
            итог.замечание(f"запись {позиция}: не разобрана ({ошибка})")
            итог.пропустить("не разобрана")
            continue
        if карточка is None:
            итог.пропустить("нет фамилии и имени")
            continue
        итог.записи.append(карточка)
    итог.неизвестные = неизвестные
    if неизвестные:
        итог.замечание("поля без известного соответствия (уйдут в примечание): "
                       + ", ".join(f"«{з}»" for з in неизвестные))


