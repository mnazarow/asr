#: Как называть формат, что бы ни передали в `тип`.
_ИМЕНА_ФОРМАТОВ = {
    "xml": "xml", "spreadsheetml": "xml", "excel": "xml", "xls": "xml",
    "excel_xml": "xml", "таблица": "xml",
    "xlsx": "xlsx", "excel2007": "xlsx",
    "csv": "csv", "tsv": "csv", "текст": "csv",
    "json": "json",
}

#: Начало архива ZIP (книга .xlsx) и составного документа OLE (старый
#: двоичный .xls).
_ZIP = b"PK\x03\x04"
_OLE = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"
#: Имя потока зашифрованной книги в каталоге составного документа (UTF-16).
_ЗАШИФРОВАНО = "EncryptedPackage".encode("utf-16-le")


def определить_тип(данные: bytes | str) -> str:
    """Формат выгрузки по её содержимому: xml, xlsx, json или csv.

    По содержимому, а не по имени файла и не по типу из заголовка ответа:
    веб-серверы отдают выгрузку как `application/octet-stream`, а
    справочник, сохранённый Excel'ем как «Таблица XML 2003», сплошь и
    рядом лежит с расширением `.xls`.
    """
    if isinstance(данные, bytes):
        if данные.startswith(_ZIP):
            return "xlsx"
        if данные.startswith(_OLE):
            # В том же двоичном контейнере Excel хранит и книгу .xlsx под
            # паролем: зашифрованный пакет лежит в нём потоком
            # «EncryptedPackage». Совет «пересохраните как .xlsx» такому
            # файлу не помогает — сначала надо снять пароль.
            if _ЗАШИФРОВАНО in данные[:1 << 20]:
                raise ConfigError(
                    "Книга Excel защищена паролем — сервер такую не прочтёт.",
                    hint="Откройте файл в Excel, снимите пароль (Файл → Сведения → "
                         "Защитить книгу) и сохраните как «Книга Excel (.xlsx)» или CSV.")
            raise ConfigError(
                "Это старый двоичный формат Excel (.xls) — его сервер не читает.",
                hint="Откройте файл в Excel и сохраните как «Книга Excel (.xlsx)», "
                     "«Таблица XML 2003» или «CSV (разделители — точка с запятой)».")
    начало = данные[:4096]
    if isinstance(начало, bytes):
        начало = начало.decode("utf-8", errors="replace")
    начало = начало.lstrip("﻿ \t\r\n")
    if начало.startswith("<"):
        return "xml"
    if начало.startswith(("{", "[")):
        return "json"
    return "csv"


def разобрать_подробно(данные: bytes | str, *, тип: str = "") -> Разбор:
    """Разбор с замечаниями и счётчиками — то, что показывается человеку."""
    итог = Разбор()
    формат = _ИМЕНА_ФОРМАТОВ.get(_схлопнуть(тип).lower(), "")
    if тип and not формат:
        raise ConfigError(
            f"Неизвестный формат выгрузки: «{тип}».",
            hint="Допустимые значения: xml (Excel XML 2003), xlsx, csv, json — "
                 "или пусто, чтобы определить по содержимому.")
    итог.формат = формат or определить_тип(данные)
    if not данные or not _схлопнуть(
            данные[:64].decode("utf-8", errors="replace")
            if isinstance(данные, bytes) else данные[:64]):
        raise ConfigError(
            "Выгрузка пуста.",
            hint="Проверьте адрес: по нему должен отдаваться файл справочника.")

    if итог.формат == "xlsx":
        if not isinstance(данные, bytes):
            raise ConfigError("Книгу .xlsx нужно присылать файлом, а не текстом.")
        _из_таблицы(_разобрать_xlsx(данные, итог), итог)
    elif итог.формат == "xml":
        _из_таблицы(_разобрать_spreadsheetml(данные, итог), итог)
    elif итог.формат == "json":
        _из_объектов(_разобрать_json(данные), итог)
    else:
        _из_таблицы(_разобрать_csv(данные, итог), итог)

    _проставить_ключи(итог.записи, итог)
    return итог


def разобрать(данные: bytes | str, *, тип: str = "") -> list[dict[str, Any]]:
    """Выгрузка справочника — списком карточек сотрудника.

    Формат определяется по содержимому, если не задан явно: `xml`
    (Excel XML 2003), `csv`, `json`. Ключи карточки — латинские, те же,
    что и колонки таблицы `employees`, поэтому её можно отдавать прямо в
    `db.employees_import`.

    Замечания разбора здесь не возвращаются — за ними в
    `разобрать_подробно`. Отдельные две функции нужны затем, чтобы простой
    случай («дай мне людей») читался одной строкой, а импорту досталось
    всё, что он обязан показать человеку.
    """
    return разобрать_подробно(данные, тип=тип).записи


