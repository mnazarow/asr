#: Сколько внутренних номеров брать из журнала звонков при сверке. Разрез
#: по оператору — это список различных значений колонки `agent`; в живой
#: организации их сотни, тысяча берётся с запасом на исторические номера.
НОМЕРОВ_ИЗ_ЗВОНКОВ = 1000


def _номера_из_звонков(db: Any, *, owner: Any = None,
                       since: float | None = None) -> dict[str, dict[str, Any]]:
    """Внутренние номера из журнала звонков со счётчиками.

    Берётся тем же разрезом, что и в разделе «АТС» (`db.call_tops`), —
    чтобы «звонков у сотрудника» здесь и «звонков у оператора» там были
    одним и тем же числом, а не двумя похожими.
    """
    разрез = db.call_tops("agent", owner=owner, since=since,
                          limit=НОМЕРОВ_ИЗ_ЗВОНКОВ)
    return {str(строка["value"]): строка for строка in разрез if строка.get("value")}


def статистика(db: Any, *, owner: Any = None) -> dict[str, Any]:
    """Сводка по справочнику: сколько людей, отделов и кто виден в звонках.

    Главное число здесь — последнее: сколько сотрудников с внутренним
    номером реально встречается в журнале звонков. Справочник, в котором
    номера есть у всех, но ни один не совпал с журналом, — это не
    справочник, а другая нумерация (с префиксом филиала, с иным числом
    цифр), и увидеть это надо сразу, а не через месяц по пустым отчётам.
    """
    по_отделам = db.employee_departments()
    всего = sum(int(о.get("n") or 0) for о in по_отделам)
    работают = sum(int(о.get("active") or 0) for о in по_отделам)
    # Считаем в базе, а не перебором справочника: тащить тысячу карточек в
    # память ради двух чисел незачем.
    строки = db.query(
        "SELECT phone_ext, active FROM employees WHERE COALESCE(phone_ext,'')<>''")
    номера = {str(с["phone_ext"]): int(с["active"] or 0) for с in строки}
    из_звонков = _номера_из_звонков(db, owner=owner)
    совпали = sorted(set(номера) & set(из_звонков))
    звонков = sum(int(из_звонков[н].get("count") or 0) for н in совпали)
    return {
        "total": всего,
        "active": работают,
        "inactive": всего - работают,
        "with_ext": len(номера),
        "with_ext_active": sum(1 for флаг in номера.values() if флаг),
        "departments": по_отделам,
        "departments_count": len([о for о in по_отделам if о.get("department")]),
        "matched_in_calls": len(совпали),
        "calls_matched": звонков,
        # Номера из журнала, которых в справочнике нет: это либо уволенные,
        # либо очереди и служебные линии, либо чужая нумерация.
        "unknown_agents": sorted(set(из_звонков) - set(номера))[:50],
        "unknown_agents_count": len(set(из_звонков) - set(номера)),
    }


def связать(db: Any, *, owner: Any = None, since: float | None = None,
            limit: int = 500) -> dict[str, Any]:
    """Пересчитывает, сколько звонков приходится на каждого сотрудника.

    Архив не меняется: связь считается на лету по совпадению внутреннего
    номера с полем `agent` в журнале звонков. Так и правильнее — звонок
    принадлежит номеру, а не человеку: за год за одним столом сменится
    двое, и переписать старые разговоры на нового сотрудника значило бы
    подделать его отчёт.

    Возвращает список сотрудников со счётчиками и, отдельно, номера из
    журнала, которых в справочнике нет, — по ним и видно, что нумерация
    разъехалась.
    """
    из_звонков = _номера_из_звонков(db, owner=owner, since=since)
    справочник = db.employee_list(limit=max(1, int(limit)) * 4)
    люди: list[dict[str, Any]] = []
    for карточка in справочник.get("items") or []:
        номер = str(карточка.get("phone_ext") or "")
        if not номер:
            continue
        строка = из_звонков.get(номер)
        люди.append({
            "id": карточка.get("id"),
            "external_id": карточка.get("external_id"),
            "last_name": карточка.get("last_name"),
            "first_name": карточка.get("first_name"),
            "middle_name": карточка.get("middle_name"),
            "department": карточка.get("department"),
            "position": карточка.get("position"),
            "active": int(карточка.get("active") or 0),
            "phone_ext": номер,
            "calls": int((строка or {}).get("count") or 0),
            "talk_s": int((строка or {}).get("talk_s") or 0),
            "answered": int((строка or {}).get("answered") or 0),
        })
    # Общий номер (комната на двоих) — звонки у каждого из делящих его, но
    # в итог они входят один раз: прежде 14 звонков давали calls_matched 24.
    делят: dict[str, int] = {}
    for ч in люди:
        делят[ч["phone_ext"]] = делят.get(ч["phone_ext"], 0) + 1
    for ч in люди:
        if делят[ч["phone_ext"]] > 1:
            ч["shared_ext"] = делят[ч["phone_ext"]]
    люди.sort(key=lambda ч: (-ч["calls"], str(ч.get("last_name") or "")))
    нашлись = [ч for ч in люди if ч["calls"]]
    # «Неизвестные» — номера, которых нет ни в одной карточке, а не в
    # прочитанной порции: справочник больше limit×4 карточек записывал
    # настоящих сотрудников в неизвестные.
    все_номера = {str(с["phone_ext"]) for с in db.query(
        "SELECT DISTINCT phone_ext FROM employees WHERE COALESCE(phone_ext,'')<>''")}
    чужие = sorted(set(из_звонков) - все_номера)
    return {
        "checked": len(люди),
        "matched": len(нашлись),
        "unmatched": len(люди) - len(нашлись),
        "calls_matched": sum(int((из_звонков.get(н) or {}).get("count") or 0)
                             for н in {ч["phone_ext"] for ч in нашлись}),
        "items": люди[:max(1, int(limit))],
        "unknown_agents": чужие[:50],
        "unknown_agents_count": len(чужие),
        "at": time.time(),
    }


def подписать_добавочные(db: Any, строки: list[dict[str, Any]], *,
                         имена: bool = True, ключ: str = "job_id") -> None:
    """Добавочный оператора и его имя — в строки отчёта, на месте.

    Строке с номером задания (`ключ`, обычно `job_id`) и без `agent`
    добавочный берётся из журнала звонков
    (`agent`); строке, у которой он уже есть (список звонков), только имя.
    Имя и отдел — из справочника по номеру (`agent_name`,
    `agent_department`), если связь номера с человеком не выключена
    настройкой `employees_match_ext` (её значение и есть `имена`). Всё —
    двумя запросами на страницу, а не двумя на строку.
    """
    if not строки:
        return
    без_номера = [с for с in строки if с.get(ключ) and "agent" not in с]
    if без_номера:
        по_заданию = db.agents_for_jobs([с[ключ] for с in без_номера])
        for с in без_номера:
            с["agent"] = по_заданию.get(str(с[ключ]), "")
    if not имена:
        return
    люди = db.employees_by_ext([с.get("agent") for с in строки if с.get("agent")])
    for с in строки:
        человек = люди.get(str(с.get("agent") or ""))
        if человек and человек.get("name"):
            с["agent_name"] = человек["name"]
            if человек.get("department"):
                с["agent_department"] = человек["department"]


