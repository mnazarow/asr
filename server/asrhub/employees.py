#: Какую долю работающих карточек источника импорт вправе отметить
#: уволенными за раз без явного `force`. Больше — почти всегда не
#: сокращение штата, а неполная выгрузка: обрезанный файл, страница
#: портала вместо него, выгрузка одного отдела в общий источник.
ДОЛЯ_УВОЛЬНЕНИЙ = 0.3
#: Столько уволенных за раз пропускается без вопросов при любой доле.
УВОЛЬНЕНИЙ_БЕЗ_ВОПРОСОВ = 5


def из_каталога(settings: Any, *, соединение: Any = None) -> str:
    """Справочник из каталога LDAP (Active Directory) — таблицей для `импорт`.

    Вход через каталог уже настроен (адрес, база поиска, сертификат), а
    справочник вели отдельной выгрузкой. Здесь каталог читается служебной
    учётной записью (`employees_ldap_bind_dn`, `employees_ldap_password`)
    отбором `employees_ldap_filter`: ФИО, должность, отдел, внутренний,
    рабочий и мобильный телефоны, почта. Отключённые учётные записи AD
    (userAccountControl с битом 2) идут «не работает».
    """
    from . import ldap_auth  # noqa: PLC0415

    настройки = ldap_auth.Настройки.из_настроек(settings)
    if not настройки.url or not настройки.base_dn:
        raise ConfigError("Каталог не настроен: нужны auth_ldap_url и auth_ldap_base_dn.",
                          hint="Раздел «Настройки» → «Доступ» → вход через каталог.")
    связь = соединение
    if связь is None:
        связь = ldap_auth.соединение(
            настройки, str(settings.get("employees_ldap_bind_dn") or ""),
            str(settings.get("employees_ldap_password") or ""))
    if связь is None:
        raise ConfigError("Каталог не принял служебную учётную запись справочника.",
                          hint="Проверьте employees_ldap_bind_dn и employees_ldap_password.")
    отбор = str(settings.get("employees_ldap_filter") or "").strip() or (
        "(&(objectCategory=person)(objectClass=user)(|(ipPhone=*)(telephoneNumber=*)))")
    атрибуты = ["sn", "givenName", "middleName", "displayName", "title", "department",
                "ipPhone", "telephoneNumber", "mobile", "mail", "userAccountControl"]
    связь.search(настройки.base_dn, отбор, attributes=атрибуты)
    буфер = io.StringIO()
    запись = csv.writer(буфер, delimiter=";")
    запись.writerow(["Фамилия", "Имя", "Отчество", "Должность", "Отдел",
                     "Внутренний номер", "Телефон рабочий", "Мобильный", "Почта", "Работает"])
    for элемент in list(getattr(связь, "entries", ()) or ()):
        def одно(имя: str, элемент: Any = элемент) -> str:
            return ldap_auth._одно(элемент, имя)

        фамилия, имя = одно("sn"), одно("givenName")
        if not фамилия and not имя:
            части = одно("displayName").split()
            фамилия, имя = (части + ["", ""])[:2]
        try:
            отключён = int(одно("userAccountControl") or 0) & 2
        except ValueError:
            отключён = 0
        запись.writerow([фамилия, имя, одно("middleName"), одно("title"), одно("department"),
                         одно("ipPhone"), одно("telephoneNumber"), одно("mobile"),
                         одно("mail"), "нет" if отключён else "да"])
    отпустить = getattr(связь, "unbind", None)
    if callable(отпустить) and соединение is None:
        try:
            отпустить()
        except Exception:                                    # noqa: BLE001
            pass
    return буфер.getvalue()


def импорт(db: Any, *, url: str = "", данные: bytes | str | None = None,
           source: str = "справочник", deactivate_missing: bool = True,
           тип: str = "", dry_run: bool = False, force: bool = False,
           заголовок: str = "") -> dict[str, Any]:
    """Скачать (или взять готовое), разобрать и записать в базу.

    Возвращает сводку в том виде, в каком её показывают человеку: сколько
    добавлено, обновлено, не изменилось, помечено уволенными, сколько
    строк прочитано, сколько пропущено и почему, замечания и время работы.

    Пропавшие из выгрузки не удаляются, а помечаются неработающими — это
    решает `db.employees_import`, и здесь важно лишь то, что выключить
    это поведение можно (`deactivate_missing=False`): при импорте
    справочника одного отдела в общий источник все остальные отделы
    «уволились» бы разом.

    `dry_run` — предпросмотр: всё то же, но в базу ничего не пишется.
    Сводка говорит, что БЫЛО БЫ сделано, — кого добавить, у кого что
    поменять, кого отметить уволенным, — и как легли колонки файла.
    """
    начало = time.monotonic()
    if данные is None:
        данные = загрузить(url, заголовок=заголовок)
        откуда = url
    else:
        откуда = url or "файл"
    разбор = разобрать_подробно(данные, тип=тип)
    if not разбор.записи:
        # Пустой разбор в базу не пускаем вовсе. С `deactivate_missing`
        # такой импорт уволил бы весь справочник разом — а пустая выгрузка
        # это почти всегда страница входа, отданная порталом вместо файла.
        raise ConfigError(
            "В выгрузке не нашлось ни одного сотрудника.",
            hint="Проверьте, что по адресу отдаётся сам справочник. "
                 "Разбор сообщает: " + ("; ".join(разбор.замечания[:3]) or "нет замечаний"))
    сводка = db.employees_import(
        разбор.записи, source=source, deactivate_missing=bool(deactivate_missing),
        dry_run=bool(dry_run),
        предел_увольнений=None if force else (ДОЛЯ_УВОЛЬНЕНИЙ, УВОЛЬНЕНИЙ_БЕЗ_ВОПРОСОВ))
    if сводка.get("deactivation_blocked"):
        разбор.замечание(
            f"Не отмечены уволенными {сводка['deactivation_blocked']} карточек: это "
            f"больше {ДОЛЯ_УВОЛЬНЕНИЙ:.0%} работающих — так выглядит неполная "
            "выгрузка. Если штат и правда сократился, повторите импорт с force=true.")
    if сводка.get("replaced"):
        разбор.замечание(
            f"На прежние внутренние номера пришли другие люди: {сводка['replaced']}. "
            "Прежние карточки отмечены неработающими и остались в справочнике.")
    итог = {**сводка, **разбор.to_dict(), "source": source, "from": откуда,
            "dry_run": bool(dry_run),
            "sample": [{к: з for к, з in к_.items() if к != "external_id"}
                       for к_ in разбор.записи[:ОБРАЗЦОВ]],
            "took_s": round(time.monotonic() - начало, 2), "at": time.time()}
    if dry_run:
        return итог
    log.info("Справочник «%s»: добавлено %s, обновлено %s, без изменений %s, "
             "уволено %s (из %s строк, пропущено %s)",
             source, итог.get("added"), итог.get("updated"),
             итог.get("unchanged"), итог.get("deactivated"),
             итог.get("rows"), итог.get("skipped"))
    return итог


#: Сколько первых карточек показывает предпросмотр импорта.
ОБРАЗЦОВ = 8

