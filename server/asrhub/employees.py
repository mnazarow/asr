#: Предел распакованного содержимого книги. Сжатие у XML — десятки раз, и
#: шестнадцать мегабайт архива могли бы развернуться в гигабайты: это и
#: есть «zip-бомба». Справочнику на тысячу человек хватает пары мегабайт.
XLSX_РАСПАКОВАННЫХ_МБ = 64


def _буква_столбца(ссылка: str) -> int:
    """«C7» → 2: номер столбца из адреса ячейки, с нуля."""
    номер = 0
    for знак in ссылка:
        if not знак.isalpha():
            break
        номер = номер * 26 + (ord(знак.upper()) - 64)
    return max(0, номер - 1)


def _текст_узла(элемент: ET.Element) -> str:
    """Весь текст `<t>` внутри узла: у богатой строки он кусками в `<r>`."""
    return "".join(у.text or "" for у in элемент.iter() if _локальное(у.tag) == "t")


def _листы_xlsx(данные: bytes) -> list[tuple[str, list[list[str]]]]:
    """Листы книги .xlsx: имя и строки ячеек текстом.

    Книга — архив XML: список листов (`xl/workbook.xml`), связи листов с
    файлами (`xl/_rels/workbook.xml.rels`), общие строки
    (`xl/sharedStrings.xml`) и по файлу на лист. Разбирается тем же
    недоверчивым разборщиком, что и Excel XML 2003, а размер распакованного
    проверяется до чтения.
    """
    try:
        архив = zipfile.ZipFile(io.BytesIO(данные))
    except zipfile.BadZipFile as ошибка:
        raise ConfigError("Файл похож на книгу Excel (.xlsx), но не открывается как архив.",
                          hint="Пересохраните справочник из Excel.") from ошибка
    with архив:
        всего = sum(сведения.file_size for сведения in архив.infolist())
        if всего > XLSX_РАСПАКОВАННЫХ_МБ * 1024 * 1024:
            raise ConfigError(
                f"Книга Excel разворачивается больше чем в {XLSX_РАСПАКОВАННЫХ_МБ} МБ.",
                hint="Для справочника сотрудников это слишком много. Сохраните "
                     "нужный лист отдельно или выгрузите справочник в CSV.")
        имена = set(архив.namelist())

        def прочитать(путь: str) -> ET.Element | None:
            if путь not in имена:
                return None
            # Оглавление архива цело, а член внутри — нет: оборванная
            # загрузка, неверная контрольная сумма, книга под паролем
            # (шифрованный архив) или сжатие, которого zipfile не знает.
            # Каждое из этого — вопрос к файлу, а не сбой сервера: раньше
            # импорт отвечал 500 с «Error -3 while decompressing data».
            try:
                сырые = архив.read(путь)
            except (zipfile.BadZipFile, zlib.error, NotImplementedError, RuntimeError,
                    EOFError, ValueError) as ошибка:
                raise ConfigError(
                    f"Книга Excel повреждена или защищена паролем: не читается «{путь}» "
                    f"({ошибка}).",
                    hint="Откройте файл в Excel, снимите пароль, если он есть, и "
                         "пересохраните справочник как «Книга Excel (.xlsx)» или CSV.") from ошибка
            return _разобрать_xml(сырые)

        строки_общие: list[str] = []
        общие = прочитать("xl/sharedStrings.xml")
        if общие is not None:
            строки_общие = [_текст_узла(si) for si in общие
                            if _локальное(si.tag) == "si"]
        связи: dict[str, str] = {}
        файл_связей = прочитать("xl/_rels/workbook.xml.rels")
        if файл_связей is not None:
            for связь in файл_связей:
                цель = _атрибут(связь, "target")
                путь = цель.lstrip("/") if цель.startswith("/") else f"xl/{цель}"
                связи[_атрибут(связь, "id")] = путь
        листы_книги: list[tuple[str, str]] = []
        книга = прочитать("xl/workbook.xml")
        if книга is not None:
            for лист in книга.iter():
                if _локальное(лист.tag) == "sheet":
                    путь = связи.get(_атрибут(лист, "id"), "")
                    листы_книги.append((_атрибут(лист, "name") or путь, путь))
        if not листы_книги:
            листы_книги = [(имя.rsplit("/", 1)[-1], имя) for имя in sorted(имена)
                           if имя.startswith("xl/worksheets/") and имя.endswith(".xml")]
        # Дата в книге .xlsx — не текст, а число дней от начала эпохи Excel
        # («работает до 30.05.2025» лежит в ячейке как 45807); датой её
        # делает только формат ячейки из стилей. Без них в карточку уходило
        # «45807». Эпоха — 1900 года или, у книг со старых Mac, 1904-го.
        форматы_дат = _форматы_дат(прочитать("xl/styles.xml"))
        с_1904 = книга is not None and any(
            _локальное(у.tag) == "workbookpr" and _атрибут(у, "date1904").lower() in ("1", "true")
            for у in книга.iter())

        листы: list[tuple[str, list[list[str]]]] = []
        for имя, путь in листы_книги:
            корень = прочитать(путь)
            if корень is None:
                continue
            строки: list[list[str]] = []
            for строка in корень.iter():
                if _локальное(строка.tag) != "row":
                    continue
                значения: list[str] = []
                for ячейка in строка:
                    if _локальное(ячейка.tag) != "c":
                        continue
                    место = _буква_столбца(_атрибут(ячейка, "r")) if _атрибут(ячейка, "r") \
                        else len(значения)
                    вид = _атрибут(ячейка, "t")
                    значение = ""
                    if вид == "inlineStr":
                        значение = _текст_узла(ячейка)
                    else:
                        v = next((у for у in ячейка if _локальное(у.tag) == "v"), None)
                        сырое = (v.text or "") if v is not None else ""
                        if вид == "s":
                            try:
                                значение = строки_общие[int(сырое)]
                            except (ValueError, IndexError):
                                значение = ""
                        elif вид == "b":
                            значение = "да" if сырое == "1" else "нет"
                        else:
                            значение = сырое
                            # «101.0» и «1.0E+3» — числа Excel: номер нужен целым.
                            try:
                                число = float(сырое)
                                стиль = _атрибут(ячейка, "s")
                                if стиль.isdigit() and int(стиль) in форматы_дат:
                                    значение = _дата_excel(число, с_1904,
                                                           форматы_дат[int(стиль)])
                                elif число.is_integer() and abs(число) < 1e15:
                                    значение = str(int(число))
                            except (ValueError, OverflowError):
                                pass
                    while len(значения) < место:
                        значения.append("")
                    значения.append(значение)
                строки.append(значения)
            листы.append((имя, строки))
    return листы


#: Встроенные форматы Excel с датой (14–22, 45–47 и восточноазиатские 27–36,
#: 50–58): у таких ячеек в стилях только номер формата, без его текста.
_ВСТРОЕННЫЕ_ДАТЫ = frozenset({*range(14, 23), *range(27, 37), 45, 46, 47, *range(50, 59)})
#: Встроенные из них, где есть время.
_ВСТРОЕННЫЕ_СО_ВРЕМЕНЕМ = frozenset({18, 19, 20, 21, 22, 45, 46, 47})


def _форматы_дат(стили: ET.Element | None) -> dict[int, bool]:
    """Номера стилей ячеек (`cellXfs`) с форматом даты → есть ли в нём время."""
    if стили is None:
        return {}
    свои: dict[str, str] = {}
    for узел in стили.iter():
        if _локальное(узел.tag) == "numfmt":
            свои[_атрибут(узел, "numFmtId")] = _атрибут(узел, "formatCode")
    итог: dict[int, bool] = {}
    for группа in стили.iter():
        if _локальное(группа.tag) != "cellxfs":
            continue
        for номер, xf in enumerate(у for у in группа if _локальное(у.tag) == "xf"):
            ид = _атрибут(xf, "numFmtId")
            if not ид.isdigit():
                continue
            if int(ид) in _ВСТРОЕННЫЕ_ДАТЫ:
                итог[номер] = int(ид) in _ВСТРОЕННЫЕ_СО_ВРЕМЕНЕМ
                continue
            # Свой формат: дата, если в нём есть день или год вне кавычек,
            # скобок ([Red], [$-419]) и экранированных знаков.
            код = re.sub(r'"[^"]*"|\[[^\]]*\]|\\.', "", свои.get(ид, "")).lower()
            if "d" in код or "y" in код or "д" in код or "г" in код:
                итог[номер] = "h" in код or "s" in код or "ч" in код
        break
    return итог


def _дата_excel(число: float, с_1904: bool, со_временем: bool) -> str:
    """Число дней Excel → «ГГГГ-ММ-ДД» (и «ЧЧ:ММ», если в формате есть время)."""
    import datetime as dt  # noqa: PLC0415

    основа = dt.datetime(1904, 1, 1) if с_1904 else dt.datetime(1899, 12, 30)
    момент = основа + dt.timedelta(days=число)
    if со_временем and (момент.hour or момент.minute):
        return момент.strftime("%Y-%m-%d %H:%M")
    return момент.strftime("%Y-%m-%d")


def _разобрать_xlsx(данные: bytes, итог: Разбор) -> list[list[str]]:
    """Строки первого пригодного листа книги .xlsx."""
    листы = _листы_xlsx(данные)
    if not листы:
        raise ConfigError("В книге Excel нет ни одного листа.",
                          hint="Проверьте, что выбран файл справочника.")
    return _выбрать_лист(листы, итог)


def _есть_заголовки(строка: list[str]) -> bool:
    """Похожа ли строка на строку заголовков.

    Достаточно двух узнанных колонок: справочник без фамилии и хоть
    какого-то второго поля бесполезен, а одна случайно совпавшая ячейка
    («Имя» в шапке отчёта) заголовком строку не делает.
    """
    узнано = sum(1 for ячейка in строка if поле_заголовка(ячейка))
    return узнано >= 2


