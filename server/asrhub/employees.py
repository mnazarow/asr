def _работает(значение: Any) -> bool:
    """«да/нет/+/-/1/0/true/false» → признак «работает».

    Пустое значение — «работает». Это не небрежность, а выбор в пользу
    меньшего вреда: колонку «работает» заполняют не везде и не всегда, а
    ошибочно уволенный сотрудник пропадает из справочника, и его звонки
    снова становятся безымянными. Ошибка в другую сторону заметна сразу и
    правится одной галочкой в карточке.
    """
    текст = _схлопнуть(значение).lower().replace("ё", "е")
    if not текст:
        return True
    if текст in _ДА:
        return True
    if текст in _НЕТ:
        return False
    # Непонятное значение («в отпуске», «декрет») — человек в штате.
    # Уволить по строке, которую мы не поняли, нельзя.
    return True


def рабочий(значение: Any) -> str:
    """Телефон без пробелов, скобок, дефисов и точек.

    Городской номер к единому виду не приводится, в отличие от мобильного:
    «+7 (351) 000-11-22», «8-351-000-11-22» и «внутр. 22» — это разные
    записи одного стола, и догадываться, какая из них код города, а какая
    добавочный, сервер не вправе. Чистка снимает только то, что мешает
    сравнению строк.
    """
    return _МУСОР_В_НОМЕРЕ.sub("", _схлопнуть(значение))


def мобильный(значение: Any) -> str:
    """Российский мобильный к виду +7XXXXXXXXXX; остальное — просто чистим.

    Одно и то же число приезжает как «8 (912) 345-67-89», «+7 912 3456789»
    и «9123456789». Пока они разные строки, поиск по номеру находит треть
    справочника, а сравнение «этот ли номер звонил» не работает вовсе.

    Чужие номера (+380, +995) не трогаем сверх чистки: приводить их к
    российскому виду — значит испортить.
    """
    чистый = рабочий(значение)
    if not чистый:
        return ""
    цифры = _НЕ_ЦИФРА.sub("", чистый)
    if not цифры:
        return ""
    if чистый.startswith("+") and not цифры.startswith("7"):
        return "+" + цифры                   # иностранный: только чистка
    if len(цифры) == 11 and цифры[0] in "78":
        return "+7" + цифры[1:]
    # Десять цифр без кода страны: российский мобильный начинается с 9.
    # Городской «4951234567» так же выглядит, но мобильным не является, и
    # дописывать ему +7 наугад не станем — вернём как есть.
    if len(цифры) == 10 and цифры[0] == "9":
        return "+7" + цифры
    return чистый


#: «137 (лич.149)», «лич. 149», «личный 149» — личный номер рядом с общим.
_ЛИЧНЫЙ = re.compile(r"лич\w*\.?\s*:?\s*(\d+)", re.IGNORECASE)
_ЧИСЛА = re.compile(r"\d+")


def внутренний(значение: Any) -> str:
    """Внутренний номер — только цифры.

    В выгрузке он бывает «доб. 1043», «1043 (склад)» и «1043.0» (Excel
    решил, что это число). Со звонком его сверяют строкой: в журнале АТС
    поле `agent` — это голые цифры, и «доб. 1043» не совпадёт ни с чем.

    Бывает и два номера в ячейке: «137 (лич.149)» — общий номер отдела и
    личный. Раньше цифры склеивались в «137149», которого нет ни на одной
    станции. Человека звонок узнаёт по личному номеру: общий звонит у
    нескольких столов сразу. Он и берётся, а общий уходит в примечание
    (см. `общий_внутренний`). Два номера без пометки («101, 102») — берётся
    первый; цифры через пробел или дефис («1 043», «10-43») — один номер.
    """
    текст = _схлопнуть(значение)
    личный = _ЛИЧНЫЙ.search(текст)
    if личный:
        return личный.group(1)
    текст = re.sub(r"(?<=\d)[.,]0+$", "", текст)
    if re.fullmatch(r"\D*\d[\d \-]*\d\D*", текст):
        return _НЕ_ЦИФРА.sub("", текст)
    группы = _ЧИСЛА.findall(текст)
    return группы[0] if группы else ""


def общий_внутренний(значение: Any) -> str:
    """Общий номер из ячейки «137 (лич.149)» — или пусто, если его нет."""
    текст = _схлопнуть(значение)
    личный = _ЛИЧНЫЙ.search(текст)
    if not личный:
        return ""
    for число in _ЧИСЛА.finditer(текст):
        if число.start() < личный.start(1) and not (
                личный.start(1) <= число.start() < личный.end(1)):
            return число.group(0)
    return ""


def похоже_на_адрес(значение: str) -> bool:
    """Грубая проверка почты: одна собака, точка в домене, без пробелов.

    Строгая проверка адреса по RFC 5322 здесь вредна: она отвергает
    работающие адреса и ничего не даёт взамен — письма сервер не шлёт, а
    почта в карточке нужна, чтобы человеку было куда написать.
    """
    if значение.count("@") != 1 or " " in значение:
        return False
    местное, _, домен = значение.partition("@")
    return bool(местное) and "." in домен and not домен.startswith(".") \
        and not домен.endswith(".")


def почта(значение: Any) -> str:
    """Адрес почты: без краевых пробелов и в нижнем регистре.

    Регистр домена и имени в адресе не значим, а вот поиск и сравнение по
    строке — значимы: «Ivanov@Example.RU» и «ivanov@example.ru» это один
    почтовый ящик и две разные строки в базе.
    """
    return _схлопнуть(значение).lower()


def _фио(значение: Any) -> str:
    """Часть имени: схлопнутые пробелы и ничего больше.

    `ё` не трогаем. «Фёдоров» и «Федоров» — разные фамилии в паспорте, и
    решать за кадровую службу, как правильно, не наше дело. На сведение
    карточек это не влияет: ключ считается по той же строке, что и
    показывается.
    """
    return _схлопнуть(значение)


def _дата(значение: Any) -> str:
    """Дата «работает до» как строка.

    Формат не приводим: в выгрузке он может быть и «2026-03-01», и
    «01.03.2026», и «2026-03-01T00:00:00.000» из ячейки DateTime (эту
    форму подрезает разбор ячейки). Поле в базе строковое и показывается
    человеку как есть — переписывать чужую дату в свой формат значит
    однажды перепутать день с месяцем.
    """
    return _схлопнуть(значение)


