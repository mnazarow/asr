class _ТолькоHTTP(urllib.request.HTTPRedirectHandler):
    """Перенаправления только на http и https.

    Проверить схему один раз на исходном адресе недостаточно: сервер по
    безобидному `http://…` вправе ответить «302, иди на ftp://…» или на
    `file:///etc/passwd`, и дальше читать пойдёт уже разборщик
    перенаправлений, которому наша проверка не указ.

    Штатный обработчик закрывает только часть: `file:` он отвергает сам
    (но сообщением «ответ 302», по которому никто не догадается, что
    случилось), а вот `ftp:` у него в списке разрешённых. Поэтому проверка
    стоит дважды: в `http_error_302` — чтобы сказать человеку правду, и в
    `redirect_request` — на случай, если код ответа окажется таким, что до
    первой проверки дело не дойдёт.

    Пустая схема — это относительный адрес («/employees.xml»), он остаётся
    в той же схеме, что и исходный, и запрещать его не за что.
    """

    def _проверить(self, новый: str) -> None:
        from urllib.parse import urlparse

        схема = urlparse(новый).scheme
        if схема and схема not in СХЕМЫ:
            raise ConfigError(
                f"Адрес выгрузки перенаправляет на «{новый[:80]}».",
                hint="Разрешены только http и https: по другим схемам сервер "
                     "читал бы собственные файлы вместо справочника.")

    def http_error_302(self, req, fp, code, msg, headers):  # noqa: D102, ANN001
        self._проверить(headers.get("location") or headers.get("uri") or "")
        return super().http_error_302(req, fp, code, msg, headers)

    # Псевдонимы в родителе указывают на его собственный метод, поэтому
    # переопределить один `http_error_302` мало: без этих строк ответ 301
    # или 308 ушёл бы мимо проверки.
    http_error_301 = http_error_303 = http_error_307 = http_error_308 = http_error_302

    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: D102, ANN001
        self._проверить(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _открыватель() -> urllib.request.OpenerDirector:
    """Открыватель, у которого нет обработчиков file:// и ftp://.

    Второй рубеж к проверке схемы. `urllib.request.build_opener()` ставит
    обработчики всех схем, какие знает, в том числе `FileHandler` и
    `FTPHandler`; собирая открыватель вручную, мы оставляем ровно два. Если
    сквозь проверки всё же проедет `file:///etc/shadow`, читать его будет
    некому — urllib ответит «unknown url type».
    """
    # Обработчика прокси здесь намеренно нет. Справочник лежит во
    # внутренней сети, куда корпоративный прокси и не ходит, а
    # `build_opener()` подхватил бы `http_proxy` из окружения и погнал бы
    # внутренний адрес наружу — запрос не дошёл бы вовсе.
    открыватель = urllib.request.OpenerDirector()
    for обработчик in (urllib.request.HTTPHandler(),
                       urllib.request.HTTPSHandler(),
                       urllib.request.HTTPDefaultErrorHandler(),
                       urllib.request.HTTPErrorProcessor(),
                       _ТолькоHTTP()):
        открыватель.add_handler(обработчик)
    return открыватель


def проверить_адрес(url: str) -> str:
    """Адрес выгрузки, годный для загрузки, или понятная ошибка."""
    from urllib.parse import urlparse

    адрес = _схлопнуть(url)
    if not адрес:
        raise ConfigError(
            "Не указан адрес выгрузки справочника.",
            hint="Заполните настройку employees_url или передайте url в запросе.")
    разобранный = urlparse(адрес)
    if разобранный.scheme not in СХЕМЫ:
        raise ConfigError(
            f"Адрес выгрузки должен начинаться с http:// или https:// "
            f"(получено «{разобранный.scheme or адрес[:24]}»).",
            hint="Другие схемы запрещены: по file:// и ftp:// сервер читал бы "
                 "свои файлы и ходил во внутреннюю сеть вместо загрузки справочника.")
    if not разобранный.hostname:
        raise ConfigError(f"В адресе выгрузки «{адрес}» не указан узел.",
                          hint="Пример: http://portal.local/employees.xml")
    return адрес


def загрузить(url: str, *, timeout: float = ТАЙМАУТ,
              максимум_мб: int = МАКСИМУМ_МБ) -> bytes:
    """Скачивает выгрузку по открытому адресу. Возвращает байты как есть.

    Авторизация не нужна и не поддерживается: справочник выкладывают
    открытым файлом во внутренней сети. Поэтому здесь нет проверки «адрес
    смотрит внутрь сети», которая стоит у обратных вызовов
    (`job_queue.check_outbound_url`): внутренний портал — это ровно то
    место, где справочник и лежит, и запрет на локальные адреса сделал бы
    настройку неработающей у всех.

    Что проверяется: схема (только http и https — и на исходном адресе, и
    на каждом перенаправлении) и размер (читаем кусками и обрываем, как
    только перевалило за предел, не дожидаясь конца передачи).
    """
    from .phone_compat import encode_url  # noqa: PLC0415

    адрес = проверить_адрес(url)
    предел = max(1, int(максимум_мб)) * 1024 * 1024
    # Путь с кириллицей («…/справочник.xml») валит запрос ещё до сети:
    # строка запроса уходит в сокет как ascii. Кодирование — тем же
    # способом, что и у записей с АТС, где имена файлов кириллические
    # сплошь и рядом; уже закодированный адрес при этом не портится.
    запрос = urllib.request.Request(encode_url(адрес), headers={
        # Заголовки уходят в сеть в latin-1, поэтому подпись здесь
        # латиницей: кириллическая валила запрос ещё до отправки, на
        # `UnicodeEncodeError` внутри http.client.
        "User-Agent": "ASRHub/3.0 (employees directory)",
        # Некоторые порталы отдают HTML-обёртку, если не сказать, что нужен
        # файл. Просим что угодно — разберёмся по содержимому.
        "Accept": "*/*",
    })
    собрано = bytearray()
    try:
        with _открыватель().open(запрос, timeout=timeout) as ответ:
            while True:
                кусок = ответ.read(КУСОК)
                if not кусок:
                    break
                собрано += кусок
                # Предел проверяется по ходу чтения, а не по Content-Length:
                # заголовок приходит не всегда и не обязан быть правдой, а
                # память сервера кончается по-настоящему.
                if len(собрано) > предел:
                    raise ConfigError(
                        f"Выгрузка по адресу {адрес} больше {максимум_мб} МБ.",
                        hint="Проверьте, что по адресу лежит справочник, а не "
                             "архив или образ. Предел меняется параметром "
                             "максимум_мб при вызове.")
    except urllib.error.HTTPError as ошибка:
        raise ConfigError(
            f"Справочник по адресу {адрес} недоступен: ответ {ошибка.code}.",
            hint="Проверьте, что ссылка открывается с самого сервера и без "
                 "входа по паролю: загрузка идёт без авторизации.") from ошибка
    except urllib.error.URLError as ошибка:
        raise ConfigError(
            f"Не удалось скачать справочник: {адрес} ({ошибка.reason}).",
            hint="Проверьте адрес и доступность узла с сервера: "
                 "curl -sI <адрес>") from ошибка
    except (TimeoutError, OSError) as ошибка:
        raise ConfigError(
            f"Не удалось скачать справочник: {адрес} ({ошибка}).",
            hint=f"Узел не ответил за {timeout:.0f} с. Проверьте сеть и доступность "
                 "адреса с сервера.") from ошибка
    if not собрано:
        raise ConfigError(
            f"По адресу {адрес} отдан пустой ответ.",
            hint="Проверьте, что ссылка ведёт на файл выгрузки, а не на "
                 "страницу без содержимого.")
    return bytes(собрано)


# ---------------------------------------------------------------------------
# Импорт
# ---------------------------------------------------------------------------

def импорт(db: Any, *, url: str = "", данные: bytes | str | None = None,
           source: str = "справочник", deactivate_missing: bool = True,
           тип: str = "") -> dict[str, Any]:
    """Скачать (или взять готовое), разобрать и записать в базу.

    Возвращает сводку в том виде, в каком её показывают человеку: сколько
    добавлено, обновлено, не изменилось, помечено уволенными, сколько
    строк прочитано, сколько пропущено и почему, замечания и время работы.

    Пропавшие из выгрузки не удаляются, а помечаются неработающими — это
    решает `db.employees_import`, и здесь важно лишь то, что выключить
    это поведение можно (`deactivate_missing=False`): при импорте
    справочника одного отдела в общий источник все остальные отделы
    «уволились» бы разом.
    """
    начало = time.monotonic()
    if данные is None:
        данные = загрузить(url)
        откуда = url
    else:
        откуда = url or "файл"
    разбор = разобрать_подробно(данные, тип=тип)
    if not разбор.записи:
        # Пустой разбор в базу не пускаем вовсе. С `deactivate_missing`
        # такой импорт уволил бы весь справочник разом — а пустая выгрузка
        # это почти всегда страница входа, отданная порталом вместо файла.
        raise ConfigError(
            "В выгрузке не нашлось ни одного сотрудника.",
            hint="Проверьте, что по адресу отдаётся сам справочник. "
                 "Разбор сообщает: " + ("; ".join(разбор.замечания[:3]) or "нет замечаний"))
    сводка = db.employees_import(разбор.записи, source=source,
                                 deactivate_missing=bool(deactivate_missing))
    итог = {**сводка, **разбор.to_dict(), "source": source, "from": откуда,
            "took_s": round(time.monotonic() - начало, 2), "at": time.time()}
    log.info("Справочник «%s»: добавлено %s, обновлено %s, без изменений %s, "
             "уволено %s (из %s строк, пропущено %s)",
             source, итог.get("added"), итог.get("updated"),
             итог.get("unchanged"), итог.get("deactivated"),
             итог.get("rows"), итог.get("skipped"))
    return итог


