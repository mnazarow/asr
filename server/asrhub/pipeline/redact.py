"""Редакция звука: заглушить персональные данные в самой записи.

Обезличивание текста у сервера есть давно: расшифровка отдаётся с пометками
вместо номера карты. Но запись разговора при этом лежит целой, и номер в ней
звучит. Для проверяющего это одно хранилище персональных данных, а не два
разных: «в тексте замазано» не отвечает на вопрос «а в звуке?».

Здесь недостающий кусок. Всё нужное уже есть по отдельности: `masking.find`
находит в тексте номер карты, СНИЛС, паспорт и прочее, а выравнивание
проставляет время каждому слову. Остаётся соединить одно с другим и позвать
ffmpeg.

Два решения, которые стоит назвать вслух:

* **Что делать со звуком.** Тишина или писк. По умолчанию писк: тишина в
  записи неотличима от обрыва связи и от того, что человек молчал, а писк
  слышно — и сразу понятно, что здесь не потеря, а редакция.
* **Что делать без таймкодов слов.** Выравнивание включено не у всех, и тогда
  время известно только у реплики целиком. Заглушать реплику целиком нельзя:
  из-за одного номера пропадёт полминуты разговора. Поэтому границы
  оцениваются по месту знаков в тексте реплики — доля от её длительности. Это
  оценка, и она честно помечена в ответе: `estimated: true`. Запас по краям
  (`padding_ms`) для такой оценки берётся больше.
"""
from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..content import masking
from ..errors import ASRHubError
from ..logging_setup import get_logger

log = get_logger("redact")

#: Частота писка. Тысяча герц — то, чем «запикивают» на телевидении: хорошо
#: слышно, ни с чем не путается и не режет ухо, как две тысячи.
ЧАСТОТА_ПИСКА = 1000

#: Громкость писка множителем к тому, что даёт сам генератор. Единица — не
#: «во всю мощь»: генератор `sine` в ffmpeg выдаёт не полную шкалу, а примерно
#: −18 дБ по пику и −21 дБ по среднему, и это ровно уровень речи в телефонной
#: записи. Проверено замером: −21,1 дБ у исходника и −21,1 дБ у тона.
#:
#: Первым значением стояло 0,16 — «чтобы не било по ушам». Замер показал −37
#: дБ: писк оказался вшестеро тише речи и на шумной записи просто терялся, то
#: есть редакция была не слышна там, где её и надо услышать.
ГРОМКОСТЬ_ПИСКА = 1.0

#: Запас по краям, когда время слова известно точно.
ЗАПАС_МС = 120

#: Запас, когда время оценено по месту знаков в реплике. Больше, потому что
#: оценка может промахнуться на слог: лучше заглушить лишнюю четверть
#: секунды, чем оставить в записи последние цифры номера карты.
ЗАПАС_ОЦЕНКИ_МС = 350


class RedactError(ASRHubError):
    """Редакция не удалась."""

    code = "redact_error"
    http_status = 500


@dataclass
class Интервал:
    """Кусок записи, который надо заглушить."""

    start: float
    end: float
    kind: str
    estimated: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {"start": round(self.start, 3), "end": round(self.end, 3),
                "kind": self.kind, "estimated": self.estimated}


@dataclass
class Итог:
    """Что получилось: файл, интервалы и сколько чего заглушено."""

    path: Path | None = None
    intervals: list[Интервал] = field(default_factory=list)
    counts: dict[str, int] = field(default_factory=dict)
    estimated: int = 0

    def to_dict(self) -> dict[str, Any]:
        return {"intervals": [и.to_dict() for и in self.intervals],
                "counts": dict(self.counts),
                "estimated": self.estimated,
                "seconds": round(sum(и.end - и.start for и in self.intervals), 2)}


def _границы_слова(слово: dict[str, Any]) -> tuple[float, float] | None:
    начало, конец = слово.get("start"), слово.get("end")
    if начало is None or конец is None:
        return None
    try:
        return float(начало), float(конец)
    except (TypeError, ValueError):
        return None


def _по_словам(текст: str, слова: list[dict[str, Any]],
               находки: list[dict[str, Any]]
               ) -> tuple[list[Интервал], list[dict[str, Any]]]:
    """Интервалы по таймкодам слов и находки, которым слов не досталось.

    Второе значение возвращается не для порядка. Таймкоды бывают у части
    реплики: распознавание отдало слова до половины, дальше их нет; или
    постобработка переписала текст, и часть слов не нашлась. Первая версия
    этой функции в таком случае отдавала интервалы только для найденного, а
    остальные находки ИСЧЕЗАЛИ — то есть почта после номера карты оставалась
    в записи звучать, и ни в ответе, ни в журнале об этом не было ни слова.
    Для редакции персональных данных это худший вид ошибки: она выглядит как
    успех.

    Слова сопоставляются тексту реплики поиском по порядку, а не делением по
    пробелам: распознавание отдаёт слова без знаков препинания, а в тексте они
    есть, и позиции разъезжаются с первой же запятой.
    """
    позиции: list[tuple[int, int, float, float]] = []
    курсор = 0
    низкий = текст.lower()
    for слово in слова:
        границы = _границы_слова(слово)
        форма = str(слово.get("word") or "").strip().lower()
        if границы is None or not форма:
            continue
        место = низкий.find(форма, курсор)
        if место < 0:
            # Слово не нашлось (постобработка переписала текст) — пропускаем
            # его, но остальные позиции остаются верными.
            continue
        позиции.append((место, место + len(форма), границы[0], границы[1]))
        курсор = место + len(форма)
    if not позиции:
        return [], list(находки)

    интервалы: list[Интервал] = []
    осталось: list[dict[str, Any]] = []
    for находка in находки:
        задетые = [п for п in позиции
                   if п[0] < находка["end"] and находка["start"] < п[1]]
        if not задетые:
            осталось.append(находка)
            continue
        интервалы.append(Интервал(
            start=min(п[2] for п in задетые),
            end=max(п[3] for п in задетые),
            kind=str(находка["kind"])))
    return интервалы, осталось


def _по_доле(реплика: dict[str, Any], текст: str,
             находки: list[dict[str, Any]]) -> list[Интервал]:
    """Оценка границ по месту знаков в тексте реплики.

    Речь неравномерна, и доля знаков — не доля времени. Но выбор здесь не
    между оценкой и точностью, а между оценкой и заглушенной репликой
    целиком: из-за одного номера карты пропала бы полминуты разговора.
    """
    начало = float(реплика.get("start") or реплика.get("start_s") or 0.0)
    конец = float(реплика.get("end") or реплика.get("end_s") or 0.0)
    длина = max(0.0, конец - начало)
    знаков = max(1, len(текст))
    интервалы: list[Интервал] = []
    for находка in находки:
        интервалы.append(Интервал(
            start=начало + длина * (находка["start"] / знаков),
            end=начало + длина * (находка["end"] / знаков),
            kind=str(находка["kind"]), estimated=True))
    return интервалы


def найти_интервалы(segments: list[dict[str, Any]], *,
                    kinds: tuple[str, ...] | None = None,
                    padding_ms: int = ЗАПАС_МС,
                    estimated_padding_ms: int = ЗАПАС_ОЦЕНКИ_МС) -> list[Интервал]:
    """Где в записи звучат персональные данные.

    `kinds` — какие виды заглушать; None — все, что умеет находить `masking`.
    """
    нужные = set(kinds) if kinds else None
    собрано: list[Интервал] = []
    for реплика in segments or []:
        текст = str(реплика.get("text") or "")
        if not текст.strip():
            continue
        находки = [н for н in masking.find(текст)
                   if нужные is None or н["kind"] in нужные]
        if not находки:
            continue
        слова = реплика.get("words") or []
        точные, без_времени = (_по_словам(текст, слова, находки) if слова
                               else ([], находки))
        собрано.extend(точные)
        # Находка, которой не досталось ни одного слова с таймкодом, всё равно
        # обязана быть заглушена — пусть по оценке. Пропустить её означало бы
        # оставить персональные данные звучать в «отредактированной» записи.
        if без_времени:
            собрано.extend(_по_доле(реплика, текст, без_времени))

    with_padding: list[Интервал] = []
    for и in собрано:
        запас = (estimated_padding_ms if и.estimated else padding_ms) / 1000.0
        with_padding.append(Интервал(max(0.0, и.start - запас), и.end + запас,
                                     и.kind, и.estimated))
    return _слить(with_padding)


def _слить(интервалы: list[Интервал]) -> list[Интервал]:
    """Складывает пересекающиеся куски в один.

    Без этого два номера подряд дают два фильтра ffmpeg на один и тот же
    участок, а на записи с полусотней находок команда разрастается до
    неприличия и начинает упираться в предел длины аргументов.
    """
    if not интервалы:
        return []
    по_порядку = sorted(интервалы, key=lambda и: и.start)
    итог = [Интервал(по_порядку[0].start, по_порядку[0].end,
                     по_порядку[0].kind, по_порядку[0].estimated)]
    for текущий in по_порядку[1:]:
        последний = итог[-1]
        if текущий.start <= последний.end:
            последний.end = max(последний.end, текущий.end)
            последний.estimated = последний.estimated or текущий.estimated
            if текущий.kind not in последний.kind.split("+"):
                последний.kind = f"{последний.kind}+{текущий.kind}"
        else:
            итог.append(Интервал(текущий.start, текущий.end,
                                 текущий.kind, текущий.estimated))
    return итог


def _условие(интервалы: list[Интервал]) -> str:
    """Условие ffmpeg «время внутри любого из интервалов»."""
    return "+".join(f"between(t,{и.start:.3f},{и.end:.3f})" for и in интервалы)


def построить_команду(src: Path, dst: Path, интервалы: list[Интервал], *,
                      mode: str = "beep", ffmpeg: str = "ffmpeg") -> list[str]:
    """Команда ffmpeg, которая заглушает указанные куски.

    Тишина — один фильтр громкости. Писк — подмешанный синус, который слышно
    ровно в те же мгновения: исходный звук глушится, а тон, наоборот,
    пропускается. Порядок именно такой — сначала заглушить, потом подмешать,
    иначе тон уйдёт в ноль вместе с речью.
    """
    условие = _условие(интервалы)
    если_тишина = [
        ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(src),
        "-af", f"volume=0:enable='{условие}'", str(dst)]
    if mode == "silence":
        return если_тишина
    return [
        ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(src),
        "-f", "lavfi", "-i", f"sine=frequency={ЧАСТОТА_ПИСКА}:sample_rate=48000",
        "-filter_complex",
        f"[0:a]volume=0:enable='{условие}'[речь];"
        f"[1:a]volume={ГРОМКОСТЬ_ПИСКА},volume=0:enable='not({условие})'[тон];"
        # normalize=0 обязателен. Без него amix делит уровень на число входов,
        # и вся запись — не только заглушенные куски — становится тише на
        # шесть децибел. Замер это и показал: −21 дБ до редакции, −27 после,
        # причём в тех местах, которых редакция не касалась вовсе.
        "[речь][тон]amix=inputs=2:duration=first:dropout_transition=0:"
        "normalize=0[итог]",
        "-map", "[итог]", str(dst)]


def заглушить(src: Path, dst: Path, segments: list[dict[str, Any]], *,
              mode: str = "beep", kinds: tuple[str, ...] | None = None,
              padding_ms: int = ЗАПАС_МС, ffmpeg: str = "ffmpeg",
              timeout_s: float = 600.0) -> Итог:
    """Делает отредактированную копию записи.

    Ничего не найдено — файл не создаётся вовсе, и это не ошибка: ответ так и
    говорит. Копия без единой правки только занимала бы место и создавала
    впечатление, что редакция что-то сделала.
    """
    интервалы = найти_интервалы(segments, kinds=kinds, padding_ms=padding_ms)
    счёт: dict[str, int] = {}
    for и in интервалы:
        for вид in и.kind.split("+"):
            счёт[вид] = счёт.get(вид, 0) + 1
    итог = Итог(intervals=интервалы, counts=счёт,
                estimated=sum(1 for и in интервалы if и.estimated))
    if not интервалы:
        return итог

    источник = Path(src)
    if not источник.is_file():
        raise RedactError(f"Файл записи не найден: {источник.name}",
                          hint="Запись могла быть удалена по сроку хранения.")
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    команда = построить_команду(источник, dst, интервалы, mode=mode, ffmpeg=ffmpeg)
    try:
        готово = subprocess.run(команда, capture_output=True, text=True,
                                timeout=max(10.0, float(timeout_s)), check=False)
    except FileNotFoundError as exc:
        raise RedactError("ffmpeg не найден — редакция звука без него невозможна.",
                          hint="Установите ffmpeg: apt install ffmpeg.") from exc
    except subprocess.TimeoutExpired as exc:
        raise RedactError("ffmpeg не уложился в отведённое время.",
                          hint="Увеличьте предел или отредактируйте запись частями."
                          ) from exc
    if готово.returncode != 0 or not dst.is_file() or dst.stat().st_size == 0:
        # Слова ffmpeg подставляются, когда они есть: без них подсказка
        # отправляет искать неисправность не туда.
        хвост = (готово.stderr or "").strip().splitlines()
        подробность = f" {хвост[-1]}" if хвост else ""
        raise RedactError(f"ffmpeg не смог отредактировать запись.{подробность}",
                          hint="Проверьте, что исходный файл читается.")
    итог.path = dst
    log.info("Редакция звука: %s → %s, заглушено %d %s",
             источник.name, dst.name, len(интервалы), "куск(ов)")
    return итог
