"""Сшивка фрагментов: убирает то, что распозналось дважды на стыке.

Механическая нарезка режет запись на куски с перекрытием — иначе слово,
пришедшееся ровно на разрез, теряется целиком. Плата за это в том, что
речь в зоне перекрытия распознаётся дважды, и обе копии попадают в
расшифровку: при перекрытии в секунду и фрагментах по двадцать пять
секунд это по секунде лишнего текста на каждом стыке, то есть примерно
четыре процента расшифровки — повторённые слова посреди фразы.

Справочник обещает обратное прямым текстом: «дубликаты в зоне перекрытия
убираются при сшивке результатов». Убирать их было некому. Здесь они и
убираются.

Способов два, и выбор между ними — по тому, что вернул движок.

* Есть метки слов — режем по времени. Середина зоны перекрытия становится
  швом: у левого фрагмента остаются слова до шва, у правого — от шва.
  Каждое слово остаётся ровно один раз, и остаётся то, у которого больше
  контекста с его стороны.
* Меток нет — сличаем слова текстом. Хвост левого фрагмента и начало
  правого сравниваются по словам без учёта регистра и знаков; самое
  длинное совпадение убирается из правого. Не совпало ничего — не трогаем
  ничего: лучше оставить повтор, чем срезать настоящую речь.
"""
from __future__ import annotations

import re
from typing import Any

#: Сколько слов с краю имеет смысл сличать. Перекрытие — единицы секунд,
#: это десяток-полтора слов даже у быстрой речи; больший запас начинает
#: находить случайные совпадения посреди фразы.
ОКНО_СЛОВ = 24

_ЗНАКИ = re.compile(r"[^\w\-]+", re.UNICODE)


def _ключ(слово: str) -> str:
    """Слово в виде, пригодном для сравнения: без знаков и регистра."""
    return _ЗНАКИ.sub("", str(слово or "")).casefold()


def _слова_текста(текст: str) -> list[str]:
    return [ч for ч in str(текст or "").split() if ч]


def _текст_из_слов(слова: list[dict[str, Any]]) -> str:
    части: list[str] = []
    for слово in слова:
        часть = str(слово.get("word") or слово.get("text") or "").strip()
        if часть:
            части.append(часть)
    return " ".join(части)


def _общий_хвост(левые: list[str], правые: list[str]) -> int:
    """Длина самого длинного совпадения «хвост левого = начало правого»."""
    предел = min(len(левые), len(правые), ОКНО_СЛОВ)
    левые_к = [_ключ(с) for с in левые[-предел:]] if предел else []
    правые_к = [_ключ(с) for с in правые[:предел]] if предел else []
    for длина in range(предел, 0, -1):
        if not _всё_значимо(левые_к[-длина:]):
            continue
        if левые_к[-длина:] == правые_к[:длина]:
            return длина
    return 0


def _всё_значимо(ключи: list[str]) -> bool:
    """Совпадение из пустых ключей (одни знаки) ничего не доказывает."""
    return bool(ключи) and all(ключи)


def убрать_повторы(segments: list[Any], overlap: float) -> list[Any]:
    """Убирает повторы на стыках фрагментов. Список меняется на месте.

    `overlap` — заявленное перекрытие в секундах. Ноль означает «нарезали
    встык», и тогда убирать нечего: любое совпадение слов на стыке —
    настоящий повтор в речи.
    """
    if overlap <= 0 or len(segments) < 2:
        return segments
    итог = [segments[0]]
    for следующий in segments[1:]:
        предыдущий = итог[-1]
        начало = float(getattr(следующий, "start", 0.0) or 0.0)
        конец = float(getattr(предыдущий, "end", 0.0) or 0.0)
        if начало >= конец:                      # фрагменты не перекрываются
            итог.append(следующий)
            continue
        шов = (начало + конец) / 2.0
        if getattr(предыдущий, "words", None) and getattr(следующий, "words", None):
            _по_словам(предыдущий, следующий, шов)
        else:
            _по_тексту(предыдущий, следующий)
        итог.append(следующий)
    # Фрагмент, из которого убрали всё, в расшифровке не нужен.
    return [с for с in итог if str(getattr(с, "text", "") or "").strip()]


def _по_словам(предыдущий: Any, следующий: Any, шов: float) -> None:
    """Режем по времени: слово остаётся у того фрагмента, где его больше."""
    левые = [с for с in предыдущий.words
             if float(с.get("start") or 0.0) < шов]
    правые = [с for с in следующий.words
              if float(с.get("start") or 0.0) >= шов]
    # Пустой результат означает, что метки слов разъехались с границами
    # фрагмента (так бывает у движков, считающих время от начала куска).
    # Резать вслепую нельзя — оставляем как было и пробуем текстом.
    if not левые or not правые:
        _по_тексту(предыдущий, следующий)
        return
    предыдущий.words = левые
    следующий.words = правые
    предыдущий.text = _текст_из_слов(левые)
    следующий.text = _текст_из_слов(правые)
    предыдущий.end = min(float(предыдущий.end),
                         max(float(с.get("end") or шов) for с in левые))
    следующий.start = max(float(следующий.start),
                          min(float(с.get("start") or шов) for с in правые))


def _по_тексту(предыдущий: Any, следующий: Any) -> None:
    """Меток слов нет — сличаем хвост и начало по словам."""
    левые = _слова_текста(getattr(предыдущий, "text", ""))
    правые = _слова_текста(getattr(следующий, "text", ""))
    сколько = _общий_хвост(левые, правые)
    if not сколько:
        return
    следующий.text = " ".join(правые[сколько:]).strip()
    if getattr(следующий, "words", None):
        следующий.words = следующий.words[сколько:]
