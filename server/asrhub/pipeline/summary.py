"""Краткое содержание расшифровки — без языковой модели.

Параметр `summary_enabled` обещал сводку, а конвейер её не делал: выгрузки
Markdown и Word ждали поле `summary` (раздел «Краткое содержание»), и
заполнять его было некому. Здесь — выжимка: несколько предложений самой
расшифровки, выбранных по частоте значимых слов и по месту в разговоре.
Пересказ своими словами — задача языковой модели (разбор моделью, задача
summary): он появляется в карточке записи позже, когда модель ответит, а
выжимка готова вместе с выгрузкой и ничего не стоит.
"""
from __future__ import annotations

import math
import re
from collections import Counter
from collections.abc import Iterable
from typing import Any

from ..content.keywords import counts

#: Граница предложения: знак конца и пробел после него.
_ГРАНИЦА = re.compile(r"(?<=[.!?…])\s+")

#: Короче этого — не содержание, а реплика поддержки: «да», «угу, понятно».
МИН_СЛОВ = 4

#: Сколько предложений брать: доля от всех, но не меньше двух и не больше
#: пяти — выжимка длиннее пяти предложений уже не краткое содержание.
ДОЛЯ = 0.1
НЕ_МЕНЬШЕ = 2
НЕ_БОЛЬШЕ = 5

#: Начало разговора — причина обращения, конец — договорённости: им
#: небольшая прибавка к весу.
НАЧАЛО = 0.15
КОНЕЦ = 0.10
ПРИБАВКА = 1.2


def предложения(реплики: Iterable[dict[str, Any]]) -> list[str]:
    """Предложения расшифровки по порядку — без коротких реплик поддержки."""
    итог: list[str] = []
    for реплика in реплики:
        текст = str(реплика.get("text") or "").strip()
        for часть in _ГРАНИЦА.split(текст):
            часть = часть.strip()
            if len(часть.split()) >= МИН_СЛОВ:
                итог.append(часть)
    return итог


def выжимка(реплики: Iterable[dict[str, Any]], *, предел: int = НЕ_БОЛЬШЕ) -> str:
    """Самые содержательные предложения расшифровки — в порядке разговора.

    Вес предложения — сумма частот его значимых основ по всей записи,
    делённая на корень из их числа: иначе побеждало бы самое длинное. Пусто,
    если выбирать не из чего.
    """
    все = предложения(реплики)
    if not все:
        return ""
    основы = [counts(предложение) for предложение in все]
    частоты: Counter[str] = Counter()
    for набор in основы:
        частоты.update(набор.keys())
    if not частоты:
        return ""
    вершина = max(частоты.values())
    сколько = max(НЕ_МЕНЬШЕ, min(max(1, предел), round(len(все) * ДОЛЯ)))

    def вес(индекс: int) -> float:
        своё = основы[индекс]
        if not своё:
            return 0.0
        значение = sum(частоты[о] / вершина for о in своё) / math.sqrt(len(своё))
        место = индекс / max(1, len(все) - 1)
        if место <= НАЧАЛО or место >= 1.0 - КОНЕЦ:
            значение *= ПРИБАВКА
        return значение

    лучшие = sorted(range(len(все)), key=lambda и: (-вес(и), и))[:сколько]
    return " ".join(все[и] for и in sorted(лучшие) if основы[и])
