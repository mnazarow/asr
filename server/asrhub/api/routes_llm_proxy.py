def _взять_слот(клиент: Any, ждать: float) -> threading.BoundedSemaphore:
    """Занимает ТОТ ЖЕ слот одновременности, что и внутренний разбор.

    Это главное решение всего файла, поэтому объясню целиком.

    `LLMClient` держит семафор на `llm_max_concurrent` (по умолчанию —
    один) и берёт его на каждый вызов модели. Смысл настройки не в
    вежливости, а в памяти: модель и распознавание живут на одной
    видеокарте, и второй одновременный вызов не ускоряет ответ, а делит
    память — в худшем случае до отказа «не хватило памяти» у обоих.

    Если бы шлюз завёл свой семафор на ту же единицу, предел стал бы
    двойкой: один разбор записи и один запрос из сети идут разом, и
    настройка «одновременных вызовов: 1» перестала бы значить то, что
    написано в её описании. Поэтому мы берём не такой же семафор, а
    буквально тот же объект — через `LLMClient._семафор()`, который
    вдобавок пересобирает его при смене настройки на живом сервере.

    Отсюда и обращение к «внутреннему» методу клиента: любой другой способ
    честным не будет. Дублировать семафор нельзя по написанному выше,
    а публичного «дай слот» у клиента нет, потому что до сих пор он был
    нужен только ему самому.

    Ждать вечно тоже нельзя: очередь разбора архива занимает слот часами, а
    на том конце сидит чужая программа со своим тайм-аутом. Ждём столько,
    сколько отведено на один вызов модели (`llm_timeout_s`), и отвечаем
    503 с понятным текстом — клиент OpenAI такой ответ повторяет сам.
    """
    семафор = клиент._семафор()                               # noqa: SLF001
    if not семафор.acquire(timeout=max(0.5, float(ждать))):
        raise ШлюзЗанят(
            f"Модель занята: свободного слота не дождались за {ждать:g} с.",
            hint="Сейчас идёт разбор записей или другой запрос из сети. "
                 "Повторите позже или поднимите llm_max_concurrent, если "
                 "сервер модели держит несколько запросов разом (vLLM).")
    return семафор


#: Сколько ждать, пока ответ потоком начнёт отдаваться клиенту. Слот
#: занимается ДО ответа (иначе нельзя честно ответить 503 «модель занята»),
#: а освобождается в генераторе тела. Клиент, отключившийся до первого
#: куска, генератор не запускал вовсе — слот не освобождался никогда, и
#: очередь разбора вставала: внутренний `chat()` ждёт слот без срока.
НЕ_НАЧАЛСЯ_С = 60.0

#: Предел жизни одного потокового ответа. Медленный клиент, который не
#: читает ответ, держал единственный слот модели сколько угодно.
def _предел_потока(клиент: Any) -> float:
    return max(600.0, 5.0 * float(getattr(клиент, "timeout", 90.0) or 90.0))


class _Слот:
    """Занятый слот модели, который отпускается ровно один раз.

    Отпускают его трое: генератор тела ответа (штатно), сторож «ответ так
    и не начался» и сторож предельного срока. Повторный `release()` у
    BoundedSemaphore — это ValueError и лишний слот, поэтому отпускание
    идёт под замком и только однажды.
    """

    def __init__(self, семафор: threading.BoundedSemaphore) -> None:
        self._семафор = семафор
        self._замок = threading.Lock()
        self._отпущен = False
        self._часы: list[threading.Timer] = []
        self.начат = False
        self.источник: Any = None
        #: Почему слот отпустил сторож; пусто — отпустили штатно.
        self.сторож = ""

    def отпустить(self) -> bool:
        with self._замок:
            if self._отпущен:
                return False
            self._отпущен = True
        for часы in self._часы:
            часы.cancel()
        self._семафор.release()
        return True

    @property
    def отпущен(self) -> bool:
        return self._отпущен

    def сторожить(self, через: float, почему: str) -> None:
        часы = threading.Timer(max(0.1, float(через)), self._сработал, args=(почему,))
        часы.daemon = True
        self._часы.append(часы)
        часы.start()

    def _сработал(self, почему: str) -> None:
        if почему == "не начался" and self.начат:
            return
        if not self.отпустить():
            return
        self.сторож = почему
        log.warning("Шлюз модели: слот освобождён сторожем (%s)", почему)
        # Источник закрываем, чтобы сервер модели перестал отвечать в
        # пустоту: иначе модель продолжала бы занимать видеокарту.
        источник = self.источник
        if источник is not None:
            try:
                источник.close()
            except Exception:                               # noqa: BLE001
                pass


@contextlib.contextmanager
def _слот(клиент: Any) -> Iterator[None]:
    """Слот на время одного обычного (не потокового) запроса."""
    семафор = _взять_слот(клиент, клиент.timeout)
    try:
        _хватит_памяти(клиент)
        yield
    finally:
        # Освобождаем именно тот объект, который заняли. При смене
        # `llm_max_concurrent` клиент заводит новый семафор, и `release()`
        # на новом уронил бы `ValueError` из BoundedSemaphore, а заодно
        # раздал бы лишний слот.
        семафор.release()


def _хватит_памяти(клиент: Any) -> None:
    """Порог свободной видеопамяти — тот же, что у внутреннего разбора.

    `llm_min_free_vram_gb` проверяется внутри `LLMClient.chat`, а шлюз в сеть
    ходит к модели мимо него — прямо через `_http`. Порог этот не про
    вежливость: он держит место под веса РАСПОЗНАВАНИЯ, и придуман ровно для
    того, чтобы запрос к языковой модели не выдавил их с карты посреди
    очереди заданий. Шлюз его не соблюдал вовсе, то есть любой сторонний
    клиент мог занять память, которую сервер для себя берёг, — а
    распознавание после этого падало с нехваткой памяти.
    """
    проверка = getattr(клиент, "_check_vram", None)
    if not callable(проверка):
        return
    try:
        проверка()
    except LLMError as exc:
        # Это «занято», а не «сервер модели сломался»: память освободится
        # сама, как только распознавание закончит запись. Поэтому 503 и
        # «повторяемо», как у переполненной очереди, а не 502.
        raise _отказ(ШлюзЗанят(
            str(exc),
            hint="Порог свободной видеопамяти задан параметром "
                 "llm_min_free_vram_gb и держит место под веса "
                 "распознавания. Повторите запрос позже или уменьшите "
                 "порог, если языковая модель для вас важнее.")) from exc


