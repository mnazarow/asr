def наборы() -> list[dict[str, Any]]:
    """Список отраслевых наборов для выбора в интерфейсе."""
    return [{"id": ключ, "title": набор["title"],
             "description": набор["description"],
             "count": len(набор["categories"])}
            for ключ, набор in НАБОРЫ.items()]


def с_набором(имя: str, основа: list[dict[str, Any]] | None = None
              ) -> list[dict[str, Any]]:
    """Общий набор плюс отраслевой. Неизвестное имя — просто общий.

    Совпадающие идентификаторы разводятся: отраслевая категория с тем же
    именем, что у общей, не должна её затирать — иначе выбор отрасли молча
    отменял бы правило, которое человек до этого правил руками.
    """
    основа = list(основа if основа is not None else ГОТОВЫЕ)
    набор = НАБОРЫ.get(str(имя or "").strip().lower())
    if not набор:
        return основа
    занятые = {str(к.get("id") or "") for к in основа}
    добавка: list[dict[str, Any]] = []
    for категория in набор["categories"]:
        своя = dict(категория)
        имя_категории = str(своя.get("id") or "")
        if имя_категории in занятые:
            своя["id"] = f"{имя_категории}_{имя}"
        занятые.add(str(своя["id"]))
        добавка.append(своя)
    return [*основа, *добавка]


def _имя(подпись: str, занятые: set[str], n: int) -> str:
    основа = _НЕ_ИМЯ.sub("_", str(подпись or "").lower().replace("ё", "е")).strip("_")
    имя = основа or f"category{n}"
    k = 2
    while имя in занятые:
        имя = f"{основа or 'category'}{k}"
        k += 1
    return имя


def normalize(категории: Any) -> list[dict[str, Any]]:
    """Список категорий с заполненными полями и уникальными именами.

    Терпимо к тому, что приходит из настроек: строки вместо чисел, пустые
    поля, отсутствующие имена. Непонятное не выбрасывает — заполняет
    значением по умолчанию: молча потерять категорию хуже, чем применить
    её без окна.
    """
    if not isinstance(категории, list):
        return []
    out: list[dict[str, Any]] = []
    занятые: set[str] = set()
    for n, сырое in enumerate(категории):
        if not isinstance(сырое, dict):
            continue
        имя = str(сырое.get("id") or "").strip()
        if not имя or имя in занятые:
            имя = _имя(сырое.get("label") or имя, занятые, n + 1)
        занятые.add(имя)
        try:
            окно = max(0.0, float(сырое.get("within_s") or 0))
        except (TypeError, ValueError):
            окно = 0.0
        try:
            штраф = max(0.0, float(сырое.get("penalty") or 0))
        except (TypeError, ValueError):
            штраф = 0.0
        try:
            вес = float(сырое.get("weight") if сырое.get("weight") is not None else 1)
        except (TypeError, ValueError):
            вес = 1.0
        out.append({
            "id": имя,
            "label": str(сырое.get("label") or имя).strip(),
            "kind": сырое.get("kind") if сырое.get("kind") in ВИДЫ else "topic",
            "who": сырое.get("who") if сырое.get("who") in КТО else "any",
            "where": сырое.get("where") if сырое.get("where") in ГДЕ else "any",
            "within_s": окно or None,
            "rule": str(сырое.get("rule") or "").strip(),
            "notify": bool(сырое.get("notify")),
            "penalty": штраф,
            "weight": вес,
        })
    return out


def notes(категории: Any) -> list[str]:
    """Предупреждения по набору — не ошибки: сохранить такой набор можно.

    Правило из одних НЕ срабатывает там, где фраз нет, и совпадений у него
    нет: «что нашли» оно не покажет, а в счёте даёт одно совпадение на
    запись. Так и задумывают «не попрощался», но так же легко получить
    категорию, которая горит на каждой короткой записи.

    Принимает и сырой набор из настройки, и уже разобранный.
    """
    if not isinstance(категории, list):
        return []
    out: list[str] = []
    for категория in compile(категории):
        if категория.error or категория.tree is None:
            continue
        if not rules.positive(категория.tree):
            out.append(f"«{категория.label}»: правило из одних НЕ — срабатывает там, "
                       f"где фраз нет, считается одним совпадением на запись и «что "
                       f"нашли» не покажет")
    return out


def validate(категории: Any) -> list[str]:
    """Ошибки набора — для проверки настройки при сохранении.

    Пустой список — набор годный. Ошибка правила называет категорию и
    позицию: редактор подсвечивает её, а настройка с такой ошибкой в базу
    не попадает — иначе она всплыла бы через сутки в фоновом разборе.
    """
    if not isinstance(категории, list):
        return ["ожидается список категорий"]
    if len(категории) > МАКС_КАТЕГОРИЙ:
        return [f"категорий больше {МАКС_КАТЕГОРИЙ}"]
    ошибки: list[str] = []
    имена: set[str] = set()
    for n, сырое in enumerate(категории, start=1):
        if not isinstance(сырое, dict):
            ошибки.append(f"категория {n}: ожидается объект")
            continue
        подпись = str(сырое.get("label") or "").strip()
        кто = подпись or f"категория {n}"
        if not подпись:
            ошибки.append(f"{кто}: нет названия")
        имя = str(сырое.get("id") or "").strip()
        if имя:
            if имя in имена:
                ошибки.append(f"{кто}: имя «{имя}» уже занято")
            имена.add(имя)
        for поле, допустимые in (("kind", ВИДЫ), ("who", КТО), ("where", ГДЕ)):
            значение = сырое.get(поле)
            if значение is not None and значение not in допустимые:
                ошибки.append(f"{кто}: поле {поле} — одно из "
                              f"{', '.join(допустимые)}")
        try:
            if float(сырое.get("within_s") or 0) < 0:
                raise ValueError
        except (TypeError, ValueError):
            ошибки.append(f"{кто}: окно within_s должно быть числом секунд")
        ошибка = rules.check(str(сырое.get("rule") or ""))
        if ошибка:
            ошибки.append(f"{кто}: {ошибка}")
    return ошибки


def compile(категории: Any) -> list[Compiled]:  # noqa: A001
    """Разобрать набор один раз — применять к каждой записи.

    Ошибка в правиле одной категории не останавливает остальные: она
    остаётся в `error`, попадает в ответ проверки и в состояние раздела, а
    запись разбирается по годным.
    """
    if категории and all(isinstance(к, Compiled) for к in категории):
        return list(категории)
    out: list[Compiled] = []
    for к in normalize(категории):
        дерево, ошибка = None, ""
        try:
            дерево = rules.parse(к["rule"])
        except rules.RuleError as exc:
            ошибка = f"{exc.message} (позиция {exc.position + 1})"
        out.append(Compiled(
            id=к["id"], label=к["label"], kind=к["kind"], who=к["who"],
            where=к["where"], within_s=float(к["within_s"] or 0),
            rule=к["rule"], tree=дерево, error=ошибка, notify=к["notify"],
            penalty=к["penalty"], weight=к["weight"]))
    return out


def _время(с: dict[str, Any], край: str) -> float:
    for ключ in (край, f"{край}_s"):
        if с.get(ключ) is not None:
            try:
                return float(с[ключ])
            except (TypeError, ValueError):
                continue
    return 0.0


def _область(сегменты: list[dict[str, Any]], категория: Compiled,
             стороны: dict[str, str | None]) -> tuple[list[int], bool]:
    """Номера реплик, в которых ищется категория, и известна ли сторона.

    Когда сторона не определена (говорящий один или не размечен), ищем по
    всем репликам — лучше найти без разделения, чем не искать вовсе; но
    отмечаем это: «нарушение оператора», найденное в реплике неизвестно
    кого, — не обвинение, а повод послушать.

    Возвращаются номера, а не сами реплики: возражению клиента нужно знать,
    какие реплики идут *после* него в полной записи, а не в области поиска.
    """
    кто = стороны.get(категория.who) if категория.who != "any" else None
    сторона_известна = категория.who == "any" or кто is not None
    свои = [i for i, с in enumerate(сегменты)
            if кто is None or str(с.get("speaker") or "") == кто]
    if категория.where == "any" or not свои:
        return свои, сторона_известна
    if категория.within_s:
        первая = min((_время(с, "start") for с in сегменты), default=0.0)
        последняя = max((_время(с, "end") for с in сегменты), default=0.0)
        if категория.where == "start":
            куски = [i for i in свои
                     if _время(сегменты[i], "start") - первая <= категория.within_s]
        else:
            куски = [i for i in свои
                     if последняя - _время(сегменты[i], "end") <= категория.within_s]
        return куски, сторона_известна
    край = max(1, int(len(свои) * ДОЛЯ_КРАЯ))
    return (свои[:край] if категория.where == "start" else свои[-край:]), сторона_известна


def apply(segments: list[dict[str, Any]], categories: list[Compiled] | list[dict[str, Any]],
          *, agent: str | None = None, customer: str | None = None,
          everything: bool = False, objections_limit: int = 20) -> dict[str, Any]:
    """Применить набор к одной записи.

    Возвращает сработавшие категории со счётом совпадений, временем первого
    и примерами реплик; с `everything=True` — все категории, включая те,
    что не сработали и не разобрались: так проверяет редактор. Отдельно —
    возражения клиента и то, были ли они отработаны (см. `_возражения`);
    `objections_limit` — сколько возражений отдать списком (подсказкам в
    живом разговоре нужны все, отчёту — первые двадцать).
    """
    набор = compile(categories)
    сегменты = list(segments or [])
    стороны = {"agent": agent, "customer": customer}
    items: list[dict[str, Any]] = []
    ошибок = 0
    #: Номера реплик с совпадениями по категориям возражений и отработки —
    #: для проверки «за возражением не последовало».
    возражения: list[tuple[int, str, str]] = []
    отработки: set[int] = set()
    есть_отработка = any(к.kind == "handling" and not к.error for к in набор)
    for категория in набор:
        if категория.error:
            ошибок += 1
            if everything:
                items.append({**категория.to_dict(), "count": 0, "first_s": None,
                              "hits": [], "sides": True})
            continue
        номера, известна = _область(сегменты, категория, стороны)
        if not номера:
            # Искать негде: у стороны нет ни одной реплики. Правило из
            # одних НЕ на пустом месте сработало бы всегда — и «не
            # попрощался» доставался бы оператору, который вообще не говорил.
            if everything:
                items.append({**категория.to_dict(), "count": 0, "first_s": None,
                              "hits": [], "sides": известна, "error": None})
            continue
        куски = [сегменты[i] for i in номера]
        текст = rules.Text.of(куски)
        итог = rules.evaluate(категория.tree, текст)
        if not итог.matched and not everything:
            continue
        примеры = []
        первое = None
        for совпадение in sorted(итог.hits, key=lambda h: h.start):
            местный = текст.segment[совпадение.start] if текст.segment else 0
            номер = номера[местный] if местный < len(номера) else 0
            реплика = сегменты[номер] if номер < len(сегменты) else {}
            когда = _время(реплика, "start")
            первое = когда if первое is None else min(первое, когда)
            if категория.kind == "objection":
                возражения.append((номер, категория.id, совпадение.text))
            elif категория.kind == "handling":
                отработки.add(номер)
            if len(примеры) < ПРИМЕРОВ:
                примеры.append({
                    "start_s": round(когда, 2),
                    "speaker": реплика.get("speaker"),
                    "matched": совпадение.text,
                    "text": str(реплика.get("text") or "").strip()[:200],
                })
        # Правило из одних НЕ совпадений не даёт: «не попрощался» — это
        # отсутствие слов, а не слова. Сработавшее такое правило считается
        # одним совпадением на запись, иначе категория не засчитывалась
        # вовсе: ни нарушения, ни штрафа, ни строки в таблице совпадений,
        # хотя пункт скрипта с тем же правилом был «выполнен».
        сколько = len(итог.hits) or (1 if итог.matched else 0)
        items.append({
            "id": категория.id, "label": категория.label, "kind": категория.kind,
            "who": категория.who, "count": сколько,
            "first_s": round(первое, 2) if первое is not None else None,
            "hits": примеры, "sides": известна, "penalty": категория.penalty,
            **({"error": None, "rule": категория.rule, "where": категория.where,
                "within_s": категория.within_s or None} if everything else {}),
        })
    сработали = [и["id"] for и in items if и.get("count")]
    штрафы = {к.id: к.penalty for к in набор if к.penalty}
    # Нарушение, найденное в реплике неизвестно кого (говорящий один или не
    # размечен), — не обвинение, а повод послушать: в число нарушений
    # оператора и в штраф к его баллу оно не идёт. Иначе на моно-записи «не
    # знаю» клиента снимало с оператора баллы и отправляло запись в коучинг
    # как его нарушение.
    доказано = [и for и in items if и.get("count") and и.get("sides", True)]
    return {"checked": len(набор), "errors": ошибок, "matched": сработали,
            "items": items,
            "objections": _возражения(сегменты, возражения, отработки, есть_отработка,
                                      предел=objections_limit),
            # Нарушения оператора и штрафы к баллу: штраф — за категорию, а
            # не за каждое совпадение: пять «не знаю» в одном разговоре —
            # одно нарушение, а не пять; сколько раз — видно по счёту.
            "violations": [{"id": и["id"], "label": и["label"], "count": и["count"],
                            "penalty": штрафы.get(и["id"], 0.0)}
                           for и in доказано if и["kind"] == "violation"],
            # Те же нарушения, но без известной стороны: показываются в
            # карточке записи с пометкой, в балл и в счёт не входят.
            "violations_unsure": [{"id": и["id"], "label": и["label"], "count": и["count"]}
                                  for и in items if и.get("count") and not и.get("sides", True)
                                  and и["kind"] == "violation"],
            "penalty_total": sum(штрафы.get(и["id"], 0.0) for и in доказано)}


#: В скольких следующих репликах ждать отработки возражения. Три — это
#: ответ оператора, уточнение клиента и второй ответ: дальше разговор уже
#: о другом, и «отработка» на десятой реплике — совпадение слов.
ОКНО_ОТРАБОТКИ = 3


def _возражения(сегменты: list[dict[str, Any]], найденные: list[tuple[int, str, str]],
                отработки: set[int], есть_отработка: bool, *,
                предел: int = 20) -> dict[str, Any]:
    """Возражения клиента и было ли за каждым что-то из «отработки».

    Правило Т-Банка «где менеджер не отработал возражение»: за репликой
    вида «дорого», «подумаю», «не нужно» в следующих трёх репликах нет ни
    одной из категории «отработка возражения». Без категорий отработки в
    наборе неотработанность не считается вовсе: иначе каждое возражение
    было бы «без ответа», и число ничего бы не значило.
    """
    # Одна реплика — одно возражение, сколько бы примет в ней ни совпало.
    по_репликам: dict[int, tuple[str, list[str]]] = {}
    for номер, категория, примета in найденные:
        запись = по_репликам.setdefault(номер, (категория, []))
        if примета not in запись[1]:
            запись[1].append(примета)
    items = []
    без_ответа = 0
    for номер in sorted(по_репликам):
        категория, приметы = по_репликам[номер]
        отработано = (any(номер < i <= номер + ОКНО_ОТРАБОТКИ for i in отработки)
                      if есть_отработка else None)
        if отработано is False:
            без_ответа += 1
        реплика = сегменты[номер] if номер < len(сегменты) else {}
        items.append({
            "start_s": round(_время(реплика, "start"), 2),
            "speaker": реплика.get("speaker"),
            "category": категория,
            "matched": ", ".join(приметы),
            "text": str(реплика.get("text") or "").strip()[:200],
            "handled": отработано,
            # Номер реплики: подсказке в живом разговоре нужно знать, прошло
            # ли после возражения окно на отработку, а по времени реплик
            # (у переписки его нет вовсе) этого не понять.
            "index": номер,
        })
    return {"count": len(items),
            "unhandled": без_ответа if есть_отработка else None,
            "items": items[:max(1, int(предел))]}


def for_db(результат: dict[str, Any]) -> list[dict[str, Any]]:
    """Строки таблицы совпадений из результата по записи."""
    return [{"category": и["id"], "kind": и.get("kind") or "topic",
             "count": int(и.get("count") or 0), "first_s": и.get("first_s")}
            for и in результат.get("items") or [] if и.get("count")]


def suspicious(категории: Any, document_frequency: dict[str, int] | None = None,
               corpus_size: int = 0) -> list[dict[str, str]]:
    """Операнды, совпадающие со слишком частыми словами, — как у скрипта.

    Правило «оплата ИЛИ это» сработает в каждой записи из-за «это», и
    категория «Оплата» покроет весь архив. Кавычки не спасают: точная
    форма частого слова так же часта.
    """
    найдено: list[dict[str, str]] = []
    for категория in compile(категории):
        if категория.error:
            continue
        for операнд in rules.operands(категория.tree):
            if len(операнд.words) != 1:
                continue
            основа = stem(операнд.words[0]) if операнд.exact else операнд.words[0]
            if frequent_marker(основа, document_frequency, corpus_size):
                найдено.append({"word": операнд.text, "label": категория.label})
    return найдено
