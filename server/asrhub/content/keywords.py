"""О чём говорили: ключевые слова разговора и темы по корпусу.

Внутри одной записи «часто» — плохая мера: в любом разговоре чаще всего
встречается «договор», если разговор про договор, и это не новость. Поэтому
вес слова считается по TF-IDF: часто здесь и редко в остальных записях. Для
одиночной записи, когда корпуса ещё нет, берётся простая частота без
служебных слов — с честной пометкой, что это именно частота.
"""
from __future__ import annotations

import math
import re
from collections import Counter
from typing import Any

from .lexicons import СТОП_СЛОВА
from .stemmer import stem, words

#: Короткие слова и основы почти всегда служебные, а не значимые.
МИН_ДЛИНА = 3
MIN_STEM = 3

#: Сколько основ записи попадает в корпусный указатель (таблица
#: `content_terms`). Хранить весь словарь записи не нужно: основа, не
#: вошедшая в кандидаты ни в одной записи, никогда и не взвешивается, а
#: разница в размере таблицы — на порядок.
LIMIT_ОСНОВ = 60


#: Почта, ссылки и телефоны выбрасываются до разбора на слова: иначе адрес
#: «anna@romashka.ru» распадался на «anna» и «romashka», и обе половинки
#: лезли в ключевые слова записи, где им делать нечего. Сами адреса лежат в
#: разрезе сущностей — там от них польза есть.
_МУСОР = re.compile(
    r"[A-Za-z0-9._%+-]+@\S+|https?://\S+|(?<!\d)(?:\+7|8)[\s\-(]*\d[\d\s\-()]{8,}")


def _значимые(текст: str) -> list[tuple[str, str]]:
    """Пары «основа, исходное слово» — без служебных, коротких и мусора."""
    out = []
    for слово in words(_МУСОР.sub(" ", текст or "")):
        if len(слово) < МИН_ДЛИНА or слово.isdigit():
            continue
        основа = stem(слово)
        if len(основа) < MIN_STEM or основа in СТОП_СЛОВА:
            continue
        out.append((основа, слово))
    return out


def counts(текст: str) -> Counter[str]:
    """Частоты основ одного текста."""
    return Counter(о for о, _ in _значимые(текст))


def surface_forms(текст: str) -> dict[str, str]:
    """Самая частая исходная форма каждой основы — её и показываем человеку.

    Показывать основу нельзя: «договор» ещё читается, а «оперативн» и
    «недовольн» выглядят как опечатка.
    """
    по_основам: dict[str, Counter[str]] = {}
    for основа, слово in _значимые(текст):
        по_основам.setdefault(основа, Counter())[слово] += 1
    return {о: c.most_common(1)[0][0] for о, c in по_основам.items()}


def corpus_terms(текст: str, limit: int = LIMIT_ОСНОВ) -> list[dict[str, Any]]:
    """Основы записи для корпусного знаменателя — самые частые в ней.

    Вместе с основой хранится и форма для показа. Без неё темы по корпусу
    пришлось бы подписывать основами, а «оперативн» и «недовольн» человек
    читает как опечатку; восстанавливать же форму по основе нельзя — из
    «поставк» одинаково выводятся «поставка» и «поставки».
    """
    формы = surface_forms(текст)
    return [{"stem": основа, "word": формы.get(основа, основа), "n": n}
            for основа, n in counts(текст).most_common(limit)]


def keywords(текст: str, *, document_frequency: dict[str, int] | None = None,
             corpus_size: int = 0, limit: int = 25,
             min_df: int = 2) -> list[dict[str, Any]]:
    """Ключевые слова записи.

    `document_frequency` — в скольках записях корпуса встречалась основа;
    без него считается простая частота.

    `min_df` — отсечка, с которой словарь частот собран. Знать её здесь
    обязательно: основы, встретившиеся реже, в словарь не попали, а
    `.get(основа, 0)` возвращает для них ноль — то есть самую большую
    редкость и самый большой вес во всём корпусе. Отсечка, заведённая
    против опечаток распознавания, поднимала их на первое место вместо
    того, чтобы убрать. Считаем такую основу встретившейся ровно `min_df`
    раз: реже, чем всё, что есть в словаре, но не реже возможного.
    """
    частоты = counts(текст)
    if not частоты:
        return []
    формы = surface_forms(текст)
    всего = sum(частоты.values())

    out = []
    for основа, n in частоты.items():
        tf = n / всего
        if document_frequency and corpus_size > 1:
            # Сглаживание в знаменателе: слово, встреченное впервые, иначе
            # делило бы на ноль, а слово из всех записей давало бы ровно
            # ноль и исчезало, хотя оно может быть важным.
            df = max(document_frequency.get(основа, 0), min_df) + 1
            idf = math.log((corpus_size + 1) / df) + 1.0
            вес = tf * idf
        else:
            вес = tf
        out.append({"stem": основа, "word": формы.get(основа, основа),
                    "count": n, "weight": round(вес, 5)})
    out.sort(key=lambda з: (-з["weight"], -з["count"], з["word"]))
    return out[:limit]


def phrases(текст: str, *, size: int = 2, limit: int = 15) -> list[dict[str, Any]]:
    """Устойчивые сочетания из двух-трёх слов.

    Отдельные слова отвечают «о чём», сочетания — «о чём именно»: «срок» и
    «поставка» по отдельности говорят меньше, чем «срок поставки».
    """
    значимые = _значимые(текст)
    if len(значимые) < size:
        return []
    счётчик: Counter[tuple[str, ...]] = Counter()
    показ: dict[tuple[str, ...], str] = {}
    for i in range(len(значимые) - size + 1):
        окно = значимые[i:i + size]
        ключ = tuple(о for о, _ in окно)
        счётчик[ключ] += 1
        показ.setdefault(ключ, " ".join(с for _, с in окно))
    return [{"phrase": показ[к], "count": n}
            for к, n in счётчик.most_common(limit) if n > 1]
