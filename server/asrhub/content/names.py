_ШИПЯЩИЕ = set("гкхжшчщ")


def _формы(имя: str) -> set[str]:
    """Падежные и звательная формы имени по правилам склонения."""
    имя = имя.lower().replace("ё", "е")
    формы = {имя}
    if имя.endswith("ия"):
        основа = имя[:-1]
        формы |= {основа + "и", основа + "ю", основа + "ей"}
    elif имя.endswith("я"):
        основа = имя[:-1]
        формы |= {основа + "и", основа + "е", основа + "ю", основа + "ей"}
        if len(основа) >= 2:
            формы.add(основа + "ь")                    # «Вань», «Оль», «Кать»
    elif имя.endswith("а"):
        основа = имя[:-1]
        родительный = "и" if основа[-1] in _ШИПЯЩИЕ else "ы"
        формы |= {основа + родительный, основа + "е", основа + "у", основа + "ой"}
        if len(основа) >= 3:
            формы.add(основа)                          # «Наташ», «Саш», «Ань»
    elif имя.endswith(("й", "ь")):
        основа = имя[:-1]
        формы |= {основа + "я", основа + "ю", основа + "ем", основа + "е"}
    else:
        формы |= {имя + "а", имя + "у", имя + "ом", имя + "е"}
    return формы


#: Беглые гласные и прочие исключения правил.
_ОСОБЫЕ: dict[str, tuple[str, ...]] = {
    "павел": ("павла", "павлу", "павлом", "павле"),
    "лев": (),
}

#: Формы, совпадающие с обычными словами разговора, — вычтены: «ИНН» —
#: не Инна, «лид» и «лиды» — не Лида, «марка» — не Марк, «кеш» — не Кеша,
#: «ген» — не Гена, «люд» — не Люда, «ник» — не Ника.
_ЛИШНИЕ = frozenset("инн лид лиды лиду лидой лиде марк марка марку марком марке "
                    "кеш ген люд ник зоь".split())

#: Все формы всех имён — для сравнения по точной форме.
ФОРМЫ_ИМЁН: frozenset[str] = frozenset(
    ф for имя in _ИМЕНА.split()
    for ф in (_ОСОБЫЕ.get(имя) or _формы(имя))) - _ЛИШНИЕ


def is_name(слово: str) -> bool:
    """Похоже ли слово на имя из словаря — по точной форме."""
    return (слово or "").lower().replace("ё", "е") in ФОРМЫ_ИМЁН
