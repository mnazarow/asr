"""Приведение русского слова к основе — без единой сторонней зависимости.

Зачем вообще. Всё, что делает раздел «Аналитика записей», упирается в один
вопрос: «договор», «договора», «договору» и «договорами» — это одно слово
или четыре? Без ответа не работает ни поиск ключевых слов (в верх списка
лезут падежи одного и того же), ни словарь оценочной лексики (в нём не
перечислить все формы), ни сравнение разговоров между собой.

Почему не библиотека. `pymorphy3` разбирает русский заметно лучше: он знает
части речи и словарь словоформ. Но сервер ставят в закрытый контур на
Python 3.14, где половина колёс ещё не собрана, и каждая обязательная
зависимость там — отдельный разговор. Здесь реализован алгоритм Snowball
для русского: опубликован, детерминирован, укладывается в две сотни строк
и не требует ничего, кроме стандартной библиотеки.

Чего он не умеет — и это надо знать, читая цифры раздела. Это не
морфологический разбор: основа не равна лемме. Чередование согласных
(«оплатить»/«оплачу») и беглые гласные («поставка»/«поставок») он не
сводит, а «банк» и «банка» сводит в одно, потому что различить их без
разбора предложения нельзя в принципе. Для задач раздела этого хватает:
там важно, чтобы формы одного слова считались вместе.
"""
from __future__ import annotations

import re

#: Гласные русского языка — по ним размечаются области слова.
ГЛАСНЫЕ = frozenset("аеиоуыэюя")

# --- окончания по группам алгоритма ----------------------------------------
#
# Ключевое правило, которое легко упустить: окончания «первой группы»
# засчитываются, только если перед ними стоит «а» или «я». Без него «он»
# терял «н» (оно есть в списке глагольных) и превращался в «о», а любое
# слово на «-л» считалось глаголом прошедшего времени.

_ДЕЕПРИЧАСТИЕ_1 = ("вшись", "вши", "в")
_ДЕЕПРИЧАСТИЕ_2 = ("ившись", "ывшись", "ивши", "ывши", "ив", "ыв")

_ПРИЧАСТИЕ_1 = ("ющ", "нн", "вш", "ем", "щ")
_ПРИЧАСТИЕ_2 = ("ивш", "ывш", "ующ")

_ПРИЛАГАТЕЛЬНОЕ = (
    "ее", "ие", "ые", "ое", "ими", "ыми", "ей", "ий", "ый", "ой", "ем", "им",
    "ым", "ом", "его", "ого", "ему", "ому", "их", "ых", "ую", "юю", "ая",
    "яя", "ою", "ею",
)

_ВОЗВРАТНОЕ = ("ся", "сь")

_ГЛАГОЛ_1 = (
    "ла", "на", "ете", "йте", "ли", "й", "л", "ем", "н", "ло", "но", "ет",
    "ют", "ны", "ть", "ешь", "нно",
)
_ГЛАГОЛ_2 = (
    "ила", "ыла", "ена", "ейте", "уйте", "ите", "или", "ыли", "ей", "уй",
    "ил", "ыл", "им", "ым", "ен", "ило", "ыло", "ено", "ят", "ует", "уют",
    "ит", "ыт", "ены", "ить", "ыть", "ишь", "ю",
)

_СУЩЕСТВИТЕЛЬНОЕ = (
    "а", "ев", "ов", "ие", "ье", "е", "иями", "ями", "ами", "еи", "ии", "и",
    "ией", "ей", "ой", "ий", "й", "иям", "ям", "ием", "ем", "ам", "ом", "о",
    "у", "ах", "иях", "ях", "ы", "ь", "ию", "ью", "ю", "ия", "ья", "я",
)

_ПРЕВОСХОДНАЯ = ("ейше", "ейш")
_ПРОИЗВОДНОЕ = ("ость", "ост")

_НЕ_БУКВА = re.compile(r"[^а-яa-z0-9-]+")
_ЕСТЬ_КИРИЛЛИЦА = re.compile(r"[а-я]")


def _границы(слово: str) -> tuple[int, int]:
    """RV и R2 — области, левее которых алгоритм ничего не срезает.

    RV начинается сразу после первой гласной, R2 — после второй пары
    «гласная-согласная». Без этих границ короткие слова съедались бы
    целиком: «дом» стал бы «д».
    """
    длина = len(слово)
    rv = длина
    for i, буква in enumerate(слово):
        if буква in ГЛАСНЫЕ:
            rv = i + 1
            break

    def после_пары(начало: int) -> int:
        i = начало
        while i + 1 < длина:
            if слово[i] in ГЛАСНЫЕ and слово[i + 1] not in ГЛАСНЫЕ:
                return i + 2
            i += 1
        return длина

    return rv, после_пары(после_пары(0))


def _найти(слово: str, rv: int, окончания: tuple[str, ...],
           после_а_я: bool = False) -> str | None:
    """Самое длинное подходящее окончание — или None.

    `после_а_я` включает правило первой группы: окончание засчитывается,
    только если непосредственно перед ним стоит «а» или «я».
    """
    for окончание in sorted(окончания, key=len, reverse=True):
        if not слово.endswith(окончание):
            continue
        граница = len(слово) - len(окончание)
        if граница < rv:
            continue
        if после_а_я:
            # «а»/«я» — условие, а не часть окончания: в основе она
            # остаётся («работал» → «работа», а не «работ»). И сама она
            # обязана лежать внутри RV. Без второго требования короткие
            # слова переусекались: «даёт» становилось «да» и склеивалось с
            # «дали» и «данные» — а «да» в расшифровке разговора встречается
            # в каждой второй реплике, и такая основа отравляла бы и
            # ключевые слова, и словарь оценок.
            if граница - 1 < rv or слово[граница - 1] not in ("а", "я"):
                continue
        return слово[:граница]
    return None


def _шаг_один(слово: str, rv: int) -> str:
    """Деепричастие, иначе возвратность и затем прилагательное/глагол/существительное."""
    основа = (_найти(слово, rv, _ДЕЕПРИЧАСТИЕ_2)
              or _найти(слово, rv, _ДЕЕПРИЧАСТИЕ_1, после_а_я=True))
    if основа is not None:
        return основа

    слово = _найти(слово, rv, _ВОЗВРАТНОЕ) or слово

    # Прилагательное, возможно с примыкающим причастием: «читающего».
    без_прилагательного = _найти(слово, rv, _ПРИЛАГАТЕЛЬНОЕ)
    if без_прилагательного is not None:
        return (_найти(без_прилагательного, rv, _ПРИЧАСТИЕ_2)
                or _найти(без_прилагательного, rv, _ПРИЧАСТИЕ_1, после_а_я=True)
                or без_прилагательного)

    основа = (_найти(слово, rv, _ГЛАГОЛ_2)
              or _найти(слово, rv, _ГЛАГОЛ_1, после_а_я=True))
    if основа is not None:
        return основа
    return _найти(слово, rv, _СУЩЕСТВИТЕЛЬНОЕ) or слово


def stem(слово: str) -> str:
    """Основа слова. Латиница, числа и аббревиатуры возвращаются как есть."""
    исходное = слово or ""
    # Аббревиатуры не склоняются и разбору не подлежат: «ООО» теряло «о» и
    # становилось «оо», после чего сливалось с чем попало в ключевых словах.
    if исходное.isupper() and len(исходное) <= 5 and _ЕСТЬ_КИРИЛЛИЦА.search(
            исходное.lower()):
        return исходное.lower()

    слово = исходное.lower().replace("ё", "е")
    if not слово or not _ЕСТЬ_КИРИЛЛИЦА.search(слово):
        return слово                     # латиница, числа, коды — не трогаем
    if not any(б in ГЛАСНЫЕ for б in слово):
        return слово

    rv, r2 = _границы(слово)
    основа = _шаг_один(слово, rv)

    # Шаг 2: «и» на конце.
    if основа.endswith("и") and len(основа) - 1 >= rv:
        основа = основа[:-1]

    # Шаг 3: производное «ость»/«ост», но только целиком внутри R2 —
    # иначе «мост» и «хвост» лишились бы половины себя.
    for суффикс in _ПРОИЗВОДНОЕ:
        if основа.endswith(суффикс) and len(основа) - len(суффикс) >= r2:
            основа = основа[: len(основа) - len(суффикс)]
            break

    # Шаг 4: удвоенная «н», превосходная степень или мягкий знак.
    if основа.endswith("нн"):
        основа = основа[:-1]
    else:
        без_превосходной = _найти(основа, rv, _ПРЕВОСХОДНАЯ)
        if без_превосходной is not None:
            основа = без_превосходной
            if основа.endswith("нн"):
                основа = основа[:-1]
        elif основа.endswith("ь") and len(основа) - 1 >= rv:
            основа = основа[:-1]
    return основа


def words(текст: str) -> list[str]:
    """Слова текста в нижнем регистре, без знаков препинания.

    Дефис сохраняется: «интернет-магазин» и «из-за» — это одно слово, а
    разбиение по дефису превратило бы их в мусор вроде «за».
    """
    очищено = _НЕ_БУКВА.sub(" ", (текст or "").lower().replace("ё", "е"))
    return [w.strip("-") for w in очищено.split() if w.strip("-")]


def stems(текст: str) -> list[str]:
    """Основы всех слов текста, в порядке появления."""
    return [stem(w) for w in words(текст)]


_КОНЕЦ_ПРЕДЛОЖЕНИЯ = re.compile(r"(?<=[.!?…])\s+")


def sentences(текст: str) -> list[str]:
    """Предложения. Грубо, по знакам конца — расшифровке этого достаточно.

    Точной сегментации мешает то, что знаки расставляет распознавание и
    ошибается: тонкий разбор с сокращениями и инициалами дал бы точность,
    которой в исходных данных всё равно нет.
    """
    куски = [к.strip() for к in _КОНЕЦ_ПРЕДЛОЖЕНИЯ.split(текст or "")]
    return [к for к in куски if к]
