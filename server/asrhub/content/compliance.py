"""Соответствие разговора скрипту: что оператор обязан был сказать.

Проверка по фразам, а не по смыслу: скрипт и сам написан фразами, и от
проверки ждут ровно этого — «поздоровался», «представился», «назвал
компанию», «попрощался». Список настраивается: у каждой службы поддержки он
свой, и зашитый в код был бы бесполезен.

Отдельно считается, кто именно проверяется. В записи разговора говорящих
двое, и требовать приветствия от клиента бессмысленно — поэтому у пункта
есть указание, к какому говорящему он относится.
"""
from __future__ import annotations

from typing import Any

from .stemmer import stem, words

#: Скрипт по умолчанию: то, что спрашивают почти в любой службе поддержки.
#: Значение — список вариантов; достаточно одного совпадения.
ПО_УМОЛЧАНИЮ: list[dict[str, Any]] = [
    {"id": "greeting", "label": "Поздоровался",
     "any": ["здравствуйте", "добрый день", "доброе утро", "добрый вечер",
             "приветствую"],
     "where": "start"},
    {"id": "introduce", "label": "Представился",
     # Голого «это» здесь стояло — и «алло, это опять вы?» засчитывалось
     # как представление оператора. Примета, совпадающая с одним из самых
     # частых слов языка, не примета: она делает пункт выполненным всегда,
     # а разрез — постоянной единицей.
     "any": ["меня зовут", "моё имя", "на связи", "вас беспокоит",
             "вы позвонили"],
     "where": "start"},
    {"id": "company", "label": "Назвал компанию",
     "any": ["компания", "фирма", "организация", "ооо", "ип"],
     "where": "start"},
    {"id": "offer_help", "label": "Предложил помощь",
     "any": ["чем могу помочь", "чем помочь", "слушаю вас", "что случилось",
             "какой у вас вопрос"],
     "where": "start"},
    {"id": "confirm", "label": "Подтвердил понимание",
     # «То есть» убрано по той же причине: в устной речи это связка, а не
     # переспрос, и в расшифровке она встречается почти в каждом разговоре.
     # «Уточню» отсюда переехало в «следующий шаг»: это обещание сходить и
     # посмотреть, а не переспрос. И основа у него общая с «уточнить», из-за
     # чего пункт срабатывал на любой фразе вроде «хотел уточнить по заказу»
     # — то есть на реплике клиента, а не оператора.
     "any": ["правильно понимаю", "верно ли", "если я вас правильно",
             "правильно ли", "верно понял", "верно поняла"],
     "where": "any"},
    {"id": "next_step", "label": "Назвал следующий шаг",
     "any": ["перезвоню", "отправлю", "вышлю", "передам", "сделаем",
             "свяжемся", "решим", "уточню"],
     "where": "any"},
    {"id": "thanks", "label": "Поблагодарил",
     "any": ["спасибо", "благодарю"], "where": "any"},
    {"id": "farewell", "label": "Попрощался",
     "any": ["до свидания", "всего доброго", "всего хорошего", "хорошего дня",
             "до связи"],
     "where": "end"},
]

#: Какую долю разговора считать началом и концом для пунктов «в начале» и
#: «в конце». Пятая часть: приветствие в середине часового разговора — это
#: не приветствие, а случайное совпадение слов.
ДОЛЯ_КРАЯ = 0.2


def _основы(текст: str) -> list[str]:
    return [stem(w) for w in words(текст)]


def _есть(последовательность: list[str], образец: list[str]) -> bool:
    if not образец:
        return False
    for i in range(len(последовательность) - len(образец) + 1):
        if последовательность[i:i + len(образец)] == образец:
            return True
    return False


def _оператор(сегменты: list[dict[str, Any]]) -> str | None:
    """Кто из говорящих оператор: тот, кто заговорил первым.

    None, когда говорящий один или их нет: делить нечего, и проверка идёт
    по всей записи.
    """
    метки = [str(с.get("speaker") or "") for с in сегменты if с.get("speaker")]
    return метки[0] if len(set(метки)) > 1 else None


def check(segments: list[dict[str, Any]], *, script: list[dict[str, Any]] | None = None,
          speaker: str | None = None) -> dict[str, Any]:
    """Проверяет разговор по скрипту.

    `speaker` — чьи реплики проверять. Без него оператор определяется сам:
    берётся тот, кто заговорил первым. Правило грубое, но верное чаще
    любого другого: разговор начинает принимающая сторона, и «здравствуйте,
    компания такая-то» — это первая реплика, а не ответ на неё.

    Жёстко задать метку в настройках нельзя было бы при всём желании:
    разделение по говорящим нумерует их по порядку появления в каждой
    записи отдельно, и «SPEAKER_00» — это разные люди в двух соседних
    разговорах. Поэтому определяем на месте, по самой записи.

    Когда говорящий один или их нет вовсе, проверяем по всему тексту:
    лучше проверить не разделяя, чем не проверить.
    """
    пункты = script if script is not None else ПО_УМОЛЧАНИЮ
    все = list(segments or [])
    кто = speaker if speaker is not None else _оператор(все)
    сегменты = [с for с in все
                if кто is None or str(с.get("speaker") or "") == кто]
    if not сегменты:
        return {"score": None, "checked": 0, "passed": 0, "items": [],
                "speaker": кто}

    край = max(1, int(len(сегменты) * ДОЛЯ_КРАЯ))
    области = {
        "start": сегменты[:край],
        "end": сегменты[-край:],
        "any": сегменты,
    }
    основы = {имя: _основы(" ".join(str(с.get("text") or "") for с in куски))
              for имя, куски in области.items()}

    итог = []
    выполнено = 0
    for пункт in пункты:
        где = str(пункт.get("where") or "any")
        последовательность = основы.get(где, основы["any"])
        нашлось = None
        for вариант in пункт.get("any") or []:
            if _есть(последовательность, _основы(вариант)):
                нашлось = вариант
                break
        if нашлось:
            выполнено += 1
        итог.append({"id": пункт.get("id"), "label": пункт.get("label"),
                     "where": где, "passed": нашлось is not None,
                     "matched": нашлось})
    return {
        "score": round(выполнено / len(пункты), 3) if пункты else None,
        "checked": len(пункты), "passed": выполнено,
        "items": итог, "speaker": кто,
    }
