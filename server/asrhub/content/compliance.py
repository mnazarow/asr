"""Соответствие разговора скрипту: что оператор обязан был сказать.

Проверка по фразам, а не по смыслу: скрипт и сам написан фразами, и от
проверки ждут ровно этого — «поздоровался», «представился», «назвал
компанию», «попрощался». Список настраивается: у каждой службы поддержки он
свой, и зашитый в код был бы бесполезен.

Отдельно считается, кто именно проверяется. В записи разговора говорящих
двое, и требовать приветствия от клиента бессмысленно — поэтому у пункта
есть указание, к какому говорящему он относится.
"""
from __future__ import annotations

from typing import Any

from . import rules
from .lexicons import СЛУЖЕБНЫЕ
from .stemmer import stem

#: Скрипт по умолчанию: то, что спрашивают почти в любой службе поддержки.
#: Значение — список вариантов; достаточно одного совпадения.
ПО_УМОЛЧАНИЮ: list[dict[str, Any]] = [
    {"id": "greeting", "label": "Поздоровался",
     "any": ["здравствуйте", "добрый день", "доброе утро", "добрый вечер",
             "приветствую"],
     "where": "start"},
    {"id": "introduce", "label": "Представился",
     # Голого «это» здесь стояло — и «алло, это опять вы?» засчитывалось
     # как представление оператора. Примета, совпадающая с одним из самых
     # частых слов языка, не примета: она делает пункт выполненным всегда,
     # а разрез — постоянной единицей.
     "any": ["меня зовут", "моё имя", "на связи", "вас беспокоит",
             "вы позвонили"],
     "where": "start"},
    {"id": "company", "label": "Назвал компанию",
     "any": ["компания", "фирма", "организация", "ооо", "ип"],
     "where": "start"},
    {"id": "offer_help", "label": "Предложил помощь",
     "any": ["чем могу помочь", "чем помочь", "слушаю вас", "что случилось",
             "какой у вас вопрос"],
     "where": "start"},
    {"id": "confirm", "label": "Подтвердил понимание",
     # «То есть» убрано по той же причине: в устной речи это связка, а не
     # переспрос, и в расшифровке она встречается почти в каждом разговоре.
     # «Уточню» отсюда переехало в «следующий шаг»: это обещание сходить и
     # посмотреть, а не переспрос. И основа у него общая с «уточнить», из-за
     # чего пункт срабатывал на любой фразе вроде «хотел уточнить по заказу»
     # — то есть на реплике клиента, а не оператора.
     "any": ["правильно понимаю", "верно ли", "если я вас правильно",
             "правильно ли", "верно понял", "верно поняла"],
     "where": "any"},
    {"id": "next_step", "label": "Назвал следующий шаг",
     # «Передам» отсюда убрано: основа у него «перед» — та же, что у
     # предлога, и пункт засчитывался на «перед тем как оформить». Нашла
     # это новая проверка примет, которую редактор скрипта показывает
     # рядом с каждым пунктом; на «передать» и «передайте» основа другая
     # («переда»), их оставляем.
     "any": ["перезвоню", "отправлю", "вышлю", "передадим", "передать",
             "сделаем", "свяжемся", "решим", "уточню", "оформлю"],
     "where": "any"},
    {"id": "thanks", "label": "Поблагодарил",
     "any": ["спасибо", "благодарю"], "where": "any"},
    {"id": "farewell", "label": "Попрощался",
     "any": ["до свидания", "всего доброго", "всего хорошего", "хорошего дня",
             "до связи"],
     "where": "end"},
]

#: С какой доли записей примета считается слишком частой. Половина — не
#: строгая граница, а порог разумного подозрения: слово из каждой второй
#: записи почти наверняка попадёт и в проверяемую часть тоже.
ДОЛЯ_ЧАСТОГО = 0.5

#: Какую долю разговора считать началом и концом для пунктов «в начале» и
#: «в конце». Пятая часть: приветствие в середине часового разговора — это
#: не приветствие, а случайное совпадение слов.
ДОЛЯ_КРАЯ = 0.2


def suspicious(script: list[dict[str, Any]] | None,
               document_frequency: dict[str, int] | None = None,
               corpus_size: int = 0) -> list[dict[str, str]]:
    """Приметы, совпадающие со слишком частыми словами.

    Примета, встречающаяся в большинстве записей, делает пункт выполненным
    почти всегда, а разрез соблюдения скрипта — постоянной единицей. Именно
    на этом попался пункт «Представился», искавший среди прочего голое
    «это»: «алло, это опять вы?» засчитывалось как представление оператора.

    Частота берётся из корпуса самого сервера, а не из общего списка частых
    слов русского языка: «договор» в службе поддержки банка и в отделе
    доставки — слова разной частоты, и подсказка должна опираться на то,
    о чём говорят здесь.
    """
    if not script:
        return []
    найдено: list[dict[str, str]] = []
    for пункт in script:
        подпись = str(пункт.get("label") or пункт.get("id") or "")
        try:
            дерево = _правило(пункт)
        except rules.RuleError:
            continue
        for операнд in rules.operands(дерево):
            # Оборот из нескольких слов проверять незачем: «чем могу помочь»
            # частым не бывает, даже если каждое слово в нём частое.
            if len(операнд.words) != 1:
                continue
            основа = stem(операнд.words[0]) if операнд.exact else операнд.words[0]
            if frequent_marker(основа, document_frequency, corpus_size):
                найдено.append({"word": операнд.text, "label": подпись})
    return найдено


def frequent_marker(основа: str, document_frequency: dict[str, int] | None,
                    corpus_size: int) -> bool:
    """Слишком ли часто слово, чтобы быть приметой.

    Служебное слово — подозрительно само по себе, без всякого корпуса. Это
    и есть главный случай: «это», «так», «то» в словарь частот вообще не
    попадают (их отсеивают на входе), то есть проверка по корпусу молчала
    бы ровно там, где ошибка опаснее всего. Голое «это» в пункте
    «Представился» именно так и прожило до первого снимка экрана.

    Сверяемся со служебными, а не со всеми стоп-словами: там же лежат
    «здравствуйте» и «спасибо», а они — правильные приметы, частые ровно
    потому, что скрипт их и требует.
    """
    if основа in СЛУЖЕБНЫЕ:
        return True
    return (corpus_size >= 20 and document_frequency is not None
            and document_frequency.get(основа, 0) >= corpus_size * ДОЛЯ_ЧАСТОГО)


def _правило(пункт: dict[str, Any]) -> Any:
    """Дерево правила пункта: строка `rule`, а без неё — список примет.

    Пункт скрипта — частный случай категории: «здравствуйте, добрый день»
    — это «здравствуйте ИЛИ добрый день», и проверяет его тот же движок.
    С полем `rule` пункту доступны и остальные операторы: «представился»
    можно записать как «меня зовут ИЛИ на связи НЕ вы позвонили в».
    """
    правило = str(пункт.get("rule") or "").strip()
    if правило:
        return rules.parse(правило)
    return rules.parse_any([str(в) for в in (пункт.get("any") or [])])


def _время(сегмент: dict[str, Any], край: str) -> float:
    ключи = (край, f"{край}_s")
    for к in ключи:
        if сегмент.get(к) is not None:
            try:
                return float(сегмент[к])
            except (TypeError, ValueError):
                continue
    return 0.0


def _окно(пункт: dict[str, Any]) -> float:
    """Окно пункта в секундах; ноль — окно не задано."""
    try:
        return max(0.0, float(пункт.get("within_s") or 0))
    except (TypeError, ValueError):
        return 0.0


def _оператор(сегменты: list[dict[str, Any]]) -> str | None:
    """Кто из говорящих оператор: тот, кто заговорил первым.

    None, когда говорящий один или их нет: делить нечего, и проверка идёт
    по всей записи.
    """
    метки = [str(с.get("speaker") or "") for с in сегменты if с.get("speaker")]
    return метки[0] if len(set(метки)) > 1 else None


def agent(segments: list[dict[str, Any]], speaker: str | None = None) -> str | None:
    """Кто оператор: заданный настройкой или определённый по записи."""
    return speaker if speaker is not None else _оператор(list(segments or []))


def check(segments: list[dict[str, Any]], *, script: list[dict[str, Any]] | None = None,
          speaker: str | None = None) -> dict[str, Any]:
    """Проверяет разговор по скрипту.

    `speaker` — чьи реплики проверять. Без него оператор определяется сам:
    берётся тот, кто заговорил первым. Правило грубое, но верное чаще
    любого другого: разговор начинает принимающая сторона, и «здравствуйте,
    компания такая-то» — это первая реплика, а не ответ на неё.

    Жёстко задать метку в настройках нельзя было бы при всём желании:
    разделение по говорящим нумерует их по порядку появления в каждой
    записи отдельно, и «SPEAKER_00» — это разные люди в двух соседних
    разговорах. Поэтому определяем на месте, по самой записи.

    Когда говорящий один или их нет вовсе, проверяем по всему тексту:
    лучше проверить не разделяя, чем не проверить.
    """
    пункты = script if script is not None else ПО_УМОЛЧАНИЮ
    все = list(segments or [])
    кто = speaker if speaker is not None else _оператор(все)
    сегменты = [с for с in все
                if кто is None or str(с.get("speaker") or "") == кто]
    if not сегменты:
        return {"score": None, "checked": 0, "passed": 0, "items": [],
                "speaker": кто}

    край = max(1, int(len(сегменты) * ДОЛЯ_КРАЯ))
    области = {
        "start": сегменты[:край],
        "end": сегменты[-край:],
        "any": сегменты,
    }
    тексты = {имя: rules.Text.of(куски) for имя, куски in области.items()}
    # Границы записи по времени — для пунктов с окном в секундах.
    первая = min((_время(с, "start") for с in все), default=0.0)
    последняя = max((_время(с, "end") for с in все), default=0.0)

    итог = []
    выполнено = 0
    for пункт in пункты:
        где = str(пункт.get("where") or "any")
        окно = _окно(пункт)
        if окно and где in ("start", "end"):
            # Окно в секундах, а не пятая часть реплик. «Разговор
            # записывается» обязано прозвучать в первые тридцать секунд —
            # так это формулируют NICE и Verint, и так спрашивают
            # проверяющие. Пятая часть реплик в часовом разговоре — это
            # двенадцать минут, и приветствие на десятой засчитывалось.
            куски = [с for с in сегменты
                     if (_время(с, "start") - первая <= окно if где == "start"
                         else последняя - _время(с, "end") <= окно)]
            текст = rules.Text.of(куски)
        else:
            текст = тексты.get(где, тексты["any"])
        нашлось = None
        ошибка = None
        try:
            найдено = rules.evaluate(_правило(пункт), текст)
        except rules.RuleError as exc:
            # Пункт с негодным правилом не выполнен и говорит почему:
            # молча пропустить его значило бы завысить соблюдение скрипта.
            найдено = rules.Result(False, [])
            ошибка = exc.message
        if найдено.matched:
            выполнено += 1
            # Что именно совпало: первая по порядку примета — как раньше, когда
            # варианты перебирались по списку. Для правила с И это одна из
            # обязательных частей, для ИЛИ — сработавшая.
            нашлось = min(найдено.hits, key=lambda h: h.start).text if найдено.hits else "—"
        итог.append({"id": пункт.get("id"), "label": пункт.get("label"),
                     "where": где, "within_s": окно or None,
                     "passed": найдено.matched, "matched": нашлось,
                     **({"error": ошибка} if ошибка else {})})
    return {
        "score": round(выполнено / len(пункты), 3) if пункты else None,
        "checked": len(пункты), "passed": выполнено,
        "items": итог, "speaker": кто,
    }
