"""Что называли в разговоре: суммы, даты, сроки, телефоны, почта, номера.

Всё на выражениях, без обучаемых моделей — и это не компромисс, а верный
выбор для задачи. Сумма, дата и номер телефона имеют строгую форму, и
правило узнаёт их точнее любой модели, ничего не требуя от установки.
Имена и названия организаций правилами не берутся, и их здесь нет: лучше
не отдавать разрез вовсе, чем отдавать наполовину выдуманный.

Ценность в том, что по этим полям можно искать: «покажи звонки, где
называли сумму больше миллиона», «где обещали до пятницы», «где оставили
почту».
"""
from __future__ import annotations

import re
from typing import Any

#: Числа словами — распознавание отдаёт суммы и словами тоже.
_ЧИСЛА_СЛОВАМИ = {
    "ноль": 0, "один": 1, "одна": 1, "два": 2, "две": 2, "три": 3, "четыре": 4,
    "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14,
    "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19, "двадцать": 20, "тридцать": 30, "сорок": 40,
    "пятьдесят": 50, "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80,
    "девяносто": 90, "сто": 100, "двести": 200, "триста": 300, "четыреста": 400,
    "пятьсот": 500, "шестьсот": 600, "семьсот": 700, "восемьсот": 800,
    "девятьсот": 900,
}
_МНОЖИТЕЛИ = {"тысяч": 1_000, "тысячи": 1_000, "тысяча": 1_000, "тыс": 1_000,
              "миллион": 1_000_000, "миллиона": 1_000_000, "миллионов": 1_000_000,
              "млн": 1_000_000, "миллиард": 1_000_000_000, "млрд": 1_000_000_000}

_ВАЛЮТЫ = {"руб": "RUB", "рубль": "RUB", "рубля": "RUB", "рублей": "RUB",
           "р": "RUB", "₽": "RUB", "доллар": "USD", "долларов": "USD",
           "$": "USD", "евро": "EUR", "€": "EUR", "тенге": "KZT",
           "гривен": "UAH", "юаней": "CNY"}

_ДЕНЬГИ = re.compile(
    r"(?P<число>\d[\d\s  .,]{0,15}?)\s*"
    r"(?P<множ>тыс(?:\.|яч[аи]?)?|млн|миллион\w*|млрд|миллиард\w*)?\s*"
    r"(?P<валюта>руб(?:\.|л[яейи]\w*)?|₽|\$|€|долл\w*|евро|тенге|гривен\w*|юан\w*)",
    re.IGNORECASE)

_ПРОЦЕНТЫ = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:%|процент\w*)", re.IGNORECASE)

_ТЕЛЕФОН = re.compile(
    r"(?<!\d)(?:\+7|8|7)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)")

_ПОЧТА = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")

#: Числовая дата. Разделитель «-» здесь опасен: кусок телефона «123-45-67»
#: выглядит как «45-67» и уезжал в даты. Поэтому дефис принимается только
#: там, где рядом нет ещё цифр, а день и месяц проверяются на правдоподобие
#: уже после разбора.
_ДАТА_ЧИСЛОМ = re.compile(
    r"(?<![\d\-.])(\d{1,2})([.\-/])(\d{1,2})(?:\2(\d{2,4}))?(?![\d\-])")
_ДАТА_СЛОВОМ = re.compile(
    r"\b(\d{1,2})\s+(январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|"
    r"октябр|ноябр|декабр)\w*", re.IGNORECASE)

#: Единицы времени — то, что может стоять после «через» и «в течение».
#: Без этого ограничения «через» ловило «через курьера», «через приложение»,
#: «через нашего менеджера»: предлог «через» в русском чаще не про время
#: вовсе, и каждое такое совпадение приписывало обещанию срок, которого не
#: называли. Разрез «обещания без названного срока» из-за этого молчал
#: ровно там, где должен был сработать.
_ЕДИНИЦЫ = (r"(?:\d+\s+)?(?:минут\w*|час\w*|сутк\w*|день|дня|дней|"
            r"недел\w*|месяц\w*|год\w*|лет|полчаса|"
            r"пару\s+\w+|неделю|месяц|квартал\w*)")

_ОТНОСИТЕЛЬНЫЕ_СРОКИ = re.compile(
    r"\b(сегодня|завтра|послезавтра|на\s+днях|до\s+конца\s+(?:дня|недели|месяца)|"
    rf"в\s+течение\s+{_ЕДИНИЦЫ}|через\s+{_ЕДИНИЦЫ}|на\s+следующей\s+неделе|"
    r"в\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье))\b",
    re.IGNORECASE)

#: Номер договора, счёта, заявки. Именно с указанием, чего именно: голое
#: число в разговоре — это что угодно, от суммы до номера дома.
_НОМЕР = re.compile(
    r"\b(договор\w*|счет\w*|счёт\w*|заявк\w*|заказ\w*|накладн\w*|"
    r"обращени\w*|тикет\w*|номер)\s*(?:№|N|номер)?\s*"
    r"([A-Za-zА-Яа-я]{0,3}[-/]?\d{2,10}(?:[-/]\d{1,6})?)", re.IGNORECASE)


def _к_числу(текст: str) -> float | None:
    очищено = re.sub(r"[\s  ]", "", текст).replace(",", ".").rstrip(".")
    try:
        return float(очищено)
    except ValueError:
        return None


def money(текст: str) -> list[dict[str, Any]]:
    """Денежные суммы с валютой и приведённым значением."""
    найдено = []
    for м in _ДЕНЬГИ.finditer(текст or ""):
        число = _к_числу(м.group("число") or "")
        if число is None:
            continue
        множитель = 1
        if м.group("множ"):
            ключ = м.group("множ").lower().rstrip(".")
            множитель = next((v for k, v in _МНОЖИТЕЛИ.items()
                              if ключ.startswith(k[:4])), 1)
        валюта = "RUB"
        сырая = (м.group("валюта") or "").lower().rstrip(".")
        for ключ, код in _ВАЛЮТЫ.items():
            if сырая.startswith(ключ):
                валюта = код
                break
        найдено.append({"text": м.group(0).strip(),
                        "amount": round(число * множитель, 2),
                        "currency": валюта})
    return найдено


def _dates(текст: str) -> list[str]:
    """Даты, отсеянные по правдоподобию.

    Без отсева в даты уезжали куски телефонов и номеров: «123-45-67» даёт
    «45-67», а сорок пятого месяца не бывает. Проверка простая — день от 1
    до 31, месяц от 1 до 12, — но именно она отличает дату от обрывка
    номера.
    """
    найдено: set[str] = set()
    for м in _ДАТА_ЧИСЛОМ.finditer(текст or ""):
        день, месяц = int(м.group(1)), int(м.group(3))
        if not (1 <= день <= 31 and 1 <= месяц <= 12):
            continue
        # Точка между однозначными числами — почти всегда не дата, а дробь:
        # «счёт на 1.5 миллиона» давало «1.5» → первое мая, «скидка 2.5
        # процента» → второе мая. В карточке записи эти числа стояли в
        # «названных датах», а в разборе обещаний становились сроком, и
        # обещаний без срока не оставалось вовсе.
        #
        # Дату отличаем по написанию: либо день и месяц записаны двумя
        # знаками (01.05), либо назван год (1.5.2026). В расшифровке речи
        # это не потеря: сказанную вслух дату распознавание пишет словами
        # («пятого июня»), а их ловит соседнее выражение.
        двузначные = len(м.group(1)) == 2 and len(м.group(3)) == 2
        if м.group(2) == "." and not (двузначные or м.group(4)):
            continue
        найдено.add(м.group(0).strip())
    for м in _ДАТА_СЛОВОМ.finditer(текст or ""):
        if 1 <= int(м.group(1)) <= 31:
            найдено.add(м.group(0).strip())
    return sorted(найдено)


def _простой(выражение: re.Pattern[str], текст: str) -> list[str]:
    return [м.group(0).strip() for м in выражение.finditer(текст or "")]


def extract(текст: str) -> dict[str, Any]:
    """Все сущности одного текста."""
    суммы = money(текст)
    номера = [{"kind": м.group(1).lower(), "number": м.group(2)}
              for м in _НОМЕР.finditer(текст or "")]
    return {
        "money": суммы[:50],
        "money_max": max((с["amount"] for с in суммы), default=None),
        "percents": [float(з.replace(",", ".")) for з in
                     (м.group(1) for м in _ПРОЦЕНТЫ.finditer(текст or ""))][:20],
        "phones": sorted(set(_простой(_ТЕЛЕФОН, текст)))[:20],
        "emails": sorted(set(_простой(_ПОЧТА, текст)))[:20],
        "dates": _dates(текст)[:20],
        "deadlines": sorted({м.group(0).strip().lower()
                             for м in _ОТНОСИТЕЛЬНЫЕ_СРОКИ.finditer(текст or "")})[:20],
        "numbers": номера[:20],
    }
