"""Тональность реплики и разговора по словарю.

Как считается. Слово из словаря даёт свой вес; стоящий перед ним усилитель
умножает («очень плохо» весит больше, чем «плохо»), а отрицание в пределах
трёх слов меняет знак («не понравилось»). Оценка реплики — средний вес
сработавших слов, плавно сжатый к отрезку от −1 до +1; делитель — число
оценочных слов, а не всех, иначе длинная спокойная реплика с одним резким
словом выглядела бы нейтральной ровно потому, что она длинная.

Чего этот способ не умеет — и об этом сказано прямо в главе документации.
Он не понимает иронию («ну спасибо, удружили»), не различает «проблема
решена» и «проблема есть», не знает предметной области. Поэтому в
интерфейсе рядом с оценкой всегда стоит сама фраза: число без фразы здесь
было бы враньём с точностью до знака, а с фразой человек за секунду видит,
верно ли машина поняла.
"""
from __future__ import annotations

import math
from collections.abc import Iterable
from dataclasses import dataclass, field
from typing import Any

from .lexicons import (
    ДЛИНА_ФРАЗЫ,
    НЕ_ПЕРЕВОРАЧИВАЮТСЯ,
    ОКНО_ОТРИЦАНИЯ,
    ОТРИЦАНИЯ,
    ОЦЕНКИ,
    САМОСТОЯТЕЛЬНЫЕ_ОТРИЦАНИЯ,
    УСИЛИТЕЛИ,
    ФРАЗЫ,
)
from .stemmer import sentences, stem, слова_по_мыслям

#: Глаголы, которые забирают отрицание целиком: «не переживайте», «не
#: волнуйтесь» — это утешение, и следующее за ним «всё хорошо» отрицанием уже
#: не накрыто, даже когда распознавание не поставило запятую.
УТЕШЕНИЯ: frozenset[str] = frozenset(stem(с) for с in (
    "переживайте", "переживай", "волнуйтесь", "волнуйся", "беспокойтесь",
    "беспокойся", "расстраивайтесь", "расстраивайся", "стесняйтесь", "стесняйся",
))

#: Граница, за которой реплика считается окрашенной. Ниже — нейтральная.
#: Взята не с потолка: одно слово веса 1 в реплике из одного оценочного
#: слова даёт 0.46, и порог 0.15 пропускает даже слабую окраску, оставляя
#: нулём только реплики совсем без оценочных слов.
ПОРОГ = 0.15


@dataclass(slots=True)
class Оценка:
    """Итог разбора одного куска текста."""

    score: float = 0.0                      # от −1 до +1
    positive: int = 0                       # сколько слов сработало в плюс
    negative: int = 0
    words: list[dict[str, Any]] = field(default_factory=list)
    #: Сумма весов и число сработавших слов — чтобы складывать оценки
    #: предложений по весам, а не по уже приведённым числам.
    _сумма: float = 0.0
    _сработало: int = 0

    @property
    def label(self) -> str:
        if self.score > ПОРОГ:
            return "положительная"
        if self.score < -ПОРОГ:
            return "отрицательная"
        return "нейтральная"

    def to_dict(self) -> dict[str, Any]:
        return {"score": round(self.score, 3), "label": self.label,
                "positive": self.positive, "negative": self.negative,
                "words": self.words}


def score_text(текст: str | Iterable[str]) -> Оценка:
    """Тональность куска текста — или нескольких кусков разом.

    Разбирается по предложениям, а результаты складываются. Разбор целиком
    был неверен из-за окна отрицания: оно смотрит на три слова назад и не
    видело точки. «Никаких претензий. Спасибо, помогли!» получало −0.23
    «отрицательная» — «никаких» переворачивало и «спасибо», и «помогли»
    через границу предложения.

    Список кусков — это реплики разговора. Оценка записи раньше считалась по
    склеенному тексту, и без пунктуации (движок без знаков, пунктуация не
    поставлена) весь разговор становился одним предложением: «нет» из
    реплики клиента переворачивало похвалу в следующей реплике оператора.
    Граница реплики — граница мысли всегда, поставлены знаки или нет.
    """
    куски = [текст] if isinstance(текст, str) or текст is None else list(текст)
    предложения = [п for кусок in куски for п in sentences(str(кусок or ""))]
    if len(предложения) == 1:
        return _score_one(предложения[0])
    if len(предложения) > 1:
        общая = Оценка()
        суммарно = 0.0
        всего = 0
        for предложение in предложения:
            часть = _score_one(предложение)
            if not часть.words:
                continue
            # Складываем не оценки, а веса: среднее от средних завысило бы
            # вклад короткого предложения с одним резким словом.
            суммарно += часть._сумма
            всего += часть._сработало
            общая.positive += часть.positive
            общая.negative += часть.negative
            общая.words.extend(часть.words[:20 - len(общая.words)])
        if всего:
            общая.score = math.tanh(суммарно / всего / 2.0)
        общая._сумма, общая._сработало = суммарно, всего
        return общая
    return Оценка()


def _под_отрицанием(основы: list[str], мысли: list[int]) -> list[bool]:
    """Какие слова накрыты отрицанием.

    Отрицание действует на следующие `ОКНО_ОТРИЦАНИЯ` слов, но не дальше
    конца своей мысли: запятая после «нет» или «не переживайте» означает,
    что дальше уже другое. Самостоятельное «нет» не переворачивает
    благодарность и без запятой — «нет спасибо» всегда «нет, спасибо», — а
    утешение («не волнуйтесь») забирает отрицание себе целиком.
    """
    под = [False] * len(основы)
    for j, о in enumerate(основы):
        if о not in ОТРИЦАНИЯ:
            continue
        for i in range(j + 1, min(len(основы), j + 1 + ОКНО_ОТРИЦАНИЯ)):
            if мысли[i] != мысли[j]:
                break
            if о in САМОСТОЯТЕЛЬНЫЕ_ОТРИЦАНИЯ and основы[i] in НЕ_ПЕРЕВОРАЧИВАЮТСЯ:
                break
            под[i] = True
            if основы[i] in УТЕШЕНИЯ:
                break
    return под


def _score_one(текст: str) -> Оценка:
    """Тональность одного предложения."""
    список, мысли = слова_по_мыслям(текст)
    if not список:
        return Оценка()

    основы = [stem(w) for w in список]
    под_отрицанием = _под_отрицанием(основы, мысли)
    итог = Оценка()
    сумма = 0.0
    сработало = 0

    # Сначала обороты, от длинных к коротким. Слова, вошедшие в оборот,
    # помечаются занятыми и вторым проходом не считаются: иначе «не
    # работает» дало бы и вес оборота, и вес слова «работает» отдельно.
    занято = [False] * len(основы)
    for i in range(len(основы)):
        if занято[i]:
            continue
        for длина in range(min(ДЛИНА_ФРАЗЫ, len(основы) - i), 0, -1):
            вес = ФРАЗЫ.get(tuple(основы[i:i + длина]))
            if вес is None:
                continue
            сумма += вес
            сработало += 1
            if вес > 0:
                итог.positive += 1
            else:
                итог.negative += 1
            if len(итог.words) < 20:
                итог.words.append({"word": " ".join(список[i:i + длина]),
                                   "weight": round(вес, 2), "negated": False})
            for j in range(i, i + длина):
                занято[j] = True
            break

    for i, основа in enumerate(основы):
        if занято[i]:
            continue
        вес = ОЦЕНКИ.get(основа)
        if вес is None:
            continue

        # Усилитель — только непосредственно перед словом или через одно:
        # «очень сильно недоволен» усиливает, а «очень» из соседнего
        # предложения — уже нет.
        множитель = 1.0
        for назад in (1, 2):
            if i - назад >= 0:
                у = УСИЛИТЕЛИ.get(основы[i - назад])
                if у is not None:
                    множитель *= у
                    break

        # Отрицание в окне переворачивает знак, но не полностью: «не
        # плохо» — это не «хорошо», а «сносно», и весить оно должно меньше.
        отрицание = под_отрицанием[i]
        значение = вес * множитель * (-0.7 if отрицание else 1.0)

        сумма += значение
        сработало += 1
        if значение > 0:
            итог.positive += 1
        else:
            итог.negative += 1
        if len(итог.words) < 20:
            итог.words.append({"word": список[i], "weight": round(значение, 2),
                               "negated": отрицание})

    итог._сумма, итог._сработало = сумма, сработало
    if сработало:
        # Делим на число сработавших слов, а не на длину текста: иначе
        # оценка реплики зависела бы от её длины сильнее, чем от смысла.
        средний = сумма / сработало
        # Приводим к отрезку плавно, а не обрезкой. Обрезка стояла здесь
        # первой и оказалась хуже, чем выглядела: веса словаря доходят до
        # ±2, а деление на 2 с подрезкой означало, что всё от −2 и ниже —
        # это ровно −1. На корпусе в две тысячи разговоров в границы
        # упиралась почти половина записей, и «самые тяжёлые разговоры»
        # получались списком из шестисот штук с одинаковой оценкой −1.00,
        # то есть выбранных как попало. Усилитель при этом не значил
        # ничего: «плохо» и «очень плохо» давали одно и то же число.
        #
        # Гиперболический тангенс монотонен и границ не достигает: порядок
        # сохраняется на любых весах, крайние значения различимы между
        # собой, а калибровка почти не сдвинулась — одно слово веса 1
        # давало 0.5, теперь даёт 0.46.
        итог.score = math.tanh(средний / 2.0)
    return итог


def score_segments(segments: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Тональность каждой реплики — с её временем и говорящим.

    Именно это, а не одно число на разговор, отвечает на вопрос «что там
    случилось»: разговор, начавшийся ссорой и кончившийся благодарностью,
    и обратный ему дают одну и ту же среднюю оценку.
    """
    out = []
    for i, сегмент in enumerate(segments or []):
        оценка = score_text(str(сегмент.get("text") or ""))
        out.append({
            "idx": i,
            "start_s": float(сегмент.get("start") or сегмент.get("start_s") or 0.0),
            "end_s": float(сегмент.get("end") or сегмент.get("end_s") or 0.0),
            "speaker": сегмент.get("speaker"),
            "score": round(оценка.score, 3),
            "label": оценка.label,
            "words": оценка.words,
        })
    return out


def trajectory(оценки: list[dict[str, Any]], корзин: int = 12) -> list[float | None]:
    """Ход тональности по разговору, свёрнутый до нескольких точек.

    Нужен, чтобы увидеть форму: «упало и не поднялось», «выправилось к
    концу», «ровно». По списку реплик это не видно — их сотни.
    """
    если_нет: list[float | None] = [None] * корзин
    if not оценки:
        return если_нет
    конец = max(float(о["end_s"]) for о in оценки) or 1.0
    корзины: list[list[float]] = [[] for _ in range(корзин)]
    for о in оценки:
        доля = min(0.999999, max(0.0, float(о["start_s"]) / конец))
        корзины[int(доля * корзин)].append(float(о["score"]))
    return [round(sum(k) / len(k), 3) if k else None for k in корзины]


def turn(оценки: list[dict[str, Any]]) -> dict[str, Any]:
    """Чем разговор начался и чем кончился.

    Разворот важнее среднего: «пришёл злой — ушёл довольный» это удачно
    отработанное обращение, а обратное — то, ради чего запись и слушают.
    Берём по трети реплик с каждого края, но не меньше одной.
    """
    если_нет = {"start": None, "end": None, "shift": None, "shape": "нет данных"}
    осмысленные = [о for о in оценки if о.get("score") is not None]
    if len(осмысленные) < 2:
        return если_нет
    треть = max(1, len(осмысленные) // 3)
    начало = sum(о["score"] for о in осмысленные[:треть]) / треть
    конец = sum(о["score"] for о in осмысленные[-треть:]) / треть
    сдвиг = конец - начало

    if сдвиг > 0.25:
        форма = "выправился"
    elif сдвиг < -0.25:
        форма = "испортился"
    elif начало < -ПОРОГ and конец < -ПОРОГ:
        форма = "тяжёлый с начала до конца"
    elif начало > ПОРОГ and конец > ПОРОГ:
        форма = "ровный доброжелательный"
    else:
        форма = "ровный"
    return {"start": round(начало, 3), "end": round(конец, 3),
            "shift": round(сдвиг, 3), "shape": форма}
