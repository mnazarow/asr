def настроение(оценки: list[dict[str, Any]], тон: dict[str, Any],
               оператор: str | None, клиент: str | None) -> dict[str, Any]:
    """Знак эмоции по сторонам разговора и куда он двигался.

    Средняя по разговору смешивает раздражённого клиента с ровным
    оператором и получает «нейтрально» — то есть теряет ровно то, что
    хотели узнать. Поэтому настроение считается по сторонам, а итог
    разговора берётся со стороны клиента: оценивают работу по нему.
    """
    по_сторонам: dict[str, list[float]] = {}
    for о in оценки:
        по_сторонам.setdefault(str(о.get("speaker") or "—"), []).append(float(о["score"]))

    def среднее(кто: str | None) -> float | None:
        значения = по_сторонам.get(str(кто)) if кто else None
        return round(mean(значения), 3) if значения else None

    начало_конец: dict[str, float | None] = {"start": None, "end": None}
    свои = по_сторонам.get(str(клиент)) if клиент else [
        float(о["score"]) for о in оценки]
    if свои and len(свои) >= 3:
        треть = max(1, len(свои) // 3)
        начало_конец["start"] = round(mean(свои[:треть]), 3)
        начало_конец["end"] = round(mean(свои[-треть:]), 3)

    сдвиг = None
    if начало_конец["start"] is not None and начало_конец["end"] is not None:
        # Разность двух средних из −1…+1 живёт в −2…+2, а колонка базы
        # объявлена как −1…+1. Приводим к объявленному: «разошлись лучше,
        # чем начали» — это направление и величина, а не вторая шкала.
        сдвиг = round((начало_конец["end"] - начало_конец["start"]) / 2, 3)
    итоговая = среднее(клиент) if клиент else тон.get("score")
    return {
        "score": итоговая,
        "label": _метка_настроения(итоговая),
        "agent": среднее(оператор),
        "customer": среднее(клиент),
        "start": начало_конец["start"], "end": начало_конец["end"],
        "shift": сдвиг,
        # «Разошлись лучше, чем начали» — самостоятельный факт: разговор с
        # тяжёлым началом и тёплым концом сделан хорошо, а по средней он
        # неотличим от ровно-никакого.
        "recovered": bool(сдвиг is not None and сдвиг > 0.15),
        "worsened": bool(сдвиг is not None and сдвиг < -0.15),
    }


def _метка_настроения(значение: float | None) -> str | None:
    if значение is None:
        return None
    if значение <= -0.5:
        return "подавленное"
    if значение <= -0.15:
        return "напряжённое"
    if значение < 0.15:
        return "ровное"
    if значение < 0.5:
        return "доброжелательное"
    return "приподнятое"


def интенсивность(оценки: list[dict[str, Any]]) -> int | None:
    """Сила эмоции 1–5 — отдельно от её знака.

    Пусто, когда эмоции в разговоре нет вовсе: ноль по этой шкале означал
    бы «измерили и не нашли», а разница между «ровный деловой разговор» и
    «эмоций не измеряли» существенна.
    """
    силы = [abs(float(о["score"])) for о in оценки if abs(float(о["score"])) > 0.05]
    if not силы:
        return None
    пик = max(силы)
    средняя = mean(силы)
    # Две трети веса — пику: вспышка в одном месте важнее ровного фона,
    # именно её идут слушать.
    итог = 0.65 * пик + 0.35 * средняя
    return max(1, min(5, int(round(1 + итог * 4))))


def стресс(*, сегменты: list[dict[str, Any]], речь: dict[str, Any],
           оценки: list[dict[str, Any]], клиент: str | None,
           оператор: str | None, фрустрация: int, повторное: int,
           мат: int | None) -> dict[str, Any]:
    """Напряжение в разговоре: 0 — спокойно, 100 — на пределе.

    Считается из признаков, каждый из которых сам по себе не приговор, а
    вместе они складываются в то, что слышно ухом: резкие реплики,
    перебивания, наложение речи, вспышки раздражения, повторное обращение,
    брань. Отдельно — чей это стресс: у клиента и у оператора он значит
    разное и чинится по-разному.
    """
    минут = max(1.0, float(речь.get("duration_s") or 0) / 60.0)
    отрицательные = [о for о in оценки if float(о["score"]) < -0.2]
    доля_резких = len(отрицательные) / max(1, len(оценки))
    перебиваний = float(речь.get("interruptions") or 0) / минут
    наложение = float(речь.get("overlap_share") or 0)
    восклицаний = sum(str(с.get("text") or "").count("!") for с in сегменты) / минут

    признаки: list[dict[str, Any]] = []

    def добавить(имя: str, вес: float, доля: float, пояснение: str) -> float:
        if доля > 0.02:
            признаки.append({"name": имя, "share": round(доля, 3),
                             "weight": вес, "hint": пояснение})
        return вес * доля

    итог = 0.0
    итог += добавить("резкие реплики", 0.26, _шкала(доля_резких, 0.05, 0.45),
                     "доля реплик с явно отрицательной окраской")
    итог += добавить("перебивания", 0.18, _шкала(перебиваний, 0.5, 5.0),
                     "перебиваний в минуту")
    итог += добавить("речь поверх речи", 0.12, _шкала(наложение, 0.02, 0.15),
                     "доля времени, когда говорят оба")
    # На минуту, как перебивания и восклицания: сырой счётчик делал
    # получасовой разговор вчетверо «напряжённее» пятиминутного при той же
    # плотности вспышек, и сотрудник на длинных разговорах выглядел хуже
    # просто потому, что они длинные.
    итог += добавить("раздражение", 0.20, _шкала(фрустрация / минут, 0.1, 1.2),
                     "реплик с признаками раздражения в минуту")
    итог += добавить("повторное обращение", 0.12, _шкала(повторное, 0.5, 3.0),
                     "клиент говорит, что обращается не впервые")
    итог += добавить("восклицания", 0.06, _шкала(восклицаний, 0.5, 6.0),
                     "восклицательных знаков в минуту")
    if мат:
        итог += добавить("брань", 0.06, _шкала(мат / минут, 0.1, 0.8),
                         "нецензурных реплик в минуту")

    def сторона(кто: str | None) -> int | None:
        if not кто:
            return None
        свои = [о for о in оценки if str(о.get("speaker") or "") == кто]
        if not свои:
            return None
        резких = sum(1 for о in свои if float(о["score"]) < -0.2) / len(свои)
        return _процент(_шкала(резких, 0.05, 0.5))

    # Разговор из двух слов не «спокойный», а неизмеренный: ноль здесь
    # читался бы как «проверили и тихо», и такие записи тянули бы вниз
    # средний уровень напряжения по сотруднику.
    if len(оценки) < МИН_РЕПЛИК:
        return {"index": None, "level": None, "customer": None, "agent": None,
                "signals": []}
    значение = _процент(итог)
    return {
        "index": значение,
        "level": ("низкий" if значение < 25 else
                  "заметный" if значение < 55 else "высокий"),
        "customer": сторона(клиент), "agent": сторона(оператор),
        "signals": sorted(признаки, key=lambda з: -(з["weight"] * з["share"]))[:6],
    }


def усилие(сегменты: list[dict[str, Any]], клиент: str | None,
           повторное: int) -> dict[str, Any]:
    """Усилие клиента: сколько ему стоило добиться ответа. −5…+5.

    Шкала знаковая, как у Qualtrics: минус — клиенту пришлось пробиваться,
    плюс — всё решилось с первого захода. Значение важнее тональности:
    клиент может остаться вежливым и больше не вернуться.
    """
    свои = _реплики(сегменты, клиент)
    слова_клиента = words(_текст(свои))
    маркеры = _фразы(слова_клиента, _без_ё(УСИЛИЕ_ФРАЗЫ))
    лёгкость = _фразы(words(_текст(сегменты)), _без_ё(РЕШЕНО_ФРАЗЫ))
    # `повторное` считается по тем же словам, что и половина маркеров
    # усилия: «я звоню третий раз» попадает и туда, и сюда, и одна реплика
    # клиента утаскивала балл на две ступени вместо одной. Поэтому повторное
    # добавляет только то, чего маркеры не увидели.
    тяжесть = len(маркеры) + max(0, повторное - len(маркеры))
    балл = len(лёгкость) * 1.2 - тяжесть * 1.6
    return {
        "score": round(max(-5.0, min(5.0, балл)), 1),
        "markers": маркеры[:6], "resolved_markers": лёгкость[:4],
        "level": ("высокое" if тяжесть >= 3 else
                  "заметное" if тяжесть >= 1 else "низкое"),
    }


def усталость(сегменты: list[dict[str, Any]], оператор: str | None) -> dict[str, Any]:
    """Усталость оператора по ходу разговора: 0 — не видно, 100 — очевидна.

    Сравнивается первая треть его реплик с последней: падает ли темп,
    растёт ли доля пауз и паразитов, короче ли становятся ответы. Это
    измерение внутри одного разговора; усталость за смену складывается из
    таких измерений в разрезе по сотруднику.
    """
    свои = _речь_оператора(сегменты, оператор) or []
    пусто = {"index": None, "level": None, "signals": [],
             "wpm_start": None, "wpm_end": None}
    if len(свои) < 6:
        # На пяти репликах «первая треть» — это одна реплика, и разницу с
        # такой опоры считать нельзя: получится шум, названный усталостью.
        return пусто
    треть = max(2, len(свои) // 3)
    начало, конец = свои[:треть], свои[-треть:]

    def темпы(часть: list[dict[str, Any]]) -> float | None:
        значения = [т for т in (_темп(с) for с in часть) if т]
        return mean(значения) if значения else None

    def паразитов(часть: list[dict[str, Any]]) -> float:
        слова = words(_текст(часть))
        if not слова:
            return 0.0
        сколько = sum(1 for с in слова if с in lexicons.ПАРАЗИТЫ
                      or с in lexicons.ЗВУКИ_ПАУЗЫ)
        return сколько / len(слова)

    def длина(часть: list[dict[str, Any]]) -> float:
        значения = [len(words(str(с.get("text") or ""))) for с in часть]
        return mean(значения) if значения else 0.0

    темп_начало, темп_конец = темпы(начало), темпы(конец)
    признаки: list[dict[str, Any]] = []
    итог = 0.0
    if темп_начало and темп_конец:
        падение = (темп_начало - темп_конец) / темп_начало
        if падение > УСТАЛОСТЬ_ПОРОГ / 2:
            признаки.append({"name": "темп речи падает",
                             "from": round(темп_начало), "to": round(темп_конец)})
        итог += 0.4 * _шкала(падение, 0.05, 0.35)
    рост = паразитов(конец) - паразитов(начало)
    if рост > 0.01:
        признаки.append({"name": "больше слов-паразитов к концу",
                         "from": round(паразитов(начало), 3),
                         "to": round(паразитов(конец), 3)})
    итог += 0.3 * _шкала(рост, 0.005, 0.06)
    укорочение = (длина(начало) - длина(конец)) / максимум(длина(начало))
    if укорочение > 0.2:
        признаки.append({"name": "ответы становятся короче",
                         "from": round(длина(начало), 1), "to": round(длина(конец), 1)})
    итог += 0.3 * _шкала(укорочение, 0.1, 0.6)

    значение = _процент(итог)
    return {
        "index": значение,
        "level": ("не видно" if значение < 25 else
                  "заметна" if значение < 55 else "выраженная"),
        "signals": признаки,
        "wpm_start": round(темп_начало) if темп_начало else None,
        "wpm_end": round(темп_конец) if темп_конец else None,
    }


def максимум(значение: float) -> float:
    """Знаменатель, который не бывает нулём."""
    return значение if значение else 1.0


def понятность(сегменты: list[dict[str, Any]], речь: dict[str, Any],
               оператор: str | None) -> dict[str, Any]:
    """Насколько речь оператора легко слушать: 0 — тяжело, 100 — легко.

    Слушатель не может перечитать фразу, поэтому к обычным признакам
    читаемости — длине фразы и доле длинных слов — добавляются темп и
    слова-паразиты. Считается по речи оператора: понятность клиента — не
    его работа.
    """
    свои = _речь_оператора(сегменты, оператор)
    пусто = {"index": None, "grade": None, "wpm": None, "sentence_words": None,
             "long_sentences": 0, "hard_words": 0, "filler_rate": None, "signals": []}
    if свои is None:
        return пусто
    текст = _текст(свои)
    слова_ = words(текст)
    if len(слова_) < 20:
        return пусто

    фразы = [ф for ф in re.split(r"[.!?…]+", текст) if ф.strip()]
    длины = [len(words(ф)) for ф in фразы if words(ф)]
    средняя_фраза = mean(длины) if длины else len(слова_)
    длинных = sum(1 for д in длины if д > ФРАЗА_ДЛИННАЯ) / max(1, len(длины))
    сложных = sum(1 for с in слова_ if _слогов(с) >= СЛОЖНОЕ_СЛОВО_СЛОГОВ) / len(слова_)
    паразитов = sum(1 for с in слова_ if с in lexicons.ПАРАЗИТЫ
                    or с in lexicons.ЗВУКИ_ПАУЗЫ)
    доля_паразитов = паразитов / len(слова_)
    темпы = [т for т in (_темп(с) for с in свои) if т]
    темп = mean(темпы) if темпы else (речь.get("wpm") or None)

    # Темп штрафуется в обе стороны: вязкая речь так же тяжела, как
    # скороговорка, и односторонняя шкала прощала бы одну из этих бед.
    штраф_темпа = 0.0
    if темп:
        if темп < ТЕМП_НИЗ:
            штраф_темпа = _шкала(ТЕМП_НИЗ - темп, 5, 45)
        elif темп > ТЕМП_ВЕРХ:
            штраф_темпа = _шкала(темп - ТЕМП_ВЕРХ, 5, ТЕМП_ПРЕДЕЛ - ТЕМП_ВЕРХ)

    штраф = (0.28 * _шкала(средняя_фраза, 9, 26)
             + 0.22 * _шкала(длинных, 0.05, 0.5)
             + 0.20 * _шкала(сложных, 0.06, 0.30)
             + 0.16 * _шкала(доля_паразитов, ПАРАЗИТЫ_ЗАМЕТНО, 0.12)
             + 0.14 * штраф_темпа)
    значение = _процент(1 - штраф)
    признаки = []
    if средняя_фраза > ФРАЗА_ДЛИННАЯ:
        признаки.append(f"длинные фразы: в среднем {средняя_фраза:.0f} слов")
    if сложных > 0.15:
        признаки.append(f"канцелярит: {сложных * 100:.0f} % длинных слов")
    if доля_паразитов > ПАРАЗИТЫ_ЗАМЕТНО:
        признаки.append(f"слова-паразиты: {доля_паразитов * 100:.1f} %")
    if темп and темп > ТЕМП_ВЕРХ:
        признаки.append(f"быстро: {темп:.0f} слов в минуту")
    if темп and темп < ТЕМП_НИЗ:
        признаки.append(f"медленно: {темп:.0f} слов в минуту")
    return {
        "index": значение,
        "grade": ("лёгкая" if значение >= 75 else
                  "обычная" if значение >= 55 else
                  "тяжеловатая" if значение >= 35 else "тяжёлая"),
        "wpm": round(темп) if темп else None,
        "sentence_words": round(средняя_фраза, 1),
        "long_sentences": int(round(длинных * 100)),
        "hard_words": int(round(сложных * 100)),
        "filler_rate": round(доля_паразитов, 4),
        "signals": признаки,
    }


def точность(сегменты: list[dict[str, Any]], оператор: str | None,
             confidence: float | None = None) -> dict[str, Any]:
    """Конкретность ответов оператора: 0 — общие слова, 100 — по существу.

    Считается соотношением определённого и неопределённого: числа, сроки,
    названия документов — против «наверное», «где-то так», «должно быть».
    Уверенность распознавания, если она есть, входит четвертью веса: по
    плохо расслышанной записи судить о конкретности нельзя.
    """
    свои = _речь_оператора(сегменты, оператор)
    пусто = {"index": None, "vague": [], "specific_hits": 0, "confidence": confidence}
    if свои is None:
        return пусто
    текст = _текст(свои)
    слова_ = words(текст)
    if len(слова_) < 20:
        return пусто
    размыто = _фразы(слова_, _без_ё(НЕОПРЕДЕЛЁННОСТЬ))
    конкретно = len(ОПРЕДЕЛЁННОСТЬ.findall(текст))
    на_сто = 100.0 / len(слова_)
    доля_размытого = len(размыто) * на_сто
    доля_конкретного = конкретно * на_сто
    основа = (0.55 * (1 - _шкала(доля_размытого, 0.3, 3.0))
              + 0.45 * _шкала(доля_конкретного, 0.5, 6.0))
    if confidence is not None:
        основа = 0.75 * основа + 0.25 * max(0.0, min(1.0, float(confidence)))
    return {
        "index": _процент(основа),
        "vague": размыто[:8],
        "specific_hits": конкретно,
        "confidence": round(float(confidence), 3) if confidence is not None else None,
    }


def вежливость_индекс(сегменты: list[dict[str, Any]],
                      оператор: str | None) -> dict[str, Any]:
    """Вежливость оператора: формулы против обрывающих оборотов.

    Тот же счёт, что у индекса эмпатии: (вежливых − невежливых) ÷ сумму,
    но приведённый к 0–100, чтобы лежать в одном ряду с остальными
    показателями сотрудника.
    """
    свои = _речь_оператора(сегменты, оператор)
    if свои is None:
        return {"index": None, "polite": 0, "impolite": 0, "kinds": {}, "missing": []}
    текст = _текст(свои).lower().replace("ё", "е")
    слова_ = words(текст)
    найдено: dict[str, int] = {}
    вежливых = 0
    for назначение, формулы in lexicons.ВЕЖЛИВОСТЬ.items():
        # По словам, а не подстрокой: «приветствую» содержит «привет», и
        # одно приветствие засчитывалось дважды, завышая индекс.
        образцы = tuple(tuple(ф.replace("ё", "е").split()) for ф in формулы)
        сколько = len(_фразы(слова_, образцы, все_вхождения=True))
        if сколько:
            найдено[назначение] = сколько
            вежливых += сколько
    невежливых = len(_фразы(слова_, lexicons.НЕВЕЖЛИВОСТЬ, все_вхождения=True))
    всего = вежливых + невежливых
    индекс = None if not всего else _процент((вежливых - невежливых) / всего / 2 + 0.5)
    return {
        "index": индекс, "polite": вежливых, "impolite": невежливых,
        "kinds": найдено,
        "missing": [н for н in ("приветствие", "прощание", "благодарность")
                    if н not in найдено],
    }


def персонализация(сегменты: list[dict[str, Any]], оператор: str | None,
                   по_имени: dict[str, Any], длительность: float) -> dict[str, Any]:
    """Насколько разговор был про этого клиента, а не вообще.

    Обращение по имени — главный признак, но не единственный: отсылки к
    прошлым обращениям и к тому, что клиент сам сказал, значат не меньше.
    Считается на десять минут разговора: в часовом разговоре два раза по
    имени — это не персонализация.
    """
    свои = _речь_оператора(сегменты, оператор)
    if свои is None:
        return {"index": None, "name_uses": None, "per_10min": None,
                "references": [], "name": по_имени.get("name")}
    слова_ = words(_текст(свои))
    отсылки = _фразы(слова_, tuple(tuple(ф.split()) for ф in (
        "вы говорили", "вы упоминали", "как вы сказали", "в прошлый раз",
        "по вашему заказу", "по вашему договору", "ваш номер",
        "вы обращались", "мы с вами", "как мы договаривались")))
    имён = по_имени.get("count")
    if имён is None:
        # Оператор не определён — обращаться по имени некому, и ноль здесь
        # был бы обвинением на пустом месте.
        return {"index": None, "name_uses": None, "per_10min": None,
                "references": отсылки[:6], "name": по_имени.get("name")}
    имён = int(имён)
    # Знаменатель — настоящая длительность, а не «не меньше половины
    # десятка минут»: с прежним полом все разговоры короче пяти минут были
    # неразличимы, а для типичного трёхминутного звонка частота обращений
    # занижалась впятеро. Совсем короткие всё же отсекаются — на десяти
    # секундах любая частота превращается в бессмыслицу.
    минут = (длительность or 0) / 60.0
    if минут < 0.5:
        return {"index": None, "name_uses": имён, "per_10min": None,
                "references": отсылки[:6], "name": по_имени.get("name")}
    на_десять = имён / (минут / 10.0)
    индекс = _процент(0.6 * _шкала(на_десять, 0.4, 4.0)
                      + 0.4 * _шкала(len(отсылки), 0.4, 4.0))
    return {
        "index": индекс, "name_uses": имён, "per_10min": round(на_десять, 2),
        "references": отсылки[:6], "name": по_имени.get("name"),
    }


def ритмичность(сегменты: list[dict[str, Any]], речь: dict[str, Any],
                оператор: str | None) -> dict[str, Any]:
    """Ровность речи: 0 — рвано, 100 — ровно.

    Ритм — это про предсказуемость: слушать ровную речь легче, чем речь
    рывками, даже если средний темп у них одинаковый. Меряется разбросом
    темпа по репликам и разбросом длин пауз, приведёнными к среднему
    (коэффициент вариации) — иначе быстрый говорящий всегда выглядел бы
    более рваным просто потому, что у него больше числа.
    """
    свои = _речь_оператора(сегменты, оператор)
    пусто = {"index": None, "wpm_spread": None, "pause_spread": None,
             "wpm": None, "level": None}
    if свои is None:
        return пусто
    темпы = [т for т in (_темп(с) for с in свои) if т]
    if len(темпы) < 4:
        return пусто
    средний = mean(темпы)
    разброс_темпа = pstdev(темпы) / максимум(средний)

    паузы = []
    предыдущий = None
    for с in sorted(сегменты, key=lambda с: float(с.get("start") or 0)):
        начало = float(с.get("start") or 0)
        if предыдущий is not None and начало > предыдущий:
            паузы.append(начало - предыдущий)
        предыдущий = max(предыдущий or 0, float(с.get("end") or 0))
    # Пауз мало — про них ничего не известно, и объявлять их «идеально
    # ровными» значит завышать индекс на коротких разговорах. Тогда вес
    # целиком уходит темпу, а не делится с выдумкой.
    хватает_пауз = len(паузы) >= 4
    разброс_пауз = (pstdev(паузы) / максимум(mean(паузы))) if хватает_пауз else 0.0
    рваность = (0.6 * _шкала(разброс_темпа, 0.12, 0.55)
                + 0.4 * _шкала(разброс_пауз, 0.6, 2.2)) if хватает_пауз \
        else _шкала(разброс_темпа, 0.12, 0.55)
    индекс = _процент(1 - рваность)
    return {
        "index": индекс,
        "level": ("ровная" if индекс >= 70 else
                  "обычная" if индекс >= 45 else "рваная"),
        "wpm": round(средний), "wpm_spread": round(разброс_темпа, 3),
        "pause_spread": round(разброс_пауз, 3),
    }


def паразиты(сегменты: list[dict[str, Any]], оператор: str | None) -> dict[str, Any]:
    """Слова-паразиты списком: доля, частые и чьи они.

    Одной доли мало: «ну» пятьдесят раз и «как бы» пятьдесят раз лечатся
    разными разговорами с сотрудником, а в общей доле они неразличимы.
    """
    свои = _речь_оператора(сегменты, оператор)
    если_нет = {"rate": None, "count": 0, "top": [], "sounds": 0}
    if свои is None:
        return если_нет
    слова_ = words(_текст(свои))
    if not слова_:
        return если_нет
    счёт: dict[str, int] = {}
    for слово in слова_:
        if слово in lexicons.ПАРАЗИТЫ:
            счёт[слово] = счёт.get(слово, 0) + 1
    звуков = sum(1 for с in слова_ if с in lexicons.ЗВУКИ_ПАУЗЫ)
    for образец in lexicons.ФРАЗЫ_ПАРАЗИТЫ:
        длина = len(образец)
        сколько = sum(1 for н in range(len(слова_) - длина + 1)
                      if tuple(слова_[н:н + длина]) == образец)
        if сколько:
            счёт[" ".join(образец)] = счёт.get(" ".join(образец), 0) + сколько
    всего = sum(счёт.values())
    return {
        "rate": round((всего + звуков) / len(слова_), 4),
        "count": всего, "sounds": звуков,
        "top": [{"word": с, "count": n} for с, n in
                sorted(счёт.items(), key=lambda п: -п[1])[:10]],
    }


def уменьшительные(сегменты: list[dict[str, Any]],
                   оператор: str | None) -> dict[str, Any]:
    """Уменьшительно-ласкательные и фамильярность в речи оператора.

    В деловом разговоре «секундочку» и «договорчик» звучат снисходительно,
    и в скриптах контакт-центров это отдельный пункт. Ищутся списком, а не
    по суффиксам: суффиксный поиск зачисляет сюда «точку», «ссылку» и
    «заявку» — и показатель превращается в счётчик обычных слов.
    """
    свои = _речь_оператора(сегменты, оператор)
    если_нет = {"count": None, "rate": None, "top": [], "familiar": []}
    if свои is None:
        return если_нет
    слова_ = words(_текст(свои))
    if not слова_:
        return {**если_нет, "count": 0}
    счёт: dict[str, int] = {}
    for слово in слова_:
        # `words()` заменяет ё на е, поэтому и словарь сверяется в том же
        # виде: без этого «денёчек» и «счётик» не находились никогда.
        if слово in _УМЕНЬШИТЕЛЬНЫЕ_БЕЗ_Ё:
            счёт[слово] = счёт.get(слово, 0) + 1
    фамильярно = _фразы(слова_, _без_ё(ФАМИЛЬЯРНОСТЬ))
    всего = sum(счёт.values())
    return {
        "count": всего,
        "rate": round(всего / len(слова_), 4),
        "top": [{"word": с, "count": n} for с, n in
                sorted(счёт.items(), key=lambda п: -п[1])[:10]],
        "familiar": фамильярно[:5],
    }


def nps(сегменты: list[dict[str, Any]], *, настроение_: dict[str, Any],
        усилие_: dict[str, Any], стресс_: dict[str, Any],
        решено: bool | None = None, клиент: str | None = None) -> dict[str, Any]:
    """Балл готовности рекомендовать: названный клиентом или предсказанный.

    Названный — если в разговоре прозвучал вопрос про оценку и вслед за
    ним число: это настоящий NPS, и он всегда главнее. Предсказанный
    считается из настроения к концу разговора, усилия клиента и
    напряжения: методики Verint и Level AI строят предсказанный CSAT/NPS
    ровно на этих трёх опорах. Предсказанный помечен `predicted: true` —
    смешивать его с названным в отчётах нельзя.
    """
    слова_ = words(_текст(сегменты))
    названный = _названный_балл(сегменты, слова_, клиент)
    if названный is not None:
        return {"score": названный, "group": _группа(названный),
                "predicted": False, "confidence": 1.0}

    настрой = настроение_.get("end")
    if настрой is None:
        настрой = настроение_.get("score")
    if настрой is None and не_о_чем(усилие_, стресс_):
        return {"score": None, "group": None, "predicted": True, "confidence": 0.0}

    основа = 0.5 + 0.5 * max(-1.0, min(1.0, float(настрой or 0)))
    усилие_доля = (float(усилие_.get("score") or 0) + 5) / 10
    напряжение = 1 - _шкала(float(стресс_.get("index") or 0), 10, 80)
    смесь = 0.45 * основа + 0.30 * усилие_доля + 0.25 * напряжение
    if решено is True:
        смесь = min(1.0, смесь + 0.08)
    elif решено is False:
        смесь = max(0.0, смесь - 0.12)
    балл = int(round(смесь * 10))
    return {
        "score": балл, "group": _группа(балл), "predicted": True,
        # Уверенность падает на коротких разговорах и там, где эмоции нет:
        # предсказание по трём ровным репликам — это не предсказание.
        "confidence": round(min(1.0, len(слова_) / 400.0), 2),
    }


def не_о_чем(усилие_: dict[str, Any], стресс_: dict[str, Any]) -> bool:
    return not усилие_.get("markers") and not (стресс_.get("index") or 0)


def _группа(балл: int | None) -> str | None:
    if балл is None:
        return None
    if балл >= NPS_ПРОМОУТЕР:
        return "промоутер"
    if балл >= NPS_НЕЙТРАЛ:
        return "нейтрал"
    return "критик"


def _названный_балл(сегменты: list[dict[str, Any]], слова_: list[str],
                    клиент: str | None = None) -> int | None:
    """Балл, названный КЛИЕНТОМ вслед за вопросом об оценке.

    Только вслед за вопросом: число «десять» в разговоре про сроки — это
    не оценка, и принимать любое число от 0 до 10 за NPS значило бы
    считать оценкой половину разговоров про доставку.

    И только из реплики клиента. Без этого в «названный балл» — единственное
    число раздела, которое объявлено не предсказанным, — попадали номер
    заказа из ответа оператора и его собственное «я поставлю десять».
    """
    if not _фразы(слова_, _без_ё(NPS_ВОПРОС)):
        return None
    словами = {"ноль": 0, "один": 1, "два": 2, "три": 3, "четыре": 4,
               "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9,
               "десять": 10, "единица": 1, "двойка": 2, "тройка": 3,
               "четвёрка": 4, "четверка": 4, "пятёрка": 5, "пятерка": 5,
               "шестёрка": 6, "шестерка": 6, "семёрка": 7, "семерка": 7,
               "восьмёрка": 8, "восьмерка": 8, "девятка": 9, "десятка": 10}
    спросили = False
    for сегмент in сегменты:
        текст = str(сегмент.get("text") or "")
        свои = words(текст)
        чей = str(сегмент.get("speaker") or "")
        # Реплика того, кто спрашивал, оценкой быть не может. Когда стороны
        # не размечены, довериться нечему — и балл считается предсказанным.
        клиентская = (чей == клиент) if клиент else False
        if спросили and клиентская:
            for цифра in re.findall(r"\b(\d{1,2})\b", текст):
                значение = int(цифра)
                if 0 <= значение <= 10:
                    return значение
            for слово in свои:
                if слово in словами:
                    return словами[слово]
        if _фразы(свои, _без_ё(NPS_ВОПРОС)):
            спросили = True
    return None


