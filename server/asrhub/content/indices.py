def _слогов(слово: str) -> int:
    return sum(1 for б in слово if б in ГЛАСНЫЕ)


def _шкала(значение: float, низ: float, верх: float) -> float:
    """Линейное приведение к 0…1 с обрезкой по краям."""
    if верх == низ:
        return 0.0
    доля = (значение - низ) / (верх - низ)
    return max(0.0, min(1.0, доля))


def _процент(доля: float) -> int:
    return int(round(max(0.0, min(1.0, доля)) * 100))


def _без_ё(образцы: tuple[tuple[str, ...], ...]) -> tuple[tuple[str, ...], ...]:
    """Обороты в том написании, в каком их отдаёт `words()` — без «ё»."""
    return tuple(tuple(с.replace("ё", "е") for с in образец) for образец in образцы)


def _фразы(слова: list[str], образцы: tuple[tuple[str, ...], ...], *,
           все_вхождения: bool = False) -> list[str]:
    """Ищет обороты последовательностью слов. Возвращает найденные.

    По умолчанию оборот считается один раз: для «клиент упоминал, что
    звонит не впервые» важен факт, а не счёт. `все_вхождения` нужен там,
    где счёт и есть показатель: шесть «подождите» и одно «подождите» — это
    разные разговоры, а одинаковый индекс вежливости у них был ошибкой.
    """
    найдено = []
    всего = len(слова)
    for образец in образцы:
        длина = len(образец)
        for начало in range(всего - длина + 1):
            if tuple(слова[начало:начало + длина]) == образец:
                найдено.append(" ".join(образец))
                if not все_вхождения:
                    break
    return найдено


def _реплики(сегменты: list[dict[str, Any]], кто: str | None) -> list[dict[str, Any]]:
    if кто is None:
        return list(сегменты)
    return [с for с in сегменты if str(с.get("speaker") or "") == кто]


def _речь_оператора(сегменты: list[dict[str, Any]],
                    оператор: str | None) -> list[dict[str, Any]] | None:
    """Реплики оператора — или None, когда его не определили.

    Раньше на этом месте стояло «или весь разговор», и показатели речи
    оператора считались по обеим сторонам: паразиты клиента становились
    паразитами сотрудника, а его «вы должны» — невежливостью оператора.
    Записи без разметки по сторонам (движок без диаризации, одна дорожка)
    — обычное дело, и молчать о них честнее, чем считать наугад. Так же
    ведёт себя обращение по имени: без оператора оно NULL, а не ноль.
    """
    if оператор is None:
        return None
    свои = [с for с in сегменты if str(с.get("speaker") or "") == оператор]
    return свои or None


def _текст(сегменты: list[dict[str, Any]]) -> str:
    return " ".join(str(с.get("text") or "") for с in сегменты)


def _темп(сегмент: dict[str, Any]) -> float | None:
    """Слов в минуту в одной реплике. Короткие реплики не в счёт.

    Реплика в полсекунды из одного слова даёт 120 слов в минуту ровно так
    же, как минута связной речи, — но говорит только о том, что человек
    сказал «да». Такие реплики портят и средний темп, и его разброс.
    """
    длина = float(сегмент.get("end") or 0) - float(сегмент.get("start") or 0)
    слов = len(words(str(сегмент.get("text") or "")))
    if длина < 1.5 or слов < 4:
        return None
    return слов / (длина / 60.0)


