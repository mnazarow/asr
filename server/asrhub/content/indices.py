def показатели(*, сегменты: list[dict[str, Any]], речь: dict[str, Any],
               тон: dict[str, Any], оценки: list[dict[str, Any]],
               оператор: str | None, клиент: str | None,
               по_имени: dict[str, Any], фрустрация: int = 0,
               повторное: int = 0, мат: int | None = None,
               решено: bool | None = None,
               confidence: float | None = None) -> dict[str, Any]:
    """Все показатели разом — то, что уходит в разбор записи."""
    длительность = float(речь.get("duration_s") or 0)
    настрой = настроение(оценки, тон, оператор, клиент)
    напряжение = стресс(сегменты=сегменты, речь=речь, оценки=оценки,
                        клиент=клиент, оператор=оператор,
                        фрустрация=фрустрация, повторное=повторное, мат=мат)
    усилие_ = усилие(сегменты, клиент, повторное)
    return {
        "mood": настрой,
        "intensity": интенсивность(оценки),
        "stress": напряжение,
        "effort": усилие_,
        "fatigue": усталость(сегменты, оператор),
        "clarity": понятность(сегменты, речь, оператор),
        "accuracy": точность(сегменты, оператор, confidence),
        "politeness": вежливость_индекс(сегменты, оператор),
        "personalization": персонализация(сегменты, оператор, по_имени, длительность),
        "rhythm": ритмичность(сегменты, речь, оператор),
        "fillers": паразиты(сегменты, оператор),
        "diminutives": уменьшительные(сегменты, оператор),
        "nps": nps(сегменты, настроение_=настрой, усилие_=усилие_,
                   стресс_=напряжение, решено=решено, клиент=клиент),
    }


