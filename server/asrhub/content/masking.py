"""Маскирование персональных данных в текстах расшифровок.

Расшифровка разговора с клиентом — это персональные данные, и чаще всего
не те, ради которых её читают: номер карты, продиктованный оператору,
нужен платёжной системе, а не аналитику. Здесь — обезличивание по форме:
телефоны, почта, номера карт, паспорт, СНИЛС, ИНН и даты рождения
заменяются пометками вида «[карта]». Всё на правилах и контрольных
суммах — карта по Луну, СНИЛС и ИНН по своим алгоритмам, — поэтому
случайные десятизначные числа за ИНН не принимаются, а паспорт и дата
рождения берутся только рядом со словами, которые их называют: голые
«4512 345678» или «12.05.1980» в разговоре означают что угодно.

Что не делается: имена, адреса и числа, произнесённые словами. Первые
правилами не берутся честно (см. `entities`), вторые требуют разбора речи,
которого здесь нет. Маскирование — защита выгрузки, а не гарантия
обезличивания; документация говорит об этом прямо.

Две точки применения: выгрузки (настройка `export_mask_pii`) и ответы
API ключу с флагом `mask_pii` — ключ аналитика или интеграции, которой
текст нужен, а персональные данные — нет.
"""
from __future__ import annotations

import re
from typing import Any

from .entities import _ПОЧТА, _ТЕЛЕФОН

#: Чем заменяется найденное — по видам.
ПОМЕТКИ: dict[str, str] = {
    "phone": "[телефон]", "email": "[почта]", "card": "[карта]",
    "passport": "[паспорт]", "snils": "[СНИЛС]", "inn": "[ИНН]",
    "birthdate": "[дата рождения]",
}

def _карта_внутри(text: str, начало: int, конец: int) -> tuple[int | None, int]:
    """Где внутри цепочки цифр лежит номер карты — или что его там нет.

    Выражение жадное и забирает всё подряд, а карту редко диктуют в
    одиночку: следом идут код с оборота и срок. На такой цепочке Лун не
    сходится, и маскировалась не «часть номера», а ничего — полный номер
    уезжал в выгрузку, а отчёт об обезличивании показывал, что находок нет.

    Поэтому, если целиком не сошлось, пробуем начало и конец цепочки — но
    только по границам групп, разделённых пробелом или дефисом. Резать
    посередине группы нельзя: на девятнадцати цифрах подряд окно из
    тринадцати проходит Луна каждый десятый раз случайно, и номер заказа
    превращался бы в карту. Граница групп — это то, как карту записывают
    и диктуют, и она же отделяет номер от кода и срока.
    """
    группы: list[list[tuple[int, str]]] = [[]]
    for и, с in enumerate(text[начало:конец], начало):
        if с.isdigit():
            группы[-1].append((и, с))
        elif группы[-1]:
            группы.append([])
    группы = [г for г in группы if г]
    цифры = "".join(с for г in группы for _, с in г)
    if 13 <= len(цифры) <= 19 and luhn(цифры):
        return начало, конец
    if len(группы) < 2:
        return None, конец
    for сколько in range(len(группы) - 1, 0, -1):
        for окно in (группы[:сколько], группы[-сколько:]):
            плоско = [пара for г in окно for пара in г]
            строка = "".join(с for _, с in плоско)
            if 13 <= len(строка) <= 19 and luhn(строка):
                return плоско[0][0], плоско[-1][0] + 1
    return None, конец


#: Международный номер: плюс, код страны и 9–14 цифр с разделителями.
_ТЕЛЕФОН_МЕЖД = re.compile(r"(?<![\d\w])\+\d[\d\s\-()]{8,16}\d(?!\d)")

#: Мобильный без восьмёрки и без +7: «916 123-45-67», «9031234567». Так
#: номер диктуют чаще всего — код страны люди опускают, — а выражение
#: сущностей без него номер не видит. Только для маскирования: здесь лучше
#: спрятать лишний десятизначный номер заказа, начинающийся с девятки, чем
#: оставить в выгрузке телефон клиента.
_ТЕЛЕФОН_БЕЗ_КОДА = re.compile(
    r"(?<![\d+])\(?9\d{2}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?![\d])")

#: Городской без восьмёрки: «495 123-45-67», «(812) 123-45-67». Коды городов
#: России начинаются с 3, 4 и 8. Только с разделителями групп — так городской
#: номер пишут и диктуют; десять цифр подряд с тройки–восьмёрки — это чаще
#: номер договора или ИНН с неверной суммой, и прятать их незачем.
_ГОРОДСКОЙ_БЕЗ_КОДА = re.compile(
    r"(?<![\d+])(?:\([3-8]\d{2}\)\s?|[3-8]\d{2}[\s\-])\d{3}[\s\-]\d{2}[\s\-]\d{2}(?!\d)")

#: Почта с кириллицей: «иван@почта.рф», «ivan@пример.рф». Выражение
#: сущностей знает только латиницу — для поиска по почте этого хватает, а
#: для обезличивания нет.
_ПОЧТА_ЛЮБАЯ = re.compile(r"[\w.%+-]+@[\w-]+(?:\.[\w-]+)*\.[^\W\d_]{2,}")

#: Номер карты: 13–19 цифр группами через пробел, дефис или запятую — так
#: карту и диктуют («4111, 1111, 1111, 1111»), и распознавание ставит между
#: группами то запятую, то два пробела. Подтверждается Луном.
_КАРТА = re.compile(r"(?<!\d)(?:\d(?:[ \-]{1,2}|, ?)?){12,18}\d(?!\d)")

#: СНИЛС: 123-456-789 01 (разделители необязательны); подтверждается суммой.
_СНИЛС = re.compile(r"(?<!\d)\d{3}[- ]?\d{3}[- ]?\d{3}[- ]?\d{2}(?!\d)")

#: ИНН: ровно 10 или 12 цифр, слитно или группами через пробел («7707 083
#: 893» — так его читают с карточки организации); подтверждается
#: контрольными цифрами.
_ИНН = re.compile(r"(?<![\d\-])\d(?: ?\d){9}(?:(?: ?\d){2})?(?![\d\-])(?! \d)")

#: Паспорт — только рядом с называющим словом: «паспорт 45 12 345678»,
#: «серия 4512 номер 345678», «паспортные данные: 4512 345678». Номер —
#: слитно, по три («345 678») или по две цифры («34 56 78»): как продиктовали.
_ПАСПОРТ = re.compile(
    r"(паспорт\w*(?:\s+\w+){0,3}?[\s:№#-]*|сери[яи]\s*)"
    r"(\d{2}\s?\d{2})[\s,]*(?:номер|№|n)?[\s:]*"
    r"(\d{6}|\d{3}\s\d{3}|\d{2}\s\d{2}\s\d{2})(?!\d)", re.IGNORECASE)

#: Дата рождения — только рядом с называющим словом.
_ДАТА = (r"(\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}"
         r"|\d{1,2}\s+(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|"
         r"октябр|ноябр|декабр)\w*(?:\s+\d{4})?(?:\s+года?)?)")
#: Сокращение «д. р.», «др» — только отдельным словом. Без границы «др»
#: находилось внутри «адресу» и «Андреем», и «Доставка по адресу с
#: 12.09.2026» и «Встреча с Андреем 12 мая» становились «[дата рождения]».
_ДАТА_РОЖДЕНИЯ = re.compile(
    r"((?:дата|день|год[а]?)\s+рождения|родил[ас][сья]+|(?<!\w)д\.?\s?р\.?(?!\w))"
    r"[\s:—-]*(?:\w+\s+){0,2}?" + _ДАТА, re.IGNORECASE)

#: Ключи ответов, где живёт текст, и ключи со списками найденных сущностей.
#:
#: Сюда же входят поля смыслового слоя: модель пересказывает разговор
#: своими словами, и номер карты из разговора попадает в пересказ ровно
#: так же, как в расшифровку. Раньше `quote` маскировалась, а `summary` в
#: том же объекте — нет, и ключ, заведённый специально «без персональных
#: данных», получал их из пересказа.
#:
#: `stem` и `phrase` — ключевые слова, сочетания и темы. Их разбор строит из
#: текста, а маскирование смотрит на текст: номер через дефис
#: «916-123-45-67» уезжал основой в ключевые слова и в корпус тем, и ключ
#: с `mask_pii` получал его в разборе записи и в «Темах».
TEXT_KEYS = frozenset({"text", "word", "reference_text", "filename", "message",
                       "ref", "hyp", "raw", "excerpt", "snippet", "quote", "title",
                       "summary", "reason_quote", "outcome_quote", "what", "answer",
                       "note", "question", "stem", "phrase"})
LIST_KEYS = frozenset({"phones", "emails"})


#: Цифры у обреза выдержки: «…карта 4111 1111 1111…». Выдержка режет текст
#: по словам, и номер, обрезанный на середине, не узнаётся ни Луном, ни
#: шаблоном телефона — а это начало номера карты клиента.
_ЦИФРЫ_У_ОБРЕЗА = re.compile(r"(?:\d[\d\s\-().,]*\d|\d)(?=\s*…)|(?<=…)\s*(?:\d[\d\s\-().,]*\d|\d)")
_МНОГО_ЦИФР = re.compile(r"\d")

#: Ключи со списками строк, каждая из которых — кусок текста: основы темы.
STRING_LIST_KEYS = frozenset({"stems"})

#: Знаки, которыми поиск обрамляет найденное в выдержке (`db.search_segments`).
#: Внутри номера они рвут его на части: «8 ‹916› 765 43 21» выражение
#: телефона уже не узнаёт, и выдержка уходила с полным номером.
_ПОДСВЕТКА = ("‹", "›")
_ОБРАМЛЕНИЕ = "".join(_ПОДСВЕТКА)

#: Многоточие, которым поиск помечает обрезанный край выдержки.
_ОБРЕЗ = "…"



def luhn(цифры: str) -> bool:
    """Контрольная сумма Луна — по ней проверяются номера карт."""
    total = 0
    for i, ch in enumerate(reversed(цифры)):
        d = int(ch)
        if i % 2 == 1:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return total % 10 == 0


def snils_ok(цифры: str) -> bool:
    """Контрольное число СНИЛС по правилам ПФР."""
    if len(цифры) != 11:
        return False
    номер, контроль = цифры[:9], int(цифры[9:])
    # Номера до 001-001-998 контрольным числом не проверяются.
    if int(номер) <= 1001998:
        return False
    сумма = sum(int(d) * (9 - i) for i, d in enumerate(номер))
    if сумма < 100:
        ожидается = сумма
    elif сумма in (100, 101):
        ожидается = 0
    else:
        ожидается = сумма % 101
        if ожидается in (100, 101):
            ожидается = 0
    return ожидается == контроль


def inn_ok(цифры: str) -> bool:
    """Контрольные цифры ИНН: одна у организаций (10), две у людей (12)."""
    d = [int(ch) for ch in цифры]
    if len(d) == 10:
        веса = (2, 4, 10, 3, 5, 9, 4, 6, 8)
        return d[9] == sum(w * x for w, x in zip(веса, d, strict=False)) % 11 % 10
    if len(d) == 12:
        в11 = (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
        в12 = (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
        return (d[10] == sum(w * x for w, x in zip(в11, d, strict=False)) % 11 % 10
                and d[11] == sum(w * x for w, x in zip(в12, d, strict=False)) % 11 % 10)
    return False


def find(text: str) -> list[dict[str, Any]]:
    """Все персональные данные в тексте: вид, границы, значение.

    Порядок видов — по надёжности: почта и телефон, потом карта, СНИЛС,
    ИНН, паспорт, дата рождения. Наложения не допускаются: цифры,
    ставшие телефоном, за карту уже не сойдут.
    """
    if not text:
        return []
    занято: list[tuple[int, int]] = []
    out: list[dict[str, Any]] = []

    def взять(kind: str, start: int, end: int, value: str) -> None:
        if any(s < end and start < e for s, e in занято):
            return
        занято.append((start, end))
        out.append({"kind": kind, "start": start, "end": end, "value": value})

    for выражение in (_ПОЧТА, _ПОЧТА_ЛЮБАЯ):
        for m in выражение.finditer(text):
            взять("email", m.start(), m.end(), m.group(0))
    for выражение in (_ТЕЛЕФОН, _ТЕЛЕФОН_МЕЖД):
        for m in выражение.finditer(text):
            взять("phone", m.start(), m.end(), m.group(0))
    for m in _КАРТА.finditer(text):
        начало, конец = _карта_внутри(text, m.start(), m.end())
        if начало is not None:
            взять("card", начало, конец, text[начало:конец])
    for m in _СНИЛС.finditer(text):
        if snils_ok(re.sub(r"\D", "", m.group(0))):
            взять("snils", m.start(), m.end(), m.group(0))
    for m in _ИНН.finditer(text):
        if inn_ok(re.sub(r"\D", "", m.group(0))):
            взять("inn", m.start(), m.end(), m.group(0))
    # Номер без кода страны — после карты, СНИЛС и ИНН: те подтверждены
    # контрольной суммой и потому надёжнее, а десять цифр ИНН организации,
    # начинающиеся с семёрки, иначе стали бы «телефоном». Граница цифр в
    # выражениях не даёт одному забрать кусок другого.
    for выражение in (_ТЕЛЕФОН_БЕЗ_КОДА, _ГОРОДСКОЙ_БЕЗ_КОДА):
        for m in выражение.finditer(text):
            взять("phone", m.start(), m.end(), m.group(0))
    for m in _ПАСПОРТ.finditer(text):
        взять("passport", m.start(2), m.end(3), text[m.start(2):m.end(3)])
    for m in _ДАТА_РОЖДЕНИЯ.finditer(text):
        взять("birthdate", m.start(2), m.end(2), m.group(2))
    out.sort(key=lambda x: x["start"])
    return out


def mask_text(text: str) -> str:
    """Текст с пометками вместо персональных данных."""
    if text and any(з in text for з in _ОБРАМЛЕНИЕ):
        return _mask_framed(text)
    найдено = find(text)
    if not найдено:
        return text
    части: list[str] = []
    позиция = 0
    for н in найдено:
        части.append(text[позиция:н["start"]])
        части.append(ПОМЕТКИ[н["kind"]])
        позиция = н["end"]
    части.append(text[позиция:])
    return "".join(части)


def _mask_framed(text: str) -> str:
    """Выдержка поиска: найденное обрамлено ‹ ›, края обрезаны «…».

    Знаки обрамления рвали номер — «8 ‹916› 765 43 21» шаблон телефона не
    узнавал, — а обрезанный край оставлял начало карты. Поэтому ищем по
    тексту без знаков, а знаки возвращаем на места вне найденного; цифры
    у обреза прячем целиком: что там за число, по куску не понять.
    """
    чистый: list[str] = []
    знаки: dict[int, str] = {}
    for с in text:
        if с in _ОБРАМЛЕНИЕ:
            знаки[len(чистый)] = знаки.get(len(чистый), "") + с
        else:
            чистый.append(с)
    строка = "".join(чистый)
    найдено = find(строка)
    части: list[str] = []
    позиция = 0
    for н in [*найдено, {"start": len(строка), "end": len(строка), "kind": None}]:
        for i in range(позиция, н["start"]):
            части.append(знаки.get(i, "") + строка[i])
        if н["kind"] is None:
            части.append(знаки.get(len(строка), ""))
            break
        части.append(ПОМЕТКИ[н["kind"]])
        позиция = н["end"]
    итог = "".join(части)
    if "…" in итог:
        итог = _ЦИФРЫ_У_ОБРЕЗА.sub(
            lambda м: "[…]" if len(_МНОГО_ЦИФР.findall(м.group(0))) >= 4 else м.group(0),
            итог)
    return итог


def _mask_words(text: str, слова: list[Any]) -> list[Any]:
    """Пословные метки реплики: слова, попавшие в найденное в её тексте.

    По одному слову номер не узнать: «8», «916», «765», «43», «21» — пять
    обычных чисел, и `words[]` отдавал телефон целиком ключу, которому его
    не положено видеть. Поэтому найденное ищется в тексте реплики, а
    слова, чей отрезок с ним пересекается, получают ту же пометку. Слово,
    которого в тексте не нашлось (движок нормализовал текст иначе, чем
    слова), маскируется само по себе, как раньше.
    """
    найдено = find(text or "")
    out: list[Any] = []
    позиция = 0
    for слово in слова:
        if not isinstance(слово, dict) or not isinstance(слово.get("word"), str):
            out.append(mask_payload(слово))
            continue
        чистое = слово["word"].strip()
        где = text.find(чистое, позиция) if (чистое and text) else -1
        пометка = None
        if где >= 0:
            конец = где + len(чистое)
            позиция = конец
            for н in найдено:
                if н["start"] < конец and где < н["end"]:
                    пометка = ПОМЕТКИ[н["kind"]]
                    break
        новое = mask_payload(слово)
        if пометка:
            новое["word"] = пометка
        out.append(новое)
    return out


def _mask_date(значение: Any) -> Any:
    """Дата из списка названных: старая — пометкой, свежая — как есть.

    В разборе сущностей даты лежат списком без окружения, и по нему не
    понять, дата ли это рождения. Различает год: дата с годом давнее двух
    лет назад — почти всегда день рождения или выдачи документа, то есть
    персональные данные, а «12.05» и «до пятнадцатого мая» — сроки
    разговора, ради которых список и нужен.
    """
    if not isinstance(значение, str):
        return значение
    import time  # noqa: PLC0415

    год = (re.fullmatch(r"\s*\d{1,2}[.\-/]\d{1,2}[.\-/](\d{4}|\d{2})\s*", значение)
           or re.search(r"[^\W\d_]\s+(\d{4})(?:\s*г\.?|\s+года?)?\s*$", значение))
    if not год:
        return значение
    число = int(год.group(1))
    if len(год.group(1)) == 2:
        число += 2000 if число <= time.localtime().tm_year % 100 else 1900
    return "[дата]" if число < time.localtime().tm_year - 2 else значение


def count(text: str) -> dict[str, int]:
    """Сколько чего найдено — для проверок и для отчёта об обезличивании."""
    итог: dict[str, int] = {}
    for н in find(text):
        итог[н["kind"]] = итог.get(н["kind"], 0) + 1
    return итог


def _без_подсветки(выдержка: str) -> tuple[str, list[tuple[int, str]]]:
    """Выдержка без знаков подсветки и места, где они стояли."""
    чистая: list[str] = []
    знаки: list[tuple[int, str]] = []
    for знак in выдержка:
        if знак in _ПОДСВЕТКА:
            знаки.append((len(чистая), знак))
        else:
            чистая.append(знак)
    return "".join(чистая), знаки


def mask_snippet(выдержка: str, текст: str = "") -> str:
    """Выдержка поиска с пометками вместо персональных данных.

    Выдержку собирает поиск: кусок реплики в дюжину слов, края обрезаны
    многоточием, найденное обрамлено «‹…›». Маскировать её как обычный текст
    нельзя по двум причинам: знаки подсветки рвут номер посередине, а край
    выдержки отрезает от номера начало — и «…765 43 21» не похоже на
    телефон, хотя это его хвост.

    Поэтому персональные данные ищутся в ЦЕЛОЙ реплике (`текст`), а в
    выдержке закрывается всё, что попало в найденные отрезки, — в том числе
    кусок номера на краю. Подсветка внутри закрытого отрезка пропадает
    вместе с ним, снаружи — остаётся. Без реплики (или если выдержка в ней
    не нашлась) ищем в самой выдержке, сняв подсветку.
    """
    if not выдержка:
        return выдержка
    чистая, знаки = _без_подсветки(выдержка)
    слева = чистая.startswith(_ОБРЕЗ)
    справа = чистая.endswith(_ОБРЕЗ) and len(чистая) > len(_ОБРЕЗ)
    ядро = чистая[len(_ОБРЕЗ) if слева else 0:len(чистая) - (len(_ОБРЕЗ) if справа else 0)]
    сдвиг = len(_ОБРЕЗ) if слева else 0

    начало = текст.find(ядро) if (текст and ядро) else -1
    if начало >= 0:
        отрезки = [(max(0, н["start"] - начало), min(len(ядро), н["end"] - начало), н["kind"])
                   for н in find(текст)
                   if н["start"] < начало + len(ядро) and н["end"] > начало]
    else:
        отрезки = [(н["start"], н["end"], н["kind"]) for н in find(ядро)]
    отрезки = [(н, к, в) for н, к, в in отрезки if к > н]
    if not отрезки:
        return выдержка

    # Пересобираем ядро: закрытый отрезок — одной пометкой. Подсветка,
    # попавшая внутрь закрытого отрезка, выносится на его край: открывающая
    # — перед ним, закрывающая — после. Так пара «‹…›» не рвётся, а то, что
    # поиск нашёл внутри номера, видно как подсвеченная пометка.
    закрыто = [False] * len(ядро)
    пометка_с: dict[int, str] = {}
    for нач, кон, вид in отрезки:
        for место in range(нач, кон):
            закрыто[место] = True
        пометка_с[нач] = вид
    по_месту: dict[int, list[str]] = {}
    for место, знак in знаки:
        место = min(len(ядро), max(0, место - сдвиг))
        for нач, кон, _ in отрезки:
            if нач < место < кон:
                место = нач if знак == _ПОДСВЕТКА[0] else кон
                break
        по_месту.setdefault(место, []).append(знак)
    части: list[str] = [_ОБРЕЗ] if слева else []
    for место in range(len(ядро) + 1):
        части.extend(по_месту.get(место, ()))
        if место == len(ядро):
            break
        if место in пометка_с:
            части.append(ПОМЕТКИ[пометка_с[место]])
        elif not закрыто[место]:
            части.append(ядро[место])
    if справа:
        части.append(_ОБРЕЗ)
    return "".join(части)


def _слова_по_отрезкам(слова: list[Any]) -> list[Any]:
    """Пословные метки с пометками там, где слова складываются в находку.

    Маска ищется по форме — телефон, карта, СНИЛС, — а у пословных меток
    номер разбит на слова: карта — четыре слова по четыре цифры, телефон —
    пять. По одному слову ни одно не похоже ни на что, и обезличенная
    выгрузка отдавала номер целиком в `words[]`, при том что текст той же
    реплики был закрыт. Здесь слова склеиваются в строку, находки ищутся в
    ней, и каждое слово, задетое находкой, получает её пометку. Время слова
    сохраняется: по нему заглушают звук и строят субтитры.
    """
    куски: list[str] = []
    места: list[tuple[int, int] | None] = []
    длина = 0
    for слово in слова:
        if isinstance(слово, dict) and isinstance(слово.get("word"), str):
            if куски:
                длина += 1
            места.append((длина, длина + len(слово["word"])))
            куски.append(слово["word"])
            длина += len(слово["word"])
        else:
            места.append(None)
    строка = " ".join(куски)
    находки = find(строка)
    if not находки:
        return слова
    итог: list[Any] = []
    for слово, место in zip(слова, места, strict=True):
        if место is not None:
            вид = next((н["kind"] for н in находки
                        if н["start"] < место[1] and н["end"] > место[0]), None)
            if вид is not None:
                слово = {**слово, "word": ПОМЕТКИ[вид]}
        итог.append(слово)
    return итог


def mask_payload(данные: Any) -> Any:
    """Обезличивает ответ API: строки под текстовыми ключами и списки
    найденных телефонов и адресов; остальное — как есть.

    Одна функция на все пути, которыми текст уходит ключу с `mask_pii`:
    ответы JSON, лента событий, выгрузки. Свои копии маскирования в
    обработчиках расходились с ней и друг с другом — то выдержка поиска, то
    пословные метки, то основы тем уходили незакрытыми.
    """
    if isinstance(данные, dict):
        out: dict[str, Any] = {}
        текст = данные.get("text")
        for k, v in данные.items():
            if k == "snippet" and isinstance(v, str):
                # Выдержка поиска — по целой реплике рядом, если она есть.
                out[k] = mask_snippet(v, текст if isinstance(текст, str) else "")
            elif k in TEXT_KEYS and isinstance(v, str):
                out[k] = mask_text(v)
            elif k == "words" and isinstance(v, list):
                # Сначала — находки в склеенных словах (номер, разбитый на
                # слова), затем — находки в тексте реплики рядом, если он есть.
                слова = _слова_по_отрезкам(v)
                out[k] = (_mask_words(текст, слова) if isinstance(текст, str)
                          else mask_payload(слова))
            elif k == "dates" and isinstance(v, list):
                out[k] = [_mask_date(x) if isinstance(x, str) else mask_payload(x) for x in v]
            elif k in LIST_KEYS and isinstance(v, list):
                out[k] = [ПОМЕТКИ["phone" if k == "phones" else "email"]
                          if isinstance(x, str) else mask_payload(x) for x in v]
            elif k in STRING_LIST_KEYS and isinstance(v, list):
                out[k] = [mask_text(x) if isinstance(x, str) else mask_payload(x)
                          for x in v]
            elif k == "numbers" and isinstance(v, list):
                out[k] = [{**x, "number": "[номер]"} if isinstance(x, dict) else x for x in v]
            else:
                out[k] = mask_payload(v)
        return out
    if isinstance(данные, list):
        return [mask_payload(x) for x in данные]
    return данные


def нужно(principal: Any) -> bool:
    """Получает ли этот участник обезличенные ответы.

    Источник один — участник, которого нашла проверка доступа
    (`request.state.principal`): ключ заголовком, ключ в адресе, билет,
    сессия. Прослойка маскирования раньше разбирала ключ заново и билета не
    знала — по `?ticket=` ключ с `mask_pii` получал полные телефоны во всех
    ответах JSON.
    """
    return bool(getattr(principal, "mask_pii", False))
