"""Текстовые каналы: разбор переписки без звука.

Слой разбора у сервера текстовый по своей природе: тональность, категории,
скрипт разговора, обязательства, балл оператора — всё это считается по
расшифровке, а не по звуку. Значит, переписка из чата или почты проходит тот
же путь без единой новой модели: нет только распознавания, которое ей и не
нужно.

Единственное, с чем нельзя смошенничать, — время. В переписке его нет: между
репликами проходит минута или час, и это не пауза в разговоре, а совсем
другое явление. Поэтому всё, что меряется секундами — темп речи, паузы,
мёртвый эфир, перебивания, — для текстовых заданий возвращается пустым, а не
нулём. Ноль пауз в чате читается как «отвечали мгновенно», хотя мерить там
нечего, и по такому числу принимают решения.

Формат на входе намеренно терпимый: список реплик со стороной и текстом или
просто текст с разметкой «Клиент: …» построчно. Интеграции пишут кто во что
горазд, и отказ разобрать переписку из-за лишнего поля — это отказ от канала
целиком.
"""
from __future__ import annotations

import re
from typing import Any

from .errors import ConfigError

#: Как в тексте отмечают, кто говорит. Двоеточие после короткого слова в
#: начале строки — то, во что превращается экспорт почти любого чата.
СТОРОНА = re.compile(r"^\s*([A-Za-zА-Яа-яЁё0-9 _.\-]{1,32}?)\s*:\s+(.*)$")

#: Каналы, которые сервер называет своими именами. Чужое имя не отвергается —
#: оно просто сохраняется как есть: список каналов у каждого свой, и спорить
#: с интеграцией из-за слова «telegram» незачем.
КАНАЛЫ = ("chat", "email", "messenger", "review", "ticket", "social")

#: Кого считать оператором, когда сторона названа словом, а не ролью.
ОПЕРАТОР = {"оператор", "менеджер", "агент", "поддержка", "сотрудник",
            "agent", "operator", "support", "manager"}

#: Кого считать клиентом. Нужен не меньше, чем список операторов: в чате
#: первым обычно пишет клиент, и когда оператор подписан именем («Анна»),
#: правило «кто заговорил первым» отдавало скрипт и балл оператора клиенту.
#: Раз одна из двух сторон — клиент, оператор — другая.
КЛИЕНТ = {"клиент", "покупатель", "пользователь", "абонент", "гость",
          "заказчик", "посетитель", "customer", "client", "user", "visitor",
          "guest"}


def _сторона(имя: str) -> str:
    """Приводит подпись к стороне разговора, не теряя исходного имени."""
    чистое = str(имя or "").strip()
    return чистое or "—"


def разобрать(payload: Any) -> tuple[list[dict[str, Any]], str]:
    """Реплики и склеенный текст из того, что прислали.

    Принимает список реплик (`[{"speaker": …, "text": …}]`), список строк или
    одну строку с разметкой «Кто: текст». Возвращает реплики с порядковыми
    номерами вместо времени: слой разбора ждёт `start`/`end`, а выдумывать
    секунды нельзя — они пойдут в показатели и станут ложью.
    """
    сырые: list[dict[str, Any]] = []
    if isinstance(payload, str):
        строки = [с for с in payload.splitlines() if с.strip()]
        for строка in строки:
            совпало = СТОРОНА.match(строка)
            if совпало:
                сырые.append({"speaker": _сторона(совпало.group(1)),
                              "text": совпало.group(2).strip()})
            elif сырые:
                # Продолжение предыдущей реплики: в экспортах чатов длинное
                # сообщение переносится на следующую строку без подписи.
                сырые[-1]["text"] = f"{сырые[-1]['text']} {строка.strip()}".strip()
            else:
                сырые.append({"speaker": "—", "text": строка.strip()})
    elif isinstance(payload, list):
        for кусок in payload:
            if isinstance(кусок, str):
                совпало = СТОРОНА.match(кусок)
                if совпало:
                    сырые.append({"speaker": _сторона(совпало.group(1)),
                                  "text": совпало.group(2).strip()})
                else:
                    сырые.append({"speaker": "—", "text": кусок.strip()})
            elif isinstance(кусок, dict):
                текст = str(кусок.get("text") or кусок.get("message") or "").strip()
                if not текст:
                    continue
                сырые.append({
                    "speaker": _сторона(кусок.get("speaker") or кусок.get("author")
                                        or кусок.get("from") or кусок.get("role")),
                    "text": текст,
                    # Время, если его прислали, сохраняется как есть — но в
                    # показатели не идёт: оно про переписку, а не про речь.
                    "ts": кусок.get("ts") or кусок.get("time") or None})
    else:
        raise ConfigError(
            "Переписку нужно прислать текстом или списком реплик.",
            hint='Например: {"messages": [{"speaker": "клиент", "text": "…"}]}')

    реплики: list[dict[str, Any]] = []
    for номер, кусок in enumerate(сырые):
        if not str(кусок.get("text") or "").strip():
            continue
        # Порядковый номер вместо секунд. Ноль длины — честная пометка «эта
        # реплика не занимала времени»: слой разбора по ней время и не считает.
        реплики.append({"start": float(номер), "end": float(номер),
                        "speaker": кусок["speaker"], "text": кусок["text"],
                        **({"ts": кусок["ts"]} if кусок.get("ts") else {})})
    if not реплики:
        raise ConfigError("В переписке нет ни одной реплики с текстом.")
    return реплики, "\n".join(f"{р['speaker']}: {р['text']}" for р in реплики)


def оператор_среди(реплики: list[dict[str, Any]], подсказка: str = "") -> str:
    """Кто здесь оператор: по подсказке или по названию стороны.

    Без этого скрипт разговора и балл оператора считались бы по клиенту —
    и показывали бы, насколько вежливо клиент здоровается.
    """
    если_сказали = str(подсказка or "").strip()
    стороны = [р["speaker"] for р in реплики]
    if если_сказали and если_сказали in стороны:
        return если_сказали
    for сторона in стороны:
        if сторона.strip().lower() in ОПЕРАТОР:
            return сторона
    # Оператор подписан именем, а клиент — ролью: оператор — другая сторона.
    разные = list(dict.fromkeys(с for с in стороны if с and с != "—"))
    if len(разные) == 2:
        клиенты = [с for с in разные if с.strip().lower() in КЛИЕНТ]
        if len(клиенты) == 1:
            return разные[1] if разные[0] == клиенты[0] else разные[0]
    return ""


def задание(payload: dict[str, Any]) -> dict[str, Any]:
    """Готовит поля задания для переписки: без файла, сразу завершённое."""
    источник = payload.get("messages")
    if источник is None:
        источник = payload.get("text")
    реплики, текст = разобрать(источник)
    канал = str(payload.get("channel") or "chat").strip().lower() or "chat"
    имя = str(payload.get("filename") or "").strip() or (
        f"{канал}-{str(payload.get('external_id') or '').strip() or 'переписка'}")
    return {
        "segments": реплики,
        "text": текст,
        "channel": канал,
        "agent": оператор_среди(реплики, str(payload.get("agent") or "")),
        "filename": имя,
        "known_channel": канал in КАНАЛЫ,
    }
