def _длительность_файла(путь: Path) -> int:
    """Секунды звука в файле — из заголовка, без чтения самого звука.

    Нужна источнику «каталог записей»: у такого звонка длительности нет
    ниоткуда, а ноль выключал бы разом и порог «не брать короче», и
    выдержку — обе проверки написаны как «если длительность известна».

    WAV читается заголовком, остальное — через ffprobe, если он есть.
    Не прочиталось — ноль, и это честнее выдуманного числа.
    """
    if путь.suffix.lower() == ".wav":
        try:
            with wave.open(str(путь), "rb") as файл:
                частота = файл.getframerate() or 1
                return int(файл.getnframes() / частота)
        except (OSError, EOFError, wave.Error, ValueError) as exc:
            # EOFError — это пустой или обрезанный файл: `wave` не находит в
            # нём даже заголовка. Раньше он не ловился и ронял весь заход по
            # станции — один пустой файл в каталоге останавливал забор.
            log.debug("Длительность %s не прочиталась: %s", путь, exc)
            return 0
    try:
        вывод = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "default=nw=1:nk=1", str(путь)],
            capture_output=True, text=True, timeout=10, check=False)
        return int(float(вывод.stdout.strip() or 0))
    except (OSError, ValueError, subprocess.SubprocessError):
        return 0


def _число(настройки: Any, ключ: str, по_умолчанию: float) -> float:
    """Значение настройки с оглядкой на то, что ноль — это значение.

    `float(настройки.get(ключ) or 30)` выглядит безобидно и врёт ровно на
    нуле: в Python ноль ложен, и «выдержка ноль секунд» превращалась в
    тридцать. Каталог объявляет минимум 0 у половины этих параметров и
    объясняет, что он означает, — значит, ноль надо уметь принимать.
    """
    значение = настройки.get(ключ)
    if значение is None or значение == "":
        return float(по_умолчанию)
    try:
        return float(значение)
    except (TypeError, ValueError):
        return float(по_умолчанию)


class Импортёр:
    """Фоновый перенос звонков с ОДНОЙ станции в очередь распознавания."""

    def __init__(self, db: Any, станция: Станция, queue: Any, settings: Any = None):
        self.db = db
        self.станция = станция
        self.settings = settings
        self.queue = queue
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._lock = threading.Lock()
        #: Замок на один заход: фоновый поток и кнопка «Забрать сейчас» не
        #: должны читать журнал с одной позиции одновременно. Общий на
        #: станцию во всём процессе (см. `_замок_станции`).
        self._заход = _замок_станции(станция.id)
        #: Указатель каталога записей — живёт между заходами и обходится
        #: заново по сроку (см. `УказательЗаписей.устарел`).
        self._указатель: УказательЗаписей | None = None
        #: Сколько заходов подряд споткнулись о сбой хранения на звонке (по
        #: ключу звонка) — см. `ПОПЫТОК_НА_ЗВОНОК`.
        self._сбои_звонка: dict[str, int] = {}
        #: Сколько заходов подряд кончились сбоем — первое переподключение
        #: к станции идёт сразу, а не через минуту (см. `_loop`).
        self._сбоев_подряд = 0
        #: Как кончился предыдущий полный сбор: на пределе — значит,
        #: следующий продолжает с той же позиции, а не с начала журнала.
        self._сбор_на_пределе: str = ""
        self.last_error: str | None = None
        self.last_run: float | None = None
        self.imported = 0
        self.skipped = 0
        self.failed = 0
        self._ami: AMIClient | None = None
        #: Чем было открыто соединение: адрес, порт, учётная запись, пароль.
        self._подпись_ami: tuple[str, int, str, str] | None = None
        #: События AMI, прочитанные, но не записанные (база была недоступна):
        #: идут первыми в следующий заход — станция их больше не пришлёт.
        self._непринятые: list[Звонок] = []
        #: Обрыв AMI посреди захода, после которого прочитанное всё же
        #: разобрано: заход удался, но человек должен видеть, что связь рвётся.
        self._обрыв = ""
        #: AMI только что (пере)подключился: события за время разрыва станция
        #: не пришлёт никогда — их дочитываем из журнала CDR, если он задан
        #: (см. `_scan`). Первый заход после запуска — тоже «после разрыва».
        self._дочитать_журнал = True
        #: Последний разрыв связи с AMI: когда оборвалась и когда вернулась.
        self.ami_разрыв: dict[str, Any] = {}
        self._ami_оборвана: float | None = None
        #: Конец журнала CDR, замеченный прошлым заходом (размер, inode).
        self._конец_журнала: tuple[int, int] | None = None
        #: Когда последний раз сверялся каталог записей станции «диалплан».
        self._сверка_была = 0.0
        #: Свод последнего захода — для раздела «АТС».
        self.last_scan: dict[str, Any] = {}
        #: Полный сбор архива: отдельный поток и его ход. Обычный заход
        #: берёт порцию и уходит спать до следующего такта — на архиве в
        #: сорок тысяч звонков это недели. «Собрать всё» идёт подряд, пока
        #: журнал не кончится, и показывает, сколько прошло.
        self.сбор: dict[str, Any] = {}
        self._поток_сбора: threading.Thread | None = None
        #: Позиция чтения журнала — СВОЯ у каждой станции. Общий ключ
        #: означал бы, что вторая станция продолжает читать с того места,
        #: до которого дочитала первая: половина архива не приехала бы
        #: никогда, и понять почему было бы нельзя.
        self._ключ_позиции = f"telephony_cdr_offset:{станция.id}"
        self._ключ_позиции_сбора = f"telephony_cdr_offset_collect:{станция.id}"
        self._ключ_аренды = f"telephony_lease:{станция.id}"
        #: Отпечаток первой строки журнала, прочитанного этим заходом:
        #: (inode, отпечаток) — пишется рядом с позицией.
        self._голова: tuple[int, str] = (0, "")

    @staticmethod
    def _ключ_inode(ключ_позиции: str) -> str:
        """Ключ номера файла журнала рядом с позицией: смещение без него —
        число, не говорящее, в каком файле оно отсчитано."""
        return ключ_позиции.replace("telephony_cdr_offset", "telephony_cdr_inode", 1)

    @staticmethod
    def _ключ_головы(ключ_позиции: str) -> str:
        """Ключ отпечатка первой строки журнала рядом с позицией."""
        return ключ_позиции.replace("telephony_cdr_offset", "telephony_cdr_head", 1)

    def _запомнить_позицию(self, ключ: str, смещение: int, inode: int) -> None:
        """Позиция и файл — одной записью: половина пары хуже, чем ничего.

        Вместе с ними — отпечаток первой строки файла, в котором позиция
        отсчитана (см. `голова_журнала`): по нему видна ротация с
        copytruncate и тогда, когда файл уже перерос запомненное место.
        """
        файл, голова = self._голова
        self.db.set_kv_many({ключ: int(смещение), self._ключ_inode(ключ): int(inode or 0),
                             self._ключ_головы(ключ): голова if inode == файл else ""})

    # --- настройки --------------------------------------------------------

    @property
    def id(self) -> str:                                     # noqa: A003
        return self.станция.id

    @property
    def enabled(self) -> bool:
        return bool(self.станция.enabled)

    @property
    def source(self) -> str:
        return self.станция.source

    def путь(self, поле: str) -> Path | None:
        """Путь станции по имени поля. Поля называются без приставки."""
        имя = поле.replace("telephony_", "")
        return self.станция.путь(имя)

    # --- состояние --------------------------------------------------------

    def status(self, *, for_admin: bool = False,
               owner: Any = None) -> dict[str, Any]:
        with self._lock:
            свод = {
                **self.станция.to_dict(for_admin=for_admin),
                "running": bool(self._thread and self._thread.is_alive()),
                "imported": self.imported,
                "skipped": self.skipped,
                "failed": self.failed,
                "last_run": self.last_run,
                "last_scan": dict(self.last_scan),
                "ami_gap": dict(self.ami_разрыв),
            }
            if for_admin:
                свод["last_error"] = self.last_error
            else:
                # Свод захода и счётчики потока — на всю станцию, а не на
                # владельца: ключу отдела они раскрывали объёмы и причины
                # пропусков чужих отделов, а `held_by` — имя узла и номер
                # процесса сервера. Своё он видит в `calls` (по владельцу).
                for поле in ("imported", "skipped", "failed"):
                    свод.pop(поле, None)
                свод["last_scan"] = ({"at": self.last_scan.get("at")}
                                     if self.last_scan else {})
        try:
            свод["calls"] = self.db.call_counts(owner=owner, station=self.id)
        except Exception as exc:                             # noqa: BLE001
            log.debug("Счётчики звонков не прочитаны: %s", exc)
            свод["calls"] = {}
        return свод

    def проверить_связь(self) -> dict[str, Any]:
        """Достучаться до источника этой станции и сказать, что именно не так.

        «Не работает» — не диагноз. Проверка отвечает по-разному на «порт
        закрыт», «пароль не тот», «файла нет» и «файл есть, но в нём ноль
        строк»: каждое из этих состояний чинится по-своему.
        """
        начало = time.perf_counter()
        станция = self.станция
        если_мс = lambda: round((time.perf_counter() - начало) * 1000, 1)  # noqa: E731
        if станция.source == "ami":
            итог = проверить(станция.host or "127.0.0.1", станция.port or 5038,
                             станция.username, станция.secret,
                             tls=bool(getattr(станция, "tls", False)),
                             ca_file=str(getattr(станция, "ca_file", "") or ""),
                             auth=str(getattr(станция, "auth", "") or "plain"))
            итог.update({"source": "ami", "station": станция.id})
            return итог
        if станция.source == "dialplan":
            # Ходить некуда: звонки присылает сама станция. Проверяется то,
            # что от сервера зависит, — каталог для приёма путём (если он
            # задан) — и показывается, приходило ли что-нибудь вообще.
            from .dialplan import журнал as журнал_приёма  # noqa: PLC0415

            каталог = станция.путь("recordings_dir")
            if каталог is not None and not каталог.is_dir():
                raise ConfigError(
                    f"«{станция.name}»: каталог записей не найден.",
                    hint="Каталог нужен только для приёма путём к файлу на общем "
                         "диске. Если записи присылаются файлом — оставьте поле "
                         "пустым.")
            свод = журнал_приёма.свод(станция.id)
            return {"ok": True, "source": "dialplan", "station": станция.id,
                    "dir": str(каталог) if каталог else "",
                    "requests": int(свод.get("requests") or 0),
                    "last_at": свод.get("last_at"),
                    "last_error": свод.get("last_error"),
                    "ms": если_мс()}
        if станция.source == "folder":
            каталог = станция.путь("recordings_dir")
            if каталог is None or not каталог.is_dir():
                raise ConfigError(
                    f"«{станция.name}»: каталог записей не найден.",
                    hint="Проверьте путь и права на чтение у пользователя, "
                         "от которого работает сервер.")
            файлов = sum(1 for п in каталог.rglob("*") if _запись_ли(п))
            return {"ok": True, "source": "folder", "station": станция.id,
                    "dir": str(каталог), "files": файлов, "ms": если_мс()}
        журнал = станция.путь("cdr_file")
        if журнал is None or not журнал.is_file():
            raise ConfigError(
                f"«{станция.name}»: журнал звонков не найден.",
                hint="Обычно это /var/log/asterisk/cdr-csv/Master.csv; "
                     "нужен доступ на чтение.")
        размер = журнал.stat().st_size
        # Читаем хвост, а не начало: журнал бывает в гигабайт, а вопрос
        # проверки — «разбирается ли то, что станция пишет сейчас».
        with журнал.open("rb") as файл:
            файл.seek(max(0, размер - 65536))
            строки = [с for с in файл.read().decode("utf-8", "replace").splitlines()
                      if с.strip()]
        образцы = [z for z in (разобрать_cdr_строку(с, пояс=станция.пояс)
                               for с in строки[-5:]) if z]
        return {
            "ok": True, "source": "cdr_csv", "station": станция.id,
            "file": str(журнал), "bytes": размер,
            "offset": int(self.db.get_kv(self._ключ_позиции, 0) or 0),
            "lines": len(строки),
            "sample": [{"uniqueid": z.uniqueid, "src": z.src, "dst": z.dst,
                        "disposition": z.disposition, "billsec": z.billsec,
                        "direction": направление(
                            z, внутренние_знаков=станция.internal_digits,
                            контексты=станция.contexts),
                        "started_at": z.started_at} for z in образцы],
            "ms": если_мс(),
        }

    # --- поток ------------------------------------------------------------

    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            self._stop.clear()
            return
        self._stop.clear()
        self._thread = threading.Thread(target=self._loop,
                                        name=f"asrhub-pbx-{self.станция.id}"[:15],
                                        daemon=True)
        self._thread.start()

    def stop(self, timeout: float = 5.0) -> None:
        self._stop.set()
        поток = self._thread
        if поток and поток.is_alive():
            поток.join(timeout=timeout)
            if поток.is_alive():
                log.warning("Поток телефонии ещё занят; завершится сам.")
                return
        self._thread = None
        self._закрыть_ami()
        # Аренду отдаём сразу: соседний сервер на общей базе иначе ждал бы
        # её истечения, хотя станцию уже никто не обслуживает. Но только
        # если прямо сейчас по станции не идёт заход: аренда общая на
        # процесс, и новый импортёр той же станции (правка полей) мог уже
        # начать свой.
        if self._заход.acquire(blocking=False):
            try:
                self.db.lease_release(self._ключ_аренды, INSTANCE_ID)
            except Exception as exc:                         # noqa: BLE001
                log.debug("Аренда станции «%s» не отдана: %s", self.id, exc)
            finally:
                self._заход.release()

    def _забор_включён(self) -> bool:
        """Общий выключатель телефонии — проверяется и самим потоком.

        Правка через PUT /api/settings не проходит через раздел «АТС», и
        поток, заведённый до выключения, продолжал ходить на станцию и
        ставить задания. Набор потоков сводит `Телефония` (см. её сверку),
        а этот признак — страховка на время до сверки.
        """
        получить = getattr(self.settings, "get", None)
        if получить is None:
            return True
        try:
            return bool(получить("telephony_enabled", True))
        except Exception:                                    # noqa: BLE001
            return True

    def _loop(self) -> None:
        пауза = 2.0
        while not self._stop.wait(timeout=пауза):
            if not self.enabled or not self._забор_включён():
                пауза = 30.0
                continue
            try:
                итог = self.scan()
                self._сбоев_подряд = 0
                пауза = max(5.0, float(self.станция.poll_s or 60))
                if итог.get("backpressure"):
                    # Очередь полна — ждать полный интервал: чаще бессмысленно.
                    pass
                elif итог.get("full"):
                    # Порция набрана целиком — значит, в журнале есть ещё:
                    # первое подключение к длинному журналу иначе шло по
                    # пятьдесят звонков раз в poll_s, и до сегодняшних
                    # разговоров добиралось через сутки.
                    пауза = 1.0
                elif итог.get("imported"):
                    # Есть что везти — заходим чаще: живой поток звонков
                    # не должен ждать полного интервала.
                    пауза = 5.0
            except Exception as exc:                         # noqa: BLE001
                with self._lock:
                    self.last_error = str(exc)
                    self.failed += 1
                log.warning("Заход «%s» не удался: %s", self.станция.name, exc)
                # Первая попытка после сбоя — почти сразу: обрыв AMI
                # (перезапуск Asterisk, «manager reload») чаще всего лечится
                # первым же переподключением, а минута ожидания — это
                # минута звонков, которые станция за это время не пришлёт.
                self._сбоев_подряд += 1
                пауза = 2.0 if self._сбоев_подряд == 1 else ПАУЗА_СБОЯ

    # --- один заход -------------------------------------------------------

    def scan(self, *, limit: int = ПОРЦИЯ, всё: bool = False,
             окно: tuple[float, float] | None = None) -> dict[str, Any]:
        """Один заход: взять новые звонки и поставить задания.

        Заходы не идут вдвоём: кнопка «Забрать сейчас» и фоновый поток
        иначе прочитали бы журнал с одной и той же позиции и разобрали бы
        одни и те же звонки дважды. Дублей заданий это не даёт — от них
        держит первичный ключ таблицы, — но заход впустую и путаница в
        счётчиках получаются на ровном месте.

        `всё` — читать журнал с начала, а каталог записей без оглядки на
        глубину просмотра. `окно` — брать только звонки, начавшиеся в
        заданном промежутке; остальные пропускаются молча и не помечаются
        в архиве, иначе «собрать за март» закрыл бы дорогу апрелю.
        """
        with self._заход:
            чужой = self.db.lease_take(
                self._ключ_аренды, INSTANCE_ID,
                max(АРЕНДА_С, 3.0 * float(self.станция.poll_s or 60)))
            if чужой:
                # Станцию ведёт соседний сервер на общей базе. Это не сбой,
                # а раскладка: заход вдвоём задвоил бы задания.
                свод = {"station": self.станция.id, "name": self.станция.name,
                        "seen": 0, "imported": 0, "skipped": 0, "reasons": {},
                        "outside": 0, "deferred": 0, "at": time.time(),
                        "held_by": чужой}
                with self._lock:
                    self.last_scan = свод
                return свод
            # Указатель каталога записей живёт между заходами: обход каталога
            # раньше шёл на каждый звонок порции, а потом — на каждый заход,
            # и при живом потоке и сборе архива импортёр почти всё время
            # обходил каталог. Теперь — по сроку (`УказательЗаписей.устарел`),
            # а промах по свежему звонку пересобирает его и так.
            if self._указатель is not None and self._указатель.устарел():
                self._указатель = None
            итог = self._scan(limit=limit, всё=всё, окно=окно)
            self._очереди()
            return итог

    def _очереди(self) -> int:
        """Приращение журнала очередей станции (`queue_log`), если он задан."""
        путь = self.станция.путь("queue_log") if hasattr(self.станция, "queue_log") else None
        if путь is None or not путь.is_file():
            return 0
        from . import queue_log as журнал_очередей  # noqa: PLC0415

        ключ = f"telephony:queue_log:{self.id}"
        место = self.db.get_kv(ключ) or {}
        try:
            события, позиция, inode = журнал_очередей.прочитать_приращение(
                путь, int(место.get("offset") or 0), int(место.get("inode") or 0))
        except OSError as exc:
            log.warning("Станция «%s»: журнал очередей %s не читается: %s",
                        self.станция.name, путь, exc)
            return 0
        добавлено = self.db.queue_events_add(self.id, события)
        self.db.set_kv(ключ, {"offset": позиция, "inode": inode, "at": time.time()})
        return добавлено

    def _каталог_указатель(self, каталог: Path) -> УказательЗаписей:
        if self._указатель is None or self._указатель.каталог != каталог:
            self._указатель = УказательЗаписей(каталог)
        return self._указатель

    def _место_в_очереди(self) -> int | None:
        """Сколько ещё заданий примет очередь; None — неизвестно.

        Порция захода не больше этого: брать из журнала то, что очередь всё
        равно не примет, значит сдвигать позицию впустую.
        """
        предел = getattr(self.queue, "_max_queue", None)
        if not isinstance(предел, int) or isinstance(предел, bool):
            return None
        try:
            занято = int(self.db.count_jobs(status=["queued", "retry"]))
        except Exception:                                    # noqa: BLE001
            return None
        return предел - занято

    def _scan(self, *, limit: int = ПОРЦИЯ, всё: bool = False,
              окно: tuple[float, float] | None = None) -> dict[str, Any]:
        # Сначала отложенные: звонки, которые в прошлый заход ещё писались
        # или не влезли в очередь. Из журнала они больше не придут — позиция
        # чтения сдвинута, событие AMI разовое, — поэтому очередь отложенных
        # разбирается раньше новых и своей долей порции.
        # Только свои и только те, у которых ещё есть шанс: запись, не
        # появившаяся за срок хранения отложенных, не появится уже никогда.
        # Такие переводятся в окончательный пропуск с причиной — раньше они
        # оставались «отложенными» навсегда, а срок считался от последнего
        # откладывания, которое каждый заход обновлял: безнадёжный звонок
        # крутился по кругу вечно и тратил на себя каждый заход. Отложенные
        # из-за очереди срока не имеют: запись у них на месте, ждут они
        # места в очереди (см. `Database.ОТЛОЖЕН_БЕССРОЧНО`).
        порог = time.time() - СРОК_ОТЛОЖЕННЫХ
        просрочено = self.db.calls_expire_deferred(station=self.id, older_than=порог)
        if просрочено:
            log.info("Станция «%s»: %d звонков не дождались записи за сутки — "
                     "отмечены пропущенными", self.станция.name, просрочено)
        источник = self.source
        if источник != "ami" and self._ami is not None:
            # Источник переключили — соединение больше не нужно. Без этой
            # строки сокет и сессия на станции держались до перезапуска.
            self._закрыть_ami()
        # Обратное давление: из журнала берётся не больше, чем примет
        # очередь. Полная очередь — журнал не читается вовсе, позиция стоит;
        # события AMI читаются всё равно — они разовые и копятся на станции.
        место = self._место_в_очереди()
        if место is not None and место <= 0 and источник != "ami":
            свод = {"station": self.станция.id, "name": self.станция.name,
                    "seen": 0, "imported": 0, "skipped": 0, "reasons": {},
                    "outside": 0, "deferred": 0, "fresh": 0, "full": False,
                    "backpressure": True, "at": time.time()}
            with self._lock:
                self.last_run = time.time()
                self.last_scan = свод
            return свод
        if место is not None and место > 0:
            limit = max(1, min(limit, место))
        отложенные = [Звонок.из_записи(з) for з in self.db.calls_deferred(
            limit=max(1, limit // 2), station=self.id, older_than=порог)]
        # Сбор за период читает журнал своей позицией: общую трогать нельзя.
        ключ = self._ключ_позиции_сбора if окно is not None else self._ключ_позиции
        позиция_после: int | None = None
        inode_после = 0
        старше: dict[str, int] = {}
        if источник == "ami":
            придержанные, self._непринятые = self._непринятые, []
            try:
                новые = [*придержанные, *self._из_ami(limit)]
            except BaseException:
                self._непринятые = придержанные + self._непринятые
                raise
            # AMI не хранит событий: всё, что завершилось, пока связи не
            # было (перезапуск сервера, обрыв сети), станция не пришлёт
            # никогда. Если у станции задан журнал CDR, после каждого
            # (пере)подключения он дочитывается с позиции до конца — ключ
            # архива тот же, «станция:uniqueid», и звонок, пришедший обоими
            # путями, не задвоится.
            if self._журнал_дозабора() is not None and окно is None:
                if self._дочитать_журнал:
                    из_журнала, позиция_после, inode_после = self._из_csv(
                        limit, ключ=ключ, сводка=старше)
                    новые = [*новые, *из_журнала]
                    if len(из_журнала) < limit:
                        self._дочитать_журнал = False
                        self._конец_журнала = None
                elif len(новые) < limit:
                    # Связь цела и события разобраны: всё, что журнал успел
                    # записать, пришло событиями. Позиция журнала встаёт в
                    # конец — следующий дочит после разрыва начнётся с места
                    # разрыва, а не с прошлого дочита.
                    self._журнал_в_конец(ключ)
        elif источник == "folder":
            новые = self._из_папки(limit, всё=всё)
        elif источник == "dialplan":
            # Звонки этой станции присылает сам диалплан (POST
            # /api/telephony/dialplan/call). Заход нужен отложенным — записям
            # на общем диске, которые в момент обращения ещё писались, — и
            # сверке каталога записей: CURL() не повторяет обращение, и
            # звонок, на отбое которого сервер был недоступен, иначе не
            # пришёл бы никогда (см. `_сверка_каталога`).
            новые = self._сверка_каталога(limit) if окно is None else []
        else:
            новые, позиция_после, inode_после = self._из_csv(
                limit, всё=всё or окно is not None, ключ=ключ, сводка=старше)
        свежих = len(новые)
        # Строки одного звонка (Asterisk 12+ пишет их по одной на каждый
        # Dial, попытку очереди, перевод) — одним звонком, см. `свести_ноги`.
        новые = свести_ноги(новые)
        было_отложено = {з.uniqueid for з in отложенные}
        # Тот же звонок мог прийти и из очереди отложенных, и из журнала,
        # который читается с начала («собрать всё», «забыть позицию»). Обе
        # копии считались отложенными и обе проходили мимо `call_exists` —
        # одна запись уезжала в распознавание двумя заданиями, а в архиве
        # оставалась одна строка со ссылкой на второе: первое становилось
        # сиротой. Копии сводятся в одну: из журнала могла прийти и новая
        # нога звонка, которая раньше молча выбрасывалась.
        звонки = list(отложенные)
        место_в_списке = {з.uniqueid: н for н, з in enumerate(звонки)}
        for звонок in новые:
            н = место_в_списке.get(звонок.uniqueid) if звонок.uniqueid else None
            if н is None:
                звонки.append(звонок)
            else:
                звонки[н] = свести([звонки[н], звонок])

        # Порядок — по месту в журнале: отложенный звонок, сведённый с новой
        # строкой, получает позицию этой строки, и стоял он в начале списка.
        # Позиция журнала уходила за него вперёд, и строки перед ней, ещё не
        # разобранные, при прерванном заходе больше не читались. Звонки без
        # места в журнале (только отложенные) — первыми, как и были.
        звонки.sort(key=lambda з: (з.конец_строки >= 0, з.конец_строки))
        поставлено, пропущено, вне_окна = 0, 0, 0
        причины: dict[str, int] = {}
        прервано = ""
        for номер, звонок in enumerate(звонки):
            # Один плохой звонок не должен уносить всю порцию. Позиция
            # чтения журнала уже сдвинута, и необработанный остаток не
            # придёт больше никогда: исключение здесь означало бы тихую
            # потерю сорока девяти разговоров из-за одного.
            if окно is not None and звонок.started_at:
                # Вне запрошенного промежутка — молча мимо: пометка в
                # архиве закрыла бы звонку дорогу при следующем сборе.
                if not (окно[0] <= звонок.started_at <= окно[1]):
                    вне_окна += 1
                    if звонок.конец_строки >= 0 and позиция_после is not None:
                        self._запомнить_позицию(ключ, звонок.конец_строки,
                                                звонок.inode_журнала)
                    continue
            try:
                почему = self._взять(
                    звонок, отложенный=звонок.uniqueid in было_отложено, всё=всё)
                self._сбои_звонка.pop(self._ключ(звонок), None)
            except ОчередьОтказала:
                # Звонок уже отложен; остаток — не трогаем (журнал), а
                # разовые события AMI — откладываем, иначе их не будет нигде.
                пропущено += 1
                причины["очередь отказала"] = причины.get("очередь отказала", 0) + 1
                if звонок.конец_строки >= 0 and позиция_после is not None:
                    self._запомнить_позицию(ключ, звонок.конец_строки,
                                            звонок.inode_журнала)
                прервано = "очередь отказала"
                self._отложить_разовые(звонки[номер + 1:], было_отложено,
                                       "очередь отказала")
                break
            except _СБОИ_ХРАНЕНИЯ as exc:
                if self._сбой_хранения(звонок, exc):
                    почему = "сбой разбора"
                else:
                    прервано = f"сбой хранения: {exc}"
                    self._придержать_разовые(звонки[номер:], было_отложено)
                    break
            except Exception as exc:                         # noqa: BLE001
                log.warning("Звонок %s не разобран: %s", звонок.uniqueid, exc)
                with self._lock:
                    self.failed += 1
                    self.last_error = f"звонок {звонок.uniqueid}: {exc}"
                # Строки в архиве такой звонок не получает намеренно: после
                # исправления «Забыть позицию» поднимет его заново, а
                # строка с пометкой закрыла бы ему дорогу («уже импортирован»).
                почему = "сбой разбора"
            if почему is None:
                поставлено += 1
            else:
                пропущено += 1
                причины[почему] = причины.get(почему, 0) + 1
            # Позиция журнала — за каждым обработанным звонком, а не за всей
            # порцией до обработки: перезапуск посреди захода (на звонок
            # уходит 0,4 с проверки роста файла, и порция из пятидесяти —
            # это двадцать секунд, а остановка ждёт поток пять) терял
            # необработанный остаток навсегда.
            if звонок.конец_строки >= 0 and позиция_после is not None:
                self._запомнить_позицию(ключ, звонок.конец_строки,
                                        звонок.inode_журнала)
        if позиция_после is not None and not прервано:
            # Порция пройдена целиком — позиция встаёт за последнюю
            # прочитанную строку, включая строки без звонка в хвосте.
            self._запомнить_позицию(ключ, позиция_после, inode_после)
        if старше.get("старше"):
            # Старше глубины просмотра — мимо без поиска записи и без пометки
            # в архиве: «Собрать весь архив» поднимет их, если они нужны.
            пропущено += старше["старше"]
            причины["старше глубины просмотра"] = старше["старше"]
        with self._lock:
            self.imported += поставлено
            self.skipped += пропущено
            self.last_run = time.time()
            if прервано.startswith("сбой хранения"):
                self.failed += 1
                self.last_error = прервано
            elif self._обрыв:
                self.last_error = self._обрыв
            elif поставлено or пропущено:
                self.last_error = None
            self._обрыв = ""
        if поставлено:
            log.info("Телефония: поставлено заданий %d, пропущено %d %s",
                     поставлено, пропущено, причины or "")
        if прервано:
            log.warning("Станция «%s»: заход прерван (%s) — остаток журнала "
                        "придёт следующим заходом", self.станция.name, прервано)
        свод = {"station": self.станция.id, "name": self.станция.name,
                "seen": len(звонки), "imported": поставлено,
                "skipped": пропущено, "reasons": причины,
                "outside": вне_окна,
                "deferred": len(отложенные), "fresh": свежих,
                "full": свежих >= limit and not прервано,
                "backpressure": прервано == "очередь отказала",
                "interrupted": прервано, "at": time.time()}
        with self._lock:
            self.last_scan = свод
        return свод

    def _сбой_хранения(self, звонок: Звонок, exc: BaseException) -> bool:
        """Сбой хранения на звонке; True — пора пропустить звонок насовсем.

        Сбой базы или диска — повод прервать заход, не сдвигая позицию:
        звонки дождутся следующего захода. Но если о тот же звонок
        спотыкаются заход за заходом, дело в нём самом, а не в базе — и
        стоять перед всем остальным журналом вечно он не должен.
        """
        ключ = self._ключ(звонок) or звонок.uniqueid
        try:
            # База пишется вообще? Если нет — это общий сбой, и звонок тут
            # ни при чём: считать ему попытки значило бы списать за час
            # простоя базы по звонку на каждые три захода.
            self.db.set_kv(f"telephony_probe:{self.id}", time.time())
        except Exception:                                    # noqa: BLE001
            log.warning("Звонок %s: база недоступна на запись (%s) — заход "
                        "прерван, позиция журнала стоит", звонок.uniqueid, exc)
            return False
        раз = self._сбои_звонка.get(ключ, 0) + 1
        self._сбои_звонка[ключ] = раз
        log.warning("Звонок %s: сбой хранения (%d-й раз подряд): %s",
                    звонок.uniqueid, раз, exc)
        if раз < ПОПЫТОК_НА_ЗВОНОК:
            return False
        self._сбои_звонка.pop(ключ, None)
        with self._lock:
            self.failed += 1
            self.last_error = f"звонок {звонок.uniqueid}: {exc}"
        return True

    def _отложить_разовые(self, остаток: list[Звонок], было_отложено: set[str],
                          почему: str) -> None:
        """События AMI из прерванного захода — в отложенные.

        Строки журнала придут снова (позиция стоит перед ними), файлы каталога
        тоже, а событие AMI станция больше не пришлёт.
        """
        for звонок in остаток:
            if not self._разовый(звонок, было_отложено):
                continue
            try:
                self._отложить(звонок, почему)
            except _СБОИ_ХРАНЕНИЯ:
                self._придержать_разовые([звонок], было_отложено)

    def _придержать_разовые(self, остаток: list[Звонок], было_отложено: set[str]) -> None:
        """События AMI, которые некуда записать (база недоступна), — в памяти
        до следующего захода: событие разовое, и позиции, которая вернула бы
        его, у AMI нет."""
        for звонок in остаток:
            if self._разовый(звонок, было_отложено):
                self._непринятые.append(звонок)

    def _разовый(self, звонок: Звонок, было_отложено: set[str]) -> bool:
        return (self.source == "ami" and звонок.конец_строки < 0
                and звонок.uniqueid not in было_отложено
                and not звонок.uniqueid.startswith("file:"))

