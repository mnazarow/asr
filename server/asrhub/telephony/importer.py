    def _отложить(self, звонок: Звонок, почему: str) -> str:
        """Кладёт звонок в таблицу с пометкой «взять позже».

        Из журнала он больше не придёт: позиция чтения сдвигается сразу
        после чтения строки, а событие AMI вообще разовое. Раньше такой
        звонок просто терялся — и при выдержке в тридцать секунд с опросом
        раз в минуту под это попадала половина потока: за час импортёр
        ставил 289 заданий и терял 311.
        """
        # Владелец нужен и пропущенным: без него карточка «Пропущено» у
        # ключа подразделения вечный ноль, а причины пусты — то есть
        # единственное, что объясняет расхождение архива со станцией, не
        # видно тому, кто с архивом и работает.
        self.db.save_call(self._ключ(звонок), job_id=None,
                          skipped=f"{self.db.ОТЛОЖЕН}{почему}",
                          owner=self._владелец(звонок), station=self.id, **звонок.поля_записи())
        return почему

    def _ключ(self, звонок: Звонок) -> str:
        """Ключ звонка в архиве: станция плюс её идентификатор звонка.

        У Asterisk `uniqueid` уникален только внутри одной АТС — это
        «эпоха.счётчик», где счётчик локален станции и сбрасывается при её
        перезапуске. Две станции в одну секунду дают одинаковый
        идентификатор, и второй звонок молча выбрасывался как «уже
        импортирован». Настоящий идентификатор при этом никуда не девается:
        он едет в колонке `pbx_uid`.
        """
        if not звонок.uniqueid:
            return ""
        return f"{self.id}:{звонок.uniqueid}" if self.id else звонок.uniqueid

    def _с_архивом(self, звонок: Звонок, прежний: dict[str, Any], *,
                   всё: bool = False) -> tuple[str | None, Звонок, bool]:
        """Звонок, который архив уже знает: повтор, новая нога или отложенный.

        Возвращает причину пропуска (None — разбирать дальше), звонок для
        разбора и признак «был отложен». Раньше любой известный ключ давал
        «уже импортирован», и у звонка из нескольких строк CDR (Asterisk 12+
        пишет строку на каждый Dial, попытку очереди, перевод) отвечённая нога
        выбрасывалась: «101 не ответил» ложился пропущенным «без ответа», а
        пять минут разговора с 102 не распознавались никогда.

        * Отложенный — разбирается сейчас, сведённым с пришедшей ногой.
        * С заданием — новая нога лучше прежней (`нога_лучше`): поля строки
          обновляются (кто ответил, сколько говорили), задание остаётся.
        * Пропущенный без задания — новая нога лучше: разбирается заново
          целиком. «Собрать весь архив» перепроверяет и «нет записи»: запись
          могла появиться позже.
        """
        пометка = str(прежний.get("skipped") or "")
        старый = Звонок.из_записи(прежний)
        if пометка.startswith(self.db.ОТЛОЖЕН):
            return None, свести([старый, звонок]), True
        лучше = нога_лучше(звонок, старый)
        if прежний.get("job_id"):
            if not лучше:
                return "уже импортирован", звонок, False
            сводный = свести([старый, звонок])
            разметить(сводный, внутренние_знаков=self.станция.internal_digits,
                      контексты=self.станция.contexts)
            сводный.recording = старый.recording or сводный.recording
            # Владелец не трогается: он уже у задания, и разойтись с ним
            # строке звонка незачем (`owner=None` прежнего не затирает).
            self.db.save_call(self._ключ(звонок), job_id=None, skipped=пометка,
                              owner=None, station=self.id, **сводный.поля_записи())
            return "ещё нога звонка", звонок, False
        перепроверить = всё and any(пометка == п or (п.endswith(": ") and пометка.startswith(п))
                                    for п in ПЕРЕПРОВЕРЯТЬ)
        if лучше or перепроверить:
            return None, свести([старый, звонок]), False
        return "уже импортирован", звонок, False

    def _взять(self, звонок: Звонок, *, отложенный: bool = False,
               всё: bool = False, готов: bool = False,
               разметка: bool = True) -> str | None:
        """Ставит задание по звонку; возвращает причину пропуска или None.

        Отказ очереди — `ОчередьОтказала` (звонок к тому мигу отложен), сбой
        базы — исключение хранения: заход прекращается, позиция журнала
        остаётся перед необработанным (см. `_scan`).

        `готов` — запись заведомо закрыта: её прислали файлом или сказали
        «MixMonitor закончил» (приём из диалплана). Тогда выдержка и замер
        роста не нужны: они отвечают на вопрос «дописан ли файл», а ответ
        уже известен. Пустой файл и тогда — окончательный пропуск.

        `разметка=False` — направление, добавочный и очередь уже названы
        (их прислал диалплан: он знает, кто ответил в очереди), и
        перевычислять их по номерам незачем.
        """
        if not звонок.uniqueid:
            return "без идентификатора"
        ключ = self._ключ(звонок)
        if not отложенный:
            прежний = self.db.call_get(ключ)
            if прежний is not None:
                почему, звонок, отложенный = self._с_архивом(звонок, прежний, всё=всё)
                if почему is not None:
                    return почему
        if отложенный and звонок.uniqueid.startswith("file:") and звонок.recording:
            # Звонок из каталога записей вернулся из отложенных — с той
            # длительностью, что была, когда файл ещё писался (у WAV в это
            # время в заголовке нули). Перечитываем её из файла.
            self._освежить_из_файла(звонок)
        # Направление, оператор и очередь — до первого сохранения: и у
        # пропущенных, и у отложенных (см. `разметить`). Кроме звонков из
        # диалплана: их поля названы самой станцией, в том числе у
        # отложенных, которые дозабирает поток станции с источником dialplan.
        if разметка and self.source != "dialplan":
            разметить(звонок, внутренние_знаков=self.станция.internal_digits,
                      контексты=self.станция.contexts)

        минимум = int(self.станция.min_duration_s or 0)
        длительность = звонок.billsec or звонок.duration
        if минимум and длительность and длительность < минимум:
            self.db.save_call(ключ, job_id=None, skipped="короткий",
                              owner=self._владелец(звонок), station=self.id, **звонок.поля_записи())
            return "короткий"
        if bool(self.станция.skip_unanswered) and звонок.disposition \
                and not звонок.answered:
            self.db.save_call(ключ, job_id=None, skipped="без ответа",
                              owner=self._владелец(звонок), station=self.id, **звонок.поля_записи())
            return "без ответа"

        выдержка = float(self.станция.settle_s or 0)
        # Конец разговора — по полной длительности, а не по разговорной:
        # `billsec` не считает гудки, и разговор «минута дозвона, десять
        # секунд разговора» выглядел законченным пятьдесят секунд назад,
        # хотя MixMonitor закрыл файл только что.
        полная = звонок.duration or звонок.billsec
        конец = звонок.started_at + полная if звонок.started_at and полная else 0.0
        if not готов and конец and time.time() - конец < выдержка:
            return self._отложить(звонок, "ещё пишется")

        путь = Path(звонок.recording) if звонок.recording else None
        if путь is None:
            каталог = self.станция.путь("recordings_dir")
            if каталог is None and self.source == "dialplan":
                # Диалплан не прислал ни файла, ни пути, а искать негде:
                # ждать тут нечего, запись уже не появится.
                self.db.save_call(ключ, job_id=None, skipped="нет записи",
                                  owner=self._владелец(звонок), station=self.id,
                                  **звонок.поля_записи())
                return "нет записи"
            if каталог is None:
                return self._отложить(звонок, "не задан каталог записей")
            путь = найти_запись(звонок, каталог, шаблон=self.станция.filename,
                                окно_дней=int(self.станция.lookback_days or 7),
                                окно_минут=int(self.станция.match_window or 0),
                                пояс=self.станция.пояс,
                                указатель=self._каталог_указатель(каталог),
                                занят=lambda п: self.db.call_has_recording(
                                    str(п), station=self.id, кроме=ключ))
        if путь is not None and путь.is_file():
            if готов:
                try:
                    почему = "" if путь.stat().st_size > 0 else "пустая запись"
                except OSError:
                    почему = "файл записи не читается"
            else:
                почему = self._файл_не_готов(путь, выдержка)
            if почему == "пустая запись":
                self.db.save_call(ключ, job_id=None, skipped=почему,
                                  owner=self._владелец(звонок), station=self.id,
                                  **звонок.поля_записи())
                return почему
            if почему:
                return self._отложить(звонок, почему)
        if путь is None or not путь.is_file():
            if not готов and выдержка > 0 and конец and time.time() - конец < ПОЗДНЯЯ_ЗАПИСЬ_С:
                # Свежему звонку запись ещё может приехать (rsync раз в пять
                # минут, перекодирование после разговора), а «нет записи»
                # окончательно — подождём десять минут от конца разговора.
                return self._отложить(звонок, "записи ещё нет")
            # Файла может не быть законно: запись не велась. Отмечаем, чтобы
            # не искать его на каждом заходе до скончания века.
            self.db.save_call(ключ, job_id=None, skipped="нет записи",
                              owner=self._владелец(звонок), station=self.id, **звонок.поля_записи())
            return "нет записи"

        звонок.recording = str(путь)
        владелец = self._владелец(звонок)
        метки = ",".join(м for м in (
            "АТС", self.станция.name, звонок.direction or "",
            f"очередь {звонок.queue}" if звонок.queue else "",
            self.станция.tags,
        ) if м)
        # Строка звонка — ДО задания, а задание дописывается в неё после.
        # Наоборот сбой базы между двумя шагами оставлял задание-сироту без
        # строки в журнале звонков; а если база недоступна вовсе, заход
        # кончается здесь, и задание не заводится.
        self.db.save_call(ключ, job_id=None, skipped=f"{self.db.ОТЛОЖЕН}ставится в очередь",
                          owner=владелец, station=self.id, **звонок.поля_записи())
        try:
            файл, временный = self._подготовить_запись(путь)
        except (ASRHubError, OSError, subprocess.SubprocessError) as exc:
            почему = f"запись не читается: {getattr(exc, 'message', None) or exc}"[:200]
            log.warning("Звонок %s: %s", звонок.uniqueid, почему)
            self.db.save_call(ключ, job_id=None, skipped=почему, owner=владелец,
                              station=self.id, **звонок.поля_записи())
            return почему
        try:
            задание = self.queue.submit(
                file_path=файл, filename=путь.name,
                settings=(self.settings.merged({}) if self.settings is not None else {}),
                owner=владелец, api_key_name="telephony",
                priority=int(self.станция.priority or 40),
                source="asterisk", tags=метки)
        except Exception as exc:                             # noqa: BLE001
            if временный:
                файл.unlink(missing_ok=True)
            with self._lock:
                self.failed += 1
                self.last_error = str(exc)
            log.warning("Звонок %s не поставлен в очередь: %s", звонок.uniqueid, exc)
            if self._очередь_полна(exc):
                # Очередь полна или кончился диск — состояние временное.
                # Звонок ждёт без срока, а заход кончается здесь: читать
                # журнал дальше значило бы откладывать всё подряд.
                self._отложить(звонок, "очередь отказала")
                raise ОчередьОтказала(str(exc)) from exc
            # Отказ из-за самого звонка (файл не читается, запись не той
            # природы) — отложить на срок и идти дальше: такой звонок не
            # должен стоять перед всем журналом.
            return self._отложить(звонок, f"не поставлено в очередь: {exc}"[:200])
        try:
            self.db.save_call(ключ, job_id=задание.get("id"), skipped="",
                              owner=владелец, station=self.id, **звонок.поля_записи())
        except _СБОИ_ХРАНЕНИЯ:
            # Строка есть (отложенная «ставится в очередь»), а задание к ней
            # не привязалось — снимаем его, иначе следующий заход поставит
            # второе, а первое останется сиротой.
            try:
                self.queue.cancel(str(задание.get("id") or ""), by="telephony")
            except Exception as сбой:                        # noqa: BLE001
                log.warning("Задание %s не снято после сбоя базы: %s",
                            задание.get("id"), сбой)
            raise
        return None

    @staticmethod
    def _очередь_полна(exc: BaseException) -> bool:
        """Отказ очереди — из-за её состояния, а не из-за звонка.

        Из-за звонка — то, что очередь объяснила про сам файл (не читается,
        не звук, не тот формат): такой звонок не должен стоять перед всем
        журналом. Всё прочее — переполнение, диск, неожиданный сбой — считается
        состоянием очереди: звонок ждёт, а заход кончается. Ошибиться в эту
        сторону дешевле: звонок не теряется, а приходит следующим заходом.
        """
        if isinstance(exc, (QueueFull, StorageError)):
            return True
        return not isinstance(exc, (OSError, ASRHubError))

    def _каталог_заданий(self) -> Path:
        """Куда класть запись, приведённую к читаемому виду: в загрузки сервера.

        Записи станции очередь не трогает (их «удалять исходник» не удаляет),
        а сведённая или перекодированная копия — файл задания, и живёт она
        там же, где файлы остальных заданий, по тем же правилам уборки.
        """
        пути = getattr(self.settings, "paths", None)
        загрузки = getattr(пути, "uploads", None) if пути is not None else None
        каталог = Path(загрузки) if загрузки else Path(tempfile.gettempdir()) / "asrhub-telephony"
        каталог.mkdir(parents=True, exist_ok=True)
        return каталог

    def _подготовить_запись(self, путь: Path) -> tuple[Path, bool]:
        """Файл для задания: сама запись, а если её так не прочитать — копия.

        Две вещи конвейер сам не умеет. Записи без заголовка (`.alaw`,
        `.ulaw`, `.sln`) ffmpeg без подсказки формата не читает — каждое
        задание с такой записью падало. А Monitor() без сведения пишет две
        дорожки, `…-in` и `…-out`, и в распознавание уходила одна сторона
        разговора. Первое перекодируется в WAV с нужным форматом и частотой,
        второе сводится в стерео — как две дорожки у `/process-call`.
        Возвращает путь и признак «это временная копия».
        """
        пара = пара_дорожек(путь)
        сырой = СЫРЫЕ.get(путь.suffix.lower())
        if пара is None and сырой is None:
            return путь, False
        from ..db import new_id  # noqa: PLC0415
        from ..phone_compat import _merge_to_stereo  # noqa: PLC0415

        каталог = self._каталог_заданий()
        цель = каталог / f"{new_id('pbx')}.wav"
        временные: list[Path] = []
        try:
            if пара is None:
                self._в_wav(путь, цель)
            else:
                стороны = []
                for дорожка in пара:
                    if дорожка.suffix.lower() in СЫРЫЕ:
                        копия = каталог / f"{new_id('pbx')}.wav"
                        временные.append(копия)
                        self._в_wav(дорожка, копия)
                        стороны.append(копия)
                    else:
                        стороны.append(дорожка)
                _merge_to_stereo(стороны[0], стороны[1], цель)
        except BaseException:
            цель.unlink(missing_ok=True)
            raise
        finally:
            for копия in временные:
                копия.unlink(missing_ok=True)
        return цель, True

    @staticmethod
    def _в_wav(путь: Path, цель: Path) -> None:
        """Запись без заголовка — в WAV: формат и частоту ffmpeg подсказываем."""
        формат, частота = СЫРЫЕ[путь.suffix.lower()]
        ffmpeg = shutil.which("ffmpeg")
        if not ffmpeg:
            raise ConfigError("Для записей без заголовка (alaw, ulaw, sln) нужен ffmpeg.")
        итог = subprocess.run(
            [ffmpeg, "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
             "-f", формат, "-ar", str(частота), "-ac", "1", "-i", str(путь), str(цель)],
            capture_output=True, text=True, timeout=600, check=False)
        if итог.returncode != 0 or not цель.exists():
            raise ConfigError(f"ffmpeg не перекодировал {путь.name}: "
                              f"{(итог.stderr or '').strip()[:200]}")

    def _файл_не_готов(self, путь: Path, выдержка: float) -> str:
        """Почему файл записи брать рано; пусто — можно брать.

        Конец записи — это время последнего изменения файла, а не конец
        разговора по журналу. У источника «каталог записей» журнала нет
        вовсе, а у WAV, который ещё пишется, в заголовке нули: длительность
        выходила нулевой, и проверка выдержки («если длительность известна»)
        не выполнялась — оставался только замер роста за 0,4 с, и файл,
        дописываемый рывками, уходил в распознавание обрезанным.

        Замер роста — только для файлов, изменённых недавно: у файла,
        которого не касались десять минут, мерить нечего, а сбор архива в
        сорок тысяч звонков тратил на эти полсекунды четыре с половиной часа.

        Пустой файл — отдельный случай: свежий ещё может наполниться, а
        пустой через десять минут — это запись, которая не велась, и держать
        его в отложенных сутки незачем («пустая запись» — окончательно).
        """
        try:
            сведения = путь.stat()
        except OSError:
            return "файл записи не читается"
        возраст = time.time() - сведения.st_mtime
        if сведения.st_size == 0:
            return "файл ещё пуст" if возраст < ЗАМЕР_РОСТА_ДО_С else "пустая запись"
        if выдержка <= 0:
            return ""
        if возраст < выдержка:
            return "файл ещё пишется"
        if возраст < ЗАМЕР_РОСТА_ДО_С and not self._дописан(путь):
            # Обещано в справке параметра и в шапке модуля: сервер
            # проверяет, что файл перестал расти.
            return "файл ещё растёт"
        return ""

    def _освежить_из_файла(self, звонок: Звонок) -> None:
        """Длительность и время звонка из каталога записей — заново по файлу."""
        путь = Path(звонок.recording)
        try:
            изменён = путь.stat().st_mtime
        except OSError:
            return
        длительность = _длительность_файла(путь)
        звонок.duration = звонок.billsec = длительность
        звонок.started_at = изменён - длительность

    def _дописан(self, путь: Path) -> bool:
        """Перестал ли файл расти — короткая проверка в два замера.

        MixMonitor закрывает запись уже после того, как станция отчиталась
        о звонке, а иногда ещё и перекодирует её. Выдержка по времени
        отвечает на вопрос «наверное, пора», а этот замер — на вопрос
        «точно ли». Полсекунды на звонок, и только для тех, что дошли
        досюда.
        """
        try:
            было = путь.stat().st_size
        except OSError:
            return False
        time.sleep(ПАУЗА_ЗАМЕРА)
        try:
            стало = путь.stat().st_size
        except OSError:
            return False
        return стало == было and стало > 0

    def _владелец(self, звонок: Звонок) -> str:
        """Кому принадлежит запись: по внутреннему номеру или общий.

        Разрез по владельцу — это то, что отделяет отдел от отдела в
        отчётах. Сопоставление «номер → владелец» задаётся настройкой; чего
        в нём нет, достаётся общему владельцу.
        """
        карта = self.станция.owner_map
        for номер in (звонок.agent, звонок.dst, звонок.src):
            if номер and номер in карта:
                return str(карта[номер])
        return self.станция.owner or "telephony"


