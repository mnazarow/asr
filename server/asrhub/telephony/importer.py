    def проверить_набросок(self, данные: dict[str, Any]) -> dict[str, Any]:
        """Проверка связи со станцией, которой ещё нет в настройках.

        Это и есть «проверить при добавлении»: человек заполнил форму и
        хочет знать, доедет ли сервер до станции, ДО того как сохранит
        настройки. Заводить ради этого станцию в настройках и потом убирать
        — способ оставить мусор при первом же закрытии вкладки.
        """
        from .stations import _станция_из  # noqa: PLC0415

        сырые = dict(данные or {})
        набросок = _станция_из(сырые, 0)
        # Форма правки не присылает нетронутый пароль — интерфейс его и не
        # знает, — и проверка существующей AMI-станции шла с пустым паролем:
        # рабочая станция отвечала «АТС отклонила вход». Берём сохранённый,
        # но только для того же адреса, порта и учётной записи: иначе
        # проверкой можно было бы отправить сохранённый пароль на любой
        # узел, указанный в форме.
        ид = str(сырые.get("id") or "").strip()
        if ид and str(сырые.get("secret") or "") in ("", "***"):
            сохранённая = next((с for с in self.станции() if с.id == ид), None)
            if сохранённая is not None and (
                    (сохранённая.host, int(сохранённая.port or 0), сохранённая.username)
                    == (набросок.host, int(набросок.port or 0), набросок.username)):
                набросок.secret = сохранённая.secret
        набросок.id = набросок.id or "проба"
        return Импортёр(self.db, набросок, self.queue, self.settings).проверить_связь()


