    def _из_csv(self, limit: int, *, всё: bool = False, ключ: str = "",
                сводка: dict[str, int] | None = None) -> tuple[list[Звонок], int, int]:
        путь = self.станция.путь("cdr_file")
        if путь is None:
            raise ConfigError(
                f"«{self.станция.name}»: не задан журнал звонков.",
                hint="Обычно это /var/log/asterisk/cdr-csv/Master.csv")
        ключ = ключ or self._ключ_позиции
        # Позиция общая у обычного захода и полного сбора архива; у сбора за
        # период — своя (см. `собрать`). Раньше при `всё=True` она обнулялась
        # на КАЖДОМ заходе, а сбор состоит из заходов подряд — и каждый
        # перечитывал один и тот же первый кусок файла. На архиве в сорок
        # тысяч звонков из него поднимались первые двести, после чего сбор
        # упирался в предел и рапортовал «остановлено», не прочитав девяносто
        # девять процентов журнала. Обнуление делается один раз, в начале сбора.
        позиция = int(self.db.get_kv(ключ, 0) or 0)
        inode = int(self.db.get_kv(self._ключ_inode(ключ), 0) or 0)
        # Позиция НЕ сдвигается здесь: её двигает `_scan` за каждым
        # обработанным звонком (см. там). Номер файла журнала — чтобы после
        # ротации дочитать хвост повёрнутого файла, а не потерять его.
        # Глубина просмотра — та же, что обещает справка параметра: звонки
        # старше неё обычный заход не берёт (сбор архива — берёт).
        глубина = float(self.станция.lookback_days or 0)
        не_старше = 0.0 if всё or глубина <= 0 else time.time() - глубина * 86400
        голова = голова_журнала(путь)
        try:
            номер_файла = путь.stat().st_ino
        except OSError:
            номер_файла = 0
        self._голова = (номер_файла, голова)
        была = str(self.db.get_kv(self._ключ_головы(ключ), "") or "")
        обрезан = bool(позиция and была and голова and голова != была
                       and inode == номер_файла)
        if обрезан:
            log.warning("Станция «%s»: журнал %s обрезан на месте (copytruncate) и "
                        "уже перерос прежнюю позицию — дочитываю хвост из копии, "
                        "дальше с начала", self.станция.name, путь)
        return читать_журнал(путь, offset=позиция, inode=inode, limit=limit,
                             пояс=self.станция.пояс, не_старше=не_старше,
                             сводка=сводка, обрезан=обрезан)

    def _из_ami(self, limit: int) -> list[Звонок]:
        """События `Cdr` из интерфейса управления.

        Соединение держится между заходами: вход на каждый заход — это
        строка в журнале безопасности АТС раз в минуту и повод для
        подозрений у того, кто этот журнал читает.
        """
        # Подпись соединения: адрес, порт, учётная запись и пароль. Раньше
        # соединение просто держалось, и смена любого из них не доходила
        # до станции до перезапуска сервера: правка пароля в настройках
        # ничего не меняла, а переключение источника на журнал CDR
        # оставляло сокет и сессию на станции висеть навсегда — а сессий у
        # AMI ограниченное число.
        подпись = (self.станция.host or "127.0.0.1", int(self.станция.port or 5038),
                   self.станция.username, self.станция.secret,
                   bool(getattr(self.станция, "tls", False)),
                   str(getattr(self.станция, "ca_file", "") or ""),
                   str(getattr(self.станция, "auth", "") or "plain"),
                   self._классы_событий_ami())
        if self._ami is not None and self._подпись_ami != подпись:
            log.info("Настройки AMI изменились — соединение открывается заново")
            self._закрыть_ami()
        клиент = self._ami
        if клиент is None:
            клиент = AMIClient(*подпись[:4], tls=подпись[4], ca_file=подпись[5],
                               auth=подпись[6], события=подпись[7])
            try:
                клиент.connect()
                # Сокет вычитывается всё время, а не пять секунд в минуту:
                # иначе загруженная станция рвёт сессию, которую не читают.
                фон = getattr(клиент, "читать_в_фоне", None)
                if callable(фон):
                    фон()
            except AMIError:
                if self._ami_оборвана is None:
                    self._ami_оборвана = time.time()
                raise
            self._ami = клиент
            self._подпись_ami = подпись
            self._дочитать_журнал = True
            if self._ami_оборвана is not None:
                self.ami_разрыв = {"since": self._ami_оборвана, "until": time.time()}
                log.warning("Станция «%s»: связь с AMI восстановлена после разрыва в %.0f с%s",
                            self.станция.name, time.time() - self._ami_оборвана,
                            " — дочитываю журнал CDR" if self._журнал_дозабора()
                            else ": звонки этого промежутка AMI не пришлёт (журнал CDR "
                                 "у станции не задан или не виден серверу)")
                self._ami_оборвана = None
        звонки: list[Звонок] = []
        очереди: list[dict[str, Any]] = []
        from . import queue_log as журнал_очередей  # noqa: PLC0415

        крайний = time.time() + 5.0
        while len(звонки) < limit and time.time() < крайний:
            try:
                # `getattr` — подменные клиенты тестов и прежних сборок
                # отметки последнего приёма не знают: тогда без проверки.
                принято = getattr(клиент, "последний_приём", None)
                if принято is not None and time.monotonic() - принято > ПИНГ_ПОСЛЕ_С:
                    # Долгая тишина — спросить станцию: мёртвое соединение
                    # отвечает тайм-аутом, живое — ответом (события,
                    # пришедшие за время ожидания, клиент не выбрасывает).
                    клиент.ping()
                событие = клиент.пакет(timeout=1.0)
            except AMIError as exc:
                # Соединение не просто забывается, а закрывается: брошенный
                # сокет держит и дескриптор здесь, и сессию на станции —
                # а сессий у AMI ограниченное число.
                self._закрыть_ami()
                if self._ami_оборвана is None:
                    self._ami_оборвана = time.time()
                if not звонки:
                    raise
                # Уже прочитанное отдаётся заходу: повторно AMI эти события
                # не пришлёт, и раньше `raise` выбрасывал их вместе со
                # списком. Сбой виден в разделе, а переподключение — на
                # следующем же заходе.
                log.warning("Станция «%s»: связь с AMI оборвалась после %d "
                            "событий: %s", self.станция.name, len(звонки), exc)
                self._обрыв = str(exc)
                break
            if not событие:
                break
            if str(событие.get("Event") or "").lower() != "cdr":
                # События очередей (класс agent) — когда queue_log станции
                # серверу не виден: ожидание, брошенные, пропуски операторов.
                if "agent" in подпись[7]:
                    из_ami = журнал_очередей.из_события_ami(событие)
                    if из_ami is not None:
                        очереди.append(из_ami)
                continue
            поля = {имя: событие.get(ключ, "") for ключ, имя in _ПОЛЯ_AMI.items()}
            звонок = звонок_из_полей(поля, пояс=self.станция.пояс)
            if звонок.uniqueid:
                звонки.append(звонок)
        if очереди:
            try:
                self.db.queue_events_add(self.id, очереди)
            except Exception as exc:                        # noqa: BLE001
                log.warning("Станция «%s»: события очередей из AMI не сохранены: %s",
                            self.станция.name, exc)
        return звонки

    def _классы_событий_ami(self) -> str:
        """Какие события просить у AMI: звонки, а без queue_log — и очереди."""
        try:
            путь = self.станция.путь("queue_log") if getattr(self.станция, "queue_log", "") \
                else None
            есть_журнал = путь is not None and путь.is_file()
        except OSError:
            есть_журнал = False
        return "cdr" if есть_журнал else "cdr,agent"

    def _закрыть_ami(self) -> None:
        """Закрывает соединение со станцией и забывает его подпись."""
        клиент, self._ami = self._ami, None
        self._подпись_ami = None
        if клиент is not None:
            клиент.close()

    def _журнал_дозабора(self) -> Path | None:
        """Журнал CDR станции AMI, если он задан и виден серверу.

        AMI обычно удалённая, и путь к журналу в её полях может быть путём
        на самой АТС: такого файла здесь нет, и дозабор просто не делается
        (разрыв виден в состоянии станции, `ami_gap`).
        """
        путь = self.станция.путь("cdr_file")
        try:
            return путь if путь is not None and путь.is_file() else None
        except OSError:
            return None

    def _журнал_в_конец(self, ключ: str) -> None:
        """Позиция журнала CDR — туда, где был его конец заход назад.

        Связь с AMI цела: всё, что журнал записал к прошлому заходу, AMI уже
        прислала событиями — у неё был целый заход. Конец журнала «сейчас»
        брать нельзя: звонок, завершившийся только что, AMI ещё не прислала,
        и обрыв связи в этот миг потерял бы его для обоих путей.
        """
        путь = self.станция.путь("cdr_file")
        try:
            сведения = путь.stat() if путь is not None else None
        except OSError:
            return
        if сведения is None:
            return
        прошлый, self._конец_журнала = self._конец_журнала, (сведения.st_size, сведения.st_ino)
        if прошлый is None or прошлый[1] != сведения.st_ino or прошлый[0] > сведения.st_size:
            return                                   # первый заход или журнал повёрнут
        if int(self.db.get_kv(ключ, 0) or 0) < прошлый[0]:
            self._запомнить_позицию(ключ, прошлый[0], прошлый[1])

    #: Как часто сверять каталог записей станции «диалплан» и сколько ждать
    #: после записи файла: обычный путь — обращение из диалплана — должен
    #: успеть первым.
    СВЕРКА_КАЖДЫЕ_С = 600.0
    СВЕРКА_ВЫДЕРЖКА_С = 600.0

    def _сверка_каталога(self, limit: int) -> list[Звонок]:
        """Записи в каталоге станции «диалплан», о которых сервер не знает.

        Станция сообщает о звонке обращением из диалплана, а `CURL()` его не
        повторяет: сервер перезапускался, ответил 429 или 5xx — и звонок не
        приходил никогда. Раз в десять минут каталог записей сверяется с
        архивом: файл `…/<uniqueid>.wav` старше десяти минут, звонка
        которого в архиве нет, заводится звонком тем же ключом
        «станция:uniqueid» — обращение, пришедшее позже, увидит «уже
        импортирован». Полей у такого звонка — сколько видно по имени файла.
        """
        каталог = self.станция.путь("recordings_dir")
        if каталог is None or not каталог.is_dir():
            return []
        сейчас = time.time()
        if сейчас - self._сверка_была < self.СВЕРКА_КАЖДЫЕ_С:
            return []
        self._сверка_была = сейчас
        глубина = max(1.0, min(float(self.станция.lookback_days or 2), 7.0))
        свежее = сейчас - глубина * 86400
        созрело = сейчас - self.СВЕРКА_ВЫДЕРЖКА_С
        # Сначала — подкаталоги дат (asrhub/ГГГГ/ММ/ДД и ГГГГ/ММ/ДД, как
        # раскладывают MixMonitor и FreePBX): полный обход дерева архива на
        # каждой сверке не нужен.
        места: list[Path] = []
        for сутки in range(int(глубина) + 1):
            день = time.localtime(сейчас - сутки * 86400)
            for основа in (каталог / "asrhub", каталог):
                место = основа / time.strftime("%Y/%m/%d", день)
                if место.is_dir() and место not in места:
                    места.append(место)
        обход = (п for место in места for п in место.iterdir()) if места else каталог.rglob("*")
        звонки: list[Звонок] = []
        uid_вид = re.compile(r"(\d{9,}\.\d+)$")
        for путь in обход:
            if len(звонки) >= limit:
                break
            try:
                if not _запись_ли(путь) or not путь.is_file():
                    continue
                изменён = путь.stat().st_mtime
            except OSError:
                continue
            if not (свежее <= изменён <= созрело):
                continue
            совпало = uid_вид.search(путь.stem)
            if not совпало:
                continue
            # Свои записи (MixMonitor из модуля ASR Hub) названы ровно
            # ${UNIQUEID} — вместе с systemname станции, если он задан
            # («pbx1-1700000000.12»): так же звонок назовёт и обращение из
            # диалплана. У FreePBX имя длиннее («in-101-7999…-<uniqueid>»), и
            # отделить systemname от номеров нельзя — берётся «эпоха.счётчик».
            имя = путь.name
            freepbx = имя.startswith(_ПРИСТАВКИ_FREEPBX)
            uid = совпало.group(1) if freepbx or not _ВЕСЬ_UID.fullmatch(путь.stem) \
                else путь.stem
            if any(self.db.call_exists(f"{self.id}:{вид}")
                   for вид in {uid, совпало.group(1), путь.stem}):
                continue
            длительность = _длительность_файла(путь)
            звонок = Звонок(uniqueid=uid, started_at=изменён - длительность,
                            duration=длительность, disposition="ANSWERED", answered=True)
            звонок.billsec = звонок.duration
            звонок.recording = str(путь)
            звонок.userfield = "сверка каталога"
            звонок.direction = ("входящий" if имя.startswith(("in-", "q-", "external-")) else
                                "исходящий" if имя.startswith("out-") else
                                "внутренний" if имя.startswith(("exten-", "internal-")) else "")
            if freepbx:
                # in-<кому>-<кто>-<дата>-<время>-<uniqueid>: первые два поля.
                поля = имя.split("-")
                if len(поля) > 3:
                    звонок.dst, звонок.src = поля[1], поля[2]
            звонки.append(звонок)
        if звонки:
            log.warning("Станция «%s»: сверка каталога нашла %d записей без обращения из "
                        "диалплана — звонки заведены по файлам", self.станция.name, len(звонки))
        return звонки

    def _из_папки(self, limit: int, *, всё: bool = False) -> list[Звонок]:
        """Когда до АТС не дотянуться: звонок — это файл записи.

        Полей у такого звонка ровно столько, сколько удалось прочитать в
        имени файла, и раздел это показывает как есть. Идентификатором
        служит имя файла: оно уникально в пределах папки, а большего для
        защиты от повторного импорта не нужно.
        """
        каталог = self.станция.путь("recordings_dir")
        if каталог is None or not каталог.is_dir():
            raise ConfigError(
                f"«{self.станция.name}»: каталог записей не найден.",
                hint="Проверьте путь и права на чтение у пользователя, "
                     "от которого работает сервер.")
        известные = self.db.known_call_ids(station=self.id)
        # Множество — только свежие звонки. На архиве больше предела старые
        # известные файлы в него не попадали, проходили как новые и
        # занимали всю порцию: полный сбор топтался на уже импортированном
        # и до новых записей не доходил. Промах неполного множества
        # доспрашивается у базы — по указателю, одним запросом на файл.
        неполное = len(известные) >= self.db.ПРЕДЕЛ_ИЗВЕСТНЫХ_ЗВОНКОВ
        # При полном сборе глубина просмотра не действует: её смысл —
        # «не перебирать архив на каждом такте», а тут архив и нужен.
        свежее = 0.0 if всё else \
            time.time() - float(self.станция.lookback_days or 7) * 86400
        звонки: list[Звонок] = []
        for путь in обойти_свежее(каталог, свежее):
            if len(звонки) >= limit:
                break
            try:
                # Те же виды записей, что ищет журнал CDR: «каталог записей»
                # брал только wav, mp3 и ogg, и станция, пишущая в gsm или
                # ulaw, через этот источник не отдавала ничего.
                if not _запись_ли(путь) or not путь.is_file():
                    continue
                изменён = путь.stat().st_mtime
            except OSError:
                continue
            if изменён < свежее:
                continue
            пара = пара_дорожек(путь)
            if пара is not None and путь == пара[1]:
                # Вторая дорожка пары Monitor() — едет вместе с первой одним
                # стереофайлом (см. `_подготовить_запись`), отдельным
                # звонком её не заводим.
                continue
            # Ключ — по пути от каталога, а не по имени: Asterisk
            # раскладывает записи по годам и месяцам, и «out-101-…wav» из
            # марта и из апреля — это два разных разговора с одним именем.
            # По имени второй молча терялся как «уже импортирован».
            try:
                относительный = путь.relative_to(каталог).as_posix()
            except ValueError:
                относительный = путь.name
            свой = f"file:{относительный}"
            ключ = f"{self.id}:{свой}" if self.id else свой
            if ключ in известные or (неполное and self.db.call_exists(ключ)):
                continue
            # Длительность из имени файла не узнать, и поставить ноль
            # значило бы выключить и порог длительности, и выдержку разом:
            # обе проверки написаны как «если длительность известна». Берём
            # настоящую — из самого файла; не прочиталась, значит ноль, и
            # это честно.
            длительность = _длительность_файла(путь)
            # Время последней записи в файл — это КОНЕЦ разговора, а не его
            # начало: запись дописывается по ходу. Ставить mtime началом
            # значило бы отодвинуть конец разговора в будущее на всю его
            # длину — и выдержка откладывала бы каждый файл до тех пор,
            # пока это будущее не наступит.
            звонок = Звонок(uniqueid=свой,
                            started_at=изменён - длительность,
                            duration=длительность,
                            disposition="ANSWERED", answered=True)
            звонок.billsec = звонок.duration
            звонок.recording = str(путь)
            # Номера из имени файла: «...-79161234567-101-...» встречается
            # в шаблонах чаще всего.
            номера = [ч for ч in путь.stem.replace("_", "-").split("-") if ч.isdigit()]
            if len(номера) >= 2:
                звонок.src, звонок.dst = номера[0], номера[1]
            звонки.append(звонок)
        return звонки

