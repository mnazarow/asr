    def диагностика(self) -> dict[str, Any]:
        """Почему со станции не приходят звонки — по пунктам.

        Живёт в отдельном модуле: разбор длинный, ничего не меняет и нужен
        не всегда. Импорт от него не зависит вовсе.
        """
        from .diagnose import диагноз  # noqa: PLC0415

        return диагноз(self)

    def собрать(self, *, режим: str = "all", since: float = 0.0,
                until: float = 0.0, предел: int = 100000) -> dict[str, Any]:
        """Полный сбор архива станции в отдельном потоке.

        Обычный заход берёт порцию и уходит спать до следующего такта: на
        архиве в сорок тысяч звонков это недели ожидания. Здесь заходы идут
        подряд, пока журнал не кончится, а ход виден в разделе.

        Повторный вызов при идущем сборе ничего не начинает: два потока
        читали бы журнал с одной позиции.
        """
        if self._поток_сбора is not None and self._поток_сбора.is_alive():
            return dict(self.сбор)
        окно: tuple[float, float] | None = None
        if режим == "period":
            if not since or not until or until <= since:
                raise ConfigError(
                    "Для сбора за период нужны начало и конец промежутка.",
                    hint="Выберите даты в разделе «АТС».")
            окно = (float(since), float(until))
        # Предыдущий сбор того же вида остановился на пределе — этот
        # продолжает с того же места. Раньше каждый запуск обнулял позицию, и
        # сбор журнала длиннее предела всякий раз перечитывал те же строки и
        # вставал там же: дальше первых ста тысяч он не уходил никогда.
        продолжить = self._сбор_на_пределе == f"{режим}:{since}:{until}"
        # Сбор архива читает журнал с начала — за этим его и запускают.
        # Позиция сбрасывается здесь, один раз: внутри заходов её обнулять
        # нельзя, иначе каждый заход перечитывает один и тот же кусок.
        # Звонки при этом не задваиваются: от повтора держит `call_exists`.
        #
        # Сбор за период — своей позицией. Общую он раньше обнулял и дочитывал
        # до конца журнала, а звонки вне окна пропускал без пометки: всё, до
        # чего обычный заход ещё не дошёл, и всё, что пришло за часы сбора,
        # оказывалось «вне окна» — и обычный заход этих звонков больше не
        # видел никогда.
        if self.станция.source == "cdr_csv" and not продолжить:
            self._запомнить_позицию(self._ключ_позиции_сбора if режим == "period"
                                    else self._ключ_позиции, 0, 0)
        self._сбор_на_пределе = ""
        # Каталог записей — заново: указатель живёт между заходами, а сбор
        # затем и запускают, что записи могли лечь после последнего обхода.
        self._указатель = None
        self.сбор = {
            "station": self.id, "mode": режим, "running": True,
            "started_at": time.time(), "finished_at": None,
            "passes": 0, "seen": 0, "imported": 0, "skipped": 0,
            "outside": 0, "reasons": {}, "error": "", "new": 0,
            "since": since or None, "until": until or None,
            "continued": продолжить,
        }
        поток = threading.Thread(
            target=self._сбор_поток, args=(окно, предел, f"{режим}:{since}:{until}"),
            name=f"asrhub-collect-{self.id}"[:15], daemon=True)
        self._поток_сбора = поток
        поток.start()
        return dict(self.сбор)

    #: Пауза сбора, пока очередь распознавания полна: журнал при этом не
    #: читается (см. `_scan`), и опрашивать её чаще незачем.
    ПАУЗА_ПОЛНОЙ_ОЧЕРЕДИ = 5.0

    def _сбор_поток(self, окно: tuple[float, float] | None, предел: int,
                    вид: str = "") -> None:
        """Заходы подряд, пока источник не перестанет приносить новое.

        Конец — когда источник дочитан (`fresh` — ноль новых строк), а не
        когда заход ничего не «увидел»: в увиденное входят и отложенные, и
        пока они были (полная очередь, живой поток, «ещё пишется»), заходы
        шли каждые 0,2 с до самого предела, на журнале в триста звонков
        насчитывая тысячи. Предел — по НОВЫМ звонкам: «уже импортирован»
        его не тратит, иначе повторный сбор упирался в предел на уже
        собранном.
        """
        пусто_подряд = 0
        # У AMI архива нет: «дочитан» — значит, два захода подряд без событий
        # (события приходят пачками, пауза между ними нормальна). Журнал и
        # каталог дочитаны с первого пустого захода.
        пустых_до_конца = 2 if self.source == "ami" else 1
        try:
            while not self._stop.is_set():
                свод = self.scan(limit=ПОРЦИЯ_СБОРА, всё=True, окно=окно)
                сбор = self.сбор
                сбор["passes"] = int(сбор.get("passes", 0)) + 1
                for ключ in ("seen", "imported", "skipped", "outside"):
                    сбор[ключ] = int(сбор.get(ключ, 0)) + int(свод.get(ключ) or 0)
                причины = сбор.setdefault("reasons", {})
                for причина, сколько in (свод.get("reasons") or {}).items():
                    причины[причина] = причины.get(причина, 0) + сколько
                известных = sum(int((свод.get("reasons") or {}).get(п) or 0)
                                for п in ("уже импортирован", "ещё нога звонка"))
                сбор["new"] = int(сбор.get("new", 0)) + max(
                    0, int(свод.get("imported") or 0) + int(свод.get("skipped") or 0)
                    - известных)
                сбор["at"] = time.time()
                if свод.get("held_by"):
                    сбор["error"] = (f"Станцию ведёт другой сервер ({свод['held_by']}) "
                                     "— сбор не начат.")
                    break
                if свод.get("backpressure"):
                    # Очередь полна — журнал стоит на месте; ждём места, а не
                    # считаем это концом источника.
                    пусто_подряд = 0
                    self._stop.wait(self.ПАУЗА_ПОЛНОЙ_ОЧЕРЕДИ)
                    continue
                if not свод.get("fresh"):
                    пусто_подряд += 1
                    if пусто_подряд >= пустых_до_конца:
                        break
                    self._stop.wait(1.0)
                    continue
                пусто_подряд = 0
                if int(сбор.get("new", 0)) >= предел:
                    сбор["error"] = (f"Остановлено на пределе в {предел} новых "
                                     "звонков — следующий запуск продолжит с этого места.")
                    self._сбор_на_пределе = вид
                    break
                # Очередь распознавания не резиновая: сбор архива не должен
                # вытеснять свежие звонки и загрузки людей.
                self._stop.wait(0.2)
        except Exception as exc:                             # noqa: BLE001
            log.warning("Сбор архива «%s» прерван: %s", self.id, exc)
            self.сбор["error"] = str(exc)
        finally:
            self.сбор["running"] = False
            self.сбор["finished_at"] = time.time()

    def сбор_состояние(self) -> dict[str, Any]:
        свод = dict(self.сбор)
        свод["running"] = bool(self._поток_сбора and self._поток_сбора.is_alive())
        return свод

    def забыть_позицию(self) -> dict[str, Any]:
        """Сбрасывает позицию чтения журнала: следующий заход пойдёт с начала.

        Нужно после того, как журнал подменили или позиция уехала: звонки
        из архива при этом не задваиваются — от повтора держит первичный
        ключ таблицы.
        """
        было = int(self.db.get_kv(self._ключ_позиции, 0) or 0)
        self._запомнить_позицию(self._ключ_позиции, 0, 0)
        log.info("Станция «%s»: позиция чтения журнала сброшена (была %d)",
                 self.id, было)
        return {"station": self.id, "was": было, "now": 0}

