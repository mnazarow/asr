"""Приём звонков из диалплана Asterisk: станция сама сообщает о разговоре.

Три прежних пути забора — журнал CDR, интерфейс AMI и каталог записей —
устроены одинаково: сервер распознавания сам ходит к станции и ищет, что
появилось нового. Приём из диалплана работает в обратную сторону: в конце
каждого разговора станция сама вызывает `POST /api/telephony/dialplan/call`
— из обработчика отбоя (hangup handler) или командой по окончании
MixMonitor — и присылает запись файлом либо путь к ней на общем диске.

Что это даёт по сравнению с журналом:

* поля, которых в журнале CDR нет или которые там неверны: добавочный,
  который на самом деле ответил (участник очереди, перевод), направление,
  известное самому диалплану, очередь, метка из SIP-заголовка;
* звонок приезжает через секунды после отбоя — без опроса и без выдержки
  «а вдруг запись ещё пишется», когда её присылают уже закрытой;
* серверу не нужен доступ к станции вовсе: ни учётной записи AMI, ни
  смонтированного каталога. Нужен только исходящий HTTP со станции.

Звонок принимается за станцией с источником `dialplan` из раздела «АТС»:
у неё свои пороги (минимальная длительность, «без ответа»), владелец,
приоритет, метки, правила направления и часовой пояс. Решение «брать или
нет» принимает тот же `Импортёр._взять`, что и для журнала: один и тот же
звонок не может пройти одним путём и быть отсеян другим. Отложенные звонки
(запись на общем диске ещё пишется) дозабирает поток этой станции.

Модуль ничего не знает про HTTP: разбор полей, выбор станции, проверка
пути и решение — здесь, а чтение запроса и файла — в
`api/routes_dialplan.py`. Так всё это проверяется без сервера.
"""
from __future__ import annotations

import re
import threading
import time
from collections import deque
from datetime import datetime
from pathlib import Path
from typing import Any

from ..errors import ConfigError, ForbiddenError, UnsupportedFormat
