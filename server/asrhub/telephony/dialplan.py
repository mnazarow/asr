def станции_приёма(settings: Any) -> list[Станция]:
    """Станции, которые принимают звонки из диалплана."""
    return [с for с in станции_из_настроек(settings) if с.source == ИСТОЧНИК]


def выбрать_станцию(settings: Any, имя: str) -> Станция:
    """Станция, за которой записать звонок.

    Назвать можно идентификатором или именем. Не назвали — годится
    единственная станция с источником «dialplan»; если их несколько, угадывать
    нельзя: архивы филиалов перемешались бы. Станцию с другим источником
    тоже можно назвать явно — тогда звонок встаёт в её архив тем же ключом
    «станция:идентификатор», что и при чтении журнала, и задвоиться не может.
    """
    все = станции_из_настроек(settings)
    имя = str(имя or "").strip()
    if имя:
        найдена = next((с for с in все if с.id == имя), None) or next(
            (с for с in все if с.name.strip().lower() == имя.lower()), None)
        if найдена is None:
            raise ConfigError(
                f"Станция «{имя}» не найдена.",
                hint="Заведите станцию с источником «вызов из диалплана» в разделе "
                     "«АТС» и передайте её идентификатор полем station.")
        return найдена
    свои = [с for с in все if с.source == ИСТОЧНИК]
    if len(свои) == 1:
        return свои[0]
    if not свои:
        raise ConfigError(
            "Нет станции для приёма из диалплана.",
            hint="Заведите станцию с источником «вызов из диалплана» в разделе "
                 "«АТС» (или кнопкой в разделе «Asterisk: диалплан»): у неё "
                 "задаются пороги, владелец и приоритет звонков.")
    raise ConfigError(
        f"Станций для приёма из диалплана {len(свои)} — непонятно, к какой "
        "относится звонок.",
        hint="Передайте поле station: " + ", ".join(с.id for с in свои) + ".")


def путь_записи(станция: Станция, значение: str) -> Path:
    """Путь к записи на общем диске — только внутри каталога станции.

    Иначе приём превращается в «прочитай любой файл сервера»: ключ с правом
    записи называл бы путь к чужому архиву или к /etc/shadow, и сервер
    распознал бы его как разговор. Поэтому путь принимается, только если у
    станции задан каталог записей, и только внутри него — после раскрытия
    ссылок: символическая ссылка из каталога наружу тоже не годится.
    Относительный путь считается от каталога станции.
    """
    корень = станция.путь("recordings_dir")
    if корень is None:
        raise ConfigError(
            f"Станция «{станция.name}» принимает записи только файлом.",
            hint="Путь к записи (поле recording) принимается, когда у станции "
                 "задан каталог записей — тот, что смонтирован с АТС. Либо "
                 "присылайте сам файл полем file.")
    путь = Path(значение)
    if not путь.is_absolute():
        путь = корень / путь
    try:
        настоящий = путь.resolve(strict=False)
        корень_настоящий = корень.resolve(strict=False)
    except (OSError, RuntimeError) as exc:
        raise ConfigError(f"Путь к записи не разбирается: {exc}") from exc
    if настоящий != корень_настоящий and корень_настоящий not in настоящий.parents:
        raise ForbiddenError(
            "Запись лежит вне каталога записей станции.",
            hint=f"Принимаются только файлы внутри {корень}. Если записи лежат "
                 "в другом месте — поправьте каталог записей станции.")
    расширение = настоящий.suffix.lower()
    if расширение not in ЗВУК:
        ошибка = UnsupportedFormat(настоящий.name)
        ошибка.message = f"«{настоящий.name}»: такие записи сервер не принимает."
        ошибка.hint = "Ожидаются " + ", ".join(sorted(ЗВУК)) + "."
        raise ошибка
    return настоящий


def проверить_расширение(имя: str) -> str:
    """Расширение присланного файла; не звук — понятный отказ (415)."""
    расширение = Path(имя).suffix.lower()
    if расширение not in ЗВУК:
        ошибка = UnsupportedFormat(имя)
        ошибка.message = f"«{имя}»: такие записи сервер не принимает."
        ошибка.hint = ("Ожидаются " + ", ".join(sorted(ЗВУК)) + ". MixMonitor пишет "
                       "wav, если имя файла кончается на .wav.")
        raise ошибка
    return расширение


def решение_пробы(звонок: Звонок, станция: Станция, *, есть_запись: bool,
                  владелец: str) -> dict[str, Any]:
    """Что сервер сделал бы со звонком — для проверки настройки, без записи.

    Те же правила и в том же порядке, что в `Импортёр._взять`: короткий,
    без ответа, нет записи. Выдержку и готовность файла проба не смотрит —
    для них нужен сам файл.
    """
    минимум = int(станция.min_duration_s or 0)
    длительность = звонок.billsec or звонок.duration
    if минимум and длительность and длительность < минимум:
        итог = "короткий"
    elif bool(станция.skip_unanswered) and звонок.disposition and not звонок.answered:
        итог = "без ответа"
    elif not есть_запись and станция.путь("recordings_dir") is None:
        итог = "нет записи"
    else:
        итог = ""
    return {"would": "skip" if итог else "queue", "reason": итог,
            "owner": владелец, "priority": int(станция.priority or 40)}


# ---------------------------------------------------------------------------
# Журнал приёма
# ---------------------------------------------------------------------------

class ЖурналПриёма:
    """Последние обращения из диалплана и счётчики — на весь процесс.

    Настройка диалплана — это всегда «отправил, а дошло ли и что ответил
    сервер». Журнал сервера на это отвечает плохо: строки приёма тонут
    среди остальных, а отказы до проверки ключа туда не попадают вовсе.
    Здесь — ровно то, что нужно разделу «Asterisk: диалплан»: время, адрес,
    станция, идентификатор, итог и причина, в том числе для 401 и 403.

    Хранится в памяти: это инструмент наладки, а не архив. Сами звонки — в
    таблице `calls`, и там они остаются.
    """

    РАЗМЕР = 200

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._записи: deque[dict[str, Any]] = deque(maxlen=self.РАЗМЕР)
        self._счёт: dict[str, dict[str, Any]] = {}

    def отметить(self, **запись: Any) -> dict[str, Any]:
        запись.setdefault("at", time.time())
        ид = str(запись.get("station") or "")
        итог = str(запись.get("result") or "rejected")
        with self._lock:
            self._записи.append(запись)
            счёт = self._счёт.setdefault(ид, {
                "requests": 0, "queued": 0, "skipped": 0, "deferred": 0,
                "duplicate": 0, "rejected": 0, "dry_run": 0, "bytes": 0,
                "last_at": None, "last_ok_at": None, "last_error": None,
                "last_error_at": None})
            счёт["requests"] += 1
            счёт[итог] = int(счёт.get(итог) or 0) + 1
            счёт["bytes"] += int(запись.get("bytes") or 0)
            счёт["last_at"] = запись["at"]
            if итог == "rejected":
                счёт["last_error"] = str(запись.get("reason") or "")[:300]
                счёт["last_error_at"] = запись["at"]
            elif итог != "dry_run":
                счёт["last_ok_at"] = запись["at"]
        return запись

    def последние(self, *, station: str = "", limit: int = 50) -> list[dict[str, Any]]:
        """Свежие первыми. Отказы до выбора станции (ключ, станция не
        найдена) показываются и в разрезе станции: чьи они — неизвестно, а
        при наладке это как раз самые нужные строки."""
        with self._lock:
            записи = list(self._записи)
        записи.reverse()
        if station:
            записи = [з for з in записи if з.get("station") in (station, "")]
        return [dict(з) for з in записи[:max(1, int(limit))]]

    def свод(self, station: str = "") -> dict[str, Any]:
        with self._lock:
            if station:
                return dict(self._счёт.get(station) or {})
            итого: dict[str, Any] = {"requests": 0, "queued": 0, "skipped": 0,
                                     "deferred": 0, "duplicate": 0, "rejected": 0,
                                     "dry_run": 0, "bytes": 0, "last_at": None}
            for счёт in self._счёт.values():
                for ключ in ("requests", "queued", "skipped", "deferred", "duplicate",
                             "rejected", "dry_run", "bytes"):
                    итого[ключ] += int(счёт.get(ключ) or 0)
                if счёт.get("last_at") and (итого["last_at"] or 0) < счёт["last_at"]:
                    итого["last_at"] = счёт["last_at"]
            return итого

    def сбросить(self) -> None:
        with self._lock:
            self._записи.clear()
            self._счёт.clear()


