#: Имя источника станции в настройке `telephony_stations`.
ИСТОЧНИК = "dialplan"

#: Расширения записей, которые принимаются. Тот же набор, что у агента на
#: станции: это всё, что MixMonitor умеет писать, плюс сжатые форматы, в
#: которые записи перекодируют после разговора.
ЗВУК = {".wav", ".mp3", ".ogg", ".gsm", ".alaw", ".ulaw", ".sln", ".g722",
        ".opus", ".flac", ".m4a"}

#: Имена полей запроса → поле звонка. Каноническое имя — первое; остальные —
#: как те же значения называются в диалплане, в чужих интеграциях и в
#: прежних версиях примеров. Требовать от диалплана ровно одного написания
#: незачем: ошибка в имени поля здесь не видна никому, кроме журнала приёма.
ИМЕНА: dict[str, str] = {
    "station": "station",
    "uniqueid": "uniqueid", "uid": "uniqueid", "call_id": "uniqueid",
    "src": "src", "callerid": "src", "caller": "src", "from": "src", "cid": "src",
    "dst": "dst", "callee": "dst", "to": "dst", "exten": "dst", "did": "dst",
    "clid": "clid",
    "agent": "agent", "extension": "agent", "operator": "agent", "member": "agent",
    "direction": "direction",
    "queue": "queue",
    "context": "context", "channel": "channel", "dstchannel": "dstchannel",
    "disposition": "disposition", "status": "disposition", "dialstatus": "dialstatus",
    "answered": "answered",
    "duration": "duration", "billsec": "billsec", "talk_s": "billsec",
    "started_at": "started_at", "start": "started_at", "started": "started_at",
    "epoch": "started_at",
    "userfield": "userfield", "accountcode": "accountcode",
    "recording": "recording", "path": "recording", "file": "recording",
    "ready": "ready",
    "dry_run": "dry_run", "test": "dry_run",
    "linkedid": "linkedid",
}

#: Предел длины одного поля. Номера и имена каналов короче в разы; длинное
#: значение — это либо ошибка в диалплане (подставился целый заголовок), либо
#: попытка забить архив мусором. Обрезаем, а не отвергаем: звонок важнее.
ПРЕДЕЛ_ПОЛЯ = 256
ПРЕДЕЛ_МЕТКИ = 1024

#: Исход звонка: журнал CDR пишет «ANSWERED / NO ANSWER / BUSY / FAILED /
#: CONGESTION», а Dial() кладёт в DIALSTATUS «ANSWER / NOANSWER / CANCEL /
#: CHANUNAVAIL…». Разделы «Телефония» и «АТС» понимают первый набор, поэтому
#: всё приводится к нему. «NOANSWER» — это ещё и «NO ANSWER», пропущенный
#: через FILTER(A-Z) в диалплане: пробел фильтр выбрасывает.
ИСХОДЫ = {
    "ANSWERED": "ANSWERED", "ANSWER": "ANSWERED",
    "NO ANSWER": "NO ANSWER", "NOANSWER": "NO ANSWER", "CANCEL": "NO ANSWER",
    "BUSY": "BUSY",
    "FAILED": "FAILED", "CHANUNAVAIL": "FAILED", "DONTCALL": "FAILED",
    "TORTURE": "FAILED", "INVALIDARGS": "FAILED",
    "CONGESTION": "CONGESTION",
}

#: Направление — ровно те слова, которыми его называет импортёр
#: (`asterisk.направление`): отбор в разделах идёт точным совпадением.
НАПРАВЛЕНИЯ = ("входящий", "исходящий", "внутренний")
СИНОНИМЫ_НАПРАВЛЕНИЯ = {
    "in": "входящий", "inbound": "входящий", "incoming": "входящий",
    "вх": "входящий", "входящая": "входящий",
    "out": "исходящий", "outbound": "исходящий", "outgoing": "исходящий",
    "исх": "исходящий", "исходящая": "исходящий",
    "internal": "внутренний", "local": "внутренний", "int": "внутренний",
    "вн": "внутренний", "внутренняя": "внутренний",
}

#: Секунды эпохи раньше 2000 года — это ошибка ввода (ноль, миллисекунды
#: пополам с секундами, мусор), а не история.
НЕ_РАНЬШЕ = 946684800.0

#: Управляющие символы из значений выбрасываются: они не нужны ни одному
#: полю звонка, а в журнале приёма и в выгрузках ломают строки.
_УПРАВЛЯЮЩИЕ = re.compile(r"[\x00-\x1f\x7f]")

ДА = {"1", "true", "yes", "y", "on", "да"}


# ---------------------------------------------------------------------------
# Разбор полей
# ---------------------------------------------------------------------------

def _чисто(значение: Any, предел: int = ПРЕДЕЛ_ПОЛЯ) -> str:
    текст = _УПРАВЛЯЮЩИЕ.sub("", str(значение if значение is not None else "")).strip()
    return текст[:предел]


def разобрать_поля(сырые: dict[str, Any]) -> tuple[dict[str, str], list[str]]:
    """Поля запроса → канонические имена; второе — что не узнано.

    Пустые значения выбрасываются сразу: диалплан подставляет пустую строку
    вместо переменной, которой нет (`${QUEUE}` вне очереди), и считать её
    «переданным» значением — значит затирать то, что сервер узнал бы сам.
    Первое непустое значение под любым из имён поля выигрывает.
    """
    поля: dict[str, str] = {}
    лишние: list[str] = []
    for имя, значение in сырые.items():
        ключ = ИМЕНА.get(str(имя).strip().lower())
        if ключ is None:
            лишние.append(str(имя)[:64])
            continue
        if isinstance(значение, (list, tuple)):
            значение = next((з for з in значение if str(з or "").strip()), "")
        текст = _чисто(значение, ПРЕДЕЛ_МЕТКИ if ключ == "userfield" else ПРЕДЕЛ_ПОЛЯ)
        if текст and ключ not in поля:
            поля[ключ] = текст
    return поля, sorted(set(лишние))


def да(значение: Any) -> bool:
    return str(значение or "").strip().lower() in ДА


def _целое(значение: str, беды: list[str], имя: str) -> int:
    if not значение:
        return 0
    try:
        число = int(float(значение))
    except ValueError:
        беды.append(f"{имя}: «{значение}» не число — не учтено")
        return 0
    if число < 0:
        беды.append(f"{имя}: отрицательное значение — не учтено")
        return 0
    # Двое суток — потолок для любого звонка. Больше — это миллисекунды
    # вместо секунд или мусор, и в сводки «часов разговора» он не попадёт.
    if число > 172800:
        беды.append(f"{имя}: {число} с — больше двух суток, не учтено")
        return 0
    return число


def разобрать_время(значение: str, пояс: Any = None) -> tuple[float, str]:
    """Время начала звонка. Возвращает (секунды эпохи, беда).

    Принимаются три вида: секунды эпохи (`${EPOCH}` — лучший выбор: ни
    пояса, ни формата), миллисекунды эпохи и строка даты (`${CDR(start)}`
    пишет «2026-10-27 14:03:11» — местное время станции без пояса). Строка
    без пояса читается в поясе станции, а если он не задан — в поясе
    сервера, ровно как журнал CDR.
    """
    текст = str(значение or "").strip()
    if not текст:
        return 0.0, ""
    try:
        число: float | None = float(текст)
    except ValueError:
        число = None
    if число is not None:
        if число >= 1e11:                       # миллисекунды
            число /= 1000.0
        if число < НЕ_РАНЬШЕ:
            return 0.0, f"время начала «{текст}» раньше 2000 года — не учтено"
        return число, ""
    подготовленное = текст.replace("Z", "+00:00").replace("z", "+00:00")
    for разбор in (datetime.fromisoformat,
                   lambda s: datetime.strptime(s[:19], "%Y-%m-%d %H:%M:%S"),
                   lambda s: datetime.strptime(s[:16], "%Y-%m-%d %H:%M")):
        try:
            когда = разбор(подготовленное)
        except (TypeError, ValueError):
            continue
        if когда.tzinfo is None and пояс is not None:
            когда = когда.replace(tzinfo=пояс)
        отметка = когда.timestamp()
        if отметка < НЕ_РАНЬШЕ:
            return 0.0, f"время начала «{текст}» раньше 2000 года — не учтено"
        return отметка, ""
    return 0.0, (f"время начала «{текст}» не разобрано — ожидаются секунды эпохи "
                 f"(${{EPOCH}}) или дата «ГГГГ-ММ-ДД ЧЧ:ММ:СС» — не учтено")


def разобрать_направление(значение: str) -> tuple[str, str]:
    текст = str(значение or "").strip().lower()
    if not текст:
        return "", ""
    if текст in НАПРАВЛЕНИЯ:
        return текст, ""
    if текст in СИНОНИМЫ_НАПРАВЛЕНИЯ:
        return СИНОНИМЫ_НАПРАВЛЕНИЯ[текст], ""
    return "", (f"направление «{значение}» не понято — ожидается in, out или "
                f"internal (входящий, исходящий, внутренний); определю сам")


def собрать_звонок(поля: dict[str, str], станция: Станция, *,
                   есть_запись: bool = False) -> tuple[Звонок, list[str]]:
    """Звонок из полей запроса — в том виде, в каком его ждёт импортёр.

    Направление, если его не назвали, вычисляется так же, как для журнала:
    по правилам контекстов станции, затем по длине номеров. Добавочный, если
    его не назвали, — тот, кого вызывали во входящем, и тот, кто звонил, в
    остальных. Но диалплан почти всегда знает и то и другое лучше сервера:
    поэтому присланное значение не перезаписывается никогда.
    """
    беды: list[str] = []
    звонок = Звонок()
    звонок.uniqueid = поля.get("uniqueid", "")
    for имя in ("src", "dst", "clid", "channel", "dstchannel", "context",
                "queue", "agent", "userfield", "accountcode"):
        setattr(звонок, имя, поля.get(имя, ""))
    if not звонок.clid and звонок.src:
        # Поиск по номеру в разделе «Телефония» смотрит и в определитель.
        звонок.clid = звонок.src
    звонок.duration = _целое(поля.get("duration", ""), беды, "duration")
    звонок.billsec = _целое(поля.get("billsec", ""), беды, "billsec")
    if звонок.duration and звонок.billsec > звонок.duration:
        # Разговор не бывает длиннее звонка: это переставленные поля.
        звонок.duration, звонок.billsec = звонок.billsec, звонок.duration
    звонок.started_at, беда = разобрать_время(поля.get("started_at", ""), станция.пояс)
    if беда:
        беды.append(беда)

    исход_сырой = (поля.get("disposition") or поля.get("dialstatus") or "").upper()
    исход = ИСХОДЫ.get(исход_сырой, "")
    if исход_сырой and not исход:
        беды.append(f"исход «{исход_сырой}» не понят — ожидается ANSWERED, NO ANSWER, "
                    "BUSY, FAILED, CONGESTION или значение DIALSTATUS")
    звонок.disposition = исход
    if "answered" in поля:
        звонок.answered = да(поля["answered"])
    elif исход:
        звонок.answered = исход == "ANSWERED"
    else:
        # Исход не назвали: разговор был, если была разговорная часть, а при
        # нулевой — если прислали запись (её с опцией b пишут только по
        # соединённому разговору). Обратное умолчание обнулило бы долю
        # отвеченных у всех звонков, где диалплан исход не передаёт.
        звонок.answered = звонок.billsec > 0 or есть_запись or bool(поля.get("recording"))

    куда, беда = разобрать_направление(поля.get("direction", ""))
    if беда:
        беды.append(беда)
    звонок.direction = куда or направление(
        звонок, внутренние_знаков=станция.internal_digits, контексты=станция.contexts)
    if not звонок.agent:
        звонок.agent = звонок.dst if звонок.direction == "входящий" else звонок.src
    return звонок, беды


