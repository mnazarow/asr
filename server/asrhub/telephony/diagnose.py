"""Почему со станции не приходят звонки.

«Заход прошёл, новых звонков ноль» — самый неприятный ответ из всех
возможных: он выглядит как исправная работа. Причин у него десяток, и
почти все молчаливые: журнал не пополняется, позиция чтения стоит в конце
повёрнутого файла, AMI подключается, но не шлёт события `Cdr`, каталог
записей смонтирован, но пуст, порог длительности отсекает всё, глубина
просмотра короче возраста архива.

Этот модуль проходит по всем таким причинам по очереди и отвечает не «не
работает», а «вот что именно не так и что с этим делать». Ничего не меняет
и ничего не импортирует: позиция чтения журнала остаётся на месте, звонки
в очередь не ставятся. Разбор читает — и только.

Каждая проверка — словарь с полями:

``id``       ключ проверки (для интерфейса);
``title``    как называется;
``state``    ``ok`` | ``warn`` | ``fail`` | ``info``;
``value``    что увидели;
``hint``     что делать, если плохо;
``details``  подробности для раскрывающегося блока.
"""
from __future__ import annotations

import os
import time
from pathlib import Path
from typing import Any

from ..logging_setup import get_logger
from .asterisk import (
    AMIClient,
    AMIError,
    Звонок,
    найти_запись,
    направление,
    разобрать_cdr_строку,
)

log = get_logger("telephony")

#: Сколько байт хвоста журнала читать для образца. Журнал бывает в
#: гигабайт, а вопрос у нас один: разбирается ли то, что станция пишет
#: сейчас, и подходит ли оно под настройки.
ХВОСТ = 256 * 1024

#: Сколько строк журнала брать в разбор образца.
ОБРАЗЕЦ = 200

#: Сколько секунд слушать события AMI. Меньше пяти — и на тихой станции
#: проверка объявит поломку там, где просто никто не звонил.
СЛУШАТЬ = 6.0

#: Журнал, в который сутки ничего не дописали, — это не «тихо», а «мимо».
СУТКИ = 86400.0


def _возраст(секунды: float) -> str:
    """Человеческая запись возраста: «14 минут назад», «3 дня назад»."""
    if not секунды or секунды < 0:
        return "неизвестно"
    if секунды < 90:
        return f"{int(секунды)} с назад"
    if секунды < 5400:
        return f"{int(секунды // 60)} мин назад"
    if секунды < 172800:
        return f"{секунды / 3600:.1f} ч назад"
    return f"{int(секунды // 86400)} дн назад"


def _проверка(id: str, title: str, state: str, value: str = "",   # noqa: A002
              hint: str = "", **details: Any) -> dict[str, Any]:
    return {"id": id, "title": title, "state": state, "value": value,
            "hint": hint, "details": details}


def _доступ(путь: Path) -> str:
    """Что мы можем с этим путём — словами, а не восьмеричным числом."""
    права = []
    if os.access(путь, os.R_OK):
        права.append("чтение")
    if os.access(путь, os.W_OK):
        права.append("запись")
    if путь.is_dir() and os.access(путь, os.X_OK):
        права.append("вход")
    return ", ".join(права) or "нет доступа"


def _строки_хвоста(путь: Path, *, байт: int = ХВОСТ) -> tuple[list[str], int]:
    """Последние строки файла и его размер, без сдвига позиции чтения.

    Первая строка отбрасывается, если читали не с начала: она почти
    наверняка обрезана посередине, и её разбор дал бы «журнал сдвинут на
    колонку» там, где всё в порядке.
    """
    размер = путь.stat().st_size
    начало = max(0, размер - байт)
    with путь.open("rb") as файл:
        файл.seek(начало)
        текст = файл.read().decode("utf-8", "replace")
    строки = [с for с in текст.splitlines() if с.strip()]
    if начало and строки:
        строки = строки[1:]
    return строки, размер


def _что_отсеет(звонки: list[Звонок], станция: Any) -> dict[str, int]:
    """Сколько звонков из образца не дошли бы до очереди и почему.

    Ровно те же правила, что и в импортёре, — но без записи в базу:
    проверка обязана оставаться безобидной.
    """
    минимум = int(станция.min_duration_s or 0)
    пропускать = bool(станция.skip_unanswered)
    итог = {"короткий": 0, "без ответа": 0, "годится": 0}
    for звонок in звонки:
        длительность = звонок.billsec or звонок.duration
        if минимум and длительность and длительность < минимум:
            итог["короткий"] += 1
        elif пропускать and звонок.disposition and not звонок.answered:
            итог["без ответа"] += 1
        else:
            итог["годится"] += 1
    return итог


