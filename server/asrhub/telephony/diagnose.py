def _журнал_csv(импортёр: Any, проверки: list[dict[str, Any]]) -> list[Звонок]:
    """Журнал CDR: файл, позиция чтения, образец строк."""
    станция = импортёр.станция
    путь = станция.путь("cdr_file")
    if путь is None:
        проверки.append(_проверка(
            "cdr_file", "Журнал звонков", "fail", "путь не задан",
            "Укажите файл журнала CDR — обычно /var/log/asterisk/cdr-csv/Master.csv."))
        return []
    if not путь.exists():
        проверки.append(_проверка(
            "cdr_file", "Журнал звонков", "fail", f"{путь} — файла нет",
            "Проверьте путь. Если сервер распознавания стоит отдельно от АТС, "
            "каталог нужно смонтировать или поставить на АТС агента "
            "(раздел «АТС» → «Агент на станции»)."))
        return []
    if not os.access(путь, os.R_OK):
        проверки.append(_проверка(
            "cdr_file", "Журнал звонков", "fail", f"{путь} — нет доступа на чтение",
            f"Дайте право на чтение пользователю, от которого работает сервер: "
            f"chmod o+r '{путь}'"))
        return []

    try:
        строки, размер = _строки_хвоста(путь)
        изменён = путь.stat().st_mtime
    except OSError as exc:
        проверки.append(_проверка("cdr_file", "Журнал звонков", "fail",
                                  f"не читается: {exc}"))
        return []

    возраст = time.time() - изменён
    проверки.append(_проверка(
        "cdr_file", "Журнал звонков",
        "ok" if возраст < СУТКИ else "warn",
        f"{путь} — {размер / 1048576:.1f} МБ, дописан {_возраст(возраст)}",
        "" if возраст < СУТКИ else
        "Станция сутки ничего не дописала в журнал. Либо звонков не было, "
        "либо CDR пишется не сюда: проверьте /etc/asterisk/cdr.conf и "
        "cdr_csv.conf, модуль cdr_csv.so должен быть загружен.",
        path=str(путь), bytes=размер, mtime=изменён, access=_доступ(путь)))

    позиция = int(импортёр.db.get_kv(импортёр._ключ_позиции, 0) or 0)
    впереди = размер - позиция
    if позиция > размер:
        состояние, пояснение = "warn", (
            "Позиция чтения больше размера файла — журнал повернули. "
            "Следующий заход начнёт с начала сам.")
    elif впереди == 0 and возраст > СУТКИ:
        состояние, пояснение = "warn", (
            "Всё прочитано, и файл давно не пополнялся: новых звонков "
            "просто нет. Если они должны быть — журнал пишется не в этот файл.")
    elif впереди == 0:
        состояние, пояснение = "ok", "Всё прочитано, ждём новых строк."
    else:
        состояние, пояснение = "ok", ""
    проверки.append(_проверка(
        "cdr_position", "Позиция чтения",
        состояние, f"{позиция} из {размер} байт, впереди {max(0, впереди)}",
        пояснение, offset=позиция, size=размер, ahead=max(0, впереди),
        key=импортёр._ключ_позиции))

    образцы = [z for z in (разобрать_cdr_строку(с) for с in строки[-ОБРАЗЕЦ:]) if z]
    разобрано = len(образцы)
    всего = len(строки[-ОБРАЗЕЦ:])
    if not всего:
        проверки.append(_проверка(
            "cdr_parse", "Разбор строк журнала", "fail", "в журнале нет строк",
            "Файл есть, но пуст. Обычно это значит, что Asterisk пишет CDR в "
            "другое место или модуль cdr_csv не загружен: "
            "asterisk -rx 'cdr show status'"))
    elif not разобрано:
        проверки.append(_проверка(
            "cdr_parse", "Разбор строк журнала", "fail",
            f"ни одна из {всего} строк не разобралась",
            "Формат журнала не похож на Master.csv. Так бывает при своём "
            "наборе полей (cdr_custom.conf): порядок колонок должен совпадать "
            "с обычным для cdr-csv.", sample=строки[-3:]))
    else:
        проверки.append(_проверка(
            "cdr_parse", "Разбор строк журнала",
            "ok" if разобрано > всего * 0.5 else "warn",
            f"разобрано {разобрано} из {всего}",
            "" if разобрано > всего * 0.5 else
            "Разбирается меньше половины строк — похоже, набор колонок свой.",
            sample=[{"uniqueid": z.uniqueid, "src": z.src, "dst": z.dst,
                     "disposition": z.disposition, "billsec": z.billsec,
                     # Направление показываем сразу: «все звонки внутренние»
                     # — верный признак того, что длины внутренних номеров
                     # или контексты заданы не так, а по одним номерам это
                     # не видно.
                     "direction": направление(
                         z, внутренние_знаков=станция.internal_digits,
                         контексты=станция.contexts),
                     "started_at": z.started_at} for z in образцы[-3:]]))
    return образцы


def _журнал_ami(импортёр: Any, проверки: list[dict[str, Any]]) -> list[Звонок]:
    """AMI: связь, поток событий и главное — приходят ли события Cdr.

    Про `cdr_manager` знают не все, а без него AMI не шлёт `Cdr` вовсе:
    станция подключается, отвечает на Ping, показывает события каналов — и
    ни одного звонка. Снаружи это выглядит как «всё хорошо, звонков нет».
    """
    станция = импортёр.станция
    клиент = AMIClient(станция.host or "127.0.0.1", станция.port or 5038,
                       станция.username, станция.secret)
    try:
        приветствие = клиент.connect()
    except AMIError as exc:
        проверки.append(_проверка(
            "ami_connect", "Связь с AMI", "fail", str(exc),
            getattr(exc, "hint", "") or
            "Проверьте адрес, порт, логин и пароль в manager.conf, а также "
            "permit/deny для адреса этого сервера."))
        return []

    проверки.append(_проверка(
        "ami_connect", "Связь с AMI", "ok",
        приветствие or f"{станция.host}:{станция.port}", banner=приветствие))

    события: dict[str, int] = {}
    звонки: list[Звонок] = []
    крайний = time.time() + СЛУШАТЬ
    try:
        while time.time() < крайний:
            пакет = клиент.пакет(timeout=max(0.5, крайний - time.time()))
            if not пакет:
                continue
            имя = пакет.get("Event", "")
            if not имя:
                continue
            события[имя] = события.get(имя, 0) + 1
    except AMIError as exc:
        проверки.append(_проверка(
            "ami_stream", "Поток событий", "warn", f"обрыв: {exc}"))
    finally:
        клиент.close()

    всего = sum(события.values())
    cdr = события.get("Cdr", 0)
    if cdr:
        состояние, значение, подсказка = "ok", f"событий Cdr: {cdr}", ""
    elif всего:
        состояние = "warn"
        значение = f"событий {всего}, из них Cdr — ни одного"
        подсказка = (
            "Станция шлёт события, но не о завершённых звонках. Две причины, "
            "обе на АТС: не загружен cdr_manager (asterisk -rx 'module show "
            "like cdr_manager', в /etc/asterisk/cdr_manager.conf нужно "
            "[general] enabled = yes) или у учётной записи AMI нет права "
            "read = cdr в manager.conf. Проверить можно и так: за время "
            "наблюдения должен был завершиться хотя бы один звонок.")
    else:
        состояние = "warn"
        значение = "за время наблюдения не пришло ни одного события"
        подсказка = (
            "Возможно, на станции сейчас просто тихо. Если звонки идут — "
            "посмотрите eventfilter в manager.conf: он может отсекать всё.")
    проверки.append(_проверка(
        "ami_cdr", "События о звонках", состояние, значение, подсказка,
        seconds=СЛУШАТЬ, events=события))
    return звонки


def _каталог_как_источник(импортёр: Any, проверки: list[dict[str, Any]]) -> list[Звонок]:
    """Источник «каталог записей»: звонок — это файл."""
    станция = импортёр.станция
    каталог = станция.путь("recordings_dir")
    if каталог is None or not каталог.is_dir():
        проверки.append(_проверка(
            "dir", "Каталог записей", "fail",
            f"{каталог or 'путь не задан'} — каталога нет",
            "Проверьте путь и права. Если записи лежат на самой АТС, "
            "смонтируйте каталог или поставьте на станцию агента."))
        return []

    глубина = float(станция.lookback_days or 7)
    порог = time.time() - глубина * 86400
    всего = свежих = 0
    новейший = 0.0
    примеры: list[str] = []
    for путь in каталог.rglob("*"):
        try:
            if not путь.is_file() or путь.suffix.lower() not in (".wav", ".mp3", ".ogg"):
                continue
            изменён = путь.stat().st_mtime
        except OSError:
            continue
        всего += 1
        новейший = max(новейший, изменён)
        if изменён >= порог:
            свежих += 1
            if len(примеры) < 3:
                примеры.append(путь.name)
        if всего > 20000:            # каталог на сотни тысяч файлов считать нечем
            break

    проверки.append(_проверка(
        "dir", "Каталог записей", "ok" if всего else "fail",
        f"{каталог} — файлов {всего}, доступ: {_доступ(каталог)}",
        "" if всего else
        "В каталоге нет ни одного файла подходящего вида (.wav, .mp3, .ogg). "
        "Проверьте, тот ли это путь и видит ли его пользователь сервера.",
        path=str(каталог), files=всего))

    if всего:
        возраст = time.time() - новейший
        проверки.append(_проверка(
            "dir_recent", "Глубина просмотра",
            "ok" if свежих else "fail",
            f"новее {глубина:g} дн — {свежих} из {всего}; "
            f"самый свежий файл {_возраст(возраст)}",
            "" if свежих else
            f"Все записи старше {глубина:g} дней, и забор их не видит. "
            f"Поднимите «Глубину просмотра» у станции — например, до "
            f"{max(1, int(возраст // 86400) + 1)} дней.",
            fresh=свежих, total=всего, newest=новейший, examples=примеры))

    известные = импортёр.db.known_call_ids(station=импортёр.id)
    проверки.append(_проверка(
        "dir_known", "Уже импортировано", "info",
        f"{len(известные)} записей этой станции в архиве",
        known=len(известные)))
    return []


def _записи(импортёр: Any, образцы: list[Звонок],
            проверки: list[dict[str, Any]]) -> None:
    """Находится ли файл записи для звонков из журнала.

    Самая частая тихая поломка после самого журнала: звонки читаются, а
    записи не находятся — и все они уходят в «нет записи», то есть в
    пропущенные, без единой ошибки в журнале сервера.
    """
    станция = импортёр.станция
    каталог = станция.путь("recordings_dir")
    if каталог is None:
        проверки.append(_проверка(
            "rec_dir", "Каталог записей", "fail", "путь не задан",
            "Без каталога записей распознавать нечего: звонки будут "
            "помечаться как «нет записи»."))
        return
    if not каталог.is_dir():
        проверки.append(_проверка(
            "rec_dir", "Каталог записей", "fail", f"{каталог} — каталога нет",
            "Проверьте путь и монтирование. Если записи на самой АТС — "
            "поставьте на неё агента."))
        return

    файлов = 0
    новейший = 0.0
    примеры: list[str] = []
    for путь in каталог.rglob("*"):
        try:
            if not путь.is_file() or путь.suffix.lower() not in (
                    ".wav", ".mp3", ".gsm", ".ogg", ".alaw", ".ulaw", ".sln"):
                continue
            изменён = путь.stat().st_mtime
        except OSError:
            continue
        файлов += 1
        новейший = max(новейший, изменён)
        if len(примеры) < 5:
            примеры.append(путь.relative_to(каталог).as_posix())
        if файлов > 20000:
            break
    проверки.append(_проверка(
        "rec_dir", "Каталог записей", "ok" if файлов else "fail",
        f"{каталог} — файлов {файлов}"
        + (f", самый свежий {_возраст(time.time() - новейший)}" if файлов else "")
        + f", доступ: {_доступ(каталог)}",
        "" if файлов else
        "Каталог пуст. Проверьте, включена ли запись разговоров на станции "
        "(MixMonitor) и тот ли это путь.",
        path=str(каталог), files=файлов, examples=примеры))

    if not образцы or not файлов:
        return
    найдено, пропало = 0, []
    for звонок in образцы[-10:]:
        путь = найти_запись(звонок, каталог, шаблон=станция.filename,
                            окно_дней=int(станция.lookback_days or 7))
        if путь is not None and путь.is_file():
            найдено += 1
        elif len(пропало) < 3:
            пропало.append({"uniqueid": звонок.uniqueid, "src": звонок.src,
                            "dst": звонок.dst, "started_at": звонок.started_at})
    сколько = len(образцы[-10:])
    проверки.append(_проверка(
        "rec_match", "Записи к звонкам из журнала",
        "ok" if найдено else "fail",
        f"найдено {найдено} из {сколько} последних",
        "" if найдено else
        "Ни к одному звонку из журнала запись не нашлась. Обычно причина в "
        "имени файла: MixMonitor зовут без ${UNIQUEID}, и сопоставить звонок "
        "с файлом не по чему. Задайте «Шаблон имени файла» у станции — "
        "например, {uniqueid}.wav или {src}-{dst}-*.wav — либо включите в "
        "имя записи идентификатор звонка.",
        found=найдено, checked=сколько, missing=пропало,
        pattern=станция.filename or "", examples=примеры[:3]))


