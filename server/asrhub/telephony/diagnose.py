def диагноз(импортёр: Any) -> dict[str, Any]:
    """Полный разбор забора по одной станции."""
    станция = импортёр.станция
    проверки: list[dict[str, Any]] = []

    проверки.append(_проверка(
        "enabled", "Станция включена", "ok" if станция.enabled else "fail",
        "включена" if станция.enabled else "выключена",
        "" if станция.enabled else "Включите станцию в разделе «АТС»."))

    живой = bool(импортёр._thread and импортёр._thread.is_alive())
    проверки.append(_проверка(
        "thread", "Поток забора", "ok" if живой else ("warn" if станция.enabled else "info"),
        "работает" if живой else "не запущен",
        "" if живой or not станция.enabled else
        "Поток забора не поднят. Перезапустите сервер или выключите и "
        "включите станцию.",
        poll_s=станция.poll_s))

    свод = импортёр.last_scan or {}
    if свод:
        причины = свод.get("reasons") or {}
        расшифровка = ", ".join(f"{к}: {з}" for к, з in причины.items()) or "—"
        поставлено = int(свод.get("imported") or 0)
        увидено = int(свод.get("seen") or 0)
        проверки.append(_проверка(
            "last_scan", "Последний заход",
            "ok" if поставлено else ("warn" if увидено else "info"),
            f"увидено {увидено}, поставлено {поставлено}, "
            f"пропущено {свод.get('skipped') or 0} ({расшифровка})",
            "" if поставлено or not увидено else
            "Звонки читаются, но ни один не дошёл до очереди — причина в "
            "строке выше: «нет записи» чинится каталогом и шаблоном имени, "
            "«короткий» и «без ответа» — порогами станции.",
            **свод))
    else:
        проверки.append(_проверка(
            "last_scan", "Последний заход", "info", "заходов ещё не было",
            "Нажмите «Забрать сейчас» и повторите разбор."))

    if импортёр.last_error:
        проверки.append(_проверка(
            "last_error", "Последняя ошибка", "fail", str(импортёр.last_error)))

    образцы: list[Звонок] = []
    try:
        if станция.source == "ami":
            образцы = _журнал_ami(импортёр, проверки)
        elif станция.source == "folder":
            образцы = _каталог_как_источник(импортёр, проверки)
        else:
            образцы = _журнал_csv(импортёр, проверки)
    except Exception as exc:                                 # noqa: BLE001
        log.warning("Разбор источника «%s» не удался: %s", станция.id, exc)
        проверки.append(_проверка(
            "source", "Источник", "fail", str(exc),
            "Разбор источника прервался — смотрите журнал сервера."))

    if станция.source != "folder":
        _записи(импортёр, образцы, проверки)

    if образцы:
        отсев = _что_отсеет(образцы, станция)
        годится = отсев.get("годится", 0)
        проверки.append(_проверка(
            "filters", "Пороги станции", "ok" if годится else "fail",
            f"из {len(образцы)} звонков журнала прошли бы {годится}: "
            f"короткие — {отсев['короткий']}, без ответа — {отсев['без ответа']}",
            "" if годится else
            f"Все звонки из образца отсекаются настройками станции. "
            f"Порог длительности — {станция.min_duration_s} с; "
            f"«Пропускать неотвеченные» — "
            f"{'включено' if станция.skip_unanswered else 'выключено'}.",
            **отсев))

    в_архиве = импортёр.db.call_counts(station=импортёр.id) \
        if hasattr(импортёр.db, "call_counts") else {}
    if в_архиве:
        проверки.append(_проверка(
            "archive", "Архив станции", "info",
            f"звонков {в_архиве.get('total', 0)}, "
            f"с записями {в_архиве.get('with_job', 0)}, "
            f"пропущено {в_архиве.get('skipped', 0)}", **в_архиве))

    беды = [п for п in проверки if п["state"] == "fail"]
    предупреждения = [п for п in проверки if п["state"] == "warn"]
    if беды:
        итог = беды[0]["hint"] or беды[0]["value"]
        состояние = "fail"
    elif предупреждения:
        итог = предупреждения[0]["hint"] or предупреждения[0]["value"]
        состояние = "warn"
    else:
        итог = "Забор настроен верно: источник читается, записи находятся."
        состояние = "ok"
    return {
        "station": станция.id, "name": станция.name, "source": станция.source,
        "state": состояние, "verdict": итог, "checks": проверки,
        "failed": len(беды), "warned": len(предупреждения), "at": time.time(),
    }
