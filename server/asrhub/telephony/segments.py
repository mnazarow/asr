"""Кто говорил на каком отрезке записи: разговор с переводами — по участникам.

Перевод с оператора на оператора у Asterisk 12+ — отдельные строки CDR
(ноги) с общим `linkedid`. Запись при этом обычно одна — на канале клиента,
который живёт весь разговор, — и раньше она целиком доставалась одному
добавочному: и оценка, и тональность, и минуты разговора второго оператора
записывались первому.

Здесь отрезки записи раскладываются по ногам: нога с ответом — окно
«от ответа до конца» на времени записи (ноль записи — ответ записанной ноги:
MixMonitor с `b` пишет с соединения). Реплика расшифровки идёт тому, в чьё
окно попала её середина; в общем окне (консультация при переводе с
предупреждением — на линии двое) — тому, кто подключился позже: он принимает
разговор. По каждому участнику — своя оценка: сколько звучал его отрезок,
сколько слов и какая тональность.

Точность — секунды: время ног пишет станция, а запись начинается с
соединения. Для разбора «кто вёл разговор и как» этого достаточно; на
границе перевода реплика может уйти соседу.

Точнее — по событиям перевода из AMI (`telephony.transfers`): момент
перевода режет окна. Переводивший ведёт разговор до него, принявший — с
него: при переводе с предупреждением второй оператор снимает трубку на
консультации, пока клиент слушает музыку ожидания, и по CDR его окно
начиналось раньше, чем клиент его слышит.
"""
from __future__ import annotations

from typing import Any

from ..content.sentiment import score_text

#: Окно короче — не участие (перехват и сразу отбой, ошибка набора).
МИН_ОКНО_С = 1.0


def _число(значение: Any) -> float:
    try:
        return float(значение or 0)
    except (TypeError, ValueError):
        return 0.0


def _ответ(нога: dict[str, Any]) -> float:
    """Когда ногу сняли: начало + (длительность − разговор)."""
    начало = _число(нога.get("started_at"))
    длительность, разговор = _число(нога.get("duration")), _число(нога.get("billsec"))
    return начало + max(0.0, длительность - разговор)


def _ноль(звонок: dict[str, Any], ноги: list[dict[str, Any]]) -> float:
    """Ноль времени записи: ответ записанной ноги, без него — первый ответ."""
    if _число(звонок.get("billsec")) > 0:
        return _ответ(звонок)
    ответы = [_ответ(н) for н in ноги if _число(н.get("billsec")) > 0]
    return min(ответы) if ответы else _ответ(звонок)


def окна(звонок: dict[str, Any], ноги: list[dict[str, Any]], *,
         длительность: float = 0.0,
         переводы: list[dict[str, Any]] | None = None) -> list[dict[str, Any]]:
    """Окна участников на времени записи — по ногам с ответом и добавочным.

    `переводы` — события перевода разговора (`call_transfers`): момент
    перевода — конец окна переводившего и начало окна принявшего, если
    момент внутри окна.
    """
    все = [звонок, *[н for н in ноги if н.get("uniqueid") != звонок.get("uniqueid")]]
    с_разговором = [н for н in все if _число(н.get("billsec")) > 0]
    if not с_разговором:
        return []
    ноль = _ноль(звонок, ноги)
    итог: list[dict[str, Any]] = []
    for нога in sorted(с_разговором, key=lambda н: (int(_число(н.get("sequence"))),
                                                     _число(н.get("started_at")))):
        кто = str(нога.get("agent") or "").strip()
        if not кто:
            continue
        с = _ответ(нога) - ноль
        по = с + _число(нога.get("billsec"))
        с = max(0.0, с)
        if длительность > 0:
            по = min(по, длительность)
        if по - с < МИН_ОКНО_С:
            continue
        итог.append({"agent": кто, "from_s": round(с, 1), "to_s": round(по, 1),
                     "uniqueid": str(нога.get("uniqueid") or ""),
                     "queue": str(нога.get("queue") or ""),
                     "recorded": нога is звонок})
    for перевод in переводы or []:
        момент = round(_число(перевод.get("ts")) - ноль, 1)
        от, к = str(перевод.get("from_agent") or ""), str(перевод.get("to_agent") or "")
        for окно in итог:
            if not (окно["from_s"] < момент < окно["to_s"]):
                continue
            if окно["agent"] == от and от != к:
                окно["to_s"], окно["by_event"] = момент, True
            elif окно["agent"] == к and от != к:
                окно["from_s"], окно["by_event"] = момент, True
    return [о for о in итог if о["to_s"] - о["from_s"] >= МИН_ОКНО_С]


def _чьё(окна_: list[dict[str, Any]], момент: float) -> dict[str, Any] | None:
    подходят = [о for о in окна_ if о["from_s"] <= момент < о["to_s"]]
    if подходят:
        return max(подходят, key=lambda о: о["from_s"])      # подключился позже — ведёт
    if not окна_:
        return None
    # Мимо окон (часы станции, хвост записи) — ближайшее окно.
    return min(окна_, key=lambda о: min(abs(момент - о["from_s"]), abs(момент - о["to_s"])))


def по_участникам(звонок: dict[str, Any], ноги: list[dict[str, Any]],
                  реплики: list[dict[str, Any]], *, длительность: float = 0.0,
                  переводы: list[dict[str, Any]] | None = None
                  ) -> dict[str, Any] | None:
    """Отрезки записи по участникам и оценка каждого; None — участник один.

    `segments` — подряд идущие отрезки одного участника (как их видно на
    времени записи), `agents` — итог по участнику: сколько звучал, слов,
    доля разговора и тональность его отрезков.
    """
    окна_ = окна(звонок, ноги, длительность=длительность, переводы=переводы)
    if len({о["agent"] for о in окна_}) < 2:
        return None
    отрезки: list[dict[str, Any]] = []
    for реплика in реплики:
        начало = _число(реплика.get("start", реплика.get("start_s")))
        конец = _число(реплика.get("end", реплика.get("end_s"))) or начало
        текст = str(реплика.get("text") or "").strip()
        if not текст:
            continue
        окно = _чьё(окна_, (начало + конец) / 2)
        if окно is None:
            continue
        if отрезки and отрезки[-1]["agent"] == окно["agent"]:
            отрезок = отрезки[-1]
            отрезок["to_s"] = round(max(отрезок["to_s"], конец), 1)
        else:
            отрезок = {"agent": окно["agent"], "queue": окно["queue"],
                       "from_s": round(начало, 1), "to_s": round(конец, 1),
                       "_тексты": [], "_звучало": 0.0}
            отрезки.append(отрезок)
        отрезок["_тексты"].append(текст)
        отрезок["_звучало"] += max(0.0, конец - начало)
    всего_звучало = sum(о["_звучало"] for о in отрезки) or 1.0
    участники: dict[str, dict[str, Any]] = {}
    for отрезок in отрезки:
        тексты, звучало = отрезок.pop("_тексты"), отрезок.pop("_звучало")
        отрезок.update(replicas=len(тексты), words=sum(len(т.split()) for т in тексты),
                       talk_s=round(звучало, 1),
                       sentiment=score_text(тексты).to_dict(),
                       preview=" ".join(тексты)[:200])
        итог = участники.setdefault(отрезок["agent"], {
            "agent": отрезок["agent"], "talk_s": 0.0, "words": 0, "replicas": 0,
            "segments": 0, "_тексты": []})
        итог["talk_s"] += звучало
        итог["words"] += отрезок["words"]
        итог["replicas"] += len(тексты)
        итог["segments"] += 1
        итог["_тексты"].extend(тексты)
    for итог in участники.values():
        итог["sentiment"] = score_text(итог.pop("_тексты")).to_dict()
        итог["share"] = round(итог["talk_s"] / всего_звучало, 3)
        итог["talk_s"] = round(итог["talk_s"], 1)
    по_событиям = any(о.get("by_event") for о in окна_)
    return {"windows": окна_, "segments": отрезки, "agents": list(участники.values()),
            "zero": "ответ записанной ноги",
            "transfers": [{"at_s": round(_число(п.get("ts")) - _ноль(звонок, ноги), 1),
                           "kind": п.get("kind"), "from_agent": п.get("from_agent"),
                           "to_agent": п.get("to_agent")} for п in переводы or []],
            "note": ("по времени ног CDR, граница перевода — по событию AMI" if по_событиям
                     else "по времени ног CDR; на границе перевода реплика может уйти соседу")}
