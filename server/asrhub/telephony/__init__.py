"""Телефония: записи разговоров приезжают с АТС сами.

Речевая аналитика начинается не с распознавания, а с вопроса «где взять
записи». Пока их носят руками, разбор охватывает те разговоры, о которых
кто-то вспомнил, — то есть в основном скандальные. Здесь сервер забирает
записи с Asterisk сам, каждую, со всеми полями звонка: кто звонил, кому,
куда попал, сколько ждал, чем кончилось.

Внутри три части: `asterisk` — разговор с самой АТС (интерфейс управления
AMI, журнал звонков, поиск файла записи), `stations` — описание станций и
разбор их списка из настроек, и `importer` — фоновые потоки, которые
превращают звонки в задания распознавания и не дают завести одно и то же
задание дважды.

Станций может быть сколько угодно, и у каждой своё всё: источник, учётные
данные, каталог записей, длины внутренних номеров, правила контекстов,
владелец, приоритет. `Импортёр` обслуживает одну станцию, `Телефония`
держит их набор.
"""
