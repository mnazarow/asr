"""Подсказки оператору прямо в идущем разговоре.

Самая дорогая доработка из отраслевого списка и самый частый вопрос
заказчика. Дорогая она не из-за подсказок — те считаются теми же правилами,
что и после разговора, — а из-за потокового распознавания под ними. Оно у
сервера уже есть (движок T-one, куски по 300 мс), и это меняет цену: здесь
надстройка, а не новая подсистема.

Что подсказывается:

* **Пункт скрипта, который ещё не прозвучал.** Не «вы забыли» в конце
  разговора, а «осталось: представиться» посреди него — пока это ещё можно
  исправить.
* **Сработавшая категория с пометкой «сообщать».** Те самые трекеры, что
  после разговора шлют уведомление: в живом разговоре они нужнее.
* **Нарушение.** Стоп-слово или запрещённый оборот — сразу, и заметно.
* **Возражение без отработки.** Клиент возразил, а в следующих репликах
  оператора нет ни одной отработки — самое частое место, где теряют сделку.

Два решения, за которыми стоит опыт, а не вкус:

1. **Подсказки считаются только по ЗАКРЕПЛЁННОМУ тексту** (`final`), а не по
   предварительной гипотезе. Гипотеза переписывается на каждом куске звука, и
   подсказка, посчитанная по ней, мигает: появилась, исчезла, появилась
   снова. Оператор в разговоре на такое не смотрит — он его выключает.
2. **Одна и та же подсказка не повторяется.** Сказанное один раз висит, пока
   не станет неверным. Повторять «представьтесь» каждые три секунды — это
   способ добиться, чтобы помощника отключили в первый же день.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .content import categories as категории_модуль
from .content import compliance
from .logging_setup import get_logger

log = get_logger("liveassist")

#: Сколько реплик оператора даётся на отработку возражения, прежде чем
#: подсказать. Три — столько же, сколько у разбора после разговора: если
#: числа разойдутся, живая подсказка и итоговый отчёт начнут спорить.
РЕПЛИК_НА_ОТРАБОТКУ = 3

#: Через сколько секунд разговора напоминать о непройденных пунктах скрипта.
#: Раньше — бессмысленно (человек ещё здоровается), позже — поздно.
НАПОМНИТЬ_ЧЕРЕЗ_С = 25.0

#: Сколько подсказок показывать разом. Больше трёх в живом разговоре не
#: читает никто.
СРАЗУ = 3

ВАЖНОСТЬ = {"violation": 3, "objection": 2, "tracker": 2, "script": 1}


@dataclass
class Подсказка:
    kind: str
    title: str
    detail: str = ""
    category: str = ""

    def ключ(self) -> str:
        return f"{self.kind}:{self.category or self.title}"

    def to_dict(self) -> dict[str, Any]:
        return {"kind": self.kind, "title": self.title,
                "detail": self.detail, "category": self.category,
                "weight": ВАЖНОСТЬ.get(self.kind, 0)}


@dataclass
class Помощник:
    """Состояние подсказок для одного разговора."""

    категории: list[Any] = field(default_factory=list)
    скрипт: list[dict[str, Any]] = field(default_factory=list)
    оператор: str = ""
    реплики: list[dict[str, Any]] = field(default_factory=list)
    показанные: set[str] = field(default_factory=set)

    @classmethod
    def из_настроек(cls, settings: Any, *, agent: str = "") -> Помощник:
        """Собирает помощника из тех же настроек, что и разбор после разговора.

        Правила берутся ровно те же — иначе живая подсказка и итоговый отчёт
        будут говорить разное об одном разговоре, и верить перестанут обоим.
        """
        свои = (settings or {}).get("content_categories")
        отрасль = str((settings or {}).get("content_category_preset") or "")
        сырые = (свои if isinstance(свои, list) and свои
                 else категории_модуль.с_набором(отрасль))
        скрипт = (settings or {}).get("content_script")
        return cls(
            категории=категории_модуль.compile(сырые),
            скрипт=(скрипт if isinstance(скрипт, list) and скрипт
                    else list(compliance.ПО_УМОЛЧАНИЮ)),
            оператор=str(agent or (settings or {}).get("content_agent_speaker") or ""))

    def добавить(self, text: str, *, speaker: str = "",
                 start: float = 0.0, end: float = 0.0) -> list[Подсказка]:
        """Принимает закреплённую реплику и возвращает НОВЫЕ подсказки.

        Новые — то есть те, которых человек ещё не видел. Повторять уже
        показанное значит добиться, чтобы помощника отключили.
        """
        чистый = str(text or "").strip()
        if not чистый:
            return []
        self.реплики.append({"start": float(start), "end": float(end),
                             "speaker": str(speaker or ""), "text": чистый})
        найденные = [*self._нарушения(), *self._трекеры(),
                     *self._возражения(), *self._скрипт(end)]
        новые: list[Подсказка] = []
        for подсказка in найденные:
            ключ = подсказка.ключ()
            if ключ in self.показанные:
                continue
            self.показанные.add(ключ)
            новые.append(подсказка)
        новые.sort(key=lambda п: -ВАЖНОСТЬ.get(п.kind, 0))
        return новые[:СРАЗУ]

    # -- источники подсказок ------------------------------------------------

    def _разбор(self) -> dict[str, Any]:
        return категории_модуль.apply(self.реплики, self.категории,
                                      agent=self.оператор or None)

    def _нарушения(self) -> list[Подсказка]:
        разбор = self._разбор()
        готово: list[Подсказка] = []
        for нарушение in (разбор.get("violations") or []):
            имя = str(нарушение.get("label") or нарушение.get("id") or "")
            готово.append(Подсказка(
                "violation", f"Нарушение: {имя}",
                detail=str((нарушение.get("hits") or [{}])[0].get("matched") or ""),
                category=str(нарушение.get("id") or имя)))
        return готово

    def _трекеры(self) -> list[Подсказка]:
        """Категории с пометкой «сообщать» — те же, что шлют уведомление.

        Флаг берётся у СОБРАННЫХ правил, а не из разбора: `apply` его в свой
        ответ не кладёт, и проверка «пункт.get(\"notify\")» была бы вечно
        ложной — трекеры молча не подсказывались бы никогда.
        """
        сообщать = {str(к.id) for к in self.категории if getattr(к, "notify", False)}
        if not сообщать:
            return []
        разбор = self._разбор()
        готово: list[Подсказка] = []
        for пункт in (разбор.get("items") or []):
            if not пункт.get("count") or str(пункт.get("id")) not in сообщать:
                continue
            имя = str(пункт.get("label") or пункт.get("id") or "")
            готово.append(Подсказка(
                "tracker", имя,
                detail=str((пункт.get("hits") or [{}])[0].get("text") or "")[:160],
                category=str(пункт.get("id") or имя)))
        return готово

    def _возражения(self) -> list[Подсказка]:
        """Возражение, на которое оператор ещё не ответил.

        Считается так же, как после разговора: окно в три реплики оператора.
        Расходиться этим числам нельзя — иначе подсказка и отчёт спорят.
        """
        разбор = self._разбор()
        свод = разбор.get("objections") or {}
        if not свод.get("unhandled"):
            return []
        последнее = (свод.get("items") or [{}])[-1]
        return [Подсказка(
            "objection", "Возражение без отработки",
            detail=str(последнее.get("text") or "")[:160],
            category=str(последнее.get("category") or "objection"))]

    def _скрипт(self, сейчас: float) -> list[Подсказка]:
        if сейчас < НАПОМНИТЬ_ЧЕРЕЗ_С:
            return []
        итог = compliance.check(self.реплики, script=self.скрипт,
                                speaker=self.оператор or None)
        пропущены = [п for п in (итог.get("items") or []) if not п.get("done")]
        if not пропущены:
            return []
        имена = ", ".join(str(п.get("label") or п.get("id") or "") for п in пропущены[:3])
        return [Подсказка(
            "script", "Осталось по скрипту", detail=имена,
            category="script:" + ",".join(str(п.get("id") or "") for п in пропущены[:3]))]
