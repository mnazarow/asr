"""Подсказки оператору прямо в идущем разговоре.

Самая дорогая доработка из отраслевого списка и самый частый вопрос
заказчика. Дорогая она не из-за подсказок — те считаются теми же правилами,
что и после разговора, — а из-за потокового распознавания под ними. Оно у
сервера уже есть (движок T-one, куски по 300 мс), и это меняет цену: здесь
надстройка, а не новая подсистема.

Что подсказывается:

* **Пункт скрипта, который ещё не прозвучал.** Не «вы забыли» в конце
  разговора, а «осталось: представиться» посреди него — пока это ещё можно
  исправить.
* **Сработавшая категория с пометкой «сообщать».** Те самые трекеры, что
  после разговора шлют уведомление: в живом разговоре они нужнее.
* **Нарушение.** Стоп-слово или запрещённый оборот — сразу, и заметно.
* **Возражение без отработки.** Клиент возразил, а в следующих репликах
  оператора нет ни одной отработки — самое частое место, где теряют сделку.

Два решения, за которыми стоит опыт, а не вкус:

1. **Подсказки считаются только по ЗАКРЕПЛЁННОМУ тексту** (`final`), а не по
   предварительной гипотезе. Гипотеза переписывается на каждом куске звука, и
   подсказка, посчитанная по ней, мигает: появилась, исчезла, появилась
   снова. Оператор в разговоре на такое не смотрит — он его выключает.
2. **Одна и та же подсказка не повторяется.** Сказанное один раз висит, пока
   не станет неверным. Повторять «представьтесь» каждые три секунды — это
   способ добиться, чтобы помощника отключили в первый же день.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .content import categories as категории_модуль
from .content import compliance
from .logging_setup import get_logger

log = get_logger("liveassist")

#: Сколько реплик даётся на отработку возражения, прежде чем подсказать.
#: Три — столько же, сколько у разбора после разговора (`ОКНО_ОТРАБОТКИ`):
#: если числа разойдутся, живая подсказка и итоговый отчёт начнут спорить.
#: Раньше число было объявлено и не применялось нигде: подсказка приходила
#: прямо на реплике возражения, когда ответить на него ещё никто не успел.
РЕПЛИК_НА_ОТРАБОТКУ = категории_модуль.ОКНО_ОТРАБОТКИ

#: Через сколько секунд разговора напоминать о непройденных пунктах скрипта.
#: Раньше — бессмысленно (человек ещё здоровается), позже — поздно.
НАПОМНИТЬ_ЧЕРЕЗ_С = 25.0

#: Сколько подсказок показывать разом. Больше трёх в живом разговоре не
#: читает никто.
СРАЗУ = 3

ВАЖНОСТЬ = {"violation": 3, "objection": 2, "tracker": 2, "script": 1}


@dataclass
class Подсказка:
    kind: str
    title: str
    detail: str = ""
    category: str = ""

    def ключ(self) -> str:
        return f"{self.kind}:{self.category or self.title}"

    def to_dict(self) -> dict[str, Any]:
        return {"kind": self.kind, "title": self.title,
                "detail": self.detail, "category": self.category,
                "weight": ВАЖНОСТЬ.get(self.kind, 0)}


@dataclass
class Помощник:
    """Состояние подсказок для одного разговора."""

    категории: list[Any] = field(default_factory=list)
    скрипт: list[dict[str, Any]] = field(default_factory=list)
    оператор: str = ""
    реплики: list[dict[str, Any]] = field(default_factory=list)
    показанные: set[str] = field(default_factory=set)

    @classmethod
    def из_настроек(cls, settings: Any, *, agent: str = "") -> Помощник:
        """Собирает помощника из тех же настроек, что и разбор после разговора.

        Правила берутся ровно те же — иначе живая подсказка и итоговый отчёт
        будут говорить разное об одном разговоре, и верить перестанут обоим.
        """
        свои = (settings or {}).get("content_categories")
        отрасль = str((settings or {}).get("content_category_preset") or "")
        сырые = (свои if isinstance(свои, list) and свои
                 else категории_модуль.с_набором(отрасль))
        скрипт = (settings or {}).get("content_script")
        return cls(
            категории=категории_модуль.compile(сырые),
            скрипт=(скрипт if isinstance(скрипт, list) and скрипт
                    else list(compliance.ПО_УМОЛЧАНИЮ)),
            оператор=str(agent or (settings or {}).get("content_agent_speaker") or ""))

    def добавить(self, text: str, *, speaker: str = "",
                 start: float = 0.0, end: float = 0.0) -> list[Подсказка]:
        """Принимает закреплённую реплику и возвращает НОВЫЕ подсказки.

        Новые — то есть те, которых человек ещё не видел. Повторять уже
        показанное значит добиться, чтобы помощника отключили.
        """
        чистый = str(text or "").strip()
        if not чистый:
            return []
        self.реплики.append({"start": float(start), "end": float(end),
                             "speaker": str(speaker or ""), "text": чистый})
        # Разбор — ОДИН на реплику. Раньше его считал каждый источник
        # подсказок заново, по всем накопленным репликам: трижды на реплику,
        # и на часовом разговоре это складывалось в заметную нагрузку.
        разбор = self._разбор()
        найденные = [*self._нарушения(разбор), *self._трекеры(разбор),
                     *self._возражения(разбор), *self._скрипт(end)]
        новые: dict[str, Подсказка] = {}
        for подсказка in найденные:
            ключ = подсказка.ключ()
            if ключ not in self.показанные and ключ not in новые:
                новые[ключ] = подсказка
        отданные = sorted(новые.values(), key=lambda п: -ВАЖНОСТЬ.get(п.kind, 0))[:СРАЗУ]
        # Показанными помечаются только ОТДАННЫЕ. Раньше помечалось всё
        # найденное, а отдавались первые три: подсказка сверх трёх (обычно
        # «осталось по скрипту» — у неё самый низкий вес) считалась
        # показанной, хотя её никто не видел, и не приходила уже никогда.
        self.показанные.update(п.ключ() for п in отданные)
        return отданные

    # -- источники подсказок ------------------------------------------------

    def _клиент_слышен(self) -> bool:
        """Есть ли в разговоре реплики клиента, а не только оператора.

        В потоке одна дорожка — гарнитура оператора, — и все реплики
        подписаны оператором. Категории «только клиент» тогда искали по
        всему тексту, то есть по речи самого оператора: «вам не нужно ничего
        делать» давало «возражение без отработки».
        """
        метки = {str(р.get("speaker") or "") for р in self.реплики}
        if self.оператор:
            return any(м != self.оператор for м in метки)
        return len(метки - {""}) > 1

    def _разбор(self) -> dict[str, Any]:
        категории = self.категории
        if not self._клиент_слышен():
            категории = [к for к in категории
                         if getattr(к, "who", "") != "customer"
                         and getattr(к, "kind", "") != "objection"]
        return категории_модуль.apply(self.реплики, категории,
                                      agent=self.оператор or None,
                                      objections_limit=10**6)

    def _нарушения(self, разбор: dict[str, Any]) -> list[Подсказка]:
        # Что именно сработало, берётся из примеров категории: в списке
        # нарушений `apply` примеров не кладёт, и подсказка приходила с
        # пустой подробностью — оператор видел «Нарушение: стоп-слова», но
        # не видел, какое слово.
        примеры = {str(п.get("id")): п.get("hits") or [] for п in (разбор.get("items") or [])}
        готово: list[Подсказка] = []
        for нарушение in (разбор.get("violations") or []):
            имя = str(нарушение.get("label") or нарушение.get("id") or "")
            попадания = примеры.get(str(нарушение.get("id"))) or [{}]
            готово.append(Подсказка(
                "violation", f"Нарушение: {имя}",
                detail=str(попадания[-1].get("matched") or ""),
                category=str(нарушение.get("id") or имя)))
        return готово

    def _трекеры(self, разбор: dict[str, Any]) -> list[Подсказка]:
        """Категории с пометкой «сообщать» — те же, что шлют уведомление.

        Флаг берётся у СОБРАННЫХ правил, а не из разбора: `apply` его в свой
        ответ не кладёт, и проверка «пункт.get(\"notify\")» была бы вечно
        ложной — трекеры молча не подсказывались бы никогда.
        """
        сообщать = {str(к.id) for к in self.категории if getattr(к, "notify", False)}
        if not сообщать:
            return []
        готово: list[Подсказка] = []
        for пункт in (разбор.get("items") or []):
            if not пункт.get("count") or str(пункт.get("id")) not in сообщать:
                continue
            имя = str(пункт.get("label") or пункт.get("id") or "")
            готово.append(Подсказка(
                "tracker", имя,
                detail=str((пункт.get("hits") or [{}])[0].get("text") or "")[:160],
                category=str(пункт.get("id") or имя)))
        return готово

    def _возражения(self, разбор: dict[str, Any]) -> list[Подсказка]:
        """Возражения, на которые за окно в три реплики не ответили.

        Считается так же, как после разговора: окно в три реплики.
        Расходиться этим числам нельзя — иначе подсказка и отчёт спорят. И
        подсказка приходит, только когда окно ПРОШЛО: на самой реплике
        возражения ответа ещё нет и быть не может. Каждое возражение — своя
        подсказка (номер реплики в ключе): второе возражение в том же
        разговоре раньше молчало, потому что ключ был общий на категорию.
        """
        свод = разбор.get("objections") or {}
        if свод.get("unhandled") is None:
            return []
        последняя = len(self.реплики) - 1
        готово: list[Подсказка] = []
        for возражение in свод.get("items") or []:
            номер = возражение.get("index")
            if возражение.get("handled") is not False or номер is None:
                continue
            if последняя - int(номер) < РЕПЛИК_НА_ОТРАБОТКУ:
                continue
            готово.append(Подсказка(
                "objection", "Возражение без отработки",
                detail=str(возражение.get("text") or "")[:160],
                category=f"{возражение.get('category') or 'objection'}#{номер}"))
        return готово

    def _скрипт(self, сейчас: float) -> list[Подсказка]:
        """Пункты скрипта, которые ещё не прозвучали и ещё могут прозвучать.

        Не напоминаем о пунктах «в конце» (попрощаться посреди разговора
        нельзя), о пунктах «в начале», окно которых уже прошло (исправить
        уже нечего), и о пунктах, проверяемых по фактам, которых в живом
        разговоре нет («обратился по имени» знает только разбор после).
        """
        if сейчас < НАПОМНИТЬ_ЧЕРЕЗ_С:
            return []
        итог = compliance.check(self.реплики, script=self.скрипт,
                                speaker=self.оператор or None)
        пункты = {str(п.get("id")): п for п in self.скрипт if isinstance(п, dict)}
        первая = min((float(р.get("start") or 0.0) for р in self.реплики), default=0.0)
        пропущены = []
        for п in итог.get("items") or []:
            # Выполненный пункт отмечен ключом `passed`. Раньше проверялся
            # `done`, которого в ответе нет вовсе, — и напоминание «осталось
            # по скрипту» перечисляло всё, включая уже сказанное.
            if п.get("passed"):
                continue
            исходный = пункты.get(str(п.get("id"))) or {}
            if исходный.get("check"):
                continue
            где = str(п.get("where") or "any")
            if где == "end":
                continue
            окно = float(п.get("within_s") or 0)
            if где == "start" and окно and сейчас - первая > окно:
                continue
            пропущены.append(п)
        if not пропущены:
            return []
        имена = ", ".join(str(п.get("label") or п.get("id") or "") for п in пропущены[:3])
        return [Подсказка(
            "script", "Осталось по скрипту", detail=имена,
            category="script:" + ",".join(str(п.get("id") or "") for п in пропущены[:3]))]
