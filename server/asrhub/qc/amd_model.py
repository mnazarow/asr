"""Автоответчик моделью: классификатор первых секунд после ответа.

Правило (`survey.определить_автоответчик`) смотрит на длину первой реплики,
тишину после неё и гудок голосовой почты. На станции с необычной голосовой
почтой (короткое приветствие без гудка, музыка) или с людьми, которые
отвечают длинно («Добрый день, компания такая-то, слушаю вас»), правило
ошибается одинаково из раза в раз. Здесь — модель, которая учится на
записях опросов этой станции (`qc_record`), размеченных человеком в
журнале: «человек» или «автоответчик».

Признаки — из первых четырёх секунд звука клиента: сколько звука уже
слышно, сколько тишины до первой реплики, длина первой реплики и самой
длинной, тишина после первой, доля речи, число реплик, гудок и громкость
речи. Звонок решается по ходу — с двух секунд, — поэтому каждая размеченная
запись даёт признаки на 2; 2,5; 3; 3,5 и 4 с: модель учится и на неполном
окне, как его увидит телефон. Модель — логистическая
регрессия на нормированных признаках, обучается здесь же градиентным
спуском (без внешних библиотек); точность — перекрёстной проверкой по
пяти частям. Признаки размеченной записи сохраняются вместе с меткой: сама
запись уходит по сроку `qc_record_days`, а обучать можно и после.

Решение модели принимается только уверенное (`qc_amd_model_confidence`):
сомнительный случай решает правило. Гудок голосовой почты — всегда
автоответчик, без модели.
"""
from __future__ import annotations

import json
import math
import random
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

#: Сколько секунд звука клиента смотрит модель.
ОКНО_С = 4.0
#: Байт в секунде звука клиента: 8 кГц, 16 бит.
БАЙТ_В_С = 16000
#: Метки разметки.
ЧЕЛОВЕК, АВТООТВЕТЧИК = "человек", "автоответчик"
МЕТКИ = (ЧЕЛОВЕК, АВТООТВЕТЧИК)
#: Меньше размеченных записей (всего и в каждом классе) — не обучать.
МИН_ВСЕГО, МИН_В_КЛАССЕ = 20, 5
#: Имя файла модели в каталоге данных.
ФАЙЛ = "qc_amd_model.json"

ПРИЗНАКИ = ("слышно_с", "тишина_до_с", "первая_реплика_с", "самая_длинная_с",
            "тишина_после_первой_с", "доля_речи", "реплик", "гудок", "громкость")
#: На каких секундах звука считаются признаки размеченной записи.
ОКНА_С = (2.0, 2.5, 3.0, 3.5, 4.0)


def _отрезки(кадры: list[bool], *, разрыв: int = 10) -> list[tuple[int, int]]:
    """Реплики — подряд идущие кадры речи; паузы короче `разрыв` кадров
    (0,2 с) не разрывают реплику."""
    итог: list[tuple[int, int]] = []
    for н, речь in enumerate(кадры):
        if not речь:
            continue
        if итог and н - итог[-1][1] <= разрыв:
            итог[-1] = (итог[-1][0], н)
        else:
            итог.append((н, н))
    return итог


def признаки(pcm: bytes) -> list[float]:
    """Признаки первых `ОКНО_С` секунд звука клиента (PCM 16 бит, 8 кГц)."""
    import array  # noqa: PLC0415

    from .survey import _КАДР_РЕЧИ, гудок, кадры_речи  # noqa: PLC0415

    окно = pcm[:int(ОКНО_С * БАЙТ_В_С)]
    окно = окно[:len(окно) - len(окно) % 2]
    кадры = кадры_речи(окно)
    всего = max(1, len(кадры))
    реплики = _отрезки(кадры)
    if реплики:
        первая = реплики[0]
        тишина_до = первая[0] * 0.02
        первая_с = (первая[1] - первая[0] + 1) * 0.02
        самая = max(к - н + 1 for н, к in реплики) * 0.02
        следующая = реплики[1][0] if len(реплики) > 1 else len(кадры)
        тишина_после = (следующая - первая[1] - 1) * 0.02
    else:
        тишина_до, первая_с, самая, тишина_после = len(кадры) * 0.02, 0.0, 0.0, 0.0
    громкости = []
    for н, речь in enumerate(кадры):
        if речь:
            отсчёты = array.array("h", окно[н * _КАДР_РЕЧИ:(н + 1) * _КАДР_РЕЧИ])
            if отсчёты:
                громкости.append(math.sqrt(sum(о * о for о in отсчёты) / len(отсчёты)))
    громкость = math.log10(1 + sum(громкости) / len(громкости)) if громкости else 0.0
    return [round(len(окно) / БАЙТ_В_С, 3),
            round(тишина_до, 3), round(первая_с, 3), round(самая, 3), round(тишина_после, 3),
            round(sum(кадры) / всего, 4), float(len(реплики)), 1.0 if гудок(окно) else 0.0,
            round(громкость, 4)]


def признаки_по_окнам(pcm: bytes) -> list[list[float]]:
    """Признаки размеченной записи на каждом из `ОКНА_С` (сколько звука есть)."""
    итог: list[list[float]] = []
    for окно in ОКНА_С:
        кусок = pcm[:int(окно * БАЙТ_В_С)]
        if итог and len(кусок) < int(окно * БАЙТ_В_С):
            break
        итог.append(признаки(кусок))
    return итог


def звук_клиента_из_wav(путь: Path, *, с: float | None = None) -> bytes:
    """Левый канал записи опроса (клиент) — моно PCM 16 бит, от момента `с`.

    Запись идёт от ответа, а телефон начинает слушать после паузы
    (`survey.ПАУЗА_ПОСЛЕ_ОТВЕТА_С`): признаки размеченной записи считаются с
    того же места, с которого их увидит звонок. С начала записи «тишина до
    первой реплики» выходила на длину паузы больше, чем у живого звонка, а
    окно в две секунды захватывало другой кусок звука.
    """
    import wave  # noqa: PLC0415

    if с is None:
        from .survey import ПАУЗА_ПОСЛЕ_ОТВЕТА_С  # noqa: PLC0415

        с = ПАУЗА_ПОСЛЕ_ОТВЕТА_С
    with wave.open(str(путь), "rb") as wav:
        каналов, ширина, частота = wav.getnchannels(), wav.getsampwidth(), wav.getframerate()
        if ширина != 2 or частота * 2 != БАЙТ_В_С:
            raise ValueError("запись опроса — не 16 бит 8 кГц")
        wav.setpos(min(wav.getnframes(), int(max(0.0, с) * частота)))
        данные = wav.readframes(int(ОКНО_С * частота) + 1)
    if каналов == 1:
        return данные
    шаг = 2 * каналов
    return b"".join(данные[н:н + 2] for н in range(0, len(данные) - шаг + 1, шаг))


def _сигмоида(z: float) -> float:
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


@dataclass
class Модель:
    """Логистическая регрессия: вероятность автоответчика по признакам."""

    среднее: list[float]
    разброс: list[float]
    веса: list[float]
    сдвиг: float
    обучена: float = 0.0
    образцов: int = 0
    точность: float | None = None
    по_классам: dict[str, int] = field(default_factory=dict)

    def вероятность(self, значения: list[float]) -> float:
        z = self.сдвиг + sum(в * (x - с) / р for в, x, с, р in
                             zip(self.веса, значения, self.среднее, self.разброс, strict=False))
        return _сигмоида(z)

    def наружу(self) -> dict[str, Any]:
        return {"features": list(ПРИЗНАКИ), "mean": self.среднее, "std": self.разброс,
                "weights": self.веса, "bias": self.сдвиг, "trained_at": self.обучена,
                "samples": self.образцов, "accuracy": self.точность,
                "by_label": self.по_классам}

    @classmethod
    def из_словаря(cls, д: dict[str, Any]) -> Модель:
        if list(д.get("features") or []) != list(ПРИЗНАКИ):
            raise ValueError("модель обучена на другом наборе признаков")
        среднее = [float(x) for x in д["mean"]]
        разброс = [float(x) for x in д["std"]]
        веса = [float(x) for x in д["weights"]]
        сдвиг = float(д["bias"])
        # Файл правят и руками: короткий список молча отбросил бы признаки
        # (zip по короткому), нулевой разброс — деление на ноль посреди звонка.
        if not (len(среднее) == len(разброс) == len(веса) == len(ПРИЗНАКИ)):
            raise ValueError("в модели не столько чисел, сколько признаков")
        if not all(math.isfinite(x) for x in (*среднее, *разброс, *веса, сдвиг)) \
                or any(р == 0 for р in разброс):
            raise ValueError("в модели не числа или нулевой разброс")
        точность = д.get("accuracy")
        return cls(среднее=среднее, разброс=разброс, веса=веса, сдвиг=сдвиг,
                   обучена=float(д.get("trained_at") or 0), образцов=int(д.get("samples") or 0),
                   точность=float(точность) if точность is not None else None,
                   по_классам=dict(д.get("by_label") or {}))


def _обучить(образцы: list[tuple[list[float], int]], *, шагов: int | None = None,
             скорость: float = 0.3, l2: float = 0.01) -> Модель:
    размер = len(ПРИЗНАКИ)
    n = len(образцы)
    # Шагов меньше на большой разметке: полный проход — n × признаков, а
    # обучение идёт в запросе администратора, не дольше нескольких секунд.
    шагов = шагов or max(300, min(1500, 300000 // max(1, n)))
    среднее = [sum(x[i] for x, _ in образцы) / n for i in range(размер)]
    разброс = []
    for i in range(размер):
        д = math.sqrt(sum((x[i] - среднее[i]) ** 2 for x, _ in образцы) / n)
        разброс.append(д if д > 1e-6 else 1.0)
    нормы = [[(x[i] - среднее[i]) / разброс[i] for i in range(размер)] for x, _ in образцы]
    метки = [y for _, y in образцы]
    веса, сдвиг = [0.0] * размер, 0.0
    for _ in range(шагов):
        град = [0.0] * размер
        град_сдвига = 0.0
        for x, y in zip(нормы, метки, strict=False):
            ошибка = _сигмоида(сдвиг + sum(в * xi for в, xi in zip(веса, x, strict=False))) - y
            for i in range(размер):
                град[i] += ошибка * x[i]
            град_сдвига += ошибка
        for i in range(размер):
            веса[i] -= скорость * (град[i] / n + l2 * веса[i])
        сдвиг -= скорость * град_сдвига / n
    return Модель(среднее=среднее, разброс=разброс, веса=веса, сдвиг=сдвиг)


def обучить(размеченные: list[tuple[list[list[float]], str]], *, частей: int = 5,
            зерно: int = 69) -> Модель:
    """Модель по размеченным записям; точность — перекрёстной проверкой.

    Запись — (признаки на каждом окне `признаки_по_окнам`, метка). Части
    перекрёстной проверки — по записям, а не по окнам: окна одной записи в
    обучении и в проверке разом дали бы точность лучше настоящей.
    `ValueError` — записей мало: меньше `МИН_ВСЕГО` или меньше `МИН_В_КЛАССЕ`
    в одном из классов.
    """
    записи = [([list(map(float, x)) for x in окна if len(x) == len(ПРИЗНАКИ)],
               1 if метка == АВТООТВЕТЧИК else 0)
              for окна, метка in размеченные if метка in МЕТКИ]
    записи = [(окна, y) for окна, y in записи if окна]
    по_классам = {ЧЕЛОВЕК: sum(1 for _, y in записи if y == 0),
                  АВТООТВЕТЧИК: sum(1 for _, y in записи if y == 1)}
    if len(записи) < МИН_ВСЕГО or min(по_классам.values()) < МИН_В_КЛАССЕ:
        raise ValueError(
            f"Мало размеченных записей: нужно хотя бы {МИН_ВСЕГО}, из них не меньше "
            f"{МИН_В_КЛАССЕ} каждого вида (сейчас человек {по_классам[ЧЕЛОВЕК]}, "
            f"автоответчик {по_классам[АВТООТВЕТЧИК]}).")

    def развернуть(часть: list[tuple[list[list[float]], int]]) -> list[tuple[list[float], int]]:
        return [(x, y) for окна, y in часть for x in окна]

    перемешаны = list(записи)
    random.Random(зерно).shuffle(перемешаны)
    верно = проверено = 0
    for часть in range(частей):
        проверка = перемешаны[часть::частей]
        обучение = [о for н, о in enumerate(перемешаны) if н % частей != часть]
        if not проверка or len({y for _, y in обучение}) < 2:
            continue
        модель_части = _обучить(развернуть(обучение))
        for x, y in развернуть(проверка):
            проверено += 1
            верно += (модель_части.вероятность(x) >= 0.5) == bool(y)
    модель = _обучить(развернуть(записи))
    модель.обучена = time.time()
    модель.образцов = len(записи)
    модель.точность = round(верно / проверено, 4) if проверено else None
    модель.по_классам = по_классам
    return модель


def сохранить(модель: Модель, каталог: Path) -> Path:
    путь = Path(каталог) / ФАЙЛ
    временный = путь.with_suffix(".tmp")
    временный.write_text(json.dumps(модель.наружу(), ensure_ascii=False, indent=1),
                         encoding="utf-8")
    временный.replace(путь)
    return путь


_ЗАГРУЖЕННАЯ: dict[str, tuple[float, Модель | None]] = {}


def загрузить(каталог: Path) -> Модель | None:
    """Модель из каталога данных; нет файла или он испорчен — None.

    Перечитывается, когда файл изменился: обучение на соседнем сервере над
    той же базой и каталогом подхватывается без перезапуска.
    """
    путь = Path(каталог) / ФАЙЛ
    try:
        отметка = путь.stat().st_mtime
    except OSError:
        return None
    было = _ЗАГРУЖЕННАЯ.get(str(путь))
    if было and было[0] == отметка:
        return было[1]
    try:
        модель: Модель | None = Модель.из_словаря(json.loads(путь.read_text(encoding="utf-8")))
    except (OSError, ValueError, KeyError, TypeError):
        модель = None
    _ЗАГРУЖЕННАЯ[str(путь)] = (отметка, модель)
    return модель
