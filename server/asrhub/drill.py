"""Раскрытие числа отчёта в список записей, из которых оно сложилось.

Любой раздел аналитики показывает числа: «отрицательных разговоров 42»,
«на модели X упало 7 заданий», «в понедельник в десять утра — 130 звонков».
Следующий вопрос человека всегда один: «какие именно?» Этот модуль на него
отвечает — одной ручкой на все разделы.

Устроено так, чтобы список не мог ни повесить сервер, ни разойтись с числом.

**Окно задаётся явно.** Своды считают границу периода от «сейчас» в момент
запроса, а список открывают позже — через минуту или через час. Если бы
список считал границу сам, он показывал бы уже другое окно. Поэтому каждый
свод отдаёт свои границы (`window`), а список принимает их параметрами.

**Отбор — из закрытого перечня.** Имя отбора приходит из строки запроса,
выражение SQL берётся отсюда и никогда из неё; значения уходят в запрос
только параметрами. Выражения те же, что у сводов (`CONTENT_GROUPS`,
`CONTENT_FILTERS` базы), — иначе число и список считались бы по-разному.

**Страницы — по ключу, а не по смещению.** `OFFSET 40000` читает сорок
тысяч строк, чтобы их выбросить; продолжение «после такой-то записи» идёт
по указателю и стоит одинаково на первой странице и на тысячной.

**Счёт — с потолком.** Точное «всего 1 284 301» никому не нужно, а стоит
полного прохода. Считаем до `ПРЕДЕЛ_СЧЁТА` и говорим «больше десяти тысяч».

**У запроса есть срок.** Редкий отбор за всё время читает архив целиком.
На миллионах записей это секунды, и держать ради них поток пула незачем:
запрос прерывается, а человек получает совет сузить период.

Колонку расшифровки (`jobs.text`) модуль не читает вовсе: список — это
«когда, что за запись, чем отличилась», а текст открывается по ссылке.
"""
