def раскрытие_показателя(ключ: str, лучше: int = 0) -> dict[str, Any] | None:
    """Чем раскрыть показатель свода «Аналитики записей» в список записей.

    Среднее раскрывается в записи, по которым оно посчитано, — у `AVG` это
    записи с непустой величиной — и упорядочено так, чтобы сверху стояли
    те, кто тянет показатель в плохую сторону: у «больше — лучше» это
    наименьшие, у остальных наибольшие. Пусто — показатель записями не
    выражается, и кнопки у него быть не должно: перечень показателей
    пополняется, а величина под новый ключ появляется не сама.

    Ответ — для `GET /api/drill`: `f` и `sort`; `value` — подпись столбца
    величины, когда она не совпадает с названием показателя; `zero_is_empty`
    — при нулевом значении раскрывать нечего.
    """
    особо = _ПОКАЗАТЕЛИ_ОСОБО.get(ключ)
    if особо is not None:
        отборы, порядок, подпись, пусто_при_нуле = особо
        return {"f": list(отборы), "sort": порядок, "value": подпись,
                "zero_is_empty": пусто_при_нуле}
    # Остальные показатели свода — средние, и раскрыть можно только то, что
    # свод действительно усредняет, причём по той же колонке, что у величины
    # списка. Колонка в разборе есть и у показателя, которого свод не
    # считает вовсе, — у такого на экране нет числа, и кнопке взяться неоткуда.
    величина = ЧИСЛА.get(ключ)
    if величина is None or _СРЕДНИЕ_СВОДА.get(ключ) != f"AVG({величина[0]})":
        return None
    return {"f": [f"has:{ключ}"], "sort": f"{ключ}:{'asc' if лучше > 0 else 'desc'}"}


