@dataclass(frozen=True)
class Отбор:
    """Одно условие списка: выражение, вид значения и нужные соединения."""

    sql: str
    #: `признак` — без значения; `текст` — одно значение строкой; `целое` —
    #: целое в границах; `диапазон` — «от..до», нижняя граница входит,
    #: верхняя нет; любая из двух может быть пустой.
    вид: str = "признак"
    #: Что присоединить к заданиям: `c` — разбор содержания, `l` — ответ
    #: языковой модели. Условие по колонке разбора без разбора не имеет
    #: смысла, поэтому соединение внутреннее.
    нужно: frozenset[str] = frozenset()
    границы: tuple[int, int] = (0, 0)
    описание: str = ""


def _звонок(колонка: str) -> str:
    """Поле звонка по заданию — тем же подзапросом, что и в сводах.

    Соединение с `calls` размножило бы задание, у которого оказалось два
    звонка; своды берут поле подзапросом, и список обязан делать так же.
    """
    return f"COALESCE((SELECT cl.{колонка} FROM calls cl WHERE cl.job_id = j.id),'')"


