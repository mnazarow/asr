class Отказ(ConfigError):
    """Запрос списка составлен неверно: отбор, порядок или продолжение."""

    hint = "Перечень отборов и величин: GET /api/drill/filters."


def _число(значение: str, что: str) -> float:
    try:
        число = float(значение.replace(",", "."))
    except ValueError:
        raise Отказ(f"В отборе «{что}» ожидалось число, а пришло «{значение}».") from None
    if not math.isfinite(число):
        raise Отказ(f"В отборе «{что}» ожидалось обычное число.")
    return число


def разобрать(отборы: list[str], перечень: dict[str, Отбор]
              ) -> tuple[list[str], list[Any], set[str]]:
    """Отборы из строки запроса → условия SQL, параметры и нужные соединения.

    Запись: `имя` — признак, `имя:значение` — значение (после первого
    двоеточия, сколько бы их ни было дальше: в причинах обращения они
    встречаются), `имя:от..до` — диапазон.
    """
    условия: list[str] = []
    параметры: list[Any] = []
    нужно: set[str] = set()
    for запись in отборы:
        имя, _, значение = str(запись).partition(":")
        имя = имя.strip()
        # Статус и «измерено / не ноль» — не колонка, а семейство условий.
        if имя == "status":
            статусы: list[str] = []
            for часть in значение.split(","):
                часть = часть.strip()
                if часть == "active":
                    статусы.extend(В_РАБОТЕ)
                elif часть in СТАТУСЫ:
                    статусы.append(часть)
                elif часть:
                    raise Отказ(f"Неизвестный статус «{часть}».",
                                hint="Статусы: " + ", ".join((*СТАТУСЫ, "active")))
            if not статусы or перечень is not ОТБОРЫ:
                raise Отказ("Отбор по статусу задан неверно.")
            # «Готово» — статус почти всего
            # архива, и индекс по статусу под него ничего не отбирает, но
            # планировщик без статистики берёт именно его: читает все готовые
            # задания архива, сортирует во временной таблице и только потом
            # отдаёт первые полсотни — на 400 тысячах записей это секунды на
            # страницу вместо долей миллисекунды. Унарный плюс снимает
            # условие с индекса (на смысл не влияет), и список идёт по
            # индексу времени: окно режется им же, а страница кончается на
            # пятьдесят первой строке. Редким статусам (ошибка, отмена)
            # индекс, наоборот, полезен — им он оставлен.
            колонка = "+j.status" if "completed" in статусы else "j.status"
            условия.append(f"{колонка} IN (" + ",".join("?" for _ in статусы) + ")")
            параметры.extend(статусы)
            continue
        if имя in ("has", "nz") and перечень is ОТБОРЫ:
            величина = ЧИСЛА.get(значение.strip())
            if величина is None:
                raise Отказ(f"Неизвестная величина «{значение}».",
                            hint="Величины: " + ", ".join(sorted(ЧИСЛА)))
            выражение, соединения = величина
            условия.append(f"{выражение} IS NOT NULL" if имя == "has"
                           else f"({выражение} IS NOT NULL AND {выражение} <> 0)")
            нужно |= соединения
            continue
        # Диапазон по величине: `duration:60..300`. Узнаётся по двум точкам,
        # потому что у части величин есть одноимённый признак (`alerts` —
        # «были тревоги»), и без значения имя означает именно его.
        if перечень is ОТБОРЫ and имя in ЧИСЛА and ".." in значение:
            выражение, соединения = ЧИСЛА[имя]
            отбор = Отбор(f"{выражение} >= ?|{выражение} < ?", "диапазон", соединения)
        else:
            отбор = перечень.get(имя)
        if отбор is None:
            raise Отказ(f"Неизвестный отбор «{имя}».",
                        hint="Доступные отборы: " + ", ".join(sorted(перечень)))
        нужно |= отбор.нужно
        if отбор.вид == "признак":
            условия.append(отбор.sql)
        elif отбор.вид == "текст":
            условия.append(отбор.sql)
            параметры.append(значение)
        elif отбор.вид == "целое":
            число = _число(значение, имя)
            низ, верх = отбор.границы
            if число != int(число) or not низ <= число <= верх:
                raise Отказ(f"Отбор «{имя}»: целое от {низ} до {верх}.")
            условия.append(отбор.sql)
            параметры.append(int(число))
        else:                                               # диапазон
            от, разделитель, до = значение.partition("..")
            if not разделитель:
                raise Отказ(f"Отбор «{имя}» задаётся диапазоном «от..до».")
            снизу, сверху = отбор.sql.split("|")
            if от.strip():
                условия.append(снизу)
                параметры.append(_число(от.strip(), имя))
            if до.strip():
                условия.append(сверху)
                параметры.append(_число(до.strip(), имя))
            if not от.strip() and not до.strip():
                raise Отказ(f"Отбор «{имя}»: нужна хотя бы одна граница.")
    return условия, параметры, нужно


def _порядок(sort: str, величины: dict[str, Any]) -> tuple[str, str, frozenset[str]]:
    """Порядок списка → (выражение, направление, соединения). Пусто — по времени."""
    имя, _, направление = (sort or "").partition(":")
    имя = имя.strip()
    направление = (направление or "desc").strip().lower()
    if направление not in ("asc", "desc"):
        raise Отказ("Порядок задаётся как «величина:desc» или «величина:asc».")
    if имя in ("", "time"):
        return "", направление.upper(), frozenset()
    величина = величины.get(имя)
    if величина is None:
        raise Отказ(f"Упорядочить по «{имя}» нельзя.",
                    hint="Можно по времени (time) или по величине: "
                         + ", ".join(sorted(величины)))
    if isinstance(величина, tuple):
        return величина[0], направление.upper(), величина[1]
    return str(величина), направление.upper(), frozenset()


def _продолжение(cursor: str) -> tuple[Any, str] | None:
    if not cursor:
        return None
    try:
        сырое = base64.urlsafe_b64decode(cursor.encode("ascii") + b"=" * (-len(cursor) % 4))
        значение, ключ = json.loads(сырое.decode("utf-8"))
    except (ValueError, TypeError, UnicodeError):
        raise Отказ("Продолжение списка не разобрано.",
                    hint="Передайте `cursor` из поля `next` прошлого ответа "
                         "без изменений.") from None
    if isinstance(значение, bool) or not isinstance(значение, (int, float, str)) \
            or not isinstance(ключ, str):
        raise Отказ("Продолжение списка не разобрано.")
    return значение, ключ


def _следующее(значение: Any, ключ: Any) -> str:
    сырое = json.dumps([значение, str(ключ)], ensure_ascii=False).encode("utf-8")
    return base64.urlsafe_b64encode(сырое).decode("ascii").rstrip("=")


class Drill:
    """Список записей или звонков по окну, отборам и владельцу."""

    def __init__(self, db: Database):
        self.db = db

    def page(self, *, base: str = "jobs", since: float | None = None,
             until: float | None = None, filters: list[str] | None = None,
             owner: str | list[str] | None = None, sort: str = "",
             limit: int = СТРАНИЦА, cursor: str = "",
             срок: float = СРОК_С) -> dict[str, Any]:
        """Страница списка и — на первой странице — сколько в нём всего."""
        limit = max(1, min(int(limit), ПРЕДЕЛ_СТРАНИЦЫ))
        звонки = base == "calls"
        if not звонки and base not in ОСНОВЫ:
            raise Отказ(f"Неизвестная основа списка «{base}».",
                        hint="Основы: " + ", ".join((*ОСНОВЫ, "calls")))
        условия, параметры, нужно = разобрать(
            list(filters or []), ОТБОРЫ_ЗВОНКОВ if звонки else ОТБОРЫ)
        выражение, направление, для_порядка = _порядок(
            sort, ПОРЯДОК_ЗВОНКОВ if звонки else ЧИСЛА)
        if звонки:
            время, ключ, владелец = "cl.started_at", "cl.uniqueid", "cl"
            откуда = " FROM calls cl LEFT JOIN jobs j ON j.id = cl.job_id"
            колонки = _КОЛОНКИ_ЗВОНКА
        else:
            время, ключ, владелец = "j.created_at", "j.id", "j"
            соединения = ОСНОВЫ[base] | нужно | для_порядка
            откуда = " FROM jobs j" + "".join(
                _СОЕДИНЕНИЯ[имя] for имя in ("c", "l") if имя in соединения)
            колонки = (_КОЛОНКИ
                       + (_КОЛОНКИ_РАЗБОРА if "c" in соединения else "")
                       + (_КОЛОНКИ_МОДЕЛИ if "l" in соединения else ""))
        where = list(условия)
        args = list(параметры)
        if base == "content":
            # Своды по содержанию считают только готовые задания: разбор
            # остаётся в базе и у записи, которую отправили на повтор.
            # Плюс перед колонкой — чтобы
            # список шёл по индексу времени, а не перебирал все готовые
            # задания архива по индексу статуса (см. `разобрать`).
            where.append("+j.status = 'completed'")
        # `is not None`, а не истинность: ноль — законная граница, а «нет
        # границы» в сводах записывается именно отсутствием.
        if since is not None:
            where.append(f"{время} >= ?")
            args.append(float(since))
        if until is not None:
            where.append(f"{время} < ?")
            args.append(float(until))
        отбор_владельца, свои = self.db._owner_clause(owner, владелец)
        if отбор_владельца:
            where.append(отбор_владельца)
            args.extend(свои)
        по_величине = bool(выражение)
        if по_величине:
            # Запись без величины в список «по величине» не входит: её
            # некуда поставить, и продолжение по ключу на NULL не строится.
            where.append(f"{выражение} IS NOT NULL")
            колонки += f", {выражение} AS value"
        упорядочить = выражение or время
        общее = (" WHERE " + " AND ".join(where)) if where else ""

        страница = list(where)
        аргументы = list(args)
        после = _продолжение(cursor)
        if после is not None:
            знак = "<" if направление == "DESC" else ">"
            страница.append(f"({упорядочить} {знак} ? OR ({упорядочить} = ? "
                            f"AND {ключ} {знак} ?))")
            аргументы.extend([после[0], после[0], после[1]])
        условие = (" WHERE " + " AND ".join(страница)) if страница else ""
        запрос = (f"SELECT {колонки}{откуда}{условие} "
                  f"ORDER BY {упорядочить} {направление}, {ключ} {направление} LIMIT ?")
        ответ: dict[str, Any] = {
            "base": base, "items": [], "next": None, "limit": limit,
            "total": None, "total_capped": False, "timed_out": False,
            "window": {"since": since, "until": until},
        }
        try:
            строки = [dict(r) for r in self.db.query_bounded(
                запрос, [*аргументы, limit + 1], seconds=срок)]
        except QueryTimeout:
            ответ["timed_out"] = True
            return ответ
        if len(строки) > limit:
            строки = строки[:limit]
            последняя = строки[-1]
            ответ["next"] = _следующее(
                последняя["value"] if по_величине
                else последняя["started_at" if звонки else "created_at"],
                последняя["uniqueid" if звонки else "id"])
        if звонки:
            for строка in строки:
                строка["answered"] = bool(строка.get("answered"))
        ответ["items"] = строки
        if после is None:
            # Счёт — только на первой странице и только до потолка: он нужен
            # подписи «показано 50 из 1 284», а не бухгалтерии.
            if ответ["next"] is None:
                ответ["total"] = len(строки)
            else:
                try:
                    счёт = self.db.query_bounded(
                        f"SELECT COUNT(*) AS n FROM (SELECT 1{откуда}{общее} LIMIT ?)",
                        [*args, ПРЕДЕЛ_СЧЁТА + 1], seconds=срок)
                    всего = int(счёт[0]["n"]) if счёт else 0
                    ответ["total_capped"] = всего > ПРЕДЕЛ_СЧЁТА
                    ответ["total"] = min(всего, ПРЕДЕЛ_СЧЁТА)
                except QueryTimeout:
                    ответ["total"] = None
        return ответ


def describe() -> dict[str, Any]:
    """Перечень основ, отборов и величин — для справочника и подсказок."""
    def строки(перечень: dict[str, Отбор]) -> list[dict[str, Any]]:
        return [{"name": имя, "kind": о.вид, "description": о.описание}
                for имя, о in sorted(перечень.items())]
    return {
        "bases": [*ОСНОВЫ, "calls"],
        "filters": строки(ОТБОРЫ),
        "call_filters": строки(ОТБОРЫ_ЗВОНКОВ),
        "values": sorted(ЧИСЛА),
        "call_values": sorted(ПОРЯДОК_ЗВОНКОВ),
        "statuses": [*СТАТУСЫ, "active"],
        "page": СТРАНИЦА, "page_max": ПРЕДЕЛ_СТРАНИЦЫ, "count_cap": ПРЕДЕЛ_СЧЁТА,
    }
