"""Темы без правил: о чём говорят там, куда никто не написал правило.

Категории обращений у сервера есть, и работают они хорошо — ровно в той мере,
в какой кто-то сел и написал правило. Слабое место у такого подхода одно и
известное: он показывает то, что уже искали. Новая причина звонков — сбой в
приложении, слух в соцсетях, изменившийся тариф — не попадает никуда, и
увидеть её можно только случайно, открыв десяток записей подряд.

Здесь недостающая половина: записи собираются в кучки по похожести слов, и
для каждой кучки считается, сколько её записей вообще попало хоть в одну
категорию. Кучка из двухсот разговоров, где сработавших категорий нет, — это
и есть тема, которую никто не заметил.

Как устроено и почему так:

* **Считается по `content_terms`**, а не по текстам. Таблица заполняется при
  разборе; поднимать и разбирать сто тысяч расшифровок ради кластеризации —
  это часы вместо секунд.
* **Вес — TF-IDF.** Без него все кучки получаются про «здравствуйте, чем могу
  помочь»: самые частые слова одинаковы у всех разговоров и похожесть по ним
  ничего не различает.
* **Кластеризация — «лидерами»**, без sklearn. Запись сравнивается с уже
  набранными вожаками, и либо примыкает к ближайшему, либо становится новым.
  Это один проход, память под число кластеров, и никакой новой зависимости
  ради одной кнопки. K-means здесь хуже: он требует заранее назвать число тем,
  а весь вопрос как раз в том, сколько их.
* **Название — от языковой модели, если она есть.** Нет — берутся ведущие
  слова. Название без модели читается хуже, но тема от этого не перестаёт
  существовать, и молчать о ней из-за отсутствия модели неправильно.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

from .logging_setup import get_logger

log = get_logger("topics")

#: Ниже этой похожести запись в кучку не принимается. Косинус по TF-IDF:
#: 0,35 подобрано так, чтобы разговоры об одном и том же сходились, а «оплата»
#: и «доставка» оставались разными темами.
ПОРОГ_ПОХОЖЕСТИ = 0.35

#: Сколько записей должно быть в кучке, чтобы называть её темой. Две записи —
#: это совпадение, а не тема; показывать такие значит утопить настоящие.
МИНИМУМ_ЗАПИСЕЙ = 5

#: Сколько кучек показывать. Больше двух десятков человек всё равно не
#: разберёт, а хвост из кучек по пять записей — это шум.
СКОЛЬКО_ТЕМ = 20

#: Доля записей кучки, попавших хоть в одну категорию, выше которой тема
#: считается уже описанной правилами.
ПОКРЫТА_ДОЛЯ = 0.5

#: Основы, которые есть почти в каждом разговоре: они не различают темы, а
#: вес по TF-IDF у них всё равно ненулевой, если корпус маленький.
ШУМ = frozenset({
    "здравствуйте", "добрый", "день", "спасибо", "пожалуйста", "хорошо",
    "алло", "свидания", "минуту", "секунду", "говорить", "слушать",
    "понятно", "конечно", "давайте", "сказать", "вопрос", "ответ",
})


@dataclass
class Тема:
    """Кучка похожих записей."""

    stems: list[str] = field(default_factory=list)
    jobs: list[str] = field(default_factory=list)
    covered: int = 0
    categories: dict[str, int] = field(default_factory=dict)
    title: str = ""

    @property
    def size(self) -> int:
        return len(self.jobs)

    def to_dict(self, всего: int) -> dict[str, Any]:
        доля_покрытия = self.covered / self.size if self.size else 0.0
        return {
            "title": self.title or ", ".join(self.stems[:4]),
            "stems": self.stems[:12],
            "size": self.size,
            "share": round(self.size / всего, 4) if всего else None,
            "covered": self.covered,
            "covered_share": round(доля_покрытия, 3),
            # Главное поле этого отчёта. Тема, под которую правило уже
            # написано, видна и в отчёте по категориям; здесь ищут другую.
            "uncovered": доля_покрытия < ПОКРЫТА_ДОЛЯ,
            "categories": sorted(self.categories.items(),
                                 key=lambda п: -п[1])[:5],
            "jobs": self.jobs[:10],
        }


def _веса(основы: dict[str, int], частоты: dict[str, int],
          корпус: int) -> dict[str, float]:
    """TF-IDF одной записи, нормированный к единичной длине.

    Нормировка обязательна: без неё длинный разговор похож на всё подряд
    просто потому, что у него больше слов, и он собирает вокруг себя кучку
    из записей, не имеющих между собой ничего общего.
    """
    веса: dict[str, float] = {}
    for основа, сколько in основы.items():
        if основа in ШУМ or len(основа) < 3:
            continue
        в_скольких = max(1, int(частоты.get(основа, 1)))
        idf = math.log((корпус + 1) / в_скольких) + 1.0
        веса[основа] = (1.0 + math.log(max(1, int(сколько)))) * idf
    длина = math.sqrt(sum(з * з for з in веса.values()))
    if длина <= 0:
        return {}
    return {к: з / длина for к, з in веса.items()}


def _похожесть(первый: dict[str, float], второй: dict[str, float]) -> float:
    """Косинус двух нормированных векторов — просто скалярное произведение."""
    если_короче, длиннее = ((первый, второй) if len(первый) <= len(второй)
                            else (второй, первый))
    return sum(з * длиннее.get(к, 0.0) for к, з in если_короче.items())


def собрать(записи: list[tuple[str, dict[str, int]]],
            частоты: dict[str, int], корпус: int, *,
            порог: float = ПОРОГ_ПОХОЖЕСТИ,
            минимум: int = МИНИМУМ_ЗАПИСЕЙ,
            сколько: int = СКОЛЬКО_ТЕМ) -> list[Тема]:
    """Собирает записи в кучки по похожести слов.

    Порядок обхода — тот, в котором записи пришли (свежие первыми). Это не
    придирка: у кластеризации «лидерами» результат зависит от порядка, и
    брать свежие первыми правильнее — вожаком темы становится недавний
    разговор, а не годовалый.
    """
    вожаки: list[tuple[dict[str, float], Тема]] = []
    суммы: list[dict[str, float]] = []
    for ид, основы in записи:
        вектор = _веса(основы, частоты, корпус)
        if not вектор:
            continue
        лучший, лучшая = -1, -1.0
        for н, (вожак, _) in enumerate(вожаки):
            сходство = _похожесть(вектор, вожак)
            if сходство > лучшая:
                лучший, лучшая = н, сходство
        if лучший >= 0 and лучшая >= порог:
            вожаки[лучший][1].jobs.append(ид)
            для_суммы = суммы[лучший]
            for к, з in вектор.items():
                для_суммы[к] = для_суммы.get(к, 0.0) + з
        else:
            вожаки.append((вектор, Тема(jobs=[ид])))
            суммы.append(dict(вектор))

    темы: list[Тема] = []
    for (_, тема), сумма in zip(вожаки, суммы, strict=True):
        if тема.size < максимум_минимума(минимум):
            continue
        тема.stems = [к for к, _ in sorted(сумма.items(), key=lambda п: -п[1])]
        темы.append(тема)
    темы.sort(key=lambda т: -т.size)
    return темы[:max(1, int(сколько))]


def максимум_минимума(минимум: int) -> int:
    """Не меньше двух записей в теме, что бы ни просили.

    Одна запись — это не тема, а запись, и показывать её в отчёте о темах
    значит выдавать список расшифровок за находку.
    """
    return max(2, int(минимум))


def пометить_покрытие(темы: list[Тема], попадания: dict[str, list[str]]) -> None:
    """Считает, сколько записей темы попало хоть в одну категорию."""
    for тема in темы:
        for ид in тема.jobs:
            свои = попадания.get(ид) or []
            if свои:
                тема.covered += 1
            for категория in свои:
                тема.categories[категория] = тема.categories.get(категория, 0) + 1


def подсказка(тема: Тема, примеры: list[str]) -> str:
    """Запрос к языковой модели: назвать тему двумя-тремя словами."""
    слова = ", ".join(тема.stems[:12])
    куски = "\n\n".join(f"— {т[:400]}" for т in примеры[:3])
    return (
        "Ниже — ведущие слова группы похожих телефонных разговоров и "
        "несколько выдержек из них.\n\n"
        f"Слова: {слова}\n\nВыдержки:\n{куски}\n\n"
        "Назови тему этой группы по-русски, двумя-четырьмя словами, "
        "именительным падежом, без кавычек и без пояснений. Только название."
    )


def назвать(темы: list[Тема], спросить: Any, тексты: dict[str, str]) -> None:
    """Даёт темам названия языковой моделью. Молчит, если её нет.

    `спросить` — что угодно, что принимает строку и возвращает строку.
    Ошибка модели не должна ронять отчёт: тема без красивого названия всё
    равно тема, и ведущие слова у неё есть.
    """
    if спросить is None:
        return
    for тема in темы:
        примеры = [тексты.get(ид, "") for ид in тема.jobs[:3] if тексты.get(ид)]
        try:
            ответ = str(спросить(подсказка(тема, примеры)) or "").strip()
        except Exception as exc:                            # noqa: BLE001
            log.warning("Тему не удалось назвать моделью: %s", exc)
            return
        имя = ответ.splitlines()[0].strip(' .«»"') if ответ else ""
        if имя and len(имя) <= 80:
            тема.title = имя
