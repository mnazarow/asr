class Звонок:
    """Одна запись журнала звонков, приведённая к общему виду.

    Обычный класс, а не ``dataclass``: агент обязан работать на Python 3.6,
    где ``dataclasses`` ещё нет вовсе. ``__slots__`` тут не украшение — при
    сборе архива в памяти одновременно живут десятки тысяч таких записей.
    """

    __slots__ = ("uniqueid", "src", "dst", "clid", "channel", "dstchannel",
                 "context", "disposition", "duration", "billsec", "started_at",
                 "answered", "userfield", "accountcode", "direction", "queue",
                 "agent", "recording", "lastapp", "lastdata")

    def __init__(self, uniqueid="", src="", dst="", clid="", channel="",
                 dstchannel="", context="", disposition="", duration=0,
                 billsec=0, started_at=0.0, answered=False, userfield="",
                 accountcode="", direction="", queue="", agent="",
                 recording="", lastapp="", lastdata=""):
        self.uniqueid = uniqueid
        self.src = src
        self.dst = dst
        self.clid = clid
        self.channel = channel
        self.dstchannel = dstchannel
        self.context = context
        self.disposition = disposition
        self.duration = duration
        self.billsec = billsec
        self.started_at = started_at
        self.answered = answered
        self.userfield = userfield
        self.accountcode = accountcode
        self.direction = direction
        self.queue = queue
        self.agent = agent
        self.recording = recording
        self.lastapp = lastapp
        self.lastdata = lastdata

    def поля_для_сервера(self, agent_id, пропущено=""):
        """Поле ``meta`` запроса /call — ровно те имена, что ждёт сервер.

        Список закрытый и совпадает с ``ПОЛЯ_ЗВОНКА`` в
        ``routes_agent.py``: всё остальное сервер молча отбросит, а значит,
        слать это незачем.
        """
        поля = {
            "agent_id": agent_id,
            "uniqueid": self.uniqueid,
            "src": self.src,
            "dst": self.dst,
            "clid": self.clid,
            "channel": self.channel,
            "dstchannel": self.dstchannel,
            "context": self.context,
            "disposition": self.disposition,
            "direction": self.direction,
            "queue": self.queue,
            "agent": self.agent,
            "duration": int(self.duration or 0),
            "billsec": int(self.billsec or 0),
            "answered": bool(self.answered),
            "started_at": float(self.started_at or 0.0),
            "userfield": self.userfield,
            "accountcode": self.accountcode,
        }
        if пропущено:
            поля["skipped"] = пропущено
        return поля

    def __repr__(self):
        return (f"Звонок({self.uniqueid} {self.src}→{self.dst} "
                f"{self.disposition} {self.billsec}с)")


