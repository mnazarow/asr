#: Ключи, значение которых может начинаться с минуса.
КЛЮЧИ_СО_СРОКОМ = ("--since", "--until")


def склеить_сроки(аргументы):
    """«--since -7d» — в «--since=-7d», иначе argparse видит два ключа.

    argparse считает всё, что начинается с дефиса, ключом, и на «--since
    -7d» отвечает «expected one argument» — при том, что именно такое
    написание обещано в справке и в задании. Требовать от человека
    «--since=-7d» бессмысленно: он напишет как написано.
    """
    готово = []
    пропустить = False
    for место, кусок in enumerate(аргументы):
        if пропустить:
            пропустить = False
            continue
        следующий = аргументы[место + 1] if место + 1 < len(аргументы) else ""
        if кусок in КЛЮЧИ_СО_СРОКОМ and ОТНОСИТЕЛЬНЫЙ_СРОК.match(следующий):
            готово.append(кусок + "=" + следующий)
            пропустить = True
            continue
        готово.append(кусок)
    return готово


def собрать_параметры(аргументы, настройки):
    """Ключи командной строки поверх файла настроек поверх умолчаний."""

    def взять(имя, из_файла=None, умолчание=None):
        значение = getattr(аргументы, имя, None)
        if значение is None:
            значение = настройки.get(из_файла or имя)
        if значение is None or значение == "":
            return умолчание
        return значение

    параметры = {
        "config": аргументы.config,
        "url": взять("url"),
        "key": взять("key"),
        "name": взять("name", умолчание=socket.gethostname()),
        "source": взять("source", умолчание="auto"),
        "cdr_file": взять("cdr_file"),
        "recordings_dir": взять("recordings_dir", умолчание=ЗАПИСИ_ПО_УМОЛЧАНИЮ),
        "filename": взять("filename", умолчание=""),
        "match_window": целое(взять("match_window", умолчание=120), 120),
        "internal_digits": взять("internal_digits", умолчание=5),
        "contexts": взять("contexts", умолчание=""),
        "mysql_conf": взять("mysql_conf", умолчание=MYSQL_CONF),
        "state_dir": взять("state_dir", умолчание=КАТАЛОГ_СОСТОЯНИЯ),
        "log_file": взять("log_file", умолчание=ЖУРНАЛ_ПО_УМОЛЧАНИЮ),
        "log_size_mb": целое(взять("log_size_mb", умолчание=10), 10),
        "timeout": дробное(взять("timeout", умолчание=30.0), 30.0),
        "upload_timeout": дробное(взять("upload_timeout", умолчание=120.0), 120.0),
        "retries": целое(взять("retries", умолчание=5), 5),
        "interval": дробное(взять("interval", умолчание=60.0), 60.0),
        "insecure": логическое(взять("insecure"), False),
        "dry_run": bool(аргументы.dry_run),
        "mysql": {},
    }
    # Значения, которые сервер вправе задать сам, различают «не задано» и
    # «задано нулём»: min_duration_s = 0 означает «брать всё», и подменять
    # его правилом с сервера нельзя.
    for имя, из_файла in (("min_duration_s", "min_duration_s"),
                          ("skip_unanswered", "skip_unanswered"),
                          ("max_file_mb", "max_file_mb")):
        значение = getattr(аргументы, имя, None)
        if значение is None:
            значение = настройки.get(из_файла)
        if значение is None or значение == "":
            параметры[имя] = None
        elif имя == "skip_unanswered":
            параметры[имя] = логическое(значение, True)
        else:
            параметры[имя] = целое(значение, 0)
    for поле, ключ in (("hostname", "mysql_host"), ("dbname", "mysql_db"),
                       ("table", "mysql_table"), ("user", "mysql_user"),
                       ("password", "mysql_password"), ("port", "mysql_port"),
                       ("sock", "mysql_sock")):
        значение = getattr(аргументы, ключ, None) or настройки.get(ключ)
        if значение:
            параметры["mysql"][поле] = значение
    return параметры


def список_строк(значения):
    """Аргументы списком строк — что бы ни передали вызывающие."""
    return [str(з) for з in значения]


def главная(аргументы_строки=None):
    разбор = собрать_аргументы()
    если_переданы = аргументы_строки if аргументы_строки is not None else sys.argv[1:]
    аргументы = разбор.parse_args(склеить_сроки(список_строк(если_переданы)))
    try:
        настройки = прочитать_настройки(аргументы.config)
        параметры = собрать_параметры(аргументы, настройки)
    except ОшибкаНастройки as сбой:
        print(f"Ошибка настройки: {сбой}", file=sys.stderr)
        return КОД_НАСТРОЙКИ

    настроить_журнал(параметры.get("log_file"), подробно=аргументы.verbose,
                     тихо=аргументы.quiet, ключ=параметры.get("key"),
                     предел_мб=параметры.get("log_size_mb"))
    log.debug("Агент %s, Python %s, ключ %s, сервер %s", ВЕРСИЯ,
              platform.python_version(), маска_ключа(параметры.get("key")),
              параметры.get("url"))

    if sys.version_info[:2] < МИНИМАЛЬНЫЙ_PYTHON:
        log.error("Нужен Python %d.%d или новее, а этот — %s.",
                  МИНИМАЛЬНЫЙ_PYTHON[0], МИНИМАЛЬНЫЙ_PYTHON[1],
                  platform.python_version())
        return КОД_НАСТРОЙКИ

    if аргументы.selftest:
        try:
            return самопроверка(параметры)
        except ОшибкаНастройки as сбой:
            log.error("Самопроверка не выполнена: %s", сбой)
            return КОД_НАСТРОЙКИ

    try:
        начало = разобрать_дату(аргументы.since, "начало периода (--since)")
        конец = разобрать_дату(аргументы.until, "конец периода (--until)")
    except ОшибкаНастройки as сбой:
        log.error("%s", сбой)
        return КОД_НАСТРОЙКИ
    if начало and конец and конец <= начало:
        log.error("Конец периода (%s) не позже начала (%s).",
                  время_словами(конец), время_словами(начало))
        return КОД_НАСТРОЙКИ

    if not параметры.get("url") or not параметры.get("key"):
        log.error("Не заданы адрес сервера и ключ доступа.")
        log.error("Укажите их ключами --url и --key либо в файле %s "
                  "(секция [agent], строки url = … и key = …).",
                  аргументы.config)
        return КОД_НАСТРОЙКИ

    режим = "new"
    if аргументы.весь:
        режим = "all"
    elif начало or конец:
        режим = "period"

    агент = Агент(параметры)
    try:
        агент.подготовиться()
    except УжеЗапущен as сбой:
        log.error("%s", сбой)
        return КОД_ЗАНЯТО
    except ОшибкаНастройки as сбой:
        log.error("%s", сбой)
        return КОД_НАСТРОЙКИ

    for сигнал in (signal.SIGTERM, signal.SIGINT):
        try:
            signal.signal(сигнал, агент.остановить)
        except (ValueError, OSError, AttributeError):
            # Не главный поток или система без этого сигнала — не повод
            # отказываться работать.
            log.debug("Сигнал %s не перехвачен", сигнал)

    код = КОД_УСПЕХ
    try:
        if аргументы.follow:
            код = агент.следить(параметры.get("interval"))
        else:
            агент.один_заход(режим, начало, конец)
            код = КОД_ОШИБКИ if агент.ошибок else КОД_УСПЕХ
    except Остановлен:
        log.info("Остановлен по сигналу.")
        код = КОД_УСПЕХ
    except KeyboardInterrupt:
        log.info("Остановлен с клавиатуры.")
        код = КОД_УСПЕХ
    except ОшибкаНастройки as сбой:
        log.error("%s", сбой)
        код = КОД_НАСТРОЙКИ
    except (ОшибкаСвязи, ОтказСервера) as сбой:
        log.error("%s", сбой)
        код = КОД_ОШИБКИ
    except Exception as сбой:                                # noqa: BLE001
        log.exception("Непредвиденная ошибка: %s", сбой)
        код = КОД_ОШИБКИ
    finally:
        try:
            агент.закрыть()
        except Exception as сбой:                            # noqa: BLE001
            log.error("Состояние при завершении сохранить не удалось: %s", сбой)
    return код


if __name__ == "__main__":
    sys.exit(главная())
