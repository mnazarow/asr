def самопроверка(параметры):
    """Проверяет всё, что нужно для работы, и ничего не отправляет.

    Ставится первым делом после установки: половина обращений «агент не
    работает» лечится строкой из этой таблицы — не тот путь к журналу, нет
    прав на каталог записей, закрыт порт до сервера, разъехались часы.
    """
    строки = []
    плохо = 0

    def добавить(название, состояние, подробность=""):
        строки.append((название, состояние, подробность))
        return состояние

    версия = ".".join(str(ч) for ч in sys.version_info[:3])
    годится = sys.version_info[:2] >= МИНИМАЛЬНЫЙ_PYTHON
    добавить("Python", "хорошо" if годится else "плохо",
             версия + ("" if годится else
                       f" — нужен {МИНИМАЛЬНЫЙ_PYTHON[0]}.{МИНИМАЛЬНЫЙ_PYTHON[1]}"
                       " или новее"))
    плохо += 0 if годится else 1

    файл_настроек = параметры.get("config")
    if файл_настроек and os.path.isfile(файл_настроек):
        права = oct(os.stat(файл_настроек).st_mode & 0o777)[2:]
        опасно = os.stat(файл_настроек).st_mode & 0o077
        добавить("Файл настроек", "хорошо" if not опасно else "внимание",
                 f"{файл_настроек}, права {права}"
                 + ("" if not опасно else " — в нём ключ доступа, поставьте 600"))
    else:
        добавить("Файл настроек", "внимание",
                 f"{файл_настроек} не найден — работаю на одних ключах")

    добавить("Ключ доступа",
             "хорошо" if параметры.get("key") else "плохо",
             маска_ключа(параметры.get("key")) if параметры.get("key")
             else "не задан: укажите --key или key= в файле настроек")
    плохо += 0 if параметры.get("key") else 1

    состояние = Состояние(os.path.join(
        параметры.get("state_dir") or КАТАЛОГ_СОСТОЯНИЯ, "state.json"))
    каталог_состояния = os.path.dirname(состояние.путь)
    можно_писать = os.access(каталог_состояния, os.W_OK) \
        if os.path.isdir(каталог_состояния) else os.access(
            os.path.dirname(каталог_состояния) or "/", os.W_OK)
    добавить("Каталог состояния", "хорошо" if можно_писать else "плохо",
             каталог_состояния + ("" if можно_писать else
                                  " — нет прав на запись, запустите от root"))
    плохо += 0 if можно_писать else 1

    свободно = свободно_байт(каталог_состояния if os.path.isdir(каталог_состояния)
                             else "/")
    добавить("Свободное место",
             "хорошо" if свободно >= МИНИМУМ_МЕСТА else "внимание",
             размер_словами(свободно))

    имя_источника = ""
    try:
        состояние.прочитать()
        источник = выбрать_источник(параметры, состояние)
        имя_источника = getattr(источник, "имя", "")
        подробность = источник.описание()
        if isinstance(источник, ИсточникCSV):
            живые = источник.проверить()
            всего = sum(max(0, источник.строк(п)) for п in живые)
            подробность = f"{', '.join(живые)} — строк: {всего}"
        else:
            источник.проверить()
        добавить("Журнал звонков", "хорошо", подробность)
    except ОшибкаНастройки as сбой:
        добавить("Журнал звонков", "плохо", str(сбой))
        плохо += 1
    except Exception as сбой:                                # noqa: BLE001
        добавить("Журнал звонков", "плохо", f"{type(сбой).__name__}: {сбой}")
        плохо += 1

    каталог_записей = параметры.get("recordings_dir") or ЗАПИСИ_ПО_УМОЛЧАНИЮ
    записи = Записи(каталог_записей, шаблон=параметры.get("filename") or "")
    if записи.доступен:
        сколько = записи.сколько_файлов()
        добавить("Каталог записей",
                 "хорошо" if сколько else "внимание",
                 f"{каталог_записей} — файлов: {сколько}"
                 + ("" if сколько else " (звонки поедут без записей)"))
    else:
        добавить("Каталог записей", "внимание",
                 f"{каталог_записей} не найден или не читается")

    ответ = {}
    try:
        клиент = Клиент(параметры.get("url"), параметры.get("key"),
                        таймаут=дробное(параметры.get("timeout"), 30.0),
                        повторов=1,
                        небезопасно=логическое(параметры.get("insecure"), False))
        начало = time.time()
        сведения = {
            "agent_id": состояние.данные.get("agent_id") or "",
            "name": параметры.get("name") or socket.gethostname(),
            "host": socket.gethostname(), "os": платформа(),
            "asterisk": версия_asterisk(), "version": ВЕРСИЯ,
            "source": имя_источника,
            # «Только посмотреть»: самопроверка не выполняет заданий сервера
            # и не должна их забирать — иначе нажатое в разделе «АТС»
            # «собрать всё» пропадало, если на станции в это время запускали
            # самопроверку. И состояние агента в разделе она не затирает.
            "peek": True,
            "state": {"selftest": True},
        }
        ответ = клиент.hello(сведения)
        добавить("Связь с сервером", "хорошо",
                 f"{клиент.адрес} — ответил за {int((time.time() - начало) * 1000)} мс, "
                 f"станция {ответ.get('station') or '?'}")
        if ответ.get("command"):
            добавить("Задание сервера", "внимание",
                     f"ждёт «{ответ.get('command')}» — его выполнит служба агента "
                     "следующим заходом (или asrhub-agent --once)")
        if not логическое(ответ.get("enabled"), True):
            добавить("Агент включён", "внимание",
                     "сервер держит агента выключенным — включите в разделе «АТС»")
        расхождение = time.time() - дробное(ответ.get("server_time"), 0.0) \
            if ответ.get("server_time") else 0.0
        добавить("Часы станции",
                 "хорошо" if abs(расхождение) <= ПРЕДЕЛ_РАСХОЖДЕНИЯ else "внимание",
                 f"расхождение с сервером {int(расхождение)} с"
                 + ("" if abs(расхождение) <= ПРЕДЕЛ_РАСХОЖДЕНИЯ
                    else " — включите ntp: timedatectl set-ntp true"))
        добавить("Предел записи", "хорошо",
                 f"{целое(ответ.get('max_file_mb'), 0)} МБ, отсев короче "
                 f"{целое(ответ.get('min_duration_s'), 0)} с")
    except (ОшибкаСвязи, ОтказСервера, ОшибкаНастройки) as сбой:
        добавить("Связь с сервером", "плохо", str(сбой))
        плохо += 1
    except Exception as сбой:                                # noqa: BLE001
        добавить("Связь с сервером", "плохо", f"{type(сбой).__name__}: {сбой}")
        плохо += 1

    ширина = max(len(н) for н, _, _ in строки)
    print("")
    print("Самопроверка агента ASR Hub " + ВЕРСИЯ)
    print("-" * (ширина + 60))
    for название, состояние_строки, подробность in строки:
        знак = {"хорошо": "[ ок ]", "внимание": "[ ! ]", "плохо": "[ нет ]"}.get(
            состояние_строки, "[ ? ]")
        print(f"{название.ljust(ширина)}  {знак}  {подробность}")
    print("-" * (ширина + 60))
    if плохо:
        print(f"Проверок не пройдено: {плохо}. Пока они не исправлены, звонки "
              "на сервер не поедут.")
    else:
        print("Всё на месте. Запустить сбор: asrhub-agent --once "
              "(или systemctl start asrhub-agent).")
    print("")
    return КОД_ОШИБКИ if плохо else КОД_УСПЕХ


