class ОшибкаНастройки(Exception):
    """Настройка или окружение: чинится человеком, повтор не поможет."""

    def __init__(self, сообщение, подсказка=""):
        Exception.__init__(self, сообщение)
        self.сообщение = сообщение
        self.подсказка = подсказка

    def __str__(self):
        return self.сообщение + (f" {self.подсказка}" if self.подсказка else "")


class УжеЗапущен(ОшибкаНастройки):
    """Замок держит другой агент. Отдельным классом, а не текстом ошибки:
    код возврата 3 обещан в справке, и определять его поиском подстроки в
    сообщении — значит однажды переписать сообщение и потерять код."""


class ОшибкаСвязи(Exception):
    """Сервер недоступен: сеть, имя, сертификат, тайм-аут."""

    def __init__(self, сообщение, подсказка=""):
        Exception.__init__(self, сообщение)
        self.сообщение = сообщение
        self.подсказка = подсказка

    def __str__(self):
        return self.сообщение + (f" {self.подсказка}" if self.подсказка else "")


class ОтказСервера(Exception):
    """Сервер ответил отказом и объяснил причину.

    Держим и код HTTP, и код ошибки ASR Hub: по первому решается, стоит ли
    повторять, по второму — что именно сказать человеку.
    """

    def __init__(self, статус, код="", сообщение="", подсказка=""):
        Exception.__init__(self, сообщение or f"HTTP {статус}")
        self.статус = int(статус)
        self.код = код
        self.сообщение = сообщение or f"HTTP {статус}"
        self.подсказка = подсказка

    def __str__(self):
        части = [f"HTTP {self.статус}", self.сообщение]
        if self.подсказка:
            части.append(self.подсказка)
        return " — ".join(ч for ч in части if ч)


