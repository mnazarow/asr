def прочитать_настройки(путь):
    """Секция [agent] из INI-файла. Отсутствие файла — не ошибка."""
    значения = {}
    if not путь or not os.path.isfile(путь):
        return значения
    разбор = configparser.ConfigParser(inline_comment_prefixes=(";", "#"),
                                       strict=False)
    try:
        # Файл правят руками, и BOM от «Блокнота» через WinSCP там бывает.
        with open(путь, encoding="utf-8-sig", errors="replace") as файл:
            текст = файл.read()
        if "[agent]" not in текст:
            текст = "[agent]\n" + текст
        разбор.read_string(текст)
    except (OSError, configparser.Error) as сбой:
        raise ОшибкаНастройки(
            f"Файл настроек {путь} не читается: {сбой}",
            подсказка="Это обычный INI: секция [agent] и строки вида url = …") from сбой
    if разбор.has_section("agent"):
        for ключ, значение in разбор.items("agent"):
            значения[ключ.strip().lower()] = значение.strip().strip('"')
    return значения


