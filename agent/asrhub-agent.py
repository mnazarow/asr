class МаскаКлюча(logging.Filter):
    """Заменяет ключ доступа маской во всём, что уходит в журнал.

    Маскировать «в месте вызова» недостаточно: ключ попадает в журнал
    окольными путями — в тексте исключения urllib, в адресе с параметром,
    в обрывке ответа сервера. Один фильтр на всех надёжнее двадцати
    аккуратных вызовов, в одном из которых однажды забудут.
    """

    def __init__(self, ключ):
        logging.Filter.__init__(self)
        self.ключ = str(ключ or "")
        self.маска = маска_ключа(ключ)

    def filter(self, record):
        if not self.ключ or len(self.ключ) <= 8:
            return True
        try:
            if isinstance(record.msg, str) and self.ключ in record.msg:
                record.msg = record.msg.replace(self.ключ, self.маска)
            if record.args:
                if isinstance(record.args, dict):
                    record.args = {к: self._чисто(з)
                                   for к, з in record.args.items()}
                else:
                    record.args = tuple(self._чисто(з) for з in record.args)
        except Exception:                          # noqa: BLE001
            # Фильтр журнала не имеет права уронить то, что он записывает.
            return True
        return True

    def _чисто(self, значение):
        if isinstance(значение, str) and self.ключ in значение:
            return значение.replace(self.ключ, self.маска)
        return значение


def настроить_журнал(файл, подробно=False, тихо=False, ключ="",
                     предел_мб=10, копий=3):
    """Журнал в файл с ротацией своими силами и в консоль.

    Ротация нужна именно своими силами: агент живёт на чужой станции, куда
    никто не придёт ставить logrotate, а журнал без предела за год работы
    съедает корневой раздел АТС — и вместе с ним останавливает саму АТС.
    """
    уровень = logging.DEBUG if подробно else (
        logging.WARNING if тихо else logging.INFO)
    log.setLevel(logging.DEBUG)
    for прежний in list(log.handlers):
        log.removeHandler(прежний)
    log.propagate = False

    вид = logging.Formatter("%(asctime)s %(levelname)-8s %(message)s",
                            "%Y-%m-%d %H:%M:%S")
    консоль = logging.StreamHandler(sys.stderr)
    консоль.setFormatter(вид)
    консоль.setLevel(уровень)
    log.addHandler(консоль)

    if файл:
        try:
            каталог = os.path.dirname(os.path.abspath(файл))
            if каталог and not os.path.isdir(каталог):
                os.makedirs(каталог, 0o755)
            в_файл = logging.handlers.RotatingFileHandler(
                файл, maxBytes=int(предел_мб) * 1024 * 1024,
                backupCount=int(копий), encoding="utf-8")
            в_файл.setFormatter(вид)
            в_файл.setLevel(logging.DEBUG if подробно else logging.INFO)
            log.addHandler(в_файл)
        except OSError as сбой:
            # Не падаем: агент без журнала всё равно полезнее агента,
            # который не запустился из-за прав на /var/log.
            log.warning("Журнал %s не открылся (%s). Пишу только в консоль. "
                        "Проверьте права или задайте --log-file.", файл, сбой)
    if ключ:
        фильтр = МаскаКлюча(ключ)
        for обработчик in log.handlers:
            обработчик.addFilter(фильтр)


