#: Повёрнутые копии, которые агент не распаковывает.
СЖАТЫЕ_ЖУРНАЛЫ = (".gz", ".bz2", ".xz", ".zst", ".zip")


def _соседи_журнала(путь):
    каталог = os.path.dirname(путь) or "."
    основа = os.path.basename(путь)
    try:
        имена = os.listdir(каталог)
    except OSError:
        return []
    return [os.path.join(каталог, имя) for имя in имена
            if имя != основа and имя.startswith(основа)
            and not имя.lower().endswith(СЖАТЫЕ_ЖУРНАЛЫ)]


def повёрнутый_журнал(путь, inode):
    """Прежний файл журнала после ротации — по номеру inode.

    logrotate переименовывает ``Master.csv`` в ``Master.csv.1`` и заводит
    новый; номер inode у переименованного прежний. По нему находится хвост,
    который агент не успел прочитать до ротации.
    """
    for сосед in _соседи_журнала(путь):
        try:
            if os.path.isfile(сосед) and os.stat(сосед).st_ino == inode:
                return сосед
        except OSError:
            continue
    return None


def копия_журнала(путь, смещение):
    """Копия, куда уехал хвост при ротации с ``copytruncate``.

    Журнал копируется и обрезается на месте: inode прежний, файл просто
    стал короче. Смещения в копии те же — берём самую свежую копию не
    короче запомненного места, изменённую за двое суток, и только если это
    место в ней — граница строки.
    """
    лучшая = None
    граница = time.time() - 2 * 86400
    for сосед in _соседи_журнала(путь):
        try:
            сведения = os.stat(сосед)
        except OSError:
            continue
        if not os.path.isfile(сосед) or сведения.st_size < смещение \
                or сведения.st_mtime < граница:
            continue
        if лучшая is None or сведения.st_mtime > лучшая[0]:
            лучшая = (сведения.st_mtime, сосед)
    if лучшая is None:
        return None
    if смещение > 0:
        try:
            with open(лучшая[1], "rb") as файл:
                файл.seek(смещение - 1)
                if файл.read(1) != b"\n":
                    return None
        except OSError:
            return None
    return лучшая[1]


class ИсточникCSV:
    """Журнал ``Master.csv`` и файлы ``cdr-custom/*.csv``.

    Позиция чтения — смещение в байтах плюс inode файла. Байты, потому что
    журнал только дописывается и перечитывать гигабайт ради десятка строк
    незачем. Inode — потому что журнал поворачивают: файл с тем же именем
    становится другим файлом, и продолжать читать его «с прошлого места»
    значит пропустить всё, что в него уже написали.
    """

    имя = "cdr_csv"

    def __init__(self, пути, состояние):
        self.пути = [str(п) for п in пути if п]
        self.состояние = состояние

    def описание(self):
        return ", ".join(self.пути) or "(журналы не найдены)"

    def доступен(self):
        return any(os.path.isfile(п) for п in self.пути)

    def проверить(self):
        живые = [п for п in self.пути if os.path.isfile(п)]
        if not живые:
            raise ОшибкаНастройки(
                "Журнал звонков не найден: " + (", ".join(self.пути) or "путь не задан"),
                подсказка="Включите cdr_csv в /etc/asterisk/cdr.conf или задайте "
                          "путь ключом --cdr-file.")
        for путь in живые:
            if not os.access(путь, os.R_OK):
                raise ОшибкаНастройки(
                    f"Журнал {путь} есть, но не читается.",
                    подсказка="Добавьте пользователя агента в группу asterisk "
                              "или запускайте агента от root.")
        return живые

    def строк(self, путь):
        """Сколько строк в журнале — для самопроверки. Читаем блоками."""
        сколько = 0
        try:
            with open(путь, "rb") as файл:
                while True:
                    кусок = файл.read(1 << 20)
                    if not кусок:
                        break
                    сколько += кусок.count(b"\n")
        except OSError:
            return -1
        return сколько

    def звонки(self, весь_архив=False, предел=0, двигать_позицию=True,
               начало=None, конец=None):
        """Новые звонки журнала. При ``весь_архив`` — с начала и вместе с ротациями.

        ``начало`` и ``конец`` здесь не участвуют намеренно: в текстовом
        журнале нет указателя по времени, и единственный способ собрать
        период — прочитать файл целиком, отсеивая лишнее по полю `start`.
        Принимаем их, чтобы у всех источников был один вызов.
        """
        собрано = 0
        for путь in self.пути:
            файлы = [путь]
            if весь_архив:
                файлы = self._с_ротациями(путь)
            for файл in файлы:
                с_начала = весь_архив or файл != путь
                # Позицию двигает только основной журнал: повёрнутые копии
                # читаются целиком и своей позиции не имеют. Зато после
                # полного сбора позиция встаёт в конец файла — иначе
                # следующий обычный заход перечитал бы весь архив снова.
                for звонок in self._читать(файл, с_начала=с_начала,
                                           запоминать=двигать_позицию and файл == путь):
                    yield звонок
                    собрано += 1
                    if предел and собрано >= предел:
                        return

    def _с_ротациями(self, путь):
        """Сам журнал и его повёрнутые копии — от старых к новым.

        Повёрнутые копии нужны только при сборе архива: то, что logrotate
        унёс в ``Master.csv.1``, из живого файла уже не прочитать, а звонки
        там настоящие.
        """
        каталог = os.path.dirname(путь) or "."
        основа = os.path.basename(путь)
        копии = []
        try:
            for имя in os.listdir(каталог):
                if имя == основа or not имя.startswith(основа + "."):
                    continue
                хвост = имя[len(основа) + 1:]
                if хвост.endswith(".gz") or хвост.endswith(".bz2") \
                        or хвост.endswith(".xz"):
                    log.info("Повёрнутый журнал %s сжат — пропускаю: агент "
                             "намеренно не распаковывает архивы на станции.",
                             имя)
                    continue
                копии.append(os.path.join(каталог, имя))
        except OSError as сбой:
            log.debug("Каталог журналов %s не читается: %s", каталог, сбой)
        копии.sort(reverse=True)
        return копии + [путь]

    def _хвост(self, путь, смещение):
        """Целые строки повёрнутого журнала с запомненного места."""
        try:
            with open(путь, "rb") as файл:
                файл.seek(смещение)
                for сырая in файл:
                    if not сырая.endswith(b"\n"):
                        break
                    звонок = разобрать_строку_cdr(сырая.decode("utf-8", "replace"))
                    if звонок is not None:
                        yield звонок
        except OSError as сбой:
            log.warning("Хвост повёрнутого журнала %s не дочитан: %s", путь, сбой)

    def _читать(self, путь, с_начала=False, запоминать=True):
        try:
            сведения = os.stat(путь)
        except OSError as сбой:
            log.warning("Журнал %s не читается: %s", путь, сбой)
            return
        позиция = self.состояние.позиция(путь)
        смещение = 0 if с_начала else целое(позиция.get("offset"), 0)
        прежний_inode = целое(позиция.get("inode"), 0)
        if not с_начала:
            # Хвост, дописанный в журнал между прошлым заходом и ротацией,
            # раньше терялся: новый файл читался с начала, а старый — никем.
            хвост = None
            if прежний_inode and прежний_inode != сведения.st_ino:
                хвост = повёрнутый_журнал(путь, прежний_inode)
                log.info("Журнал %s повернули (файл сменился) — %s, дальше читаю "
                         "новый с начала.", путь,
                         f"дочитываю хвост {хвост}" if хвост else "прежний файл не найден")
                смещение_хвоста = смещение
                смещение = 0
            elif смещение > сведения.st_size:
                хвост = копия_журнала(путь, смещение)
                log.info("Журнал %s стал короче (%d < %d) — %s, дальше читаю с "
                         "начала.", путь, сведения.st_size, смещение,
                         f"дочитываю хвост из копии {хвост}" if хвост
                         else "копии с хвостом нет")
                смещение_хвоста = смещение
                смещение = 0
            if хвост:
                for звонок in self._хвост(хвост, смещение_хвоста):
                    yield звонок
        прочитано = 0
        try:
            # Двоичное чтение, а позиция — по настоящим байтам. Текстовое
            # чтение с заменой нечитаемых знаков меняет длину: байт из
            # CP1251 в имени звонящего (обычное дело на российских
            # станциях) превращается в U+FFFD и кодируется тремя байтами
            # вместо одного. Позиция уезжает вперёд, и следующий звонок
            # пропадает целиком, а дрейф копится строка за строкой.
            with open(путь, "rb") as файл:
                файл.seek(смещение)
                for сырая in файл:
                    if not сырая.endswith(b"\n"):
                        # Строку станция ещё дописывает — оставим следующему
                        # заходу: разобранная наполовину, она отдаст чужие
                        # числа в полях длительности и идентификатора.
                        break
                    смещение += len(сырая)
                    прочитано += 1
                    звонок = разобрать_строку_cdr(
                        сырая.decode("utf-8", "replace"))
                    if звонок is None:
                        continue
                    yield звонок
        except OSError as сбой:
            log.error("Журнал %s оборвался на чтении: %s", путь, сбой)
        finally:
            if запоминать:
                # Прерванный сбор архива не имеет права отодвинуть позицию
                # назад: обычный заход после него перечитал бы весь журнал
                # заново. Назад она уезжает только при ротации — там это и
                # нужно, и решается выше по inode и размеру.
                if с_начала and прежний_inode == сведения.st_ino:
                    смещение = max(смещение, целое(позиция.get("offset"), 0))
                self.состояние.запомнить_позицию(путь, смещение, сведения.st_ino)
            log.debug("Журнал %s: прочитано строк %d, позиция %d",
                      путь, прочитано, смещение)


class ИсточникMySQL:
    """Журнал звонков в MySQL/MariaDB через внешнюю программу ``mysql``.

    Драйвер сюда не затащить: агент обязан работать на голом системном
    Python 3.6 без единого pip-пакета. Зато ``mysql`` на станции с
    ``cdr_mysql`` стоит всегда — им же эту базу и заводили.

    Пароль передаётся временным файлом настроек с правами 600, а не ключом
    ``-p``: аргументы процесса на станции видны любому пользователю через
    ``ps``, и пароль от журнала звонков утекал бы каждому, кто туда зашёл.
    """

    имя = "mysql"

    def __init__(self, настройки, состояние, каталог_временных=None):
        self.настройки = dict(настройки or {})
        self.состояние = состояние
        self.каталог_временных = каталог_временных or КАТАЛОГ_СОСТОЯНИЯ

    @classmethod
    def из_конфига_asterisk(cls, путь, состояние, поверх=None,
                            каталог_временных=None):
        """Настройки из ``/etc/asterisk/cdr_mysql.conf``, дополненные ключами."""
        настройки = {"hostname": "127.0.0.1", "dbname": "asteriskcdrdb",
                     "table": "cdr", "user": "", "password": "", "port": "3306",
                     "sock": ""}
        текст = ""
        try:
            with open(путь, encoding="utf-8", errors="replace") as файл:
                текст = файл.read()
        except FileNotFoundError:
            log.debug("Файла %s нет — беру настройки MySQL из ключей.", путь)
        except OSError as сбой:
            log.warning("Файл %s не читается (%s) — беру настройки из ключей.",
                        путь, сбой)
        if текст:
            разбор = configparser.ConfigParser(
                inline_comment_prefixes=(";", "#"), strict=False)
            # Часть станций держит cdr_mysql.conf без секции вовсе —
            # configparser на таком файле падает, а человек видит только
            # «источник не настроен».
            if "[global]" not in текст:
                текст = "[global]\n" + текст
            try:
                разбор.read_string(текст)
                for ключ in list(настройки):
                    if разбор.has_option("global", ключ):
                        настройки[ключ] = разбор.get("global", ключ).strip().strip('"')
            except configparser.Error as сбой:
                log.warning("Файл %s разобрать не удалось (%s) — беру ключи.",
                            путь, сбой)
        for ключ, значение in (поверх or {}).items():
            if значение:
                настройки[ключ] = значение
        return cls(настройки, состояние, каталог_временных)

    def описание(self):
        return (f"mysql {self.настройки.get('user') or '?'}@"
                f"{self.настройки.get('hostname')}:{self.настройки.get('port')}"
                f"/{self.настройки.get('dbname')}.{self.настройки.get('table')}")

    def доступен(self):
        return bool(self.программа()) and bool(self.настройки.get("dbname"))

    def программа(self):
        for каталог in os.environ.get("PATH", "/usr/bin:/bin").split(os.pathsep):
            кандидат = os.path.join(каталог, "mysql")
            if os.path.isfile(кандидат) and os.access(кандидат, os.X_OK):
                return кандидат
        return ""

    def проверить(self):
        if not self.программа():
            raise ОшибкаНастройки(
                "Программа «mysql» не найдена в PATH.",
                подсказка="Поставьте клиента: на CentOS 7 — yum install mysql; "
                          "на Debian/Ubuntu — apt install mariadb-client. "
                          "Драйвер Python агенту не нужен.")
        if not self.настройки.get("dbname"):
            raise ОшибкаНастройки(
                "Не задана база журнала звонков.",
                подсказка=f"Проверьте {MYSQL_CONF} или задайте --mysql-db.")
        self._выполнить("SELECT 1")
        return True

    def _файл_настроек(self):
        """Временный my.cnf с паролем. Права 600, живёт секунды."""
        путь = os.path.join(self.каталог_временных, f"mysql-{os.getpid()}.cnf")
        строки = ["[client]"]
        for ключ, поле in (("host", "hostname"), ("user", "user"),
                           ("password", "password"), ("port", "port"),
                           ("socket", "sock")):
            значение = str(self.настройки.get(поле) or "").strip()
            if значение:
                строки.append(f"{ключ}={значение}")
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(дескриптор, "w", encoding="utf-8") as файл:
            файл.write("\n".join(строки) + "\n")
        return путь

    def _выполнить(self, запрос):
        программа = self.программа()
        if not программа:
            raise ОшибкаНастройки(
                "Программа «mysql» не найдена в PATH.",
                подсказка="Поставьте клиента MySQL/MariaDB на станции.")
        настройки = ""
        try:
            настройки = self._файл_настроек()
            команда = [программа, f"--defaults-extra-file={настройки}",
                       "--batch", "--raw", "--skip-column-names",
                       "--connect-timeout=10"]
            if self.настройки.get("dbname"):
                команда.append(str(self.настройки["dbname"]))
            команда += ["-e", запрос]
            # Через Popen, а не subprocess.run(capture_output=...):
            # `capture_output` появился только в Python 3.7, а агент обязан
            # работать на системном Python CentOS 7.
            процесс = subprocess.Popen(
                команда, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                universal_newlines=True)
            try:
                вывод, ошибки = процесс.communicate(timeout=120)
            except subprocess.TimeoutExpired:
                процесс.kill()
                процесс.communicate()
                raise ОшибкаНастройки(
                    "Запрос к базе журнала звонков не ответил за 120 секунд.",
                    подсказка="Проверьте нагрузку на базу и индекс по calldate "
                              "в таблице cdr.") from None
        except OSError as сбой:
            raise ОшибкаНастройки(
                f"Не удалось запустить mysql: {сбой}",
                подсказка="Проверьте, что программа mysql доступна агенту.") from сбой
        finally:
            if настройки:
                try:
                    os.unlink(настройки)
                except OSError:
                    pass
        if процесс.returncode != 0:
            подсказка = "Проверьте hostname, user, password и dbname в " + MYSQL_CONF
            if "Access denied" in (ошибки or ""):
                подсказка = ("Учётная запись из cdr_mysql.conf не пускает в базу. "
                             "Проверьте пароль и права SELECT на таблицу cdr.")
            elif "Can't connect" in (ошибки or ""):
                подсказка = ("База не отвечает по указанному адресу. Проверьте, "
                             "что MySQL запущен и слушает нужный порт или сокет.")
            строки_ошибки = (ошибки or "").strip().splitlines()
            последняя = строки_ошибки[-1].strip() if строки_ошибки else ""
            raise ОшибкаНастройки(
                "Запрос к базе журнала звонков не удался"
                + (f": {последняя}" if последняя else "."),
                подсказка=подсказка)
        return вывод or ""

    ПОЛЯ_ЗАПРОСА = ("accountcode", "src", "dst", "dcontext", "clid", "channel",
                    "dstchannel", "lastapp", "lastdata", "start", "duration",
                    "billsec", "disposition", "uniqueid", "userfield")

    #: Насколько назад от последнего прочитанного начала звонка смотреть.
    #: calldate — время НАЧАЛА, а строку Asterisk пишет по ОКОНЧАНИИ звонка:
    #: получасовой разговор, начатый в 10:00, появляется в таблице в 10:30 —
    #: когда позиция давно ушла дальше за короткими звонками, начатыми
    #: позже. Отбор «calldate >= позиции» такие звонки не видел никогда, а на
    #: колл-центре терялись как раз самые длинные разговоры. Уже
    #: отправленные в окне отсеиваются по списку отправленных.
    ЗАПАС_ДЛИННЫХ = 6 * 3600

    def звонки(self, весь_архив=False, предел=0, двигать_позицию=True,
               начало=None, конец=None):
        таблица = re.sub(r"[^A-Za-z0-9_]", "", str(self.настройки.get("table") or "cdr"))
        условия = []
        позиция = self.состояние.позиция_mysql()
        последний = str(позиция.get("последний") or "")
        окно = ""
        if not весь_архив and начало is None and последний:
            окно = self._раньше(последний, self.ЗАПАС_ДЛИННЫХ)
            условия.append(f"calldate >= '{окно}'")
        if начало:
            условия.append(f"calldate >= '{self._дата(начало)}'")
        if конец:
            условия.append(f"calldate <= '{self._дата(конец)}'")
        где = (" WHERE " + " AND ".join(условия)) if условия else ""
        ограничение = f" LIMIT {int(предел)}" if предел else ""
        запрос = (
            "SELECT accountcode, src, dst, dcontext, "
            # Табуляция и перевод строки внутри поля разорвали бы разбор
            # вывода `--batch --raw`: он разделяет поля именно ими. Меняем
            # их на пробел в самом запросе — иначе одно имя звонящего с
            # табуляцией сдвигало бы всю строку.
            "REPLACE(REPLACE(clid, '\\t', ' '), '\\n', ' ') AS clid, "
            "channel, dstchannel, lastapp, "
            "REPLACE(REPLACE(lastdata, '\\t', ' '), '\\n', ' ') AS lastdata, "
            "calldate AS start, duration, billsec, disposition, uniqueid, "
            "userfield "
            f"FROM `{таблица}`{где} ORDER BY calldate ASC, uniqueid ASC{ограничение}")
        вывод = self._выполнить(запрос)
        последний_виденный = последний
        для_пропуска = str(позиция.get("uniqueid") or "")
        отдано = 0
        for строка in вывод.splitlines():
            if not строка.strip():
                continue
            значения = строка.split("\t")
            if len(значения) != len(self.ПОЛЯ_ЗАПРОСА):
                log.warning("Строка выборки MySQL с %d полями вместо %d — "
                            "пропускаю: похоже, в поле попал разделитель.",
                            len(значения), len(self.ПОЛЯ_ЗАПРОСА))
                continue
            поля = собрать_поля(self.ПОЛЯ_ЗАПРОСА, значения)
            звонок = звонок_из_полей(поля)
            if not звонок.uniqueid:
                continue
            последний_виденный = str(поля.get("start") or последний_виденный)
            # Граница включающая: иначе звонки, попавшие в ту же секунду,
            # что и последний прочитанный, терялись бы навсегда. Повтор
            # отсеет /ask и список отправленных.
            if звонок.uniqueid == для_пропуска:
                continue
            # Окно запаса повторяет уже отправленное — это не новые звонки,
            # и в свод захода «пропущено» они попадать не должны.
            if окно and self.состояние.отправлен(звонок.uniqueid):
                continue
            yield звонок
            отдано += 1
            if двигать_позицию:
                self.состояние.запомнить_mysql(последний_виденный, звонок.uniqueid)
        log.debug("MySQL: отдано звонков %d, последний %s", отдано, последний_виденный)

    def _раньше(self, значение, секунд):
        """Та же отметка, сдвинутая назад на `секунд` — в виде для запроса."""
        точная = datetime.strptime(self._дата(значение), "%Y-%m-%d %H:%M:%S")
        return (точная - timedelta(seconds=int(секунд))).strftime("%Y-%m-%d %H:%M:%S")

    def _дата(self, значение):
        """Дата для условия запроса — только после проверки образцом.

        Значение приходит из состояния и из ключей командной строки, а
        попадает прямо в текст запроса. Проверка образцом здесь —
        единственное, что стоит между журналом звонков и подстановкой SQL.
        """
        if isinstance(значение, (int, float)):
            return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(значение))
        текст = str(значение or "").strip()
        for образец in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
            try:
                разобранная = datetime.strptime(текст[:19], образец)
                return разобранная.strftime("%Y-%m-%d %H:%M:%S")
            except ValueError:
                continue
        raise ОшибкаНастройки(
            f"Отметка времени «{текст}» не годится для запроса к базе.",
            подсказка="Ожидается «2026-09-01 10:00:00».")


class ИсточникКаталога:
    """Когда журнала нет вовсе: звонок — это файл записи.

    Так живут станции, где ``cdr_csv`` выключен, а база не заводилась:
    записи есть, журнала нет. Идентификатор звонка приходится придумывать —
    берём устойчивый отпечаток пути, чтобы один и тот же файл на каждом
    заходе получал один и тот же идентификатор и не заливался дважды.
    """

    имя = "folder"

    #: Числа в имени файла, похожие на телефонные номера.
    НОМЕР = re.compile(r"(?<!\d)(\d{3,15})(?!\d)")

    def __init__(self, каталог, состояние):
        self.каталог = str(каталог or "")
        self.состояние = состояние

    def описание(self):
        return self.каталог or "(каталог не задан)"

    def доступен(self):
        return bool(self.каталог) and os.path.isdir(self.каталог)

    def проверить(self):
        if not self.каталог:
            raise ОшибкаНастройки(
                "Каталог записей не задан.",
                подсказка="Укажите --recordings-dir или recordings_dir в "
                          + НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
        if not os.path.isdir(self.каталог):
            raise ОшибкаНастройки(
                f"Каталог записей {self.каталог} не найден.",
                подсказка="Проверьте путь; по умолчанию это " + ЗАПИСИ_ПО_УМОЛЧАНИЮ)
        if not os.access(self.каталог, os.R_OK | os.X_OK):
            raise ОшибкаНастройки(
                f"Каталог записей {self.каталог} не читается.",
                подсказка="Добавьте пользователя агента в группу asterisk.")
        return True

    def звонки(self, весь_архив=False, предел=0, двигать_позицию=True,
               начало=None, конец=None):
        if not self.доступен():
            return
        порог = 0.0 if весь_архив or начало else дробное(
            (self.состояние.данные.get("каталог") or {}).get("последний"), 0.0)
        новейший = порог
        отдано = 0
        for корень, _, файлы in os.walk(self.каталог):
            for имя in sorted(файлы):
                if os.path.splitext(имя)[1].lower() not in РАСШИРЕНИЯ:
                    continue
                путь = os.path.join(корень, имя)
                try:
                    сведения = os.stat(путь)
                except OSError:
                    continue
                if порог and сведения.st_mtime <= порог:
                    continue
                звонок = self._звонок_из_файла(путь, сведения)
                новейший = max(новейший, сведения.st_mtime)
                yield звонок
                отдано += 1
                if предел and отдано >= предел:
                    break
            if предел and отдано >= предел:
                break
        if двигать_позицию and новейший > порог:
            self.состояние.данные["каталог"] = {"последний": новейший}

    def _звонок_из_файла(self, путь, сведения):
        относительный = os.path.relpath(путь, self.каталог)
        отпечаток = hashlib.sha1(
            относительный.encode("utf-8", "replace")).hexdigest()[:16]
        номера = self.НОМЕР.findall(os.path.basename(путь))
        звонок = Звонок(
            uniqueid="file-" + отпечаток,
            src=номера[0] if номера else "",
            dst=номера[1] if len(номера) > 1 else "",
            started_at=сведения.st_mtime,
            duration=длительность_wav(путь),
            answered=True,
            recording=путь,
            userfield=относительный,
        )
        звонок.billsec = звонок.duration
        return звонок


def длительность_wav(путь):
    """Секунды звука в WAV — из заголовка, без чтения самого звука.

    Нужна источнику «каталог записей»: длительности у такого звонка нет
    ниоткуда, а ноль выключал бы отсев коротких. Для остальных форматов
    честный ноль лучше выдуманного числа.
    """
    if os.path.splitext(путь)[1].lower() != ".wav":
        return 0
    try:
        with wave.open(путь, "rb") as файл:
            частота = файл.getframerate() or 1
            return int(файл.getnframes() / частота)
    except (OSError, wave.Error, EOFError, ZeroDivisionError, AttributeError):
        # Битый или недописанный WAV — обычное дело в каталоге записей;
        # честный ноль лучше выдуманной длительности.
        return 0


def найти_журналы(заданный=None):
    """Какие CSV-журналы читать: заданный ключом либо всё, что нашлось."""
    if заданный:
        return [str(заданный)]
    найдено = []
    if os.path.isfile(CDR_CSV_ПО_УМОЛЧАНИЮ):
        найдено.append(CDR_CSV_ПО_УМОЛЧАНИЮ)
    try:
        for имя in sorted(os.listdir(CDR_CUSTOM)):
            if имя.lower().endswith(".csv"):
                найдено.append(os.path.join(CDR_CUSTOM, имя))
    except OSError:
        pass
    return найдено


def выбрать_источник(параметры, состояние):
    """Источник журнала: заданный явно или найденный самостоятельно.

    Порядок поиска — от точного к приблизительному: CSV (он есть на
    большинстве станций и читается без учётных данных), затем MySQL (если
    в ``cdr_mysql.conf`` что-то настроено), затем каталог записей. Каталог
    последний не случайно: у звонка оттуда нет ни номеров, ни времени
    начала, ни расположения — только файл.
    """
    вид = str(параметры.get("source") or "auto").strip().lower()
    журналы = найти_журналы(параметры.get("cdr_file"))
    записи = параметры.get("recordings_dir") or ЗАПИСИ_ПО_УМОЛЧАНИЮ

    if вид in ("cdr_csv", "csv", "cdr"):
        return ИсточникCSV(журналы or [параметры.get("cdr_file")
                                       or CDR_CSV_ПО_УМОЛЧАНИЮ], состояние)
    if вид in ("mysql", "cdr_mysql", "mariadb"):
        return ИсточникMySQL.из_конфига_asterisk(
            параметры.get("mysql_conf") or MYSQL_CONF, состояние,
            поверх=параметры.get("mysql") or {},
            каталог_временных=параметры.get("state_dir"))
    if вид in ("folder", "dir", "каталог"):
        return ИсточникКаталога(записи, состояние)
    if вид not in ("auto", "", "сам"):
        raise ОшибкаНастройки(
            f"Неизвестный источник: «{вид}».",
            подсказка="Ожидается auto, cdr_csv, mysql или folder.")

    if журналы:
        log.info("Источник определён сам: журнал CSV (%s)", ", ".join(журналы))
        return ИсточникCSV(журналы, состояние)
    if os.path.isfile(параметры.get("mysql_conf") or MYSQL_CONF):
        источник = ИсточникMySQL.из_конфига_asterisk(
            параметры.get("mysql_conf") or MYSQL_CONF, состояние,
            поверх=параметры.get("mysql") or {},
            каталог_временных=параметры.get("state_dir"))
        if источник.доступен():
            log.info("Источник определён сам: %s", источник.описание())
            return источник
        log.warning("Настройки MySQL есть (%s), но программа «mysql» не "
                    "найдена — беру каталог записей.",
                    параметры.get("mysql_conf") or MYSQL_CONF)
    if os.path.isdir(записи):
        log.info("Источник определён сам: каталог записей %s. Журнала звонков "
                 "на станции не нашлось — сведений о номерах и времени будет "
                 "меньше, чем могло бы.", записи)
        return ИсточникКаталога(записи, состояние)
    raise ОшибкаНастройки(
        "Не нашёл ни журнала CSV, ни настроек MySQL, ни каталога записей.",
        подсказка=f"Проверьте {CDR_CSV_ПО_УМОЛЧАНИЮ}, {MYSQL_CONF} и "
                  f"{ЗАПИСИ_ПО_УМОЛЧАНИЮ} либо задайте --source и --cdr-file.")


