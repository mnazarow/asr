class Замок:
    """Файловая блокировка: второй агент на станции не нужен.

    Два агента читают один журнал с одной позиции и заливают одно и то же
    дважды, а на станции с узким каналом это ещё и вдвое дольше. Замок
    берётся неблокирующим ``flock`` — ждать нечего, лучше сказать человеку,
    кто именно держит.
    """

    def __init__(self, путь):
        self.путь = str(путь)
        self._дескриптор = None

    def взять(self):
        каталог = os.path.dirname(os.path.abspath(self.путь))
        try:
            if каталог and not os.path.isdir(каталог):
                os.makedirs(каталог, 0o700)
        except OSError as сбой:
            raise ОшибкаНастройки(
                f"Каталог {каталог} не создаётся: {сбой}",
                подсказка="Запустите агента от root или задайте свой каталог "
                          "состояния ключом --state-dir.") from сбой
        try:
            # Сознательно `os.open`, а не `open`: дескриптор обязан жить всё
            # время работы агента, и объект файла тут только мешал бы —
            # закрылся бы при сборке мусора, а с ним ушёл бы и замок.
            self._дескриптор = os.open(
                self.путь, os.O_RDWR | os.O_CREAT, 0o600)
        except OSError as сбой:
            raise ОшибкаНастройки(
                f"Файл блокировки {self.путь} не открывается: {сбой}",
                подсказка="Проверьте права на каталог состояния.") from сбой
        try:
            fcntl.flock(self._дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as сбой:
            чужой = self._чужой_pid()
            self.отпустить()
            if сбой.errno in (errno.EACCES, errno.EAGAIN, errno.EWOULDBLOCK):
                raise УжеЗапущен(
                    "Агент уже запущен" + (f" (процесс {чужой})" if чужой else "")
                    + f", файл блокировки {self.путь}.",
                    подсказка="Остановите службу: systemctl stop asrhub-agent "
                              "— или дождитесь конца текущего захода.") from сбой
            raise ОшибкаНастройки(
                f"Блокировка {self.путь} не берётся: {сбой}") from сбой
        try:
            os.ftruncate(self._дескриптор, 0)
            os.write(self._дескриптор, f"{os.getpid()}\n".encode())
            os.fsync(self._дескриптор)
        except OSError:
            pass                  # номер процесса — удобство, а не условие
        return self

    def _чужой_pid(self):
        try:
            with open(self.путь, encoding="utf-8") as файл:
                return файл.read(32).strip()
        except OSError:
            return ""

    def отпустить(self):
        if self._дескриптор is None:
            return
        try:
            fcntl.flock(self._дескриптор, fcntl.LOCK_UN)
        except OSError:
            pass
        try:
            os.close(self._дескриптор)
        except OSError:
            pass
        self._дескриптор = None


