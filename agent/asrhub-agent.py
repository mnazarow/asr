def маска_ключа(ключ):
    """Ключ доступа в виде, который не жалко записать в журнал.

    Журнал агента лежит на станции, а станцию обслуживает подрядчик. Ключ,
    попавший в ``/var/log/asrhub-agent.log``, — это доступ к архиву всех
    разговоров организации; маска оставляет ровно столько, чтобы человек
    узнал свой ключ в строке «использован ключ ah_a1b2…».
    """
    ключ = str(ключ or "")
    if not ключ:
        return "(не задан)"
    if len(ключ) <= 8:
        return "…"
    return ключ[:7] + "…"


def целое(значение, по_умолчанию=0):
    """Целое из чего угодно. Мусор — это `по_умолчанию`, а не исключение."""
    try:
        return int(float(str(значение).strip() or по_умолчанию))
    except (TypeError, ValueError):
        return по_умолчанию


def дробное(значение, по_умолчанию=0.0):
    try:
        return float(str(значение).strip() or по_умолчанию)
    except (TypeError, ValueError):
        return по_умолчанию


def логическое(значение, по_умолчанию=False):
    """Признак из настройки: «да», «yes», «1», «true», «вкл» — всё это да.

    Настройку правят руками в INI-файле, и требовать от человека ровно
    одного написания незачем: ``skip_unanswered = да`` должно работать.
    """
    if значение is None or значение == "":
        return по_умолчанию
    if isinstance(значение, bool):
        return значение
    строка = str(значение).strip().lower()
    if строка in ("1", "true", "yes", "on", "да", "вкл", "включено"):
        return True
    if строка in ("0", "false", "no", "off", "нет", "выкл", "выключено"):
        return False
    return по_умолчанию


def размер_словами(байт):
    """Размер файла для человека: «412,3 МБ» вместо «432324608»."""
    байт = float(байт or 0)
    for единица in ("Б", "КБ", "МБ", "ГБ"):
        if байт < 1024 or единица == "ГБ":
            return f"{байт:.1f} {единица}".replace(".", ",")
        байт /= 1024
    return f"{байт:.1f} ГБ"


def время_словами(момент):
    if not момент:
        return "—"
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(float(момент)))


def момент_из(значение):
    """Отметка времени Asterisk («2026-09-10 14:03:11») в секунды эпохи."""
    значение = str(значение or "").strip()
    if not значение:
        return 0.0
    for образец in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M"):
        try:
            return datetime.strptime(значение[:19], образец).timestamp()
        except ValueError:
            continue
    try:                        # некоторые сборки пишут прямо секунды эпохи
        return float(значение)
    except (TypeError, ValueError):
        return 0.0


#: Относительные сроки для --since/--until: «-7d», «-12h», «-30m».
ОТНОСИТЕЛЬНЫЙ_СРОК = re.compile(r"^-(\d+)\s*([dhmwдчмн])$", re.IGNORECASE)

#: Множители к ним. Русские буквы приняты намеренно: человек, который
#: правит настройки на станции, пишет «-7д» так же охотно, как «-7d».
МНОЖИТЕЛИ_СРОКА = {"m": 60, "h": 3600, "d": 86400, "w": 7 * 86400,
                   "н": 60, "ч": 3600, "д": 86400, "м": 30 * 86400}


def разобрать_дату(значение, имя="дата"):
    """Дата из командной строки в секунды эпохи.

    Принимает «2026-09-01», «2026-09-01 10:00», «2026-09-01T10:00:00»,
    «-7d» («семь суток назад»), «now»/«сейчас» и просто число секунд.
    Непонятное — это ошибка настройки, а не молчаливый ноль: «собрать за
    период» с датой, которую никто не разобрал, собрало бы весь архив.
    """
    значение = str(значение or "").strip()
    if not значение:
        return None
    if значение.lower() in ("now", "сейчас"):
        return time.time()
    совпадение = ОТНОСИТЕЛЬНЫЙ_СРОК.match(значение)
    if совпадение:
        число = int(совпадение.group(1))
        буква = совпадение.group(2).lower()
        return time.time() - число * МНОЖИТЕЛИ_СРОКА.get(буква, 86400)
    for образец in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M",
                    "%Y-%m-%dT%H:%M", "%Y-%m-%d", "%d.%m.%Y %H:%M", "%d.%m.%Y"):
        try:
            return datetime.strptime(значение, образец).timestamp()
        except ValueError:
            continue
    if re.match(r"^\d{9,}(\.\d+)?$", значение):
        return float(значение)
    raise ОшибкаНастройки(
        f"Не понимаю {имя}: «{значение}».",
        подсказка="Ожидается «2026-09-01», «2026-09-01 10:00», «-7d» или "
                  "секунды эпохи.")


def свободно_байт(путь):
    """Свободное место на разделе, где лежит путь. Ноль — «не удалось»."""
    try:
        каталог = путь if os.path.isdir(путь) else os.path.dirname(путь) or "."
        сведения = os.statvfs(каталог)
        return сведения.f_bavail * сведения.f_frsize
    except (OSError, ValueError):
        return 0


def безопасное(значение):
    """Значение поля звонка, пригодное для подстановки в путь."""
    return ОПАСНОЕ_В_ИМЕНИ.sub("_", str(значение or "")).strip()


def внутри(каталог, кандидат):
    """Путь, если он существует и лежит ВНУТРИ каталога записей.

    Проверка идёт после разрешения ссылок: очистка полей звонка снимает
    «..», но символическую ссылку внутри каталога кладёт не звонящий, а
    тот, у кого есть доступ к станции, — и шаблон, честно составленный из
    безопасных знаков, всё равно приводит наружу.
    """
    try:
        корень = os.path.realpath(каталог)
        путь = os.path.realpath(кандидат)
        if путь != корень and not путь.startswith(корень.rstrip(os.sep) + os.sep):
            log.warning("Шаблон имени вывел за каталог записей: %s", кандидат)
            return None
        return путь if os.path.isfile(путь) else None
    except OSError:
        return None


