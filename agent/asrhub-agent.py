class ТелоЗапроса:
    """Многочастное тело, которое читается кусками прямо с диска.

    Собирать запрос в памяти нельзя: запись двухчасового совещания — это
    гигабайт, а на станции бывает 512 МБ оперативной памяти вместе с самой
    Asterisk. ``http.client`` умеет читать из объекта с ``read`` блоками по
    восемь килобайт — этого достаточно, если честно сообщить длину.
    """

    def __init__(self, голова, файл, хвост):
        self.голова = голова
        self.файл = файл
        self.хвост = хвост
        self._части = None
        self.перемотать()

    def перемотать(self):
        """Перед повтором запроса: тело уже прочитано и его надо начать заново."""
        if self.файл is not None:
            self.файл.seek(0)
        self._части = [io.BytesIO(self.голова), self.файл, io.BytesIO(self.хвост)]
        self._части = [ч for ч in self._части if ч is not None]
        self._место = 0

    def read(self, сколько=-1):
        if сколько is None or сколько < 0:
            куски = []
            while self._место < len(self._части):
                куски.append(self._части[self._место].read())
                self._место += 1
            return b"".join(куски)
        while self._место < len(self._части):
            кусок = self._части[self._место].read(сколько)
            if кусок:
                return кусок
            self._место += 1
        return b""


class Клиент:
    """HTTP-клиент сервера ASR Hub: только четыре адреса, зато с повторами.

    Повторяем на сетевых сбоях, 5xx, 408 и 429 — это состояния, которые
    проходят сами. На остальных 4xx повтор бессмысленен и вреден: ключ не
    станет действительным оттого, что мы спросим шесть раз, а вот в журнал
    сервера это попадёт как попытка подбора.
    """

    def __init__(self, адрес, ключ, таймаут=30.0, таймаут_файла=120.0,
                 повторов=5, небезопасно=False, паузы=None, ждать=None):
        self.адрес = str(адрес or "").rstrip("/")
        if not self.адрес:
            raise ОшибкаНастройки(
                "Не задан адрес сервера ASR Hub.",
                подсказка="Укажите --url http://сервер:8081 или url= в "
                          + НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
        if not self.адрес.startswith(("http://", "https://")):
            self.адрес = "http://" + self.адрес
        self.ключ = str(ключ or "")
        try:
            # Заголовки HTTP кодируются в latin-1, и ключ с кириллицей
            # роняет запрос изнутри http.client — «UnicodeEncodeError:
            # latin-1» вместо внятной причины. А кириллица в ключе бывает:
            # его копируют из письма, и «ah_» иногда оказывается набранным
            # в русской раскладке.
            self.ключ.encode("ascii")
        except UnicodeEncodeError as сбой:
            raise ОшибкаНастройки(
                "Ключ доступа содержит не-латинские знаки.",
                подсказка="Скопируйте ключ из раздела «Доступ» веб-интерфейса "
                          "заново: он состоит только из латиницы, цифр и "
                          "подчёркиваний и начинается с «ah_».") from сбой
        self.таймаут = float(таймаут)
        self.таймаут_файла = float(таймаут_файла)
        self.повторов = max(0, целое(повторов, 5))
        self.небезопасно = bool(небезопасно)
        self.паузы = tuple(паузы or ПАУЗЫ_ПОВТОРА)
        self.ждать = ждать or time.sleep
        self._опенер = self._собрать_опенер()

    def _собрать_опенер(self):
        обработчики = []
        if self.адрес.startswith("https://"):
            if self.небезопасно:
                контекст = ssl.create_default_context()
                # Порядок важен: снять проверку имени можно только до
                # CERT_NONE, иначе ssl отвечает ValueError.
                контекст.check_hostname = False
                контекст.verify_mode = ssl.CERT_NONE
                log.warning("ВНИМАНИЕ: проверка сертификата сервера отключена "
                            "(--insecure). Записи разговоров поедут по каналу, "
                            "который может подменить кто угодно на пути. Это "
                            "годится только для проверки связи.")
            else:
                контекст = ssl.create_default_context()
            обработчики.append(запросы_url.HTTPSHandler(context=контекст))
        return запросы_url.build_opener(*обработчики)

    # --- низкий уровень ----------------------------------------------------

    def _заголовки(self, тип=None, длина=None):
        заголовки = {
            "X-API-Key": self.ключ,
            "Accept": "application/json",
            "User-Agent": f"asrhub-agent/{ВЕРСИЯ} (python "
                          f"{sys.version_info[0]}.{sys.version_info[1]})",
        }
        if тип:
            заголовки["Content-Type"] = тип
        if длина is not None:
            заголовки["Content-Length"] = str(длина)
        return заголовки

    def _запрос(self, метод, путь, тело=None, тип=None, длина=None,
                таймаут=None, повторять=True, что=""):
        адрес = self.адрес + путь
        таймаут = float(таймаут or self.таймаут)
        что = что or путь
        попытка = 0
        while True:
            попытка += 1
            if isinstance(тело, ТелоЗапроса) and попытка > 1:
                тело.перемотать()
            запрос = запросы_url.Request(
                адрес, data=тело, method=метод,
                headers=self._заголовки(тип, длина))
            try:
                ответ = self._опенер.open(запрос, timeout=таймаут)
                try:
                    сырое = ответ.read()
                finally:
                    ответ.close()
                return self._разобрать(сырое, что)
            except ошибки_url.HTTPError as сбой:
                отказ = self._отказ(сбой, что)
                if повторять and self._стоит_повторить(отказ.статус) \
                        and попытка <= self.повторов:
                    пауза = self._пауза(попытка, сбой)
                    log.warning("%s: сервер ответил %d (%s). Повтор через %s с "
                                "(попытка %d из %d).", что, отказ.статус,
                                отказ.сообщение, пауза, попытка, self.повторов)
                    self.ждать(пауза)
                    continue
                raise отказ from сбой
            # OSError покрывает и URLError, и тайм-аут сокета, и ssl.SSLError
            # на всех версиях Python: в 3.6 socket.timeout — подкласс OSError,
            # а TimeoutError им не является, и ловить его отдельно было бы
            # верно только на новых версиях.
            except (http.client.HTTPException, OSError) as сбой:
                if попытка <= self.повторов:
                    пауза = self._пауза(попытка, None)
                    log.warning("%s: связи с сервером нет (%s). Повтор через "
                                "%s с (попытка %d из %d).", что,
                                self._причина(сбой), пауза, попытка, self.повторов)
                    self.ждать(пауза)
                    continue
                raise ОшибкаСвязи(
                    f"{что}: сервер {self.адрес} недоступен ({self._причина(сбой)}).",
                    подсказка="Проверьте адрес и порт, доступ наружу со "
                              "станции и сертификат сервера. Быстрая проверка: "
                              f"curl -sS -H 'X-API-Key: …' {self.адрес}"
                              "/api/health") from сбой

    def _стоит_повторить(self, статус):
        return статус >= 500 or статус in (408, 429)

    def _пауза(self, попытка, сбой):
        пауза = self.паузы[min(попытка, len(self.паузы)) - 1]
        # 429 приходит с указанием, сколько ждать. Своя лесенка тут не
        # просто лишняя — она мешает: сервер знает про своё окно точнее.
        if сбой is not None:
            try:
                указано = целое(сбой.headers.get("Retry-After"), 0)
            except (AttributeError, TypeError):
                указано = 0
            if 0 < указано <= 300:
                return указано
        return пауза

    def _причина(self, сбой):
        причина = getattr(сбой, "reason", None)
        return str(причина or сбой) or type(сбой).__name__

    def _разобрать(self, сырое, что):
        текст = (сырое or b"").decode("utf-8", "replace").strip()
        if not текст:
            return {}
        try:
            данные = json.loads(текст)
        except ValueError as сбой:
            raise ОтказСервера(
                200, "bad_json",
                f"{что}: ответ сервера не читается как JSON ({сбой}).",
                подсказка="Похоже, по адресу отвечает не ASR Hub, а прокси "
                          "или страница входа. Проверьте --url.") from сбой
        return данные if isinstance(данные, dict) else {"результат": данные}

    def _отказ(self, сбой, что):
        """Отказ сервера, разобранный в человеческую жалобу.

        Сервер отвечает ошибкой и полями верхнего уровня, и вложенной в
        ``detail`` — так сделано ради старых клиентов. Читаем оба вида:
        разбирать только один означало бы показывать человеку «HTTP 400»
        там, где сервер прямым текстом написал, что именно не так.
        """
        текст = ""
        try:
            текст = сбой.read().decode("utf-8", "replace")
        except Exception:                                    # noqa: BLE001
            pass
        код, сообщение, подсказка = "", "", ""
        try:
            данные = json.loads(текст) if текст else {}
        except ValueError:
            данные = {}
        if isinstance(данные, dict):
            подробности = данные.get("detail") if isinstance(
                данные.get("detail"), dict) else данные
            код = str(подробности.get("code") or "")
            сообщение = str(подробности.get("message") or "")
            подсказка = str(подробности.get("hint") or "")
        if not сообщение:
            сообщение = (текст or getattr(сбой, "reason", "") or "").strip()[:300]
        if сбой.code == 401 and not подсказка:
            подсказка = ("Проверьте ключ доступа: он начинается с «ah_», "
                         "заводится в разделе «Доступ» веб-интерфейса и должен "
                         "иметь право записи.")
        if сбой.code == 413 and not подсказка:
            подсказка = ("Запись больше предела загрузки на сервере. Поднимите "
                         "«Предел размера загрузки» или сжимайте записи.")
        return ОтказСервера(сбой.code, код, f"{что}: {сообщение}".strip(": "),
                            подсказка)

    # --- адреса ------------------------------------------------------------

    def hello(self, сведения):
        тело = json.dumps(сведения, ensure_ascii=False).encode()
        return self._запрос("POST", "/api/telephony/agent/hello", тело,
                            "application/json; charset=utf-8", len(тело),
                            что="приветствие")

    def спросить(self, agent_id, идентификаторы):
        """Какие из этих звонков серверу ещё нужны.

        Спрашиваем порциями: сервер не принимает больше пяти тысяч за раз,
        а при сборе архива список идёт на десятки тысяч.
        """
        нужны = []
        известно = 0
        список = [и for и in идентификаторы if и]
        for начало in range(0, len(список), ПОРЦИЯ_ВОПРОСА):
            порция = список[начало:начало + ПОРЦИЯ_ВОПРОСА]
            тело = json.dumps({"agent_id": agent_id, "ids": порция},
                              ensure_ascii=False).encode()
            ответ = self._запрос("POST", "/api/telephony/agent/ask", тело,
                                 "application/json; charset=utf-8", len(тело),
                                 что="вопрос о звонках")
            нужны.extend(str(и) for и in (ответ.get("wanted") or []))
            известно += целое(ответ.get("known"), 0)
        return нужны, известно

    def отправить(self, поля, путь=None):
        """Звонок и, если она есть, его запись — одним многочастным запросом."""
        граница = "----asrhub" + hashlib.sha1(
            f"{time.time()}{os.getpid()}{поля.get('uniqueid')}".encode()
        ).hexdigest()[:24]
        мета = json.dumps(поля, ensure_ascii=False).encode()
        голова = io.BytesIO()
        голова.write(f"--{граница}\r\n".encode())
        голова.write(b'Content-Disposition: form-data; name="meta"\r\n')
        голова.write(b"Content-Type: application/json; charset=utf-8\r\n\r\n")
        голова.write(мета)
        голова.write(b"\r\n")
        if путь:
            имя = os.path.basename(путь)
            тип = ТИПЫ_ЗВУКА.get(os.path.splitext(имя)[1].lower(),
                                 "application/octet-stream")
            голова.write(f"--{граница}\r\n".encode())
            голова.write(
                ('Content-Disposition: form-data; name="file"; filename="'
                 + имя.replace('"', "_") + '"\r\n').encode())
            голова.write(f"Content-Type: {тип}\r\n\r\n".encode())
            хвост = f"\r\n--{граница}--\r\n".encode()
        else:
            хвост = f"--{граница}--\r\n".encode()
        тип_тела = f"multipart/form-data; boundary={граница}"
        начало = голова.getvalue()
        if not путь:
            тело = начало + хвост
            return self._запрос("POST", "/api/telephony/agent/call", тело,
                                тип_тела, len(тело), таймаут=self.таймаут,
                                что=f"звонок {поля.get('uniqueid')}")
        размер = os.path.getsize(путь)
        длина = len(начало) + размер + len(хвост)
        with open(путь, "rb") as файл:
            тело = ТелоЗапроса(начало, файл, хвост)
            return self._запрос("POST", "/api/telephony/agent/call", тело,
                                тип_тела, длина, таймаут=self.таймаут_файла,
                                что=f"звонок {поля.get('uniqueid')}")

    def команда(self, agent_id):
        адрес = "/api/telephony/agent/command?" + разбор_url.urlencode(
            {"agent_id": agent_id})
        ответ = self._запрос("GET", адрес, что="задание")
        return str(ответ.get("command") or "")


