class Состояние:
    """То, что агент обязан помнить между запусками.

    Позиция чтения журнала (байты плюс inode — чтобы пережить ротацию),
    последний звонок из MySQL, идентификаторы отправленного, отложенные
    звонки и счётчики. Запись атомарная: временный файл рядом и
    ``os.replace``. Иначе выключение станции ровно во время записи
    оставило бы обрезанный JSON, агент прочитал бы его как пустой и залил
    бы весь архив заново — десятки гигабайт по чужому каналу.
    """

    ВЕРСИЯ_ФОРМАТА = 1

    def __init__(self, путь):
        self.путь = str(путь)
        self.данные = {
            "версия": self.ВЕРСИЯ_ФОРМАТА,
            "agent_id": "",
            "csv": {},
            "mysql": {"последний": "", "uniqueid": ""},
            "каталог": {"последний": 0.0},
            "отправленные": [],
            "отложенные": {},
            "счётчики": {"отправлено": 0, "с записью": 0, "пропущено": 0,
                         "ошибок": 0, "байт": 0},
            "обновлено": 0.0,
        }
        self._множество = set()
        self._последняя_запись = 0.0

    # --- чтение и запись --------------------------------------------------

    def прочитать(self):
        try:
            with open(self.путь, encoding="utf-8") as файл:
                прочитанное = json.load(файл)
        except FileNotFoundError:
            log.debug("Состояния ещё нет: %s — первый запуск", self.путь)
            return self
        except (OSError, ValueError) as сбой:
            # Не падаем: испорченное состояние — это повод начать заново, а
            # не повод остановить сбор. Но говорим об этом громко: следом
            # поедет весь архив, и человек должен понимать почему.
            log.error("Состояние %s не прочиталось (%s). Начинаю с чистого "
                      "листа: сервер отсеет уже известные звонки на шаге "
                      "/ask, но первый заход будет долгим.", self.путь, сбой)
            return self
        if isinstance(прочитанное, dict):
            for ключ, значение in прочитанное.items():
                if ключ in self.данные and isinstance(
                        self.данные[ключ], dict) and isinstance(значение, dict):
                    self.данные[ключ].update(значение)
                else:
                    self.данные[ключ] = значение
        self.данные.setdefault("отправленные", [])
        if not isinstance(self.данные["отправленные"], list):
            self.данные["отправленные"] = []
        self._множество = set(self.данные["отправленные"])
        log.debug("Состояние прочитано: %d отправленных, %d отложенных",
                  len(self._множество), len(self.данные.get("отложенные") or {}))
        return self

    def сохранить(self, принудительно=False, не_чаще=5.0):
        """Атомарная запись состояния. Права 600: рядом лежит agent_id.

        Частая запись на станции с флеш-диском — это износ, поэтому по
        умолчанию не чаще раза в пять секунд. В конце захода и по сигналу
        вызывается принудительно.
        """
        сейчас = time.time()
        if not принудительно and (сейчас - self._последняя_запись) < не_чаще:
            return False
        self._усечь()
        self.данные["обновлено"] = сейчас
        временный = self.путь + f".tmp{os.getpid()}"
        try:
            каталог = os.path.dirname(os.path.abspath(self.путь))
            if каталог and not os.path.isdir(каталог):
                os.makedirs(каталог, 0o700)
            дескриптор = os.open(временный,
                                 os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(дескриптор, "w", encoding="utf-8") as файл:
                json.dump(self.данные, файл, ensure_ascii=False)
                файл.flush()
                os.fsync(файл.fileno())
            os.replace(временный, self.путь)
            self._синхронизировать_каталог(каталог)
        except OSError as сбой:
            log.error("Состояние не сохранено в %s: %s. Проверьте права и "
                      "свободное место — иначе следующий заход начнёт сбор "
                      "заново.", self.путь, сбой)
            try:
                os.unlink(временный)
            except OSError:
                pass
            return False
        self._последняя_запись = сейчас
        return True

    def _синхронизировать_каталог(self, каталог):
        """Сброс каталога на диск: без него `os.replace` переживает не всё.

        Само переименование атомарно, но на ext4 с отложенной записью после
        внезапного выключения станции каталог может ещё не знать о новом
        файле — и состояние окажется нулевой длины.
        """
        try:
            дескриптор = os.open(каталог or ".", os.O_RDONLY)
            try:
                os.fsync(дескриптор)
            finally:
                os.close(дескриптор)
        except OSError:
            pass

    # --- отправленные -----------------------------------------------------

    def отправлен(self, uniqueid):
        return uniqueid in self._множество

    def отметить(self, uniqueid):
        if not uniqueid or uniqueid in self._множество:
            return
        self._множество.add(uniqueid)
        self.данные["отправленные"].append(uniqueid)

    def _усечь(self):
        список = self.данные.get("отправленные") or []
        if len(список) <= ПРЕДЕЛ_ОТПРАВЛЕННЫХ:
            return
        отброшено = len(список) - ПРЕДЕЛ_ОТПРАВЛЕННЫХ
        список = список[отброшено:]
        self.данные["отправленные"] = список
        self._множество = set(список)
        log.info("Список отправленных усечён до %d записей (отброшено %d): "
                 "повторно прийти может только свежий звонок, а старые "
                 "отсеет сервер на шаге /ask.", ПРЕДЕЛ_ОТПРАВЛЕННЫХ, отброшено)

    # --- позиции источников ------------------------------------------------

    def позиция(self, путь):
        return dict(self.данные.setdefault("csv", {}).get(str(путь)) or {})

    def запомнить_позицию(self, путь, смещение, inode):
        self.данные.setdefault("csv", {})[str(путь)] = {
            "offset": int(смещение), "inode": int(inode), "время": time.time()}

    def позиция_mysql(self):
        return dict(self.данные.get("mysql") or {})

    def запомнить_mysql(self, последний, uniqueid=""):
        self.данные["mysql"] = {"последний": последний, "uniqueid": uniqueid,
                                "время": time.time()}

    # --- отложенные --------------------------------------------------------

    def отложить(self, звонок, причина):
        отложенные = self.данные.setdefault("отложенные", {})
        if len(отложенные) > 5000 and звонок.uniqueid not in отложенные:
            log.warning("Отложенных звонков уже %d — новый (%s) не запоминаю. "
                        "Похоже, записи не дописываются вовсе: проверьте "
                        "MixMonitor и свободное место на станции.",
                        len(отложенные), звонок.uniqueid)
            return
        отложенные[звонок.uniqueid] = {
            "звонок": {имя: getattr(звонок, имя) for имя in Звонок.__slots__},
            "причина": причина, "до": time.time() + СРОК_ОТЛОЖЕННЫХ}

    def отложенные(self):
        """Отложенные звонки, у которых не вышел срок. Просроченные забываем."""
        отложенные = self.данные.setdefault("отложенные", {})
        сейчас = time.time()
        готовые = []
        for uniqueid in list(отложенные):
            запись = отложенные.get(uniqueid) or {}
            if дробное(запись.get("до"), 0) < сейчас:
                отложенные.pop(uniqueid, None)
                log.info("Звонок %s снят с ожидания: запись так и не "
                         "появилась за сутки.", uniqueid)
                continue
            поля = запись.get("звонок") or {}
            звонок = Звонок()
            for имя in Звонок.__slots__:
                if имя in поля:
                    setattr(звонок, имя, поля[имя])
            if звонок.uniqueid:
                готовые.append(звонок)
        return готовые

    def снять_с_ожидания(self, uniqueid):
        self.данные.setdefault("отложенные", {}).pop(uniqueid, None)

    # --- счётчики ----------------------------------------------------------

    def посчитать(self, **добавки):
        счётчики = self.данные.setdefault("счётчики", {})
        for имя, значение in добавки.items():
            счётчики[имя] = целое(счётчики.get(имя), 0) + целое(значение, 0)

    def свод(self):
        """Состояние для поля ``state`` в /hello — то, что видно в разделе «АТС»."""
        return {
            "счётчики": dict(self.данные.get("счётчики") or {}),
            "отправленных_помню": len(self._множество),
            "отложено": len(self.данные.get("отложенные") or {}),
            "позиции": {путь: значение.get("offset")
                        for путь, значение in (self.данные.get("csv") or {}).items()},
            "обновлено": self.данные.get("обновлено"),
        }


