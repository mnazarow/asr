#!/usr/bin/env python3
"""Агент ASR Hub: живёт НА станции Asterisk и сам присылает звонки серверу.

Зачем он нужен
--------------
Забор «изнутри» (когда сервер распознавания сам читает журнал АТС и её
каталог записей) работает ровно в одном случае: файлы станции видны
серверу — общий диск, смонтированный каталог, одна машина. В жизни станция
чаще стоит отдельно: за NAT, в другом городе, под чужим присмотром. Тогда
события из AMI ещё как-то доходят, а записей не достать никак, и журнал
CDR тоже лежит там, где сервера нет.

Агент решает это с другой стороны. Он ставится на саму станцию, читает её
журнал звонков и её же каталог записей и сам отправляет разговор вместе с
файлом на сервер. Наружу станции при этом не нужно открывать ни одного
порта — достаточно исходящего соединения к серверу ASR Hub.

Чем отличается от забора «изнутри»
----------------------------------
* Ничего не надо монтировать и никуда не пускать сервер: связь всегда
  начинает агент.
* Звонок и его запись приезжают вместе, одним запросом, — сервер не ищет
  файл по имени и не гадает, дописан ли он.
* Сервер знает про агента отдельно от «своих» станций: его звонки лежат в
  архиве под станцией ``agent:<идентификатор>``, и перепутать их со
  станцией, которую сервер читает сам, нельзя.
* Задания («собрать весь архив», «собрать за период») ставятся на сервере
  и забираются агентом при очередном обращении: достучаться до станции
  снаружи сервер всё равно не может.

Как устроен обмен
-----------------
1. ``POST {url}/api/telephony/agent/hello`` — «я такой-то, вот станция,
   версия и моё состояние». В ответ: идентификатор агента, предел размера
   записи, нужен ли звук вообще, задание, признак «включён», а также
   ``min_duration_s`` и ``skip_unanswered`` — правила отсева, заданные на
   сервере, чтобы не гонять по сети то, что там всё равно не примут.
2. ``POST {url}/api/telephony/agent/ask`` — список идентификаторов
   звонков. Сервер отвечает, какие из них ему ещё нужны. Без этого шага
   повторный сбор архива тащил бы по сети всё заново: на сорока тысячах
   разговоров это десятки гигабайт впустую.
3. ``POST {url}/api/telephony/agent/call`` — звонок и его запись одним
   многочастным запросом (поле ``meta`` — JSON со сведениями о звонке,
   поле ``file`` — сама запись, необязательное).
4. ``GET {url}/api/telephony/agent/command?agent_id=…`` — задание, если
   его поставили из раздела «АТС». Задание выдаётся один раз и тут же
   снимается, поэтому выполняется сразу по получении.

Ключ доступа передаётся заголовком ``X-API-Key`` — ровно так же, как его
принимает от любого клиента ``server/asrhub/api/deps.py``. Ключ никогда не
попадает в журнал: всюду, где он мог бы там оказаться, стоит маска вида
``ah_1234…``.

Как ставится
------------
Одной строкой — установщиком, который отдаёт сам сервер::

    curl -fsSL 'http://сервер:8081/api/telephony/agent/install.sh' \\
        -H 'X-API-Key: ah_…' | sudo bash -s -- \\
        --url http://сервер:8081 --key ah_… --name pbx-msk

Установщик кладёт этот файл в ``/opt/asrhub-agent``, пишет настройки в
``/etc/asrhub-agent.conf`` (права 600) и заводит службу systemd
``asrhub-agent.service``, которая запускает агента с ``--follow``.

Чем он ограничен намеренно
--------------------------
Только стандартная библиотека Python и совместимость с Python 3.6: на
станциях до сих пор живёт CentOS 7, где системный Python — 3.6, а ставить
туда pip-пакеты ради агента никто не даст. Поэтому здесь нет ни
``requests``, ни драйвера MySQL: запрос к базе выполняется через обычную
программу ``mysql``, а HTTP — через ``urllib``.
"""

