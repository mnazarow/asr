class Агент:
    """Связывает всё вместе: источник, каталог записей, состояние и сервер."""

    def __init__(self, параметры):
        self.параметры = dict(параметры)
        self.каталог_состояния = str(параметры.get("state_dir")
                                     or КАТАЛОГ_СОСТОЯНИЯ)
        self.состояние = Состояние(
            os.path.join(self.каталог_состояния, "state.json"))
        self.замок = Замок(os.path.join(self.каталог_состояния, "agent.lock"))
        self.клиент = None
        self.источник = None
        self.записи = None
        self.agent_id = ""
        self.правила = {
            "max_file_mb": целое(параметры.get("max_file_mb"), 0) or 2048,
            "want_audio": True,
            "min_duration_s": целое(параметры.get("min_duration_s"), 0),
            "skip_unanswered": логическое(параметры.get("skip_unanswered"), True),
            "enabled": True,
        }
        self._правила_с_сервера = set()
        self._остановлен = False
        self._последний_hello = 0.0
        self._последняя_команда = 0.0
        self._отложенное_задание = ""
        self.ошибок = 0

    # --- подготовка --------------------------------------------------------

    def подготовиться(self, брать_замок=True):
        каталог = self.каталог_состояния
        try:
            if not os.path.isdir(каталог):
                os.makedirs(каталог, 0o700)
        except OSError as сбой:
            raise ОшибкаНастройки(
                f"Каталог состояния {каталог} не создаётся: {сбой}",
                подсказка="Запустите агента от root или задайте --state-dir "
                          "туда, где есть права на запись.") from сбой
        if брать_замок:
            self.замок.взять()
        self.состояние.прочитать()
        self.agent_id = str(self.состояние.данные.get("agent_id") or "")
        свободно = свободно_байт(каталог)
        if свободно and свободно < МИНИМУМ_МЕСТА:
            log.warning("На разделе с %s свободно всего %s. Состояние пишется "
                        "через временный файл, и на переполненном диске запись "
                        "не удастся — следующий заход начнёт сбор заново.",
                        каталог, размер_словами(свободно))
        self.клиент = Клиент(
            self.параметры.get("url"), self.параметры.get("key"),
            таймаут=дробное(self.параметры.get("timeout"), 30.0),
            таймаут_файла=дробное(self.параметры.get("upload_timeout"), 120.0),
            повторов=целое(self.параметры.get("retries"), 5),
            небезопасно=логическое(self.параметры.get("insecure"), False))
        self.источник = выбрать_источник(self.параметры, self.состояние)
        self.записи = Записи(
            self.параметры.get("recordings_dir") or ЗАПИСИ_ПО_УМОЛЧАНИЮ,
            шаблон=self.параметры.get("filename") or "",
            окно_минут=целое(self.параметры.get("match_window"), 120))
        return self

    def закрыть(self):
        self.состояние.сохранить(принудительно=True)
        self.замок.отпустить()

    def остановить(self, номер=0, _кадр=None):
        """Обработчик SIGTERM/SIGINT. Только флаг — работа кончится сама.

        Дописывать состояние прямо в обработчике нельзя: сигнал приходит
        посреди чего угодно, в том числе посреди записи того же файла.
        """
        self._остановлен = True
        log.info("Получен сигнал %s — заканчиваю текущий звонок и сохраняю "
                 "состояние.", номер)

    def _проверить_остановку(self):
        if self._остановлен:
            raise Остановлен()

    # --- приветствие -------------------------------------------------------

    def сведения_о_себе(self):
        return {
            "agent_id": self.agent_id,
            "name": self.параметры.get("name") or socket.gethostname(),
            "host": socket.gethostname(),
            "os": платформа(),
            "asterisk": версия_asterisk(),
            "version": ВЕРСИЯ,
            "source": getattr(self.источник, "имя", "") or "",
            "state": self.состояние.свод(),
        }

    def поздороваться(self, обязательно=True):
        """Представиться серверу и забрать правила приёма и задание."""
        ответ = self.клиент.hello(self.сведения_о_себе())
        agent_id = str(ответ.get("agent_id") or "")
        if agent_id and agent_id != self.agent_id:
            if self.agent_id:
                log.warning("Сервер выдал новый идентификатор агента: %s "
                            "(был %s). Прежние звонки останутся в архиве под "
                            "старой станцией.", agent_id, self.agent_id)
            self.agent_id = agent_id
            self.состояние.данные["agent_id"] = agent_id
            self.состояние.сохранить(принудительно=True)
        if not self.agent_id and обязательно:
            raise ОтказСервера(
                200, "no_agent_id",
                "Сервер не вернул идентификатор агента.",
                подсказка="Обновите сервер: этот адрес появился в ASR Hub 3.0.")
        # Правила приёма задаёт сервер — но только те, которых не задал
        # человек ключами. Иначе --min-duration на станции молча терял бы
        # силу после каждого приветствия.
        for имя, преобразование in (("max_file_mb", целое),
                                    ("min_duration_s", целое),
                                    ("skip_unanswered", логическое),
                                    ("want_audio", логическое),
                                    ("enabled", логическое)):
            if имя in ответ and self.параметры.get(имя) in (None, ""):
                self.правила[имя] = преобразование(ответ.get(имя))
                self._правила_с_сервера.add(имя)
        self.проверить_часы(дробное(ответ.get("server_time"), 0.0))
        if not self.правила.get("enabled", True):
            log.warning("Агент выключен на сервере: звонки приниматься не "
                        "будут. Включите его в разделе «АТС» веб-интерфейса.")
        станция = str(ответ.get("station") or "")
        log.info("Сервер: %s, станция %s, предел записи %d МБ, отсев: короче "
                 "%d с, без ответа %s", self.клиент.адрес, станция,
                 целое(self.правила.get("max_file_mb"), 0),
                 целое(self.правила.get("min_duration_s"), 0),
                 "пропускать" if self.правила.get("skip_unanswered") else "брать")
        self._последний_hello = time.time()
        return ответ

    def проверить_часы(self, время_сервера):
        if not время_сервера:
            return 0.0
        расхождение = time.time() - время_сервера
        if abs(расхождение) > ПРЕДЕЛ_РАСХОЖДЕНИЯ:
            log.warning("Часы станции расходятся с сервером на %d с. Время "
                        "звонка в архиве будет неверным, а отчёты за день — "
                        "съезжать на границе суток. Поправьте службу времени: "
                        "timedatectl set-ntp true (или systemctl enable --now "
                        "chronyd / ntpd).", int(расхождение))
        return расхождение

    # --- проход ------------------------------------------------------------

    def проход(self, режим="new", начало=None, конец=None):
        """Один заход по журналу. Возвращает свод: что отправлено и что нет.

        Ни одна ошибка на отдельном звонке не имеет права прервать заход:
        на станции с архивом за три года всегда найдётся файл с правами
        000, битый WAV или строка журнала из другой сборки, и остановка на
        первом же таком означала бы, что архив не соберётся никогда.
        """
        весь_архив = режим == "all"
        свод = {"прочитано": 0, "отправлено": 0, "с записью": 0,
                "пропущено": 0, "ошибок": 0, "байт": 0, "причины": {}}
        if not self.правила.get("enabled", True):
            log.warning("Заход не делаю: агент выключен на сервере.")
            return свод
        порция = []
        источник = self._поток(режим, начало, конец)
        try:
            for звонок in источник:
                self._проверить_остановку()
                свод["прочитано"] += 1
                причина = причина_пропуска(
                    звонок, начало=начало, конец=конец,
                    минимум=целое(self.правила.get("min_duration_s"), 0),
                    пропускать_без_ответа=логическое(
                        self.правила.get("skip_unanswered"), True))
                if not причина and not весь_архив \
                        and self.состояние.отправлен(звонок.uniqueid):
                    причина = "уже отправлен"
                if причина:
                    свод["пропущено"] += 1
                    свод["причины"][причина] = свод["причины"].get(причина, 0) + 1
                    continue
                порция.append(звонок)
                if len(порция) >= ПОРЦИЯ:
                    self._обработать_порцию(порция, свод)
                    порция = []
                    self.состояние.сохранить()
                    self._задание_во_время_сбора(режим in ("all", "period"))
            if порция:
                self._обработать_порцию(порция, свод)
        except СборПрерван:
            log.info("Сбор остановлен сервером: обработано %d звонков.",
                     свод["прочитано"])
            self._отложить_остаток(порция, "сбор остановлен")
        except Остановлен:
            log.info("Заход прерван сигналом: обработано %d звонков.",
                     свод["прочитано"])
            self._отложить_остаток(порция, "агент остановлен")
            raise
        except (ОшибкаСвязи, ОтказСервера):
            self._отложить_остаток(порция, "связь с сервером прервалась")
            raise
        finally:
            self.состояние.посчитать(
                отправлено=свод["отправлено"], пропущено=свод["пропущено"],
                ошибок=свод["ошибок"], байт=свод["байт"])
            self.состояние.сохранить(принудительно=True)
        return свод

    def _отложить_остаток(self, порция, причина):
        """Звонки прерванной порции — в отложенные, а не в никуда.

        Позиция чтения журнала к этому мигу уже сдвинута: строки прочитаны.
        Если оборвать заход и ничего не запомнить, эти звонки не придут
        больше никогда — ни из журнала, ни откуда-либо ещё.
        """
        отложено = 0
        for звонок in порция or ():
            if self.состояние.отправлен(звонок.uniqueid):
                continue
            self.состояние.отложить(звонок, причина)
            отложено += 1
        if отложено:
            log.info("Отложено до следующего захода: %d звонк(ов) (%s).",
                     отложено, причина)
        self.состояние.сохранить(принудительно=True)

    def _поток(self, режим, начало, конец):
        """Звонки из источника плюс отложенные с прошлого захода."""
        for звонок in self.состояние.отложенные():
            yield звонок
        # Сбор за период читает источник с начала, но позицию не двигает:
        # иначе «собрать за прошлый месяц» на станции, где обычный заход уже
        # дочитал журнал до конца, не нашёл бы ни одного звонка — а после
        # сдвига позиции ещё и потерял бы свежие.
        параметры = {"весь_архив": режим in ("all", "period"),
                     "двигать_позицию": режим in ("new", "all"),
                     "начало": начало, "конец": конец}
        for звонок in self.источник.звонки(**параметры):
            yield звонок

    def _обработать_порцию(self, порция, свод):
        нужны = None
        if self.agent_id:
            try:
                список, известно = self.клиент.спросить(
                    self.agent_id, [з.uniqueid for з in порция])
                нужны = set(список)
                if известно:
                    свод["пропущено"] += известно
                    свод["причины"]["уже в архиве"] = \
                        свод["причины"].get("уже в архиве", 0) + известно
                    for звонок in порция:
                        if звонок.uniqueid not in нужны:
                            # Сервер уже знает этот звонок — помечаем как
                            # отправленный, чтобы не спрашивать о нём снова
                            # на каждом заходе до скончания века.
                            self.состояние.отметить(звонок.uniqueid)
                            self.состояние.снять_с_ожидания(звонок.uniqueid)
            except ОтказСервера as сбой:
                # Отказ на вопросе не повод бросать заход: хуже то, что мы
                # зальём уже известное, а не то, что не зальём ничего.
                log.warning("Вопрос о звонках не удался (%s) — отправляю всё "
                            "подряд, сервер отсеет сам.", сбой)
        for звонок in порция:
            self._проверить_остановку()
            if нужны is not None and звонок.uniqueid not in нужны:
                continue
            try:
                self._отправить(звонок, свод)
            except (ОшибкаСвязи, Остановлен):
                raise
            except ОтказСервера as сбой:
                свод["ошибок"] += 1
                self.ошибок += 1
                log.error("Звонок %s не принят: %s", звонок.uniqueid, сбой)
                if сбой.статус in (401, 403):
                    # Ключ отозван или агент выключен: следующие девятьсот
                    # звонков получат тот же отказ. Останавливаемся и
                    # говорим об этом один раз, а не девятьсот.
                    raise
                if self.клиент._стоит_повторить(сбой.статус):
                    # Временный отказ (очередь сервера полна — 429, сервер
                    # перезапускается за прокси — 502/503), и повторы клиента
                    # уже исчерпаны. Считать такой звонок «ошибкой» и идти
                    # дальше значило потерять его навсегда: позиция журнала
                    # уже сдвинута, а в отложенные он не попадал. Прерываем
                    # заход — остаток порции вместе с этим звонком уходит в
                    # отложенные и приедет следующим заходом.
                    raise
            except Exception as сбой:                        # noqa: BLE001
                свод["ошибок"] += 1
                self.ошибок += 1
                log.exception("Звонок %s не обработан: %s", звонок.uniqueid, сбой)

    def _отправить(self, звонок, свод):
        дополнить(звонок,
                  внутренние_знаков=self.параметры.get("internal_digits") or 5,
                  контексты=self.параметры.get("contexts"))
        путь, пропущено = self._запись_для(звонок)
        if пропущено == "ещё пишется":
            self.состояние.отложить(звонок, пропущено)
            свод["пропущено"] += 1
            свод["причины"][пропущено] = свод["причины"].get(пропущено, 0) + 1
            return
        поля = звонок.поля_для_сервера(self.agent_id, пропущено)
        размер = 0
        if путь:
            try:
                размер = os.path.getsize(путь)
            except OSError:
                путь, размер = None, 0
        if логическое(self.параметры.get("dry_run"), False):
            log.info("(--dry-run) %s %s→%s, %s c, запись: %s", звонок.uniqueid,
                     звонок.src, звонок.dst, звонок.billsec,
                     (путь + f" ({размер_словами(размер)})") if путь
                     else (пропущено or "нет"))
            свод["отправлено"] += 1
            return
        try:
            ответ = self.клиент.отправить(поля, путь)
        except ОтказСервера as сбой:
            if not путь or сбой.статус not in ОТКАЗЫ_ЗАПИСИ:
                raise
            # Сервер не принял именно ЗАПИСЬ — больше предела (413, в том
            # числе от nginx с его client_max_body_size) или не того вида
            # (415). Повтор с тем же файлом получит тот же отказ, а сам
            # звонок раньше просто пропадал из журнала. Шлём его без записи
            # и с причиной: в журнале и разрезах он будет, распознавать нечего.
            причина = ("сервер не принял запись: "
                       + (сбой.сообщение or f"HTTP {сбой.статус}"))[:200]
            log.warning("Звонок %s: %s — отправляю без записи.", звонок.uniqueid,
                        причина)
            поля = звонок.поля_для_сервера(self.agent_id, причина)
            ответ = self.клиент.отправить(поля, None)
            путь, размер = None, 0
        self.состояние.отметить(звонок.uniqueid)
        self.состояние.снять_с_ожидания(звонок.uniqueid)
        свод["отправлено"] += 1
        if путь:
            свод["с записью"] += 1
            свод["байт"] += размер
            self.состояние.посчитать(**{"с записью": 1})
        отметка = str(ответ.get("skipped") or "")
        log.info("Звонок %s (%s→%s, %s c) отправлен%s%s", звонок.uniqueid,
                 звонок.src, звонок.dst, звонок.billsec,
                 f", запись {размер_словами(размер)}" if путь else " без записи",
                 f", сервер: {отметка}" if отметка else "")

    def _запись_для(self, звонок):
        """Путь к записи и причина, по которой её не будет.

        Звонок без записи всё равно едет на сервер: он нужен в журнале, в
        счётчиках и в разрезах — распознавать просто нечего. Молча
        выбрасывать такие звонки значило бы показывать в отчётах меньше
        разговоров, чем было на самом деле.
        """
        if not логическое(self.правила.get("want_audio"), True):
            return None, "сервер не просит записей"
        путь = звонок.recording if звонок.recording else None
        if not путь:
            try:
                путь = self.записи.найти(звонок)
            except OSError as сбой:
                log.warning("Поиск записи для %s не удался: %s",
                            звонок.uniqueid, сбой)
                путь = None
        if not путь:
            return None, "нет записи"
        if not os.access(путь, os.R_OK):
            log.warning("Запись %s найдена, но не читается. Добавьте "
                        "пользователя агента в группу asterisk.", путь)
            return None, "запись не читается"
        if self.записи.дописывается(путь):
            return None, "ещё пишется"
        предел = целое(self.правила.get("max_file_mb"), 0) * 1024 * 1024
        try:
            размер = os.path.getsize(путь)
        except OSError as сбой:
            log.warning("Размер записи %s не читается: %s", путь, сбой)
            return None, "запись не читается"
        if предел and размер > предел:
            log.warning("Запись %s (%s) больше предела сервера в %d МБ — "
                        "звонок отправлю без неё. Поднимите «Предел размера "
                        "загрузки» на сервере или сжимайте записи на станции.",
                        путь, размер_словами(размер),
                        целое(self.правила.get("max_file_mb"), 0))
            return None, f"запись больше предела ({размер_словами(размер)})"
        if os.path.splitext(путь)[1].lower() not in РАСШИРЕНИЯ:
            return None, "сервер не принимает такой формат записи"
        return путь, ""

    # --- задания от сервера ------------------------------------------------

    def _задание_во_время_сбора(self, долгий_заход):
        """Спрашиваем задание прямо посреди долгого сбора.

        Сбор архива идёт часами, и «остановить» из раздела «АТС» обязано
        сработать сейчас, а не через три часа — иначе кнопка бесполезна.
        """
        if not долгий_заход or not self.agent_id:
            return
        if (time.time() - self._последняя_команда) < ПЕРИОД_КОМАНДЫ:
            return
        self._последняя_команда = time.time()
        try:
            команда = self.клиент.команда(self.agent_id)
        except (ОшибкаСвязи, ОтказСервера) as сбой:
            log.debug("Задание во время сбора не спросилось: %s", сбой)
            return
        if not команда:
            return
        if команда == "collect:stop":
            log.info("Сервер велел остановить сбор — прекращаю текущий заход.")
            raise СборПрерван()
        self._отложенное_задание = команда
        log.info("Во время сбора пришло задание «%s» — выполню следом.", команда)

    def выполнить_задание(self, команда):
        """Задание из раздела «АТС». Выполняется сразу по получении."""
        команда = str(команда or "").strip()
        if not команда:
            return None
        log.info("Задание с сервера: %s", команда)
        if команда == "collect:stop":
            log.info("Сбор останавливать нечего: сейчас ничего не идёт.")
            return None
        if команда == "collect:all":
            return self.проход("all")
        if команда == "collect:new":
            return self.проход("new")
        if команда.startswith("collect:period:"):
            части = команда.split(":")
            if len(части) >= 4:
                начало = дробное(части[2], 0.0)
                конец = дробное(части[3], 0.0)
                if начало and конец and конец > начало:
                    log.info("Собираю период %s — %s", время_словами(начало),
                             время_словами(конец))
                    return self.проход("period", начало, конец)
            log.error("Задание «%s» не разобрано: ожидается "
                      "collect:period:<начало>:<конец> в секундах эпохи.",
                      команда)
            return None
        log.warning("Задание «%s» этому агенту неизвестно. Возможно, сервер "
                    "новее агента — обновите агента установщиком.", команда)
        return None

    # --- режимы ------------------------------------------------------------

    def один_заход(self, режим="new", начало=None, конец=None):
        ответ = self.поздороваться()
        задание = str(ответ.get("command") or "")
        свод = self.проход(режим, начало, конец)
        напечатать_свод(свод, режим)
        if задание and задание != "collect:stop":
            дополнительный = self.выполнить_задание(задание)
            if дополнительный:
                напечатать_свод(дополнительный, "задание")
        return свод

    def следить(self, пауза=60.0):
        """Бесконечный цикл: новые звонки, задания сервера, сон.

        Пауза считается от конца прохода, а не от начала: на станции, где
        заход идёт дольше паузы, «раз в минуту» превратилось бы в
        непрерывную работу и съело бы канал.
        """
        запрошено = дробное(пауза, 60.0)
        пауза = max(5.0, запрошено)
        if запрошено < пауза:
            log.warning("Пауза между заходами поднята с %g до %g с: чаще "
                        "смысла нет, а журнал АТС столько не успевает "
                        "накопить.", запрошено, пауза)
        log.info("Слежение включено: заход каждые %d с. Остановка — "
                 "systemctl stop asrhub-agent или Ctrl+C.", int(пауза))
        подряд_сбоев = 0
        while not self._остановлен:
            try:
                if (time.time() - self._последний_hello) >= ПЕРИОД_HELLO \
                        or not self.agent_id:
                    ответ = self.поздороваться()
                    задание = str(ответ.get("command") or "")
                else:
                    задание = self._спросить_задание()
                if задание:
                    свод = self.выполнить_задание(задание)
                    if свод:
                        напечатать_свод(свод, задание)
                    while self._отложенное_задание:
                        следующее, self._отложенное_задание = \
                            self._отложенное_задание, ""
                        свод = self.выполнить_задание(следующее)
                        if свод:
                            напечатать_свод(свод, следующее)
                else:
                    свод = self.проход("new")
                    if свод["отправлено"] or свод["ошибок"]:
                        напечатать_свод(свод, "заход")
                подряд_сбоев = 0
            except Остановлен:
                break
            except (ОшибкаСвязи, ОтказСервера) as сбой:
                подряд_сбоев += 1
                self.ошибок += 1
                log.error("Заход не удался (%d подряд): %s", подряд_сбоев, сбой)
                if isinstance(сбой, ОтказСервера) and сбой.статус in (401, 403):
                    log.error("Пока ключ не исправят, работать не с чем. "
                              "Проверяю раз в %d с.", int(max(пауза, 60)))
            except ОшибкаНастройки as сбой:
                подряд_сбоев += 1
                self.ошибок += 1
                log.error("Настройка мешает заходу: %s", сбой)
            except Exception as сбой:                        # noqa: BLE001
                подряд_сбоев += 1
                self.ошибок += 1
                log.exception("Непредвиденная ошибка в заходе: %s", сбой)
            # Растущая пауза после сбоев: станция за NAT не должна долбить
            # недоступный сервер раз в минуту сутки напролёт.
            сон = пауза * min(подряд_сбоев + 1, 5) if подряд_сбоев else пауза
            self._поспать(сон)
        self.состояние.сохранить(принудительно=True)
        log.info("Слежение остановлено.")
        return КОД_ОШИБКИ if self.ошибок else КОД_УСПЕХ

    def _спросить_задание(self):
        """Задание с сервера, с одной особой обработкой отказа.

        Если агента убрали в разделе «АТС», сервер отвечает на /command
        четырёхсоткой «агент неизвестен» — и так будет до следующего
        приветствия. Без этой ветки станция молчала бы до конца периода
        приветствий, а человек, только что заведший агента заново, видел бы
        в разделе пустоту и решил, что агент умер.
        """
        try:
            return self.клиент.команда(self.agent_id)
        except ОтказСервера as сбой:
            if 400 <= сбой.статус < 500 and сбой.статус not in (401, 403, 429):
                log.warning("Сервер не узнал агента (%s) — представляюсь заново.",
                            сбой.сообщение)
                self._последний_hello = 0.0
                return ""
            raise

    def _поспать(self, секунд):
        """Сон, который просыпается от сигнала: спим по секунде."""
        край = time.time() + max(0.0, секунд)
        while not self._остановлен and time.time() < край:
            time.sleep(min(1.0, край - time.time()))


def напечатать_свод(свод, режим=""):
    причины = ", ".join(f"{имя}: {число}" for имя, число
                        in sorted((свод.get("причины") or {}).items()))
    log.info("Итог (%s): прочитано %d, отправлено %d (с записью %d, %s), "
             "пропущено %d%s, ошибок %d", режим or "заход",
             свод.get("прочитано", 0), свод.get("отправлено", 0),
             свод.get("с записью", 0), размер_словами(свод.get("байт", 0)),
             свод.get("пропущено", 0), f" ({причины})" if причины else "",
             свод.get("ошибок", 0))


def платформа():
    """Строка об операционной системе станции — для раздела «АТС»."""
    try:
        части = [platform.system(), platform.release()]
        распознанное = ""
        try:
            with open("/etc/os-release", encoding="utf-8") as файл:
                for строка in файл:
                    if строка.startswith("PRETTY_NAME="):
                        распознанное = строка.split("=", 1)[1].strip().strip('"')
                        break
        except OSError:
            pass
        if распознанное:
            части.append(распознанное)
        return " ".join(ч for ч in части if ч)[:120]
    except Exception:                                        # noqa: BLE001
        return sys.platform


def версия_asterisk():
    """Версия АТС — из самой АТС. Нет её — не беда, поле необязательное."""
    try:
        процесс = subprocess.Popen(
            ["asterisk", "-V"], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            universal_newlines=True)
        вывод, _ = процесс.communicate(timeout=10)
        return (вывод or "").strip()[:120]
    except (OSError, subprocess.SubprocessError):
        return ""


