def подставить(шаблон, звонок):
    """Подставляет поля звонка в шаблон имени файла.

    Понимает оба написания — свойское ``{uniqueid}`` и привычное по
    ``extensions.conf`` ``${UNIQUEID}``, а даты ещё и по-русски
    (``{год}``, ``{месяц}``, ``{день}``): именно так параметр описан в
    задании, и человек, который правит ``/etc/asrhub-agent.conf``, напишет
    то, что прочитал. И короткими именами ``${YYYY}``, ``${MM}``, ``${DD}``,
    ``${HH}`` — так их показывала форма станции на сервере.
    """
    замены = {
        "uniqueid": звонок.uniqueid, "src": звонок.src, "dst": звонок.dst,
        "clid": звонок.clid, "channel": звонок.channel,
        "userfield": звонок.userfield, "accountcode": звонок.accountcode,
        "direction": звонок.direction, "queue": звонок.queue,
        "agent": звонок.agent,
    }
    русские = {}
    if звонок.started_at:
        момент = datetime.fromtimestamp(звонок.started_at)
        замены.update({
            "date": момент.strftime("%Y-%m-%d"),
            "time": момент.strftime("%H%M%S"),
            "year": момент.strftime("%Y"), "month": момент.strftime("%m"),
            "day": момент.strftime("%d"), "hour": момент.strftime("%H"),
            "minute": момент.strftime("%M"),
            "yyyy": момент.strftime("%Y"), "mm": момент.strftime("%m"),
            "dd": момент.strftime("%d"), "hh": момент.strftime("%H"),
        })
        русские = {
            "год": момент.strftime("%Y"), "месяц": момент.strftime("%m"),
            "день": момент.strftime("%d"), "час": момент.strftime("%H"),
            "дата": момент.strftime("%Y-%m-%d"),
        }
    итог = шаблон
    for ключ, значение in замены.items():
        чистое = безопасное(значение)
        итог = итог.replace("{" + ключ + "}", чистое)
        итог = итог.replace("${" + ключ.upper() + "}", чистое)
    for ключ, значение in русские.items():
        итог = итог.replace("{" + ключ + "}", значение)
        итог = итог.replace("${" + ключ.upper() + "}", значение)
    return итог


def id_в_имени(uniqueid, имя):
    """Стоит ли идентификатор звонка в имени файла ОТДЕЛЬНО, а не частью другого.

    Подстрока без границ путала соседние звонки: «1757500001.1» находится
    внутри «1757500001.12.wav», и звонку №1 доставалась запись звонка №12.
    """
    if not uniqueid:
        return False
    return re.search(r"(?<!\d)" + re.escape(uniqueid) + r"(?!\d)", имя) is not None


def номер_в_имени(номер, имя):
    """Встречается ли номер в имени файла ОТДЕЛЬНЫМ числом.

    Подстрока без границ подбирает чужую запись: в имени
    ``out-79161234567-79995554433-20260910-101020.wav`` найдутся и «101», и
    «102» — оба внутри времени «101020». Звонок 101 → 102, у которого своей
    записи нет, уехал бы на сервер с чужим внешним разговором.
    """
    if not номер:
        return False
    return re.search(r"(?<!\d)" + re.escape(номер) + r"(?!\d)", имя) is not None


class Записи:
    """Каталог записей станции: указатель по идентификаторам и поиск файла.

    Указатель строится один раз на заход, а не на каждый звонок. Обход
    ``/var/spool/asterisk/monitor`` на станции с архивом за три года — это
    сотни тысяч файлов; делать его для каждой строки журнала значит
    потратить час на то, что делается за секунду.
    """

    def __init__(self, каталог, шаблон="", окно_минут=120, срок_указателя=300.0):
        self.каталог = str(каталог or "")
        self.шаблон = str(шаблон or "")
        self.окно = float(окно_минут or 0) * 60.0
        self.срок_указателя = float(срок_указателя)
        self._по_id = {}
        self._файлы = []
        self._собран = 0.0
        self._пересобран = 0.0

    @property
    def доступен(self):
        return bool(self.каталог) and os.path.isdir(self.каталог)

    def сбросить(self):
        self._собран = 0.0

    def указатель(self):
        if self._по_id and (time.time() - self._собран) < self.срок_указателя:
            return self._по_id
        self._по_id = {}
        self._файлы = []
        if not self.доступен:
            self._собран = time.time()
            return self._по_id
        начало = time.time()
        for корень, _, файлы in os.walk(self.каталог):
            for имя in файлы:
                if os.path.splitext(имя)[1].lower() not in РАСШИРЕНИЯ:
                    continue
                путь = os.path.join(корень, имя)
                try:
                    изменён = os.path.getmtime(путь)
                except OSError:
                    continue
                self._файлы.append((изменён, имя, путь))
                for токен in ID_В_ИМЕНИ.findall(имя):
                    self._по_id.setdefault(токен, путь)
        self._собран = time.time()
        log.debug("Каталог записей: %d файл(ов), указатель собран за %.1f с",
                  len(self._файлы), time.time() - начало)
        return self._по_id

    def сколько_файлов(self):
        """Сколько записей в каталоге. Для самопроверки."""
        self.указатель()
        return len(self._файлы)

    def найти(self, звонок):
        """Файл записи или ``None``. Порядок — от точного к приблизительному."""
        if not self.доступен:
            return None
        найденный = self._искать(звонок)
        if найденный is None and self._стоит_пересобрать(звонок):
            # Указатель собран раньше, чем MixMonitor закрыл этот файл.
            # Без пересборки звонок уехал бы с пометкой «нет записи» и
            # больше бы её не получил: он уже помечен отправленным.
            log.debug("Запись для %s не нашлась — пересобираю указатель",
                      звонок.uniqueid)
            self._пересобран = time.time()
            self.сбросить()
            найденный = self._искать(звонок)
        return найденный

    def _искать(self, звонок):
        if self.шаблон:
            найденный = self._по_шаблону(звонок)
            if найденный:
                return найденный
        if звонок.uniqueid:
            найденный = self._по_идентификатору(звонок)
            if найденный:
                return найденный
        return self._по_номерам(звонок)

    def _стоит_пересобрать(self, звонок):
        """Может ли запись появиться после того, как указатель собрали.

        Пересобирать на каждом промахе нельзя: при сборе архива промахов
        тысячи, а обход каталога с сотней тысяч файлов стоит секунд. Зато
        у свежего звонка запись действительно могла лечь только что —
        такой промах и стоит перепроверить, но не чаще раза в полминуты.
        """
        if not self._собран:
            return False
        if (time.time() - self._пересобран) < 30.0:
            return False
        return (звонок.started_at or 0) >= self._собран - 3600

    def _по_шаблону(self, звонок):
        имя = подставить(self.шаблон, звонок)
        if not имя:
            return None
        if any(знак in имя for знак in "*?["):
            return self._по_маске(имя, звонок)
        кандидаты = [os.path.join(self.каталог, имя)]
        if not os.path.splitext(имя)[1]:
            кандидаты += [os.path.join(self.каталог, имя + с)
                          for с in РАСШИРЕНИЯ]
        for кандидат in кандидаты:
            найденный = внутри(self.каталог, кандидат)
            if найденный:
                return найденный
        return None

    def _по_маске(self, маска, звонок):
        """Шаблон со звёздочкой — ближайший по времени к началу разговора файл.

        Пример «out-${DST}-${SRC}-${YEAR}${MONTH}${DAY}-*.wav» раньше
        искался буквально, со звёздочкой в имени, и не находил ничего.
        """
        import glob as маски  # noqa: PLC0415

        начало = звонок.started_at or 0
        лучшее = None
        for кандидат in sorted(маски.glob(os.path.join(self.каталог, маска)))[:1000]:
            if os.path.splitext(кандидат)[1] and \
                    os.path.splitext(кандидат)[1].lower() not in РАСШИРЕНИЯ:
                continue
            найденный = внутри(self.каталог, кандидат)
            if not найденный:
                continue
            try:
                изменён = os.path.getmtime(найденный)
            except OSError:
                continue
            близость = abs(изменён - (начало or изменён))
            if начало and self.окно and близость > self.окно:
                continue
            if лучшее is None or близость < лучшее[0]:
                лучшее = (близость, найденный)
        return лучшее[1] if лучшее else None

    def _по_идентификатору(self, звонок):
        указатель = self.указатель()
        путь = указатель.get(звонок.uniqueid)
        if путь is None:
            # Идентификатор бывает с приставкой имени системы
            # («pbx-1757500001.1»), а в имя файла MixMonitor кладёт только
            # числовую часть. Ищем её отдельно.
            совпадение = ID_В_ИМЕНИ.search(звонок.uniqueid)
            if совпадение:
                путь = указатель.get(совпадение.group(0))
        if путь is None:
            for _, имя, кандидат in self._файлы:
                if id_в_имени(звонок.uniqueid, имя):
                    путь = кандидат
                    break
        return внутри(self.каталог, путь) if путь else None

    def _по_номерам(self, звонок):
        if not (звонок.src and звонок.dst):
            return None
        self.указатель()
        начало = звонок.started_at or 0
        лучшее = None
        for изменён, имя, путь in self._файлы:
            if not (номер_в_имени(звонок.src, имя)
                    and номер_в_имени(звонок.dst, имя)):
                continue
            близость = abs(изменён - (начало or изменён))
            if начало and self.окно and близость > self.окно:
                continue
            if лучшее is None or близость < лучшее[0]:
                лучшее = (близость, путь)
        return внутри(self.каталог, лучшее[1]) if лучшее else None

    def дописывается(self, путь):
        """Растёт ли файл прямо сейчас.

        MixMonitor закрывает файл уже после разговора, и запись, взятая
        через секунду после строки в журнале, приезжает обрезанной — а
        распознавание такой обрезок честно расшифрует и положит в архив
        вместо разговора.
        """
        try:
            первый = os.path.getsize(путь)
            time.sleep(ПАУЗА_ЗАМЕРА)
            второй = os.path.getsize(путь)
        except OSError:
            return False
        return первый != второй or второй == 0


