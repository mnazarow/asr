def test_один_чужой_байт_не_переводит_выгрузку_в_cp1251():
    """Тире 0x96 из cp1251 в UTF-8 выгрузке превращало весь штат в кракозябры."""
    строки = ["Фамилия;Имя;Внутренний номер",
              "Иванов;Пётр;101", "Сидорова;Анна;102", "Кузнецов;Олег;103"]
    данные = "\n".join(строки).encode("utf-8").replace(b"103", b"103 \x96 old", 1)
    разбор = employees.разобрать_подробно(данные, тип="csv")
    фамилии = [з["last_name"] for з in разбор.записи]
    assert фамилии == ["Иванов", "Сидорова", "Кузнецов"], фамилии
    assert any("utf-8 (с потерями: 1" in з for з in разбор.замечания), разбор.замечания


def test_настоящий_cp1251_читается_как_прежде():
    данные = "Фамилия;Имя;Внутренний номер\nИванов;Пётр;101\n".encode("cp1251")
    разбор = employees.разобрать_подробно(данные, тип="csv")
    assert [з["last_name"] for з in разбор.записи] == ["Иванов"]
    assert any("кодировка cp1251" in з for з in разбор.замечания)


