def test_тёзка_без_номера_не_сливается_с_первым(сервер: TestClient):
    """Второй «Иванов Пётр» переписывал карточку первого — оставался один."""
    первый = сервер.post("/api/employees", json={"last_name": "Иванов", "first_name": "Пётр",
                                                  "department": "склад"})
    второй = сервер.post("/api/employees", json={"last_name": "Иванов", "first_name": "Пётр",
                                                  "department": "бухгалтерия"})
    assert первый.status_code == второй.status_code == 200
    assert первый.json()["id"] != второй.json()["id"]
    assert "уже есть" in второй.json()["warning"]
    отделы = sorted(к["department"] for к in
                    сервер.get("/api/employees?limit=50").json()["items"])
    assert отделы == ["бухгалтерия", "склад"]


def test_тот_же_номер_и_то_же_фио_правят_карточку(сервер: TestClient):
    первый = сервер.post("/api/employees", json={"last_name": "Петров", "first_name": "Иван",
                                                  "phone_ext": "201", "position": "стажёр"})
    повтор = сервер.post("/api/employees", json={"last_name": "Петров", "first_name": "Иван",
                                                  "phone_ext": "201", "position": "менеджер"})
    assert повтор.json()["id"] == первый.json()["id"]
    assert "warning" not in повтор.json()
    сосед = сервер.post("/api/employees", json={"last_name": "Смирнова", "first_name": "Ольга",
                                                 "phone_ext": "201"})
    assert сосед.json()["id"] != первый.json()["id"]
    assert "внутренним номером" in сосед.json()["warning"]


