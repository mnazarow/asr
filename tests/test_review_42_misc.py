def _помощник(**настройки) -> Помощник:
    return Помощник.из_настроек(настройки, agent="оператор")


def test_подсказка_сверх_трёх_приходит_следующей_репликой():
    """Показанными помечались все найденные, а отдавались первые три.

    Четвёртая — обычно «осталось по скрипту» — не приходила уже никогда.
    """
    набор = [*категории_модуль.ГОТОВЫЕ,
             {"id": "vip", "label": "Важный клиент", "kind": "topic",
              "who": "any", "rule": "договор", "notify": True},
             {"id": "urgent", "label": "Срочное", "kind": "topic",
              "who": "any", "rule": "срочно", "notify": True}]
    помощник = _помощник(content_categories=набор)
    первые = помощник.добавить("сами виноваты, договор нужен срочно",
                               speaker="оператор", start=0, end=40)
    assert len(первые) == 3 and "script" not in [п.kind for п in первые]
    следом = помощник.добавить("ну что ж", speaker="оператор", start=41, end=43)
    assert "script" in [п.kind for п in следом]


def test_скрипт_не_напоминает_о_сказанном_и_о_прощании():
    """Проверялся ключ `done`, которого в ответе нет: «осталось» было всё."""
    помощник = _помощник()
    помощник.добавить("Здравствуйте, компания Ромашка, меня зовут Анна, чем могу помочь?",
                      speaker="оператор", start=0, end=6)
    помощник.добавить("хочу вернуть товар", speaker="клиент", start=6, end=9)
    подсказки = помощник.добавить("так, минуту", speaker="оператор", start=26, end=30)
    скрипт = [п for п in подсказки if п.kind == "script"]
    assert скрипт, подсказки
    for сказанное in ("Поздоровался", "Представился", "Назвал компанию", "Предложил помощь",
                      "Попрощался"):
        assert сказанное not in скрипт[0].detail, скрипт[0].detail


def test_скрипт_не_напоминает_о_невозможном():
    """Прощание посреди разговора, истёкшее окно начала, пункт по факту."""
    скрипт = [
        {"id": "greeting", "label": "Поздоровался", "any": ["здравствуйте"], "where": "start"},
        {"id": "recording", "label": "Предупредил о записи", "any": ["разговор записывается"],
         "where": "start", "within_s": 10},
        {"id": "name", "label": "Обратился по имени", "check": "customer_name"},
        {"id": "farewell", "label": "Попрощался", "any": ["до свидания"], "where": "end"},
        {"id": "thanks", "label": "Поблагодарил", "any": ["спасибо"], "where": "any"},
    ]
    помощник = _помощник(content_script=скрипт)
    помощник.добавить("здравствуйте", speaker="оператор", start=0, end=2)
    подсказки = помощник.добавить("слушаю", speaker="оператор", start=28, end=30)
    скрипт_подсказки = [п for п in подсказки if п.kind == "script"]
    assert [п.detail for п in скрипт_подсказки] == ["Поблагодарил"], скрипт_подсказки


def test_оператор_один_возражений_не_бывает():
    """В потоке одна дорожка — оператора; «возражение клиента» — это его речь."""
    помощник = _помощник()
    подсказки = []
    for номер, текст in enumerate(("вам не нужно ничего делать", "это дорого не будет",
                                   "не подходит — не страшно", "подумаю за вас", "всё")):
        подсказки += помощник.добавить(текст, speaker="оператор", start=номер, end=номер + 1)
    assert not [п for п in подсказки if п.kind == "objection"], подсказки


def test_возражение_подсказывается_после_трёх_реплик_и_каждое_своё():
    помощник = _помощник()
    помощник.добавить("здравствуйте", speaker="оператор", start=0, end=1)
    сразу = помощник.добавить("это дорого, мне не подходит", speaker="клиент", start=1, end=2)
    assert not [п for п in сразу if п.kind == "objection"], "подсказка до ответа оператора"
    подсказки = []
    for номер, текст in enumerate(("так", "угу", "ну вот")):
        подсказки += помощник.добавить(текст, speaker="оператор", start=3 + номер, end=4 + номер)
    assert len([п for п in подсказки if п.kind == "objection"]) == 1
    подсказки = помощник.добавить("всё равно дорого, не нужно", speaker="клиент", start=9, end=10)
    for номер, текст in enumerate(("хм", "ага", "ладно")):
        подсказки += помощник.добавить(текст, speaker="оператор", start=11 + номер, end=12 + номер)
    assert len([п for п in подсказки if п.kind == "objection"]) == 1, "второе возражение промолчало"


def test_нарушение_говорит_что_именно_сработало():
    помощник = _помощник()
    подсказки = помощник.добавить("это не моя проблема, сами виноваты",
                                  speaker="оператор", start=0, end=4)
    нарушение = next(п for п in подсказки if п.kind == "violation")
    assert нарушение.detail, "у подсказки о нарушении пустая подробность"
    assert нарушение.detail.lower() in "это не моя проблема, сами виноваты"


def test_разбор_один_на_реплику(monkeypatch):
    """Каждый источник подсказок считал разбор заново — трижды на реплику."""
    вызовы: list[int] = []
    исходный = категории_модуль.apply

    def считать(*а, **к):
        вызовы.append(1)
        return исходный(*а, **к)

    monkeypatch.setattr(категории_модуль, "apply", считать)
    помощник = _помощник(content_categories=[
        *категории_модуль.ГОТОВЫЕ,
        {"id": "vip", "label": "Важный", "kind": "topic", "who": "any",
         "rule": "договор", "notify": True}])
    помощник.добавить("здравствуйте, договор", speaker="оператор", start=0, end=30)
    assert len(вызовы) == 1


def test_поток_и_помощник_называют_оператора_одинаково(tmp_path: Path):
    """Пустой stream_agent и «SPEAKER_00» в разборе: стоп-слова не ловились.

    Помощник брал метку оператора из `content_agent_speaker`, а реплики
    потока подписывались «оператор» — и нарушения оператора искались в
    репликах, которых у «SPEAKER_00» не было.
    """
    from asrhub.streaming import StreamEvent, StreamSession

    сессия = StreamSession(None, {"stream_agent": "", "stream_assist": True,
                                  "content_agent_speaker": "SPEAKER_00"}, workdir=tmp_path)
    события = сессия._подсказать([StreamEvent("final", text="сами виноваты", start=0, end=3)])
    assert any(с.type == "hint" and с.extra["kind"] == "violation" for с in события)
