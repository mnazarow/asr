"""Заход 35: потеря и подмена данных.

Общее у находок этой главы — тишина. Ни одна не роняет запрос и не пишет
строку в журнал ошибок: звонок просто не доезжает до архива, запись
достаётся не тому разговору, сбор архива рапортует об успехе, прочитав
два процента журнала. Замечают такое через недели, когда искать концы уже
поздно, — поэтому каждая проверка здесь описывает, чем ошибка выглядела
со стороны владельца сервера.
"""
from __future__ import annotations

import os
import time
import wave
from pathlib import Path

from asrhub.db import Database
from asrhub.telephony.asterisk import Звонок, найти_запись
from asrhub.telephony.stations import _станция_из


def база(tmp_path: Path) -> Database:
    return Database(tmp_path / "asrhub.db")


def wav(путь: Path, *, когда: float | None = None, секунд: int = 1) -> Path:
    путь.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(8000)
        файл.writeframes(b"\x00\x00" * (8000 * секунд))
    if когда is not None:
        os.utime(путь, (когда, когда))
    return путь


def строка_cdr(uid: str, src: str, dst: str, *, начало: float,
               duration: int = 300, context: str = "from-trunk") -> str:
    н = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(начало))
    к = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(начало + duration))
    return (f'"","{src}","{dst}","{context}","<{src}>","SIP/tr","SIP/{dst}",'
            f'"Dial","SIP/{dst}","{н}","{н}","{к}",{duration},{duration - 10},'
            f'"ANSWERED","DOCUMENTATION","{uid}",""\n')


class Очередь:
    def __init__(self):
        self.вызовы: list[dict] = []

    def submit(self, **kwargs):
        self.вызовы.append(kwargs)
        return {"id": f"job_{len(self.вызовы)}"}


class Настройки(dict):
    def get(self, ключ, по_умолчанию=None):                  # noqa: A003
        return dict.get(self, ключ, по_умолчанию)

    def merged(self, поверх):
        значения = dict(self)
        значения.update(поверх or {})
        return значения


def поля_станции(каталог: Path, имя: str = "АТС", **поверх) -> dict:
    поля = {
        "name": имя, "enabled": True, "source": "cdr_csv",
        "cdr_file": str(каталог / "Master.csv"),
        "recordings_dir": str(каталог / "monitor"),
        "settle_s": 0, "min_duration_s": 0, "skip_unanswered": False,
        "internal_digits": "3", "poll_s": 60, "lookback_days": 3650,
        "contexts": {"from-trunk": "входящий"},
    }
    поля.update(поверх)
    return поля


