def test_запись_из_другого_дня_не_достаётся_звонку(tmp_path: Path):
    """Запасной поиск по номерам брал ближайший файл — без ограничения вперёд.

    `граница` в `найти_запись` отсекала файлы СТАРШЕ «начало минус глубина
    поиска», а вперёд окна не было вовсе: из подходящих по номерам файлов
    брался просто ближайший по времени изменения. В каталоге, где записи
    той же пары абонентов есть за каждый день, понедельничному звонку
    доставался четверговый разговор — под правильными номерами, с
    правильным владельцем и чужим содержимым. Заметить это можно было
    только прослушав запись.

    Агент на станции ровно здесь окно имеет (`match_window`, 120 минут).
    Сервер, забирающий записи сам, — не имел.
    """
    каталог = tmp_path / "monitor"
    понедельник = time.time() - 4 * 86400
    четверг = понедельник + 3 * 86400
    # В имени только номера — идентификатора звонка нет. Так пишет
    # MixMonitor, которого позвали с ${CALLERID(num)} вместо ${UNIQUEID}.
    wav(каталог / "out-79161234567-79995554433-четверг.wav", когда=четверг)

    звонок = Звонок(uniqueid="1789000001.1", src="79161234567",
                    dst="79995554433", started_at=понедельник)
    assert найти_запись(звонок, каталог, окно_дней=30) is None, \
        "звонку досталась запись трёхсуточной давности"

    # А своя запись, сделанная в ту же минуту, находится как и раньше.
    своя = wav(каталог / "out-79161234567-79995554433-понедельник.wav",
               когда=понедельник + 60)
    найдено = найти_запись(звонок, каталог, окно_дней=30)
    assert найдено is not None and найдено.name == своя.name


