def test_удаление_записи_убирает_её_из_очереди_разбора(tmp_path: Path):
    """Строка очереди переживала запись и не убиралась ничем.

    В состоянии «идёт» её не брала ни одна уборка: `llmq_prune` ходит по
    завершённым, кнопка «Очистить» идущих не трогает намеренно, а
    `delete_job` про эту таблицу не знал вовсе. Раздел показывал вечный
    текущий запрос к модели по записи, которой больше нет. Отдельно это
    ещё и требование 152-ФЗ: строка очереди хранит имя файла и владельца.
    """
    db = база(tmp_path)
    for н in range(3):
        db.create_job({"id": f"job{н}", "filename": f"запись-{н}.wav", "owner": "анна"})
        db.llmq_put(f"job{н}")
    db.llmq_take()                                   # job0 -> «идёт»

    for н in range(3):
        db.delete_job(f"job{н}")
    assert db.query_one("SELECT COUNT(*) n FROM llm_queue")["n"] == 0, \
        "строки очереди пережили удаление записей"
    db.close()


def test_уборка_подбирает_строки_очереди_без_задания(tmp_path: Path):
    """На базе, пережившей прежние версии, сироты уже лежат.

    Убрать их некому: и уборка по сроку, и удаление по требованию субъекта
    ходят по таблице заданий. Поэтому общий заход по сиротам знает и про
    очередь разбора.
    """
    db = база(tmp_path)
    db.create_job({"id": "живое", "filename": "живая.wav", "owner": "анна"})
    db.llmq_put("живое")
    for н in range(2):                               # строки без задания
        db.execute("INSERT INTO llm_queue (job_id, state, enqueued_at) VALUES (?,?,?)",
                   (f"призрак{н}", db.LLMQ_ИДЁТ, time.time()))
    убрано = db.cleanup(results_days=0, metrics_days=0, events_days=0)
    assert убрано["orphans"] >= 2
    остались = {с["job_id"] for с in db.query("SELECT job_id FROM llm_queue")}
    assert остались == {"живое"}, остались
    db.close()


def test_сбой_разбора_возвращает_запись_в_очередь_а_не_вешает_её(tmp_path: Path):
    """Взятая запись оставалась «идёт» навсегда — и не разбиралась никогда.

    `llmq_take` берёт только ждущих, уборка по сроку ходит по завершённым,
    кнопка «Очистить» идущих не трогает. Значит, сорвавшийся разбор обязан
    сам вернуть запись в очередь: причина срыва почти всегда временная —
    сервер модели не ответил, видеокарта занята.
    """
    db = база(tmp_path)
    db.create_job({"id": "job0", "filename": "запись.wav", "owner": "анна"})
    db.llmq_put("job0")
    db.llmq_take()
    assert db.llmq_counts()[db.LLMQ_ИДЁТ] == 1

    assert db.llmq_release("job0", error="сервер модели не ответил") is True
    assert db.llmq_counts()[db.LLMQ_ЖДЁТ] == 1
    assert db.llmq_take()["job_id"] == "job0", "запись не вернулась в очередь"
    db.close()


def test_после_нескольких_заходов_запись_уходит_в_ошибку(tmp_path: Path):
    """Возвращать бесконечно тоже нельзя.

    Запись, на которой модель падает сама по себе, иначе крутилась бы в
    очереди до скончания века и занимала бы собой весь разбор архива.
    """
    db = база(tmp_path)
    db.create_job({"id": "job0", "filename": "запись.wav", "owner": "анна"})
    db.llmq_put("job0")
    for _ in range(3):
        взято = db.llmq_take()
        if взято is None:
            break
        db.llmq_release("job0", error="модель отвечает не тем", attempts_max=3)
    assert db.llmq_counts()[db.LLMQ_ОШИБКА] == 1, db.llmq_counts()
    строка = db.query_one("SELECT error FROM llm_queue WHERE job_id='job0'")
    assert "не тем" in (строка["error"] or ""), строка["error"]
    db.close()


def test_разбор_удалённой_записи_закрывает_строку_очереди(tmp_path: Path):
    """Запись удалили, пока она стояла в очереди.

    Строку очереди уже пометил `llmq_take`, а вернуться к ней некому:
    задания больше нет. Раздел показывал вечный текущий запрос по записи,
    которой не существует, и снять его было нечем.
    """
    from asrhub.llm.client import LLMClient, LLMError
    from asrhub.llm.worker import LLMWorker

    class Настройки:
        def get(self, ключ, по_умолчанию=None):
            return {"llm_backend": "stub", "llm_model": "test",
                    "llm_tasks": ["summary"]}.get(ключ, по_умолчанию)

    db = база(tmp_path)
    настройки = Настройки()
    поток = LLMWorker(db, настройки, LLMClient(настройки, db))
    db.execute("INSERT INTO llm_queue (job_id, state, enqueued_at, started_at) "
               "VALUES (?,?,?,?)", ("пропавшее", db.LLMQ_ИДЁТ, time.time(), time.time()))
    try:
        поток.analyze_job("пропавшее", force=True, из_очереди=True)
    except LLMError:
        pass
    else:
        raise AssertionError("разбор несуществующей записи должен падать")
    строка = db.query_one("SELECT state, error FROM llm_queue WHERE job_id='пропавшее'")
    assert строка["state"] != db.LLMQ_ИДЁТ, "строка осталась «идёт» навсегда"
    assert "удален" in (строка["error"] or ""), строка["error"]
    db.close()


