def test_обрыв_ami_отличается_от_затишья(tmp_path: Path):
    """Пустой `recv` — это конец соединения, а не «событий сейчас нет».

    Оба сводились к пустым байтам, и после обрыва клиент оставался
    «подключённым»: каждый заход читал пустоту, считал, что новых звонков
    нет, и уходил спать. Станция замолкала навсегда — молча, с пустым
    `last_error` и бодрым «соединение установлено» в разделе. Возвращалась
    она только с перезапуском сервера.
    """
    import socket

    from asrhub.telephony.asterisk import AMIClient, AMIError

    клиент = AMIClient("127.0.0.1", 5038, "u", "p")

    class СокетЗатишья:
        def recv(self, _сколько):
            raise TimeoutError

    class СокетОбрыва:
        def recv(self, _сколько):
            return b""

    клиент._sock = СокетЗатишья()
    assert клиент.пакет() == {}, "затишье должно читаться как «событий нет»"

    клиент._sock = СокетОбрыва()
    try:
        клиент.пакет()
    except AMIError as сбой:
        assert "закрыла соединение" in str(сбой), сбой
        assert "manager" in (сбой.hint or "").lower(), сбой.hint
    else:
        raise AssertionError("обрыв соединения прошёл как затишье")
    assert socket is not None
