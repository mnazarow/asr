def test_отпечаток_весов_гигаам_не_пуст(tmp_path: Path):
    """Веса GigaAM — один файл, а не каталог; `rglob` по файлу пуст.

    Пустой отпечаток означает «весов на диске нет», и кеш результатов
    переставал различать версии модели: обновили веса, попросили ту же
    запись заново — и в ответ приезжала расшифровка, сделанная ПРЕЖНЕЙ
    версией. Ровно от этого отпечаток и придуман. Затронуты были все
    девять моделей GigaAM, включая ту, что стоит в каталоге умолчанием.
    """
    from asrhub import model_files

    веса = tmp_path / "v3_rnnt.ckpt"
    веса.write_bytes(b"\x00" * 4096)
    отпечаток = model_files.fingerprint(tmp_path, "ai-sage/GigaAM-v3")
    assert отпечаток, "отпечаток весов GigaAM пуст"

    # Обновились веса — обновился и отпечаток: иначе кеш отдаст старое.
    model_files.forget(tmp_path)
    веса.write_bytes(b"\x01" * 8192)
    assert model_files.fingerprint(tmp_path, "ai-sage/GigaAM-v3") != отпечаток


