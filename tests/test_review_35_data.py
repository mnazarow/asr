def test_архивный_звонок_не_выпадает_из_очереди_отложенных(tmp_path: Path):
    """Срок отложенного считается от откладывания, а не от времени разговора.

    Порог безнадёжности сравнивался со `started_at`. Для сбора архива это
    означало, что отложенный звонок выпадал из очереди в тот же миг, как в
    неё попадал: разговор десятидневной давности «старше суток» всегда.
    Такой звонок навсегда оставался в архиве с пометкой «отложен» и без
    задания, и повторный сбор его не спасал — `call_exists` отвечал «уже
    импортирован». Владелец сервера видел это как «собрал архив за март,
    половина звонков без расшифровки».
    """
    db = база(tmp_path)
    разговор = time.time() - 10 * 86400
    db.save_call("pbx:1789000004.1", job_id=None,
                 skipped=f"{db.ОТЛОЖЕН}файл ещё растёт", owner="telephony",
                 station="pbx", pbx_uid="1789000004.1", src="79161234567",
                 dst="101", started_at=разговор, duration=300, billsec=290)

    порог = time.time() - 24 * 3600
    очередь = db.calls_deferred(limit=50, station="pbx", older_than=порог)
    assert [з["pbx_uid"] for з in очередь] == ["1789000004.1"], \
        "звонок из архива выпал из очереди в тот же заход, когда в неё попал"


def test_отложенный_доживает_до_срока_и_после_него_уходит(tmp_path: Path):
    """Срок всё-таки есть: иначе безнадёжные копятся вечно.

    Проверка парная к предыдущей — она держит исправление от перегиба в
    другую сторону: «считать от откладывания» не должно означать «не
    отсеивать вовсе».
    """
    db = база(tmp_path)
    for uid in ("свежий", "древний"):
        db.save_call(f"pbx:{uid}", job_id=None,
                     skipped=f"{db.ОТЛОЖЕН}файл ещё растёт", owner="telephony",
                     station="pbx", pbx_uid=uid, src="1", dst="2",
                     started_at=time.time() - 10 * 86400, duration=300, billsec=290)
    db.execute("UPDATE calls SET imported_at=? WHERE uniqueid='pbx:древний'",
               [time.time() - 3 * 86400])
    порог = time.time() - 24 * 3600
    очередь = db.calls_deferred(limit=50, station="pbx", older_than=порог)
    assert [з["pbx_uid"] for з in очередь] == ["свежий"]


def test_очередь_отложенных_идёт_от_самых_давних(tmp_path: Path):
    """Порядок — «кто раньше отложен, тот раньше и разбирается».

    Иначе при очереди длиннее порции свежие звонки вытесняли бы давние, и
    те не доходили бы до разбора никогда.
    """
    db = база(tmp_path)
    for uid, когда in (("позже", time.time() - 600),
                       ("раньше", time.time() - 3600)):
        db.save_call(f"pbx:{uid}", job_id=None,
                     skipped=f"{db.ОТЛОЖЕН}ещё пишется", owner="telephony",
                     station="pbx", pbx_uid=uid, src="1", dst="2",
                     started_at=time.time() - 7200, duration=300, billsec=290)
        db.execute("UPDATE calls SET imported_at=? WHERE uniqueid=?",
                   [когда, f"pbx:{uid}"])
    очередь = db.calls_deferred(limit=50, station="pbx")
    assert [з["pbx_uid"] for з in очередь] == ["раньше", "позже"]


