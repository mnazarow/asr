def test_сбор_архива_читает_весь_журнал_а_не_первую_порцию(tmp_path: Path):
    """Позиция чтения обнулялась на КАЖДОМ заходе сбора.

    Сбор архива — это заходы подряд, и каждый из них звал `_из_csv(всё=True)`,
    где позиция бралась нулевой. Первая порция читалась снова и снова:
    звонки после неё не попадали в архив никогда, а сбор рапортовал
    «остановлено, разобрано N» — ровно размер одной порции. На архиве в
    сорок тысяч звонков поднимались первые двести.
    """
    from asrhub.telephony import Импортёр

    каталог = tmp_path / "pbx"
    (каталог / "monitor").mkdir(parents=True, exist_ok=True)
    начало = time.time() - 86400
    журнал = "".join(
        строка_cdr(f"1789100{н:03d}.1", "79161234567", f"10{н % 7}", начало=начало + н)
        for н in range(12))
    (каталог / "Master.csv").write_text(журнал, encoding="utf-8")

    db, очередь = база(tmp_path), Очередь()
    станция = _станция_из(поля_станции(каталог), 0)
    имп = Импортёр(db, станция, очередь, Настройки({}))

    видено = 0
    for _ in range(3):
        видено += int(имп.scan(limit=5, всё=True).get("seen") or 0)
    assert видено == 12, f"заходы перечитывали одно и то же: увидено {видено}"
    uid = {с["pbx_uid"] for с in db.list_calls(limit=100)["calls"]}
    assert len(uid) == 12, f"в архив попало {len(uid)} звонков из 12"


def test_сбор_архива_обнуляет_позицию_один_раз(tmp_path: Path):
    """Позиция сбрасывается в начале сбора, а не внутри заходов.

    Иначе сбор архива не отличался бы от обычного захода: журнал читался бы
    с той позиции, где его оставил фоновый поток, и «собрать всё» подняло
    бы только новые звонки.
    """
    from asrhub.telephony import Импортёр

    каталог = tmp_path / "pbx"
    (каталог / "monitor").mkdir(parents=True, exist_ok=True)
    начало = time.time() - 86400
    (каталог / "Master.csv").write_text(
        "".join(строка_cdr(f"1789200{н:03d}.1", "79161234567", "101",
                           начало=начало + н) for н in range(4)),
        encoding="utf-8")

    db, очередь = база(tmp_path), Очередь()
    станция = _станция_из(поля_станции(каталог), 0)
    имп = Импортёр(db, станция, очередь, Настройки({}))
    имп.scan(limit=10)                        # обычный заход дочитал журнал
    позиция = int(db.get_kv(имп._ключ_позиции, 0) or 0)
    assert позиция > 0

    db.execute("DELETE FROM calls")           # архив потеряли, журнал остался
    имп.собрать(режим="all")
    for _ in range(100):
        if not имп.сбор.get("running"):
            break
        time.sleep(0.05)
    assert not имп.сбор.get("running"), "сбор не закончился"
    assert len(db.list_calls(limit=100)["calls"]) == 4, "сбор не перечитал журнал"


def test_отложенный_и_журнальный_дубль_дают_одно_задание(tmp_path: Path):
    """Сбор архива читает журнал с начала — и встречает свои же отложенные.

    Один и тот же звонок приходил дважды: из очереди отложенных и из
    журнала. Обе копии считались отложенными и обе проходили мимо
    `call_exists` — запись уезжала в распознавание двумя заданиями, а в
    архиве оставалась одна строка со ссылкой на второе. Первое становилось
    сиротой: занимало очередь, видеокарту и место на диске, а в интерфейсе
    не показывалось никогда.
    """
    from asrhub.telephony import Импортёр

    каталог = tmp_path / "pbx"
    (каталог / "monitor").mkdir(parents=True, exist_ok=True)
    начало = time.time() - 86400
    uid = "1789300001.1"
    (каталог / "Master.csv").write_text(
        строка_cdr(uid, "79161234567", "101", начало=начало), encoding="utf-8")
    wav(каталог / "monitor" / f"{uid}.wav", когда=начало + 300)

    db, очередь = база(tmp_path), Очередь()
    станция = _станция_из(поля_станции(каталог), 0)
    имп = Импортёр(db, станция, очередь, Настройки({}))
    db.save_call(f"{станция.id}:{uid}", job_id=None,
                 skipped=f"{db.ОТЛОЖЕН}файл ещё растёт", owner="telephony",
                 station=станция.id, pbx_uid=uid, src="79161234567", dst="101",
                 started_at=начало, duration=300, billsec=290, answered=1)

    имп.scan(limit=10, всё=True)
    assert len(очередь.вызовы) == 1, f"заданий {len(очередь.вызовы)} на один звонок"
    строки = db.list_calls(limit=10)["calls"]
    assert len(строки) == 1 and строки[0]["job_id"] == "job_1"


