def test_окно_не_мешает_совпадению_по_идентификатору(tmp_path: Path):
    """Идентификатор уникален: файл с ним — тот самый, когда бы он ни лёг.

    Станция дописывает и перекодирует запись уже после разговора, и на
    загруженной АТС файл появляется через часы. Ограничить окном и этот
    способ поиска значило бы поменять одну потерю на другую.
    """
    каталог = tmp_path / "monitor"
    начало = time.time() - 4 * 86400
    wav(каталог / "out-1789000003.1-79161234567.wav", когда=начало + 2 * 86400)
    звонок = Звонок(uniqueid="1789000003.1", src="79161234567",
                    dst="79995554433", started_at=начало)
    найдено = найти_запись(звонок, каталог, окно_дней=30, окно_минут=120)
    assert найдено is not None and "1789000003.1" in найдено.name


def test_окно_подбора_доходит_до_поиска_записи(tmp_path: Path):
    """Настройка станции обязана доезжать до места, где она работает.

    Параметр, который есть в форме и в справочнике, но не передаётся в
    `найти_запись`, — хуже отсутствующего: человек считает, что ограничил
    подбор, а подбор идёт по-старому.
    """
    import inspect

    from asrhub.telephony import diagnose as модуль_диагностики
    from asrhub.telephony import importer as модуль_импортёра

    for модуль in (модуль_импортёра, модуль_диагностики):
        текст = inspect.getsource(модуль)
        assert "окно_минут=" in текст, f"{модуль.__name__} не передаёт окно подбора"
        assert "match_window" in текст, f"{модуль.__name__} не читает match_window"

    станция = _станция_из(поля_станции(tmp_path), 0)
    assert станция.match_window == 120, "умолчание станции разошлось со справочником"
    from asrhub.catalog.params import get_param
    параметр = get_param("telephony_match_window")
    assert параметр is not None, "параметра нет в справочнике"
    assert параметр.default == станция.match_window


