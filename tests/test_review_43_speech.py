def test_ритм_оператора_не_зависит_от_того_как_отвечает_клиент():
    """Ритм речи оператора считался по паузам обеих сторон."""
    def разговор(задержки: list[float]) -> list[dict]:
        out, t = [], 0.0
        for n, задержка in enumerate(задержки):
            # Оператор: две реплики по 4 с с ровной паузой 0,5 с внутри.
            out.append(реплика(t, t + 4.0, "A", "слово " * 12))
            out.append(реплика(t + 4.5, t + 8.5, "A", "слово " * 12))
            t += 8.5 + задержка
            out.append(реплика(t, t + 3.0, "B", f"ответ клиента {n}"))
            t += 3.0 + 0.4
        return out

    ровно = разговор([0.5, 0.5, 0.5, 0.5, 0.5])
    рвано = разговор([0.2, 1.9, 0.3, 1.8, 0.2])
    р1 = indices.ритмичность(ровно, speech.analyze(ровно, 0.0), "A")
    р2 = indices.ритмичность(рвано, speech.analyze(рвано, 0.0), "A")
    assert р1["index"] is not None
    assert р1["pause_spread"] == р2["pause_spread"]
    assert р1["index"] == р2["index"]


