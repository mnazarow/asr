"""Заход 43: разбор одной записи — речь, тональность, NPS, обещания, тревога.

Каждая проверка воспроизводит сценарий из сплошной проверки аналитики
содержания: на прежнем коде она падает, на исправленном — проходит.
"""
from __future__ import annotations

import importlib

import pytest
from asrhub.content import categories as категории
from asrhub.content import indices, lexicons, masking, sentiment, speech
from asrhub.content.names import is_name

разбор_модуль = importlib.import_module("asrhub.content.analyze")


def реплика(начало: float, конец: float, кто: str | None, текст: str) -> dict:
    return {"start": начало, "end": конец, "speaker": кто, "text": текст}


# ---------------------------------------------------------------------------
# Паузы, тишина, наложение, поддакивания
# ---------------------------------------------------------------------------

#: Стерео: A говорит полминуты, B поддакивает внутри, A продолжает, B отвечает.
МОНОЛОГ_С_УГУ = [
    реплика(0.0, 30.0, "A", "длинное объяснение " * 30),
    реплика(5.0, 6.0, "B", "угу"),
    реплика(31.0, 40.0, "A", "продолжение " * 10),
    реплика(40.5, 45.0, "B", "понятно спасибо"),
]


def test_угу_внутри_монолога_не_пауза_не_наложение_и_не_перебивание():
    """Прежний счёт от конца предыдущей реплики давал паузу и наложение в 25 с.

    На деле пауз длиннее секунды нет вовсе, а «угу» — знак, что слушают.
    """
    р = speech.analyze(МОНОЛОГ_С_УГУ, 45.0)
    assert р["pauses"] == 0 and р["long_pauses"] == 0
    assert р["longest_pause_s"] == 0.0 and р["dead_air_s"] == 0.0
    assert р["overlap_s"] == 0.0 and р["interruptions"] == 0
    assert р["backchannels"] == 1
    # Слово переходило один раз — от A к B в конце.
    assert р["switches"] == 1
    # Тишина — длительность минус объединение речи: полторы секунды.
    assert р["speech_s"] == 43.5 and р["silence_s"] == 1.5
    # Монолог A не прерван поддакиванием: 30 + 9 секунд.
    assert р["monologue"] == {"speaker": "A", "seconds": 39.0, "start_s": 0.0}
    b = next(з for з in р["speakers"] if з["speaker"] == "B")
    assert b["backchannels"] == 1
    # Пауза B перед ответом — от конца речи A, полсекунды.
    assert b["reply_delay_s"] == 0.5


def test_тишина_считается_по_объединению_реплик():
    """A 0–30 и B 20–40 из минуты: тишина — треть, а не шестая часть."""
    р = speech.analyze([реплика(0.0, 30.0, "A", "а"), реплика(20.0, 40.0, "B", "б")], 60.0)
    assert р["silence_share"] == pytest.approx(0.333, abs=0.001)
    assert р["speech_s"] == 40.0
    assert р["overlap_s"] == 10.0
    assert р["interruptions"] == 1
    assert р["interruption_examples"][0]["overlap_s"] == 10.0
    assert р["interruption_examples"][0]["interrupted"] == "A"


def test_пауза_меряется_от_самого_позднего_конца_речи():
    """A 0–10, «угу» B на 2–3 с, A снова с 20-й: пауза — 10 с, а не 17."""
    р = speech.analyze([реплика(0.0, 10.0, "A", "раз"), реплика(2.0, 3.0, "B", "угу"),
                        реплика(20.0, 25.0, "A", "два")], 25.0)
    assert р["pauses"] == 1 and р["longest_pause_s"] == 10.0
    assert р["dead_air_s"] == 10.0


def test_ноль_в_пороге_поддакивания_возвращает_прежний_счёт():
    """Поддакивание можно не выделять: тогда «угу» — перебивание и наложение."""
    р = speech.analyze(МОНОЛОГ_С_УГУ, 45.0, speech.Пороги(поддакивание=0.0))
    assert р["backchannels"] == 0
    assert р["interruptions"] == 1 and р["overlap_s"] == 1.0
    assert р["switches"] == 3


def test_длинная_реплика_внутри_чужой_речи_не_поддакивание():
    """Десять секунд внутри чужого монолога — это уже разговор хором."""
    р = speech.analyze([реплика(0.0, 60.0, "A", "а " * 50),
                        реплика(10.0, 20.0, "B", "подождите " * 5)], 60.0)
    assert р["backchannels"] == 0
    assert р["interruptions"] == 1 and р["overlap_s"] == 10.0


def test_короткий_ответ_после_чужой_речи_не_поддакивание():
    """«Да» после того, как собеседник договорил, — ответ и смена говорящего."""
    р = speech.analyze([реплика(0.0, 10.0, "A", "вопрос " * 10),
                        реплика(10.5, 11.5, "B", "да"),
                        реплика(12.0, 20.0, "A", "продолжение " * 8)], 20.0)
    assert р["backchannels"] == 0 and р["switches"] == 2
    b = next(з for з in р["speakers"] if з["speaker"] == "B")
    assert b["reply_delay_s"] == 0.5


def test_реплики_одного_говорящего_внахлёст_не_наложение():
    """Разметка иногда перекрывает две реплики одного человека на стыке."""
    р = speech.analyze([реплика(0.0, 5.0, "A", "раз"), реплика(4.0, 8.0, "A", "два"),
                        реплика(9.0, 12.0, "B", "три")], 12.0)
    assert р["overlap_s"] == 0.0 and р["interruptions"] == 0
    assert р["speech_s"] == 11.0


def test_реплики_встык_не_пауза_и_не_перебивание_при_нулевых_порогах():
    """«Считать паузой любой разрыв» — это разрыв, а не стык."""
    пороги = speech.Пороги(пауза=0.0, тишина=0.0, перебивание=0.0)
    встык = speech.analyze([реплика(0.0, 2.0, "A", "а"), реплика(2.0, 4.0, "B", "б")],
                           4.0, пороги)
    assert встык["pauses"] == 0 and встык["interruptions"] == 0
    с_зазором = speech.analyze([реплика(0.0, 2.0, "A", "а"), реплика(2.3, 4.0, "B", "б")],
                               4.0, пороги)
    assert с_зазором["pauses"] == 1


def test_порог_поддакивания_читается_из_настроек():
    assert speech.Пороги.из_настроек({"content_backchannel_s": 2.0}).поддакивание == 2.0
