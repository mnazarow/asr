def test_хвост_повёрнутого_журнала_агент_дочитывает(tmp_path: Path):
    """Звонки между прошлым заходом и ротацией терялись: новый файл — с начала."""
    журнал = tmp_path / "Master.csv"
    журнал.write_text(строка_cdr("1757600001.1"), encoding="utf-8")
    источник = агент.ИсточникCSV([str(журнал)], состояние(tmp_path))
    assert [з.uniqueid for з in источник.звонки()] == ["1757600001.1"]
    with журнал.open("a", encoding="utf-8") as файл:
        файл.write(строка_cdr("1757600002.1"))
    журнал.rename(tmp_path / "Master.csv.1")
    журнал.write_text(строка_cdr("1757600003.1"), encoding="utf-8")
    assert [з.uniqueid for з in источник.звонки()] == ["1757600002.1", "1757600003.1"]
    assert list(источник.звонки()) == []


def test_хвост_после_copytruncate_агент_берёт_из_копии(tmp_path: Path):
    журнал = tmp_path / "Master.csv"
    журнал.write_text(строка_cdr("1757700001.1"), encoding="utf-8")
    источник = агент.ИсточникCSV([str(журнал)], состояние(tmp_path))
    list(источник.звонки())
    with журнал.open("a", encoding="utf-8") as файл:
        файл.write(строка_cdr("1757700002.1"))
    (tmp_path / "Master.csv.1").write_bytes(журнал.read_bytes())
    журнал.write_text("", encoding="utf-8")
    assert [з.uniqueid for з in источник.звонки()] == ["1757700002.1"]


