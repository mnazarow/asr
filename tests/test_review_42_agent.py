@pytest.mark.parametrize("код", [413, 415])
def test_звонок_с_непринятой_записью_уходит_без_неё(tmp_path: Path, код: int):
    """Запись больше предела (в том числе у nginx) или не того вида.

    Повтор с тем же файлом получит тот же отказ, а звонок раньше просто
    пропадал из журнала: считался ошибкой, а позиция уже сдвинута.
    """
    with Станция() as станция:
        станция.сбои["/api/telephony/agent/call"] = [код]
        wav(tmp_path / "monitor" / "1757500001.1.wav")
        а = стенд(tmp_path, станция.адрес, строка_cdr("1757500001.1"))
        а.поздороваться()
        свод = а.проход("new")
    assert свод["ошибок"] == 0 and свод["отправлено"] == 1, свод
    принятый = станция.принятые[-1]
    assert принятый["имя_файла"] is None
    assert принятый["meta"]["skipped"].startswith("сервер не принял запись")
    assert а.состояние.отправлен("1757500001.1")


