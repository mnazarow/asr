def test_идентификатор_не_находит_запись_соседнего_звонка(tmp_path: Path):
    каталог = tmp_path / "monitor"
    wav(каталог / "q-1757500001.12-a.wav")
    записи = агент.Записи(str(каталог))
    звонок = агент.Звонок(uniqueid="1757500001.1", started_at=time.time())
    assert записи.найти(звонок) is None
    своя = wav(каталог / "q-1757500001.1-b.wav")
