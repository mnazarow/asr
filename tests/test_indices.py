"""Показатели разговора: эмоциональный фон, стресс, понятность, точность, NPS.

Каждая проверка написана на разговоре, в котором показатель обязан
сработать, и на парном к нему, в котором обязан НЕ сработать: показатель,
который срабатывает всегда, ничем не лучше отсутствующего.
"""
from __future__ import annotations

import pytest
from asrhub.content import indices


def реплики(*пары: tuple[str, str], шаг: float = 6.0) -> list[dict]:
    """Сегменты из пар «кто — что». Времена ровные: их считают отдельно."""
    сегменты = []
    начало = 0.0
    for кто, текст in пары:
        сегменты.append({"start": начало, "end": начало + шаг,
                         "speaker": кто, "text": текст})
        начало += шаг
    return сегменты


def оценки(сегменты: list[dict], значения: list[float]) -> list[dict]:
    return [{"speaker": с["speaker"], "score": з}
            for с, з in zip(сегменты, значения, strict=False)]


def речь(сегменты: list[dict], **поверх) -> dict:
    длительность = max((с["end"] for с in сегменты), default=0.0)
    return {"duration_s": длительность, "interruptions": 0, "overlap_share": 0.0,
            "wpm": 140, **поверх}


