def test_ритмичность_не_объявляет_редкие_паузы_идеально_ровными():
    """Пауз мало — про них ничего не известно.

    Объявлять их «идеально ровными» значит выдавать незнание за порядок и
    завышать индекс на коротких разговорах: рваная по темпу речь получала
    сорок очков сверху за паузы, которых никто не мерил.
    """
    сегменты = []
    начало = 0.0
    # Четыре реплики — три паузы, меньше порога измеримости.
    for н in range(4):
        слов = 70 if н % 2 else 6
        сегменты.append({"start": начало, "end": начало + 10, "speaker": "A",
                         "text": " ".join(["слово"] * слов)})
        начало += 10.5
    итог = indices.ритмичность(сегменты, речь(сегменты), "A")
    assert итог["index"] is not None
    assert итог["pause_spread"] == 0.0, "пауз мало — разброса нет"
    assert итог["index"] <= 5, итог
