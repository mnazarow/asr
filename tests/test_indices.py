def test_названный_балл_всегда_главнее_предсказанного():
    сегменты = реплики(("A", "Оцените по шкале от нуля до десяти нашу работу."),
                       ("B", "Девять."))
    итог = indices.nps(сегменты, настроение_={"end": -0.8, "score": -0.8},
                       усилие_={"score": -4, "markers": ["мне обещали"]},
                       стресс_={"index": 80}, клиент="B")
    assert итог["predicted"] is False
    assert итог["score"] == 9 and итог["group"] == "промоутер"
    assert итог["confidence"] == 1.0


def test_балл_из_реплики_оператора_не_считается_названным():
    """Единственное число раздела, объявленное «не предсказанным», —
    названное клиентом. Номер заказа из ответа оператора и его собственное
    «я поставлю десять» туда попадать не должны.
    """
    сегменты = реплики(("A", "Оцените качество обслуживания по шкале от нуля до десяти."),
                       ("A", "Я поставлю десять, хорошо?"),
                       ("B", "Нет, два."))
    итог = indices.nps(сегменты, настроение_={"end": -0.5, "score": -0.5},
                       усилие_={"score": -2, "markers": []}, стресс_={"index": 50},
                       клиент="B")
    assert итог["predicted"] is False
    assert итог["score"] == 2, "взят балл оператора вместо клиентского"
    # Стороны не размечены — доверять нечему, балл считается предсказанным.
    без_сторон = indices.nps(сегменты, настроение_={"end": -0.5, "score": -0.5},
                             усилие_={"score": -2, "markers": []},
                             стресс_={"index": 50})
    assert без_сторон["predicted"] is True


def test_показатели_речи_молчат_без_разметки_по_сторонам():
    """Записи без сторон — обычное дело: движок без диаризации, одна дорожка.

    Считать по ним «речь оператора» значило бы записывать паразиты клиента
    и его «вы должны» на счёт сотрудника.
    """
