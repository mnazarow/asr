def test_настроение_считается_по_стороне_клиента():
    """Средняя по разговору смешивает раздражённого клиента с ровным оператором.

    И получает «нейтрально» — то есть теряет ровно то, что хотели узнать.
    """
    с = реплики(("A", "Добрый день, слушаю вас."),
                ("B", "Это уже никуда не годится!"),
                ("A", "Сейчас разберёмся."),
                ("B", "Сколько можно!"))
    итог = indices.настроение(оценки(с, [0.1, -0.8, 0.1, -0.7]), {"score": -0.3},
                              "A", "B")
    assert итог["customer"] < -0.5
    assert итог["agent"] > 0
    assert итог["score"] == итог["customer"], "итог берётся со стороны клиента"
    assert итог["label"] == "подавленное"


def test_разворот_настроения_виден_отдельно():
    """Разговор с тяжёлым началом и тёплым концом сделан хорошо.

    По средней тональности он неотличим от ровно-никакого, поэтому сдвиг
    считается отдельным числом.
    """
    с = реплики(*[("B", "реплика") for _ in range(6)])
    выправился = indices.настроение(оценки(с, [-0.8, -0.7, -0.6, 0.1, 0.4, 0.6]),
                                    {}, "A", "B")
    # Сдвиг приведён к той же шкале, что и само настроение: −1…+1.
    assert 0.15 < выправился["shift"] <= 1.0 and выправился["recovered"] is True
    испортился = indices.настроение(оценки(с, [0.6, 0.4, 0.1, -0.6, -0.7, -0.8]),
                                    {}, "A", "B")
    assert испортился["worsened"] is True and испортился["recovered"] is False


def test_сила_эмоции_отдельно_от_знака():
    """«Слегка недоволен» и «в ярости» — разные разговоры при одном знаке."""
    с = реплики(*[("B", "реплика") for _ in range(4)])
    слабая = indices.интенсивность(оценки(с, [-0.12, -0.1, -0.15, -0.08]))
    сильная = indices.интенсивность(оценки(с, [-0.95, -0.9, -0.85, -0.9]))
    assert слабая is not None and сильная is not None
    assert сильная > слабая
    assert 1 <= слабая <= 5 and 1 <= сильная <= 5
    # Эмоции нет вовсе — пусто, а не ноль: «измерили и не нашли» и «не
    # измеряли» — разные утверждения.
    assert indices.интенсивность(оценки(с, [0.0, 0.01, -0.02, 0.0])) is None


