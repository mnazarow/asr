def test_напряжение_растёт_от_резких_реплик_и_перебиваний():
    с = реплики(*[("B", "Сколько можно ждать!") for _ in range(6)])
    спокойно = indices.стресс(сегменты=реплики(("A", "Добрый день."), ("B", "Здравствуйте.")),
                              речь=речь(с), оценки=оценки(с, [0.0] * 6),
                              клиент="B", оператор="A", фрустрация=0,
                              повторное=0, мат=None)
    буря = indices.стресс(сегменты=с, речь=речь(с, interruptions=8, overlap_share=0.12),
                          оценки=оценки(с, [-0.8] * 6), клиент="B", оператор="A",
                          фрустрация=4, повторное=2, мат=None)
    assert спокойно["index"] < 20 and спокойно["level"] == "низкий"
    assert буря["index"] > 60 and буря["level"] == "высокий"
    assert {з["name"] for з in буря["signals"]} >= {"резкие реплики", "раздражение"}
    # Чей стресс — вопрос отдельный: у клиента и оператора он чинится
    # по-разному.
    assert буря["customer"] is not None and буря["customer"] > (буря["agent"] or 0)


def test_раздражение_поднимает_напряжение_само_по_себе():
    """Реплики раздражения — самостоятельный признак, а не довесок к тону.

    Разговор бывает ровным по окраске слов и тяжёлым по существу: клиент
    говорит вежливо и при этом третий раз объясняет одно и то же.
    """
    с = реплики(*[("B", "Объясняю ещё раз.") for _ in range(6)])
    ровные = оценки(с, [0.0] * 6)
    без = indices.стресс(сегменты=с, речь=речь(с), оценки=ровные, клиент="B",
                         оператор="A", фрустрация=0, повторное=0, мат=None)
    с_ним = indices.стресс(сегменты=с, речь=речь(с), оценки=ровные, клиент="B",
                           оператор="A", фрустрация=5, повторное=0, мат=None)
    assert с_ним["index"] >= без["index"] + 15, (без, с_ним)
    assert any(з["name"] == "раздражение" for з in с_ним["signals"])


def test_усилие_клиента_видит_повторные_обращения():
    трудно = реплики(("B", "Я звоню третий раз, мне обещали перезвонить, "
                           "никто не перезвонил, меня переключают по кругу."))
    легко = реплики(("B", "Всё получилось, спасибо большое, вопрос решён."))
    плохо = indices.усилие(трудно, "B", повторное=2)
    хорошо = indices.усилие(легко, "B", повторное=0)
    assert плохо["score"] < -2 and плохо["level"] == "высокое"
    assert хорошо["score"] > 0 and хорошо["level"] == "низкое"
    assert "мне обещали" in плохо["markers"]


