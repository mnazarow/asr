def test_плохая_запись_не_выдаётся_за_плохой_ответ():
    """Уверенность распознавания входит в точность четвертью веса.

    Без этого хуже всех выглядели бы разговоры с плохой линией, а не с
    плохими ответами.
    """
    сегменты = реплики(("A", "Заказ 4512 приедет завтра до 18 часов, сумма 2400 рублей. "
                             "Курьер позвонит за 30 минут до приезда. Договор 77-А "
                             "от 3 сентября, квитанция придёт на почту в течение часа."),
                       шаг=30)
    чисто = indices.точность(сегменты, "A", confidence=0.95)
    шумно = indices.точность(сегменты, "A", confidence=0.35)
    assert чисто["index"] > шумно["index"]
    assert шумно["confidence"] == 0.35


