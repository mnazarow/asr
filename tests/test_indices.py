def test_напряжение_не_растёт_от_одной_только_длины_разговора():
    """Та же плотность вспышек — тот же уровень напряжения.

    Сырой счётчик раздражения делал получасовой разговор вчетверо
    «напряжённее» пятиминутного при одинаковом поведении, и сотрудник на
    длинных разговорах выглядел хуже просто потому, что они длинные.
    """
    значения = []
    for множитель in (1, 2, 4, 8):
        с = реплики(*[("B", "Сколько можно.") for _ in range(6 * множитель)])
        значения.append(indices.стресс(
            сегменты=с, речь=речь(с), оценки=оценки(с, [0.0] * len(с)),
            клиент="B", оператор="A", фрустрация=множитель,
            повторное=0, мат=None)["index"])
    assert max(значения) - min(значения) <= 6, значения


