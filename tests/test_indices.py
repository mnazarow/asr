def test_вежливость_считает_и_обрывающие_обороты():
    вежливо = реплики(("A", "Здравствуйте! Пожалуйста, назовите номер заказа. "
                            "Спасибо. Всего доброго!"))
    грубо = реплики(("A", "Подождите. Вы должны были проверить сами. "
                          "Это не моя проблема, я вам уже сказал."))
    х = indices.вежливость_индекс(вежливо, "A")
    п = indices.вежливость_индекс(грубо, "A")
    assert х["index"] == 100 and х["impolite"] == 0
    assert п["index"] == 0 and п["impolite"] >= 3
    assert "прощание" in х["kinds"] and "прощание" in п["missing"]
    # Счёт, а не факт: шесть «подождите» и одно «подождите» — разные
    # разговоры, а индекс у них был одинаковый.
    одно = indices.вежливость_индекс(
        реплики(("A", "Здравствуйте. Подождите.")), "A")
    шесть = indices.вежливость_индекс(
        реплики(("A", "Здравствуйте. " + "Подождите. " * 6)), "A")
    assert шесть["impolite"] == 6 and одно["impolite"] == 1
    assert шесть["index"] < одно["index"]


def test_персонализация_считается_на_время_разговора():
    """В часовом разговоре два раза по имени — это не персонализация."""
