def test_уменьшительные_не_путаются_с_обычными_словами():
    """Суффиксный поиск зачисляет в «ласкательные» точку, ручку и заявку.

    Тогда показатель превращается в счётчик существительных женского рода,
    и разговаривать по нему с человеком нельзя.
    """
    ласково = реплики(("A", "Секундочку, я посмотрю договорчик и заявочку, "
                            "минуточку подождите. Денёчек — и счётик пришлём."))
    обычно = реплики(("A", "Точка отправления в накладной указана неверно, "
                           "проверьте ссылку и заявку, карточка клиента открыта. "
                           "Стиральная машинка какой модели, и какая квартирка?"))
    л = indices.уменьшительные(ласково, "A")
    о = indices.уменьшительные(обычно, "A")
    assert л["count"] >= 5 and {с["word"] for с in л["top"]} >= {"секундочку", "минуточку"}
    # `words()` заменяет ё на е — словарь обязан сверяться в том же виде,
    # иначе «денёчек» и «счётик» не находятся никогда.
    assert {с["word"] for с in л["top"]} >= {"денечек", "счетик"}
    assert о["count"] == 0, о["top"]


