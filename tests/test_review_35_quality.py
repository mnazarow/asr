def test_молчащий_канал_не_уносит_расшифровку_второго(tmp_path: Path):
    """В телефонном звонке молчит то клиент, то оператор — это норма.

    Подготовка каналов идёт до поиска речи, и канал, от которого после
    обработки не осталось звука, отказывал ВСЁ задание: «Запись звучит, но
    после обработки звука не осталось». Расшифровка второго собеседника —
    уже готовая, уже оплаченная видеокартой — уходила вместе с ним.
    Дальше по конвейеру молчащий канал давно обработан правильно: он
    попадает в «речь не обнаружена в каналах» и никого не роняет. До этого
    места дело просто не доходило.
    """
    from asrhub.config import load
    from asrhub.pipeline import audio as audio_mod

    файл = стерео(тон(tmp_path / "л.wav"), тишина(tmp_path / "п.wav"),
                  tmp_path / "звонок.wav")
    настройки = load().merged({"audio_channels": "split",
                               "audio_trim_silence": True})
    готово = audio_mod.prepare(файл, tmp_path / "работа", настройки)
    assert len(готово.channels) == 1, "остался не один канал"
    assert готово.silent == ["Канал 2"], готово.silent
    assert готово.warnings and "Канал 2" in готово.warnings[0]


