def test_пустой_канал_не_портит_оценку_качества_записи():
    """Худший SNR по каналам — но не по тому, где никто не говорил.

    Пустой канал даёт честный ноль децибел, и запись целиком уезжала в
    корзину «плохой звук», а человек получал совет «включите нормализацию»
    к разговору, с которым всё в порядке.
    """
    from asrhub.pipeline import audio_profile as AP

    слитый = AP.merge([
        {"snr_db": 24.0, "has_speech": True, "silence_share": 0.35,
         "peak_dbfs": -9.0, "loudness_lufs": -21.0},
        {"snr_db": 0.2, "has_speech": False, "silence_share": 1.0,
         "peak_dbfs": -90.0, "loudness_lufs": -70.0},
    ])
    assert слитый["snr_db"] == 24.0, слитый
    assert слитый["loudness_lufs"] == -21.0
    # Пик и клиппинг по-прежнему по всем каналам: они про запись, а не про речь.
    assert слитый["peak_dbfs"] == -9.0


