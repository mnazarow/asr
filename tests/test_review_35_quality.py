def test_клон_из_кеша_сохраняет_признаки_галлюцинации(tmp_path: Path):
    """У двух полей два написания, и круг «прочитать и записать» их терял.

    Ходит этим кругом клонирование результата из кеша: повторная загрузка
    того же файла копирует реплики прежнего задания. У копии пропадали
    `no_speech_prob` и `compression_ratio` — то есть признаки, по которым
    видно выдуманный моделью текст. Запись, помеченная разбором как
    «сжимаемый текст, тишина», у клона выглядела чистой.
    """
    from asrhub import quality

    db = Database(tmp_path / "asrhub.db")
    db.create_job({"id": "исходное", "filename": "запись.wav"})
    db.save_segments("исходное", [{
        "start": 0.0, "end": 2.0, "text": "спасибо за просмотр", "speaker": "S1",
        "confidence": 0.2, "no_speech_prob": 0.9, "compression_ratio": 3.1,
        "temperature": 0.0, "language": "ru"}])

    db.create_job({"id": "клон", "filename": "запись.wav", "cached_from": "исходное"})
    db.save_segments("клон", db.get_segments("исходное"))       # ровно как _clone_cached

    было = db.get_segments("исходное")[0]
    стало = db.get_segments("клон")[0]
    assert (стало["no_speech"], стало["compression"]) == \
           (было["no_speech"], было["compression"])
    assert quality.for_job(quality.assess(db.get_segments("клон"))) == \
           quality.for_job(quality.assess(db.get_segments("исходное")))
    db.close()


def test_команда_агенту_уходит_ровно_один_раз(tmp_path: Path):
    """Чтение и снятие были двумя шагами без транзакции.

    Между ними успевал вклиниться второй заход того же агента — он
    опрашивает сервер по расписанию, а сеть иногда задваивает запрос. Обе
    стороны читали «собрать всё» и обе его выполняли: сбор архива шёл
    дважды по одной позиции журнала и грузил станцию вдвое.
    """
    import threading

    db = Database(tmp_path / "asrhub.db")
    db.agent_save("pbx-1", {"name": "агент филиала"})
    раздач: list[int] = []
    for _ in range(20):
        db.agent_command_set("pbx-1", "собрать всё")
        получили: list[str] = []
        барьер = threading.Barrier(8)

        def тянуть(барьер=барьер, получили=получили) -> None:
            # Довода два и оба со значением по умолчанию: без этого замыкание
            # смотрело бы на переменные цикла, а они меняются на каждом заходе.
            барьер.wait()
            команда = db.agent_command_take("pbx-1")
            if команда:
                получили.append(команда)

        потоки = [threading.Thread(target=тянуть) for _ in range(8)]
        for п in потоки:
            п.start()
        for п in потоки:
            п.join()
        раздач.append(len(получили))
    assert раздач == [1] * 20, f"команда уходила по нескольку раз: {раздач}"
    db.close()


def test_срочное_задание_попадает_в_окно_предвыборки(tmp_path: Path):
    """Политика «по сроку» выбирала предварительно по времени создания.

    Срочное задание, поставленное последним, в окно выборки не попадало
    вовсе: на очереди из шестисот заданий при окне в пятьсот политика молча
    вырождалась в «по очереди» — то есть не работала ровно в том случае,
    ради которого её включают.
    """
    db = Database(tmp_path / "asrhub.db")
    т = time.time()
    for н in range(600):
        db.create_job({"id": f"old{н:04d}", "filename": f"{н}.wav",
                       "status": "queued", "created_at": т - 10000 + н,
                       "queued_at": т - 10000 + н, "priority": 50})
    db.create_job({"id": "срочное", "filename": "срочное.wav", "status": "queued",
                   "created_at": т, "queued_at": т, "priority": 50,
                   "deadline": т + 600})
    окно = db.list_jobs(status=["queued", "retry"], limit=500,
                        order="deadline ASC", light=True)
    assert окно[0]["id"] == "срочное", "срочное задание не в начале окна"
    # Задания без срока при этом никуда не делись и идут по времени.
    без_срока = [з["id"] for з in окно if not з.get("deadline")]
    assert без_срока[:2] == ["old0000", "old0001"], без_срока[:3]

    # И сама очередь берёт именно срочное — с настоящей политикой и окном.
    import threading

    from asrhub.job_queue import JobQueue

    class Настройки(dict):
        def get(self, ключ, по_умолчанию=None):              # noqa: A003
            return dict.get(self, ключ, по_умолчанию)

    очередь = JobQueue.__new__(JobQueue)
    очередь.db = db
    очередь.settings = Настройки({"scheduling_policy": "deadline",
                                  "scheduling_window": 500,
                                  "max_concurrent_jobs": 2,
                                  "max_concurrent_per_model": 0})
    очередь._lock = threading.RLock()
    очередь._paused = False
    очередь._running, очередь._concurrency, очередь._model_counts = {}, {}, {}
    взято = очередь._next_job(0)
    assert взято is not None and взято["id"] == "срочное", взято
    db.close()


