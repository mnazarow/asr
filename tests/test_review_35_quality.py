"""Заход 35: неверные результаты.

Эти находки не роняют ничего и не пишут ни строчки в журнал. Они просто
дают неправильный ответ: повтор слов посреди фразы, оценка, которой клиент
не ставил, «Эскалация» на вежливом обороте, плохое качество записи из-за
канала, в котором собеседник молчал. Проверить такое можно только по
смыслу, поэтому каждая проверка здесь описывает, что человек увидел бы в
отчёте — и почему это неправда.
"""
from __future__ import annotations

import math
import struct
import subprocess
import time
import wave
from pathlib import Path

import pytest
from asrhub.db import Database

# ---------------------------------------------------------------------------
# Заготовки звука
# ---------------------------------------------------------------------------

def тон(путь: Path, *, секунд: float = 3.0, частота: float = 320.0,
        громкость: float = 0.3, rate: int = 16000) -> Path:
    путь.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(rate)
        файл.writeframes(b"".join(
            struct.pack("<h", int(32767 * громкость * math.sin(2 * math.pi * частота * и / rate)))
            for и in range(int(rate * секунд))))
    return путь


def тишина(путь: Path, *, секунд: float = 3.0, rate: int = 16000) -> Path:
    путь.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(rate)
        файл.writeframes(b"\x00\x00" * int(rate * секунд))
    return путь


def стерео(левый: Path, правый: Path, куда: Path) -> Path:
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                    "-i", str(левый), "-i", str(правый), "-filter_complex",
                    "[0:a][1:a]amerge=inputs=2[o]", "-map", "[o]", "-ac", "2",
                    str(куда)], check=True, timeout=120)
    return куда


