def test_выравнивание_идёт_по_своему_каналу(tmp_path: Path, monkeypatch):
    """Раньше сюда уходил файл первого канала и реплики обоих.

    Слова второго собеседника искались в чужом звуке: совпасть им там не с
    чем, и этап, который должен УТОЧНЯТЬ границы, растаскивал половину
    реплик по чужим местам — а те, что пришлись на конец разговора,
    оказывались за концом звука. Молча: выравнивание не жалуется, оно
    просто двигает метки.
    """
    from asrhub import processor
    from asrhub.config import load
    from asrhub.engines import EngineRegistry
    from asrhub.pipeline import alignment

    файл = стерео(тон(tmp_path / "л.wav", частота=320.0),
                  тон(tmp_path / "п.wav", частота=480.0),
                  tmp_path / "звонок.wav")

    вызовы: list[tuple[str, list[str]]] = []

    def подмена(путь, сегменты, настройки):
        вызовы.append((Path(путь).name, [с.speaker or "" for с in сегменты]))
        return сегменты

    monkeypatch.setattr(alignment, "align_segments", подмена)
    настройки = load().merged({
        "model": "demo-simulator", "engine": "demo", "vad_backend": "energy",
        "audio_channels": "split", "alignment_backend": "whisperx",
        "diarization_enabled": False})
    работа, выход = tmp_path / "w", tmp_path / "o"
    работа.mkdir()
    выход.mkdir()
    processor.process_job(файл, настройки, EngineRegistry(),
                          workdir=работа, outdir=выход, basename="звонок")

    assert len(вызовы) == 2, f"выравнивание звали {len(вызовы)} раз(а), а каналов два"
    for имя, говорящие in вызовы:
        свои = set(говорящие)
        assert len(свои) == 1, f"в один заход пришли реплики разных каналов: {свои}"
        канал = "left" if "Канал 1" in свои else "right"
        assert канал in имя, f"канал {свои} выравнивают по файлу {имя}"


