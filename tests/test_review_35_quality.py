def test_ноль_у_выгрузки_моделей_означает_никогда():
    """`int(значение or 900)` включал автовыгрузку через пятнадцать минут.

    При том что в интерфейсе стоял ноль — «не выгружать никогда». Заметить
    это можно было только по внезапной паузе на первой записи после
    затишья: веса грузятся заново полторы минуты.
    """
    import inspect

    from asrhub.api import app as модуль_приложения
    from asrhub.api import routes_system

    for модуль in (модуль_приложения, routes_system):
        текст = inspect.getsource(модуль)
        assert 'model_idle_unload_s") or 900' not in текст, \
            f"{модуль.__name__} снова теряет ноль"
        assert "model_idle_unload_s" in текст

    from asrhub import settings_access as S
    assert S.integer({"model_idle_unload_s": 0}, "model_idle_unload_s", 900) == 0
    assert S.integer({}, "model_idle_unload_s", 900) == 900


@pytest.mark.parametrize("ключ,было,стало", [
    ("audio_denoise", "demucs", "none"),
    ("punctuation_model", "vosk-punct", "auto"),
    ("itn_backend", "runorm", "auto"),
])
def test_настройки_без_кода_убраны_а_сохранённые_переведены(ключ, было, стало):
    """Три варианта показывались в интерфейсе и не делали ничего.

    `demucs` не попадал в цепочку фильтров ffmpeg, `vosk-punct` и `runorm`
    не совпадали ни с одной веткой выбора обработчика. Человек выбирал
    извлечение вокала, получал запись без обработки и нигде не видел
    почему — при том что для честно недоступных надстроек предупреждение
    в сервере есть, просто эти три до него не доходили.
    """
    from asrhub.catalog.params import coerce_value, get_param, validate_value

    возможные = {в["value"] for в in (get_param(ключ).options or [])}
    assert было not in возможные, f"«{было}» всё ещё предлагается в интерфейсе"
    assert validate_value(ключ, было)[0] is False
    # Сохранённое значение не роняет сервер, а переводится на работающее.
    assert coerce_value(ключ, было) == стало
    assert validate_value(ключ, стало)[0] is True
