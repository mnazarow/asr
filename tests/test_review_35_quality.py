def test_перекрытие_фрагментов_не_задваивает_слова():
    """Справочник обещает: «дубликаты в зоне перекрытия убираются».

    Убирать их было некому. При перекрытии в секунду и фрагментах по
    двадцать пять секунд это по секунде лишнего текста на каждом стыке —
    повторённые слова посреди фразы, примерно четыре процента расшифровки.
    """
    from asrhub.engines.base import Segment
    from asrhub.pipeline.stitch import убрать_повторы

    первый = Segment(0.0, 25.0, "мы вам перезвоним завтра утром", words=[
        {"word": "мы", "start": 1.0, "end": 1.3},
        {"word": "вам", "start": 1.4, "end": 1.7},
        {"word": "перезвоним", "start": 23.0, "end": 23.6},
        {"word": "завтра", "start": 24.2, "end": 24.4},
        {"word": "утром", "start": 24.6, "end": 24.9}])
    второй = Segment(24.0, 49.0, "завтра утром хорошо спасибо", words=[
        {"word": "завтра", "start": 24.2, "end": 24.4},
        {"word": "утром", "start": 24.6, "end": 24.9},
        {"word": "хорошо", "start": 26.0, "end": 26.4},
        {"word": "спасибо", "start": 27.0, "end": 27.5}])
    сшито = убрать_повторы([первый, второй], 1.0)
    слова = " ".join(с.text for с in сшито).split()
    assert слова.count("завтра") == 1 and слова.count("утром") == 1, слова
    assert слова == ["мы", "вам", "перезвоним", "завтра", "утром",
                     "хорошо", "спасибо"], слова


def test_сшивка_без_меток_слов_идёт_по_тексту():
    """У GigaAM без меток слов отрезок — это весь текст фрагмента."""
    from asrhub.engines.base import Segment
    from asrhub.pipeline.stitch import убрать_повторы

    сшито = убрать_повторы([Segment(0.0, 25.0, "счёт будет оплачен во вторник"),
                            Segment(24.0, 49.0, "во вторник хорошо до свидания")], 1.0)
    assert [с.text for с in сшито] == ["счёт будет оплачен во вторник",
                                       "хорошо до свидания"]


def test_сшивка_не_трогает_настоящий_повтор_в_речи():
    """«Да, да» человек и правда говорит дважды — резать это нельзя.

    Без перекрытия (`chunk_overlap_s: 0`) фрагменты встык, и любое
    совпадение слов на стыке — настоящая речь.
    """
    from asrhub.engines.base import Segment
    from asrhub.pipeline.stitch import убрать_повторы

    # Фрагменты пересекаются по времени, но резали их встык: перекрытие
    # нулевое, значит совпадение слов на стыке — настоящая речь, а не след
    # нарезки. Такое бывает у нарезки по речи: участки VAD склеиваются с
    # допуском и краями наезжают друг на друга.
    сшито = убрать_повторы([Segment(0.0, 25.0, "да да"),
                            Segment(24.0, 50.0, "да конечно")], 0.0)
    assert [с.text for с in сшито] == ["да да", "да конечно"]

    # И при перекрытии, если фрагменты по времени не пересекаются.
    сшито = убрать_повторы([Segment(0.0, 25.0, "хорошо"),
                            Segment(25.0, 50.0, "хорошо договорились")], 1.0)
    assert [с.text for с in сшито] == ["хорошо", "хорошо договорились"]


