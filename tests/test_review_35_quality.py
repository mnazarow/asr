def test_судя_по_всему_это_не_эскалация():
    """Основа у «судя» — «суд», та же, что у угрозы подать в суд.

    Вежливый оборот попадал в «Эскалацию» вместе с настоящими угрозами:
    разговор уезжал в отчёт по угрозам, поднимал напряжение записи и
    попадался руководителю на глаза как претензия.
    """
    from asrhub.content import categories

    def сработало(текст: str) -> list[str]:
        итог = categories.apply(
            [{"text": текст, "speaker": "клиент", "start": 0.0, "end": 3.0}],
            categories.ГОТОВЫЕ, customer="клиент")
        return [к["id"] for к in (итог.get("items") or [])]

    assert сработало("Судя по всему, заказ потерялся") == []
    assert сработало("Судя по описанию, это другая модель") == []
    # А настоящая угроза по-прежнему слышна, во всех падежах.
    for угроза in ("Я подам в суд", "Встретимся в суде", "Дойду до суда",
                   "Буду судиться", "Это судебный спор"):
        assert "escalation" in сработало(угроза), угроза


def test_так_вышло_это_не_следующий_шаг():
    """Основа «вышл» одна у «вышлю» и у «вышло».

    Пункт скрипта «Назвал следующий шаг» засчитывался оператору за «так
    вышло» и «вышло недоразумение» — за слова, которые никакого шага не
    называют. Оценка соблюдения скрипта — то, по чему считают премию.
    """
    from asrhub.content import compliance

    def пункт(текст: str) -> bool:
        итог = compliance.check(
            [{"text": текст, "speaker": "оператор", "start": 0.0, "end": 3.0}],
            speaker="оператор")
        пункты = итог["items"] if isinstance(итог, dict) else итог
        return bool([п for п in пункты if п["id"] == "next_step"][0]["passed"])

    assert пункт("Ну так вышло, извините") is False
    assert пункт("Вышло недоразумение") is False
    # Настоящие обещания на месте.
    for обещание in ("Я вышлю вам договор", "Мы вышлем счёт завтра",
                     "Я перезвоню после обеда", "Уточню и свяжемся"):
        assert пункт(обещание) is True, обещание


def test_примета_в_кавычках_ищется_по_точной_форме():
    """Кавычки в списке примет — то же, что в правиле.

    Без них некоторые приметы записать было нечем: по основам «вышлю» и
    «вышло» не разводятся никакими списками.
    """
    from asrhub.content import rules

    дерево = rules.parse_any(['"вышлю"', "отправлю"])
