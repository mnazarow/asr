def _разговор(*пары: tuple[str, str], шаг: float = 6.0) -> list[dict]:
    реплики, время = [], 0.0
    for кто, текст in пары:
        реплики.append({"start": время, "end": время + шаг,
                        "speaker": кто, "text": текст})
        время += шаг
    return реплики


@pytest.mark.parametrize("реплика", [
    "Лучше скажите, когда приедет заказ 3, вот это важно.",
    "А доставка будет десять дней?",
    "Мне это обошлось в 7 рублей лишних.",
])
def test_посторонее_число_не_становится_оценкой(реплика: str):
    """«Названный балл» — единственное число раздела, объявленное НЕ предсказанным.

    Годилось любое число от 0 до 10 в любой последующей реплике клиента, и
    разговор, где клиент отказался оценивать, давал «клиент назвал 3»,
    группу «критик» и уверенность 1,0 — то есть выдуманный отзыв, поданный
    как сказанный вслух. По такому «отзыву» разбирают работу оператора.
    """
    from asrhub.content import indices

    разговор = _разговор(
        ("оператор", "Оцените нашу работу по десятибалльной шкале."),
        ("клиент", "Да не хочу я ничего оценивать, некогда мне."),
        ("оператор", "Хорошо, понял вас."),
        ("клиент", реплика))
    слова = indices.words(indices._текст(разговор))
    assert indices._названный_балл(разговор, слова, "клиент") is None

    итог = indices.nps(разговор, настроение_={"end": 0.0, "score": 0.0},
                       усилие_={"score": 0.0, "markers": []},
                       стресс_={"index": 0}, решено=None, клиент="клиент")
    assert итог["predicted"] is True, "выдуманный балл подан как названный"


