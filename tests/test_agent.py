def test_сбор_за_период_читает_журнал_с_начала(tmp_path: Path):
    """«Собрать за прошлый месяц» на станции, где обычный заход уже всё дочитал.

    Позиция чтения стоит в конце файла, и если сбор за период пойдёт от
    неё, он не найдёт ни одного звонка — при совершенно исправном журнале.
    А сдвинуть позицию он не имеет права: свежие звонки после этого
    пропали бы совсем.
    """
    старый = time.mktime((2026, 8, 15, 12, 0, 0, 0, 0, -1))
    журнал = (строка_cdr("u.1", начало=старый)
              + строка_cdr("u.2", dst="102", начало=старый + 600))
    with Станция() as станция:
        агент_станции = стенд(tmp_path, станция.адрес, журнал)
        try:
            агент_станции.поздороваться()
            # Обычный заход дочитал журнал до конца и ничего не отправил:
            # звонки старше окна отсеются только по периоду, поэтому здесь
            # они уезжают — важно, что позиция встала в конец.
            агент_станции.проход("new")
            позиция = агент_станции.состояние.позиция(
                str(tmp_path / "Master.csv"))["offset"]
            станция.известные.clear()
            станция.принятые.clear()
            агент_станции.состояние.данные["отправленные"] = []
            агент_станции.состояние._множество = set()
            свод = агент_станции.проход("period", старый - 60, старый + 3600)
        finally:
            агент_станции.закрыть()
    assert свод["отправлено"] == 2, "период не прочитал журнал заново"
    assert агент_станции.состояние.позиция(
        str(tmp_path / "Master.csv"))["offset"] == позиция, \
        "сбор за период сдвинул позицию обычного захода"


