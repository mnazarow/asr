def test_отбор_по_периоду():
    """--since и --until отсекают звонок по времени начала, а не по файлу."""
    момент = time.mktime((2026, 9, 10, 14, 0, 0, 0, 0, -1))
    звонок = агент.разобрать_строку_cdr(строка_cdr("1757500005.5", начало=момент))
    сутки = 86400
    assert агент.причина_пропуска(звонок, начало=момент - сутки,
                                  конец=момент + сутки) == ""
    assert агент.причина_пропуска(звонок, начало=момент + 60) == "раньше периода"
    assert агент.причина_пропуска(звонок, конец=момент - 60) == "позже периода"


def test_короткие_и_неотвеченные_отсеиваются_на_станции():
    """Отсев именно здесь: запись неотвеченного звонка весит столько же."""
    короткий = агент.разобрать_строку_cdr(
        строка_cdr("1757500006.6", duration=8, billsec=5))
    без_ответа = агент.разобрать_строку_cdr(
        строка_cdr("1757500007.7", disposition="NO ANSWER", billsec=0))
    assert агент.причина_пропуска(короткий, минимум=10) == "короткий"
    assert агент.причина_пропуска(без_ответа) == "без ответа"
    # А если расположения нет вовсе (источник «каталог записей»), звонок
    # не считается неотвеченным: иначе отбрасывался бы весь архив.
    свой = агент.Звонок(uniqueid="file-1", started_at=time.time())
    assert агент.причина_пропуска(свой) == ""


