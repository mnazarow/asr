def test_позиция_переживает_дописывание(tmp_path: Path):
    """Второй заход не должен перечитывать то, что уже отправлено."""
    журнал = tmp_path / "Master.csv"
    журнал.write_text(строка_cdr("a.1"), encoding="utf-8")
    состояние_агента = состояние(tmp_path)
    источник = агент.ИсточникCSV([str(журнал)], состояние_агента)

    первые = list(источник.звонки())
    assert [з.uniqueid for з in первые] == ["a.1"]
    позиция = состояние_агента.позиция(str(журнал))
    assert позиция["offset"] == журнал.stat().st_size

    with журнал.open("a", encoding="utf-8") as файл:
        файл.write(строка_cdr("a.2", dst="102"))
    вторые = list(источник.звонки())
    assert [з.uniqueid for з in вторые] == ["a.2"], "журнал перечитан целиком"


def test_недописанная_строка_остаётся_следующему_заходу(tmp_path: Path):
    """Строку без перевода строки станция ещё дописывает — брать её рано."""
    журнал = tmp_path / "Master.csv"
    хвост = строка_cdr("b.2", dst="102")
    журнал.write_text(строка_cdr("b.1") + хвост[:40], encoding="utf-8")
    состояние_агента = состояние(tmp_path)
    источник = агент.ИсточникCSV([str(журнал)], состояние_агента)
    assert [з.uniqueid for з in источник.звонки()] == ["b.1"]

    with журнал.open("a", encoding="utf-8") as файл:
        файл.write(хвост[40:])
    assert [з.uniqueid for з in источник.звонки()] == ["b.2"]


def test_ротация_журнала_читается_с_начала(tmp_path: Path):
    """Журнал повернули — файл стал короче, и читать надо с начала.

    Без этого всё, что станция напишет в новый файл до прежней позиции,
    не приедет на сервер никогда, а понять почему по журналу нельзя.
    """
    журнал = tmp_path / "Master.csv"
    журнал.write_text("".join(строка_cdr(f"c.{i}") for i in range(5)),
                      encoding="utf-8")
    состояние_агента = состояние(tmp_path)
    источник = агент.ИсточникCSV([str(журнал)], состояние_агента)
    assert len(list(источник.звонки())) == 5

