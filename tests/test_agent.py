def установщик_в_песочнице(tmp_path: Path) -> Path:
    """Копия установщика, у которой все системные пути ведут в tmp_path.

    Настоящие /opt, /etc и /var трогать в проверках нельзя, а проверять
    установщик «по частям» бессмысленно: он и состоит из склейки этих
    частей — именно там ломается.
    """
    корень = tmp_path / "система"
    for каталог in ("etc/systemd", "var/log", "var/lib", "opt", "bin"):
        (корень / каталог).mkdir(parents=True, exist_ok=True)
    текст = ФАЙЛ_УСТАНОВЩИКА.read_text(encoding="utf-8")
    замены = {
        'INSTALL_DIR="/opt/asrhub-agent"': f'INSTALL_DIR="{корень}/opt/asrhub-agent"',
        'CONFIG_FILE="/etc/asrhub-agent.conf"': f'CONFIG_FILE="{корень}/etc/asrhub-agent.conf"',
        'STATE_DIR="/var/lib/asrhub-agent"': f'STATE_DIR="{корень}/var/lib/asrhub-agent"',
        'LOG_FILE="/var/log/asrhub-agent.log"': f'LOG_FILE="{корень}/var/log/asrhub-agent.log"',
        'UNIT_FILE="/etc/systemd/system/${SERVICE_NAME}.service"':
            f'UNIT_FILE="{корень}/etc/systemd/${{SERVICE_NAME}}.service"',
        'check_writable "/etc"': f'check_writable "{корень}/etc"',
        "ReadWritePaths=${STATE_DIR} /var/log":
            f"ReadWritePaths=${{STATE_DIR}} {корень}/var/log",
    }
    for было, стало in замены.items():
        assert было in текст, f"в установщике не нашлось: {было}"
        текст = текст.replace(было, стало)
    путь = tmp_path / "install.sh"
    путь.write_text(текст, encoding="utf-8")
    # Поддельный systemctl: в песочнице настоящего systemd нет, а пройти
    # ветку со службой надо целиком.
    systemctl = корень / "bin" / "systemctl"
    systemctl.write_text('#!/bin/sh\necho "systemctl $*" >>"${SYSTEMCTL_LOG}"\nexit 0\n',
                         encoding="utf-8")
    systemctl.chmod(0o755)
    return путь


