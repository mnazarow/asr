def разобрать_части(тип: str, тело: bytes) -> dict:
    """Разбирает multipart/form-data так же, как это сделает сервер."""
    совпадение = re.search(r"boundary=([^;]+)", тип)
    assert совпадение, f"в Content-Type нет границы: {тип}"
    граница = совпадение.group(1).strip().strip('"').encode()
    части = {}
    for кусок in тело.split(b"--" + граница):
        if кусок in (b"", b"--", b"--\r\n", b"\r\n"):
            continue
        голова, _, содержимое = кусок.lstrip(b"\r\n").partition(b"\r\n\r\n")
        заголовки = голова.decode("utf-8", "replace")
        имя = re.search(r'name="([^"]+)"', заголовки)
        if not имя:
            continue
        файл = re.search(r'filename="([^"]+)"', заголовки)
        if содержимое.endswith(b"\r\n"):
            содержимое = содержимое[:-2]
        части[имя.group(1)] = (файл.group(1) if файл else None, содержимое)
    return части


class Станция:
    """Поддельный сервер ASR Hub: четыре адреса из контракта агента."""

    def __init__(self, известные=(), команда: str = ""):
        self.известные = set(известные)
        self.принятые: list[dict] = []
        self.спрошенные: list[list[str]] = []
        self.ключи: list[str] = []
        self.команда = команда
        self.попытки: dict[str, int] = {}
        #: Что ответить вместо успеха: путь → список кодов HTTP подряд.
        self.сбои: dict[str, list[int]] = {}
        self.max_file_mb = 2048
        self.min_duration_s = 0
        self.skip_unanswered = False
        self.enabled = True
        self.сдвиг_часов = 0.0
        self._сервер = None
        self._поток = None

    # --- запуск -----------------------------------------------------------

    def __enter__(self):
        станция = self

        class Обработчик(BaseHTTPRequestHandler):
            def log_message(self, *_аргументы):             # тишина в выводе
                return

            def _тело(self):
                длина = int(self.headers.get("Content-Length") or 0)
                return self.rfile.read(длина) if длина else b""

            def _ответ(self, код: int, данные: dict):
                тело = json.dumps(данные, ensure_ascii=False).encode()
                self.send_response(код)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(тело)))
                self.end_headers()
                self.wfile.write(тело)

            def _сбой(self, путь: str):
                коды = станция.сбои.get(путь) or []
                if not коды:
                    return False
                код = коды.pop(0)
                self._ответ(код, {"code": "config_error",
                                  "message": f"поддельный отказ {код}",
                                  "hint": "так задумано в проверке"})
                return True

            def do_GET(self):                                # noqa: N802
                путь = urlparse(self.path).path
                станция.попытки[путь] = станция.попытки.get(путь, 0) + 1
                станция.ключи.append(self.headers.get("X-API-Key") or "")
                if self._сбой(путь):
                    return
                if путь in ("/api/health", "/health"):
                    self._ответ(200, {"status": "ok"})
                    return
                if путь == "/api/telephony/agent/asrhub-agent.py":
                    тело = ФАЙЛ_АГЕНТА.read_bytes()
                    self.send_response(200)
                    self.send_header("Content-Type", "text/x-python; charset=utf-8")
                    self.send_header("Content-Length", str(len(тело)))
                    self.end_headers()
                    self.wfile.write(тело)
                    return
                if путь == "/api/telephony/agent/command":
                    parse_qs(urlparse(self.path).query)
                    команда, станция.команда = станция.команда, ""
                    self._ответ(200, {"command": команда,
                                      "server_time": time.time()})
                    return
                self._ответ(404, {"code": "not_found", "message": "нет такого"})

            def do_POST(self):                               # noqa: N802
                путь = urlparse(self.path).path
                тело = self._тело()
                станция.попытки[путь] = станция.попытки.get(путь, 0) + 1
                станция.ключи.append(self.headers.get("X-API-Key") or "")
                if self._сбой(путь):
                    return
                if путь == "/api/telephony/agent/hello":
                    данные = json.loads(тело or b"{}")
                    self._ответ(200, {
                        "agent_id": данные.get("agent_id") or "pbx-test01",
                        "station": "agent:pbx-test01",
                        "server_time": time.time() + станция.сдвиг_часов,
                        "max_file_mb": станция.max_file_mb,
                        "want_audio": True,
                        "command": станция.команда,
                        "enabled": станция.enabled,
                        "min_duration_s": станция.min_duration_s,
                        "skip_unanswered": станция.skip_unanswered})
                    return
                if путь == "/api/telephony/agent/ask":
                    данные = json.loads(тело or b"{}")
                    ids = [str(и) for и in (данные.get("ids") or [])]
                    станция.спрошенные.append(ids)
                    нужны = [и for и in ids if и not in станция.известные]
                    self._ответ(200, {"wanted": нужны,
                                      "known": len(ids) - len(нужны)})
                    return
                if путь == "/api/telephony/agent/call":
                    части = разобрать_части(
                        self.headers.get("Content-Type") or "", тело)
                    if "meta" not in части:
                        self._ответ(400, {"code": "config_error",
                                          "message": "нет поля meta"})
                        return
                    поля = json.loads(части["meta"][1].decode("utf-8"))
                    запись = части.get("file")
                    станция.принятые.append({
                        "meta": поля,
                        "имя_файла": запись[0] if запись else None,
                        "байт": len(запись[1]) if запись else 0})
                    станция.известные.add(str(поля.get("uniqueid")))
                    self._ответ(200, {"ok": True, "uniqueid": поля.get("uniqueid"),
                                      "job_id": f"job_{len(станция.принятые)}"})
                    return
                self._ответ(404, {"code": "not_found", "message": "нет такого"})

        self._сервер = ThreadingHTTPServer(("127.0.0.1", 0), Обработчик)
        self._поток = threading.Thread(target=self._сервер.serve_forever,
                                       daemon=True)
        self._поток.start()
        return self

    def __exit__(self, *_):
        self._сервер.shutdown()
        self._сервер.server_close()
        self._поток.join(timeout=5)
        return False

    @property
    def адрес(self) -> str:
        хост, порт = self._сервер.server_address[:2]
        return f"http://{хост}:{порт}"


def параметры(tmp_path: Path, адрес: str, *ключи: str) -> dict:
    """Настройки агента так, как их собрала бы командная строка."""
    разбор = агент.собрать_аргументы()
    аргументы = разбор.parse_args([
        "--url", адрес, "--key", "ah_test1234567890",
        "--state-dir", str(tmp_path / "state"),
        "--log-file", str(tmp_path / "agent.log"),
        "--cdr-file", str(tmp_path / "Master.csv"),
        "--recordings-dir", str(tmp_path / "monitor"),
        "--source", "cdr_csv", "--retries", "1",
        *ключи])
    return агент.собрать_параметры(аргументы, {})


