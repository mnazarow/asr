СЕЙЧАС = time.time() - 600


def строка_cdr(uid: str, src: str = "79161234567", dst: str = "101",
               disposition: str = "ANSWERED", duration: int = 300,
               billsec: int = 290, *, context: str = "from-trunk",
               clid: str | None = None, lastapp: str = "Queue",
               lastdata: str = "sales,t", начало: float = СЕЙЧАС,
               колонок: int = 19) -> str:
    """Строка Master.csv в том виде, в каком её пишет Asterisk.

    По умолчанию девятнадцать колонок — с вторым `accountcode` перед
    идентификатором, как в задании. Восемнадцатиколоночная раскладка тоже
    встречается, и агент обязан разбирать обе.
    """
    н = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(начало))
    к = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(начало + duration))
    имя = clid if clid is not None else f'"""Клиент, отдел продаж"" <{src}>"'
    второй_код = '"",' if колонок == 19 else ""
    return (f'"","{src}","{dst}","{context}",{имя},"SIP/tr-01","SIP/{dst}",'
            f'"{lastapp}","{lastdata}","{н}","{н}","{к}",{duration},{billsec},'
            f'"{disposition}","DOCUMENTATION",{второй_код}"{uid}",""\n')


def wav(путь: Path, секунд: int = 1) -> Path:
    путь.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(8000)
        файл.writeframes(b"\x01\x02" * (8000 * секунд))
    return путь


