"""Приём звонков от агента, поставленного на саму станцию.

Забор «изнутри» работает, только когда сервер распознавания видит файлы
АТС. В жизни станция чаще стоит отдельно — за NAT, в другом городе, — и
тогда звонок вместе с записью присылает агент, живущий на самой станции.
Наружу при этом не открывается ничего: связь всегда начинает агент.

Отсюда и то, за чем здесь следят. Через эти ручки в сервер заезжают файлы
и поля со стороны, которой сервер не управляет, а сам разговор агента с
сервером устроен так, что ошибка в любой из трёх его частей стоит дорого:

* агент, не узнанный после переустановки станции, заливает весь архив
  заново — десятки гигабайт по сети и вторая станция «agent:…» в отчётах;
* `/ask`, не отсеивающий известное, делает то же самое каждым сбором;
* `/call`, не убирающий за собой файл при отказе, копит на диске сервера
  записи, о которых не знает никто: в архиве их нет, в очереди нет, а
  место они занимают.

Проверки написаны по этим точкам, а не по «ручка ответила 200».
"""
from __future__ import annotations

import io
import json
import wave
from pathlib import Path

import pytest
from asrhub.api import create_app
from asrhub.api.routes_agent import ЗВУК
from asrhub.config import load
from fastapi.testclient import TestClient

АДМИН = {"X-API-Key": "ah_admin"}


def wav(секунд: int = 1) -> bytes:
    """Запись разговора: тишина нужной длины, важен только размер и заголовок."""
    буфер = io.BytesIO()
    with wave.open(буфер, "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(16000)
        файл.writeframes(b"\x00\x00" * (16000 * секунд))
    return буфер.getvalue()


@pytest.fixture()
def сервер(data_dir: Path, monkeypatch: pytest.MonkeyPatch):
    """Сервер с ключами трёх ролей и остановленной очередью."""
    monkeypatch.setenv("ASRHUB_MODEL", "demo-simulator")
    monkeypatch.setenv("ASRHUB_ENGINE", "demo")
    monkeypatch.setenv("ASRHUB_AUTH_ENABLED", "true")
    настройки = load()
    настройки.api_keys.update({
        "ah_admin": {"name": "админ", "role": "admin", "enabled": True},
        "ah_agent": {"name": "агент", "role": "user", "enabled": True},
        "ah_ro": {"name": "чтение", "role": "readonly", "enabled": True},
    })
    app = create_app(настройки, start_queue=False)
    with TestClient(app) as клиент:
        yield клиент


def здравствуй(клиент: TestClient, **поля) -> dict:
    """POST /hello с полями агента."""
    поля.setdefault("host", "pbx1.local")
    поля.setdefault("name", "Головная АТС")
    ответ = клиент.post("/api/telephony/agent/hello", headers=АДМИН, json=поля)
    assert ответ.status_code == 200, ответ.text
    return ответ.json()


def прислать(клиент: TestClient, agent_id: str, uniqueid: str, *,
             файл: tuple[str, bytes] | None = ("запись.wav", None), **поля):
    """POST /call: поля звонка обязательным JSON и запись — необязательным файлом."""
    поля = {"agent_id": agent_id, "uniqueid": uniqueid,
            "src": "79161234567", "dst": "101", "direction": "входящий",
            "duration": 40, "billsec": 30, "answered": True,
            "started_at": 1789000000.0, **поля}
    файлы = None
    if файл is not None:
        имя, содержимое = файл
        файлы = {"file": (имя, содержимое if содержимое is not None else wav(),
                          "audio/wav")}
    return клиент.post("/api/telephony/agent/call", headers=АДМИН,
                       data={"meta": json.dumps(поля)}, files=файлы)


def загрузки(клиент: TestClient) -> set[str]:
    """Что сейчас лежит в каталоге принятых файлов."""
    каталог = клиент.app.state.hub.settings.paths.uploads
    return {п.name for п in каталог.iterdir() if п.is_file()}


def звонки(клиент: TestClient, станция: str) -> list[dict]:
    return клиент.app.state.hub.db.list_calls(station=станция, limit=100)["calls"]


