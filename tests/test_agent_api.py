def test_звонок_с_записью_становится_заданием_и_строкой_архива(сервер: TestClient):
    """Главный путь: приехал звонок с записью — появилось задание и звонок.

    Строка звонка и задание связаны в обе стороны: `job_id` ведёт из архива
    в расшифровку, `recording` — к файлу на диске, `station` отделяет эту
    станцию от остальных, а `pbx_uid` хранит родной идентификатор со
    станции — по нему человек находит разговор в самой АТС. Потеря любого
    из четырёх полей превращает архив в список без связей.
    """
    agent_id = здравствуй(сервер)["agent_id"]
    станция = f"agent:{agent_id}"

    ответ = прислать(сервер, agent_id, "200.1", файл=("200.1.wav", wav(2)))

    assert ответ.status_code == 200, ответ.text
    тело = ответ.json()
    assert тело["ok"] is True and тело["job_id"]
    assert тело["bytes"] > 0

    строки = звонки(сервер, станция)
    assert len(строки) == 1, строки
    звонок = строки[0]
    assert звонок["uniqueid"] == f"{станция}:200.1"
    assert звонок["pbx_uid"] == "200.1"
    assert звонок["station"] == станция
    assert звонок["job_id"] == тело["job_id"]
    assert звонок["direction"] == "входящий" and звонок["billsec"] == 30
    assert Path(звонок["recording"]).is_file(), "запись не легла на диск"

    задание = сервер.app.state.hub.db.get_job(тело["job_id"])
    assert задание is not None and задание["status"] == "queued"


def test_счётчики_агента_растут_на_каждой_записи(сервер: TestClient):
    """Раздел «АТС» показывает, сколько агент прислал и сколько весит.

    Это единственная обратная связь о работе станции, до которой нельзя
    дотянуться: она за NAT. Счётчик, который не растёт, выглядит как
    «агент молчит» — и туда едут разбираться напрасно.
    """
    agent_id = здравствуй(сервер)["agent_id"]
    прислать(сервер, agent_id, "300.1", файл=("300.1.wav", wav(2)))
    прислать(сервер, agent_id, "300.2", файл=("300.2.wav", wav(1)))

    запись = сервер.app.state.hub.db.agent_get(agent_id)

    assert запись["calls_sent"] == 2
    assert запись["files_sent"] == 2
    assert запись["bytes_sent"] > 16000 * 3, запись["bytes_sent"]
    assert запись["errors"] == 0


def test_повторный_звонок_не_создаёт_второго_задания(сервер: TestClient):
    """Агент шлёт повторно после обрыва связи — и не должен задваивать архив.

    Обрыв на середине заливки — обычное дело для станции в другом городе:
    агент не знает, дошло ли, и шлёт ещё раз. Второе задание означало бы
    двойную расшифровку одного разговора, двойной счёт в аналитике и
    двойную запись на диске.
    """
    agent_id = здравствуй(сервер)["agent_id"]
    первый = прислать(сервер, agent_id, "400.1").json()

    второй = прислать(сервер, agent_id, "400.1")

    assert второй.status_code == 200, второй.text
    assert второй.json()["skipped"] == "уже импортирован"
    assert "job_id" not in второй.json()
    db = сервер.app.state.hub.db
    assert len(db.list_jobs(limit=50)) == 1, "создано второе задание"
    assert [з["uniqueid"] for з in звонки(сервер, f"agent:{agent_id}")] \
        == [f"agent:{agent_id}:400.1"]
    assert db.get_job(первый["job_id"]) is not None


def test_звонок_без_записи_попадает_в_архив_как_пропущенный(сервер: TestClient):
    """Разговор без записи — тоже разговор: он нужен в журнале и в разрезах.

    Выбросить его нельзя: счётчики станции разойдутся с её собственными, и
    «почему у нас в отчёте втрое меньше звонков» станет вопросом без
    ответа. Но и задание заводить не на что — распознавать нечего.
    """
    agent_id = здравствуй(сервер)["agent_id"]

    ответ = прислать(сервер, agent_id, "500.1", файл=None)

    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["skipped"] == "нет записи"
    строки = звонки(сервер, f"agent:{agent_id}")
    assert len(строки) == 1 and строки[0]["skipped"] == "нет записи"
    assert строки[0]["job_id"] is None
    assert сервер.app.state.hub.db.list_jobs(limit=50) == [], "заведено задание без записи"


