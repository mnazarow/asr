@pytest.mark.parametrize("плохой", [
    "../../etc/passwd", "../pbx", "pbx/../..", "агент", "pbx id", "a" * 65,
])
def test_идентификатор_с_путём_внутри_отвергается(сервер: TestClient, плохой: str):
    """Идентификатор приходит от агента — значит, это ввод.

    Он служит частью имени станции в архиве и частью адреса ручек, где
    подставляется в путь. Косые и точки в нём — это попытка собрать путь, и
    ответ обязан называть их прямо: «неизвестный агент» на такой строке —
    это приглашение сначала позвать `/hello` с ней же и завести станцию с
    именем `agent:../../etc/passwd`, которую потом не выключить и не
    удалить по имени.
    """
    отказ = сервер.post("/api/telephony/agent/call", headers=АДМИН,
                        data={"meta": json.dumps({"agent_id": плохой,
                                                  "uniqueid": "1.1"})})

    assert отказ.status_code == 400, отказ.text
    подробности = отказ.json()["detail"]
    assert подробности["code"] == "config_error"
    assert "Недопустимый идентификатор" in подробности["message"], подробности
    assert подробности["hint"], "отказ не говорит, каким идентификатор быть должен"

    # И завести такого агента тоже нельзя: иначе он станет «известным» и
    # первая проверка перестанет что-либо значить.
    заведение = сервер.post("/api/telephony/agent/hello", headers=АДМИН,
                            json={"agent_id": плохой, "host": "pbx1.local"})
    assert заведение.status_code == 400, заведение.text
    assert сервер.app.state.hub.db.agent_list() == []


