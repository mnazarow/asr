    assert поставлено.json()["command"] == "collect:all"

    первый = сервер.get(f"/api/telephony/agent/command?agent_id={agent_id}",
                        headers=АДМИН)
    assert первый.status_code == 200, первый.text
    assert первый.json()["command"] == "collect:all"

    второй = сервер.get(f"/api/telephony/agent/command?agent_id={agent_id}",
                        headers=АДМИН)
    assert второй.json()["command"] == "", "задание выдано во второй раз"


