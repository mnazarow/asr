def test_удаление_агента_не_трогает_присланные_им_звонки(сервер: TestClient):
    """Агента убирают, когда станцию вывели из работы. Разговоры при этом остаются.

    Иначе «убрать агента» означало бы стереть архив станции целиком —
    действие, которого никто не ожидает от строки в списке, и отменить его
    нельзя. Записи и расшифровки нужны и после того, как станции не стало.
    """
    agent_id = здравствуй(сервер)["agent_id"]
    станция = f"agent:{agent_id}"
    прислать(сервер, agent_id, "1200.1")
    прислать(сервер, agent_id, "1200.2", файл=None)
    было = звонки(сервер, станция)
    assert len(было) == 2

    удаление = сервер.delete(f"/api/telephony/agents/{agent_id}", headers=АДМИН)

    assert удаление.status_code == 200, удаление.text
    assert сервер.app.state.hub.db.agent_get(agent_id) is None
    стало = звонки(сервер, станция)
    assert [з["uniqueid"] for з in стало] == [з["uniqueid"] for з in было]
    assert [з["job_id"] for з in стало] == [з["job_id"] for з in было], \
        "звонки отвязались от расшифровок"
    assert len(сервер.app.state.hub.db.list_jobs(limit=50)) == 1


