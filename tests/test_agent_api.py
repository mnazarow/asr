    agent_id = здравствуй(сервер)["agent_id"]
    assert прислать(сервер, agent_id, "100.1").status_code == 200

    ответ = сервер.post("/api/telephony/agent/ask", headers=АДМИН,
                        json={"agent_id": agent_id,
                              "ids": ["100.1", "100.2", "100.3"]})

    assert ответ.status_code == 200, ответ.text
    assert ответ.json() == {"wanted": ["100.2", "100.3"], "known": 1}


