def test_повторное_приветствие_узнаёт_прежнего_агента(сервер: TestClient):
    """Потерянный файл состояния на станции не должен заводить второго агента.

    После переустановки станции агент приходит без идентификатора — ровно
    как новый. Выдать ему новый нельзя: архив получил бы вторую станцию
    «agent:…» с теми же разговорами, `/ask` перестал бы узнавать уже
    привезённое, и весь архив заехал бы по сети заново. На сорока тысячах
    разговоров это десятки гигабайт и сутки работы канала.

    Узнавание идёт по хосту и имени — единственному, что у агента остаётся
    после потери состояния.
    """
    первый = здравствуй(сервер)["agent_id"]

    второй = здравствуй(сервер)["agent_id"]

    assert второй == первый, "агенту выдан новый идентификатор вместо прежнего"
    assert len(сервер.app.state.hub.db.agent_list()) == 1, "в списке появился двойник"


