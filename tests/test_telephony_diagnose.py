"""Разбор забора с АТС: «звонков ноль» обязан превращаться в причину.

Заказчик сообщил ровно так: «скачивание с АТС не работает, ошибок не видно,
ноль звонков». Это худший из ответов — он выглядит как исправная работа, и
человеку не за что зацепиться. Модуль `telephony/diagnose.py` существует
затем, чтобы на этот вопрос всегда был ответ по существу: не «не
работает», а «журнал пишется не сюда», «имя файла записи без ${UNIQUEID}»,
«глубина просмотра короче возраста архива».

Поэтому проверки здесь написаны не про «разбор отработал», а про каждую
молчаливую причину по отдельности: подстраивается обстановка, при которой
забор молча не везёт ничего, и утверждается, что разбор её НАЗВАЛ — нужным
состоянием и подсказкой по делу. Разбор, который на любую поломку отвечает
«всё хорошо» или общим «что-то не так», бесполезен ровно настолько же,
насколько бесполезен был молчаливый заход.

Отдельно закреплено, что разбор безобиден: он читает журнал и каталог, но
не двигает позицию чтения и не ставит заданий. Диагностика, которая сама
импортирует, — это не диагностика, а второй заход, и после неё уже нельзя
понять, что видел настоящий.

Помощники (станция, журнал Master.csv, wav-файл) берутся из
`test_telephony`: формат строки Master.csv должен быть один на оба набора
проверок, иначе однажды разойдётся именно он, а не то, что мы проверяем.
"""
