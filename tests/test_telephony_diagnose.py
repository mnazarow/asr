def test_журнал_без_права_на_чтение_подсказывает_права(tmp_path: Path,
                                                       monkeypatch: pytest.MonkeyPatch):
    """Файл есть, но пользователь сервера его не читает.

    Каталог `/var/log/asterisk` обычно закрыт от посторонних, а сервер
    распознавания работает не от root. Без отдельной проверки это выглядит
    точно так же, как «журнал пуст»: строк ноль, ошибок ноль. Разбор обязан
    отличать «нечего читать» от «не дают читать» — чинятся они по-разному.

    Права подделываются подменой `os.access`, а не `chmod`: проверки часто
    идут от root, которому файловая система разрешает всё, и `chmod 000`
    ничего бы не доказал.
    """
    db, _, импортёр = стенд(tmp_path, строка_cdr("r.1", "79161234567", "101"))
    журнал = tmp_path / "Master.csv"
    настоящий = os.access

    def без_чтения(путь, режим, **прочее):
        if Path(путь) == журнал and режим == os.R_OK:
            return False
        return настоящий(путь, режим, **прочее)

    monkeypatch.setattr(os, "access", без_чтения)

    файл = проверка(диагноз(импортёр), "cdr_file")

    assert файл["state"] == "fail", файл
    assert "нет доступа на чтение" in файл["value"]
    assert "chmod" in файл["hint"], "подсказка не показывает, чем чинить"


