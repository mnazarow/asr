def test_все_записи_старше_глубины_просмотра(tmp_path: Path):
    """Настоящая тихая причина «ноль звонков» у источника «каталог записей».

    Глубина просмотра по умолчанию — семь дней, а архив, который ставят
    забирать, обычно старше: его копят месяцами. Заход честно обходит
    каталог, отбрасывает каждый файл по возрасту и ничего не находит —
    ошибок нет, звонков нет. Разбор обязан сказать, что дело в глубине, и
    назвать число, до которого её надо поднять: считать возраст архива
    руками никто не станет.
    """
    db, импортёр = разбор_каталога(tmp_path, lookback_days=7)
    запись = wav(tmp_path / "monitor" / "старая.wav")
    состарить(запись, дней=40)

    итог = диагноз(импортёр)
    каталог = проверка(итог, "dir")
    глубина = проверка(итог, "dir_recent")

    assert каталог["state"] == "ok", "каталог с файлом объявлен пустым"
    assert глубина["state"] == "fail", глубина
    assert глубина["details"]["fresh"] == 0
    assert глубина["details"]["total"] == 1
    assert "Глубину просмотра" in глубина["hint"]
    assert "41 дней" in глубина["hint"], "подсказка не называет, до чего поднимать"
    assert итог["state"] == "fail"


