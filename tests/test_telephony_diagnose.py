def test_маршрут_разбора_отдаёт_состояние_и_проверки(сервер: TestClient):
    """POST /api/telephony/diagnose — то, что открывает раздел «АТС».

    Ответ обязан нести и общее состояние, и приговор словами, и список
    проверок: интерфейс рисует по нему строки, а человек читает приговор.
    Ответ без `checks` превращает разбор обратно в «не работает».
    """
    ответ = сервер.post("/api/telephony/diagnose?station=pbx",
                        headers={"X-API-Key": "ah_admin"})

    assert ответ.status_code == 200, ответ.text
    тело = ответ.json()
    assert тело["state"] in ("ok", "warn", "fail")
    станции = тело["stations"]
    assert [с["station"] for с in станции] == ["pbx"]
    разбор = станции[0]
    assert разбор["verdict"], "разбор не назвал причину словами"
    ключи = {п["id"] for п in разбор["checks"]}
    assert {"cdr_file", "cdr_position", "cdr_parse", "rec_dir"} <= ключи, ключи
    # Каталог записей пуст — разбор обязан объявить это поломкой, а не
    # отвечать «всё хорошо, звонков нет».
    assert тело["failed"] >= 1 and тело["state"] == "fail"


