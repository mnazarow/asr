    for _ in range(2):
        assert сервер.post("/api/telephony/diagnose?station=pbx",
                           headers={"X-API-Key": "ah_admin"}).status_code == 200

    assert db.get_kv("telephony_cdr_offset:pbx", 0) == было
    assert db.call_counts()["total"] == 0
    assert db.list_jobs(limit=10) == []
