def проверка(итог: dict, ид: str) -> dict:
    """Одна проверка разбора по её ключу.

    Отдельной функцией, потому что отсутствие проверки — это тоже поломка
    разбора, и сообщение об этом должно быть внятным, а не `StopIteration`
    посреди утверждения.
    """
    найдено = [п for п in итог["checks"] if п["id"] == ид]
    assert найдено, (f"разбор не сделал проверки «{ид}»; сделаны: "
                     + ", ".join(п["id"] for п in итог["checks"]))
    return найдено[0]


def состарить(путь: Path, дней: float) -> None:
    """Сдвигает время изменения файла в прошлое.

    Возраст журнала и записей — половина всех молчаливых причин, а ждать
    сутки в проверке нельзя.
    """
    когда = time.time() - дней * СУТКИ
    os.utime(путь, (когда, когда))


