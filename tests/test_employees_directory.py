def test_csv_в_cp1251_с_точкой_с_запятой():
    """Excel в русской локали пишет именно так: cp1251 и «;».

    Запятая в такой выгрузке занята под десятичный разделитель, а
    определение кодировки «на глазок» даёт кракозябры вместо фамилий.
    """
    выгрузка = ("работает;фамилия;имя;отчество;отдел;тел. внутренний\r\n"
                "да;Кузнецова;Анна;Петровна;Склад;1051\r\n"
                "нет;Фёдоров;Илья;;Продажи;1052\r\n").encode("cp1251")
    разбор = employees.разобрать_подробно(выгрузка)
    assert разбор.формат == "csv"
    люди = по_фамилии(разбор.записи)
    assert люди["Кузнецова"]["middle_name"] == "Петровна"
    assert люди["Кузнецова"]["active"] == 1
    assert люди["Фёдоров"]["active"] == 0, "«нет» — это уволен"
    assert "Фёдоров" in люди, "ё в фамилии не трогаем"


def test_csv_с_запятыми_и_табуляцией_тоже_читается():
    через_запятую = "фамилия,имя,отдел\nИванов,Иван,Продажи\n".encode()
    через_табуляцию = "фамилия\tимя\tотдел\nПетров\tПётр\tСклад\n".encode()
    assert employees.разобрать(через_запятую)[0]["department"] == "Продажи"
    assert employees.разобрать(через_табуляцию)[0]["department"] == "Склад"


def test_json_принимается_и_списком_и_обёрткой():
    списком = json.dumps([
        {"фамилия": "Иванов", "имя": "Иван", "внутренний": "1070"}]).encode()
