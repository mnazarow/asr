def test_ss_index_не_даёт_полям_съехать():
    """Главная проверка разбора: пропуск `ss:Index` сдвигает всю строку.

    У Марии не заполнен рабочий телефон, и Excel вместо пустой ячейки
    ставит `ss:Index="9"` на внутреннем номере. Без уважения к атрибуту
    внутренний номер оказался бы в рабочем телефоне, мобильный — во
    внутреннем, а почта — в мобильном; импорт при этом прошёл бы успешно.
    """
    мария = по_фамилии(employees.разобрать(ОБРАЗЕЦ))["Петрова (ЧЛБ)"]
    assert мария["phone_work"] == "", "рабочего телефона в выгрузке нет"
    assert мария["phone_ext"] == "1043"
    assert мария["phone_mobile"] == "+79123456789"
    assert мария["email"] == "maria@example.com"


