class Настройки(dict):
    """Настройки-пустышка: только `get`, как у обслуживания."""

    def get(self, ключ, по_умолчанию=None):                  # noqa: A003
        return dict.get(self, ключ, по_умолчанию)


def test_расписание_обновляет_справочник(tmp_path, портал):
    from asrhub import maintenance

    db = база(tmp_path)
    настройки = Настройки(employees_sync_enabled=True,
                          employees_url=портал.адрес + "/employees.xml",
                          employees_sync_hours=24)
    # Первый заход только ставит отметку: сервер только поднялся.
    assert maintenance._справочник(db, настройки) is None
    db.set_kv(maintenance.KV_EMPLOYEES, 1.0)
    итог = maintenance._справочник(db, настройки)
    assert итог and итог["added"] == 2
    assert db.employee_by_ext("1043") is not None
    assert any(с["kind"] == "employees_synced" for с in db.get_events())


