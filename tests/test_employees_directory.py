def по_фамилии(записи: list[dict]) -> dict[str, dict]:
    return {з["last_name"]: з for з in записи}


class Портал:
    """Веб-сервер на localhost, отдающий выгрузку по ссылке.

    Нужен там, где проверяется именно загрузка: подменять `urlopen` значит
    проверять подмену, а не то, что сервер умеет скачать файл.
    """

    def __init__(self, ответы: dict[str, bytes]):
        тело = dict(ответы)

        class Ручка(http.server.BaseHTTPRequestHandler):
            def do_GET(self):                                # noqa: N802
                if self.path.startswith("/redirect-to-file"):
                    self.send_response(302)
                    self.send_header("Location", "file:///etc/passwd")
                    self.end_headers()
                    return
                if self.path == "/big":
                    кусок = b"x" * 65536
                    self.send_response(200)
                    self.send_header("Content-Length", str(len(кусок) * 48))
                    self.end_headers()
                    for _ in range(48):
                        self.wfile.write(кусок)
                    return
                данные = тело.get(self.path)
                if данные is None:
                    self.send_response(404)
                    self.end_headers()
                    return
                self.send_response(200)
                self.send_header("Content-Length", str(len(данные)))
                self.end_headers()
                self.wfile.write(данные)

            def log_message(self, *args):                    # noqa: A003
                pass

        class Сервер(socketserver.TCPServer):
            allow_reuse_address = True

            def handle_error(self, request, client_address):
                """Обрыв соединения — это и есть проверяемое поведение.

                Когда загрузка упирается в предел размера, сервер перестаёт
                читать, и отдающая сторона получает «broken pipe». Печатать
                на это след вызовов посреди прогона незачем.
                """

        self._сервер = Сервер(("127.0.0.1", 0), Ручка)
        self.порт = self._сервер.server_address[1]
        self.адрес = f"http://127.0.0.1:{self.порт}"
        self._поток = threading.Thread(target=self._сервер.serve_forever,
                                       daemon=True)
        self._поток.start()

    def закрыть(self) -> None:
        self._сервер.shutdown()
        self._сервер.server_close()


@pytest.fixture()
def портал():
    сервер = Портал({"/employees.xml": ОБРАЗЕЦ})
    yield сервер
    сервер.закрыть()


