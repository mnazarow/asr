def test_внешняя_сущность_не_подставляется():
    """XXE: файл приезжает извне, и `file:///etc/passwd` в нём — нападение.

    Проверяется не только то, что содержимое файла не попало в карточку,
    но и то, что разбор отказался целиком: молча разобранный документ с
    объявлением типа означал бы, что защита держится на везении.
    """
    нападение = ("<?xml version=\"1.0\"?>\n"
                 '<!DOCTYPE foo [ <!ENTITY xxe SYSTEM "file:///etc/passwd"> ]>\n'
                 '<Workbook xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">'
                 '<Worksheet ss:Name="a"><Table>'
                 + строка("фамилия", "имя")
                 + "<Row>" + "<Cell><Data>&xxe;</Data></Cell>"
                 + ячейка("Иван") + "</Row>"
                 + "</Table></Worksheet></Workbook>").encode("utf-8")
    with pytest.raises(ConfigError) as отказ:
        employees.разобрать(нападение)
    assert "DOCTYPE" in отказ.value.message
    assert "root:" not in отказ.value.message


def test_миллиард_смешков_не_разворачивается():
    """Вложенные сущности раздувают килобайт в гигабайты памяти.

    `ElementTree` разворачивает внутренние сущности сам и от этого не
    защищён — это задокументированная уязвимость стандартной библиотеки.
    Отказ на объявлении типа закрывает её целиком: объявить сущность
    больше негде.
    """
    бомба = (b'<?xml version="1.0"?>\n'
             b"<!DOCTYPE lolz [\n"
             b' <!ENTITY lol "lol">\n'
             b' <!ENTITY lol1 "&lol;&lol;&lol;&lol;&lol;&lol;&lol;&lol;&lol;&lol;">\n'
             b' <!ENTITY lol2 "&lol1;&lol1;&lol1;&lol1;&lol1;&lol1;&lol1;&lol1;&lol1;&lol1;">\n'
             b"]>\n"
             b"<Workbook><Worksheet><Table><Row><Cell><Data>&lol2;</Data></Cell>"
             b"</Row></Table></Worksheet></Workbook>")
    with pytest.raises(ConfigError) as отказ:
        employees.разобрать(бомба)
    assert "DOCTYPE" in отказ.value.message


def test_не_xml_объясняется_по_человечески():
    """Портал вместо файла отдал страницу входа — так и надо сказать."""
