    assert isinstance(тело["overrides"]["beam_size"], int), тело["overrides"]
    assert тело["overrides"]["temperature"] == pytest.approx(0.2)
    параметры = задание(сервер, готовое)["params"]
    assert параметры["beam_size"] == 5 and isinstance(параметры["beam_size"], int)
    assert параметры["temperature"] == pytest.approx(0.2)


