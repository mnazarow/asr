"""Повторное распознавание архива: POST /api/jobs/rescan.

Причина повтора почти всегда не в сбое, а в том, что изменилось вокруг:
вышла модель лучше, поправили словарь замен, включили разделение по
говорящим, сменили язык. Прежний архив при этом распознан по-старому, и
перебрать его по одной записи руками нельзя — их тысячи.

Отсюда и то, что здесь проверяется. Ручка принимает ввод снаружи и кладёт
его прямо в параметры задания, а отбор делает на сервере — то есть одна
кнопка способна поставить в очередь весь архив, в том числе чужой, и с
любыми параметрами. Каждая проверка закрывает один из способов сделать это
не так:

* переопределения проверяются каталогом ДО того, как поставлено первое
  задание: половина архива, поставленная с негодным параметром, — это
  часы работы впустую и очередь, которую потом разгребают руками;
* в параметры попадает только белый список полей: рядом с ними живут
  `webhook_url` и пути на диске;
* пустой отбор отвечает отказом, а не «раз ничего не выбрано — значит,
  всё»;
* чужие задания не перераспознаются: разрез по владельцу — единственное,
  что отделяет чужие разговоры от своих.
"""
from __future__ import annotations

import io
import math
import struct
import time
import wave
from pathlib import Path

import pytest
from asrhub.api import create_app
from asrhub.api.routes_jobs import ПОЛЯ_ПЕРЕРАСПОЗНАВАНИЯ
from asrhub.config import load
from fastapi.testclient import TestClient


def _wav() -> bytes:
    """Секунда тона: очередь не запущена, файл нужен только как файл."""
    буфер = io.BytesIO()
    with wave.open(буфер, "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(16000)
        файл.writeframes(b"".join(struct.pack("<h", int(3000 * math.sin(i / 8)))
                                  for i in range(16000)))
    return буфер.getvalue()


@pytest.fixture()
def сервер(data_dir: Path, monkeypatch: pytest.MonkeyPatch):
    """Сервер с тремя ключами и остановленной очередью.

    Очередь нарочно не запускаем: проверяется постановка заново, а не
    распознавание. С запущенной очередью демо-движок успевал бы увести
    задание из состояния «в очереди» прямо посреди утверждения.
    """
    monkeypatch.setenv("ASRHUB_MODEL", "demo-simulator")
    monkeypatch.setenv("ASRHUB_ENGINE", "demo")
    monkeypatch.setenv("ASRHUB_AUTH_ENABLED", "true")
    настройки = load()
    настройки.api_keys.update({
        "ah_admin": {"name": "админ", "role": "admin", "enabled": True},
        "ah_alice": {"name": "Алиса", "role": "user", "enabled": True},
        "ah_bob": {"name": "Боб", "role": "user", "enabled": True},
    })
    app = create_app(настройки, start_queue=False)
    with TestClient(app) as клиент:
        yield клиент


def завести(клиент: TestClient, ключ: str = "ah_alice", *, имя: str = "разговор.wav",
            состояние: str = "completed", **настройки) -> str:
    """Задание в архиве: загружено и доведено до нужного состояния.

    Прямая правка состояния вместо прогона через движок — нарочно:
    перераспознавать имеет смысл готовое, а гонять демо-движок ради статуса
    значит держать проверку на полминуты дольше без единого нового
    утверждения.
    """
    ответ = клиент.post("/api/jobs", headers={"X-API-Key": ключ},
                        files={"file": (имя, _wav(), "audio/wav")},
                        data={к: str(з) for к, з in настройки.items()})
    assert ответ.status_code == 200, ответ.text
    job_id = ответ.json()["id"]
    клиент.app.state.hub.db.update_job(job_id, status=состояние)
    return job_id


def задание(клиент: TestClient, job_id: str) -> dict:
    return клиент.app.state.hub.db.get_job(job_id)


