def test_чужое_задание_по_списку_не_перераспознаётся(сервер: TestClient):
    """Идентификаторы приходят списком — значит, чужой в нём тоже придёт.

    Без проверки владельца перераспознать чужой разговор мог бы кто угодно,
    знающий идентификатор: задание вернулось бы в очередь, пересчиталось
    новыми параметрами и переписало бы чужую расшифровку.
    """
    чужое = завести(сервер, ключ="ah_bob")

    тело = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                       json={"ids": [чужое]}).json()

    assert тело["queued"] == 0, тело
    assert [о["id"] for о in тело["failed"]] == [чужое]
    assert задание(сервер, чужое)["status"] == "completed"


def test_отбор_на_сервере_не_захватывает_чужие_задания(сервер: TestClient):
    """Вторая дорога к тому же: отбор без списка идентификаторов.

    Здесь никто не называет чужое задание — его выбирает сам сервер.
    Разрез по владельцу обязан стоять и в этой ветке: «перераспознать всё
    за месяц», отправленное обычным ключом, иначе поднимет весь архив
    организации.
    """
    своё = завести(сервер, ключ="ah_alice")
    чужое = завести(сервер, ключ="ah_bob")

    тело = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                       json={"filter": {}}).json()

    assert тело["ids"] == [своё], тело
    assert задание(сервер, чужое)["status"] == "completed", "чужое задание поставлено заново"
    # Чужое задание не должно даже попадать в отбор. Проверка владельца
    # стоит и при постановке, и без разреза в отборе она отбила бы саму
    # постановку — но идентификатор чужого задания уехал бы в ответ
    # строкой отказа, то есть наружу утёк бы перечень чужих записей.
    assert тело["failed"] == [], тело["failed"]


