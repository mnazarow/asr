def test_приоритет_применяется_к_поставленным_заданиям(сервер: TestClient):
    """Архив ставится ниже живой загрузки — иначе он её и вытеснит.

    Пересчёт сорока тысяч разговоров с обычной важностью означает, что
    человек, загрузивший запись совещания, получит её через сутки. Поэтому
    важность у ручки своя и обязана доходить до задания.
    """
    готовое = завести(сервер)

    ответ = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                        json={"ids": [готовое], "priority": 10})

    assert ответ.status_code == 200, ответ.text
    запись = задание(сервер, готовое)
    assert запись["priority"] == 10, запись["priority"]
    assert запись["status"] == "queued"


def test_без_приоритета_важность_задания_не_меняется(сервер: TestClient):
    """Не прислали важность — значит, не трогаем.

    Ноль и «не задано» различаются: важность 0 — это самый конец очереди, а
    молчание означает «как было». Подмена одного другим тихо опустила бы на
    дно всё, что перераспознаётся без явной важности.
    """
    готовое = завести(сервер)
    db = сервер.app.state.hub.db
    db.update_job(готовое, priority=70)

    сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                json={"ids": [готовое]})

    assert задание(сервер, готовое)["priority"] == 70
