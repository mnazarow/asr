def test_по_списку_ставит_задания_заново_с_новыми_параметрами(сервер: TestClient):
    """Перечисленные записи возвращаются в очередь, и параметры заменены.

    Это самая суть ручки: «перераспознать вот эти пять — новой моделью».
    Постановка без замены параметров означала бы, что архив пересчитали
    той же моделью, то есть потратили часы на тот же результат, и заметить
    это можно только по датам.
    """
    первое = завести(сервер)
    второе = завести(сервер)

    ответ = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                        json={"ids": [первое, второе],
                              "overrides": {"model": "gigaam-v3-ctc",
                                            "language": "en"}})

    assert ответ.status_code == 200, ответ.text
    тело = ответ.json()
    assert тело["queued"] == 2 and тело["failed"] == []
    assert set(тело["ids"]) == {первое, второе}
    for job_id in (первое, второе):
        запись = задание(сервер, job_id)
        assert запись["status"] == "queued", запись["status"]
        assert запись["params"]["model"] == "gigaam-v3-ctc"
        assert запись["params"]["language"] == "en"


