def test_поле_из_списка_но_не_из_каталога_не_доходит_до_задания(сервер: TestClient):
    """Белого списка мало: проверять значение нечем, если параметра нет в каталоге.

    В списке разрешённых к замене полей числятся `punctuation`,
    `num_speakers` и `align_words` — а параметрами каталога они не
    являются. Проверка каталогом такие ключи молча пропускала, и они
    уезжали в параметры задания с любым значением: строкой, объектом,
    чем угодно. Раз проверить нечем — значит, и принимать нечего.
    """
    from asrhub import catalog

    готовое = завести(сервер)
    ответ = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                        json={"ids": [готовое],
                              "overrides": {"punctuation": "чепуха", "beam_size": 4}})

    assert ответ.status_code == 200, ответ.text
    assert "punctuation" not in catalog.PARAMS_BY_KEY, \
        "параметр появился в каталоге — проверку надо переписать на другой ключ"
    assert "punctuation" not in ответ.json()["overrides"]
    assert "punctuation" not in задание(сервер, готовое)["params"]
    assert задание(сервер, готовое)["params"]["beam_size"] == 4, \
        "соседнее годное переопределение должно примениться"


def test_поля_вне_белого_списка_не_доходят_до_задания(сервер: TestClient):
    """В `overrides` приходит ввод снаружи, и кладётся он прямо в параметры.

    Рядом с безобидными полями живут адрес уведомления, каталоги на диске и
    прочее, что задание исполняет, а не просто хранит. Список закрытый
    именно поэтому: «всё, кроме опасного» пришлось бы дополнять при каждом
    новом параметре, и однажды забыли бы.
    """
    готовое = завести(сервер)
    прежние = dict(задание(сервер, готовое)["params"])

    тело = сервер.post("/api/jobs/rescan", headers={"X-API-Key": "ah_alice"},
                       json={"ids": [готовое], "overrides": {
                           "beam_size": 3,
                           "webhook_url": "http://169.254.169.254/latest/meta-data/",
                           "output_dir": "/etc",
                           "max_upload_mb": 999999,
                           "auth_enabled": False,
                       }}).json()

    assert тело["overrides"] == {"beam_size": 3}, тело["overrides"]
    параметры = задание(сервер, готовое)["params"]
    assert параметры["beam_size"] == 3, "разрешённое поле не применилось"
    for запрещённое in ("webhook_url", "output_dir", "max_upload_mb", "auth_enabled"):
        assert параметры.get(запрещённое) == прежние.get(запрещённое), \
            f"поле «{запрещённое}» просочилось в параметры задания"


