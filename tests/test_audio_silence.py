"""Тишина в записи — это не битый файл.

Разговор на шесть секунд, в котором никто не заговорил, возвращался с
сообщением «ffmpeg не смог обработать; проверьте целостность файла». Файл при
этом целый, ffmpeg отработал успешно, а звука на выходе не осталось, потому
что обрезка тишины убрала всё.

Цена ошибки та же, что у вчерашней истории с видеокартой: человек идёт
проверять исправное. Поэтому здесь проверяется не «поднялось исключение», а
какое именно и что в нём написано — по каждому из четырёх способов остаться
без звука.
"""
from __future__ import annotations

import shutil
import struct
import wave
from pathlib import Path

import pytest
from asrhub.errors import AudioError, NoSpeechDetected
from asrhub.pipeline import audio

pytestmark = pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="нужен ffmpeg")


# ---------------------------------------------------------------------------
# Записи
# ---------------------------------------------------------------------------


def тишина(путь: Path, секунд: float = 6.66, частота: int = 8000) -> Path:
    """Запись, в которой одна тишина — ровно как у неотвеченного звонка."""
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(частота)
        файл.writeframes(b"\x00\x00" * int(частота * секунд))
    return путь


def пустой_заголовок(путь: Path, частота: int = 8000) -> Path:
    """WAV из одного заголовка: станция файл создала, звук не записала."""
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(частота)
        файл.writeframes(b"")
    return путь


def речь(путь: Path, секунд: float = 2.0, частота: int = 16000) -> Path:
    """Запись со звуком — тон, который никакая обрезка тишины не съест."""
    import math

    кадры = bytearray()
    for i in range(int(частота * секунд)):
        кадры += struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440 * i / частота)))
    with wave.open(str(путь), "wb") as файл:
        файл.setnchannels(1)
        файл.setsampwidth(2)
        файл.setframerate(частота)
        файл.writeframes(bytes(кадры))
    return путь


НАСТРОЙКИ = {"audio_sample_rate": 16000, "audio_channels": "mono"}


def преобразовать(src: Path, dst: Path, **прочее):
    настройки = {**НАСТРОЙКИ, **прочее.pop("settings", {})}
    return audio.convert(src, dst, настройки, **прочее)


