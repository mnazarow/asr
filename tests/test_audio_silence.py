def test_молчаливый_разговор_это_нет_речи(tmp_path: Path):
    """Тот самый случай с боевого сервера.

    Шесть секунд тишины и включённая обрезка: ffmpeg отрабатывает успешно и
    выдаёт заголовок без единого отсчёта.
    """
    src = тишина(tmp_path / "1789584349.4961.wav")
    with pytest.raises(NoSpeechDetected) as отказ:
        преобразовать(src, tmp_path / "out.wav",
                      settings={"audio_trim_silence": True})
    assert отказ.value.code == "no_speech"
    assert "молчит" in отказ.value.message
    assert "6.7" in отказ.value.message or "6.6" in отказ.value.message
    # Приговор вынесен по измерению, а не по включённой настройке.
    assert отказ.value.details["peak_db"] <= audio.ТИШИНА_ДБ


def test_подсказка_не_отправляет_чинить_файл(tmp_path: Path):
    """Половина пользы подсказки — сказать, чего проверять не нужно."""
    src = тишина(tmp_path / "тихий.wav")
    with pytest.raises(NoSpeechDetected) as отказ:
        преобразовать(src, tmp_path / "out.wav",
                      settings={"audio_trim_silence": True})
    подсказка = отказ.value.hint
    assert "не поломка файла" in подсказка
    assert "целостность" not in подсказка
    # И сказать, что делать: отсев на приёме либо отключение обрезки.
    assert "Пропускать неотвеченные" in подсказка
    assert "Обрезать тишину" in подсказка


def test_без_обрезки_тишина_доходит_до_распознавания(tmp_path: Path):
    """Выключенная обрезка — работающий путь, а не обходной.

    Задание должно дойти до движка и вернуть пустой текст: это честнее, чем
    отказ, и именно это советует подсказка.
    """
    src = тишина(tmp_path / "тихий.wav")
    dst = преобразовать(src, tmp_path / "out.wav",
                        settings={"audio_trim_silence": False})
    assert dst.exists()
    assert dst.stat().st_size > audio.ПУСТОЙ_WAV


def test_срез_начальной_тишины_за_концом_файла(tmp_path: Path):
    """Сервер сам считает, сколько тишины в начале, и режет через -ss.

    На записи, которая молчит целиком, срез уходит за конец — и это тоже
    «нет речи», а не поломка.
    """
    src = тишина(tmp_path / "тихий.wav", секунд=3.0)
    with pytest.raises(NoSpeechDetected) as отказ:
        преобразовать(src, tmp_path / "out.wav", start_s=3.0)
    assert "молчит" in отказ.value.message


