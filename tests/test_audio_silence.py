# Совет разбирается отдельно от конвертации: ffmpeg на фильтре выше потолка
# не молчит начисто, а оставляет остаток, и через настоящий проход эта ветка
# не достаётся. Проверять её всё равно надо — она про слова, которые человек
# прочитает, и слова эти должны быть точными.


@pytest.mark.parametrize("порог,частота,ожидаем", [
    (5000, 8000, ["5000", "8000", "4000", "нет ничего"]),
    (4000, 8000, ["4000", "8000", "нет ничего"]),
    (3800, 8000, ["3800", "8000", "почти весь"]),
    (2000, 8000, ["2000", "8000", "почти весь"]),
])
def test_совет_про_фильтр_называет_числа(порог: int, частота: int,
                                         ожидаем: list[str]):
    """Один и тот же фильтр безобиден на студийной записи и смертелен на звонке.

    Поэтому порог сравнивается с частотой записи, а не с абстрактным числом,
    и в совете стоят оба числа: без них «многовато» ничего не объясняет.
    """
    совет = audio._совет_фильтры(
        {"audio_highpass_hz": порог}, частота, f"highpass=f={порог}")
    for кусок in ожидаем:
        assert кусок in совет, совет


def test_на_студийной_записи_тот_же_фильтр_не_виноват():
    """160 Гц при 44 100 — норма, и обвинять фильтр не за что."""
    совет = audio._совет_фильтры(
        {"audio_highpass_hz": 160}, 44100, "highpass=f=160")
    assert "Фильтр высоких частот" not in совет
    assert "Файл целый и звучит" in совет


def test_совет_без_известной_частоты(tmp_path: Path):
    """Частоту узнать не удалось — сравнивать не с чем, но сказать есть что."""
    совет = audio._совет_фильтры({"audio_highpass_hz": 3000}, 0, "highpass=f=3000")
    assert "3000" in совет
    assert "80–200" in совет


# ---------------------------------------------------------------------------
# Отпечаток исходника
# ---------------------------------------------------------------------------
#
# Настоящий отказ с боевого сервера воспроизвести не удалось: файл проходит
# обработку. Осталась версия, что его читали, пока он ещё дописывался, — и
# проверить её было нечем. Теперь размер и время исходника попадают в
# подробности отказа, и такую версию можно подтвердить или отвергнуть за
# один взгляд, а не за три часа переписки.


def test_размер_исходника_в_подробностях_при_пустом_выходе(tmp_path: Path):
    src = тишина(tmp_path / "тихий.wav", секунд=2.0)
    with pytest.raises(NoSpeechDetected) as отказ:
        преобразовать(src, tmp_path / "out.wav",
                      settings={"audio_trim_silence": True})
    assert отказ.value.details["source_bytes"] == src.stat().st_size
    assert отказ.value.details["source_mtime"] > 0


def test_размер_исходника_в_подробностях_при_отказе_ffmpeg(tmp_path: Path):
    """И во второй ветке тоже: отказ ffmpeg бывает от недописанного файла."""
    src = tmp_path / "битый.wav"
    src.write_bytes(b"RIFF" + b"\x00" * 64 + b"garbage" * 40)
    with pytest.raises(AudioError) as отказ:
        преобразовать(src, tmp_path / "out.wav")
    assert отказ.value.details["source_bytes"] == src.stat().st_size
    assert отказ.value.details["returncode"] != 0


def test_исчезнувший_файл_не_роняет_разбор(tmp_path: Path):
    """Файл могли убрать между отказом и снятием отпечатка.

    Разбор отказа не имеет права падать сам: тогда вместо причины человек
    получит трассировку, а причина — то единственное, зачем он сюда смотрит.
    """
    from asrhub.pipeline.audio import _отпечаток

    assert _отпечаток(tmp_path / "нет-такого.wav") == {"source_bytes": 0}
