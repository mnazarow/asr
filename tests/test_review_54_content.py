import pytest
from asrhub.content import compliance, entities, keywords, masking, sentiment

_модуль_разбора = importlib.import_module("asrhub.content.analyze")
разбор = _модуль_разбора.analyze


def _р(кто: str, текст: str, с: float, по: float) -> dict[str, Any]:
    return {"speaker": кто, "text": текст, "start": с, "end": по}


