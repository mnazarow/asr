def test_разовый_сбой_базы_не_оставляет_запись_пустой_навсегда(tmp_path, monkeypatch):
    from asrhub import content_index
    from asrhub.db import Database

    db = Database(tmp_path / "x.db")
    db.create_job({"id": "j1", "filename": "a.wav", "owner": "", "engine": "demo",
                   "model": "demo", "language": "ru", "source": "api",
                   "media_duration_s": 10.0})
    db.update_job("j1", status="completed", text="Здравствуйте, спасибо, до свидания.",
                  finished_at=1.0)
    db.save_segments("j1", [{"start": 0.0, "end": 3.0, "text": "Здравствуйте, спасибо.",
                             "speaker": "SPEAKER_00"}])
    индекс = content_index.ContentIndex(db, None)
    настоящее = db.get_segments
    сбоев = {"n": 0}

    def сбойное(*a: Any, **k: Any) -> Any:
        if сбоев["n"] == 0:
            сбоев["n"] += 1
            raise RuntimeError("database is locked")
        return настоящее(*a, **k)

    monkeypatch.setattr(db, "get_segments", сбойное)
    индекс.backfill_once(limit=10)
    индекс.backfill_once(limit=10)
    строка = db.query_one("SELECT sentiment_label FROM content WHERE job_id='j1'")
    assert строка is not None and строка["sentiment_label"] is not None
    assert db.content_stats(version=1)["failed"] == 0
    db.close()
