def test_образцовый_короткий_разговор_не_теряет_приветствие_и_прощание():
    """Пока у оператора меньше десяти реплик, «начало» и «конец» были одной
    репликой: «Здравствуйте.» — «Алло» — «Компания Ромашка, меня зовут
    Ольга…» давало «не представился», а прощание в предпоследней реплике —
    «не попрощался»."""
    реплики = [
        _р("A", "Здравствуйте.", 0, 1), _р("B", "Алло", 1, 2),
        _р("A", "Компания Ромашка, меня зовут Ольга, чем могу помочь?", 2, 5),
        _р("B", "Хочу узнать про заказ", 5, 8), _р("A", "Сейчас посмотрю", 8, 10),
        _р("B", "Хорошо", 10, 11), _р("A", "Всё готово, заказ в пути", 40, 45),
        _р("B", "Спасибо", 45, 46), _р("A", "Всего доброго, до свидания.", 80, 82),
        _р("B", "До свидания.", 82, 83), _р("A", "Угу.", 83, 84),
    ]
    итог = {п["id"]: п["passed"] for п in compliance.check(реплики)["items"]}
    assert итог["introduce"] and итог["company"] and итог["offer_help"]
    assert итог["farewell"]


def test_уточните_номер_это_не_следующий_шаг():
    """«Уточню» в скрипте совпадало по основе с «уточните»: вопрос клиенту
    засчитывался оператору как названный следующий шаг."""
    реплики = [_р("A", "Здравствуйте. Уточните номер заказа, пожалуйста.", 0, 3),
               _р("B", "Сто двадцать три.", 3, 5)]
    итог = {п["id"]: п["passed"] for п in compliance.check(реплики)["items"]}
    assert итог["next_step"] is False


def test_скрипт_проверяется_при_сохранении():
    """Пункт без примет молчал всегда, а сохранение его принимало."""
    assert compliance.validate([{"id": "x", "label": "Пустой"}])
    assert compliance.validate([{"id": "ok", "label": "Привет", "any": ["здравствуйте"]}]) == []


def test_настройка_скрипта_с_ошибкой_отвергается_проверкой_каталога():
    from asrhub.catalog import params

    ошибки = params.validate("content_script", [{"id": "x", "label": "Пустой"}]) \
        if hasattr(params, "validate") else params._ПРОВЕРКИ["content_script"](
            [{"id": "x", "label": "Пустой"}])
