def test_основы_и_фразы_тем_обезличиваются():
    """Номер через дефис становился ключевым словом, а поля stem, phrase и
    stems не маскировались вовсе."""
    данные = {"stem": "9161234567", "phrase": "звоните 916 123-45-67",
              "stems": ["9161234567", "доставк"]}
    итог = masking.mask_payload(данные)
    assert "916" not in str(итог["phrase"])
    assert "9161234567" not in str(итог["stem"])
    assert "9161234567" not in str(итог["stems"])


