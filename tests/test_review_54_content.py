def test_обычный_вежливый_звонок_не_критик():
    """Предсказанный NPS ставил обычному вежливому звонку «критика»."""
    реплики = [
        _р("A", "Здравствуйте, компания Ромашка, Ольга, чем могу помочь?", 0, 4),
        _р("B", "Здравствуйте, хотел узнать, когда привезут заказ.", 4, 8),
        _р("A", "Сейчас посмотрю. Заказ привезут завтра до обеда.", 8, 14),
        _р("B", "Хорошо, спасибо.", 14, 16),
        _р("A", "Пожалуйста. Всего доброго, до свидания.", 16, 19),
        _р("B", "До свидания.", 19, 20),
    ]
    итог = разбор(text=" ".join(р["text"] for р in реплики), segments=реплики)
    nps = итог["indices"]["nps"]
    assert nps["predicted"] and nps["group"] != "критик", nps
    assert nps["score"] >= 7, nps


